<?php
// temy7.php — темы третьей системы («витрина»): под размеченный контент с блоками
// hero-value, value-pillars, slots-dashboard, recent-payouts, faq-section и т. д.
declare(strict_types=1);

// Сочетание полей темы повторяется только через 1440 номеров, поэтому таблицу
// можно раздвигать: номера 1–120 при этом считаются ровно как раньше.
function v7Количество(): int { return 240; }

/** Палитры: четыре тёмные подложки и четыре светлые. */
function v7Палитры(): array {
    return [
        'чернила' => ['тёмная', '#0d1016', '#161a24', '#1d2230', '#eef1f7', '#98a2b6', '#262c3a'],
        'ночь'    => ['тёмная', '#0a1322', '#111f38', '#16294a', '#e9f0ff', '#8ea5c8', '#1c3052'],
        'графит'  => ['тёмная', '#141618', '#1e2124', '#262a2e', '#ecEEF0', '#99a0a8', '#2c3035'],
        'слива'   => ['тёмная', '#140f1d', '#1e1630', '#281d40', '#f1eaf8', '#a698bd', '#2e2245'],
        'бумага'  => ['светлая', '#f6f5f2', '#ffffff', '#fbfaf7', '#1b1d21', '#6b7178', '#e2e1dc'],
        'лён'     => ['светлая', '#f3f1ea', '#fffdf8', '#faf7ef', '#221f1a', '#6f6a5e', '#e1ddd0'],
        'мел'     => ['светлая', '#f1f4f7', '#ffffff', '#f8fafc', '#161a20', '#657080', '#dee3ea'],
        'песок'   => ['светлая', '#f7f2ec', '#fffbf6', '#fdf7f0', '#241f19', '#7a6a5b', '#eadfd0'],
    ];
}

function v7Tema(int $n): array {
    $n = (($n - 1) % v7Количество()) + 1;
    $k = $n - 1;
    $имена = array_keys(v7Палитры());
    $пал = $имена[($k * 3) % 8];
    [$семья, $фон, $карта, $карта2, $текст, $тускло, $рамка] = v7Палитры()[$пал];
    $тон = fmod($k * 61.7 + 23, 360);
    $тон2 = fmod($тон + 214, 360);
    $тьма = $семья === 'тёмная';
    return [
        'номер' => $n,
        'палитра' => $пал,
        'семья' => $семья,
        'фон' => $фон, 'карта' => $карта, 'карта2' => $карта2,
        'текст' => $текст, 'тускло' => $тускло, 'рамка' => $рамка,
        'тон' => $тон, 'тон2' => $тон2,
        'акцент'  => sprintf('hsl(%.1f %d%% %d%%)', $тон, $тьма ? 66 : 60, $тьма ? 56 : 42),
        'акцент2' => sprintf('hsl(%.1f %d%% %d%%)', $тон2, $тьма ? 70 : 62, $тьма ? 60 : 46),
        'мягкий'  => sprintf('hsl(%.1f %d%% %d%% / %s)', $тон, 70, $тьма ? 56 : 46, $тьма ? '.16' : '.12'),
        'заголовок' => ['полоса', 'капс', 'крупный', 'номерной'][intdiv($k, 8) % 4],
        'форма'     => ['острые', 'мягкие', 'круглые', 'скос'][$k % 4],
        'слот'      => ['градиент', 'картинка', 'компакт'][intdiv($k, 4) % 3],
        'картинка'  => ['шапка', 'фон', 'врезка', 'полосы', 'постеры'][($k * 7) % 5],
        'метка'     => ['подчерк', 'угол', 'точки'][intdiv($k, 5) % 3],
        'шрифт'     => ['гротеск', 'сериф', 'узкий'][intdiv($k, 3) % 3],
        'сюжет'     => intdiv($k, 3) % 3,                        // какой предмет рисуется в баннере раздела
        'раскладка' => ['справа', 'ряд', 'край'][$k % 3],        // как он стоит на баннере
    ];
}
