/** Яркость и контраст по WCAG — чтобы акцент читался на своём фоне. */
function v7Яркость(array $rgb): float {
    $f = function ($x) { $x /= 255; return $x <= 0.03928 ? $x / 12.92 : (($x + 0.055) / 1.055) ** 2.4; };
    return 0.2126 * $f($rgb[0]) + 0.7152 * $f($rgb[1]) + 0.0722 * $f($rgb[2]);
}

function v7Контраст(array $a, array $b): float {
    $x = v7Яркость($a); $y = v7Яркость($b);
    if ($x < $y) { [$x, $y] = [$y, $x]; }
    return ($x + 0.05) / ($y + 0.05);
}

function v7ИзHsl(float $h, float $s, float $l): array {
    $c = (1 - abs(2 * $l - 1)) * $s; $x = $c * (1 - abs(fmod($h / 60, 2) - 1)); $m = $l - $c / 2;
    $q = [[$c,$x,0],[$x,$c,0],[0,$c,$x],[0,$x,$c],[$x,0,$c],[$c,0,$x]][(int)($h / 60) % 6];
    return [($q[0]+$m)*255, ($q[1]+$m)*255, ($q[2]+$m)*255];
}

function v7ИзHex(string $hex): array {
    return [hexdec(substr($hex,1,2)), hexdec(substr($hex,3,2)), hexdec(substr($hex,5,2))];
}

/** Светлота акцента: от базовой идём в сторону фона, пока контраст не дотянет до 4.5. */
function v7Светлота(float $тон, int $нас, int $база, string $фон, bool $тьма): int {
    $ф = v7ИзHex($фон);
    for ($l = $база; $l >= 18 && $l <= 82; $l += $тьма ? 2 : -2) {
        if (v7Контраст(v7ИзHsl($тон, $нас / 100, $l / 100), $ф) >= 4.5) return $l;
    }
    return $тьма ? 82 : 18;
}


/** Что читается на цветной кнопке: белый или почти чёрный. */
function v7НаЦвете(float $тон, int $нас, int $l): string {
    $rgb = v7ИзHsl($тон, $нас / 100, $l / 100);
    return v7Контраст($rgb, [255, 255, 255]) >= v7Контраст($rgb, [17, 19, 22]) ? '#fff' : '#111316';
}


function v7Tema(int $n): array {
    $n = (($n - 1) % v7Количество()) + 1;
    $k = $n - 1;
    $имена = array_keys(v7Палитры());
    $пал = $имена[($k * 3) % 8];
    [$семья, $фон, $карта, $карта2, $текст, $тускло, $рамка] = v7Палитры()[$пал];
    $тон = fmod($k * 61.7 + 23, 360);
    $тон2 = fmod($тон + 214, 360);
    $тьма = $семья === 'тёмная';
    return [
        'номер' => $n,
        'палитра' => $пал,
        'семья' => $семья,
        'фон' => $фон, 'карта' => $карта, 'карта2' => $карта2,
        'текст' => $текст, 'тускло' => $тускло, 'рамка' => $рамка,
        'тон' => $тон, 'тон2' => $тон2,
        'наАкценте'  => v7НаЦвете($тон, $тьма ? 66 : 60, v7Светлота($тон, $тьма ? 66 : 60, $тьма ? 56 : 42, $фон, $тьма)),
        'наАкценте2' => v7НаЦвете($тон2, $тьма ? 70 : 62, v7Светлота($тон2, $тьма ? 70 : 62, $тьма ? 60 : 46, $фон, $тьма)),
        'акцент'  => sprintf('hsl(%.1f %d%% %d%%)', $тон, $тьма ? 66 : 60,
                             v7Светлота($тон, $тьма ? 66 : 60, $тьма ? 56 : 42, $фон, $тьма)),
        'акцент2' => sprintf('hsl(%.1f %d%% %d%%)', $тон2, $тьма ? 70 : 62,
                             v7Светлота($тон2, $тьма ? 70 : 62, $тьма ? 60 : 46, $фон, $тьма)),
        'мягкий'  => sprintf('hsl(%.1f %d%% %d%% / %s)', $тон, 70, $тьма ? 56 : 46, $тьма ? '.16' : '.12'),
        'заголовок' => ['полоса', 'капс', 'крупный', 'номерной'][intdiv($k, 8) % 4],
        'форма'     => ['острые', 'мягкие', 'круглые', 'скос'][$k % 4],
        'слот'      => ['градиент', 'картинка', 'компакт'][intdiv($k, 4) % 3],
        'картинка'  => ['шапка', 'фон', 'врезка', 'полосы', 'постеры'][($k * 7) % 5],
        'метка'     => ['подчерк', 'угол', 'точки'][intdiv($k, 5) % 3],
        'шрифт'     => ['гротеск', 'сериф', 'узкий'][intdiv($k, 3) % 3],
        'сюжет'     => intdiv($k, 3) % 3,                        // какой предмет рисуется в баннере раздела
        'раскладка' => ['справа', 'ряд', 'край'][$k % 3],        // как он стоит на баннере
    ];
}
