<?php
// проверка-тем.php — все номера тем различаются хотя бы одним полем или тоном акцента.
// Запас объявлен в v7Количество(); перебор показывает, что в нём нет двух одинаковых тем.
declare(strict_types=1);
require __DIR__ . '/temy7.php';
$видели = [];
$всего = v7Количество();
for ($n = 1; $n <= $всего; $n++) {
    $т = v7Tema($n);
    unset($т['номер']);
    $ключ = json_encode($т, JSON_UNESCAPED_UNICODE);
    if (isset($видели[$ключ])) {
        printf("повтор: тема %d совпадает с темой %d\n", $n, $видели[$ключ]);
        exit(1);
    }
    $видели[$ключ] = $n;
}
printf("тем %d, все разные\n", $всего);
