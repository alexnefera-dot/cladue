/** Плитка игрового автомата: фон, рассыпанные символы, главный символ, рамка. */
function g7Плитка(string $file, string $игра, int $w = 640, int $h = 400): void {
    $s = crc32(mb_strtolower($игра));
    $rnd = function (int $i) use ($s) { return (($s >> ($i % 24)) ^ ($s * ($i + 7))) & 0x7fffffff; };
    $сем = g7Семья($игра);
    $сдвиг = ($s % 64) - 32;                       // игры одной семьи не повторяются в цвете
    $тон = $сем['тон'] + $сдвиг; $тон2 = $сем['тон2'] + $сдвиг;
    $тьма  = g7hsl($тон, .68, .10);
    $глубь = g7hsl($тон, .62, .27);
    $угол  = g7hsl($тон2, .70, .40);
    $ярк   = g7hsl($тон, .84, .58);
    $свет  = g7hsl($тон2, .32, .93);

    $W = $w * G7; $H = $h * G7;
    // Подложка со свечениями рисуется вчетверо мельче и растягивается: та же мягкость, но быстро.
    $sw = (int) ($W / 4); $sh = (int) ($H / 4);
    $под = imagecreatetruecolor($sw, $sh);
    imagealphablending($под, true);
    for ($y = 0; $y < $sh; $y++) {
        imageline($под, 0, $y, $sw, $y, g7c($под, g7микс($тьма, $глубь, $y / $sh)));
    }
    for ($r = (int) ($sh * .8); $r > 0; $r -= 2) g7круг($под, $sw * .04, $sh * .04, $r, $угол, .006);
    foreach ([[.16, .30], [.62, .12]] as $п) {
        $x0 = $sw * $п[0];
        for ($i = 0; $i < (int) ($sw * $п[1]); $i++) {
            imageline($под, (int) ($x0 + $i), 0, (int) ($x0 + $i - $sh * .5), $sh, g7c($под, $угол, .022));
        }
    }
    for ($r = (int) ($sh * .58); $r > 0; $r--) {
        g7круг($под, $sw * .5, $sh * .46, $r, $ярк, .030 * pow(1 - $r / ($sh * .58), 1.9) + .002);
    }
    $im = imagecreatetruecolor($W, $H);
    imagealphablending($im, false);
    imagecopyresampled($im, $под, 0, 0, 0, 0, $W, $H, $sw, $sh);
    imagedestroy($под);
    imagealphablending($im, true);
    $cx = $W * .5; $cy = $H * .46;
    // мелкие символы по углам
    $мел = $сем['мелкие'];
    $места = [[.13, .20], [.87, .17], [.09, .78], [.90, .80], [.28, .90], [.72, .09]];
    foreach ($места as $i => $м) {
        $вид = $мел[$i % count($мел)];
        g7символ($im, $вид, $W * $м[0], $H * $м[1], $H * (.16 + (($rnd($i) % 7) / 100)), $свет, $свет, .13);
    }
    // главный символ: тень, тело, блик
    $разм = $H * .56;
    g7символ($im, $сем['герой'], $cx + $H * .022, $cy + $H * .028, $разм, [0, 0, 0], [0, 0, 0], .30);
    g7символ($im, $сем['герой'], $cx, $cy, $разм, $ярк, $свет, 1);
    // рамка и виньетка
    $b = (int) ($H * .30);
    for ($i = 0; $i < $b; $i++) {
        $op = .34 * pow(1 - $i / $b, 2.2);
        imageline($im, 0, $H - 1 - $i, $W, $H - 1 - $i, g7c($im, [0, 0, 0], $op));
        imageline($im, 0, $i, $W, $i, g7c($im, [0, 0, 0], $op * .5));
    }
    imagesetthickness($im, (int) max(2, $H * .012));
    imagerectangle($im, 2, 2, $W - 3, $H - 3, g7c($im, $свет, .16));
    imagesetthickness($im, 1);

    $out = imagecreatetruecolor($w, $h);
    imagecopyresampled($out, $im, 0, 0, 0, 0, $w, $h, $W, $H);
    imagedestroy($im);
    imagewebp($out, $file, 82);
    imagedestroy($out);
}

