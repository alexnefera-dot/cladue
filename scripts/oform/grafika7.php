/**
 * Подложка баннера раздела в тоне комплекта: градиент, крупный предметный символ
 * сбоку и пара мелких. Возвращает картинку и цвета для подписи.
 */
function g7Сцена(int $w, int $h, float $тон, float $тон2, string $символ, int $seed, float $ярче = 1.0, string $раскладка = 'справа') {
    $W = $w * G7; $H = $h * G7;
    $тьма  = g7hsl($тон, .55, .11 * $ярче + .04);
    $глубь = g7hsl($тон2, .50, .20 * $ярче + .04);
    $ярк   = g7hsl($тон, .72, .56);
    $свет  = g7hsl($тон2, .35, .92);
    $sw = (int) ($W / 4); $sh = (int) ($H / 4);
    $под = imagecreatetruecolor($sw, $sh);
    imagealphablending($под, true);
    for ($y = 0; $y < $sh; $y++) imageline($под, 0, $y, $sw, $y, g7c($под, g7микс($тьма, $глубь, $y / $sh)));
    for ($i = 0; $i < 3; $i++) {                       // мягкие световые пятна
        $x = $sw * (.62 + .12 * (($seed >> ($i * 3)) % 4) / 4);
        for ($r = (int) ($sh * (.5 + .15 * $i)); $r > 0; $r--) g7круг($под, $x, $sh * .5, $r, $ярк, .012);
    }
    $im = imagecreatetruecolor($W, $H);
    imagealphablending($im, false);
    imagecopyresampled($im, $под, 0, 0, 0, 0, $W, $H, $sw, $sh);
    imagedestroy($под);
    imagealphablending($im, true);
    if ($раскладка === 'ряд') {                        // три средних по правому краю
        foreach ([[.60, .40, .40], [.78, .56, .52], [.95, .34, .34]] as $i => $п) {
            g7символ($im, $символ, $W * $п[0] + $H * .015, $H * $п[1] + $H * .02, $H * $п[2], [0, 0, 0], [0, 0, 0], .14);
            g7символ($im, $символ, $W * $п[0], $H * $п[1], $H * $п[2], $ярк, $свет, .30 + $i * .12);
        }
        g7символ($im, $символ, $W * .10, $H * .26, $H * .2, $свет, $свет, .09);
    } elseif ($раскладка === 'край') {                  // крупный, обрезанный краем
        g7символ($im, $символ, $W * .94 + $H * .02, $H * .5 + $H * .02, $H * 1.15, [0, 0, 0], [0, 0, 0], .16);
        g7символ($im, $символ, $W * .94, $H * .5, $H * 1.15, $ярк, $свет, .40);
        g7символ($im, $символ, $W * .12, $H * .8, $H * .22, $свет, $свет, .09);
    } else {                                            // один крупный справа
        g7символ($im, $символ, $W * .78 + $H * .02, $H * .52 + $H * .02, $H * .74, [0, 0, 0], [0, 0, 0], .18);
        g7символ($im, $символ, $W * .78, $H * .52, $H * .74, $ярк, $свет, .55);
        g7символ($im, $символ, $W * .10, $H * .28, $H * .26, $свет, $свет, .10);
        g7символ($im, $символ, $W * .22, $H * .84, $H * .18, $свет, $свет, .08);
    }
    imagesetthickness($im, (int) max(2, $H * .008));
    imageline($im, 0, $H - 2, $W, $H - 2, g7c($im, $ярк, .5));
    imagesetthickness($im, 1);
    return [$im, $свет, $ярк];
}
