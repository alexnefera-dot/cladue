function таблица(шапка, строки, ширины, моно) {
  const ячейка = (текст, жирн, ш, код) => new TableCell({
    width: { size: ш, type: WidthType.DXA },
    shading: жирн ? { type: ShadingType.CLEAR, fill: СЕРЫЙ } : undefined,
    margins: { top: 80, bottom: 80, left: 120, right: 120 },
    children: [new Paragraph({ spacing: { after: 0, line: 280 },
      children: [new TextRun({ text: текст, size: код ? 19 : 21, bold: жирн, font: код ? "Consolas" : undefined })] })],
  });
  return new Table({
    columnWidths: ширины,
    width: { size: ширины.reduce((a, b) => a + b, 0), type: WidthType.DXA },
    rows: [
      new TableRow({ tableHeader: true, children: шапка.map((t, i) => ячейка(t, true, ширины[i], false)) }),
      ...строки.map(r => new TableRow({ children: r.map((t, i) => ячейка(t, false, ширины[i], моно ? моно.includes(i) : false)) })),
    ],
  });
}

