<?php

declare(strict_types=1);

namespace YandexSites\Visit;

use YandexSites\Content\KnownBrands;

/**
 * «Подборка офферов» — страница-подмена вместо настоящего сайта (клоакинг).
 *
 * Часть сайтов показывает не свой контент, а витрину партнёрских бонусов: крупный заголовок,
 * «В подборке 6 офферов», кружки/карточки чужих брендов с «ЗАБРАТЬ БОНУС», бегущая строка
 * «7K КАЗИНО CASINO — 300 000 ₽ 500 FS FREEBET» и снизу «18+ Азартные игры являются развлечением.
 * Проверяйте условия бонуса партнёра перед регистрацией». Настоящий сайт за такой заглушкой прячется
 * и показывается другим посетителям, поэтому страницу нельзя сохранять как контент: её нужно
 * перезапросить с ДРУГОГО IP и под ДРУГИМ User-Agent (этим занимается PageVisitor::runWithRetry()).
 *
 * Признак засчитывается по подстроке видимого текста; «сильные» (встречаются практически только у
 * витрин) весят 2, «слабые» — 1. Часть признаков считается по ПОВТОРАМ: одна кнопка «Забрать бонус»
 * есть и на обычном сайте казино, а вот пять таких кнопок подряд — это витрина. Плюс жёсткое
 * ограничение: витрина всегда короткая, у настоящего сайта на главной есть SEO-текст, поэтому
 * страницы длиннее MAX_TEXT витриной не считаются никогда — ложно выбросить настоящий сайт
 * дороже, чем не распознать очередную заглушку.
 */
final class OfferWall
{
    /** Подпись для таблицы, статистики и причины визита. */
    public const LABEL = 'подборка офферов';

    /** Порог суммы весов; нужен ещё хотя бы один сильный признак. */
    public const MIN_SCORE = 4;

    /** Длиннее этого (символов видимого текста) — это уже настоящая страница, а не витрина. */
    public const MAX_TEXT = 4000;

    /**
     * Сильные признаки (вес 2): формулировки, которыми витрина описывает ЧУЖИЕ предложения
     * («оффер», «партнёр»). На сайте самого бренда таких слов нет — он рассказывает про себя.
     */
    private const STRONG = [
        'в подборке',
        'оффер',
        'условия бонуса партнёра',
        'условия бонуса партнера',
        'бонуса партнёра',
        'бонуса партнера',
    ];

    /**
     * Слабые признаки (вес 1). Сюда же — дисклеймер «Азартные игры являются развлечением» и «18+»:
     * их ставят и обычные сайты казино, поэтому сами по себе они ничего не доказывают (короткая
     * главная настоящего сайта из-за такого «сильного» признака попадала в витрины).
     */
    private const WEAK = [
        'freebet',
        'фрибет',
        'азартные игры являются развлечением',
        'на 1-й депозит',
        'все проверены',
        'бонус до',
        'первый номер',
        '18+',
    ];

    /**
     * Повторяющиеся элементы витрины: подстрока => [сколько раз встретилась, вес, сильный ли].
     * Одна кнопка «Забрать бонус» есть и на обычном сайте, пять подряд — это список чужих офферов.
     */
    private const REPEATS = [
        'забрать бонус' => [3, 2, true],
        'казино casino' => [2, 2, true],
        ' fs' => [4, 1, false],
    ];

    /** Сколько РАЗНЫХ чужих брендов на странице считается витриной (вес 2). */
    private const BRANDS_MIN = 3;

    /**
     * Похожа ли страница на витрину офферов вместо настоящего сайта.
     *
     * @param list<string> $brands список известных брендов (по умолчанию встроенный + brands.txt)
     */
    public static function looksLike(string $html, ?array $brands = null): bool
    {
        [$score, $strong] = self::score($html, $brands);

        return $strong > 0 && $score >= self::MIN_SCORE;
    }

    /**
     * Сумма весов и число сильных признаков — отдельно, чтобы можно было проверить разбор
     * конкретной страницы в тестах и при отладке.
     *
     * @param list<string>|null $brands
     * @return array{0: int, 1: int}
     */
    public static function score(string $html, ?array $brands = null): array
    {
        $text = mb_strtolower(Fingerprint::text($html));
        if ($text === '' || mb_strlen($text) > self::MAX_TEXT) {
            return [0, 0];
        }
        $score = 0;
        $strong = 0;
        foreach (self::STRONG as $marker) {
            if (mb_strpos($text, $marker) !== false) {
                $score += 2;
                $strong++;
            }
        }
        foreach (self::WEAK as $marker) {
            if (mb_strpos($text, $marker) !== false) {
                $score++;
            }
        }
        foreach (self::REPEATS as $marker => [$times, $weight, $isStrong]) {
            if (mb_substr_count($text, (string) $marker) >= $times) {
                $score += $weight;
                $strong += $isStrong ? 1 : 0;
            }
        }
        // Витрина перечисляет ЧУЖИЕ бренды: у настоящего сайта на главной свой бренд, а не пять соседей.
        if (self::countBrands($text, $brands ?? self::brands()) >= self::BRANDS_MIN) {
            $score += 2;
            $strong++;
        }

        return [$score, $strong];
    }

    /**
     * Встроенный список брендов, прочитанный один раз за процесс: страниц тысячи, а KnownBrands::all()
     * каждый раз читает brands.txt с диска.
     *
     * @return list<string>
     */
    private static function brands(): array
    {
        static $cache = null;

        return $cache ??= KnownBrands::all();
    }

    /**
     * Сколько разных известных брендов упомянуто в тексте.
     *
     * @param list<string> $brands
     */
    private static function countBrands(string $text, array $brands): int
    {
        $found = [];
        foreach ($brands as $brand) {
            $brand = mb_strtolower(trim($brand));
            if ($brand === '' || mb_strpos($text, $brand) === false) {
                continue;
            }
            // Однокоренные записи одного бренда («vulkan» и «вулкан») считаем за один.
            $found[preg_replace('~[^a-z0-9]~u', '', self::translit($brand)) ?: $brand] = true;
        }

        return count($found);
    }

    /** Грубая транслитерация, чтобы «вулкан» и «vulkan» не считались двумя разными брендами. */
    private static function translit(string $s): string
    {
        $map = [
            'а' => 'a', 'б' => 'b', 'в' => 'v', 'г' => 'g', 'д' => 'd', 'е' => 'e', 'ё' => 'e',
            'ж' => 'zh', 'з' => 'z', 'и' => 'i', 'й' => 'i', 'к' => 'k', 'л' => 'l', 'м' => 'm',
            'н' => 'n', 'о' => 'o', 'п' => 'p', 'р' => 'r', 'с' => 's', 'т' => 't', 'у' => 'u',
            'ф' => 'f', 'х' => 'h', 'ц' => 'c', 'ч' => 'ch', 'ш' => 'sh', 'щ' => 'sch', 'ъ' => '',
            'ы' => 'y', 'ь' => '', 'э' => 'e', 'ю' => 'yu', 'я' => 'ya',
        ];

        return strtr($s, $map);
    }
}
