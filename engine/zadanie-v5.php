<?php
declare(strict_types=1);

/**
 * Задание на комплект v5 — что писать реалайзеру или руками.
 *
 *   php engine/zadanie-v5.php --выход=tmp/gen-<имя> [--сид=<n>] [--набор=<имя>]
 *
 * Генератор `generator-v5.php` собирает страницу из фраз доноров, и это даёт
 * верную форму, но не даёт корпусной уникальности: доля каждого из
 * одиннадцати доноров в собранном тексте ≈ 9 %, плюс общая библиотека блоков
 * ≈ 6 %, итого 13–18 % шинглов против корпусного потолка 8–11 %. Ниже этой
 * арифметики пересборка не опускается — уникальность покупается написанием.
 *
 * Поэтому второй путь тот же, что в v4: задание → написание → замер → правка.
 * Здесь готовится первый шаг. На каждую из двенадцати страниц выписывается:
 *
 *  · скелет: какие виджеты в голове и хвосте, сколько разделов в теле;
 *  · разделы: H2 из закрытого списка фабрики, в наблюдённом порядке;
 *  · плотность: сколько абзацев в зачине, фраз в абзаце, пунктов в списке;
 *  · цели: поля профиля с `держат=true` и их коридоры;
 *  · фактура набора: каталог, провайдеры, вейджер, герои;
 *  · бюджет ссылок: сколько и на какие адреса (у корпуса их ровно шесть).
 *
 * Виджеты при этом берутся сборкой — их разметка и так общая у всех доноров;
 * пишется только проза тела и пары «вопрос-ответ».
 */

require_once __DIR__ . '/src/V5Blocks.php';
require_once __DIR__ . '/src/Generator/Rng.php';

$выход = ''; $сид = null; $набор = '';
foreach (array_slice($argv, 1) as $a) {
    if (str_starts_with($a, '--выход=')) { $выход = rtrim(substr($a, strlen('--выход=')), '/'); }
    elseif (str_starts_with($a, '--сид=')) { $сид = (int) substr($a, strlen('--сид=')); }
    elseif (str_starts_with($a, '--набор=')) { $набор = substr($a, strlen('--набор=')); }
}
if ($выход === '') { fwrite(STDERR, "usage: php engine/zadanie-v5.php --выход=tmp/gen-<имя> [--сид=n]\n"); exit(1); }
$набор = $набор !== '' ? $набор : basename($выход);
$сид ??= crc32($набор);

$данные = __DIR__ . '/data-v5';
$блоки   = json_decode((string) file_get_contents("$данные/bloki.json"), true);
$пулы    = json_decode((string) file_get_contents("$данные/pools.json"), true);
$профиль = json_decode((string) file_get_contents("$данные/profil-v5.json"), true);
if (!$блоки || !$пулы || !$профиль) { fwrite(STDERR, "нет выкладок в data-v5\n"); exit(1); }

$rng = new Rng($сид);
$банки = $пулы['общие']['банки'];
$изБанка = fn(string $k) => (string) $rng->pick(array_keys($банки[$k] ?? ['0' => 1]));
$медиана = function (array $v, int $п): int {
    $v = array_values(array_filter($v, fn($x) => $x > 0));
    if (!$v) { return $п; }
    sort($v);
    return (int) $v[intdiv(count($v), 2)];
};

$факты = [
    'каталог'     => $изБанка('СЛОТОВ') . '+ слотов',
    'провайдеры'  => $изБанка('ПРОВАЙДЕРОВ') . '+ провайдеров',
    'вейджер'     => 'x' . $изБанка('ВЕЙДЖЕР'),
    'герои'       => implode(', ', $rng->sample(array_keys($банки['ИМЯ']), 8)),
    'героини'     => implode(', ', $rng->sample(array_keys($банки['ИМЯЖ']), 4)),
];

if (!is_dir($выход)) { mkdir($выход, 0777, true); }

$шапка = "# Задание на комплект `$набор`\n\n"
    . "Сид $сид. Формат — двенадцать HTML-фрагментов без `<html>/<head>/<body>`,\n"
    . "имя площадки только плейсхолдерами `%brand_name_ru%` и `%brand_name_en%`.\n\n"
    . "## Фактура набора\n\n"
    . "| Что | Значение |\n|---|---|\n"
    . "| Каталог | {$факты['каталог']} |\n"
    . "| Провайдеры | {$факты['провайдеры']} |\n"
    . "| Вейджер | {$факты['вейджер']} |\n"
    . "| Герои историй | {$факты['герои']} |\n"
    . "| Героини | {$факты['героини']} |\n\n"
    . "Фактура держится на весь комплект: каталог и провайдеров нельзя менять от\n"
    . "страницы к странице. Суммы выигрышей, RTP и сроки вывода — наоборот,\n"
    . "свои в каждом разделе; банк наблюдённых значений в `data-v5/pools.json`.\n\n"
    . "## Адреса\n\n"
    . "В корпусе ровно шесть адресов, внешних ссылок нет:\n\n";
foreach ($профиль['ссылки']['адреса_корпуса'] ?? [] as $u => $n) { $шапка .= "* `$u`\n"; }
$шапка .= "\nСтраницы `bonus`, `obzor`, `promo`, `news`, `info`, `partnery` входящих\n"
    . "ссылок не получают — так у доноров, и это воспроизводится.\n\n";
file_put_contents("$выход/zadanie.md", $шапка);

$сводка = [];
foreach (V5_TYPES as $тип) {
    $варианты = [];
    foreach ($блоки['скелеты'][$тип] ?? [] as $подпись => $n) {
        [$голова, , $хвост] = array_map('trim', explode('|', $подпись));
        $классы = array_filter(array_map('trim', array_merge(
            $голова === '' ? [] : explode(' + ', $голова),
            $хвост === '' ? [] : explode(' + ', $хвост))));
        $известны = true;
        foreach ($классы as $k) { if (!isset($блоки['блоки'][$тип][$k])) { $известны = false; break; } }
        if ($известны) { $варианты[$подпись] = $n; }
    }
    $подпись = $rng->weighted($варианты);
    [$головаС, $серёдкаС, $хвостС] = array_map('trim', explode('|', $подпись));
    $сколькоH2 = (int) (preg_match('~H2×(\d+)~u', $серёдкаС, $m) ? $m[1] : 5);

    $пул = $пулы['разделы'][$тип] ?? [];
    $доноров = max(1, $блоки['источник']['наборов'] ?? 12);
    $обяз = []; $прочие = [];
    foreach ($пул as $h2 => $r) {
        if ($r['встреч'] >= $доноров * 0.9) { $обяз[$h2] = $r['встреч']; } else { $прочие[$h2] = $r['встреч']; }
    }
    $выбор = array_slice(array_keys($обяз), 0, $сколькоH2);
    while (count($выбор) < $сколькоH2 && $прочие) {
        $h2 = $rng->weighted($прочие);
        unset($прочие[$h2]);
        $выбор[] = $h2;
    }
    usort($выбор, function ($a, $b) use ($пул) {
        $м = function ($h) use ($пул) { $p = $пул[$h]['позиции'] ?? [0]; sort($p); return $p[intdiv(count($p), 2)]; };
        return $м($a) <=> $м($b);
    });

    $поля = $профиль['страницы'][$тип]['поля'] ?? [];
    $цели = [];
    foreach ($поля as $k => $п) {
        if (!$п['держат']) { continue; }
        if (in_array($k, ['words', 'h2', 'h3_per_h2', 'sections', 'lists', 'paragraphs', 'words_per_para',
                          'strong', 'faq_pairs', 'questions_total', 'numbers_per100', 'nausea_acad',
                          'water', 'brand_ru', 'brand_en', 'emoji', 'anchor_once_pct'], true)) {
            $цели[$k] = $п;
        }
    }

    $т = "# $тип\n\n**Скелет:** `$подпись`\n\n"
       . "Голова и хвост собираются виджетами из библиотеки (`bloki-v5.php`), писать в них\n"
       . "нужно только пары «вопрос-ответ» блока FAQ. Тело — $сколькоH2 разделов.\n\n"
       . "## Разделы\n\n";
    foreach ($выбор as $i => $h2) {
        $r = $пул[$h2];
        $встреч = max(1, $r['встреч']);
        $зачинов = max(1, (int) round(count($r['зачин']) / $встреч));
        $пунктов = max(3, min(9, (int) round(count($r['пункты']) / $встреч)));
        $фраз = $медиана($r['зачинДлины'] ?? [], 3);
        $н = $i + 1;
        $т .= "### $н. $h2\n\n"
            . "* зачин: $зачинов абзаца(ев) по ~$фраз фразы\n"
            . "* один H3, затем список на $пунктов пунктов, затем финальный абзац\n"
            . "* у доноров раздел встречается $встреч раз из $доноров\n\n";
    }
    $т .= "## Цели замера (поля, которые фабрика держит)\n\n| поле | цель | полоса |\n|---|---|---|\n";
    foreach ($цели as $k => $п) {
        $т .= "| `$k` | {$п['цель']} | {$п['полоса'][0]}–{$п['полоса'][1]} |\n";
    }
    $ссылки = $профиль['ссылки']['на_страницу'][$тип] ?? null;
    if ($ссылки) {
        $т .= "\n**Ссылок на странице:** цель {$ссылки['цель']}, полоса {$ссылки['полоса'][0]}–{$ссылки['полоса'][1]}.\n";
    }
    $u = $профиль['уникальность']['по_типам'][$тип] ?? null;
    if ($u) {
        $т .= "\n**Уникальность:** против каждого донора не выше {$u['потолок']} % шинглов\n"
            . "(медиана внутри корпуса {$u['медиана']} %).\n";
    }
    file_put_contents("$выход/$тип.md", $т);
    $сводка[$тип] = ['скелет' => $подпись, 'разделов' => count($выбор)];
}

printf("══ задание %s (сид %d) ══\n", $набор, $сид);
printf("%s, %s, вейджер %s\n\n", $факты['каталог'], $факты['провайдеры'], $факты['вейджер']);
foreach ($сводка as $t => $s) { printf("%-13s %d разделов  %s\n", $t, $s['разделов'], $s['скелет']); }
printf("\nзаписано в %s (zadanie.md + 12 страниц)\n", $выход);
