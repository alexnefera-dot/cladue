<?php
declare(strict_types=1);

/**
 * Приёмка комплекта v5: двенадцать страниц против профиля корпуса.
 *
 *   php engine/priyomka-v5.php <папка> [--корпус=samples/v5-donors] [--json]
 *
 * Три слоя проверки, и они ловят разное:
 *
 *  1. **Постранично** — поля профиля с `держат=true` по правилу коридора
 *     `|наше − цель| ≤ max(0,25·|цель|; пол)`. Порог 95 % полей.
 *  2. **Комплектно** — то, чего в одной странице не видно: сетка ссылок
 *     (у корпуса ровно шесть адресов и ни одного внешнего), плейсхолдеры
 *     бренда, разметка schema.org, незакрытые прорези.
 *  3. **Уникальность** — шинглы против каждого донора и против наших прошлых
 *     наборов. Корпусный потолок — p90 попарных совпадений внутри самого
 *     корпуса: фабрика держит этот уровень, и подниматься выше значит выдать
 *     себя, а опускаться сильно ниже — писать не в жанре.
 *
 *     У набора, собранного `generator-v5.php` из фраз доноров, есть свой пол,
 *     и он выше корпусного: доля каждого из одиннадцати доноров ≈ 100/11 %
 *     плюс общая для всех библиотека блоков ≈ 6 %. Требовать от пересборки
 *     корпусной полосы — значит требовать невозможного, поэтому для наборов
 *     со `способ: сборка` в `nabor.json` порог поднят на 100/доноров, а
 *     корпусный печатается рядом как ориентир. Убрать разрыв может только
 *     переписывание прозы: задание готовит `zadanie-v5.php`.
 */

require_once __DIR__ . '/src/V5Blocks.php';
require_once __DIR__ . '/src/PageMetrics.php';
require_once __DIR__ . '/instrumenty/shingle.php';

$папка = ''; $корпус = 'samples/v5-donors'; $наши = 'samples/v5-final';
$чужие_наборы = 'samples/v5-vhod33,samples/v5-konkurent';
$asJson = in_array('--json', $argv, true);
foreach (array_slice($argv, 1) as $a) {
    if (str_starts_with($a, '--корпус=')) { $корпус = rtrim(substr($a, strlen('--корпус=')), '/'); }
    elseif (str_starts_with($a, '--наши=')) { $наши = rtrim(substr($a, strlen('--наши=')), '/'); }
    elseif (str_starts_with($a, '--чужие=')) { $чужие_наборы = substr($a, strlen('--чужие=')); }
    elseif ($a[0] !== '-') { $папка = rtrim($a, '/'); }
}
if ($папка === '' || !is_dir($папка)) {
    fwrite(STDERR, "usage: php engine/priyomka-v5.php <папка> [--корпус=…] [--json]\n"); exit(1);
}
$профиль = json_decode((string) file_get_contents(__DIR__ . '/data-v5/profil-v5.json'), true);
if (!$профиль) { fwrite(STDERR, "нет data-v5/profil-v5.json\n"); exit(1); }
$паспорт = is_file("$папка/nabor.json")
    ? json_decode((string) file_get_contents("$папка/nabor.json"), true) : [];
$сборка = ($паспорт['способ'] ?? '') === 'сборка';
$надбавка = $сборка ? 100 / max(1, (int) ($профиль['источник']['в_расчёте'] ?? 11)) : 0.0;

function v5Pochinit(string $h): string { return preg_replace('~<(?![a-zA-Z/!?])~', '&lt;', $h); }

$a = new Analyzer();
$итог = ['набор' => basename($папка), 'страницы' => [], 'комплект' => [], 'уникальность' => []];
$всеHtml = [];

// ── 1. постранично ──────────────────────────────────────────────────
foreach (V5_TYPES as $тип) {
    $f = "$папка/$тип.html";
    if (!is_file($f)) { $итог['страницы'][$тип] = ['нет файла' => true]; continue; }
    $html = (string) file_get_contents($f);
    $всеHtml[$тип] = $html;
    $карта = PageMetrics::measure($a, $тип, v5Pochinit($html),
        ['ru' => '%brand_name_ru%', 'en' => '%brand_name_en%']);
    // «вы»-набор меряется по своей подгруппе корпуса: требовать от него
    // нулевого «вы» значит требовать того, чего у образцов этого регистра нет.
    $поля = v5PoliaObrashcheniya($профиль['страницы'][$тип]['поля'] ?? [],
                                 $профиль, $тип, $паспорт['обращение'] ?? 'ты', $карта);
    $всего = 0; $сошлось = 0; $мимо = [];
    foreach ($поля as $k => $п) {
        if (!$п['держат']) { continue; }
        if (!isset($карта[$k]) || !is_numeric($карта[$k])) { continue; }
        $всего++;
        $наше = (float) $карта[$k]; $цель = (float) $п['цель'];
        $пол = $п['дробное'] ? 0.8 : 2.0;
        if (abs($наше - $цель) <= max(0.25 * abs($цель), $пол)) { $сошлось++; }
        else { $мимо[$k] = [round($наше, 1), $цель]; }
    }
    $итог['страницы'][$тип] = [
        'сошлось' => $сошлось, 'из' => $всего,
        'процент' => $всего ? round($сошлось / $всего * 100) : 0,
        'мимо' => $мимо,
    ];
}

// ── 2. комплектные ворота ───────────────────────────────────────────
$адресаКорпуса = array_keys($профиль['ссылки']['адреса_корпуса'] ?? []);
$ссылки = []; $чужие = []; $прорези = []; $схема = [];
foreach ($всеHtml as $тип => $html) {
    preg_match_all('~href="([^"]*)"~', $html, $m);
    $ссылки[$тип] = 0;
    foreach ($m[1] as $u) {
        if (str_starts_with($u, '#')) { continue; }
        $ссылки[$тип]++;
        if (!in_array($u, $адресаКорпуса, true)) { $чужие[$u] = ($чужие[$u] ?? 0) + 1; }
    }
    // Цифра в имени прорези обязана ловиться: незаполненный `{RTP2}` уехал в
    // выдачу именно потому, что счётчик её не видел.
    if (preg_match_all('~\{[А-ЯA-Z][А-ЯA-Z0-9]*(?::[а-я]{1,2})?\}~u', $html, $m2)) {
        foreach ($m2[0] as $x) { $прорези[$x] = ($прорези[$x] ?? 0) + 1; }
    }
    if (preg_match_all('~itemtype="https://schema\.org/(\w+)"~', $html, $m3)) {
        foreach ($m3[1] as $x) { $схема[$x] = ($схема[$x] ?? 0) + 1; }
    }
}
$ссылкиМимо = [];
foreach ($профиль['ссылки']['на_страницу'] ?? [] as $тип => $п) {
    if (!isset($ссылки[$тип])) { continue; }
    [$низ, $верх] = $п['полоса'];
    if ($ссылки[$тип] < $низ || $ссылки[$тип] > $верх) { $ссылкиМимо[$тип] = [$ссылки[$тип], $п['полоса']]; }
}
$брендRu = 0;
foreach ($всеHtml as $html) { $брендRu += substr_count($html, '%brand_name_ru%'); }
$итог['комплект'] = [
    'страниц'        => count($всеHtml),
    'ссылок'         => array_sum($ссылки),
    'ссылки_мимо'    => $ссылкиМимо,
    'чужие_адреса'   => $чужие,
    'открытые_прорези' => $прорези,
    'бренд_ru'       => $брендRu,
    'schema'         => $схема,
];

// ── 3. уникальность ─────────────────────────────────────────────────
// Чужие корпуса тоже соседи: с тех пор как проза NEW33 попала в пулы
// (`sbor-new33.php`), набор может совпасть не только с донором и нашим
// прошлым комплектом, но и с той страницей, откуда фраза пришла. Рядом
// лежат свежие тексты конкурента (`samples/v5-konkurent`): с ними мы
// не пересекались по прозе, но пересекаемся по донорам, и совпадение
// там ловится тем же порогом. Корней может быть несколько, через запятую.
$соседи = [];
$чужие_корни = array_filter(array_map(
    static fn (string $x): string => rtrim(trim($x), '/'),
    explode(',', $чужие_наборы)
));
foreach (array_merge([$корпус, $наши], $чужие_корни) as $где) {
    if ($где === '' || !is_dir($где)) { continue; }
    foreach (glob("$где/*", GLOB_ONLYDIR) ?: [] as $d) {
        // Корпус бывает двухуровневым: samples/v5-vhod33/nodate/arkada.
        $вложенные = is_file("$d/main.html") ? [$d] : (glob("$d/*", GLOB_ONLYDIR) ?: []);
        foreach ($вложенные as $к) {
            if (realpath($к) === realpath($папка)) { continue; }
            $соседи[basename($где) . '/' . basename(dirname($к)) . '/' . basename($к)]
                = ['путь' => $к, 'чужой' => in_array($где, $чужие_корни, true)];
        }
    }
}
foreach ($всеHtml as $тип => $html) {
    $наш = shingles(chist($html));
    $корпусный = (float) ($профиль['уникальность']['по_типам'][$тип]['потолок'] ?? 12.0);
    $потолок = round($корпусный + $надбавка, 1);
    $худший = ['—', 0.0];
    foreach ($соседи as $имя => $сосед) {
        $f = $сосед['путь'] . "/$тип.html";
        if (!is_file($f)) { continue; }
        $их = shingles(chist((string) file_get_contents($f)));
        if (!$их || !$наш) { continue; }
        $общих = count(array_intersect_key($наш, $их));
        if (count($их) >= 600) {
            $p = $общих / min(count($наш), count($их)) * 100;
        } elseif ($сосед['чужой']) {
            // Обрубок: у чужих корпусов пятая часть страниц короче 600
            // шинглов, и доля от меньшей на них врёт — любая наша страница
            // даёт против сотни слов 25–40 % на пустом месте. Считаем долю
            // от нашей страницы: столько нашего текста реально совпало.
            // Настоящее заимствование короткой страницы так тоже видно.
            $p = $общих / count($наш) * 100;
        } else {
            // У доноров и у нас страница ниже 1200 шинглов не опускается
            // ни разу, так что сюда попадают только битые файлы.
            continue;
        }
        if ($p > $худший[1]) { $худший = [$имя, round($p, 1)]; }
    }
    $итог['уникальность'][$тип] = ['худший' => $худший[0], 'процент' => $худший[1],
                                   'потолок' => $потолок, 'корпусный' => $корпусный,
                                   'прошло' => $худший[1] <= $потолок];
}

// ── вывод ───────────────────────────────────────────────────────────
if ($asJson) { echo json_encode($итог, JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT), "\n"; exit(0); }

printf("══ приёмка v5: %s ══\n\n", $итог['набор']);
$провалов = 0;
foreach ($итог['страницы'] as $тип => $s) {
    if (isset($s['нет файла'])) { printf("%-14s НЕТ ФАЙЛА\n", $тип); $провалов++; continue; }
    $знак = $s['процент'] >= 95 ? '✓' : '✗';
    if ($s['процент'] < 95) { $провалов++; }
    printf("%s %-12s %2d/%-2d %3d%%", $знак, $тип, $s['сошлось'], $s['из'], $s['процент']);
    $хвост = [];
    foreach (array_slice($s['мимо'], 0, 4, true) as $k => [$наше, $цель]) { $хвост[] = "$k {$наше}→{$цель}"; }
    echo $хвост ? '  — ' . implode(', ', $хвост) : '';
    echo "\n";
}
$k = $итог['комплект'];
printf("\nкомплект: страниц %d, ссылок %d, бренд-ru %d, схем %d типов\n",
    $k['страниц'], $k['ссылок'], $k['бренд_ru'], count($k['schema']));
if ($k['чужие_адреса']) {
    printf("✗ чужие адреса: %s\n", implode(', ', array_keys($k['чужие_адреса']))); $провалов++;
}
if ($k['открытые_прорези']) {
    printf("✗ незакрытые прорези: %s\n", implode(', ', array_keys($k['открытые_прорези']))); $провалов++;
}
if ($k['ссылки_мимо']) {
    foreach ($k['ссылки_мимо'] as $тип => [$наше, $полоса]) {
        printf("· ссылок на %s: %d, полоса корпуса %d–%d\n", $тип, $наше, $полоса[0], $полоса[1]);
    }
}
printf("\nуникальность (шинглы против доноров и наших наборов)%s:\n",
    $сборка ? ', режим сборки' : '');
foreach ($итог['уникальность'] as $тип => $u) {
    printf("%s %-12s %5.1f%%  порог %5.1f  корпус %4.1f — ближайший %s\n",
        $u['прошло'] ? '✓' : '✗', $тип, $u['процент'], $u['потолок'], $u['корпусный'], $u['худший']);
    if (!$u['прошло']) { $провалов++; }
}
if ($сборка) {
    echo "порог сборки = корпусный + 100/доноров: ниже своей доли пересборка не\n"
       . "опускается. Корпусную полосу даёт написание прозы по zadanie-v5.php.\n";
}
printf("\n%s\n", $провалов === 0 ? '✓ приёмка пройдена' : "✗ провалов: $провалов");
exit($провалов === 0 ? 0 : 1);
