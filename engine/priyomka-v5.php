<?php
declare(strict_types=1);

/**
 * Приёмка комплекта v5: двенадцать страниц против профиля корпуса.
 *
 *   php engine/priyomka-v5.php <папка> [--корпус=samples/v5-donors] [--json]
 *
 * Три слоя проверки, и они ловят разное:
 *
 *  1. **Постранично** — поля профиля с `держат=true` по правилу коридора
 *     `|наше − цель| ≤ max(0,25·|цель|; пол)`. Порог 95 % полей.
 *  2. **Комплектно** — то, чего в одной странице не видно: сетка ссылок
 *     (у корпуса ровно шесть адресов и ни одного внешнего), плейсхолдеры
 *     бренда, разметка schema.org, незакрытые прорези.
 *  3. **Уникальность** — шинглы против каждого донора и против наших прошлых
 *     наборов. Корпусный потолок — p90 попарных совпадений внутри самого
 *     корпуса: фабрика держит этот уровень, и подниматься выше значит выдать
 *     себя, а опускаться сильно ниже — писать не в жанре.
 *
 *     У набора, собранного `generator-v5.php` из фраз доноров, есть свой пол,
 *     и он выше корпусного: доля каждого из одиннадцати доноров ≈ 100/11 %
 *     плюс общая для всех библиотека блоков ≈ 6 %. Требовать от пересборки
 *     корпусной полосы — значит требовать невозможного, поэтому для наборов
 *     со `способ: сборка` в `nabor.json` порог поднят на 100/доноров, а
 *     корпусный печатается рядом как ориентир. Убрать разрыв может только
 *     переписывание прозы: задание готовит `zadanie-v5.php`.
 */

require_once __DIR__ . '/src/V5Blocks.php';
require_once __DIR__ . '/src/PageMetrics.php';
require_once __DIR__ . '/instrumenty/shingle.php';

$папка = ''; $корпус = 'samples/v5-donors'; $наши = 'samples/v5-final';
$чужие_наборы = 'samples/v5-vhod33,samples/v5-konkurent';
$asJson = in_array('--json', $argv, true);
foreach (array_slice($argv, 1) as $a) {
    if (str_starts_with($a, '--корпус=')) { $корпус = rtrim(substr($a, strlen('--корпус=')), '/'); }
    elseif (str_starts_with($a, '--наши=')) { $наши = rtrim(substr($a, strlen('--наши=')), '/'); }
    elseif (str_starts_with($a, '--чужие=')) { $чужие_наборы = substr($a, strlen('--чужие=')); }
    elseif ($a[0] !== '-') { $папка = rtrim($a, '/'); }
}
if ($папка === '' || !is_dir($папка)) {
    fwrite(STDERR, "usage: php engine/priyomka-v5.php <папка> [--корпус=…] [--json]\n"); exit(1);
}
$профиль = json_decode((string) file_get_contents(__DIR__ . '/data-v5/profil-v5.json'), true);
if (!$профиль) { fwrite(STDERR, "нет data-v5/profil-v5.json\n"); exit(1); }
$паспорт = is_file("$папка/nabor.json")
    ? json_decode((string) file_get_contents("$папка/nabor.json"), true) : [];
$сборка = ($паспорт['способ'] ?? '') === 'сборка';
$сид = (int) ($паспорт['сид'] ?? 0);
// Манера с именем бренда берётся только из паспорта. Набор, собранный до
// появления манер, густым не считается, даже если его сид попадает в густую
// долю: его двенадцать страниц написаны по обычной полосе, и судить их
// густыми воротами — значит задним числом провалить сданное.
$густой = !empty($паспорт['густой']);
// Длины густой манеры, снятые с 18 густых наборов NEW100 нашей же меркой.
const V5_GUSTYE_DLINY = [
    'main' => ['paragraphs' => 23, 'words_per_para' => 18.3, 'para_short' => 11, 'para_spread' => 10.9, 'words' => 943, 'sections' => 17],
    'bonus' => ['paragraphs' => 20, 'words_per_para' => 17.5, 'para_short' => 12, 'para_spread' => 8.9, 'words' => 557, 'sections' => 8],
    'registracia' => ['paragraphs' => 20, 'words_per_para' => 15.1, 'para_short' => 12, 'para_spread' => 6.2, 'words' => 639, 'sections' => 9],
    'vhod' => ['paragraphs' => 22, 'words_per_para' => 17.9, 'para_short' => 11, 'para_spread' => 8.6, 'words' => 752, 'sections' => 11],
    'zerkalo' => ['paragraphs' => 23, 'words_per_para' => 16.8, 'para_short' => 14, 'para_spread' => 8.6, 'words' => 544, 'sections' => 11],
    'app' => ['paragraphs' => 34, 'words_per_para' => 17.6, 'para_short' => 20, 'para_spread' => 12.4, 'words' => 809, 'sections' => 17],
];
const V5_BREND_POLIA = ['brand_ru', 'brand_en', 'brand_in_h', 'brand_first_third'];
$надбавка = $сборка ? 100 / max(1, (int) ($профиль['источник']['в_расчёте'] ?? 11)) : 0.0;

function v5Pochinit(string $h): string { return preg_replace('~<(?![a-zA-Z/!?])~', '&lt;', $h); }

$a = new Analyzer();
$итог = ['набор' => basename($папка), 'страницы' => [], 'комплект' => [], 'уникальность' => []];
$всеHtml = [];
$брендМимо = [];

// ── 1. постранично ──────────────────────────────────────────────────
foreach (V5_TYPES as $тип) {
    $f = "$папка/$тип.html";
    if (!is_file($f)) { $итог['страницы'][$тип] = ['нет файла' => true]; continue; }
    $html = (string) file_get_contents($f);
    $всеHtml[$тип] = $html;
    $карта = PageMetrics::measure($a, $тип, v5Pochinit($html),
        ['ru' => '%brand_name_ru%', 'en' => '%brand_name_en%']);
    // «вы»-набор меряется по своей подгруппе корпуса: требовать от него
    // нулевого «вы» значит требовать того, чего у образцов этого регистра нет.
    $поля = v5PoliaObrashcheniya($профиль['страницы'][$тип]['поля'] ?? [],
                                 $профиль, $тип, $паспорт['обращение'] ?? 'ты', $карта, $сид);
    $всего = 0; $сошлось = 0; $мимо = [];
    foreach ($поля as $k => $п) {
        if (!$п['держат']) { continue; }
        // Полосы бренда сняты с двенадцати доноров, и все они обычной манеры:
        // ноль имени на slots, promo и bonus. У густого набора имя стоит на
        // каждой странице — его бренд судят отдельные ворота ниже.
        if ($густой && in_array($k, V5_BREND_POLIA, true)) { continue; }
        // Длины густого набора судим по густому корпусу: полосы профиля сняты
        // с обычных доноров, где абзац 47 слов, а у густых страниц он 15–18 на
        // main, bonus, registracia, vhod, zerkalo и app.
        if ($густой && isset(V5_GUSTYE_DLINY[$тип][$k])) {
            $всего++;
            $цельГ = (float) V5_GUSTYE_DLINY[$тип][$k];
            if (abs((float) $карта[$k] - $цельГ) <= max(0.3 * $цельГ, 2.0)) { $сошлось++; }
            else { $мимо[$k] = [round((float) $карта[$k], 1), $цельГ]; }
            continue;
        }
        if (!isset($карта[$k]) || !is_numeric($карта[$k])) { continue; }
        $всего++;
        $наше = (float) $карта[$k];
        // Цель своя у каждого набора: она разыграна внутри корпусной полосы,
        // и приёмка обязана считать ровно ту же, что считали генератор и
        // перекрут, — иначе набор проверяется не по тому, к чему его вели.
        // Ширина коридора остаётся корпусной: она свойство метрики, а не
        // этого набора, и профиль строился по ней же.
        // Замороженная цель из паспорта — главная; расчёт остаётся только для
        // наборов, собранных до заморозки.
        $цель = isset($паспорт['цели'][$тип][$k])
            ? (float) $паспорт['цели'][$тип][$k]
            : v5CelNabora($п, $сид, $k);
        $пол = $п['дробное'] ? 0.8 : 2.0;
        if (abs($наше - $цель) <= max(0.25 * abs((float) $п['цель']), $пол)) { $сошлось++; }
        else { $мимо[$k] = [round($наше, 1), $цель]; }
    }
    // Ворота густой манеры: имя стоит на каждой странице, но не гуще, чем у
    // самых плотных чужих (17.22 на 1000 слов на главной — потолок корпуса).
    if ($густой) {
        $имени = (int) ($карта['brand_ru'] ?? 0) + (int) ($карта['brand_en'] ?? 0);
        $плотность = $имени * 1000 / max(1, (int) ($карта['words'] ?? 1));
        if ($имени < 2) { $брендМимо[$тип] = "имени $имени"; }
        elseif ($плотность > 17.0) { $брендМимо[$тип] = sprintf('%.1f на 1000 слов', $плотность); }
    }
    $итог['страницы'][$тип] = [
        'сошлось' => $сошлось, 'из' => $всего,
        'процент' => $всего ? round($сошлось / $всего * 100) : 0,
        'мимо' => $мимо,
    ];
}

// ── 2. комплектные ворота ───────────────────────────────────────────
$адресаКорпуса = array_keys($профиль['ссылки']['адреса_корпуса'] ?? []);
$ссылки = []; $чужие = []; $прорези = []; $схема = [];
foreach ($всеHtml as $тип => $html) {
    preg_match_all('~href="([^"]*)"~', $html, $m);
    $ссылки[$тип] = 0;
    foreach ($m[1] as $u) {
        if (str_starts_with($u, '#')) { continue; }
        $ссылки[$тип]++;
        if (!in_array($u, $адресаКорпуса, true)) { $чужие[$u] = ($чужие[$u] ?? 0) + 1; }
    }
    // Цифра в имени прорези обязана ловиться: незаполненный `{RTP2}` уехал в
    // выдачу именно потому, что счётчик её не видел.
    if (preg_match_all('~\{[А-ЯA-Z][А-ЯA-Z0-9]*(?::[а-я]{1,2})?\}~u', $html, $m2)) {
        foreach ($m2[0] as $x) { $прорези[$x] = ($прорези[$x] ?? 0) + 1; }
    }
    if (preg_match_all('~itemtype="https://schema\.org/(\w+)"~', $html, $m3)) {
        foreach ($m3[1] as $x) { $схема[$x] = ($схема[$x] ?? 0) + 1; }
    }
}
// Повелительное после подчинительного союза: «до того, как зарегистрируйся».
// Пришло не из сборки, а из самих записей пула — анкор написан призывом там,
// где придаточное требует изъявительного или инфинитива. Читается как сбой
// грамматики, так что запись должна падать на приёмке, а не уезжать в выдачу.
// Имена героев банка — по ним опознаётся рассказ в прошедшем времени.
const V5_IMENA_GEROEV = 'Алексей|Андрей|Антон|Артём|Борис|Вадим|Валентин|Василий|Виктор|Виталий'
    . '|Владимир|Вячеслав|Геннадий|Георгий|Григорий|Даниил|Денис|Дмитрий|Евгений|Егор|Иван|Игорь'
    . '|Илья|Кирилл|Константин|Леонид|Максим|Марк|Михаил|Никита|Николай|Олег|Павел|Пётр|Роман'
    . '|Руслан|Сергей|Станислав|Степан|Тимур|Фёдор|Юрий|Ярослав|Анна|Алина|Виктория|Дарья'
    . '|Екатерина|Елена|Ирина|Ксения|Марина|Мария|Наталья|Ольга|Светлана|Татьяна|Юлия';
$повелительные = [];
$импер = 'зарегистрируй(?:ся|тесь)|заходи(?:те)?|играй(?:те)?|проверь(?:те)?|смотри(?:те)?'
    . '|читай(?:те)?|выбирай(?:те)?|жми(?:те)?|начни(?:те)?|бери(?:те)?|пробуй(?:те)?'
    . '|скачай(?:те)?|войди(?:те)?|войдите|открой(?:те)?|забери(?:те)?|активируй(?:те)?';
foreach ($всеHtml as $тип => $html) {
    $плоский = preg_replace('~\s+~u', ' ', strip_tags($html));
    if (preg_match_all('~(до того,?\s+как|после того,?\s+как|перед тем,?\s+как|прежде чем)\s+('
        . $импер . ')\b~ui', $плоский, $mи, PREG_SET_ORDER)) {
        foreach ($mи as $x) { $повелительные[] = "$тип: {$x[1]} {$x[2]}"; }
    }
    // Повелительное внутри рассказа о герое: «Валентин зашёл без драмы:
    // сначала зарегистрируйся, потом открыл пару слотов». Предложение о
    // герое ведётся в прошедшем, и анкор-императив ломает в нём время.
    // Признак — имя в начале предложения и глагол прошедшего рядом.
    // Заголовок склеивается с первым предложением абзаца, поэтому имя ищем
    // не в начале, а где угодно: важно, что сразу за ним идёт прошедшее.
    $прош = 'зашёл|зашла|получил\w*|открыл\w*|закинул\w*|поднял\w*|вывел\w*|отыграл\w*'
          . '|начал\w*|крутил\w*|прочитал\w*|нажал\w*|внёс|взял\w*|успел\w*|пошёл|ушёл|сел';
    foreach (preg_split('~(?<=[.!?])\s+~u', $плоский) as $пр) {
        if (!preg_match('~\b(' . V5_IMENA_GEROEV . ')\b[^.!?]{0,40}?\b(?:' . $прош . ')\b~u', $пр, $mн)) { continue; }
        $хвост = mb_substr($пр, (int) mb_strpos($пр, $mн[0]));
        if (preg_match('~\b(' . $импер . ')\b~ui', $хвост)) {
            $повелительные[] = "$тип (рассказ о герое): " . mb_substr(trim($хвост), 0, 90);
        }
    }
}

// Анкор не в том падеже, которого требует управление: «через войти в
// аккаунт», «что в обзор бонусной программы», «следи за новости о слотах».
// Замер до правки: 53 сбоя на десять наборов. Проход `v5AnkorPoPadezhu`
// их снимает, а проверка стоит здесь, чтобы новая запись пула не завела
// новую рамку молча.
$падежи = [];
$анкИнф = 'войти|играть|зарегистрироваться|скачать|проверить|смотреть|читать|открыть|забрать|активировать|пройти';
$падежПравила = [
    'предлог + инфинитив' => '~\b(?:в|во|на|о|об|при|по|через|из|от|до|с|со|за|для|к|у)\s+<a\b[^>]*>\s*(?:'
        . $анкИнф . ')\b~ui',
    'следить за + им.п.'  => '~\b(?:следи\w*|следить|следят)\s+за\s+<a\b[^>]*>\s*(?:новости|акции|бонусы|условия)\b~ui',
    'с + им.п.'           => '~\b(?:рядом\s+с|с)\s+<a\b[^>]*>\s*(?:новости|акции|бонусы)\b~ui',
    'из + им.п.'          => '~\bиз\s+<a\b[^>]*>\s*(?:новости|акции|бонусы)\b~ui',
    'местный падеж'       => '~\b(?:написан\w*|указан\w*|сказан\w*|стои\w+|виде?шь|видно|лежа\w+|собран\w*'
        . '|публику\w+|прописан\w*|расписан\w*|что)\s+(?:в|на)\s+<a\b[^>]*>\s*'
        . '(?:обзор|вход|каталог|раздел|информаци[юя]|новости)\b~ui',
    // «в разделе новости о слотах» — падеж диктует «раздел», а не предлог,
    // и ни одно правило управления эту рамку не ловило: 38 случаев на партию.
    'в разделе + им.п.'   => '~\bв\s+раздел(?:е|ах)\s+<a\b[^>]*>\s*'
        . '(?:новости|акции|бонусы|промокоды|слоты|информация)\b~ui',
    // «они в информацию о казино» — без глагола движения «в» требует
    // предложного. Направление («зайди в регистрацию») правилом не задето.
    // Список глаголов движения тот же, что в `v5AnkorPoPadezhu`: иначе приёмка
    // ругается на то, что проход сознательно оставил винительным.
    'в + вин.п. без движения' => '~(?<!\p{L})(?:зайди|зайти|заходи|заходить|перейти|перейди|переходи'
        . '|идти|идёт|идет|попасть|попади|вернуться|вернись|войти|войди|ныряй|жми|нажми|нажать)\s+(?:в|на)\s+'
        . '<a\b[^>]*>(*SKIP)(*FAIL)|\b(?:в|на)\s+<a\b[^>]*>\s*(?:информацию|регистрацию)\b~ui',
];
foreach ($всеHtml as $тип => $html) {
    foreach ($падежПравила as $имя => $рег) {
        if (preg_match_all($рег, $html, $mп)) {
            foreach ($mп[0] as $x) {
                $падежи[] = "$тип ($имя): " . trim(preg_replace('~\s+~u', ' ', strip_tags($x)));
            }
        }
    }
}

$ссылкиМимо = [];
foreach ($профиль['ссылки']['на_страницу'] ?? [] as $тип => $п) {
    if (!isset($ссылки[$тип])) { continue; }
    // Густая манера — свой формат: у их густых страниц 12.1 ссылки медианой
    // (полоса 11.4–16.8) против 44.8 у обычных, и полосы профиля тут не судьи.
    [$низ, $верх] = $густой ? [9, 20] : $п['полоса'];
    if ($ссылки[$тип] < $низ || $ссылки[$тип] > $верх) { $ссылкиМимо[$тип] = [$ссылки[$тип], $п['полоса']]; }
}
$брендRu = 0;
foreach ($всеHtml as $html) { $брендRu += substr_count($html, '%brand_name_ru%'); }
$вложенные = 0;
foreach ($всеHtml as $html) { $вложенные += preg_match_all('~<a\b[^>]*>[^<]*<a\b~su', $html); }
$итог['комплект'] = [
    'вложенные_ссылки' => $вложенные,
    'манера'         => $густой ? 'густая' : 'обычная',
    'бренд_мимо'     => $брендМимо,
    'страниц'        => count($всеHtml),
    'ссылок'         => array_sum($ссылки),
    'ссылки_мимо'    => $ссылкиМимо,
    'чужие_адреса'   => $чужие,
    'открытые_прорези' => $прорези,
    'повелительные'  => $повелительные,
    'падежи'         => $падежи,
    'бренд_ru'       => $брендRu,
    'schema'         => $схема,
];

// ── 3. уникальность ─────────────────────────────────────────────────
// Чужие корпуса тоже соседи: с тех пор как проза NEW33 попала в пулы
// (`sbor-new33.php`), набор может совпасть не только с донором и нашим
// прошлым комплектом, но и с той страницей, откуда фраза пришла. Рядом
// лежат свежие тексты конкурента (`samples/v5-konkurent`): с ними мы
// не пересекались по прозе, но пересекаемся по донорам, и совпадение
// там ловится тем же порогом. Корней может быть несколько, через запятую.
$соседи = [];
$чужие_корни = array_filter(array_map(
    static fn (string $x): string => rtrim(trim($x), '/'),
    explode(',', $чужие_наборы)
));
foreach (array_merge([$корпус, $наши], $чужие_корни) as $где) {
    if ($где === '' || !is_dir($где)) { continue; }
    foreach (glob("$где/*", GLOB_ONLYDIR) ?: [] as $d) {
        // Корпус бывает двухуровневым: samples/v5-vhod33/nodate/arkada.
        $вложенные = is_file("$d/main.html") ? [$d] : (glob("$d/*", GLOB_ONLYDIR) ?: []);
        foreach ($вложенные as $к) {
            if (realpath($к) === realpath($папка)) { continue; }
            $соседи[basename($где) . '/' . basename(dirname($к)) . '/' . basename($к)]
                = ['путь' => $к, 'чужой' => in_array($где, $чужие_корни, true)];
        }
    }
}
foreach ($всеHtml as $тип => $html) {
    $наш = shingles(chist($html));
    $корпусный = (float) ($профиль['уникальность']['по_типам'][$тип]['потолок'] ?? 12.0);
    // Корпусный потолок bonus — 2.3 при 8.3–18.7 у остальных типов: у доноров
    // страницы бонусов почти не пересекаются между собой, а наши собраны из
    // их же фраз и против своих наборов дают те же 10–13 %, что и другие
    // типы (12–17 %). В режиме сборки выброс поднимаем до минимума остальных
    // типов, иначе bonus валил каждый сид при ста своих наборах рядом.
    if ($сборка) {
        $остальные = array_values(array_filter(array_map(
            static fn (array $u): float => (float) ($u['потолок'] ?? 0),
            array_diff_key($профиль['уникальность']['по_типам'] ?? [], [$тип => 1])
        ), static fn (float $x): bool => $x > 0));
        if ($остальные && $корпусный < min($остальные)) { $корпусный = min($остальные); }
    }
    $потолок = round($корпусный + $надбавка, 1);
    $худший = ['—', 0.0];
    foreach ($соседи as $имя => $сосед) {
        $f = $сосед['путь'] . "/$тип.html";
        if (!is_file($f)) { continue; }
        $их = shingles(chist((string) file_get_contents($f)));
        if (!$их || !$наш) { continue; }
        $общих = count(array_intersect_key($наш, $их));
        if (count($их) >= 600) {
            $p = $общих / min(count($наш), count($их)) * 100;
        } elseif ($сосед['чужой']) {
            // Обрубок: у чужих корпусов пятая часть страниц короче 600
            // шинглов, и доля от меньшей на них врёт — любая наша страница
            // даёт против сотни слов 25–40 % на пустом месте. Считаем долю
            // от нашей страницы: столько нашего текста реально совпало.
            // Настоящее заимствование короткой страницы так тоже видно.
            $p = $общих / count($наш) * 100;
        } else {
            // У доноров и у нас страница ниже 1200 шинглов не опускается
            // ни разу, так что сюда попадают только битые файлы.
            continue;
        }
        if ($p > $худший[1]) { $худший = [$имя, round($p, 1)]; }
    }
    $итог['уникальность'][$тип] = ['худший' => $худший[0], 'процент' => $худший[1],
                                   'потолок' => $потолок, 'корпусный' => $корпусный,
                                   'прошло' => $худший[1] <= $потолок];
}

// ── вывод ───────────────────────────────────────────────────────────
if ($asJson) { echo json_encode($итог, JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT), "\n"; exit(0); }

printf("══ приёмка v5: %s ══\n\n", $итог['набор']);
$провалов = 0;
foreach ($итог['страницы'] as $тип => $s) {
    if (isset($s['нет файла'])) { printf("%-14s НЕТ ФАЙЛА\n", $тип); $провалов++; continue; }
    $знак = $s['процент'] >= 95 ? '✓' : '✗';
    if ($s['процент'] < 95) { $провалов++; }
    printf("%s %-12s %2d/%-2d %3d%%", $знак, $тип, $s['сошлось'], $s['из'], $s['процент']);
    $хвост = [];
    foreach (array_slice($s['мимо'], 0, 4, true) as $k => [$наше, $цель]) { $хвост[] = "$k {$наше}→{$цель}"; }
    echo $хвост ? '  — ' . implode(', ', $хвост) : '';
    echo "\n";
}
$k = $итог['комплект'];
printf("\nкомплект: страниц %d, ссылок %d, бренд-ru %d, схем %d типов\n",
    $k['страниц'], $k['ссылок'], $k['бренд_ru'], count($k['schema']));
if ($k['чужие_адреса']) {
    printf("✗ чужие адреса: %s\n", implode(', ', array_keys($k['чужие_адреса']))); $провалов++;
}
if ($k['открытые_прорези']) {
    printf("✗ незакрытые прорези: %s\n", implode(', ', array_keys($k['открытые_прорези']))); $провалов++;
}
if ($k['повелительные']) {
    printf("✗ повелительное после союза: %s\n", implode('; ', $k['повелительные'])); $провалов++;
}
if ($k['падежи']) {
    printf("✗ анкор не в падеже управления: %s\n", implode('; ', array_slice($k['падежи'], 0, 5))); $провалов++;
}
if ($k['вложенные_ссылки']) {
    printf("✗ вложенные ссылки: %d\n", $k['вложенные_ссылки']);
    $провалов++;
}
if ($k['бренд_мимо']) {
    foreach ($k['бренд_мимо'] as $тип => $почему) {
        printf("✗ густой набор, бренд на %s: %s\n", $тип, $почему);
    }
    $провалов++;
}
if ($k['ссылки_мимо']) {
    // Было предупреждением с точкой — и одиннадцать типов страниц из
    // двенадцати ехали ниже полосы шесть сотен наборов подряд. Ссылки несут
    // ключевые анкоры, недобор ссылок это недобор ключей.
    foreach ($k['ссылки_мимо'] as $тип => [$наше, $полоса]) {
        printf("✗ ссылок на %s: %d, полоса корпуса %d–%d\n", $тип, $наше, $полоса[0], $полоса[1]);
    }
    $провалов++;
}
printf("\nуникальность (шинглы против доноров и наших наборов)%s:\n",
    $сборка ? ', режим сборки' : '');
foreach ($итог['уникальность'] as $тип => $u) {
    printf("%s %-12s %5.1f%%  порог %5.1f  корпус %4.1f — ближайший %s\n",
        $u['прошло'] ? '✓' : '✗', $тип, $u['процент'], $u['потолок'], $u['корпусный'], $u['худший']);
    if (!$u['прошло']) { $провалов++; }
}
