<?php
declare(strict_types=1);
/**
 * Карточка стиля образца: постранично снимаем то, чем он отличается от
 * донорского профиля, и пишем markdown-карточку рядом с промптом. Движок не
 * трогаем — карточка просто перекрывает часть целей промпта для реалайзера.
 *
 *   php oldstyle-card.php <папка-со-старым-набором> <куда-положить-карточки>
 */
require_once __DIR__ . '/src/PageMetrics.php';

$BRAND = ['ru' => '', 'en' => ''];
foreach (array_slice($argv, 1) as $a) {
    if (preg_match('~^--brand-ru=(.*)$~u', $a, $m)) { $BRAND['ru'] = $m[1]; }
    if (preg_match('~^--brand-en=(.*)$~u', $a, $m)) { $BRAND['en'] = $m[1]; }
}
$args = array_values(array_filter(array_slice($argv, 1),
    fn($a) => $a !== '--no-signals' && !str_starts_with($a, '--brand-')));
$SIGNALS = !in_array('--no-signals', $argv, true);   // блок сигналов можно отключить,
                                                     // чтобы воспроизвести прежний способ
$SRC = $args[0] ?? '/tmp/old-bez-zachina/svyazka3';
$OUT = $args[1] ?? '/tmp/oldstyle-cards';
@mkdir($OUT, 0777, true);

$a = new Analyzer();
foreach (glob("$SRC/*.html") as $f) {
    // $BRAND и $SIGNALS — из глобальной области, скрипт однопроходный
    $t = pathinfo($f, PATHINFO_FILENAME);
    $raw = (string) file_get_contents($f);
    $norm = NicheLexicon::unplaceholder($raw);
    $r = $a->run([['name' => $t, 'url' => "/$t", 'html' => $norm, 'keyword' => '', 'lsi' => []]]);
    $m = $r['pages'][0]['metrics']; $s = $r['pages'][0]['stylistics'];

    preg_match_all('~<p\b[^>]*>(.*?)</p>~is', $raw, $pm);
    $ps = array_values(array_filter(
        array_map(fn($x) => trim(preg_replace('~\s+~u', ' ', strip_tags($x))), $pm[1] ?? []),
        fn($x) => mb_strlen($x) > 40
    ));
    $wp = 0;
    foreach ($ps as $x) { $wp += count(preg_split('~\s+~u', NicheLexicon::unplaceholder($x), -1, PREG_SPLIT_NO_EMPTY)); }

    $prose  = NicheLexicon::prose($norm);

    // Сигналы, которых нет в основной линейке. Разбор двух удачных наборов
    // показал, что при совпадении всех привычных параметров расходятся именно
    // они: как устроен заголовок, продаёт ли текст, называет ли он минус.
    $flat = trim(preg_replace('~\s+~u', ' ', strip_tags($norm)));
    $wc   = max(1, count(preg_split('~\s+~u', $flat, -1, PREG_SPLIT_NO_EMPTY)));
    $hs   = [];
    if (preg_match_all('~<h2[^>]*>(.*?)</h2>~is', $norm, $hm)) {
        foreach ($hm[1] as $h) {
            $x = trim(preg_replace('~\s+~u', ' ', strip_tags($h)));
            if ($x !== '') { $hs[] = $x; }
        }
    }
    $h3n     = preg_match_all('~<h3[^>]*>~i', $norm);
    $hQuest  = count(array_filter($hs, fn($x) => mb_strpos($x, '?') !== false));
    $hColon  = count(array_filter($hs, fn($x) => mb_strpos($x, ':') !== false || mb_strpos($x, '—') !== false));
    $hLen    = $hs ? round(array_sum(array_map(fn($x) => count(preg_split('~\s+~u', $x, -1, PREG_SPLIT_NO_EMPTY)), $hs)) / count($hs), 1) : 0;
    $cta     = preg_match_all('~\b(зарегистрируйся|играй|жми|получи|забери|активируй|скачай|попробуй|переходи|успей)\b~ui', $flat);
    $honest  = preg_match_all('~\b(минус\w*|недостат\w*|риск\w*|осторожн\w*|не советую|не стоит|проигр\w*|потер\w*|обман\w*|развод\w*|ловушк\w*|подвох\w*|честно говоря|на самом деле|важно понимать)\b~ui', $flat);
    $bare    = preg_match_all('~\d[\d\s]*\s*(?:₽|руб|%|мин\b|час\w*|дн\w+|сут\w+|мб|гб|x\d)~ui', $flat);
    $terms  = NicheLexicon::termCounts($prose);
    arsort($terms);
    $top    = array_slice($terms, 0, 14, true);
    // Микроразметка бывает двух видов, и считать надо обе. Прежний счётчик
    // видел только <script type="application/ld+json"> и писал в карточку
    // «блоков: 0», хотя у образца вся разметка сидит в атрибутах itemtype —
    // и вместе с «ненужной схемой» генерация выбрасывала FAQ, который в неё
    // и обёрнут.
    $ld     = preg_match_all('~ld\+json~i', $raw);
    $micro  = preg_match_all('~itemtype="https?://schema\.org/~i', $raw);

    // Начало страницы: старый набор открывается списком-паспортом, а не абзацем
    $opensWithList = (bool) preg_match('~^\s*<ul~i', $raw);
    $firstBlock = mb_substr(trim(preg_replace('~\s+~u', ' ', strip_tags(mb_substr($raw, 0, 700)))), 0, 260);

    $L = [];
    $L[] = "# Карточка стиля для {$t}.html — цель НЕ донор, а образец";
    $L[] = '';
    $L[] = 'Эти числа ПЕРЕКРЫВАЮТ соответствующие строки промпта. Всё остальное в промпте';
    $L[] = '(структура разделов, фактура, перелинковка, запрещённые сущности) остаётся в силе.';
    $L[] = '';
    $L[] = '## Что берём от образца';
    $L[] = "- Объём: **~{$m['words_total']} слов** (±10%).";
    // Ритм описываем по замеру, а не утверждением: у одного образца абзац в две
    // фразы, у другого — на пятьдесят слов, и подсказка «дроби мельче» во втором
    // случае уводила бы от цели.
    $avg = $ps ? round($wp / count($ps), 1) : 0;
    $rhythm = $avg < 24
        ? 'Ритм ДРОБНЫЙ: абзац в две-три фразы, а не развёрнутая мысль.'
        : ($avg > 40
            ? 'Ритм КРУПНЫЙ: абзац — развёрнутая мысль на несколько предложений, с пояснением и связкой. Не руби его на строки.'
            : 'Ритм средний: абзац в три-четыре фразы.');
    $L[] = "- Абзацев: **~" . count($ps) . "**, в среднем по **~{$avg} слов**. {$rhythm}";
    $L[] = "- H2 **{$m['h2_count']}**, разделов H2+H3 **" . ($m['h2_count'] + ($m['h3_count'] ?? 0)) . "**, списков **{$m['list_count']}**, strong **{$m['strong_count']}**.";
    $L[] = "- Эмодзи **{$s['emoji']}**, вопросительных знаков **{$s['faq_questions']}**, цифр на 100 слов **" . round((float) $s['numbers_per_100w'], 1) . "**.";
    $L[] = "- Прилагательных **" . round((float) $s['adj_pct'], 1) . "%**, водность **" . round((float) $m['water_percent'], 1) . "%**, тошнота **" . round((float) $m['nausea_academic'], 1) . "%**.";
    $L[] = "- «я» **{$s['first_person']}**, «вы» **{$s['second_person']}**, императивов **{$s['imperatives']}**.";
    // У сохранённых страниц конкурента бренд стоит настоящим именем, а не
    // плейсхолдером: слепой подсчёт плейсхолдеров давал ноль и уводил генерацию
    // в текст, где бренд почти не назван. Считаем имя, если оно передано.
    $bru = substr_count($raw, '%brand_name_ru%') ?: ($BRAND['ru'] !== '' ? mb_substr_count(strip_tags($raw), $BRAND['ru']) : 0);
    $ben = substr_count($raw, '%brand_name_en%') ?: ($BRAND['en'] !== '' ? mb_substr_count(strip_tags($raw), $BRAND['en']) : 0);
    $L[] = "- Бренд: кириллицей **{$bru}**, латиницей **{$ben}** — в генерации это плейсхолдеры %brand_name_ru% и %brand_name_en%.";
    // Где стоит имя — отдельный параметр: наборы сходились по сумме упоминаний
    // и расходились по расположению, а именно оно и бросается в глаза.
    $pm = PageMetrics::measure($a, $t, $raw, $BRAND);
    $headTip = $pm['brand_in_h'] > 0
        ? "имя стоит В ЗАГОЛОВКАХ — {$pm['brand_in_h']} раз на этой странице; воспроизведи саму формулу заголовка с брендом, но своими словами"
        : 'в заголовках этой страницы бренда НЕТ — не вставляй';
    $L[] = "- РАСПОЛОЖЕНИЕ бренда: {$headTip}. В первой трети текста имя названо **{$pm['brand_first_third']}** раз — начало страницы у образца именно такой плотности.";
    $L[] = "- Названий игр в прозе **" . NicheLexicon::countGames($prose) . "**, названий студий **" . NicheLexicon::countProviders($prose) . "**. В этом стиле их НАЗЫВАЮТ прямо в тексте.";
    // Блок FAQ у образцов есть всегда, а прежний счётчик его не видел, и
    // пятнадцать наборов подряд обошлись без него.
    $L[] = $pm['faq_pairs'] > 0
        ? "- **FAQ обязателен: {$pm['faq_pairs']} пар «вопрос-ответ»** на этой странице, всего вопросительных знаков в тексте **{$pm['questions_total']}**. Вопрос ставится целиком, как его задал бы игрок («Как быстро выводятся деньги?»), ответ — в одно-два предложения."
        : "- FAQ-блока на этой странице у образца нет; вопросительных знаков в тексте **{$pm['questions_total']}**.";
    $L[] = $micro > 0
        ? "- Разметка: блоков JSON-LD **{$ld}**, элементов микроразметки `itemtype=\"schema.org/…\"` — **{$micro}**. Микроразметку воспроизводи: у образца в неё обёрнут блок FAQ, и без неё пропадает сам приём."
        : "- Блоков JSON-LD в конце страницы: **{$ld}** (как в образце; тип схемы бери тот же, что стоит в образце).";
    // Дата-стамп промпт требует на каждой странице, а образцы ставят его
    // от силы на одной из семи. Карточка перекрывает промпт.
    $L[] = "- Списки: **{$pm['ordered_pct']}% нумерованных** (`<ol>`), остальные маркированные. В `<ol>` у образца идёт ПОРЯДОК ДЕЙСТВИЙ — «откройте домен → нажмите Регистрация → подтвердите код → пополните счёт», в `<ul>` перечень без порядка. Не делай все списки маркированными: у нас так вышло во всех наборах подряд.";
    $L[] = $pm['reviews_rated'] > 0
        ? "- **Отзывы с оценкой: {$pm['reviews_rated']} шт.** Формат образца — «Имя / дата / оценка от 1 до 5», отзыв размечен `schema.org/Comment` с автором-`Person`. Оценки РАЗНЫЕ, пятёрок меньше половины, и в каждом отзыве есть оговорка про недостаток: минус называет игрок, а не автор."
        : "- Отзывов с оценкой на этой странице у образца нет.";
    $L[] = preg_match('~последнее обновление|обновлено:~ui', $raw)
        ? "- Дата-стамп на этой странице ЕСТЬ — как в образце."
        : "- Дата-стамп на этой странице НЕ НУЖЕН: у образца его нет, а промпт требует безусловно — здесь верна карточка.";
    $L[] = $opensWithList
        ? "- НАЧАЛО СТРАНИЦЫ: список-паспорт `<ul>` с фактами (год, каталог, отдача, лицензия) ДО первого заголовка — именно так открывается старый набор."
        : "- НАЧАЛО СТРАНИЦЫ: сразу заголовок H2, без списка-паспорта.";
    $L[] = "  Первые строки образца для примера ритма: «{$firstBlock}…»";
    $L[] = '';
    if ($SIGNALS) {
    $L[] = '## Как устроен заголовок и как звучит страница';
    // И здесь описание следует замеру: у одного образца тема уходит вглубь
    // подразделами, у другого структура плоская, и общая формулировка увела бы.
    $perH2 = $hs ? round($h3n / count($hs), 1) : 0;
    $depth = $perH2 >= 1.5
        ? 'Тема раскрывается вглубь подразделами, а не режется на новые H2.'
        : 'Структура ПЛОСКАЯ: подзаголовков почти нет, каждая тема — отдельный H2.';
    $L[] = "- Заголовков H2 — **" . count($hs) . "**, подзаголовков H3 на каждый — **~{$perH2}**. {$depth}";
    $colonPct = $hs ? round($hColon / count($hs) * 100) : 0;
    $hNote = $colonPct >= 60
        ? 'Конструкция «запрос впереди, двоеточие, обещание угла».'
        : 'Заголовок короткий и назывной, без конструкции с двоеточием — не усложняй его.';
    $L[] = "- Слов в заголовке — **~{$hLen}**; с двоеточием или тире — **{$colonPct}%**. {$hNote}";
    $L[] = "- Заголовков-вопросов — **" . ($hs ? round($hQuest / count($hs) * 100, 1) : 0) . "%**. Это НЕ FAQ-простыня: вопросительный заголовок здесь редкость.";
    $L[] = "- Прямых призывов («жми», «забери», «играй», «скачай») — **{$cta}** на страницу. Страница объясняет, а не продаёт.";
    $honestNote = $honest >= 20
        ? 'Это приём жанра, а не оговорка в подвале: убрав их, текст глянцевеет.'
        : ($honest >= 8
            ? 'Минусы называются, но сдержанно — держи именно это число.'
            : 'Минусы здесь почти не называются: не добавляй их от себя, это не тот жанр.');
    $L[] = "- Мест, где прямо назван минус или риск («минус», «ловушка», «не стоит», «проиграть») — **{$honest}**. {$honestNote}";
    $L[] = "- Голых чисел с единицами («500 ₽», «96%», «за 15 минут») — **{$bare}**. Цифра идёт внутри рассуждения, а не строкой сводки.";
    }
    $L[] = '';
    $L[] = '## Словарь: как говорит старый набор';
    $tt = [];
    foreach ($top as $lab => $c) { $tt[] = "{$lab} — ~{$c}"; }
    $L[] = '- Профильные термины и их счёт в прозе: ' . implode('; ', $tt) . '.';
    $L[] = '- Держи ИМЕННО этот состав слов: где у образца «отдача», не пиши «RTP», и наоборот. Счёт выше — это и есть словарь образца.';
    $L[] = "- Всего профильных терминов на странице: **~" . array_sum($terms) . "**.";
    $L[] = '';
    $L[] = '## Что берём из промпта без изменений';
    $L[] = '- Ссылки: ровно те анкоры, пути и их количество, что в блоке перелинковки промпта.';
    $L[] = '- Состав разделов, фактура, разрешённые и запрещённые категории сущностей, плейсхолдеры бренда.';

    file_put_contents("$OUT/style-{$t}.md", implode("\n", $L) . "\n");
    printf("%-14s абзацев %3d по %4.1f слов, терминов %3d, игр %2d, студий %2d\n",
        $t, count($ps), $ps ? $wp / count($ps) : 0, array_sum($terms),
        NicheLexicon::countGames($prose), NicheLexicon::countProviders($prose));
}
echo "→ $OUT\n";
