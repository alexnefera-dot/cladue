СТОП = set('''и в во не что он на я с со как а то все она так его но да ты к у же вы за бы по только ее мне было вот от меня еще нет о из ему теперь когда даже ну вдруг ли если уже или ни быть был него до вас нибудь опять уж вам ведь там потом себя ничего ей может они тут где есть надо ней для мы тебя их чем была сам чтоб без будто чего раз тоже себе под будет ж тогда кто этот того потому этого какой совсем ним здесь этом один почти мой тем чтобы нее сейчас были куда зачем всех никогда можно при наконец два об другой хоть после над больше тот через эти нас про всего них какая много разве три эту моя впрочем хорошо свою этой перед иногда лучше чуть том нельзя такой им более всегда конечно всю между это её ее также очень свои наш ваш'''.split())
КЛЮЧИ = ['казино','слот','бонус','джекпот','зеркал','промокод','регистрац','вход','фриспин','вейджер','депозит','вывод','RTP','турнир','лиценз','кэшбэк','автомат','выигрыш','ставк','отыгрыш']

def текст(h): return re.sub(r'\s+',' ',re.sub(r'<[^>]+>',' ',h)).strip()
def слова(t): return [w.lower() for w in re.findall(r'[А-Яа-яЁёA-Za-z]{2,}', t)]

def набор(d):
    фф = sorted(glob.glob(d+'/*.html'))
    if not фф: return None
    W=[]; H2=[]; H3=[]; предл=[]; анк=[]; адр=[]; img=0; alt=0; схемы=set(); aria=0
    текстБайт=0; htmlБайт=0; ключВh=0; ключПервые=0; страниц=0; иерархия=0
    числа=0; пассив=0
    for f in фф:
        h=open(f,encoding='utf-8',errors='ignore').read()
        t=текст(h); w=слова(t)
        if len(w)<100: continue
        страниц+=1
        W+=w; htmlБайт+=len(h); текстБайт+=len(t)
        h2=[текст(x) for x in re.findall(r'<h2\b[^>]*>(.*?)</h2>',h,re.S)]
        h3=[текст(x) for x in re.findall(r'<h3\b[^>]*>(.*?)</h3>',h,re.S)]
        H2+=h2; H3+=h3
        ключВh+=sum(1 for z in h2+h3 if any(k.lower() in z.lower() for k in КЛЮЧИ))
        первые=' '.join(w[:100])
        ключПервые+=1 if any(k.lower() in первые for k in КЛЮЧИ) else 0
        предл+=[len(слова(s)) for s in re.split(r'(?<=[.!?])\s+',t) if len(слова(s))>2]
        for m in re.finditer(r'<a\b[^>]*href="([^"]*)"[^>]*>(.*?)</a>',h,re.S):
            адр.append(m.group(1)); анк.append(текст(m.group(2)).lower())
        i=len(re.findall(r'<img\b',h)); img+=i; alt+=len(re.findall(r'<img\b[^>]*\balt="[^"]+"',h))
        схемы|=set(re.findall(r'itemtype="https?://schema\.org/([A-Za-z]+)"',h))
        aria+=len(re.findall(r'aria-label=',h))
        числа+=len(re.findall(r'\d',t))
        # точный список: прежняя широкая регулярка считала пассивом «нужен»,
        # «домен», «обмана» и даже имя «Роман» — цифра была втрое завышена
        пассив+=len(re.findall(r'\b(?:начисля|зачисля|засчитыва|выплачива|оформля|обрабатыва|проверя'
            r'|блокиру|активиру|списыва|рассчитыва|устанавлива|определя|публику|указыва|предоставля'
            r'|начисл|зачисл|провер|подтвержд|прописан|расписан|указан|заявлен|оговорен|ограничен'
            r'|установлен|назначен|рассмотрен|обработан|заблокирован|активирован|списан|выплачен)'
            r'\w*(?:ется|ются|ётся|ен|ена|ено|ены|ан|ана|ано|аны|ён|ёна|ёно|ёны)\b',t,re.I))
        # иерархия: первый заголовок страницы — h2, h3 не раньше h2
        порядок=re.findall(r'<h([23])\b',h)
        иерархия+=1 if (порядок and порядок[0]=='2') else 0
    if not страниц: return None
    ч=collections.Counter(W); всего=len(W)
    самое=ч.most_common(1)[0][1] if ч else 1
    знач=[x for x in W if x not in СТОП]
    чз=collections.Counter(знач)
    топ10=sum(n for _,n in чз.most_common(10))
    return {
        'слов в наборе': всего,
        'вода (стоп-слова), %': round(sum(1 for x in W if x in СТОП)*100/всего,1),
        'классическая тошнота': round(math.sqrt(самое),2),
        'академическая тошнота, %': round(топ10*100/всего,1),
        'разных слов на 1000': round(len(ч)*1000/всего,1),
        'слов в предложении': round(statistics.median(предл),1) if предл else 0,
        'длинных предложений (>25 слов), %': round(sum(1 for x in предл if x>25)*100/len(предл),1) if предл else 0,
        'цифр на 100 слов': round(числа*100/всего,1),
        'пассив на 1000 слов': round(пассив*1000/всего,1),
        'ключ в h2/h3, %': round(ключВh*100/max(1,len(H2)+len(H3)),1),
        'страниц с ключом в первых 100 словах, %': round(ключПервые*100/страниц,1),
        'заголовков h2+h3 на 1000 слов': round((len(H2)+len(H3))*1000/всего,1),
        'иерархия h2→h3 верна, % страниц': round(иерархия*100/страниц,1),
        'ссылок на 1000 слов': round(len(анк)*1000/всего,1),
        'уникальных анкоров, %': round(len(set(анк))*100/max(1,len(анк)),1),
        'уникальных адресов': len(set(адр)),
        'анкоров-глаголов, %': round(sum(1 for a in анк if re.match(r'^(играй|играть|войти|войди|зайти|заходи|скачать|скачай|зарегистрир|жми|бери|забрать|забери|проверь|смотри)',a))*100/max(1,len(анк)),1),
        'внешних ссылок': sum(1 for a in адр if a.startswith('http')),
        'картинок с alt, %': round(alt*100/img,1) if img else 0,
        'типов schema.org': len(схемы),
        'aria-label на набор': aria,
        'текст/HTML, %': round(текстБайт*100/htmlБайт,1),
    }

def свод(шаблоны, метка):
    строки=[]
    for ш in шаблоны:
        for d in sorted(glob.glob(ш)):
            r=набор(d)
            if r: строки.append(r)
    out={}
    for k in строки[0]:
        v=[r[k] for r in строки]
        out[k]=(round(statistics.median(v),2), round(min(v),2), round(max(v),2))
    return out, len(строки)

