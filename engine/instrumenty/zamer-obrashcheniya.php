<?php
declare(strict_types=1);
/**
 * Замер обращения: где набор говорит «ты», где «вы» и где путается.
 *
 * ЗАЧЕМ. Регистр у нас ведут пять проходов перекрута — табличный добор
 * вежливых форм, перевод «вы» → «ты», сведение смешанного предложения, дожим
 * доли «вы» и потолок вежливого императива. Каждый считает свою величину, и
 * ни один не считает ту, по которой читатель судит: не путается ли текст, к
 * кому обращается. Эта мерка считает именно её, одной меркой на корпус и на
 * нашу выдачу, чтобы числа были сравнимы.
 *
 * ЧТО СЧИТАЕТСЯ.
 *   доля «вы»      — среди местоимений обращения (ты+вы), в процентах;
 *   смесь во фразе — в одном предложении метки обоих регистров;
 *   смесь в блоке  — в одном абзаце или пункте списка, по разным фразам;
 *   «вы» в разделе — наибольшее число «вы»-блоков под одним h2;
 *   вежливых       — императивов на «-йте/-ьте/-ите» на страницу.
 *
 * Списки императивов берутся из движка (V5_VY_ИМПЕРАТИВ, V5_TY_ЛИЧНЫЕ,
 * V5_NE_IMPERATIV_SLOVA): мерка обязана видеть регистр теми же словами,
 * какими его правит перекрут, иначе правка меряется не своей меркой.
 *
 * Запуск:
 *   php engine/instrumenty/zamer-obrashcheniya.php samples/v5-final/nabor-782
 *   php engine/instrumenty/zamer-obrashcheniya.php samples/v5-konkurent/NEW100 --корпус
 *   php engine/instrumenty/zamer-obrashcheniya.php <папка> --фразы
 */

require dirname(__DIR__) . '/src/V5Blocks.php';

$путь = $argv[1] ?? '';
$корпус = in_array('--корпус', $argv, true);
$показатьФразы = in_array('--фразы', $argv, true);
$какJson = in_array('--json', $argv, true);
if ($путь === '' || !is_dir($путь)) { fwrite(STDERR, "нужна папка набора\n"); exit(2); }

/** Блоки страницы: заголовки отдельно, текст абзацев и пунктов — по одному. */
$блоки = static function (string $html): array {
    $html = (string) preg_replace('~(?s)<(script|style|svg)\b.*?</\1>~', ' ', $html);
    $html = (string) preg_replace('~<br\s*/?>~i', ' ', $html);
    $вышло = [];
    if (preg_match_all('~<(p|li|h1|h2|h3|h4|td|th|dd|dt|blockquote|figcaption)\b[^>]*>(.*?)</\1>~su',
                       $html, $м, PREG_SET_ORDER)) {
        foreach ($м as $x) {
            $t = html_entity_decode((string) preg_replace('~<[^>]+>~', '', $x[2]), ENT_QUOTES | ENT_HTML5, 'UTF-8');
            $t = trim((string) preg_replace('~\s+~u', ' ', $t));
            if ($t !== '' && preg_match('~[а-яё]~iu', $t)) { $вышло[] = [mb_strtolower($x[1]), $t]; }
        }
    }
    return $вышло;
};

// Метки — из общего списка движка (V5Blocks::v5RegistrFrazy): сито, замер и
// перекрут обязаны видеть регистр одними словами.
$метки = static function (string $ф): array {
    $р = v5RegistrFrazy($ф);
    return ['тм' => $р['тыМест'], 'вм' => $р['выМест'], 'тг' => $р['тыГлаг'],
            'ти' => $р['тыИмп'], 'вл' => $р['выЛичн'], 'ви' => $р['выИмп']];
};

$разбор = static function (string $папка) use ($блоки, $метки): array {
    $и = ['тм' => 0, 'вм' => 0, 'вл' => 0, 'ви' => 0, 'ти' => 0, 'тг' => 0,
          'смесьФраз' => 0, 'смесьРяда' => 0, 'фраз' => 0, 'смесьБлоков' => 0, 'блоков' => 0,
          'выБлоков' => 0, 'вРазделе' => 0, 'страниц' => 0, 'страницСВы' => 0, 'примеры' => []];
    foreach (glob(rtrim($папка, '/') . '/*.html') ?: [] as $файл) {
        $тип = basename($файл, '.html');
        $и['страниц']++;
        $выСтр = 0;
        $вРазделе = 0;
        foreach ($блоки((string) file_get_contents($файл)) as [$тег, $текст]) {
            if ($тег === 'h1' || $тег === 'h2') { $и['вРазделе'] = max($и['вРазделе'], $вРазделе); $вРазделе = 0; }
            $бт = 0; $бв = 0;
            foreach (preg_split('~(?<=[.!?])\s+~u', $текст) ?: [] as $ф) {
                if (trim($ф) === '') { continue; }
                $к = $метки($ф);
                foreach (['тм', 'вм', 'тг', 'ти', 'вл', 'ви'] as $г) { $и[$г] += count($к[$г]); }
                $и['фраз']++;
                $т = count($к['тм']) + count($к['тг']) + count($к['ти']);
                $в = count($к['вм']) + count($к['вл']) + count($к['ви']);
                if ($т > 0 && $в > 0) {
                    $и['смесьФраз']++;
                    // Инварианта: однородный ряд императивов в двух регистрах.
                    if ($к['ти'] && $к['ви']) { $и['смесьРяда']++; }
                    if (count($и['примеры']) < 60) { $и['примеры'][] = [$тип, $ф, $к]; }
                }
                $бт += $т; $бв += $в;
                $выСтр += count($к['вм']) + count($к['вл']);
            }
            $и['блоков']++;
            if ($бт > 0 && $бв > 0) { $и['смесьБлоков']++; }
            if ($бв > 0 && $бт === 0) { $и['выБлоков']++; $вРазделе++; }
        }
        $и['вРазделе'] = max($и['вРазделе'], $вРазделе);
        if ($выСтр > 0) { $и['страницСВы']++; }
    }
    $и['всегоМест'] = $и['тм'] + $и['вм'];
    $и['доля'] = $и['всегоМест'] > 0 ? 100 * $и['вм'] / $и['всегоМест'] : 0.0;
    return $и;
};

$строка = static function (string $имя, array $и): string {
    return sprintf('%-18s доля «вы» %5.1f%%  смесь-фраз %3d (ряд %2d)  смесь-блоков %3d  «вы»-блоков %3d (в разделе до %d)  вежл./стр %4.1f  стр. со «вы» %2d/%2d',
        $имя, $и['доля'], $и['смесьФраз'], $и['смесьРяда'], $и['смесьБлоков'], $и['выБлоков'], $и['вРазделе'],
        $и['страниц'] ? $и['ви'] / $и['страниц'] : 0, $и['страницСВы'], $и['страниц']);
};

if (!$корпус) {
    $и = $разбор($путь);
    if ($какJson) { unset($и['примеры']); echo json_encode($и, JSON_UNESCAPED_UNICODE), "\n"; exit(0); }
    echo $строка(basename(rtrim($путь, '/')), $и), "\n";
    if ($показатьФразы) {
        foreach ($и['примеры'] as [$тип, $ф, $к]) {
            printf("\n[%s] %s\n   ты: %s | вы: %s\n", $тип, mb_substr($ф, 0, 240),
                implode(',', array_merge($к['тм'], $к['тг'], $к['ти'])),
                implode(',', array_merge($к['вм'], $к['вл'], $к['ви'])));
        }
    }
    exit(0);
}

// ── свод по корпусу ──
$ряды = [];
foreach (glob(rtrim($путь, '/') . '/*') ?: [] as $д) {
    if (!is_dir($д)) { continue; }
    $и = $разбор($д);
    if ($и['всегоМест'] < 10) { continue; }
    $и['имя'] = basename($д);
    $ряды[] = $и;
}
$ты = array_values(array_filter($ряды, static fn (array $r): bool => $r['доля'] < 50));
$медиана = static function (array $x): float {
    if (!$x) { return 0.0; }
    sort($x); $n = count($x);
    return $n % 2 ? (float) $x[intdiv($n, 2)] : ($x[$n / 2 - 1] + $x[$n / 2]) / 2;
};
$кв = static function (array $x, float $p): float { sort($x); return (float) ($x[(int) floor($p * (count($x) - 1))] ?? 0); };
printf("наборов %d, «ты»-наборов %d\n", count($ряды), count($ты));
$д = array_column($ты, 'доля');
printf("доля «вы»:      медиана %.1f%%  p25 %.1f%%  p75 %.1f%%  max %.1f%%\n",
    $медиана($д), $кв($д, 0.25), $кв($д, 0.75), max($д));
foreach (['смесьФраз' => 'смесь во фразе', 'смесьРяда' => 'смесь в ряду',
          'смесьБлоков' => 'смесь в блоке',
          'выБлоков' => '«вы»-блоков', 'вРазделе' => '«вы» в разделе'] as $к => $п) {
    $v = array_column($ты, $к);
    printf("%-15s медиана %5.1f  p75 %5.1f  max %4d  (сумма %d)\n", $п, $медиана($v), $кв($v, 0.75), max($v), array_sum($v));
}
$в = array_map(static fn (array $r): float => $r['страниц'] ? $r['ви'] / $r['страниц'] : 0.0, $ты);
printf("вежл./страницу  медиана %5.1f  p75 %5.1f\n", $медиана($в), $кв($в, 0.75));
// Наборы в нашей полосе доли — с ними и сравнивается выдача.
$узк = array_values(array_filter($ты, static fn (array $r): bool => $r['доля'] >= 4 && $r['доля'] <= 16));
if ($узк) {
    printf("\nиз них с долей 4–16%% (%d шт.):\n", count($узк));
    foreach (['смесьФраз' => 'смесь во фразе', 'смесьРяда' => 'смесь в ряду',
              'смесьБлоков' => 'смесь в блоке',
              'выБлоков' => '«вы»-блоков', 'вРазделе' => '«вы» в разделе'] as $к => $п) {
        $v = array_column($узк, $к);
        printf("  %-15s медиана %5.1f  p75 %5.1f  max %4d\n", $п, $медиана($v), $кв($v, 0.75), max($v));
    }
}
