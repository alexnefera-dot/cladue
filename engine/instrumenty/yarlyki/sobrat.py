# -*- coding: utf-8 -*-
"""Вкручивание пунктов с тематическим ярлыком в пулы.

Запас помеченных записей — причина просадки мечения: их 2 599 в прорези
«пункты» при спросе вдвое выше доли (разбор в docs/partiya-777-781.md).
Здесь они дописываются.

Проверок восемь, и каждая закрывает уже случавшуюся ошибку:
  ярлык — глазами движка (v5EstYarlyk), а не своей копией правила;
  ярлык не повторяется внутри записи раздела — список берёт пункты из одной;
  текст не лежит в пулах уже;
  нет левых частей PK_TERMY — перекрут превращает их в термины;
  нет формул заголовков;
  нет «вы/вас/ваш» — в «ты»-наборах такая запись идёт на шаг ниже;
  прорези только из белого списка;
  плотность терминов не выше медианы существующих пунктов типа.

Доноры «наш16»–«наш19» по кругу: потолок донора на странице — 60 слов и
больше, и один донор на все записи упёрся бы в него на пятом пункте.
"""
import os, importlib.util, json, re, subprocess, sys

SB = os.path.dirname(os.path.abspath(__file__))
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
П = КОРЕНЬ + '/engine/data-v5/pools.json'
ДОНОРЫ = ['наш16', 'наш17', 'наш18', 'наш19']
ТИПЫ = [т for т in sys.argv[1:] if not т.startswith('--')]
ПИСАТЬ = '--писать' in sys.argv
# Полоса плотности терминов 0.75–1.25 поставлена по косвенной улике: промахи
# terms_total 29 → 37 на траншах promo и app. Но те транши шли с ×0.37–0.66 и
# по общему счёту промахов оказались бесплатными (−0.12). Значит полоса —
# догадка, а не замер, и ломать из-за неё транш нельзя молча. Флаг ставит
# решение в журнал: транш идёт с недобором терминов, и следующий парный замер
# скажет, стоило ли.
МИМО_ТЕРМИНОВ = '--мимо-терминов' in sys.argv

СЛОТЫ_ОК = {'{ИМЯ}', '{ИМЯ:а}', '{ИМЯ:у}', '{ИМЯ:ом}', '{ИМЯ:е}', '{ИМЯЖ}', '{СУММА}',
            '{МИН}', '{РУБЛИ}', '{ПРОЦ}', '{ДОЛЯ}', '{ДОЛЯМАЛ}', '{ПОРОГ}', '{RTP}',
            '{RTP2}', '{ДЖЕКПОТ}', '{ВЕЙДЖЕР}', '{RTPНИЗ}', '{СУММАМАЛ}', '{ДОЛЯМАЛ}', '{ФОНД}', '{СЛОТОВ}', '{РУБЛИ_МИН}', '{СУММА_ЛИМИТ}'}
В_ТЕРМИН = ['игра на деньги', 'крупная сумма', 'возврат части', 'проверка данных',
    'проверку данных', 'пробный режим', 'бесплатный режим', 'ограничение суммы',
    'разработчик игр', 'разработчики игр', 'первое пополнение', 'запасной адрес',
    'бесплатные вращения', 'отдача автоматов', 'условия отыгрыша',
    'требования по обороту', 'риск игры', 'размах выплат', 'вывод денег',
    'снять деньги', 'играть без ставок', 'без вложений']
ФОРМУЛЫ = ['официальный сайт', 'игровые автоматы', 'бонусы и промокоды', 'можно ли',
           'личный кабинет', 'зеркало сайта', 'вывод средств', 'ответы на', 'вход в']
ВЫ = re.compile(r'(?<![а-яё])(?:вы|вас|вам|вами|ваш\w*)(?![а-яё])', re.I)
# Признак honest («мест с минусом или риском») профиль держит, а новые пункты
# вытесняют старые. Первая партия bonus несла 0.01 слова honest на пункт против
# 0.16 у существующих — шестнадцатикратное разбавление, и приёмка это увидела.
HONEST = re.compile(r'\b(минус\w*|недостат\w*|риск\w*|осторожн\w*|не советую|не стоит'
                    r'|проигр\w*|потер\w*|обман\w*|развод\w*|ловушк\w*|подвох\w*'
                    r'|честно говоря|на самом деле|важно понимать)\b', re.I)
ТЕГИ = re.compile(r'(?s)<[^>]+>')
ПРОРЕЗЬ = re.compile(r'\{[^}]*\}')
# Полосы подобраны по смыслу признака: honest, ссылки и цифры профиль держит
# полями honest, anchors, numbers_per100 и fact_values, и недобор там дороже
# перебора; ведущих выделений у нас и так много, поэтому сверху полоса узкая.
МЕРКИ = [
    # Плотность терминов. Замер траншей promo и app дал промахи terms_total
    # 29 → 37 на 24 набора, хотя термины у новых пунктов НИЖЕ существующих —
    # 0.27–0.70 против 0.54–1.06, то есть ×0.37–0.66. Приёмка считает коридор
    # от цели набора, и недобор там такой же промах, как перебор: пункты без
    # терминов утянули плотность страницы ниже цели. Полоса узкая с обеих сторон.
    ('терминов', None,                                                0.75, 1.25),
    ('honest',   lambda t: len(HONEST.findall(ТЕГИ.sub('', t))),       0.7, 1.6),
    ('ссылок',   lambda t: len(re.findall(r'<a\s', t)),               0.7, 1.4),
    ('цифр',     lambda t: len(re.findall(r'\d', ТЕГИ.sub('', t))),    0.6, 1.4),
    ('прорезей', lambda t: len(ПРОРЕЗЬ.findall(t)),                   0.6, 1.4),
    ('strong',   lambda t: len(re.findall(r'<strong', t)),            0.7, 1.15),
    ('слов',     lambda t: len(ТЕГИ.sub('', t).split()),              0.85, 1.15),
]


def php(код, вход):
    r = subprocess.run(['php', '-r', код], input=json.dumps(вход), capture_output=True,
                       text=True, cwd=КОРЕНЬ)
    if r.returncode != 0:
        raise SystemExit('php: ' + r.stderr[:400])
    return json.loads(r.stdout)


def ярлыки(тексты):
    return php('require_once "engine/src/V5Blocks.php";'
               '$in=json_decode(file_get_contents("php://stdin"),true);$o=[];'
               'foreach($in as $t){$o[]=v5EstYarlyk($t);}echo json_encode($o);', тексты)


def термы(тексты):
    return php('require_once "engine/src/PageMetrics.php";'
               '$in=json_decode(file_get_contents("php://stdin"),true);$o=[];'
               'foreach($in as $t){$o[]=NicheLexicon::termsTotal($t);}echo json_encode($o);', тексты)


def темы(тексты):
    return php('require_once "engine/src/V5Roli.php";'
               '$in=json_decode(file_get_contents("php://stdin"),true);$o=[];'
               'foreach($in as $t){$o[]=v5TemaPunkta($t);}echo json_encode($o);', тексты)


def собрать(ярлык, тело, встрong):
    return ('<strong>%s:</strong> %s' % (ярлык, тело)) if встрong else ('%s: %s' % (ярлык, тело))


d = json.load(open(П, encoding='utf-8'))
есть = set()
for секции in d['разделы'].values():
    for s in секции.values():
        for x in (s.get('пункты') or []):
            if isinstance(x, dict) and x.get('т'):
                есть.add(x['т'])

беда = []
добавить = {}
счёт = 0
for тип in ТИПЫ:
    сп = importlib.util.spec_from_file_location('y_' + тип, '%s/%s.py' % (SB, тип))
    m = importlib.util.module_from_spec(сп)
    сп.loader.exec_module(m)
    разделы = list(d['разделы'][тип].keys())
    # медиана плотности терминов у существующих пунктов типа
    стар = [str(x.get('т', '')) for h2 in разделы for x in d['разделы'][тип][h2]['пункты']]
    тс = sorted(термы(стар))
    порогТерм = тс[int(0.9 * (len(тс) - 1))]
    дл = sorted(len(ТЕГИ.sub('', x).split()) for x in стар)
    низ, верх = дл[int(0.10 * (len(дл) - 1))], дл[int(0.90 * (len(дл) - 1))]
    for ин, пары in sorted(m.ПУНКТЫ.items()):
        if ин >= len(разделы):
            беда.append('%s: раздела %d нет' % (тип, ин))
            continue
        h2 = разделы[ин]
        ярлСвои = set()
        ярлЕсть = {ТЕГИ.sub('', str(x.get('т', ''))).split(':')[0].strip()
                   for x in d['разделы'][тип][h2]['пункты']}
        тексты = [собрать(*п) for п in пары]
        окЯрлык = ярлыки(тексты)
        окТерм = термы(тексты)
        окТема = темы(тексты)
        годные = []
        for (я, тело, вс), т, ея, тм, тема in zip(пары, тексты, окЯрлык, окТерм, окТема):
            где = '%s[%d] «%s»' % (тип, ин, я)
            if not ея:
                беда.append('%s: движок не считает это ярлыком' % где); continue
            if я in ярлСвои:
                беда.append('%s: ярлык повторён внутри раздела' % где); continue
            if я in ярлЕсть:
                беда.append('%s: такой ярлык в разделе уже есть' % где); continue
            if т in есть:
                беда.append('%s: текст уже в пулах' % где); continue
            н = т.lower()
            пл = [ф for ф in В_ТЕРМИН if ф in н]
            if пл:
                беда.append('%s: станет термином — %s' % (где, пл[0])); continue
            фм = [ф for ф in ФОРМУЛЫ if ф in н]
            if фм:
                беда.append('%s: формула заголовка — %s' % (где, фм[0])); continue
            if ВЫ.search(ТЕГИ.sub('', т)):
                беда.append('%s: обращение «вы»' % где); continue
            плохо = [s for s in ПРОРЕЗЬ.findall(т) if s not in СЛОТЫ_ОК]
            if плохо:
                беда.append('%s: прорезь %s' % (где, плохо[0])); continue
            if тм > порогТерм:
                беда.append('%s: терминов %d при пороге %d' % (где, тм, порогТерм)); continue
            сл = len(ТЕГИ.sub('', т).split())
            if not (низ <= сл <= верх):
                беда.append('%s: слов %d вне полосы %d–%d' % (где, сл, низ, верх)); continue
            ярлСвои.add(я)
            годные.append((т, тема))
        добавить.setdefault(тип, {})[h2] = годные
        счёт += len(годные)
    # Плотности транша против существующих пунктов типа. Новая запись вытесняет
    # старую со всем, что та несла, поэтому транш обязан нести столько же.
    # Первая партия bonus несла honest 0.01 против 0.16, ссылок ноль против 0.37
    # и цифр 0.01 против 0.19 — это промахи honest, anchors, numbers_per100 и
    # fact_values, купленные ярлыками.
    новые = [т for по in добавить.get(тип, {}).values() for т, _ in по]
    if новые:
        print('%s: плотности на пункт (новые / существующие)' % тип)
        for имя, f, низ, верх in МЕРКИ:
            if f is None:   # термины считает движок, а не регулярка
                тн = термы(новые); тс2 = термы(стар)
                бн = sum(тн) / len(тн); бс = sum(тс2) / len(тс2)
            else:
                бн = sum(f(т) for т in новые) / len(новые)
                бс = sum(f(т) for т in стар) / len(стар)
            к = (бн / бс) if бс else 1.0
            знак = 'ок ' if низ <= к <= верх else '✗  '
            print('   %s %-10s %7.3f / %7.3f  ×%.2f' % (знак, имя, бн, бс, к))
            if not (низ <= к <= верх):
                беда.append('%s: %s %.3f против %.3f у существующих (×%.2f, полоса %.1f–%.1f)'
                            % (тип, имя, бн, бс, к, низ, верх))

print('годных пунктов: %d, отбраковано: %d' % (счёт, len(беда)))
for б in беда[:40]:
    print('  ✗', б)
if len(беда) > 40:
    print('  … ещё %d' % (len(беда) - 40))

if МИМО_ТЕРМИНОВ:
    беда = [б for б in беда if ': терминов ' not in б]
    print('ВНИМАНИЕ: недобор терминов принят сознательно, замер покажет цену')

if ПИСАТЬ and not беда:
    i = 0
    for тип, по in добавить.items():
        for h2, годные in по.items():
            for т, _ in годные:
                d['разделы'][тип][h2]['пункты'].append({'т': т, 'д': ДОНОРЫ[i % len(ДОНОРЫ)]})
                i += 1
    with open(П, 'w', encoding='utf-8') as ф:
        json.dump(d, ф, ensure_ascii=False, separators=(',', ':'))
    print('записано в пулы: %d' % i)
elif ПИСАТЬ:
    print('не записано: сначала чинить отбраковку')
