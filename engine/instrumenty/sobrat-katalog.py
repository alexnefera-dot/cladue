# -*- coding: utf-8 -*-
"""Пул каталога слотов из корпуса NEW100 → engine/data-v5/katalog-slotov.json.

   python3 engine/instrumenty/sobrat-katalog.py

У двенадцати доноров на slots лежит каталог: 276 карточек «Название /
Провайдер, RTP X. Короткое описание». Каталог у всех двенадцати дословно
один — значит это блок корпуса, а не находка одного сайта.

Берём из него только факты: название, провайдера, отдачу. Описание донора
НЕ переносится: страница с чужими описаниями легла бы на донора шинглами
(их 274 штуки на страницу, это половина текста), а ворота уникальности
держат 12 %. Вместо описания из него вынимаются теги по словарю — тема и
механика, — и карточку движок собирает своими словами.
"""
import json, os, re
from collections import Counter

КОРПУС = '/home/user/cladue/samples/v5-konkurent/NEW100'
ВЫХОД = '/home/user/cladue/engine/data-v5/katalog-slotov.json'
КАРТА = re.compile(r'<div class="card">\s*<h3>\s*(.*?)\s*</h3>\s*<p>\s*(.*?)\s*</p>', re.S)
РАЗБОР = re.compile(r"([^,]+),\s*RTP\s*(\d+(?:\.\d+)?)\.?\s*(.*)")

# Тег — это факт об игре: тема или механика. Словарь закрытый: что не
# опознано, остаётся без тега, и карточка собирается от отдачи и студии.
ТЕМЫ = [
    (r'египетск|фараон|анубис|клеопатр', 'египетская тема'),
    (r'азиатск|китайск|японск|восточн|дракон', 'азиатская тема'),
    (r'греческ|мифолог|олимп|зевс', 'греческая мифология'),
    (r'викинг|скандинав|асгард', 'викинги'),
    (r'ирландск|лепрекон|клевер', 'ирландская тема'),
    (r'мексиканск|ацтек|майя|\\bинк[иа]\\b', 'тема ацтеков'),
    (r'африканск|сафари|бизон|буйвол|саванн', 'африканская тема'),
    (r'вестерн|дикий запад|ковбо', 'вестерн'),
    (r'рыболовн|рыбал|рыбн', 'рыбалка'),
    (r'фрукт|ягод|сладост|конфет|карамел', 'фруктовая тема'),
    (r'сказочн|фэнтези|магическ|волшебн|принцесс', 'сказочная тема'),
    (r'мистическ|тёмн|темн|ужас|хоррор|готическ|зомби|вампир', 'мистика'),
    (r'космическ|космос|инопланет|галакт', 'космос'),
    (r'футбольн|спортивн|хоккей|бокс', 'спортивная тема'),
    (r'пиратск|пират|море|морск', 'пиратская тема'),
    (r'приключенческ|джунгл|экспедиц|археолог', 'приключения'),
    (r'ферм|деревн|животн|\\bкот[аыов]\\w*', 'деревенская тема'),
    (r'ограблен|банд|тюрьм|полиц|детектив', 'криминальная тема'),
    (r'ювелирн|драгоценност|бриллиант|самоцвет', 'драгоценности'),
    (r'классическ|ретро|традиционн', 'классика'),
]
МЕХАНИКИ = [
    (r'megaways', 'Megaways'),
    (r'xways|xnudge|xsplit|xbomb', 'xWays'),
    (r'кластер', 'кластеры'),
    (r'каскадн|каскад|лавин', 'каскады'),
    (r'hold\s*&?\s*(?:amp;)?\s*spin|холд', 'Hold & Spin'),
    (r'множител', 'множители'),
    (r'фриспин|бесплатн\w* вращен|free spins', 'фриспины'),
    (r'респин', 'респины'),
    (r'вайлд|дик\w+ символ', 'вайлды'),
    (r'липк', 'липкие символы'),
    (r'расширяющ', 'расширяющиеся символы'),
    (r'прогрессивн', 'прогрессивный джекпот'),
    (r'джекпот', 'джекпоты'),
    (r'покупк\w* бонус|купить бонус|bonus buy', 'покупка бонуса'),
    (r'бонусн\w* раунд|бонусами|бонусной игр', 'бонусный раунд'),
    (r'волатильн', 'высокая волатильность'),
    (r'книг|book of', 'механика Book of'),
    (r'краш|crash|растущ\w* множител', 'краш-игра'),
    (r'колес|рулет|кости|dice|\\bмин[ыа]\\b', 'быстрая игра'),
    (r'способ\w* выигрыш|линий|линия', 'много линий'),
]
ВИД = [
    (r'продолжение|сиквел|сери[ия]', 'продолжение серии'),
    (r'обновлен|улучшенн|переиздан|нов\w+ верси|верси[яи]', 'переиздание'),
    (r'новинк|нов\w+ слот|2026|2025', 'новинка'),
]


def теги(описание: str) -> list:
    т = описание.lower()
    из = []
    for набор, предел in ((ТЕМЫ, 1), (МЕХАНИКИ, 3), (ВИД, 1)):
        взято = 0
        for шаблон, тег in набор:
            if взято >= предел:
                break
            if re.search(шаблон, т):
                из.append(тег)
                взято += 1
    return из


карточки = {}
источников = 0
for набор in sorted(os.listdir(КОРПУС)):
    п = os.path.join(КОРПУС, набор)
    if not os.path.isdir(п):
        continue
    for ф in sorted(os.listdir(п)):
        html = open(os.path.join(п, ф), encoding='utf-8', errors='replace').read()
        найдено = КАРТА.findall(html)
        if len(найдено) < 50:
            continue
        источников += 1
        for имя, опис in найдено:
            имя = re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', имя)).strip()
            опис = re.sub(r'\[reference:\d+\]', '', re.sub(r'\s+', ' ', опис)).strip()
            m = РАЗБОР.match(опис)
            if not m or имя in карточки:
                continue
            карточки[имя] = {'н': имя, 'п': m.group(1).strip(), 'rtp': m.group(2), 'т': теги(m.group(3))}

игры = sorted(карточки.values(), key=lambda x: x['н'])
json.dump({'источник': {'корпус': 'samples/v5-konkurent/NEW100', 'каталогов': источников},
           'игры': игры},
          open(ВЫХОД, 'w'), ensure_ascii=False, indent=0)
ст = Counter(len(и['т']) for и in игры)
print('каталогов в корпусе: %d | игр: %d' % (источников, len(игры)))
print('тегов на игру:', sorted(ст.items()))
print('провайдеров:', len({и['п'] for и in игры}))
print('без тегов:', [и['н'] for и in игры if not и['т']][:12])
print('пример:', json.dumps(игры[:3], ensure_ascii=False))
