/**
 * Замер джекпотов: сколько раз названа сумма джекпота, сколько из них мельче
 * миллиона, сколько совпадает с выигрышем героя — и какой ценой, то есть с
 * какой плотностью слово «джекпот» живёт в наборе.
 *
 * ЗАЧЕМ. Сито связности ловит два нарушения («джекпот мельче миллиона»,
 * «джекпот равен выигрышу»), но не показывает ни полосу корпуса, ни цену
 * правки. Плотность ключа «джекпот» добирается подменой «куш» → «джекпот»
 * (v5DoborBonusa), и любой запрет на эту подмену плотность роняет. Здесь оба
 * числа стоят рядом, чтобы правка не выменивала нарушение на выпадение из
 * полосы.
 *
 * ПОЛОСА КОРПУСА (NEW100, сто наборов, октябрь 2026):
 *   пар «джекпот + сумма» — 36.9 на набор, дециль 8…67;
 *   мельче миллиона — 0.21 на набор, хотя бы одна у 20 наборов из ста;
 *   равных названному выигрышу — 0.23 на набор, 19 разных случаев на сто
 *   наборов;
 *   «джекпот» — 3.30 на 1000 слов (медиана 3.23), «куш» — 1.86.
 *
 * Из двадцати восьми сырых совпадений «мельче миллиона» пять оказались
 * отрицанием («выиграл не джекпот, но приятные 520 тысяч»), четыре —
 * составным («джекпот-зона», «сектор джекпота»); v5Dzhekpoty их не считает,
 * отсюда 0.21 вместо 0.28. «Равных» без условия «в другом предложении» было
 * 0.45: «сорвал джекпот 120 млн» — одно утверждение, а не спор.
 *
 * ДЛЯ СРАВНЕНИЯ. Набор 782, который читал человек: 25 мелких и 8 равных на
 * один набор. Партия 793–797: 1.60 и 0.00.
 *
 * Запуск:
 *   php engine/instrumenty/zamer-dzhekpotov.php samples/v5-final/nabor-793 …
 *   php engine/instrumenty/zamer-dzhekpotov.php --korpus
 */
require __DIR__ . '/../src/V5Blocks.php';

$плоско = static function (string $html): string {
    $html = (string) preg_replace('~(?s)<(script|style|svg)\b.*?</\1>~', ' ', $html);
    $html = (string) preg_replace('~<br\s*/?>~i', ' ', $html);
    $t = html_entity_decode((string) preg_replace('~<[^>]+>~', ' ', $html), ENT_QUOTES | ENT_HTML5, 'UTF-8');
    return trim((string) preg_replace('~\s+~u', ' ', $t));
};

$замерить = static function (string $т): array {
    $слов = max(1, count(preg_split('~\s+~u', $т) ?: []));
    $итог = [
        'слов' => $слов,
        'джекпот' => preg_match_all('~\bджекпот\w*~ui', $т),
        'куш' => preg_match_all('~\bкуш(?:а|у|ем|е|и|ей)?\b~ui', $т),
        'пар' => 0, 'мелких' => 0, 'равных' => 0, 'случаи' => [],
    ];
    // Разбор пар — v5Dzhekpoty, та же функция, что у сита: иначе замер и сито
    // дают разные числа про одно и то же (черновой замер давал один «равный»
    // там, где сито находило пять).
    foreach (v5Dzhekpoty($т) as $д) {
        $итог['пар']++;
        // Два признака считаются порознь: джекпот бывает равен выигрышу и при
        // сумме от миллиона, и первая версия замера их складывала (считала
        // «равных» только среди мелких), а потому показывала ноль там, где
        // сито находило четыре.
        if ($д['мелкий']) {
            $итог['мелких']++;
            $итог['случаи'][] = 'мелкий ' . $д['сумма'] . ' | ' . mb_substr($д['фраза'], 0, 110);
        }
        if ($д['равный']) {
            $итог['равных']++;
            $итог['случаи'][] = 'равный ' . $д['сумма'] . ' | ' . mb_substr($д['фраза'], 0, 110);
        }
    }
    return $итог;
};

$наборы = [];
if (in_array('--korpus', $argv, true)) {
    foreach (glob('/home/user/cladue/samples/v5-konkurent/NEW100/*', GLOB_ONLYDIR) ?: [] as $д) {
        $наборы[basename($д)] = $д;
    }
} else {
    foreach (array_slice($argv, 1) as $д) { if (is_dir($д)) { $наборы[basename($д)] = $д; } }
}
if (!$наборы) { fwrite(STDERR, "нужны папки наборов или --korpus\n"); exit(2); }

$подробно = count($наборы) <= 12;
$свод = ['пар' => [], 'мелких' => [], 'равных' => [], 'плотность' => [], 'куш' => []];
foreach ($наборы as $имя => $д) {
    $н = ['пар' => 0, 'мелких' => 0, 'равных' => 0, 'джекпот' => 0, 'куш' => 0, 'слов' => 0, 'случаи' => []];
    foreach (glob("$д/*.html") ?: [] as $ф) {
        $м = $замерить($плоско((string) file_get_contents($ф)));
        foreach (['пар', 'мелких', 'равных', 'джекпот', 'куш', 'слов'] as $k) { $н[$k] += $м[$k]; }
        foreach ($м['случаи'] as $c) { $н['случаи'][] = basename($ф, '.html') . ': ' . $c; }
    }
    $свод['пар'][] = $н['пар'];
    $свод['мелких'][] = $н['мелких'];
    $свод['равных'][] = $н['равных'];
    $свод['плотность'][] = $н['слов'] ? $н['джекпот'] * 1000 / $н['слов'] : 0.0;
    $свод['куш'][] = $н['слов'] ? $н['куш'] * 1000 / $н['слов'] : 0.0;
    if ($подробно) {
        printf("%s: пар %d, мельче млн %d, равных выигрышу %d, «джекпот» %.2f/1000, «куш» %.2f/1000\n",
            $имя, $н['пар'], $н['мелких'], $н['равных'],
            end($свод['плотность']), end($свод['куш']));
        foreach ($н['случаи'] as $c) { echo "    • $c\n"; }
    }
}
$мед = static function (array $v): float {
    sort($v); $n = count($v);
    return $n % 2 ? (float) $v[intdiv($n, 2)] : ($v[$n / 2 - 1] + $v[$n / 2]) / 2;
};
$ср = static fn (array $v): float => array_sum($v) / max(1, count($v));
printf("\nнаборов %d | пар ср %.2f мед %.1f | мельче млн ср %.2f мед %.1f | равных ср %.2f"
     . " | «джекпот»/1000 ср %.2f мед %.2f | «куш»/1000 ср %.2f\n",
    count($наборы), $ср($свод['пар']), $мед($свод['пар']), $ср($свод['мелких']), $мед($свод['мелких']),
    $ср($свод['равных']), $ср($свод['плотность']), $мед($свод['плотность']), $ср($свод['куш']));
printf("наборов с мелким джекпотом: %d из %d\n",
    count(array_filter($свод['мелких'], static fn ($x): bool => $x > 0)), count($наборы));
