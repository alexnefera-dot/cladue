/**
 * Замер джекпотов: сколько раз названа сумма джекпота, сколько из них мельче
 * миллиона, сколько совпадает с выигрышем героя — и какой ценой, то есть с
 * какой плотностью слово «джекпот» живёт в наборе.
 *
 * ЗАЧЕМ. Сито связности ловит два нарушения («джекпот мельче миллиона»,
 * «джекпот равен выигрышу»), но не показывает ни полосу корпуса, ни цену
 * правки. Плотность ключа «джекпот» добирается подменой «куш» → «джекпот»
 * (v5DoborBonusa), и любой запрет на эту подмену плотность роняет. Здесь оба
 * числа стоят рядом, чтобы правка не выменивала нарушение на выпадение из
 * полосы.
 *
 * ПОЛОСА КОРПУСА (NEW100, сто наборов, октябрь 2026):
 *   пар «джекпот + сумма» — 36.9 на набор, дециль 8…67;
 *   мельче миллиона — 0.09 на набор, хотя бы одна у 8 наборов из ста;
 *   равных названному выигрышу — 0.18 на набор;
 *   «джекпот» — 3.30 на 1000 слов (медиана 3.23), «куш» — 1.86.
 *
 * Сырым счётом «мельче миллиона» было 0.28, и три вычета довели её до 0.09:
 * пять случаев из двадцати восьми — отрицание («выиграл не джекпот, но
 * приятные 520 тысяч»), четыре — составное («джекпот-зона», «сектор
 * джекпота»), двенадцать — сумма другой роли рядом со словом («Лимит на вывод
 * джекпота — 87к в сутки»), которую движок и так берёт из банка историй.
 * «Равных» сырым счётом было 0.45: половину дали фразы вида «сорвал джекпот
 * 120 млн» — одно утверждение, а не спор.
 *
 * ДЛЯ СРАВНЕНИЯ. Набор 782, который читал человек: 25 мелких и 8 равных на
 * один набор — то есть превышение корпуса в 280 и 44 раза. Партия 793–797:
 * 1.60 и 0.00. Партия 798–802: 0.20 и 0.20. Партия 803–807: 0.00 и 0.00.
 *
 * РЕЖИМ --pravilo. Обратная проверка правила v5DzhekpotPered по пулам: не
 * «сколько поймало», а «сколько случаев, где слово „джекпот" и прорезь суммы
 * стоят в одной фразе, оно пропустило». Детерминированная, не зависит ни от
 * сида, ни от отбора записей. Именно её не хватало, когда окно правила было
 * сорок символов.
 *
 * Запуск:
