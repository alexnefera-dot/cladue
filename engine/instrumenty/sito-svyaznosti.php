<?php
declare(strict_types=1);
/**
 * Сито связности: проверка готового набора на то, что видит читатель.
 *
 * ЗАЧЕМ ОНО ЕСТЬ. Ворота драйвера, приёмка, смысл и сверка меряют плотности и
 * распределения — сколько слов в абзаце, сколько ссылок на страницу, как
 * разложены доли по корпусным полосам. Ни одна из этих мерок не умеет сказать
 * «джекпот не может быть равен выигрышу героя» или «у имени одна история».
 * Набор 782 прошёл все четыре гейта и при этом нёс:
 *
 *   — джекпот, равный кушу героя той же страницы (37 случаев на шесть наборов);
 *   — пятнадцать разных процентов приветственного пакета на двенадцать страниц;
 *   — одно имя с тремя разными историями на трёх страницах (21 имя из 21);
 *   — дословно повторённый зачин-механизм (четыре раза в одном наборе);
 *   — анкер в падеже, которого не требует управление (семь случаев).
 *
 * Каждый из этих дефектов нашёл человек, прочитав двенадцать страниц. Сито
 * существует, чтобы такое чтение не требовалось дважды: инвариант, однажды
 * найденный глазами, дальше проверяется машиной.
 *
 * ЧЕМ ОНО НЕ ЯВЛЯЕТСЯ. Это не мерка близости к корпусу. Сито не говорит «так у
 * доноров» — оно говорит «так не бывает ни у кого»: сумма не может быть
 * одновременно джекпотом и выигрышем, имя не может принадлежать двум людям,
 * предложение не может требовать двух падежей. Корпусные полосы живут в
 * приёмке, инварианты — здесь.
 *
 * Запуск:
 *   php engine/instrumenty/sito-svyaznosti.php samples/v5-final/nabor-782
 *   php engine/instrumenty/sito-svyaznosti.php <папка> --json
 */

$корень = dirname(__DIR__, 2);
require $корень . '/engine/src/V5Blocks.php';

$папка = $argv[1] ?? '';
$какJson = in_array('--json', $argv, true);
if ($папка === '' || !is_dir($папка)) {
    fwrite(STDERR, "нужна папка набора\n");
    exit(2);
}

$пулы = json_decode((string) file_get_contents($корень . '/engine/data-v5/pools.json'), true);
$именаБанка = array_flip(array_merge(
    array_keys($пулы['общие']['банки']['ИМЯ'] ?? []),
    array_keys($пулы['общие']['банки']['ИМЯЖ'] ?? [])
));
$механизмы = array_map(
    static fn (array $x): string => trim((string) preg_replace('~<[^>]+>~', '', (string) ($x['т'] ?? ''))),
    $пулы['общие']['механизмГероя'] ?? []
);

/** Текст страницы без скриптов, стилей и тегов. Тег стыкуется без пробела. */
$плоско = static function (string $html): string {
    $html = (string) preg_replace('~(?s)<(script|style|svg)\b.*?</\1>~', ' ', $html);
    // Тег заменяется ПУСТОТОЙ, а не пробелом: иначе «казино</a>, чтобы»
    // читается как «казино , чтобы», и мерка выдумывает пробел перед запятой,
    // которого на странице нет. Это уже случалось — доклад о чтении 782
    // сообщал о 255 таких пробелах, и все 255 были артефактом извлечения.
    $html = (string) preg_replace('~</?(?:a|strong|b|em|i|span|sup|sub|u|mark|small)\b[^>]*>~i', '', $html);
    $html = (string) preg_replace('~<[^>]+>~', ' ', $html);
    return trim((string) preg_replace('~\s+~u', ' ', html_entity_decode($html, ENT_QUOTES | ENT_HTML5, 'UTF-8')));
};

/** Разделы страницы: текст от одного <h2> до следующего. */
$разделы = static function (string $html) use ($плоско): array {
    $html = (string) preg_replace('~(?s)<(script|style|svg)\b.*?</\1>~', ' ', $html);
    $части = preg_split('~(?i)<h2\b~', $html);
    return array_map($плоско, array_map(static fn (string $x): string => '<h2' . $x, array_slice($части ?: [], 1)));
};

$СУММА  = '(\d[\d\s]*(?:[.,]\d+)?\s*(?:млн|тыс|к\b))';
$ВЫИГРЫШ = '(?:вывел|вывела|снял|сняла|забрал|забрала|поднял|подняла|выиграл|выиграла|сорвал|сорвала'
    . '|вынес|вынесла|унёс|унесла|довёл|довела|вытащил|вытащила|вышел\s+с|вышла\s+с)';

$страницы = [];
foreach (glob(rtrim($папка, '/') . '/*.html') ?: [] as $ф) {
    $страницы[basename($ф, '.html')] = (string) file_get_contents($ф);
}
if (!$страницы) { fwrite(STDERR, "в папке нет страниц\n"); exit(2); }

$нарушения = [];
$добавить = static function (string $правило, string $где, string $что) use (&$нарушения): void {
    $нарушения[] = ['правило' => $правило, 'где' => $где, 'что' => mb_substr($что, 0, 160)];
};

// 1. Джекпот не равен названному выигрышу — и не мельче миллиона.
foreach ($страницы as $тип => $html) {
    $т = $плоско($html);
    // Между словом «джекпот» и суммой не должно стоять глагола выигрыша: в
    // заголовке «Джекпот слоты — Борис сорвал 87к здесь» первое слово — часть
    // ключевой фразы типа, а сумма принадлежит герою. Первая версия правила
    // считала это нарушением, и зря.
    preg_match_all('~[Дд]жекпот\w*((?:(?!' . $ВЫИГРЫШ . ')[^.!?]){0,40}?)' . $СУММА . '~u', $т, $дж);
    preg_match_all('~' . $ВЫИГРЫШ . '\w*[^.!?]{0,30}?' . $СУММА . '~u', $т, $выи);
    $нормА = static fn (string $x): string => (string) preg_replace('~\s~u', '', $x);
    $выиграно = array_map($нормА, $выи[1] ?? []);
    foreach ($дж[2] ?? [] as $v) {
        if (in_array($нормА($v), $выиграно, true)) {
            $добавить('джекпот равен выигрышу', $тип, 'джекпот ' . trim($v) . ' — он же назван выигрышем');
        }
        if (!preg_match('~млн|миллион~u', $v) && v5Summa(trim($v)) < 1_000_000) {
            $добавить('джекпот мельче миллиона', $тип, 'джекпот ' . trim($v));
        }
    }
}

// 2. Процент приветственного пакета — один на набор.
$пакетные = [];
foreach ($страницы as $тип => $html) {
    $т = $плоско($html);
    if (preg_match_all('~(?:пакет|приветственн\w+)[^.!?]{0,40}?(\d{2,4})\s?%~ui', $т, $м)) {
        foreach ($м[1] as $v) { $пакетные[$v][$тип] = 1; }
    }
}
// У доноров значений пакета 3–10 на набор (docs/konkurenty-ABC.md), поэтому
// два-три числа — не нарушение, а четыре и больше — уже спор с самим собой.
if (count($пакетные) > 3) {
    $свод = [];
    foreach ($пакетные as $v => $где) { $свод[] = $v . '% (' . implode(', ', array_keys($где)) . ')'; }
    $добавить('пакет звучит разными числами', 'набор', implode('; ', $свод));
}

// 3. У имени — одна история.
$истории = [];
foreach ($страницы as $тип => $html) {
    foreach ($разделы($html) as $р) {
        preg_match_all('~\b([А-ЯЁ][а-яё]{2,11})\b~u', $р, $им);
        $кто = null; $лучший = 0; $счёт = [];
        foreach ($им[1] ?? [] as $и) { if (isset($именаБанка[$и])) { $счёт[$и] = ($счёт[$и] ?? 0) + 1; } }
        foreach ($счёт as $и => $n) { if ($n > $лучший) { $лучший = $n; $кто = $и; } }
        if ($кто === null) { continue; }
        if (preg_match_all('~' . $ВЫИГРЫШ . '\w*[^.!?]{0,30}?' . $СУММА . '~u', $р, $с)) {
            foreach ($с[1] as $v) { $истории[$кто][trim((string) preg_replace('~\s~u', '', $v))][$тип] = 1; }
        }
    }
}
foreach ($истории as $имя => $суммы) {
    if (count($суммы) < 2) { continue; }
    $страницыИмени = [];
    foreach ($суммы as $где) { $страницыИмени += $где; }
    if (count($страницыИмени) < 2) { continue; }   // внутри одной страницы это рост суммы, а не спор
    $добавить('одно имя — разные истории', implode(', ', array_keys($страницыИмени)),
        $имя . ': ' . implode(' | ', array_keys($суммы)));
}

// 4. Зачин-механизм не повторяется дословно.
$всёПодряд = implode(' ', array_map($плоско, $страницы));
foreach ($механизмы as $м) {
    if ($м === '') { continue; }
    $n = substr_count($всёПодряд, mb_substr($м, 0, 60));
    if ($n > 1) { $добавить('механизм повторён дословно', 'набор', '×' . $n . ' ' . mb_substr($м, 0, 70)); }
}

// 5. Падеж анкора: проход v5AnkorPoPadezhu должен был всё снять. Если здесь
//    что-то есть — завелась новая рамка, и её надо добавить в проход.
$рамки = [
    'к + им.п.' => '~\b(?:к|ко)\s+<a\b[^>]*>\s*(?:раздел|вход|обзор|каталог|информация|информацию|новости)\b~ui',
    'управляющий глагол + ярлык' => '~\b(?:используй|смотри|проверь|выбери|открой|читай|изучи|сравни)\w*\s+'
        . '<a\b[^>]*>\s*(?:войти|войди|заходи|играй|играть|зарегистрируйся|скачай)\b~ui',
    'прилагательное + ярлык' => '~\b(?:быстрый|быстрая|простой|простая|удобный|удобная|надёжный|новый|полный|свежий)\w*\s+'
        . '<a\b[^>]*>\s*(?:войти|войди|играй|играть|зарегистрируйся|скачай)\b~ui',
    'подлежащее в вин.п.' => '~<a\b[^>]*>\s*(?:информацию|регистрацию)[^<]{0,40}</a>\s+'
        . '(?:объясня|говор|пиш|советова|помога|реша)\w+'
        . '|\b(?:объясня|говор|пиш|советова|помога|реша)\w+\s+<a\b[^>]*>\s*(?:информацию|регистрацию)\b'
        . '|,\s*[а-яё]+\s+и\s+<a\b[^>]*>\s*(?:информацию|регистрацию)\b~ui',
];
foreach ($страницы as $тип => $html) {
    foreach ($рамки as $имя => $рег) {
        if (preg_match_all($рег, $html, $м)) {
            foreach ($м[0] as $x) {
                $добавить('падеж анкора: ' . $имя, $тип, trim((string) preg_replace('~\s+~u', ' ', strip_tags($x))));
            }
        }
    }
}

// 6. Обращение: набор на «ты» не говорит «вы».
$обращение = 'ты';
$нб = rtrim($папка, '/') . '/nabor.json';
if (is_file($нб)) {
    $j = json_decode((string) file_get_contents($нб), true);
    $обращение = (string) ($j['обращение'] ?? ($j['паспорт']['обращение'] ?? 'ты'));
}
if ($обращение === 'ты') {
    $ВЫ = '~(?<![а-яё])(?:вы|вас|вам|вами|ваш\w*|читайте|ставьте|оставьте|будьте|учитывайте|заходите'
        . '|настройте|проходите|жмите|рискуете|понимаете|ищете|закройте|получайте|остановитесь|наслаждайтесь)(?![а-яё])~ui';
    foreach ($страницы as $тип => $html) {
        $т = $плоско($html);
        if (preg_match_all($ВЫ, $т, $м)) {
            $добавить('«вы» в «ты»-наборе', $тип, count($м[0]) . ' шт.: ' . implode(', ', array_slice(array_unique($м[0]), 0, 8)));
        }
    }
}

if ($какJson) {
    echo json_encode(['набор' => basename(rtrim($папка, '/')), 'нарушений' => count($нарушения),
                      'нарушения' => $нарушения], JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT), "\n";
    exit($нарушения ? 1 : 0);
}
printf("сито связности: %s — нарушений %d\n", basename(rtrim($папка, '/')), count($нарушения));
$поПравилу = [];
foreach ($нарушения as $н) { $поПравилу[$н['правило']][] = $н; }
foreach ($поПравилу as $правило => $сп) {
    printf("\n%s — %d\n", $правило, count($сп));
    foreach (array_slice($сп, 0, 6) as $н) { printf("   [%s] %s\n", $н['где'], $н['что']); }
    if (count($сп) > 6) { printf("   … ещё %d\n", count($сп) - 6); }
}
exit($нарушения ? 1 : 0);
