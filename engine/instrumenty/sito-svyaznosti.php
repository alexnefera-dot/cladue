// 3. У имени — одна история.
//
// Истории считаются согласными, если делят хотя бы одно число: «с 135к поднял
// до 330к» на обзоре и «вытащил 135к» на входе — один вечер, рассказанный с
// разной подробностью, а не спор. Спор — это когда числа не пересекаются
// вовсе: «вывел 180к» на бонусах и «выиграл 38к» в FAQ новостей.
$истории = [];
foreach ($страницы as $тип => $html) {
    foreach ($разделы($html) as $р) {
        preg_match_all('~\b([А-ЯЁ][а-яё]{2,11})\b~u', $р, $им);
        $кто = null; $лучший = 0; $счёт = [];
        foreach ($им[1] ?? [] as $и) { if (isset($именаБанка[$и])) { $счёт[$и] = ($счёт[$и] ?? 0) + 1; } }
        foreach ($счёт as $и => $n) { if ($n > $лучший) { $лучший = $n; $кто = $и; } }
        if ($кто === null) { continue; }
        $свои = array_values(array_unique(array_map(
            static fn (string $v): string => trim((string) preg_replace('~\s~u', '', $v)), $выигрыши($р))));
        if ($свои) { $истории[$кто][] = ['суммы' => $свои, 'тип' => $тип]; }
    }
}
foreach ($истории as $имя => $разделыИмени) {
    $группы = [];
    foreach ($разделыИмени as $х) {
        $свои = null;
        foreach ($группы as $i => $г) {
            if (!array_intersect($г['суммы'], $х['суммы'])) { continue; }
            if ($свои === null) {
                $группы[$i]['суммы'] = array_values(array_unique(array_merge($г['суммы'], $х['суммы'])));
                $группы[$i]['типы'][$х['тип']] = 1;
                $свои = $i;
            } else {
                // Запись связала две группы — сливаем их в одну.
                $группы[$свои]['суммы'] = array_values(array_unique(array_merge($группы[$свои]['суммы'], $г['суммы'])));
                $группы[$свои]['типы'] += $г['типы'];
                unset($группы[$i]);
            }
        }
        if ($свои === null) { $группы[] = ['суммы' => $х['суммы'], 'типы' => [$х['тип'] => 1]]; }
        $группы = array_values($группы);
    }
    if (count($группы) < 2) { continue; }
    $страницыИмени = []; $подписи = [];
    foreach ($группы as $г) {
        $страницыИмени += $г['типы'];
        $подписи[] = implode('/', $г['суммы']);
    }
    if (count($страницыИмени) < 2) { continue; }   // внутри одной страницы это рост суммы, а не спор
    $добавить('одно имя — разные истории', implode(', ', array_keys($страницыИмени)),
        $имя . ': ' . implode(' | ', $подписи));
}

// 4. Зачин-механизм не повторяется дословно.
$всёПодряд = implode(' ', array_map($плоско, $страницы));
foreach ($механизмы as $м) {
    if ($м === '') { continue; }
    $n = substr_count($всёПодряд, mb_substr($м, 0, 60));
    if ($n > 1) { $добавить('механизм повторён дословно', 'набор', '×' . $n . ' ' . mb_substr($м, 0, 70)); }
}

// 5. Падеж анкора: проход v5AnkorPoPadezhu должен был всё снять. Если здесь
//    что-то есть — завелась новая рамка, и её надо добавить в проход.
$рамки = [
    'к + им.п.' => '~\b(?:к|ко)\s+<a\b[^>]*>\s*(?:раздел|вход|обзор|каталог|информация|информацию|новости)\b~ui',
    'управляющий глагол + ярлык' => '~\b(?:используй|смотри|проверь|выбери|открой|читай|изучи|сравни)\w*\s+'
        . '<a\b[^>]*>\s*(?:войти|войди|заходи|играй|играть|зарегистрируйся|скачай)\b~ui',
    'прилагательное + ярлык' => '~\b(?:быстрый|быстрая|простой|простая|удобный|удобная|надёжный|новый|полный|свежий)\w*\s+'
        . '<a\b[^>]*>\s*(?:войти|войди|играй|играть|зарегистрируйся|скачай)\b~ui',
    'подлежащее в вин.п.' => '~<a\b[^>]*>\s*(?:информацию|регистрацию)[^<]{0,40}</a>\s+'
        . '(?:объясня|говор|пиш|советова|помога|реша)\w+'
        . '|\b(?:объясня|говор|пиш|советова|помога|реша)\w+\s+<a\b[^>]*>\s*(?:информацию|регистрацию)\b'
        . '|,\s*[а-яё]+\s+и\s+<a\b[^>]*>\s*(?:информацию|регистрацию)\b~ui',
];
foreach ($страницы as $тип => $html) {
    foreach ($рамки as $имя => $рег) {
        if (preg_match_all($рег, $html, $м)) {
            foreach ($м[0] as $x) {
                $добавить('падеж анкора: ' . $имя, $тип, trim((string) preg_replace('~\s+~u', ' ', strip_tags($x))));
            }
        }
    }
}

// 6. Обращение: однородный ряд императивов — в одном регистре.
//
// Здесь стояло «набор на „ты" не говорит „вы"», и это была не инварианта, а
// корпусная полоса, выданная за инварианту — ровно то, чего эта мерка себе
// не позволяет. Счёт по 99 наборам NEW100 той же меркой: из 59 «ты»-наборов
// монолитен ОДИН, медиана доли «вы» среди местоимений 13.0 %, «вы»-блоков на
// набор 43 по медиане, и целый раздел на «вы» среди «ты»-разделов — тоже
// норма (8.2 % разделов чисто «вы», 11.0 % смешаны). У набора 782 доля была
// 10.2 % при корпусной медиане 13.0 %: по этой мерке набор стоял в полосе, и
// девять «нарушений», о которых докладывал замер правки анкеров, нарушениями
// не были. Доля живёт в перекруте (поле vy_share) и проверяется замером
// engine/instrumenty/zamer-obrashcheniya.php, а не здесь.
//
// Инварианта узкая: однородный ряд императивов не бывает в двух регистрах.
// «Читай условия, считай цифры, тестируйте», «остановитесь и запроси
// помощь», «Найди информацию о входе и выйдите победителем» — это не выбор
// регистра, а поломка согласования. У корпуса такого 0.29 на набор (медиана 0,
// max 3; шесть случаев из семнадцати — артефакт склейки заголовка с текстом,
// так что чистая частота около 0.19), у нас на восьми парных наборах выходило
// 1.12, и делал их один проход — потолок вежливого императива, снимавший формы
// по одной внутри уже переведённой фразы.
foreach ($страницы as $тип => $html) {
    foreach ($абзацы($html) as $абз) {
        foreach (preg_split('~(?<=[.!?])\s+~u', $абз) ?: [] as $фраза) {
            $р = v5RegistrFrazy($фраза);
            if (!$р['тыИмп'] || !$р['выИмп']) { continue; }
            $добавить('два регистра в одном ряду', $тип,
                implode('/', array_unique($р['тыИмп'])) . ' + ' . implode('/', array_unique($р['выИмп']))
                . ' — «' . mb_substr(trim($фраза), 0, 110) . '»');
        }
    }
}

// 7. Ответ FAQ — ответ на свой вопрос, а не склейка чужих.
//
// Запись пула у нас короче донорской (33 слова медианой против 56), и длину
// добирал добор предложения из другой записи. Родством считалась одна общая
// основа от пяти букв, и этого хватало, чтобы к «Отличается ли игра с
// телефона?» приклеить «Почту и телефон можно поменять в настройках», а к
// «Можно ли увидеть историю всех бонусов?» — ответы про исключённые автоматы
// и про вывод бонусных денег. На отданном наборе 782 так склеено 24 ответа
// из 53, по две-три записи в одном.
//
// Инварианта: у вопроса один ответ. Запись-близнец по вопросу
// (v5BliznetsVoprosa) склейкой не считается — это тот же вопрос другими
// словами, и разворачивать его подробностью нормально. Концовка из банка
// faqКонцовки тоже не считается: она обращена к решению читателя, а не к
// другому вопросу.
$хвосты = $пулы['хвосты'] ?? [];
$скелетФразы = static function (string $s): string {
    $s = mb_strtolower((string) preg_replace('~<[^>]+>~', '', $s));
    $s = (string) preg_replace(['~\{[^}]*\}~u', '~%[a-z_]+%~', '~[\d.,]+~u'], ['#', '#', '#'], $s);
    return trim((string) preg_replace('~\s+~u', ' ', (string) preg_replace('~[^а-яёa-z#]~u', ' ', $s)));
};
$фразыОтвета = static function (string $s): array {
    $чист = trim((string) preg_replace('~\s+~u', ' ',
        html_entity_decode((string) preg_replace('~<[^>]+>~', '', $s), ENT_QUOTES | ENT_HTML5, 'UTF-8')));
    $в = [];
    foreach (preg_split('~(?<=[.!?])\s+~u', $чист) ?: [] as $ф) {
        if (count(preg_split('~\s+~u', trim($ф), -1, PREG_SPLIT_NO_EMPTY)) >= 8) { $в[] = $ф; }
    }
    return $в;
};
foreach ($страницы as $тип => $html) {
    $faq = $хвосты[$тип]['faq'] ?? [];
    if (!$faq) { continue; }
    $индекс = [];
    foreach ($faq as $i => $x) {
        foreach ($фразыОтвета((string) ($x['о'] ?? '')) as $ф) {
            $к = $скелетФразы($ф);
            if (mb_strlen($к) > 25) { $индекс[$к][$i] = true; }
        }
    }
    // Строка, живущая больше чем в трёх записях, — общая формула, а не улика.
    foreach ($индекс as $к => $кто) { if (count($кто) > 3) { unset($индекс[$к]); } }
    if (!preg_match_all('~<(div|article)\b[^>]*\bitemprop="mainEntity"[^>]*>(.*?)itemprop="text"[^>]*>(.*?)</div>~su',
                        $html, $блоки, PREG_SET_ORDER)) { continue; }
    foreach ($блоки as $б) {
        if (!preg_match('~itemprop="name"[^>]*>(.*?)</~su', $б[2], $мв)) { continue; }
        $вопрос = trim((string) preg_replace('~\s+~u', ' ', (string) preg_replace('~<[^>]+>~', '', $мв[1])));
        $ответ = (string) $б[3];
        if ($вопрос === '' || trim($ответ) === '') { continue; }
        $наборы = [];
        foreach ($фразыОтвета($ответ) as $ф) {
            $к = $скелетФразы($ф);
            if (isset($индекс[$к])) { $наборы[] = array_keys($индекс[$к]); }
        }
        if (count($наборы) < 2) { continue; }
        $осталось = $наборы; $выбрано = [];
        while ($осталось) {
            $счёт = [];
            foreach ($осталось as $н) { foreach ($н as $i) { $счёт[$i] = ($счёт[$i] ?? 0) + 1; } }
            arsort($счёт);
            $луч = (int) array_key_first($счёт);
            $выбрано[] = $луч;
            $осталось = array_values(array_filter($осталось, static fn(array $н): bool => !in_array($луч, $н, true)));
        }
        foreach (array_slice($выбрано, 1) as $i) {
            $вд = trim((string) preg_replace('~\s+~u', ' ', (string) preg_replace('~<[^>]+>~', '', (string) ($faq[$i]['в'] ?? ''))));
            if ($вд === '' || v5BliznetsVoprosa($вопрос, $вд)) { continue; }
            $добавить('ответ FAQ склеен с чужим', $тип, '«' . $вопрос . '» ← ответ на «' . $вд . '»');
        }
    }
}

