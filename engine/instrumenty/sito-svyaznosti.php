/**
 * Сито связности: проверка готового набора на то, что видит читатель.
 *
 * ЗАЧЕМ ОНО ЕСТЬ. Ворота драйвера, приёмка, смысл и сверка меряют плотности и
 * распределения — сколько слов в абзаце, сколько ссылок на страницу, как
 * разложены доли по корпусным полосам. Ни одна из этих мерок не умеет сказать
 * «джекпот не может быть равен выигрышу героя» или «у имени одна история».
 * Набор 782 прошёл все четыре гейта и при этом нёс:
 *
 *   — джекпот, равный кушу героя той же страницы, и джекпот мельче миллиона
 *     (на самом 782 — 8 и 25 случаев; число «37 на шесть наборов» из первой
 *     записи считало вперемешку и фразу «сорвал джекпот 120 млн», в которой
 *     никакого спора нет);
 *   — пятнадцать разных процентов приветственного пакета на двенадцать страниц;
 *   — одно имя с тремя разными историями на трёх страницах (21 имя из 21);
 *   — дословно повторённый зачин-механизм (четыре раза в одном наборе);
 *   — анкер в падеже, которого не требует управление (семь случаев).
 *
 * Каждый из этих дефектов нашёл человек, прочитав двенадцать страниц. Сито
 * существует, чтобы такое чтение не требовалось дважды: инвариант, однажды
 * найденный глазами, дальше проверяется машиной.
 *
 * ЧЕМ ОНО НЕ ЯВЛЯЕТСЯ. Это не мерка близости к корпусу. Сито не говорит «так у
 * доноров» — оно говорит «так не бывает ни у кого»: имя не может принадлежать
 * двум людям, предложение не может требовать двух падежей. Корпусные полосы
 * живут в приёмке, инварианты — здесь.
 *
 * ГДЕ ЭТО НЕ СОВСЕМ ТАК. Два правила про джекпот — не чистые инварианты, и
 * числа у них измеренные, а не объявленные (замер: zamer-dzhekpotov.php,
 * корпус NEW100, сто наборов):
 *
 *   «мельче миллиона» — у доноров 0.09 случая на набор, хотя бы один у 8
 *   наборов из ста. То есть сумма меньше миллиона рядом со словом «джекпот» у
 *   них бывает, но набор с нею — исключение. У набора 782, который читал
 *   человек, таких случаев 25 на один набор;
 *
 *   «равен выигрышу» — 0.18 на набор. У 782 их восемь.
 *
 * Оба правила оставлены здесь, а не в приёмке, потому что превышение у 782
 * двухпорядковое — 280 и 44 корпусных нормы. Полоса, в которую сто чужих
 * наборов упираются на уровне «ноль-одна штука», работает как инвариант, а не
 * как распределение. Но считать её нулём нельзя — это уже случалось с правилом
 * про регистр, и ложная мерка тогда не выдумала дефект, а спрятала настоящий.
 *
 * Решение «названа ли сумма джекпотом» сито не принимает само: его принимает
 * v5DzhekpotPered — тот же предикат, по которому движок выбирает прорези банк.
 * Иначе два счёта одного и того же расходятся, и это уже было: на наборе 805
 * движок верно оставил «Лимит на вывод джекпота — 87к в сутки» суточным
 * лимитом, а сито читало его как джекпот мельче миллиона.
 *
 * Запуск:
 *   php engine/instrumenty/sito-svyaznosti.php samples/v5-final/nabor-782
 *   php engine/instrumenty/sito-svyaznosti.php <папка> --json
