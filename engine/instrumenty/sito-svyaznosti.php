// 1. Джекпот не равен названному выигрышу — и не мельче миллиона.
foreach ($страницы as $тип => $html) {
    $т = $плоско($html);
    // Между словом «джекпот» и суммой не должно стоять глагола выигрыша: в
    // заголовке «Джекпот слоты — Борис сорвал 87к здесь» первое слово — часть
    // ключевой фразы типа, а сумма принадлежит герою. Первая версия правила
    // считала это нарушением, и зря.
    preg_match_all('~[Дд]жекпот\w*((?:(?!' . $ВЫИГРЫШ . ')[^.!?]){0,40}?)' . $СУММА . '~u', $т, $дж);
    $нормА = static fn (string $x): string => (string) preg_replace('~\s~u', '', $x);
    $выиграно = array_map($нормА, $выигрыши($т));
    foreach ($дж[2] ?? [] as $v) {
        if (in_array($нормА($v), $выиграно, true)) {
            $добавить('джекпот равен выигрышу', $тип, 'джекпот ' . trim($v) . ' — он же назван выигрышем');
        }
        if (!preg_match('~млн|миллион~u', $v) && v5Summa(trim($v)) < 1_000_000) {
            $добавить('джекпот мельче миллиона', $тип, 'джекпот ' . trim($v));
        }
    }
}

