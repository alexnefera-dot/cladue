// 3. У имени — одна история.
//
// Истории считаются согласными, если делят хотя бы одно число: «с 135к поднял
// до 330к» на обзоре и «вытащил 135к» на входе — один вечер, рассказанный с
// разной подробностью, а не спор. Спор — это когда числа не пересекаются
// вовсе: «вывел 180к» на бонусах и «выиграл 38к» в FAQ новостей.
$истории = [];
foreach ($страницы as $тип => $html) {
    foreach ($разделы($html) as $р) {
        preg_match_all('~\b([А-ЯЁ][а-яё]{2,11})\b~u', $р, $им);
        $кто = null; $лучший = 0; $счёт = [];
        foreach ($им[1] ?? [] as $и) { if (isset($именаБанка[$и])) { $счёт[$и] = ($счёт[$и] ?? 0) + 1; } }
        foreach ($счёт as $и => $n) { if ($n > $лучший) { $лучший = $n; $кто = $и; } }
        if ($кто === null) { continue; }
        $свои = array_values(array_unique(array_map(
            static fn (string $v): string => trim((string) preg_replace('~\s~u', '', $v)), v5NazvannyeVyigryshi($р))));
        if ($свои) { $истории[$кто][] = ['суммы' => $свои, 'тип' => $тип]; }
    }
}
foreach ($истории as $имя => $разделыИмени) {
    $группы = [];
    foreach ($разделыИмени as $х) {
        $свои = null;
        foreach ($группы as $i => $г) {
            if (!array_intersect($г['суммы'], $х['суммы'])) { continue; }
            if ($свои === null) {
                $группы[$i]['суммы'] = array_values(array_unique(array_merge($г['суммы'], $х['суммы'])));
                $группы[$i]['типы'][$х['тип']] = 1;
                $свои = $i;
            } else {
                // Запись связала две группы — сливаем их в одну.
                $группы[$свои]['суммы'] = array_values(array_unique(array_merge($группы[$свои]['суммы'], $г['суммы'])));
                $группы[$свои]['типы'] += $г['типы'];
                unset($группы[$i]);
            }
        }
        if ($свои === null) { $группы[] = ['суммы' => $х['суммы'], 'типы' => [$х['тип'] => 1]]; }
        $группы = array_values($группы);
    }
    if (count($группы) < 2) { continue; }
    $страницыИмени = []; $подписи = [];
    foreach ($группы as $г) {
        $страницыИмени += $г['типы'];
        $подписи[] = implode('/', $г['суммы']);
    }
    if (count($страницыИмени) < 2) { continue; }   // внутри одной страницы это рост суммы, а не спор
    $добавить('одно имя — разные истории', implode(', ', array_keys($страницыИмени)),
        $имя . ': ' . implode(' | ', $подписи));
}

