/** Абзацы и пункты страницы по отдельности: предложение не бывает длиннее блока. */
$абзацы = static function (string $html): array {
    $html = (string) preg_replace('~(?s)<(script|style|svg)\b.*?</\1>~', ' ', $html);
    $html = (string) preg_replace('~<br\s*/?>~i', ' ', $html);
    $вышло = [];
    if (preg_match_all('~<(p|li|h1|h2|h3|h4|td|th|dd|dt|blockquote|figcaption)\b[^>]*>(.*?)</\1>~su',
                       $html, $м, PREG_SET_ORDER)) {
        foreach ($м as $x) {
            $t = html_entity_decode((string) preg_replace('~<[^>]+>~', '', $x[2]), ENT_QUOTES | ENT_HTML5, 'UTF-8');
            $t = trim((string) preg_replace('~\s+~u', ' ', $t));
            if ($t !== '' && preg_match('~[а-яё]~iu', $t)) { $вышло[] = $t; }
        }
    }
    return $вышло;
};

/** Текст страницы без скриптов, стилей и тегов. Тег стыкуется без пробела. */
$плоско = static function (string $html): string {
    $html = (string) preg_replace('~(?s)<(script|style|svg)\b.*?</\1>~', ' ', $html);
    // Тег заменяется ПУСТОТОЙ, а не пробелом: иначе «казино</a>, чтобы»
    // читается как «казино , чтобы», и мерка выдумывает пробел перед запятой,
    // которого на странице нет. Это уже случалось — доклад о чтении 782
    // сообщал о 255 таких пробелах, и все 255 были артефактом извлечения.
    $html = (string) preg_replace('~</?(?:a|strong|b|em|i|span|sup|sub|u|mark|small)\b[^>]*>~i', '', $html);
    $html = (string) preg_replace('~<[^>]+>~', ' ', $html);
    return trim((string) preg_replace('~\s+~u', ' ', html_entity_decode($html, ENT_QUOTES | ENT_HTML5, 'UTF-8')));
};

/** Разделы страницы: текст от одного <h2> до следующего. */
$разделы = static function (string $html) use ($плоско): array {
    $html = (string) preg_replace('~(?s)<(script|style|svg)\b.*?</\1>~', ' ', $html);
    $части = preg_split('~(?i)<h2\b~', $html);
    return array_map($плоско, array_map(static fn (string $x): string => '<h2' . $x, array_slice($части ?: [], 1)));
};

$СУММА  = '(\d[\d\s]*(?:[.,]\d+)?\s*(?:млн|тыс|к\b))';
$ВЫИГРЫШ = '(?:вывел|вывела|снял|сняла|забрал|забрала|поднял|подняла|выиграл|выиграла|сорвал|сорвала'
    . '|вынес|вынесла|унёс|унесла|довёл|довела|вытащил|вытащила|вышел\s+с|вышла\s+с)';

/**
 * Пары «глагол выигрыша + сумма» в тексте — но только те, где сумма
 * действительно чья-то история. Два оборота жанра выглядят так же и историей
 * не являются; на партии 788–792 они дали четыре мнимых нарушения из десяти:
 *
 *   безличная выкладка про отыгрыш — «Вейджер x45 — это не формальность:
 *   выиграл 5 тысяч — прокрутить нужно 225 тысяч». Подлежащего у глагола нет,
 *   сумма условная, а сито приписывало её герою раздела («Борис: 100к | 5тыс»,
 *   «Герман: 10тыс | 92к», «Геннадий: 56к | 10тысяч»);
 *
 *   обращение к читателю — «Если вы выиграли джекпот 1.3 млн, платформа
 *   обязана выплатить». Это про «вы», а не про Данила из того же раздела.
 */
$выигрыши = static function (string $т) use ($СУММА, $ВЫИГРЫШ): array {
    $итог = [];
    foreach (preg_split('~(?<=[.!?])\s+~u', $т) ?: [] as $фраза) {
        // Глагол сразу после двоеточия или тире, и фраза — про отыгрыш:
        // подлежащего нет, сумма условная.
        if (preg_match('~вейджер|прокрут|отыгра~ui', $фраза)
            && preg_match('~(?:^|[:—–-])\s*' . $ВЫИГРЫШ . '~ui', $фраза)) { continue; }
        // «вы/ты» подлежащим при глаголе выигрыша — это к читателю.
        if (preg_match('~(?<![а-яё])(?:вы|ты)\s+(?:[а-яё]+\s+){0,2}' . $ВЫИГРЫШ . '~ui', $фраза)) { continue; }
        if (preg_match_all('~' . $ВЫИГРЫШ . '\w*[^.!?]{0,30}?' . $СУММА . '~u', $фраза, $м)) {
            foreach ($м[1] as $v) { $итог[] = $v; }
        }
        // Низ диапазона роста — часть той же истории: «с 135к поднял до 330к».
        // Без него раздел отдаёт только верх, и «вытащил 135к» на другой
        // странице читается как вторая история, хотя это тот же вечер.
        if (preg_match_all('~(?<![а-яё])с\s+' . $СУММА . '\s+(?:[а-яё]+\s+){0,2}' . $ВЫИГРЫШ . '~ui', $фраза, $м2)) {
            foreach ($м2[1] as $v) { $итог[] = $v; }
        }
        if (preg_match_all('~' . $ВЫИГРЫШ . '\w*\s+(?:[а-яё]+\s+){0,2}с\s+' . $СУММА . '~ui', $фраза, $м3)) {
            foreach ($м3[1] as $v) { $итог[] = $v; }
        }
    }
    return $итог;
};

$страницы = [];
