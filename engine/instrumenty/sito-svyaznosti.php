/** Абзацы и пункты страницы по отдельности: предложение не бывает длиннее блока. */
$абзацы = static function (string $html): array {
    $html = (string) preg_replace('~(?s)<(script|style|svg)\b.*?</\1>~', ' ', $html);
    $html = (string) preg_replace('~<br\s*/?>~i', ' ', $html);
    $вышло = [];
    if (preg_match_all('~<(p|li|h1|h2|h3|h4|td|th|dd|dt|blockquote|figcaption)\b[^>]*>(.*?)</\1>~su',
                       $html, $м, PREG_SET_ORDER)) {
        foreach ($м as $x) {
            $t = html_entity_decode((string) preg_replace('~<[^>]+>~', '', $x[2]), ENT_QUOTES | ENT_HTML5, 'UTF-8');
            $t = trim((string) preg_replace('~\s+~u', ' ', $t));
            if ($t !== '' && preg_match('~[а-яё]~iu', $t)) { $вышло[] = $t; }
        }
    }
    return $вышло;
};

/** Текст страницы без скриптов, стилей и тегов. Тег стыкуется без пробела. */
$плоско = static function (string $html): string {
    $html = (string) preg_replace('~(?s)<(script|style|svg)\b.*?</\1>~', ' ', $html);
    // Тег заменяется ПУСТОТОЙ, а не пробелом: иначе «казино</a>, чтобы»
    // читается как «казино , чтобы», и мерка выдумывает пробел перед запятой,
    // которого на странице нет. Это уже случалось — доклад о чтении 782
    // сообщал о 255 таких пробелах, и все 255 были артефактом извлечения.
    $html = (string) preg_replace('~</?(?:a|strong|b|em|i|span|sup|sub|u|mark|small)\b[^>]*>~i', '', $html);
    $html = (string) preg_replace('~<[^>]+>~', ' ', $html);
    return trim((string) preg_replace('~\s+~u', ' ', html_entity_decode($html, ENT_QUOTES | ENT_HTML5, 'UTF-8')));
};

/** Разделы страницы: текст от одного <h2> до следующего. */
$разделы = static function (string $html) use ($плоско): array {
    $html = (string) preg_replace('~(?s)<(script|style|svg)\b.*?</\1>~', ' ', $html);
    $части = preg_split('~(?i)<h2\b~', $html);
    return array_map($плоско, array_map(static fn (string $x): string => '<h2' . $x, array_slice($части ?: [], 1)));
};

