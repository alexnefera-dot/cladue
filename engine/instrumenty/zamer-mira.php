<?php
declare(strict_types=1);
/**
 * Замер мира набора: сколько его слов, не повторяется ли одна и та же фраза и
 * не прорвался ли чужой мир.
 *
 * ЗАЧЕМ. Мир — приём конкурента: десять площадок из двадцати пяти пишут весь
 * комплект в одних декорациях (гладиаторы, фараон, джунгли). Мерка плотности у
 * нас была с самого начала — 37–68 слов мира на страницу, полоса снята с
 * подкорпуса A, — и по ней набор 782 стоял НИЖЕ полосы. А читатель назвал его
 * цирк тиком. Потому что тик делает не плотность, а повтор: «это реквизит, а
 * не аплодисменты» десять раз, «быстрее, чем униформисты убирают реквизит»
 * тринадцать. Эта мерка считает повтор, а не только объём.
 *
 * ЧТО СЧИТАЕТСЯ.
 *   слов мира/стр — те же основы, что считает v5SlovMira (полоса A: 37–68);
 *   фраз из мира  — сколько готовых фраз мира стоит в наборе;
 *   повтор        — наибольшее число вхождений ОДНОЙ фразы и сколько фраз
 *                   встречаются больше двух раз;
 *   чужой мир     — слова других одиннадцати миров, которых нет в своём.
 *
 * Запуск:
 *   php engine/instrumenty/zamer-mira.php samples/v5-final/nabor-782 [--показ] [--json]
 */

require dirname(__DIR__) . '/src/V5Mir.php';

$папка = $argv[1] ?? '';
$показ = in_array('--показ', $argv, true);
$какJson = in_array('--json', $argv, true);
if ($папка === '' || !is_dir($папка)) { fwrite(STDERR, "нужна папка набора\n"); exit(2); }

$нб = rtrim($папка, '/') . '/nabor.json';
$паспорт = is_file($нб) ? (json_decode((string) file_get_contents($нб), true) ?: []) : [];
$паспорт = $паспорт['паспорт'] ?? $паспорт;
$мир = $паспорт['мир'] ?? null;
$имяНабора = basename(rtrim($папка, '/'));
if (!is_array($мир)) {
    if ($какJson) { echo json_encode(['набор' => $имяНабора, 'мир' => null], JSON_UNESCAPED_UNICODE), "\n"; exit(0); }
    printf("%-16s мира нет\n", $имяНабора);
    exit(0);
}

/** Все готовые фразы мира, по кучам. */
$фразыМира = static function (array $м): array {
    $в = [];
    // Имя пакета и программы набору даёт тот же мир («Базовый лагерь» у
    // Вершины, «Парад-алле» у Шапито), и по набору оно расходится десятками
    // вхождений — это не повтор фразы, а название, которое и должно
    // повторяться. У H3 оно иногда совпадает слово в слово, и мерка считала
    // «Базовый лагерь» 46 раз повторённой фразой мира. Исключаем.
    $названия = array_filter([(string) ($м['пакет'] ?? ''), (string) ($м['программа'] ?? '')]);
    foreach (['исход', 'короткие', 'h3', 'обращение'] as $к) {
        foreach ($м[$к] ?? [] as $ф) {
            if (in_array(trim((string) $ф), $названия, true)) { continue; }
            $в[$к][] = (string) $ф;
        }
    }
    foreach (['штампы', 'объекты', 'пункты'] as $к) {
        foreach ($м[$к] ?? [] as $под => $список) {
            foreach ((array) $список as $ф) { $в[$к . '/' . $под][] = (string) $ф; }
        }
    }
    return $в;
};

$плоско = static function (string $html): string {
    $html = (string) preg_replace('~(?s)<(script|style)\b.*?</\1>~', ' ', $html);
    $html = (string) preg_replace('~<[^>]+>~', '', $html);
    return trim((string) preg_replace('~\s+~u', ' ', html_entity_decode($html, ENT_QUOTES | ENT_HTML5, 'UTF-8')));
};
/** Фраза ищется без тегов и без хвостовой пунктуации: вставка их меняет. */
$ключФразы = static function (string $ф) use ($плоско): string {
    $ф = mb_strtolower($плоско($ф));
    $ф = (string) preg_replace('~[\s\p{P}]+~u', ' ', $ф);
    return trim($ф);
};

$страницы = [];
foreach (glob(rtrim($папка, '/') . '/*.html') ?: [] as $ф) {
    $страницы[basename($ф, '.html')] = (string) file_get_contents($ф);
}

$словМира = 0;
$текстНабора = '';
foreach ($страницы as $html) {
    $словМира += v5SlovMira($html, $мир);
    $текстНабора .= ' ' . mb_strtolower((string) preg_replace('~[\s\p{P}]+~u', ' ', $плоско($html)));
}
$текстНабора = (string) preg_replace('~\s+~u', ' ', $текстНабора);

// Повторы готовых фраз.
$повторы = [];
foreach ($фразыМира($мир) as $куча => $список) {
    foreach ($список as $ф) {
        $к = $ключФразы($ф);
        // Короткая строка ловится подстрокой чужого слова: «купол» и «ложа»
        // давали по тридцать «повторов» из одного «под куполом» и «положил».
        // Поэтому считаются фразы от четырнадцати знаков и по границам слов.
        if (mb_strlen($к) < 14) { continue; }
        $n = preg_match_all('~(?<![а-яё])' . preg_quote($к, '~') . '(?![а-яё])~u', $текстНабора);
        if ($n > 0) { $повторы[] = ['куча' => $куча, 'фраза' => $плоско($ф), 'раз' => $n]; }
    }
}
usort($повторы, static fn(array $a, array $b): int => $b['раз'] <=> $a['раз']);

// «Чужого мира» эта мерка не считает, и вот почему. Первая проба считала
// слова других одиннадцати миров, которых нет в своём, и выдавала 294–516
// попаданий на набор — но попадались общие основы, стоящие у нескольких миров
// сразу: «заход», «гарант», «програ», «запас», «получи». Это не чужая
// метафора, а русский язык.
//
// Настоящая чужая шкура (сафари, прайд, саванна, следопыт) проверена отдельно
// по корпусу, и она оказалась НОРМОЙ: среди наборов NEW100, где такое слово
// есть, медиана — ОДНО вхождение («сафари» в 13 наборах из 100, 12 из них с
// одним вхождением; «охота» в 30, 26 из них с одним). Мир у конкурента либо
// занимает набор целиком (саванна 105 раз, тропа 130), либо встречается разом
// и мимоходом. У нас 1–6 разрозненных попаданий на набор — это вторая картина,
// то есть полоса корпуса, а не дефект. Поэтому здесь её нет.

$свод = [
    'набор' => $имяНабора,
    'мир' => (string) ($мир['имя'] ?? '?'),
    'страниц' => count($страницы),
    'словМираНаСтраницу' => count($страницы) ? round($словМира / count($страницы), 1) : 0.0,
    'фразМира' => count($повторы),
    'повторМакс' => $повторы ? $повторы[0]['раз'] : 0,
    'фразСвышеДвух' => count(array_filter($повторы, static fn(array $x): bool => $x['раз'] > 2)),
];
if ($какJson) { echo json_encode($свод, JSON_UNESCAPED_UNICODE), "\n"; exit(0); }
printf("%-16s мир %-18s слов мира/стр %5.1f (цель движка 28–45, полоса A 37–68)  фраз %3d  повтор до %2d  фраз >2 раз %2d\n",
    $свод['набор'], $свод['мир'], $свод['словМираНаСтраницу'], $свод['фразМира'],
    $свод['повторМакс'], $свод['фразСвышеДвух']);
if ($показ) {
    echo "\n  самые частые фразы мира:\n";
    foreach (array_slice($повторы, 0, 12) as $x) {
        printf("   %2d× [%s] %s\n", $x['раз'], $x['куча'], mb_substr($x['фраза'], 0, 110));
    }
}
