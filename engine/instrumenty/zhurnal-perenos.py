# -*- coding: utf-8 -*-
"""Перенос истории журнала при переписывании текстов пулов.

Ключ журнала — «метка|md5(текст записи)», а невыданная запись в отборе идёт
вне очереди. Значит правка текста записи обнуляет её историю: запись выглядит
свежей и вытесняет из наборов те, что лежат в журнале честно. Инструмент
сверяет пулы до и после правки по одинаковым путям и переносит историю со
старого хеша на новый.

  python3 engine/instrumenty/zhurnal-perenos.py пулы-до.json пулы-после.json \
      vydano.json vydano-новый.json [--проверка]

При совпадении нового ключа с уже существующим остаётся запись с бо́льшим
номером набора: история не удлиняется, запись не выглядит давней.
"""
import hashlib, json, re, sys

НАБОР = re.compile(r'(\d+)')


def строки(файл):
    """Все строковые значения дерева, по пути до каждого."""
    корень = json.load(open(файл, encoding='utf-8'))
    итог = {}

    def го(узел, путь=''):
        if isinstance(узел, dict):
            for ключ, знач in узел.items():
                го(знач, путь + '/' + str(ключ))
        elif isinstance(узел, list):
            for i, знач in enumerate(узел):
                го(знач, путь + '[' + str(i) + ']')
        elif isinstance(узел, str):
            итог[путь] = узел

    го(корень)
    return итог


def карта(до, после):
    """Старый md5 → новый md5 для записей, чей текст переписан на месте."""
    итог = {}
    for путь, текст in до.items():
        новый = после.get(путь)
        if новый is None or новый == текст:
            continue
        итог[hashlib.md5(текст.encode()).hexdigest()] = hashlib.md5(новый.encode()).hexdigest()
    return итог


def номер(значение):
    найдено = НАБОР.search(str(значение))
    return int(найдено.group(1)) if найдено else -1


def перенести(журнал, пары):
    итог, перенесено, слито = {}, 0, 0
    for ключ, значение in журнал.items():
        срез = ключ.rfind('|')
        хеш = ключ[срез + 1:] if срез >= 0 else ''
        if хеш in пары:
            ключ = ключ[:срез + 1] + пары[хеш]
            перенесено += 1
        if ключ in итог:
            слито += 1
            if номер(итог[ключ]) >= номер(значение):
                continue
        итог[ключ] = значение
    return итог, перенесено, слито


def главная(аргв):
    если_проверка = '--проверка' in аргв
    аргв = [а for а in аргв if а != '--проверка']
    if len(аргв) < 4:
        print(__doc__)
        return 1
    пулыДо, пулыПосле, журналФайл, выход = аргв[:4]
    пары = карта(строки(пулыДо), строки(пулыПосле))
    журнал = json.load(open(журналФайл, encoding='utf-8'))
    новый, перенесено, слито = перенести(журнал, пары)
    print('переписанных записей: %d' % len(пары))
    print('ключей журнала: %d → %d (перенесено %d, слито %d)'
          % (len(журнал), len(новый), перенесено, слито))
    if если_проверка:
        return 0
    with open(выход, 'w', encoding='utf-8') as ф:
        json.dump(новый, ф, ensure_ascii=False, separators=(',', ':'))
    return 0


if __name__ == '__main__':
    sys.exit(главная(sys.argv[1:]))
