<?php
declare(strict_types=1);
/**
 * Замер FAQ: из скольких записей пула собран ответ и держится ли он вопроса.
 *
 * ЗАЧЕМ. Ответ у нас короче донорского (медиана записи пула 33 слова против
 * корпусных 56), и генератор дотягивает длину, приклеивая предложение из
 * другой записи. Приёмка этого не видит: у неё поля «вопросительных знаков» и
 * «пар вопрос-ответ», а длина и предмет ответа в них не входят. Видит это
 * читатель — «вопрос про один, ответ про три».
 *
 * ЧТО СЧИТАЕТСЯ. Предложения ответа опознаются в пуле по скелету (без тегов,
 * цифр и слотов — подстановка их меняет), и для каждого ответа считается
 * наименьшее число записей, которым он покрывается. Запись-близнец по вопросу
 * (v5BliznetsVoprosa) склейкой не считается: это тот же вопрос другими
 * словами, и разворачивать его подробностью — норма.
 *
 * Запуск:
 *   php engine/instrumenty/zamer-faq.php samples/v5-final/nabor-782
 *   php engine/instrumenty/zamer-faq.php <папка> --показ
 *   php engine/instrumenty/zamer-faq.php <папка> --json
 */

require dirname(__DIR__) . '/src/V5Blocks.php';

$папка = $argv[1] ?? '';
$показ = in_array('--показ', $argv, true);
$какJson = in_array('--json', $argv, true);
if ($папка === '' || !is_dir($папка)) { fwrite(STDERR, "нужна папка набора\n"); exit(2); }

$пулы = json_decode((string) file_get_contents(dirname(__DIR__) . '/data-v5/pools.json'), true);
$хвосты = $пулы['хвосты'] ?? [];

$плоско = static function (string $s): string {
    $s = (string) preg_replace('~(?s)<(script|style)\b.*?</\1>~', ' ', $s);
    $s = (string) preg_replace('~<[^>]+>~', '', $s);
    return trim((string) preg_replace('~\s+~u', ' ', html_entity_decode($s, ENT_QUOTES | ENT_HTML5, 'UTF-8')));
};
/** Скелет предложения: подстановка слотов и цифр его меняет, тема — нет. */
$скелет = static function (string $s) use ($плоско): string {
    $s = mb_strtolower($плоско($s));
    $s = (string) preg_replace(['~\{[^}]*\}~u', '~%[a-z_]+%~', '~[\d.,]+~u'], ['#', '#', '#'], $s);
    return trim((string) preg_replace('~\s+~u', ' ', (string) preg_replace('~[^а-яёa-z#]~u', ' ', $s)));
};
// Опознаются предложения от восьми слов: короткая общая строка («Сравнить
// автоматы проще в обзоре слотов») стоит в десятках записей, и приписывать по
// ней ответ чужой записи — выдумывать склейку. Такие же отбрасываются ниже по
// числу записей, в которых встречаются.
$фразы = static function (string $s) use ($плоско): array {
    $в = [];
    foreach (preg_split('~(?<=[.!?])\s+~u', $плоско($s)) ?: [] as $ф) {
        if (count(preg_split('~\s+~u', trim($ф), -1, PREG_SPLIT_NO_EMPTY)) >= 8) { $в[] = $ф; }
    }
    return $в;
};

$итог = ['ответов' => 0, 'опознано' => 0, 'склеено' => 0, 'чужих' => 0,
         'записейМакс' => 0, 'слов' => [], 'предложений' => [], 'случаи' => []];

foreach (glob(rtrim($папка, '/') . '/*.html') ?: [] as $файл) {
    $тип = basename($файл, '.html');
    $faq = $хвосты[$тип]['faq'] ?? [];
    if (!$faq) { continue; }
    // Индекс: скелет предложения записи → номера записей.
    $индекс = [];
    foreach ($faq as $i => $x) {
        foreach ($фразы((string) ($x['о'] ?? '')) as $ф) {
            $к = $скелет($ф);
            if (mb_strlen($к) > 25) { $индекс[$к][$i] = true; }
            // (общие строки снимаются после сборки индекса)
        }
    }
    // Строка, живущая больше чем в трёх записях, — общая формула, а не улика.
    foreach ($индекс as $к => $кто) { if (count($кто) > 3) { unset($индекс[$к]); } }
    $html = (string) file_get_contents($файл);
    // Пара берётся внутри одного faq-item: иначе вопрос склеивается с чужим ответом.
    if (!preg_match_all('~<(div|article)\b[^>]*\bitemprop="mainEntity"[^>]*>(.*?)itemprop="text"[^>]*>(.*?)</div>~su',
                        $html, $блоки, PREG_SET_ORDER)) { continue; }
    foreach ($блоки as $б) {
        if (!preg_match('~itemprop="name"[^>]*>(.*?)</~su', $б[2], $мв)) { continue; }
        $вопрос = $плоско($мв[1]);
        $ответ = $плоско($б[3]);
        if ($вопрос === '' || $ответ === '') { continue; }
        $итог['ответов']++;
        $итог['слов'][] = count(preg_split('~\s+~u', $ответ, -1, PREG_SPLIT_NO_EMPTY));
        $ф = $фразы($ответ);
        $итог['предложений'][] = count($ф);
        $наборы = [];
        foreach ($ф as $x) {
            $к = $скелет($x);
            if (isset($индекс[$к])) { $наборы[] = array_keys($индекс[$к]); }
        }
        if (!$наборы) { continue; }
        $итог['опознано']++;
        // Наименьшее покрытие: жадно берём запись, покрывающую больше всего предложений.
        $осталось = $наборы; $выбрано = [];
        while ($осталось) {
            $счёт = [];
            foreach ($осталось as $s) { foreach ($s as $i) { $счёт[$i] = ($счёт[$i] ?? 0) + 1; } }
            arsort($счёт);
            $луч = (int) array_key_first($счёт);
            $выбрано[] = $луч;
            $осталось = array_values(array_filter($осталось, static fn(array $s): bool => !in_array($луч, $s, true)));
        }
        $итог['записейМакс'] = max($итог['записейМакс'], count($выбрано));
        if (count($выбрано) < 2) { continue; }
        $итог['склеено']++;
        // Чужая запись — не близнец по вопросу.
        $чужие = [];
        foreach (array_slice($выбрано, 1) as $i) {
            $вд = (string) ($faq[$i]['в'] ?? '');
            if (!v5BliznetsVoprosa($вопрос, $вд)) { $чужие[] = $плоско($вд); }
        }
        if ($чужие) {
            $итог['чужих']++;
            if (count($итог['случаи']) < 20) {
                $итог['случаи'][] = ['тип' => $тип, 'вопрос' => $вопрос, 'чужие' => $чужие,
                                     'ответ' => mb_substr($ответ, 0, 300)];
            }
        }
    }
}

$медиана = static function (array $x): float {
    if (!$x) { return 0.0; }
    sort($x); $n = count($x);
    return $n % 2 ? (float) $x[intdiv($n, 2)] : ($x[$n / 2 - 1] + $x[$n / 2]) / 2;
};
$свод = [
    'набор' => basename(rtrim($папка, '/')),
    'ответов' => $итог['ответов'], 'опознано' => $итог['опознано'],
    'склеено' => $итог['склеено'], 'чужих' => $итог['чужих'],
    'записейМакс' => $итог['записейМакс'],
    'слов' => $медиана($итог['слов']), 'предложений' => $медиана($итог['предложений']),
];
if ($какJson) { echo json_encode($свод, JSON_UNESCAPED_UNICODE), "\n"; exit(0); }
printf("%-16s ответов %3d (опознано %3d)  склеено %3d  из них с чужим вопросом %3d  записей до %d  слов %3.0f  предложений %2.0f\n",
    $свод['набор'], $свод['ответов'], $свод['опознано'], $свод['склеено'], $свод['чужих'],
    $свод['записейМакс'], $свод['слов'], $свод['предложений']);
if ($показ) {
    foreach ($итог['случаи'] as $с) {
        printf("\n[%s] В: %s\n", $с['тип'], $с['вопрос']);
        foreach ($с['чужие'] as $ч) { printf("   чужой вопрос: %s\n", $ч); }
        printf("   ответ: %s\n", $с['ответ']);
    }
}
