ДОЛЯ = 4          # каждое третье вхождение уходит в вариант
путь = 'engine/data-v5/pools.json'
s = open(путь, encoding='utf-8').read()
счёт = collections.Counter()
заменено = collections.Counter()

def замена(m):
    адрес, текст = m.group(1), m.group(2)
    низ = текст.strip().lower()
    сп = ВАРИАНТЫ.get(низ)
    if not сп:
        return m.group(0)
    счёт[низ] += 1
    if счёт[низ] % ДОЛЯ != 0:
        return m.group(0)
    новый = сп[(счёт[низ] // ДОЛЯ - 1) % len(сп)]
    if текст[0].isupper():
        новый = новый[0].upper() + новый[1:]
    заменено[низ] += 1
    return '<a href=\\"%s\\">%s</a>' % (адрес, новый)

новый = re.sub(r'<a href=\\"([^"\\]+)\\"[^>]*>([^<]{1,60})</a>', замена, s)
json.loads(новый)   # проверка целости
if len(sys.argv) > 1 and sys.argv[1] == '--писать':
    open(путь, 'w', encoding='utf-8').write(новый)
    print('записано')
print('заменено вхождений:', sum(заменено.values()))
for k, n in заменено.most_common(12):
    print('  %-24s %4d из %d' % (k, n, счёт[k]))
