<?php
/**
 * Полосы приёмки по корпусу из ста наборов.
 *
 * Профиль строится по двенадцати донорам, и на многих полях их население
 * заметно уже корпуса из ста: разовых анкоров у доноров 33 % медианой против
 * 78 у NEW100, разброс длин абзаца ограничен 20–24 против 24–58. Этот
 * инструмент считает дециль p10–p90 по каждому полю и типу на NEW100 и
 * сравнивает с профильной полосой.
 *
 * Поля, где NEW100 не мерится (значение нулевое больше чем у половины
 * страниц либо полоса вырождена в точку), остаются на профильной полосе:
 * метрика на чужой разметке не считается, и подменять ею профиль нельзя.
 *
 *   php engine/instrumenty/polosy-new100.php [--json=файл]
 */
require_once __DIR__ . '/../src/PageMetrics.php';
$КОРПУС = '/home/user/cladue/samples/v5-konkurent/NEW100';
$ТИПЫ = ['main','obzor','slots','bonus','promo','registracia','vhod','zerkalo','app','news','partnery','info'];
$вJson = null;
foreach (array_slice($argv, 1) as $a) {
    if (str_starts_with($a, '--json=')) { $вJson = substr($a, 7); }
}
$профиль = json_decode((string) file_get_contents(__DIR__ . '/../data-v5/profil-v5.json'), true);
$дец = function (array $v, float $q) { sort($v); $n = count($v);
    $i = ($n - 1) * $q; $l = (int) floor($i); $h = (int) ceil($i);
    return $l == $h ? (float) $v[$l] : $v[$l] + ($v[$h] - $v[$l]) * ($i - $l); };

$собрано = [];
foreach (scandir($КОРПУС) as $н) {
    if ($н[0] === '.' || !is_dir("$КОРПУС/$н")) { continue; }
    foreach ($ТИПЫ as $т) {
        $f = "$КОРПУС/$н/$т.html"; if (!is_file($f)) { continue; }
        $raw = (string) file_get_contents($f);
        $a = new Analyzer($raw);
        $м = PageMetrics::measure($a, $т, $raw, ['ru' => '%brand_name_ru%', 'en' => '%brand_name_en%']);
        foreach ($м as $k => $v) { if (is_numeric($v)) { $собрано[$т][$k][] = (float) $v; } }
    }
}

$полосы = []; $шире = 0; $уже = 0; $сдвиг = 0; $отброшено = []; $расхождения = [];
foreach ($ТИПЫ as $т) {
    foreach ($собрано[$т] ?? [] as $поле => $v) {
        $п = $профиль['страницы'][$т]['поля'][$поле] ?? null;
        if (!$п || empty($п['держат']) || !isset($п['полоса'])) { continue; }
        if (count($v) < 60) { $отброшено[$поле] = 'мало страниц'; continue; }
        $нулей = count(array_filter($v, fn($x) => $x == 0.0)) / count($v);
        if ($нулей > 0.5) { $отброшено[$поле] = 'нули у большинства'; continue; }
        [$низ, $верх] = [$дец($v, 0.10), $дец($v, 0.90)];
        if ($верх - $низ < 1e-9) { $отброшено[$поле] = 'полоса в точку'; continue; }
        [$пн, $пв] = [(float) $п['полоса'][0], (float) $п['полоса'][1]];
        $ширН = $верх - $низ; $ширП = $пв - $пн;
        if ($ширН > $ширП * 1.15) { $шире++; } elseif ($ширН < $ширП * 0.85) { $уже++; } else { $сдвиг++; }
        // Берём полосу NEW100 только там, где корпуса расходятся о середине:
        // профильная полоса не содержит медиану NEW100. Это те поля, где верный
        // для корпуса из ста наборов вывод обязан провалить профиль. Там, где
        // медиана внутри профильной полосы, спор идёт о ширине, а не о норме,
        // и подменять профиль незачем — иначе приёмка просто слабеет.
        $мед = $дец($v, 0.50);
        if ($мед >= $пн && $мед <= $пв) { continue; }
        $полосы[$поле][$т] = [round($низ, 1), round($верх, 1)];
        $расхождения[$поле][$т] = sprintf('медиана %.1f вне профиля %.1f–%.1f', $мед, $пн, $пв);
    }
}
printf("полей·типов с полосой NEW100: %d   шире профиля %d, уже профиля %d, той же ширины %d\n",
    array_sum(array_map('count', $полосы)), $шире, $уже, $сдвиг);
printf("полей отброшено: %d\n", count($отброшено));
printf("\nрасхождение о середине — полоса NEW100 ставится здесь:\n");
foreach ($расхождения as $поле => $типы) {
    printf("  %-18s %d типов: %s\n", $поле, count($типы),
        implode(', ', array_map(fn($т) => $т . ' ' . implode('–', $полосы[$поле][$т]), array_keys($типы))));
}
if ($вJson) {
    file_put_contents($вJson, json_encode($полосы, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE));
    printf("записано: %s\n", $вJson);
}
