<?php
/**
 * Максимальное сравнение набора с корпусом: каждое числовое поле PageMetrics
 * на каждом из двенадцати типов против своей манеры корпуса NEW100.
 *
 * Приёмка судит набор по профильным полосам и целям, а они сняты с двенадцати
 * доноров и подправлены по корпусу лишь там, где корпуса расходятся о середине
 * (см. polosy-new100.php). Это сравнение не судит, а показывает: где мы стоим
 * относительно самого корпуса, поле за полем, без отбора полей.
 *
 * Манера корпуса делится тем же правилом, что даёт полосы приёмки, — медиана
 * бренд-переменных на страницу больше восьми. Сравнивать густой набор с
 * обычными страницами корпуса бессмысленно: это другой формат.
 *
 *   php engine/instrumenty/sravnenie-maksimum.php samples/v5-final/nabor-751 [--json=f] [--манера=густая]
 */
require_once __DIR__ . '/../src/PageMetrics.php';

$КОРПУС = __DIR__ . '/../../samples/v5-konkurent/NEW100';
$ТИПЫ = ['main','obzor','slots','bonus','promo','registracia','vhod','zerkalo','app','news','partnery','info'];

$позиц = array_values(array_filter(array_slice($argv, 1), fn($a) => $a[0] !== '-'));
$наш = rtrim($позиц[0] ?? '', '/');
if (!is_dir($наш)) { fwrite(STDERR, "нет папки набора\n"); exit(1); }
$вJson = null; $манераАрг = null;
foreach (array_slice($argv, 1) as $a) {
    if (str_starts_with($a, '--json=')) { $вJson = substr($a, 7); }
    if (str_starts_with($a, '--манера=')) { $манераАрг = substr($a, strlen('--манера=')); }
}

$дец = function (array $v, float $q): float {
    sort($v); $n = count($v); $i = ($n - 1) * $q;
    $l = (int) floor($i); $h = (int) ceil($i);
    return $l === $h ? (float) $v[$l] : $v[$l] + ($v[$h] - $v[$l]) * ($i - $l);
};
$медиана = fn(array $v): float => $дец($v, 0.5);

/** Бренд-переменных на страницу: по нему корпус делится на манеры. */
$брендНаСтраницу = function (string $папка) use ($ТИПЫ): array {
    $из = [];
    foreach ($ТИПЫ as $т) {
        $f = "$папка/$т.html";
        if (!is_file($f)) { continue; }
        $s = preg_replace('~<(script|style)\b.*?</\1>~is', ' ', (string) file_get_contents($f));
        $из[] = preg_match_all('~%brand_name_(?:ru|en)%~u', (string) $s);
    }
    return $из;
};

// Манера нашего набора: из паспорта, если он есть, иначе по тому же правилу.
$манера = $манераАрг;
if ($манера === null) {
    $п = @json_decode((string) @file_get_contents("$наш/nabor.json"), true);
    if (isset($п['густой'])) { $манера = $п['густой'] ? 'густая' : 'обычная'; }
}
if ($манера === null) {
    $бр = $брендНаСтраницу($наш);
    $манера = ($бр && $медиана($бр) > 8) ? 'густая' : 'обычная';
}

$группа = [];
foreach (scandir($КОРПУС) as $н) {
    if ($н[0] === '.' || !is_dir("$КОРПУС/$н")) { continue; }
    $бр = $брендНаСтраницу("$КОРПУС/$н");
    if (!$бр) { continue; }
    $м = ($медиана($бр) > 8) ? 'густая' : 'обычная';
    if ($м === $манера) { $группа[] = "$КОРПУС/$н"; }
}

$мерить = function (string $папка, string $т) {
    $f = "$папка/$т.html";
    if (!is_file($f)) { return null; }
    $raw = (string) file_get_contents($f);
    return PageMetrics::measure(new Analyzer($raw), $т, $raw,
        ['ru' => '%brand_name_ru%', 'en' => '%brand_name_en%']);
};

$корпус = [];
foreach ($группа as $d) {
    foreach ($ТИПЫ as $т) {
        $м = $мерить($d, $т);
        if (!$м) { continue; }
        foreach ($м as $k => $v) { if (is_numeric($v)) { $корпус[$т][$k][] = (float) $v; } }
    }
}

printf("набор: %s, манера %s\n", basename($наш), $манера);
printf("корпус NEW100: %d наборов той же манеры из 100\n\n", count($группа));

$итог = []; $сводка = []; $точкой = [];
foreach ($ТИПЫ as $т) {
    $наше = $мерить($наш, $т);
    if (!$наше) { continue; }
    $внутри = 0; $всего = 0; $вне = [];
    foreach ($наше as $k => $v) {
        if (!is_numeric($v) || !isset($корпус[$т][$k]) || count($корпус[$т][$k]) < 10) { continue; }
        $ст = $корпус[$т][$k];
        $низ = $дец($ст, 0.1); $верх = $дец($ст, 0.9); $мед = $медиана($ст);
        $v = (float) $v;
        // Полоса, вырожденная в точку: у восьми десятых корпуса поле стоит на
        // одном значении (чаще нуле — таблиц и первого лица у них нет вовсе).
        // Делить на такую ширину нельзя: отклонение уходило в 1e11 и забивало
        // список худших. Такие поля идут отдельным списком «корпус на одном
        // значении»: там важно не «на сколько полос», а «мы не ноль, а они ноль».
        if ($верх - $низ < 1e-9) {
            if (abs($v - $мед) > 1e-9) { $точкой[$т][$k] = [round($v, 2), round($мед, 2)]; }
            continue;
        }
        // Насколько вне полосы — в ширинах самой полосы: иначе «мимо на 3»
        // читается одинаково для terms_total и для lists.
        $ш = $верх - $низ;
        $откл = $v < $низ ? ($низ - $v) / $ш : ($v > $верх ? ($v - $верх) / $ш : 0.0);
        $всего++; if ($откл == 0.0) { $внутри++; } else { $вне[$k] = $откл; }
        $итог[$т][$k] = ['наше' => round($v, 2), 'медиана' => round($мед, 2),
                         'низ' => round($низ, 2), 'верх' => round($верх, 2),
                         'откл_полос' => round($откл, 2)];
    }
    arsort($вне);
    $сводка[$т] = ['полей' => $всего, 'внутри' => $внутри,
                   'доля' => $всего ? round($внутри / $всего * 100, 1) : 0.0,
                   'худшие' => array_slice($вне, 0, 5, true)];
}

printf("%-12s %7s %8s %7s  %s\n", 'тип', 'полей', 'внутри', 'доля', 'худшие отклонения (в ширинах полосы)');
$всегоП = 0; $всегоВ = 0;
foreach ($сводка as $т => $с) {
    $всегоП += $с['полей']; $всегоВ += $с['внутри'];
    $х = [];
    foreach ($с['худшие'] as $k => $o) { $х[] = sprintf('%s %.1f', $k, $o); }
    printf("%-12s %7d %8d %6.1f%%  %s\n", $т, $с['полей'], $с['внутри'], $с['доля'], implode(', ', $х));
}
printf("%-12s %7d %8d %6.1f%%\n", 'ВСЕГО', $всегоП, $всегоВ, $всегоП ? $всегоВ / $всегоП * 100 : 0);

// Поля, которые мажут на многих типах: это про движок, а не про страницу.
$поТипам = [];
foreach ($итог as $т => $поля) {
    foreach ($поля as $k => $z) { if ($z['откл_полос'] > 0) { $поТипам[$k][] = $т; } }
}
uasort($поТипам, fn($a, $b) => count($b) <=> count($a));
printf("\nполя вне полосы на трёх и более типах:\n");
foreach ($поТипам as $k => $типы) {
    if (count($типы) < 3) { continue; }
    printf("  %-18s %2d типов: %s\n", $k, count($типы), implode(', ', $типы));
}

// Поля, где корпус стоит на одном значении, а мы — нет.
if ($точкой) {
    printf("\nкорпус на одном значении, а у нас иначе (наше / их):\n");
    $св = [];
    foreach ($точкой as $т => $поля) { foreach ($поля as $k => $z) { $св[$k][$т] = $z; } }
    uasort($св, fn($a, $b) => count($b) <=> count($a));
    foreach ($св as $k => $типы) {
        $ч = [];
        foreach ($типы as $т => $z) { $ч[] = sprintf('%s %s/%s', $т, $z[0], $z[1]); }
        printf("  %-18s %2d типов: %s\n", $k, count($типы), implode(', ', $ч));
    }
}

if ($вJson) {
    file_put_contents($вJson, json_encode(['набор' => basename($наш), 'манера' => $манера,
        'наборов_корпуса' => count($группа), 'поля' => $итог, 'сводка' => $сводка,
        'точкой' => $точкой],
        JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE));
    printf("\nзаписано: %s\n", $вJson);
}
