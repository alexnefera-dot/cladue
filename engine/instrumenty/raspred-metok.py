# -*- coding: utf-8 -*-
"""Распределение доли тематических меток по наборам: медиана, децили, вёдра по
десять процентов и размах внутри каждой манеры.

Среднее тут не решает ничего: корпусное распределение — ванна, а не горб, и две
раскладки с одинаковым средним могут лежать в разных вёдрах. Корпусная строка —
99 наборов NEW100, пересчитанные на 24 (docs/tematicheskie-metki.md).
"""
import json, sys, statistics as st

# Вёдра корпуса даны на 24 набора; на выборке другого размера их надо
# пересчитывать, иначе строка корпуса врёт — на 48 наборах она показывала
# половинные счёта и «сходство» читалось вдвое хуже настоящего.
КОРПУС = (17.0, 5.5, 67.9, 29.2, [9, 3, 2, 2, 1, 2, 3, 1, 1])
КОРПУС_НАБОРОВ = 24

def манера(н):
    ж = (н * 618033988) % 1000000000 // 10000000
    return 'скудная' if ж < 39 else ('обычная' if ж < 61 else 'густая')

def читать(ф):
    d = {}
    for с in open(ф, encoding='utf-8'):
        r = json.loads(с)
        d[r['сид']] = r
    return d

def дец(з, q):
    з = sorted(з)
    i = q * (len(з) - 1)
    н = int(i)
    return з[н] if н + 1 >= len(з) else з[н] + (з[н + 1] - з[н]) * (i - н)

плечи = [(имя, читать(ф)) for имя, ф in zip(sys.argv[1::2], sys.argv[2::2])]
общие = sorted(set.intersection(*[set(d) for _, d in плечи]))

def строка(имя, мед, н, в, ср, вёдра):
    print('%-14s мед %5.1f дец %5.1f–%-5.1f сред %5.1f |' % (имя, мед, н, в, ср)
          + ''.join('%4.0f' % к for к in вёдра))

print('парных сидов: %d\n' % len(общие))
print('%-14s %-9s %-17s %-9s |' % ('', 'медиана', 'дециль 10–90', 'среднее')
      + ''.join('%3d' % (10 * i) for i in range(9)))
к = len(общие) / КОРПУС_НАБОРОВ
строка('корпус→%d' % len(общие), КОРПУС[0], КОРПУС[1], КОРПУС[2], КОРПУС[3],
       [x * к for x in КОРПУС[4]])

for имя, d in плечи:
    доли, поМанере = [], {}
    for с in общие:
        r = d[с]
        п = r['пер']
        доля = 100.0 * п['темат'] / max(1, п['пунктов'])
        доли.append(доля)
        поМанере.setdefault(манера(int(r['имя'].split('-')[1])), []).append(доля)
    вёдра = [0] * 9
    for x in доли:
        вёдра[min(8, int(x // 10))] += 1
    строка(имя, st.median(доли), дец(доли, 0.1), дец(доли, 0.9), st.mean(доли), вёдра)
    print('%-14s ' % '' + '   '.join('%s %4.1f–%-4.1f (%d)' % (м, min(v), max(v), len(v))
                                     for м, v in sorted(поМанере.items())))
    низ = sum(1 for x in доли if x < 10)
    сер = sum(1 for x in доли if 10 <= x < 30)
    вер = len(доли) - низ - сер
    print('%-14s полосы: ниже 10 %% — %d %%, 10–29 %% — %d %%, выше 30 %% — %d %% (корпус 39 / 21 / 39)\n'
          % ('', round(100 * низ / len(доли)), round(100 * сер / len(доли)), round(100 * вер / len(доли))))
