<?php
declare(strict_types=1);

/**
 * Библиотека блоков и пулы текста поколения v5.
 *
 *   php engine/bloki-v5.php [папка] [--отчёт]
 *
 * Корпус v5 — не проза, а конструктор: двенадцать наборов собраны одной
 * фабрикой по одной грамматике. Страница любого типа читается так:
 *
 *     [головные виджеты] ( H2 · 2–3 <p> · H3 · <ul> · <p> )×N [хвостовые виджеты]
 *
 * Что здесь важно и чего не видно в отдельной странице:
 *
 *  · **H2 — закрытый список.** 123 заголовка главной на двенадцать наборов дают
 *    13 разных формулировок, у внутренних типов 6–13. То есть раздел — не
 *    свободная тема, а позиция в меню фабрики. Поэтому пулы прозы режутся не
 *    по типу страницы, а по разделу: абзацы, H3 и пункты хранятся под своим H2.
 *    Иначе генератор смешает рассказ про турниры с разделом про лицензию.
 *  · **Проза действительно переписана.** Из 415 абзацев главной разных 275 —
 *    фабрика гоняет реалайзер на каждый набор, а не тасует готовые куски.
 *  · **Числа и герои — прорези.** «RTP 96.4%», «выиграл 180к», «Роман зашёл» —
 *    это подстановки: у одного набора Роман и 180к, у другого Виктор и 195к.
 *    Поэтому текст кладётся в пул трафаретом: `{ИМЯ}`, `{СУММА}`, `{RTP}`,
 *    `{ПРОЦ}`, `{МИН}`, `{БАНК}`, `{СЛОТОВ}`, `{ПРОВАЙДЕРОВ}`, `{ВЕЙДЖЕР}`.
 *    Банки наблюдённых значений лежат рядом, в `общие`.
 *  · **Ростер слотов один на весь корпус:** двенадцать игр, у каждой свои
 *    провайдер, иконка и RTP, одинаковые у всех доноров. Это не прорезь.
 *
 * Выкладка:
 *  · `data-v5/bloki.json` — виджеты по (тип, класс, вариант) и скелеты страниц;
 *  · `data-v5/pools.json` — разделы по типам с трафаретами прозы и общие банки.
 */

require_once __DIR__ . '/src/V5Blocks.php';

/**
 * Абзац кладётся в пул дважды: целиком — чтобы знать плотность (сколько абзацев
 * в разделе и сколько в них фраз), и по предложениям — из них собирается наш.
 */
function v5AbzacVPul(array &$раздел, string $вид, string $шаблон, string $донор): void
{
    $раздел[$вид][] = ['т' => $шаблон, 'д' => $донор];
    $фразы = v5Predlozheniya($шаблон);
    $раздел[$вид . 'Длины'][] = count($фразы);
    foreach ($фразы as $i => $ф) {
        $раздел[$вид . 'Фразы'][] = ['т' => $ф, 'д' => $донор, 'п' => $i === 0 ? 1 : 0];
    }
}

$отчёт = in_array('--отчёт', $argv, true);
$позиц = array_values(array_filter(array_slice($argv, 1), fn($a) => $a[0] !== '-'));
$root  = rtrim($позиц[0] ?? 'samples/v5-donors', '/');
$данные = __DIR__ . '/data-v5';
foreach (array_slice($argv, 1) as $a) {
    if (str_starts_with($a, '--данные=')) { $данные = rtrim(substr($a, strlen('--данные=')), '/'); }
}
if (!is_dir($root)) { fwrite(STDERR, "нет папки $root\n"); exit(1); }

$sites = [];
foreach (glob("$root/*", GLOB_ONLYDIR) ?: [] as $d) { $sites[] = basename($d); }
sort($sites);
// Близнец из профиля выкидывается и здесь: его текст совпадает с исходником
// дословно, и в пуле он удваивает вес пары — генератор потом сползает на неё.
$профильФайл = "$данные/profil-v5.json";
if (is_file($профильФайл)) {
    $п = json_decode((string) file_get_contents($профильФайл), true);
    $исключены = $п['источник']['исключены'] ?? [];
    if ($исключены) {
        $sites = array_values(array_diff($sites, $исключены));
        fwrite(STDERR, 'близнецы исключены: ' . implode(', ', $исключены) . "\n");
    }
}

$блоки   = [];  // тип => класс => вариант => [html…]
$тексты  = [];  // тип => класс => роль => [{т,д}…]
$скелет  = [];  // тип => подпись => счёт
$разделы = [];  // тип => H2-трафарет => данные раздела
$хвосты  = [];  // тип => вид => пары
$банки   = [];  // прорезь => значение => счёт
$анкоры  = [];  // адрес => метка => счёт
$слоты   = [];  // имя => карточка
$эмодзи  = [];

foreach ($sites as $s) {
    foreach (V5_TYPES as $t) {
        $f = "$root/$s/$t.html";
        if (!is_file($f)) { continue; }
        $html = (string) file_get_contents($f);
        $uzly = v5Uzly($html);

        $проза = fn(array $u) => $u['класс'] === '' && in_array($u['тег'], ['h2', 'h3', 'p', 'ul', 'ol'], true);
        $первый = null; $последний = null;
        foreach ($uzly as $i => $u) {
            if ($u['тег'] === 'h2' && $u['класс'] === '' && $первый === null) { $первый = $i; }
            if ($проза($u)) { $последний = $i; }
        }
        $голова = $первый === null ? [] : array_slice($uzly, 0, $первый);
        $хвост  = $последний === null ? $uzly : array_slice($uzly, $последний + 1);
        $тело   = $первый === null ? [] : array_slice($uzly, $первый, $последний - $первый + 1);

        $h2Счёт = count(array_filter($тело, fn($u) => $u['тег'] === 'h2'));
        $подпись = implode(' + ', array_map('v5Klass', $голова)) . " | H2×{$h2Счёт} | "
                 . implode(' + ', array_map('v5Klass', $хвост));
        $скелет[$t][$подпись] = ($скелет[$t][$подпись] ?? 0) + 1;

        foreach (array_merge($голова, $хвост) as $u) {
            if ($проза($u)) { continue; }
            $k = v5Klass($u);
            // Пустая оболочка вида «<div class="info-block"></div>» встречается
            // у доноров и уносится в библиотеку наравне с наполненными: при
            // выборе она даёт на странице пустую дырку.
            if (mb_strlen(trim(strip_tags($u['html']))) < 5) { continue; }
            $блоки[$t][$k][v5Variant($u)][md5($u['html'])] = $u['html'];
            // Текст виджета уходит в пул по ролям — разметка общая, слова свои.
            $строки = explode("\n", $u['html']);
            foreach (v5Sloty($u['html']) as $слот) {
                if (in_array($слот['роль'], V5_ROLI_PAROJ, true)) { continue; }
                $знач = trim($строки[$слот['строка']]);
                if ($знач === '') { continue; }
                $тексты[$t][$k][$слот['роль']][md5($знач)] = ['т' => v5Trafaret($знач, $банки), 'д' => $s];
            }
        }

        // ── тело разбирается по разделам: H2 открывает, следующий H2 закрывает
        $текущий = null; $былH3 = false; $номер = 0;
        foreach ($тело as $u) {
            $вн = v5Vnutr($u['html']);
            if ($вн === '') { continue; }
            if ($u['тег'] === 'h2') {
                $текущий = v5Trafaret($вн, $банки);
                $былH3 = false;
                $разделы[$t][$текущий]['встреч'] = ($разделы[$t][$текущий]['встреч'] ?? 0) + 1;
                $разделы[$t][$текущий]['доноры'][$s] = 1;
                $разделы[$t][$текущий]['позиции'][] = $номер++;
                continue;
            }
            if ($текущий === null) { continue; }
            $шаб = v5Trafaret($вн, $банки);
            match ($u['тег']) {
                'h3' => [$разделы[$t][$текущий]['h3'][] = ['т' => $шаб, 'д' => $s], $былH3 = true],
                'p'  => v5AbzacVPul($разделы[$t][$текущий], $былH3 ? 'финал' : 'зачин', $шаб, $s),
                'ul', 'ol' => array_map(
                    function ($li) use (&$разделы, $t, $текущий, $s, &$банки) {
                        $разделы[$t][$текущий]['пункты'][] = [
                            'т' => v5Trafaret(trim(preg_replace('~\s*\n\s*~u', ' ', $li)), $банки), 'д' => $s];
                    },
                    preg_match_all('~<li[^>]*>(.*?)</li>~s', $u['html'], $m) ? $m[1] : []
                ),
                default => null,
            };
        }

        // ── пары FAQ и раскрывашки тематических блоков
        // Регулярка привязана к самому блоку faq-item, а не к первому попавшемуся
        // `itemprop="name"`: у карточки слота имя тоже лежит в <h3 itemprop="name">,
        // и без привязки в пул пар затягивало обрывки витрины вместо вопросов.
        if (preg_match_all('~<h3 class="faq-question" itemprop="name">\s*(.*?)\s*</h3>\s*'
            . '<div class="faq-answer"[^>]*>\s*<div itemprop="text">\s*(.*?)\s*</div>~s',
            $html, $m, PREG_SET_ORDER)) {
            foreach ($m as $x) {
                $в = v5Trafaret(trim(preg_replace('~\s+~u', ' ', $x[1])), $банки);
                // Половина доноров заворачивает ответ в <p>, половина пишет голым
                // текстом. В пуле хранится голый: обёртку ставит тот виджет, в
                // который пара встанет, иначе в одном блоке будет два стиля.
                $о = trim(preg_replace('~\s*\n\s*~u', ' ', $x[2]));
                $о = preg_replace('~^<p>\s*(.*?)\s*</p>$~s', '$1', $о);
                $о = v5Trafaret($о, $банки);
                $хвосты[$t]['faq'][md5($в . $о)] = ['в' => $в, 'о' => $о, 'д' => $s];
            }
        }
        if (preg_match_all('~<button class="faq-question"[^>]*>\s*<span>\s*(.*?)\s*</span>.*?<p class="review-quote-text">\s*(.*?)\s*</p>~s', $html, $m, PREG_SET_ORDER)) {
            foreach ($m as $x) {
                $в = v5Trafaret(trim(preg_replace('~\s+~u', ' ', $x[1])), $банки);
                $о = v5Trafaret(trim(preg_replace('~\s*\n\s*~u', ' ', $x[2])), $банки);
                $хвосты[$t]['раскрывашки'][md5($в . $о)] = ['в' => $в, 'о' => $о, 'д' => $s];
            }
        }

        // ── ростер слотов, анкоры, эмодзи
        if (preg_match_all('~<span class="slot-fallback-icon">\s*(\S+)\s*</span>.*?'
            . '<h3 class="slot-name" itemprop="name">\s*(.*?)\s*</h3>.*?'
            . '<div class="slot-provider" itemprop="gameProvider">\s*(.*?)\s*</div>.*?'
            . '<span class="slot-rtp-value"[^>]*>\s*([\d.]+)%~s', $html, $m, PREG_SET_ORDER)) {
            foreach ($m as $x) {
                $слоты[$x[2]] = ['иконка' => $x[1], 'провайдер' => $x[3], 'rtp' => $x[4],
                                 'встреч' => ($слоты[$x[2]]['встреч'] ?? 0) + 1];
            }
        }
        if (preg_match_all('~<a href="(/[^"#]*)"[^>]*>\s*(.*?)\s*</a>~s', $html, $m, PREG_SET_ORDER)) {
            foreach ($m as $x) {
                $метка = trim(preg_replace('~\s+~u', ' ', strip_tags($x[2])));
                if ($метка === '' || mb_strlen($метка) > 40) { continue; }
                $анкоры[$x[1]][$метка] = ($анкоры[$x[1]][$метка] ?? 0) + 1;
            }
        }
        if (preg_match_all('~[\x{1F300}-\x{1FAFF}\x{2190}-\x{27BF}\x{2B00}-\x{2BFF}]~u', v5Text($html), $m)) {
            foreach ($m[0] as $x) { $эмодзи[$x] = ($эмодзи[$x] ?? 0) + 1; }
        }
    }
}

// ── свод ────────────────────────────────────────────────────────────
foreach ($разделы as $t => &$rs) {
    foreach ($rs as &$r) {
        $r['доноры'] = array_keys($r['доноры'] ?? []);
        foreach (['зачин', 'h3', 'пункты', 'финал', 'зачинФразы', 'финалФразы'] as $вид) {
            if (!isset($r[$вид])) { $r[$вид] = []; continue; }
            $уник = [];
            foreach ($r[$вид] as $x) { $уник[md5($x['т'])] = $x; }
            $r[$вид] = array_values($уник);
        }
    }
    unset($r);
    uasort($rs, fn($x, $y) => $y['встреч'] <=> $x['встреч']);
}
unset($rs);
foreach ($хвосты as &$в) { foreach ($в as &$сп) { $сп = array_values($сп); } unset($сп); }
unset($в);

// ── ручное дополнение хвостов ────────────────────────────────────────
// Корпус закрывает прозу, но не короткие пары: раскрывашек у него четыре на
// тип и все четыре от одного донора, а пар «вопрос-ответ» 34–52 при семи
// парах на страницу. К восьмому десятку наборов пул отработан по многу раз,
// и уникальность добирается руками. Дополнение лежит отдельным файлом,
// чтобы пересборка из доноров его не затирала, и метится донором «наш» —
// в любом разборе видно, что пришло из корпуса, а что дописано.
$допСчёт = [];
foreach (glob("$данные/dop*-v5.php") ?: [] as $допФайл) {
    /** @var array<string, array<string, list<array{в:string,о:string}>>> $доп */
    $доп = require $допФайл;
    foreach ($доп as $вид => $поТипам) {
        foreach ($поТипам as $t => $пары) {
            if (!in_array($t, V5_TYPES, true)) {
                fwrite(STDERR, "дополнение: неизвестный тип «$t», пропущен\n");
                continue;
            }
            $былоКлючей = [];
            foreach ($хвосты[$t][$вид] ?? [] as $x) { $былоКлючей[md5($x['в'] . $x['о'])] = 1; }
            foreach ($пары as $п) {
                $ключ = md5($п['в'] . $п['о']);
                if (isset($былоКлючей[$ключ])) { continue; }   // дубль корпуса не удваиваем
                $былоКлючей[$ключ] = 1;
                $хвосты[$t][$вид][] = ['в' => $п['в'], 'о' => $п['о'], 'д' => 'наш'];
                $допСчёт[$вид] = ($допСчёт[$вид] ?? 0) + 1;
            }
        }
    }
}
// ── проза из чужого корпуса ──────────────────────────────────────────
// Собирается отдельно (`sbor-new33.php`) и кладётся только в те разделы, что
// уже есть у доноров: раскладка страницы остаётся корпусной, шире становится
// лишь выбор фраз. Каждая запись помечена своим комплектом-источником, чтобы
// балансировка в генераторе видела их как отдельные доноры, а не как один
// огромный. Разделы, которых у нас нет, сбор отбрасывает сам.
$прозаСчёт = [];
foreach (glob("$данные/proza*-v5.php") ?: [] as $прозаФайл) {
    /** @var array<string, array<string, array<string, list<array{т:string,д:string,п?:int}>>>> $проза */
    $проза = require $прозаФайл;
    foreach ($проза as $t => $поРазделам) {
        if (!in_array($t, V5_TYPES, true)) {
            fwrite(STDERR, "проза: неизвестный тип «$t», пропущен\n");
            continue;
        }
        foreach ($поРазделам as $ключ => $виды) {
            if (!isset($разделы[$t][$ключ])) { continue; }   // раздела нет у доноров — не заводим
            foreach ($виды as $вид => $список) {
                $былоКлючей = [];
                foreach ($разделы[$t][$ключ][$вид] ?? [] as $x) { $былоКлючей[md5($x['т'])] = 1; }
                foreach ($список as $x) {
                    $ключФразы = md5($x['т']);
                    if (isset($былоКлючей[$ключФразы])) { continue; }
                    $былоКлючей[$ключФразы] = 1;
                    $разделы[$t][$ключ][$вид][] = $x;
                    $прозаСчёт[$вид] = ($прозаСчёт[$вид] ?? 0) + 1;
                }
            }
        }
    }
}

foreach ($банки as &$б) { arsort($б); }
unset($б);
foreach ($анкоры as &$а) { arsort($а); }
unset($а);
uasort($слоты, fn($x, $y) => $y['встреч'] <=> $x['встреч']);
arsort($эмодзи);

$текстыВыкладка = [];
foreach ($тексты as $t => $ks) {
    foreach ($ks as $k => $роли) { foreach ($роли as $р => $сп) { $текстыВыкладка[$t][$k][$р] = array_values($сп); } }
}
$выкладкаБлоков = [];
foreach ($блоки as $t => $ks) {
    foreach ($ks as $k => $vs) { foreach ($vs as $v => $h) { $выкладкаБлоков[$t][$k][$v] = array_values($h); } }
}

if (!is_dir($данные)) { mkdir($данные, 0777, true); }
$опции = JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES;
file_put_contents("$данные/bloki.json", json_encode([
    'источник' => ['корпус' => $root, 'наборов' => count($sites)],
    'скелеты'  => $скелет,
    'блоки'    => $выкладкаБлоков,
    'тексты'   => $текстыВыкладка,
], $опции) . "\n");
file_put_contents("$данные/pools.json", json_encode([
    'источник' => ['корпус' => $root, 'наборов' => count($sites)],
    'прорези'  => ['ИМЯ' => 'герой истории', 'СУММА' => 'выигрыш', 'RTP' => 'отдача слота',
                   'ПРОЦ' => 'размер бонуса', 'МИН' => 'срок вывода', 'РУБЛИ' => 'ставка героя в рублях',
                   'СЛОТОВ' => 'размер каталога', 'ПРОВАЙДЕРОВ' => 'число провайдеров',
                   'ВЕЙДЖЕР' => 'кратность отыгрыша'],
    'разделы'  => $разделы,
    'хвосты'   => $хвосты,
    'общие'    => ['банки' => $банки, 'анкоры' => $анкоры, 'слоты' => $слоты, 'эмодзи' => $эмодзи],
], $опции) . "\n");

printf("блоки:  %s/bloki.json  (%.1f МБ)\n", $данные, filesize("$данные/bloki.json") / 1048576);
printf("пулы:   %s/pools.json  (%.1f МБ)\n", $данные, filesize("$данные/pools.json") / 1048576);
foreach ($допСчёт as $вид => $n) { printf("дополнение: %s +%d\n", $вид, $n); }
foreach ($прозаСчёт as $вид => $n) { printf("проза со стороны: %s +%d\n", $вид, $n); }
if (!$отчёт) { exit(0); }

echo "\n══ скелеты ══\n";
foreach ($скелет as $t => $вар) {
    arsort($вар);
    printf("%-12s %d разных, чаще всего: ", $t, count($вар));
    printf("%s (×%d)\n", array_key_first($вар), reset($вар));
}
echo "\n══ разделы ══\n";
printf("%-12s %8s %8s %8s %8s %8s\n", 'тип', 'разделов', 'зачинов', 'H3', 'пунктов', 'финалов');
foreach (V5_TYPES as $t) {
    $r = $разделы[$t] ?? [];
    $c = fn($вид) => array_sum(array_map(fn($x) => count($x[$вид]), $r));
    printf("%-12s %8d %8d %8d %8d %8d\n", $t, count($r), $c('зачин'), $c('h3'), $c('пункты'), $c('финал'));
}
echo "\n══ банки прорезей ══\n";
foreach ($банки as $k => $b) {
    printf("%-12s %3d значений: %s\n", $k, count($b), implode(', ', array_slice(array_keys($b), 0, 12)));
}
printf("%-12s %3d карточек: %s\n", 'СЛОТЫ', count($слоты), implode(', ', array_slice(array_keys($слоты), 0, 6)));
printf("%-12s %3d адресов: %s\n", 'АНКОРЫ', count($анкоры), implode(' ', array_map(
    fn($u, $a) => $u . '×' . count($a), array_keys($анкоры), $анкоры)));
