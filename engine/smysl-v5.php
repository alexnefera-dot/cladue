<?php
declare(strict_types=1);

/**
 * Приёмка смысла: то, по чему счётчики сходятся, а текст всё равно сломан.
 *
 *   php engine/smysl-v5.php <папка-набора> [--json] [--подробно]
 *
 * `priyomka-v5.php` меряет форму: объём, число H2, тошноту, шинглы. На наборе,
 * где герой заходил с 12 606 ₽ и «доводил сумму» до тех же 12 606 ₽, в карточке
 * слота стояло `{RTP2}`, а отдача заявлялась как «RTP 445 %», она показывала
 * сто процентов полей. Пять таких дефектов нашлись глазами — этот скрипт
 * кодирует их, чтобы больше не находить руками.
 *
 * Нормы не выдуманы, а сняты с корпуса `samples/v5-donors`:
 *
 *   RTP 92–99 %, бонус «до N%» 15–1000, вейджер x20–x90, адресов ровно шесть.
 *
 * Ссылка страницы на саму себя дефектом НЕ считается: у доноров главная ведёт
 * на «/» 138 раз, а `app` на «/app» — 118. Это их приём, а не ошибка.
 */

require_once __DIR__ . '/src/V5Blocks.php';

$папка = ''; $asJson = in_array('--json', $argv, true);
$подробно = in_array('--подробно', $argv, true);
foreach (array_slice($argv, 1) as $a) { if ($a[0] !== '-') { $папка = rtrim($a, '/'); } }
if ($папка === '' || !is_dir($папка)) {
    fwrite(STDERR, "usage: php engine/smysl-v5.php <папка-набора> [--json] [--подробно]\n"); exit(1);
}
$профиль = json_decode((string) file_get_contents(__DIR__ . '/data-v5/profil-v5.json'), true);
$адресаКорпуса = array_keys($профиль['ссылки']['адреса_корпуса'] ?? []);

const V5S_RTP    = [92.0, 99.0];
const V5S_БОНУС  = [15, 1000];
// Нижней границы у вейджера нет: доноры пишут и «он не x1», и «от x3 до x5»
// про кэшбэк. Ловится только верх — там, где подстановка вставит чужое число.
const V5S_ВЕЙДЖЕР = [1, 90];

$находки = [];
$добавить = function (string $вид, string $тип, string $что, string $где = '') use (&$находки) {
    $находки[] = ['вид' => $вид, 'страница' => $тип, 'что' => $что, 'место' => $где];
};

/**
 * Текст с границами блоков. Без них соседние пункты списка склеиваются, и
 * «…слоты с высоким RTP» + «Стартовый бонус 300%» читаются как «RTP 300%».
 */
function v5ТекстБлоками(string $html): string
{
    $html = preg_replace('~<style\b[^>]*>.*?</style>~is', ' ', $html);
    $h = preg_replace('~</(p|li|h[1-6]|div|td|th|section|article|button|span)>~i', ' ¶ ', $html);
    return trim(preg_replace('~\s+~u', ' ',
        html_entity_decode(preg_replace('~<[^>]*>~', ' ', $h), ENT_QUOTES, 'UTF-8')));
}

/** Кусок текста вокруг совпадения — чтобы находку можно было прочитать. */
function v5Окно(string $t, int $поз, int $ширина = 90): string
{
    $от = max(0, $поз - $ширина / 2);
    return trim(preg_replace('~\s+~u', ' ', mb_substr($t, (int) $от, $ширина)));
}

$каталог = []; $анкоры = [];
foreach (V5_TYPES as $тип) {
    $f = "$папка/$тип.html";
    if (!is_file($f)) { continue; }
    $html = (string) file_get_contents($f);
    $текст = v5ТекстБлоками($html);

    // ── 1. незакрытые прорези: свои и донорские ─────────────────────
    if (preg_match_all('~\{[A-ZА-Я][A-ZА-Я0-9_]*(?::[а-я]{1,2})?\}~u', $html, $m)) {
        foreach (array_unique($m[0]) as $x) { $добавить('прорезь', $тип, "не заполнено: $x"); }
    }
    if (preg_match_all('~%[a-z_]+%~', $html, $m)) {
        foreach (array_unique($m[0]) as $x) {
            if ($x !== '%brand_name_ru%' && $x !== '%brand_name_en%') {
                $добавить('прорезь', $тип, "чужой плейсхолдер: $x");
            }
        }
    }

    // ── 2. числа вне корпусных норм ─────────────────────────────────
    // Точка и знаки конца предложения обрывают поиск: иначе «RTP на акционных
    // слотах …» дотягивается до процента из соседней фразы и выдаёт «RTP 300 %».
    if (preg_match_all('~RTP[^%.!?¶]{0,24}?(\d{2,4}(?:[.,]\d+)?)%~u', $текст, $m, PREG_OFFSET_CAPTURE)) {
        foreach ($m[1] as $i => [$v, $поз]) {
            $ч = (float) str_replace(',', '.', $v);
            if ($ч < V5S_RTP[0] || $ч > V5S_RTP[1]) {
                $добавить('число', $тип, "RTP {$v} % вне корпусных " . V5S_RTP[0] . '–' . V5S_RTP[1],
                    v5Окно($текст, (int) $m[0][$i][1]));
            }
        }
    }
    if (preg_match_all('~до\s+(\d{2,5})%~u', $текст, $m, PREG_OFFSET_CAPTURE)) {
        foreach ($m[1] as $i => [$v, $поз]) {
            if ((int) $v < V5S_БОНУС[0] || (int) $v > V5S_БОНУС[1]) {
                $добавить('число', $тип, "бонус до {$v} % вне корпусных " . V5S_БОНУС[0] . '–' . V5S_БОНУС[1],
                    v5Окно($текст, (int) $m[0][$i][1]));
            }
        }
    }
    // ── 2а. спорящие цифры внутри одного абзаца ────────────────────
    // Свойство площадки одно: RTP, заявленный джекпот, размер бонуса, срок
    // выплаты. Разные значения в соседних предложениях одного абзаца — то,
    // чего у доноров нет ни разу, а у нас набиралось до пяти на комплект.
    $факты = [
        'RTP'      => '~RTP[^%.!?¶]{0,24}?(\d{2,3}(?:[.,]\d)?)\s*%~u',
        'джекпот'  => '~джекпот\w*[^.!?¶]{0,24}?(?:до|в|—|составляет|достигает)\s*(\d+(?:[.,]\d+)?\s*(?:млн|тыс|к))\b~ui',
        'бонус'    => '~(?:бонус\w*|пакет\w*|подарок\w*)[^.!?¶]{0,20}?(\d{2,4})\s*%~u',
        'вывод'    => '~вывод\w*[^.!?¶]{0,24}?(\d{1,3})\s*(?:минут|мин\b)~u',
    ];
    foreach (preg_split('~¶~u', $текст) as $абзац) {
        if (mb_strlen(trim($абзац)) < 40) { continue; }
        foreach ($факты as $имяФакта => $re) {
            if (!preg_match_all($re, $абзац, $mm)) { continue; }
            $значения = array_values(array_unique(array_map(
                static fn (string $x): string => str_replace(',', '.', mb_strtolower(trim($x))), $mm[1])));
            if (count($значения) > 1) {
                $добавить('цифры спорят', $тип, "$имяФакта: " . implode(' и ', $значения),
                    trim(preg_replace('~\s+~u', ' ', mb_substr($абзац, 0, 120))));
            }
        }
    }

    // «x5» само по себе — множитель в описании слота, у доноров это норма.
    // Вейджером считается только то, что стоит рядом со словом об отыгрыше.
    if (preg_match_all('~(?:вейджер\w*|отыгрыш\w*|отыграть)[^.¶]{0,30}?\bx(\d{1,3})\b~ui', $текст, $m, PREG_OFFSET_CAPTURE)) {
        foreach ($m[1] as $i => [$v, $поз]) {
            if ((int) $v < V5S_ВЕЙДЖЕР[0] || (int) $v > V5S_ВЕЙДЖЕР[1]) {
                $добавить('число', $тип, "вейджер x{$v} вне корпусных x" . V5S_ВЕЙДЖЕР[0] . '–x' . V5S_ВЕЙДЖЕР[1],
                    v5Окно($текст, (int) $m[0][$i][1]));
            }
        }
    }

    // ── 3. ставка и результат ───────────────────────────────────────
    // «зашёл с 12 606 ₽ … довёл сумму до 12 606 ₽» — подстановка взяла одно
    // значение дважды; «поднял до 500 ₽ со ставки 3 000 ₽» — перепутала местами.
    $re = '~(?:зашёл|зашла|начал|начала|пополнил|пополнила|поставил|поставила)[^.!?¶]{0,80}?'
        . '(\d[\d\x{00A0} ]*)\s?(?:₽|рубл\w+)[^.!?¶]{0,110}?'
        . '(?:довёл|довела|поднял|подняла|вырос\w*|забрал|забрала|до)\s+(\d[\d\x{00A0} ]*)\s?(?:₽|рубл\w+)~u';
    if (preg_match_all($re, $текст, $m, PREG_OFFSET_CAPTURE)) {
        foreach ($m[1] as $i => [$a, $поз]) {
            $ставка = (int) preg_replace('~\D~u', '', $a);
            $итог = (int) preg_replace('~\D~u', '', $m[2][$i][0]);
            if ($ставка > 0 && $итог <= $ставка) {
                $добавить('деньги', $тип, $итог === $ставка ? 'ставка равна результату' : 'результат меньше ставки',
                    v5Окно($текст, (int) $m[0][$i][1], 120));
            }
        }
    }

    // ── 4. фактура набора: каталог и провайдеры едины на все страницы ──
    if (preg_match('~([\d\x{00A0} ]+)\+\s*(?:слот|игр)~u', $текст, $m)) {
        $каталог['слотов'][trim($m[1])][] = $тип;
    }
    if (preg_match('~(\d{2,3})\+\s*провайдер~u', $текст, $m)) {
        $каталог['провайдеров'][$m[1]][] = $тип;
    }

    // ── 5. род героя и его глагола ──────────────────────────────────
    // «Елена зашёл» — подстановка не посмотрела на пол; в корпусе такого нет.
    //
    // Две ловушки, обе всплыли на калибровке по донорам:
    //  · «Ивана был» — это родительный падеж мужского имени, а не женское имя;
    //    поэтому имя должно точно совпасть с именительным из словаря;
    //  · «Михаил сначала» — наречие на «-ла» не глагол; поэтому глагол берётся
    //    только вплотную за именем и не из списка исключений.
    static $именительный = null;
    if ($именительный === null) {
        $именительный = array_flip((new ReflectionClass('PersonNames'))->getConstant('BASE'));
    }
    $неГлаголы = ['сначала' => 1, 'мало' => 1, 'немало' => 1, 'около' => 1, 'бывало' => 1,
                  'начала' => 1, 'зеркала' => 1, 'канала' => 1, 'пожалуй' => 1, 'вдоволь' => 1];
    if (preg_match_all('~(?<![\p{L}])(\p{Lu}\p{Ll}{2,11})\s+(\p{L}{3,}л(?:а|ся|ась)?)(?![\p{L}])~u',
        $текст, $m, PREG_SET_ORDER)) {
        foreach ($m as $x) {
            $имя = $x[1]; $глагол = $x[2];
            if (!isset($именительный[$имя])) { continue; }
            if (isset($неГлаголы[mb_strtolower($глагол)])) { continue; }
            $родИмени = v5Rod($имя);
            $родГлагола = preg_match('~(?:ла|лась)$~u', $глагол) ? 'ж' : 'м';
            if ($родИмени !== $родГлагола) {
                $добавить('род', $тип, "«{$имя} {$глагол}» — имя " . ($родИмени === 'ж' ? 'женское' : 'мужское')
                    . ', глагол ' . ($родГлагола === 'ж' ? 'женский' : 'мужской'));
            }
        }
    }

    // ── 6. один герой — разные города на одной странице ─────────────
    $города = [];
    if (preg_match_all('~(\p{Lu}\p{Ll}{2,11})\s+из\s+(\p{Lu}\p{Ll}{3,14})~u', $текст, $m, PREG_SET_ORDER)) {
        foreach ($m as $x) { if (preg_match(PersonNames::regex(), $x[1])) { $города[$x[1]][$x[2]] = 1; } }
    }
    foreach ($города as $имя => $сп) {
        if (count($сп) > 1) {
            $добавить('герой', $тип, "{$имя} сразу из нескольких городов: " . implode(', ', array_keys($сп)));
        }
    }

    // ── 7. анкоры: одна метка на разные адреса ──────────────────────
    if (preg_match_all('~<a href="([^"]+)"[^>]*>\s*(.*?)\s*</a>~s', $html, $m, PREG_SET_ORDER)) {
        foreach ($m as $x) {
            $метка = mb_strtolower(trim(preg_replace('~\s+~u', ' ', strip_tags($x[2]))));
            if ($метка === '') { continue; }
            $анкоры[$метка][$x[1]] = 1;
            if (!in_array($x[1], $адресаКорпуса, true)) {
                $добавить('ссылка', $тип, "адрес вне корпуса: {$x[1]}");
            }
        }
    }

    // ── 8. почти-дубли подряд в одном списке ────────────────────────
    foreach (v5Uzly($html) as $u) {
        if ($u['класс'] !== '' || !in_array($u['тег'], ['ul', 'ol'], true)) { continue; }
        if (!preg_match_all('~<li[^>]*>(.*?)</li>~s', $u['html'], $m)) { continue; }
        $пункты = array_map('v5Text', $m[1]);
        foreach ($пункты as $i => $п) {
            foreach (array_slice($пункты, $i + 1, 2) as $сосед) {
                if (v5Blizost($п, $сосед) > 0.5) {
                    $добавить('повтор', $тип, 'два почти одинаковых пункта рядом',
                        mb_substr($п, 0, 70) . ' ⟂ ' . mb_substr($сосед, 0, 70));
                }
            }
        }
    }
}

// ── сквозные проверки набора ────────────────────────────────────────
foreach ($каталог as $что => $значения) {
    if (count($значения) > 1) {
        $списком = [];
        foreach ($значения as $v => $где) { $списком[] = "$v (" . implode(', ', $где) . ')'; }
        $добавить('фактура', '—', "$что расходится по страницам: " . implode(' · ', $списком));
    }
}
// У доноров 3 % меток ведут на два адреса («слоты» на «/» и «/slots»), но ни
// одна — на три. Порог взят оттуда же: два адреса норма, три уже путаница.
foreach ($анкоры as $метка => $адреса) {
    if (count($адреса) > 2) {
        $добавить('анкор', '—', "«{$метка}» ведёт сразу на " . implode(', ', array_keys($адреса)));
    }
}

// ── вывод ───────────────────────────────────────────────────────────
if ($asJson) {
    echo json_encode(['набор' => basename($папка), 'находки' => $находки],
        JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT), "\n";
    exit($находки ? 1 : 0);
}
printf("══ приёмка смысла: %s ══\n\n", basename($папка));
if (!$находки) { echo "✓ чисто\n"; exit(0); }
$поВидам = [];
foreach ($находки as $н) { $поВидам[$н['вид']][] = $н; }
foreach ($поВидам as $вид => $список) {
    printf("── %s: %d ──\n", $вид, count($список));
    $показать = $подробно ? $список : array_slice($список, 0, 5);
    foreach ($показать as $н) {
        printf("  %-12s %s\n", $н['страница'], $н['что']);
        if ($н['место'] !== '') { printf("               … %s\n", $н['место']); }
    }
    if (!$подробно && count($список) > 5) { printf("  … ещё %d\n", count($список) - 5); }
    echo "\n";
}
printf("всего находок: %d\n", count($находки));
exit(1);
