<?php
declare(strict_types=1);

/**
 * Достижимый диапазон движка по каждому полю профиля.
 *
 *   php engine/dostizhimoe-v5.php <папка-с-наборами>… [--в-профиль]
 *
 * Зачем. Профиль описывает корпус: медиану и полосу 10–90 по донорам. Цель
 * набора разыгрывается внутри этой полосы, чтобы комплекты не сходились в одну
 * точку. Но часть полосы движку недоступна: сборка из готовых кусков даёт
 * абзацы в 33–42 слова, а доноры пишут по 39–54, и цель в пятьдесят слов на
 * абзац не берётся ни одной попыткой — страница просто проваливает приёмку.
 *
 * Замер по 288 собранным страницам: медиана покрытия полосы — 100 %, то есть
 * почти везде движок свободен. Но два десятка полей закрывают её на 15–50 %:
 * words_per_para, nausea_acad, strong_lead_pct. Розыгрыш должен знать об этом
 * и целиться в пересечение корпусной полосы с достижимым.
 *
 * Пересчитывать после расширения пулов и после правок вёрстки: и то и другое
 * двигает границы того, что движок умеет.
 *
 * ВАЖНО — выборка только из наборов ТЕКУЩЕГО движка. Замер по всем 233
 * наборам архива дал диапазон шире реального: старые комплекты собирала другая
 * версия, и цель по словам уехала на 1900 там, где сборка сегодня даёт 1400.
 * Недостижимая цель хуже отсутствия розыгрыша: она валит страницу и разброса
 * не приносит. Берите последние наборы и пробные прогоны, десятка два-три.
 */

require_once __DIR__ . '/src/Analyzer.php';
require_once __DIR__ . '/src/PageMetrics.php';
require_once __DIR__ . '/src/NicheLexicon.php';
require_once __DIR__ . '/src/Stylistics.php';
require_once __DIR__ . '/src/V5Blocks.php';

$папки = []; $вПрофиль = false;
foreach (array_slice($argv, 1) as $a) {
    if ($a === '--в-профиль') { $вПрофиль = true; continue; }
    if ($a[0] !== '-') { $папки[] = rtrim($a, '/'); }
}
if (!$папки) {
    fwrite(STDERR, "usage: php engine/dostizhimoe-v5.php <папка>… [--в-профиль]\n"); exit(1);
}

$путь = __DIR__ . '/data-v5/profil-v5.json';
$профиль = json_decode((string) file_get_contents($путь), true);
if (!$профиль) { fwrite(STDERR, "нет data-v5/profil-v5.json\n"); exit(1); }

$a = new Analyzer();
$собрано = [];   // тип => поле => [значения]
$страниц = 0;
foreach ($папки as $п) {
    foreach (V5_TYPES as $тип) {
        $f = "$п/$тип.html";
        if (!is_file($f)) { continue; }
        $страниц++;
        $карта = PageMetrics::measure($a, $тип,
            preg_replace('~<(?![a-zA-Z/!?])~', '&lt;', (string) file_get_contents($f)),
            ['ru' => '%brand_name_ru%', 'en' => '%brand_name_en%']);
        foreach ($профиль['страницы'][$тип]['поля'] ?? [] as $k => $поле) {
            if (!isset($карта[$k]) || !is_numeric($карта[$k])) { continue; }
            $собрано[$тип][$k][] = (float) $карта[$k];
        }
    }
}
if ($страниц < 24) {
    fwrite(STDERR, "мало страниц ($страниц): диапазон по такой выборке случаен\n"); exit(1);
}

$узко = [];
foreach ($собрано as $тип => $поля) {
    foreach ($поля as $k => $знач) {
        // Границы берём с запасом в четверть размаха: выборка конечна, и
        // край, который движок взял один раз из трёхсот, он возьмёт и ещё.
        $мин = min($знач); $макс = max($знач);
        $запас = ($макс - $мин) * 0.25;
        $профиль['страницы'][$тип]['поля'][$k]['достижимое'] =
            [round($мин - $запас, 2), round($макс + $запас, 2)];

        $п = $профиль['страницы'][$тип]['поля'][$k];
        if (!$п['держат'] || !isset($п['полоса'])) { continue; }
        [$lo, $hi] = [(float) $п['полоса'][0], (float) $п['полоса'][1]];
        if ($hi <= $lo) { continue; }
        $доля = max(0.0, min($hi, $макс + $запас) - max($lo, $мин - $запас)) / ($hi - $lo);
        if ($доля < 0.6) { $узко[] = [$доля, $тип, $k, $мин, $макс, $lo, $hi]; }
    }
}
usort($узко, fn($x, $y) => $x[0] <=> $y[0]);

printf("страниц в замере: %d, полей: %d\n\n", $страниц,
    array_sum(array_map('count', $собрано)));
printf("%-34s %18s %18s %9s\n", 'тип/поле', 'движок достаёт', 'полоса корпуса', 'покрытие');
foreach ($узко as [$доля, $тип, $k, $мин, $макс, $lo, $hi]) {
    printf("%-34s %18s %18s %8.0f%%\n", "$тип/$k",
        round($мин, 1) . '–' . round($макс, 1), $lo . '–' . $hi, $доля * 100);
}
printf("\nполей, где движок закрывает меньше 60%% полосы: %d\n", count($узко));

if ($вПрофиль) {
    file_put_contents($путь, json_encode($профиль,
        JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT) . "\n");
    echo "записано в data-v5/profil-v5.json\n";
} else {
    echo "\n(сухой прогон; чтобы записать — --в-профиль)\n";
}
