/** Подстановка новых пар в разметку блока: меняются слова, теги остаются. */
function v5ВставитьFaq(string $html, array $пары): string
{
    $i = 0;
    $html = preg_replace_callback('~(<h3 class="faq-question" itemprop="name">\s*)(.*?)(\s*</h3>)~s',
        function ($m) use (&$i, $пары) { return isset($пары[$i]) ? $m[1] . $пары[$i++]['в'] . $m[3] : $m[0]; },
        $html);
    $i = 0;
    return preg_replace_callback('~(<div itemprop="text">\s*)(.*?)(\s*</div>)~s',
        function ($m) use (&$i, $пары) {
            if (!isset($пары[$i])) { return $m[0]; }
            $о = str_starts_with(ltrim($m[2]), '<p>')
                ? "<p>\n            " . $пары[$i]['о'] . "\n          </p>"
                : $пары[$i]['о'];
            $i++;
            return $m[1] . $о . $m[3];
        }, $html);
}

/** Сколько абзацев и пунктов в куске прозы. */
function v5Структура(string $html): array
{
    return [preg_match_all('~<p[\s>]~', $html), preg_match_all('~<li[\s>]~', $html)];
}

