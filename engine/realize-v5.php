<?php
declare(strict_types=1);

/**
 * Реалайзер v5: проза разделов переписывается заново, каркас остаётся собранным.
 *
 *   php engine/realize-v5.php --набор=samples/v5-final/<имя> [--тип=news]
 *                             [--сухой] [--модель=…] [--эффорт=medium]
 *
 * Зачем: сборка попадает в форму (94–100 % полей профиля), но не в
 * уникальность. Замер на подвыборках корпуса дал кривую 56.8/N + 12.9 —
 * асимптота почти тринадцать процентов, то есть пересборка чужих фраз ниже
 * этого не опустится ни при каком числе доноров. Совпадение снимается только
 * написанием.
 *
 * Что здесь переписывается, а что нет:
 *
 *  · **Виджеты не трогаются.** Их разметка у всех двенадцати доноров общая, и
 *    доноры пересекаются на них между собой — воспроизводить надо, а не прятать.
 *  · **Тело раздела пишется заново:** H2 остаётся (это закрытый список фабрики),
 *    под ним модель пишет зачин, H3, список и финал.
 *  · **Фактура приходит из паспорта набора** — каталог, провайдеры, вейджер,
 *    герои. Их модель не выдумывает: числа держатся на весь комплект.
 *  · **Ссылки заданы адресами**, а метку модель пишет своими словами в нужном
 *    падеже: у корпуса 42 % анкоров встречаются ровно один раз, списком это
 *    не воспроизвести.
 *
 * Один вызов — один раздел, 250–450 слов. Это не экономия, а требование:
 * замеры v4 показали разброс главной 63–84 % при одном и том же промпте, если
 * просить страницу целиком; на коротком выходе реалайзер держится ровно.
 *
 * Ключ читает `realize.php` — из `ANTHROPIC_API_KEY`, `ANTHROPIC_AUTH_TOKEN`
 * либо из gitignored `engine/.anthropic-key`. Без ключа работает `--сухой`:
 * промпты пишутся в `tmp/realize-<набор>/`, вызовов нет.
 */

require_once __DIR__ . '/src/V5Blocks.php';

$набор = ''; $толькоТип = ''; $модель = ''; $эффорт = '';
$сухой = in_array('--сухой', $argv, true);
foreach (array_slice($argv, 1) as $a) {
    if (str_starts_with($a, '--набор=')) { $набор = rtrim(substr($a, strlen('--набор=')), '/'); }
    elseif (str_starts_with($a, '--тип=')) { $толькоТип = substr($a, strlen('--тип=')); }
    elseif (str_starts_with($a, '--модель=')) { $модель = substr($a, strlen('--модель=')); }
    elseif (str_starts_with($a, '--эффорт=')) { $эффорт = substr($a, strlen('--эффорт=')); }
}
if ($набор === '' || !is_dir($набор)) {
    fwrite(STDERR, "usage: php engine/realize-v5.php --набор=samples/v5-final/<имя> [--тип=news] [--сухой]\n");
    exit(1);
}
$паспортФайл = "$набор/nabor.json";
if (!is_file($паспортФайл)) {
    fwrite(STDERR, "нет $паспортФайл — набор сначала собирается generator-v5.php\n"); exit(1);
}
$паспорт = json_decode((string) file_get_contents($паспортФайл), true);
$профиль = json_decode((string) file_get_contents(__DIR__ . '/data-v5/profil-v5.json'), true);

// Ключ проверяется до первого вызова: без него пятьдесят девять попыток
// подряд упрутся в один и тот же отказ, а оператор увидит это только в конце.
if (!$сухой) {
    $естьКлюч = (getenv('ANTHROPIC_API_KEY') ?: getenv('ANTHROPIC_AUTH_TOKEN')) !== false
        && (getenv('ANTHROPIC_API_KEY') ?: getenv('ANTHROPIC_AUTH_TOKEN')) !== '';
    $файлКлюча = getenv('ANTHROPIC_KEY_FILE') ?: (__DIR__ . '/.anthropic-key');
    if (!$естьКлюч && (!is_file($файлКлюча) || trim((string) file_get_contents($файлКлюча)) === '')) {
        fwrite(STDERR, "нет ключа: задай ANTHROPIC_API_KEY либо положи его в engine/.anthropic-key\n"
            . "(файл в .gitignore). Промпты можно посмотреть без ключа: --сухой\n");
        exit(2);
    }
}

$промпты = 'tmp/realize-' . basename($набор);
if (!is_dir($промпты)) { mkdir($промпты, 0777, true); }

/**
 * Жанр корпуса словами. Это не украшение промпта: половина полей профиля —
 * следствие именно этих правил (`honest`, `cta`, `ty`, `numbers_per100`).
 */
const V5_ZHANR = <<<'TXT'
ЖАНР. Разговор на «ты», короткие рубленые фразы, без канцелярита и без
рекламного пафоса. Опорный приём — история живого человека: имя, ставка,
результат, и тут же честная оговорка, что так бывает не у всех. Рядом с любым
обещанием стоит риск: «можно и выиграть, и проиграть», «гарантий нет»,
«вейджер отыгрывать придётся». Слова «эксклюзивный», «лучший», «уникальный» и
восклицательные знаки в прозе не используются.

ЧИСЛА. Берутся только из блока ФАКТУРА и из перечисленных ниже значений.
Своих чисел не выдумывать. Проценты бонуса пишутся как «до N%», отдача — как
«RTP N,N%», сроки — «за N мин», суммы — «N к» или «N,N млн».

ССЫЛКИ. Ставятся внутрь предложения, метка — обычное слово или оборот в нужном
падеже («регистрацию», «рабочее зеркало», «играть бесплатно»). Одинаковые метки
не повторять: у корпуса больше сорока процентов анкоров встречаются ровно один
раз. Ссылка на саму страницу не ставится.

ВЁРСТКА. Только теги <p>, <h3>, <ul>, <li>, <strong> и <a href="…">. Никаких
<html>, <head>, <body>, <div>, классов, id и markdown. Каждый тег с новой
строки, текст внутри тега — с отступом в два пробела, как в примере разметки
ниже. Имя площадки — только плейсхолдер %brand_name_ru%.
TXT;

/** Разбор страницы на голову, разделы тела и хвост. */
function v5РазделыСтраницы(string $html): array
{
    $узлы = v5Uzly($html);
    $проза = fn(array $u) => $u['класс'] === '' && in_array($u['тег'], ['h2', 'h3', 'p', 'ul', 'ol'], true);
    $голова = []; $разделы = []; $хвост = []; $текущий = null; $начался = false;
    foreach ($узлы as $u) {
        if ($u['тег'] === 'h2' && $u['класс'] === '') {
            $начался = true;
            if ($текущий) { $разделы[] = $текущий; }
            $текущий = ['h2' => v5Vnutr($u['html']), 'узлы' => []];
            continue;
        }
        if (!$начался) { $голова[] = $u; continue; }
        if ($проза($u)) { $текущий['узлы'][] = $u; continue; }
        // виджет после начала тела — это хвост
        if ($текущий) { $разделы[] = $текущий; $текущий = null; }
        $хвост[] = $u;
    }
    if ($текущий) { $разделы[] = $текущий; }
    return [$голова, $разделы, $хвост];
}

/** Промпт на один раздел: цели, фактура, адреса и образец разметки. */
function v5ПромптРаздела(string $тип, array $раздел, array $паспорт, array $профиль): string
{
    $абзацев = 0; $пунктов = 0; $h3 = ''; $ссылки = []; $числа = [];
    foreach ($раздел['узлы'] as $u) {
        if ($u['тег'] === 'p') { $абзацев++; }
        if ($u['тег'] === 'h3') { $h3 = v5Text($u['html']); }
        if ($u['тег'] === 'ul' || $u['тег'] === 'ol') { $пунктов += preg_match_all('~<li~', $u['html']); }
        if (preg_match_all('~href="([^"]+)"~', $u['html'], $m)) { foreach ($m[1] as $h) { $ссылки[$h] = ($ссылки[$h] ?? 0) + 1; } }
        if (preg_match_all('~(?:RTP\s+\d{2}(?:[.,]\d)?%|до\s+\d{2,4}%|\d+(?:[.,]\d+)?\s?(?:к|млн)|за\s+\d{1,3}\s*мин)~u',
            v5Text($u['html']), $m2)) { foreach ($m2[0] as $x) { $числа[$x] = 1; } }
    }
    $слов = 0;
    foreach ($раздел['узлы'] as $u) {
        $слов += count(preg_split('~\s+~u', v5Text($u['html']), -1, PREG_SPLIT_NO_EMPTY));
    }
    $герой = $паспорт['герои']['м'][array_rand($паспорт['герои']['м'])];
    $героиня = $паспорт['герои']['ж'][array_rand($паспорт['герои']['ж'])];
    $адреса = [];
    foreach ($ссылки as $h => $n) { $адреса[] = "$h — {$n} шт."; }

    $фактура = "* каталог: {$паспорт['каталог']['СЛОТОВ']}+ слотов, {$паспорт['каталог']['ПРОВАЙДЕРОВ']}+ провайдеров\n"
             . "* вейджер: x{$паспорт['вейджер']}\n"
             . "* герой этого раздела: {$герой} (если нужна героиня — {$героиня})\n"
             . "* значения, которые уже стоят в разделе и должны остаться: "
             . (($числа) ? implode(', ', array_keys($числа)) : 'нет') . "\n";

    $образец = "<p>\n  Текст абзаца со <a href=\"/slots\">ссылкой</a> внутри фразы.\n</p>\n"
             . "<h3>\n  Подзаголовок\n</h3>\n<ul>\n  <li>\n    Пункт списка.\n  </li>\n</ul>";

    $u = $профиль['уникальность']['по_типам'][$тип] ?? null;
    $уник = $u ? "Совпадение с любым чужим текстом — не выше {$u['потолок']} % шестисловных цепочек.\n" : '';

    return "Напиши тело одного раздела страницы «{$тип}» для казино-портала.\n\n"
        . "ЗАГОЛОВОК РАЗДЕЛА (уже стоит, повторять его не нужно):\n{$раздел['h2']}\n\n"
        . "ЧТО ДОЛЖНО ПОЛУЧИТЬСЯ:\n"
        . "* {$абзацев} абзаца(ев) зачина, затем один H3, затем список на {$пунктов} пунктов, затем финальный абзац\n"
        . "* объём всего раздела — около {$слов} слов (±10 %)\n"
        . ($h3 !== '' ? "* H3 по смыслу близок к «{$h3}», но формулировка своя\n" : '')
        . ($адреса ? "* ссылки: " . implode('; ', $адреса) . "\n" : "* ссылок в этом разделе нет\n")
        . "\nФАКТУРА (числа только отсюда):\n{$фактура}\n"
        . V5_ZHANR . "\n\n"
        . $уник
        . "\nОБРАЗЕЦ РАЗМЕТКИ:\n{$образец}\n\n"
        . "Верни только HTML тела раздела, без заголовка H2, без пояснений.";
}

// ── прогон ──────────────────────────────────────────────────────────
$типы = $толькоТип !== '' ? [$толькоТип] : V5_TYPES;
$всего = 0; $написано = 0; $ошибок = 0;
printf("══ реалайзер v5: %s%s ══\n\n", basename($набор), $сухой ? ' (сухой прогон)' : '');

foreach ($типы as $тип) {
    $файл = "$набор/$тип.html";
    if (!is_file($файл)) { continue; }
    $html = (string) file_get_contents($файл);
    [$голова, $разделы, $хвост] = v5РазделыСтраницы($html);
    if (!$разделы) { printf("%-13s разделов нет, пропуск\n", $тип); continue; }

    $куски = array_map(fn($u) => $u['html'], $голова);
    foreach ($разделы as $i => $раздел) {
        $всего++;
        $н = $i + 1;
        $промпт = v5ПромптРаздела($тип, $раздел, $паспорт, $профиль);
        $пФайл = "$промпты/{$тип}-{$н}.md";
        file_put_contents($пФайл, $промпт);
        $куски[] = v5Uzel('h2', $раздел['h2']);

        if ($сухой) {
            foreach ($раздел['узлы'] as $u) { $куски[] = $u['html']; }
            continue;
        }

        $оФайл = "$промпты/{$тип}-{$н}.html";
        $кмд = 'php ' . escapeshellarg(__DIR__ . '/realize.php')
             . ' --prompt=' . escapeshellarg($пФайл) . ' --out=' . escapeshellarg($оФайл)
             . ($модель !== '' ? ' --model=' . escapeshellarg($модель) : '')
             . ($эффорт !== '' ? ' --effort=' . escapeshellarg($эффорт) : '')
             . ' 2>&1';
        $вывод = [];
        exec($кмд, $вывод, $код);
        if ($код !== 0 || !is_file($оФайл)) {
            $ошибок++;
            // Три отказа подряд — это не сеть, а конфигурация: дальше не идём.
            if ($ошибок >= 3 && $написано === 0) {
                fwrite(STDERR, "три отказа подряд без единого успеха — прогон остановлен\n");
                exit(3);
            }
            printf("%-13s раздел %d — сбой (%s), остаётся собранный\n", $тип, $н, trim(implode(' ', array_slice($вывод, -1))));
            foreach ($раздел['узлы'] as $u) { $куски[] = $u['html']; }
            continue;
        }
        $новое = trim((string) file_get_contents($оФайл));
        // Модель иногда оборачивает ответ в ```html — снимаем.
        $новое = preg_replace('~^```[a-z]*\s*|\s*```$~', '', $новое);
        if (v5Text($новое) === '') {
            $ошибок++;
            foreach ($раздел['узлы'] as $u) { $куски[] = $u['html']; }
            continue;
        }
        $куски[] = $новое;
        $написано++;
        printf("%-13s раздел %d — %d слов\n", $тип, $н,
            count(preg_split('~\s+~u', v5Text($новое), -1, PREG_SPLIT_NO_EMPTY)));
    }
    foreach ($хвост as $u) { $куски[] = $u['html']; }

    if (!$сухой) { file_put_contents($файл, implode("\n", $куски) . "\n"); }
}

if ($сухой) {
    printf("\nпромптов написано: %d, лежат в %s\n", $всего, $промпты);
    echo "вызовов не было: сухой прогон. Для боевого нужен ключ в ANTHROPIC_API_KEY\n"
       . "или в gitignored engine/.anthropic-key.\n";
    exit(0);
}
printf("\nразделов переписано %d из %d, сбоев %d\n", $написано, $всего, $ошибок);
echo "дальше: php engine/dovodchik-v5.php $набор && php engine/priyomka-v5.php $набор\n";
