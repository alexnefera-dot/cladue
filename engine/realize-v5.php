/**
 * Что вылетело за коридор корпуса. Правило то же, что в приёмке:
 * `|наше − цель| ≤ max(0,25·|цель|; пол)`, иначе поле в брифе.
 *
 * @return array<int,array{0:string,1:float,2:float,3:float}> ключ, наше, цель, перекос
 */
function v5Промахи(array $карта, array $поля): array
{
    $мимо = [];
    foreach ($поля as $k => $п) {
        if (!in_array($k, V5_PRAVIMYE, true)) { continue; }
        if (!($п['держат'] ?? false)) { continue; }
        if (!isset($карта[$k]) || !is_numeric($карта[$k])) { continue; }
        $наше = (float) $карта[$k]; $цель = (float) $п['цель'];
        $допуск = max(0.25 * abs($цель), $п['дробное'] ? 0.8 : 2.0);
        if (abs($наше - $цель) <= $допуск) { continue; }
        $мимо[] = [$k, $наше, $цель, abs($наше - $цель) / max($допуск, 0.001)];
    }
    usort($мимо, fn($a, $b) => $b[3] <=> $a[3]);
    return $мимо;
}

/** Бриф словами: не больше десяти строк, самые крупные перекосы сверху. */
function v5Бриф(array $мимо): string
{
    $строки = [];
    foreach (array_slice($мимо, 0, 10) as [$k, $наше, $цель, ]) {
        $подпись = PageMetrics::FIELDS[$k][0] ?? $k;
        $дробное = (PageMetrics::FIELDS[$k][1] ?? 0) === 1;
        $разница = $цель - $наше;
        $куда = $разница > 0 ? 'добавь' : 'убери';
        $сколько = $дробное
            ? sprintf('%s до %.1f', $разница > 0 ? 'подними' : 'снизь', $цель)
            : sprintf('%s %d', $куда, (int) round(abs($разница)));
        $строки[] = sprintf('* %s: сейчас %s, цель %s — %s',
            $подпись,
            $дробное ? sprintf('%.1f', $наше) : (string) (int) round($наше),
            $дробное ? sprintf('%.1f', $цель) : (string) (int) round($цель),
            $сколько);
    }
    return implode("\n", $строки);
}

