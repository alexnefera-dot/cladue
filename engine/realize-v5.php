/** Разбор страницы на голову, разделы тела и хвост. */
function v5РазделыСтраницы(string $html): array
{
    $узлы = v5Uzly($html);
    $проза = fn(array $u) => $u['класс'] === '' && in_array($u['тег'], ['h2', 'h3', 'p', 'ul', 'ol'], true);
    $голова = []; $разделы = []; $хвост = []; $текущий = null; $начался = false;
    foreach ($узлы as $u) {
        if ($u['тег'] === 'h2' && $u['класс'] === '') {
            $начался = true;
            if ($текущий) { $разделы[] = $текущий; }
            $текущий = ['h2' => v5Vnutr($u['html']), 'узлы' => []];
            continue;
        }
        if (!$начался) { $голова[] = $u; continue; }
        if ($проза($u)) { $текущий['узлы'][] = $u; continue; }
        // виджет после начала тела — это хвост
        if ($текущий) { $разделы[] = $текущий; $текущий = null; }
        $хвост[] = $u;
    }
    if ($текущий) { $разделы[] = $текущий; }
    return [$голова, $разделы, $хвост];
}

/** Промпт на один раздел: цели, фактура, адреса и образец разметки. */
function v5ПромптРаздела(string $тип, array $раздел, array $паспорт, array $профиль, int $разделов): string
{
    $абзацев = 0; $пунктов = 0; $h3 = ''; $ссылки = []; $числа = [];
    foreach ($раздел['узлы'] as $u) {
        if ($u['тег'] === 'p') { $абзацев++; }
        if ($u['тег'] === 'h3') { $h3 = v5Text($u['html']); }
        if ($u['тег'] === 'ul' || $u['тег'] === 'ol') { $пунктов += preg_match_all('~<li~', $u['html']); }
        if (preg_match_all('~href="([^"]+)"~', $u['html'], $m)) { foreach ($m[1] as $h) { $ссылки[$h] = ($ссылки[$h] ?? 0) + 1; } }
        if (preg_match_all('~(?:RTP\s+\d{2}(?:[.,]\d)?%|до\s+\d{2,4}%|\d+(?:[.,]\d+)?\s?(?:к|млн)|за\s+\d{1,3}\s*мин)~u',
            v5Text($u['html']), $m2)) { foreach ($m2[0] as $x) { $числа[$x] = 1; } }
    }
    $слов = 0;
    foreach ($раздел['узлы'] as $u) {
        $слов += count(preg_split('~\s+~u', v5Text($u['html']), -1, PREG_SPLIT_NO_EMPTY));
    }
    // Герой выбирается по заголовку раздела, а не случайно: иначе повторный
    // запуск даёт другой промпт, и написанный текст перестаёт ему отвечать.
    $ключ = crc32($тип . '|' . $раздел['h2']);
    $герой = $паспорт['герои']['м'][$ключ % count($паспорт['герои']['м'])];
    $героиня = $паспорт['герои']['ж'][($ключ >> 8) % count($паспорт['герои']['ж'])];
    $адреса = [];
    foreach ($ссылки as $h => $n) { $адреса[] = "$h — {$n} шт."; }

    $фактура = "* каталог: {$паспорт['каталог']['СЛОТОВ']}+ слотов, {$паспорт['каталог']['ПРОВАЙДЕРОВ']}+ провайдеров\n"
             . "* вейджер: x{$паспорт['вейджер']}\n"
             . "* герой этого раздела: {$герой} (если нужна героиня — {$героиня})\n"
             . "* значения, которые уже стоят в разделе и должны остаться: "
             . (($числа) ? implode(', ', array_keys($числа)) : 'нет') . "\n";

    $образец = "<p>\n  Текст абзаца со <a href=\"/slots\">ссылкой</a> внутри фразы.\n</p>\n"
             . "<h3>\n  Подзаголовок\n</h3>\n<ul>\n  <li>\n    Пункт списка.\n  </li>\n</ul>";

    $u = $профиль['уникальность']['по_типам'][$тип] ?? null;
    $уник = $u ? "Совпадение с любым чужим текстом — не выше {$u['потолок']} % шестисловных цепочек.\n" : '';

    // Квоты языка. Первый боевой прогон показал, что без них модель пишет
    // «вообще в жанре», но мимо цифр: вопросов вдвое меньше нормы, призывов
    // втрое больше, бренда вдвое чаще. Цели берутся из профиля своего типа и
    // делятся на число разделов страницы.
    $поля = $профиль['страницы'][$тип]['поля'] ?? [];
    $наРаздел = function (string $k) use ($поля, $разделов): ?int {
        if (!isset($поля[$k]['цель'])) { return null; }
        return (int) round((float) $поля[$k]['цель'] / max(1, $разделов));
    };
    $квоты = [];
    foreach ([['faq', 'вопросительных предложений'], ['cta', 'прямых призывов («играй», «забери», «жми»)'],
              ['brand_ru', 'упоминаний %brand_name_ru%'], ['honest', 'мест, где назван минус или риск'],
              ['imperatives', 'глаголов в повелительном наклонении']] as [$k, $подпись]) {
        $n = $наРаздел($k);
        if ($n === null) { continue; }
        $квоты[] = $n === 0 ? "* {$подпись}: ни одного" : "* {$подпись}: ровно {$n}";
    }
    // «Около N» модель читает как «сколько выйдет»: на боевом прогоне просили
    // по два вопроса на раздел, получили ноль во всей прозе. Числа названы
    // точно, и сказано, что их считают.
    $цели = $квоты ? "\nЦЕЛИ ЯЗЫКА (на этот раздел, сняты с корпуса). Эти величины\n"
        . "пересчитываются счётчиком после написания, и раздел с промахом\n"
        . "отправляется на переписывание — считай сам, прежде чем отдать:\n"
        . implode("\n", $квоты) . "\n" : '';

    // Доля разовых меток. В первом прогоне промпт требовал «одинаковые метки не
    // повторять», и вышло 80 % разовых против корпусных 36 %: корпус метки как
    // раз повторяет, и требование было ошибкой.
    $разовых = $поля['anchor_once_pct']['цель'] ?? null;
    $меткиПравило = $разовых === null ? '' :
        "\nМЕТКИ ССЫЛОК. Не делай все метки разными: у корпуса ровно один раз\n"
        . "встречается лишь {$разовых} % меток, остальные повторяются. Если ссылок в\n"
        . "разделе больше двух, часть меток должна совпадать между собой.\n";

    return "Напиши тело одного раздела страницы «{$тип}» для казино-портала.\n\n"
        . "ЗАГОЛОВОК РАЗДЕЛА (уже стоит, повторять его не нужно):\n{$раздел['h2']}\n\n"
        . "ЧТО ДОЛЖНО ПОЛУЧИТЬСЯ (числа точные, они пересчитываются счётчиком):\n"
        . "* ровно " . max(1, $абзацев - 1) . " тега <p> зачина, затем один H3, затем <ul> ровно на {$пунктов} <li>, затем последний <p> финала\n"
        . "* итого тегов <p> в разделе — {$абзацев}, тегов <li> — {$пунктов}\n"
        . "* объём всего раздела — около {$слов} слов (±10 %); если абзацев мало, они длинные, а не наоборот\n"
        . ($h3 !== '' ? "* H3 по смыслу близок к «{$h3}», но формулировка своя\n" : '')
        . ($адреса ? "* ссылки: " . implode('; ', $адреса) . "\n" : "* ссылок в этом разделе нет\n")
        . "\nФАКТУРА (числа только отсюда):\n{$фактура}"
        . $цели
        . $меткиПравило . "\n"
        . V5_ZHANR . "\n\n"
        . $уник
        . "\nОБРАЗЕЦ РАЗМЕТКИ:\n{$образец}\n\n"
        . "Верни только HTML тела раздела, без заголовка H2, без пояснений.";
}

