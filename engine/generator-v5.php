            // того как 245 записей vhod про «заходи/заходит» перестали считаться
            // событием и пошли в абзацы, вопросы вытеснялись — vhod валил faq в 6 из 8.
            // Пока страница отстаёт от своей доли цели, зачин без вопроса хуже.
            $долгВопросов = ($цельЗнаков[$тип] ?? 0) > 0
                && $вопросовСтраницы + 1 < 0.6 * $цельЗнаков[$тип] * $номерРаздела / max(1, count($выбор));
            $хужеВопрос = $вопросПодряд >= 1
                ? fn(array $x): int => v5VoprosВЗачине((string) ($x['т'] ?? '')) ? 1 : 0
                : ($долгВопросов ? fn(array $x): int => v5VoprosВЗачине((string) ($x['т'] ?? '')) ? 0 : 1 : null);
            $фразВАбзаце = $фразИзРаспределения($r['зачинДлины'] ?? [], 3, $сдвигФраз);
            $геройВРазделе = (bool) preg_match('~\{ИМЯ~u', $h2) || ($именаСтраницы['геройРаздела'] ?? 0) > 0
                // Раздел без героя в H2 всё равно открывается историей, если у него
                // есть свои фразы про вход героя — так у доноров устроена половина разделов.
                // На slots герой в каждом разделе, где есть чем открыть: в 341 монета легла
                // в «нет» во всех шести разделах, и статья осталась без историй.
                // И на bonus: у A история в каждом из пяти разделов, у нас была в одном из шести.
                || ($i === 0 && count(array_filter($r['зачинФразы'] ?? [], fn($x) => v5Rol((string) ($x['т'] ?? '')) === 'ист.вход')) >= (in_array($тип, ['slots', 'bonus'], true) ? 1 : 6)
                    && (in_array($тип, ['slots', 'bonus'], true) || $rng->pick([true, false])));
            $текст = $абзац($r['зачинФразы'] ?? [], $фразВАбзаце,
                "$тип|$h2|зачин", function (string $ч) use ($у) { $у('@ЗАПИСЬ:' . $ч); return v5Zapolnit($ч, $у); },
                $хужеВопрос, $поТемеФразы, v5PlanAbzatsa($i, $геройВРазделе, $фразВАбзаце));
            // Сумма героя вторым аргументом — в математический абзац раздела, как у A:
            // «на коротком отрезке автомат может отдать 410к или забрать всё». Один довод
            // на раздел, только после истории и только в абзац про отдачу.
            if ($текст !== '' && $i > 0 && !$доводБыл && $суммаРаздела !== null
                && preg_match('~RTP|дистанц|математик|отдач~ui', strip_tags($текст))) {
                $довод = $взять($пулы['общие']['доводГероя'] ?? [], 1, "$тип|довод");
                if ($довод) {
                    // Метка героя, как в его абзаце: «{СУММА} за один вечер…» с префиксом записи
                    // не ловилась регулярным выражением и брала чужие 15к при 38к героя.
                    $ч = '<!--герой-->' . (string) $довод[0]['т']; $у('@ЗАПИСЬ:' . $ч);
                    $текст = rtrim($текст) . ' ' . str_replace('<!--герой-->', '', v5Zapolnit($ч, $у)); $доводБыл = true;
                }
            }
            if ($текст !== '') {
                $куски[] = v5Uzel('p', $текст);
                $вопросПодряд = v5VoprosВЗачине($текст) ? $вопросПодряд + 1 : 0;
                $вопросовСтраницы += substr_count(strip_tags($текст), '?');
            }
        }
        // Хотим ли следующий h3 по теме: сравниваем текущую долю с целью,
        // считая заголовок ещё не поставленным. Виджеты добавят свои шапки
        // позже и в обе стороны, поэтому целимся чуть ниже — рычаг мягкий,
        // предпочтение уступает и запрету, и очереди по журналу.
        $хочуПоТеме = null;
        if (isset($цельПоТеме[$тип]) && $загВсего > 0) {
            $доля = $загПоТеме / $загВсего * 100;
            $хочуПоТеме = $доля < $цельПоТеме[$тип];
        }
        $хочуВопрос = null;
        if (isset($цельВопросов[$тип]) && $h3Всего > 0) {
            $хочуВопрос = $h3Вопросов / $h3Всего * 100 < $цельВопросов[$тип];
        }
        // Два пожелания складываются: запись, отвечающая обоим, идёт первой,
        // одному — второй, ни одному — последней. Ключ по-прежнему уступает
        // запрету профиля и очереди по журналу.
        $предпочесть = ($хочуПоТеме === null && $хочуВопрос === null) ? null
            : function (array $x) use ($тип, $поТеме, $вопросительный, $хочуПоТеме, $хочуВопрос): int {
                $т = (string) ($x['т'] ?? '');
                $ц = 0;
                if ($хочуПоТеме !== null && $поТеме($тип, $т) !== $хочуПоТеме) { $ц++; }
                if ($хочуВопрос !== null && $вопросительный($т) !== $хочуВопрос) { $ц++; }
                return $ц;
            };
        foreach ($взять($r['h3'], 1, "$тип|$h2|h3", 0.34, $предпочесть) as $x) {
            $узелH3 = $узел(); $узелH3('@ЗАПИСЬ:' . $x['т']);
            $куски[] = v5Uzel('h3', v5Zapolnit($x['т'], $узелH3));
            $загВсего++; if ($поТеме($тип, $x['т'])) { $загПоТеме++; }
            $h3Всего++; if ($вопросительный($x['т'])) { $h3Вопросов++; }
        }
        // Длина списка — из донорского распределения (среднее 6.4, медиана 6,
        // у конкурента A 6.5), а не из размера пула на донора: тот считал
        // все переписывания раздела и упирался в потолок девять почти всегда
        // (у нас 8.9 пункта в списке против 6.4). «Сухой» набор — на пункт короче.
        $пунктов = max(3, min(9, $rng->triInt([4, 6, 9]) + ($темп < 0 ? -1 : 0)));
        // Раздел-инструкция в нумерованном наборе: тянем в список шаговые
        // пункты. Без этого нумеровать нечего — под заголовком «Как установить
        // — Пошагово» лежал перечень «Минус: весит 95 МБ», и <ol> на нём читался
        // бы как порядок действий там, где порядка нет. Предпочтение мягкое: оно
        // уступает и запрету профиля, и очереди по журналу, как все прочие.
        $хужеПункт = ($нумероватьНабор && v5ShagovyiRazdel($тип, $h2))
            ? fn(array $x): int => v5ShagovyiPunkt((string) ($x['т'] ?? '')) ? 0 : 1
            : null;
        // Пункт про героя тоже держит сумму раздела: «рыбак ×10 у Виктора —
        // 150к» под абзацем с «снял с рыбалки 250к» — тот же спор, что был между H2 и телом.
        $пункты = array_map(function ($x) use ($узел) { $уп = $узел(); $уп('@ЗАПИСЬ:' . $x['т']); return v5Zapolnit($x['т'], $уп); },
            $взять($r['пункты'], $пунктов, "$тип|$h2|пункты", 0.34, $хужеПункт));
        if ($пункты) { $куски[] = v5Spisok($пункты); }
        $уф = $узел();
        // Финальный абзац стоит между зачинными и в цепочку вопросов входит
        // наравне с ними: без него тройка складывалась как зачин-финал-зачин.
        $хужеФ = $вопросПодряд >= 2
            ? fn(array $x): int => v5VoprosВЗачине((string) ($x['т'] ?? '')) ? 1 : 0
            : null;
        $фразВФинале = $фразИзРаспределения($r['финалДлины'] ?? [], 3, $сдвигФраз);
        $текст = $абзац($r['финалФразы'] ?? [], $фразВФинале,
            "$тип|$h2|финал", function (string $ч) use ($уф) { $уф('@ЗАПИСЬ:' . $ч); return v5Zapolnit($ч, $уф); },
            $хужеФ, $поТемеФразы, v5PlanAbzatsa('финал', ($именаСтраницы['геройРаздела'] ?? 0) > 0, $фразВФинале));
        if ($текст !== '') {
            $куски[] = v5Uzel('p', $текст);
            $вопросПодряд = v5VoprosВЗачине($текст) ? $вопросПодряд + 1 : 0;
            $вопросовСтраницы += substr_count(strip_tags($текст), '?');
        }
    }
    foreach ($хвостКлассы as $k) { if (($h = $виджет($k)) !== null) { $куски[] = $h; } }

    return ['html' => implode("\n", $куски) . "\n", 'скелет' => $подпись, 'разделов' => count($выбор)];
};

