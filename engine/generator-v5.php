        // как сложилась сумма (серия, бонус-раунд, фриспины, множитель, каскад),
        // после входа встаёт одна фраза-механизм из общего пула. У A объяснение
        // есть почти всегда, у нас было в половине абзацев.
        // Смотрим только на фразы самой истории: «коды на фриспины ловятся в промокодах»
        // из оффера механизмом не считается. И объяснять есть что, только если исход назван.
        // Событие без лица и без глагола прошедшего времени («свежие движки с каскадными
        // падениями, множителями до ×500») — описание продукта, не история.
        $историйные = array_filter($части, function ($y) {
