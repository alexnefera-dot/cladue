// ── выдача из пулов ─────────────────────────────────────────────────
$баланс = [];   // донор => сколько СЛОВ от него уже взято на этой странице
$запрет = [];   // доноры, исключённые перетасовкой
/**
 * Очередь на выдачу: сначала невыданное, внутри — от наименее использованных
 * на этой странице доноров. Считаются слова, а не куски: у mellstroy страница
 * вдвое длиннее соседних, и при счёте кусками его доля в тексте выходила 16 %
 * против 3–4 % у остальных. Плюс отбраковка почти-дублей: фабрика писала пул
 * по одному шаблону, и три переписывания одной мысли рядом читаются заеданием.
 */
$взять = function (array $список, int $k, string $метка, float $порогБлизости = 0.34)
        use (&$журнал, &$rng, &$баланс, &$запрет, $строгий, $имяНабора): array {
    if (!$список || $k < 1) { return []; }
    $кандидаты = [];
    foreach ($список as $x) {
        $донор = $x['д'] ?? '';
        if ($донор !== '' && in_array($донор, $запрет, true)) { continue; }
        $ключ = $метка . '|' . md5($x['т'] ?? ($x['в'] . $x['о']));
        $кандидаты[] = ['ключ' => $ключ, 'x' => $x, 'донор' => $донор,
                        'бывший' => isset($журнал[$ключ]) ? 1 : 0];
    }
    if (!$кандидаты) { return []; }
    $rng->shuffle($кандидаты);
    usort($кандидаты, fn($a, $b) => [$a['бывший'], $баланс[$a['донор']] ?? 0]
                              <=> [$b['бывший'], $баланс[$b['донор']] ?? 0]);
    // Строгий журнал: выданное другому набору не берётся вовсе. Включается
    // только при запасе вдвое больше нужного — иначе выбор сужается до одного
    // варианта и вместе с уникальностью проседает профиль (замер: 28 страниц
    // из 36 против 32 при жёстком отсечении без запаса).
    $строгоТут = $строгий !== []
        && ($строгий === ['*'] || in_array(explode('|', $метка)[0], $строгий, true));
    if ($строгоТут) {
        $свежие = array_values(array_filter($кандидаты, fn($c) => $c['бывший'] === 0));
        if (count($свежие) >= $k * 2) { $кандидаты = $свежие; }
    }

    // Потолок на донора внутри страницы: без него отбраковка почти-дублей
    // сама сводит выбор к одному донору — тому, чьё переписывание меньше похоже
    // на соседние. На замере это давало 20 % текста страницы из одного набора.
    $доноров = count(array_unique(array_filter(array_column($кандидаты, 'донор'))));
    $взято = array_sum($баланс);
    $потолокДонора = max(60, (int) ceil(($взято + $k * 20) / max(1, $доноров) * 1.4));

    $итог = [];
    foreach ([false, true] as $безРазбора) {
        foreach ($кандидаты as $c) {
            if (count($итог) >= $k) { break 2; }
            $т = $c['x']['т'] ?? ($c['x']['в'] . ' ' . $c['x']['о']);
            if (in_array($c['x'], $итог, true)) { continue; }
            if (!$безРазбора) {
                if ($c['донор'] !== '' && ($баланс[$c['донор']] ?? 0) >= $потолокДонора) { continue; }
                $похож = false;
                foreach ($итог as $y) {
                    $ty = $y['т'] ?? ($y['в'] . ' ' . $y['о']);
                    if (v5Blizost($т, $ty) > $порогБлизости) { $похож = true; break; }
                }
                if ($похож) { continue; }
            }
            $журнал[$c['ключ']] = $имяНабора;
            if ($c['донор'] !== '') {
                $слов = count(preg_split('~\s+~u', v5Text($т), -1, PREG_SPLIT_NO_EMPTY));
                $баланс[$c['донор']] = ($баланс[$c['донор']] ?? 0) + $слов;
            }
            $итог[] = $c['x'];
        }
    }
    return $итог;
};

/** Абзац из предложений: первое — из открывающих, остальные — из середины. */
$абзац = function (array $фразы, int $k, string $метка) use ($взять): string {
    if (!$фразы || $k < 1) { return ''; }
    $первые = array_values(array_filter($фразы, fn($x) => ($x['п'] ?? 0) === 1));
    $прочие = array_values(array_filter($фразы, fn($x) => ($x['п'] ?? 0) === 0));
    $части = array_merge(
        $взять($первые ?: $фразы, 1, $метка . '|перв'),
        $взять($прочие ?: $фразы, $k - 1, $метка . '|сред'));
    return trim(implode(' ', array_column($части, 'т')));
};

$медиана = function (array $v, int $поумолчанию): int {
    $v = array_values(array_filter($v, fn($x) => $x > 0));
    if (!$v) { return $поумолчанию; }
    sort($v);
    return (int) $v[intdiv(count($v), 2)];
};

$контекст = function (array $локальные) use ($паспорт, $изБанка): callable {
    return function (string $ключ) use ($паспорт, $локальные, $изБанка) {
        if (isset($паспорт['каталог'][$ключ])) { return $паспорт['каталог'][$ключ]; }
        if ($ключ === 'ВЕЙДЖЕР') { return $паспорт['вейджер']; }
        if (isset($локальные[$ключ])) { return $локальные[$ключ]; }
        return $изБанка($ключ);
    };
};

/** Пары «вопрос-ответ» внутри виджета меняются парой, разметка остаётся. */
$перебратьВиджет = function (string $html, string $тип) use (&$пулы, $взять): string {
    $замена = function (string $html, string $reВопрос, string $reОтвет, array $пары): string {
        $i = 0;
        $html = preg_replace_callback($reВопрос,
            function ($m) use (&$i, $пары) { $p = $пары[$i++] ?? null; return $p ? $m[1] . $p['в'] . $m[3] : $m[0]; },
            $html);
        $i = 0;
        return preg_replace_callback($reОтвет,
            function ($m) use (&$i, $пары) {
                $p = $пары[$i++] ?? null;
                if (!$p) { return $m[0]; }
                // Обёртка берётся у виджета: был <p> — ставим <p>, не было — нет.
                $о = str_starts_with(ltrim($m[2]), '<p>')
                    ? '<p>' . "\n            " . $p['о'] . "\n          " . '</p>'
                    : $p['о'];
                return $m[1] . $о . $m[3];
            },
            $html);
    };
    $faq = $пулы['хвосты'][$тип]['faq'] ?? [];
    if ($faq) {
        $нужно = preg_match_all('~<h3 class="faq-question" itemprop="name">~', $html);
        $html = $замена($html,
            '~(<h3 class="faq-question" itemprop="name">\s*)(.*?)(\s*</h3>)~s',
            '~(<div itemprop="text">\s*)(.*?)(\s*</div>)~s',
            $взять($faq, $нужно, "$тип|faq"));
    }
    $рас = $пулы['хвосты'][$тип]['раскрывашки'] ?? [];
    if ($рас) {
        $нужно = preg_match_all('~<p class="review-quote-text">~', $html);
        $html = $замена($html,
            '~(<button class="faq-question"[^>]*>\s*<span>\s*)(.*?)(\s*</span>)~s',
            '~(<p class="review-quote-text">\s*)(.*?)(\s*</p>)~s',
            $взять($рас, $нужно, "$тип|раскрывашки"));
    }
    return $html;
};

// ── сборка одной страницы ───────────────────────────────────────────
$собрать = function (string $тип) use (&$блоки, &$пулы, &$rng, $взять, $абзац, $медиана,
        $контекст, $перебратьВиджет, $герои, $героини, $изБанка, $банки): array {
    $варианты = [];
    foreach ($блоки['скелеты'][$тип] ?? [] as $подпись => $n) {
        [$голова, , $хвост] = array_map('trim', explode('|', $подпись));
        $классы = array_filter(array_map('trim', array_merge(
            $голова === '' ? [] : explode(' + ', $голова),
            $хвост === '' ? [] : explode(' + ', $хвост))));
        $известны = true;
        foreach ($классы as $k) { if (!isset($блоки['блоки'][$тип][$k])) { $известны = false; break; } }
        if ($известны) { $варианты[$подпись] = $n; }
    }
    if (!$варианты) { fwrite(STDERR, "нет скелета для $тип\n"); exit(1); }
    $подпись = $rng->weighted($варианты);
    [$головаС, $серёдкаС, $хвостС] = array_map('trim', explode('|', $подпись));
    $головаКлассы = $головаС === '' ? [] : array_map('trim', explode(' + ', $головаС));
    $хвостКлассы  = $хвостС === '' ? [] : array_map('trim', explode(' + ', $хвостС));
    $сколькоH2 = (int) (preg_match('~H2×(\d+)~u', $серёдкаС, $m) ? $m[1] : 5);

    // разделы: обязательные (есть почти у всех доноров) плюс добор по весу
    $пул = $пулы['разделы'][$тип] ?? [];
    $доноров = max(1, $блоки['источник']['наборов'] ?? 12);
    $обяз = []; $прочие = [];
    foreach ($пул as $h2 => $r) {
        if ($r['встреч'] >= $доноров * 0.9) { $обяз[$h2] = $r['встреч']; } else { $прочие[$h2] = $r['встреч']; }
    }
    $выбор = array_slice(array_keys($обяз), 0, $сколькоH2);
    while (count($выбор) < $сколькоH2 && $прочие) {
        $h2 = $rng->weighted($прочие);
        unset($прочие[$h2]);
        $выбор[] = $h2;
    }
    usort($выбор, function ($a, $b) use ($пул) {
        $м = function ($h) use ($пул) { $p = $пул[$h]['позиции'] ?? [0]; sort($p); return $p[intdiv(count($p), 2)]; };
        return $м($a) <=> $м($b);
    });

    $ростер = $пулы['общие']['слоты'] ?? [];
    // Скелет донора называет один и тот же класс дважды — в голове и в хвосте.
    // Два независимых выбора из одного набора вариантов регулярно совпадают, и
    // страница показывает один виджет два раза подряд. Внутри страницы уже
    // выданный вариант из выбора исключается.
    $выданныеВарианты = [];
    $виджет = function (string $k) use (&$блоки, $тип, &$rng, $перебратьВиджет, $контекст, $герои, $героини, $ростер, &$выданныеВарианты) {
        $вар = $блоки['блоки'][$тип][$k] ?? [];
        if (!$вар) { return null; }
        $плоско = [];
        foreach ($вар as $класс => $список) {
            foreach ($список as $i => $x) { $плоско["$класс|$i"] = (string) $x; }
        }
        $свободные = array_diff_key($плоско, $выданныеВарианты);
        if (!$свободные) { $свободные = $плоско; }
        $ключ = (string) $rng->pick(array_keys($свободные));
        $выданныеВарианты[$ключ] = 1;
        $html = $перебратьВиджет($свободные[$ключ], $тип);
        $html = v5Zapolnit(v5Trafaret($html),
            $контекст(['ИМЯ' => $rng->pick($герои), 'ИМЯЖ' => $rng->pick($героини)]));
        // Отдача слота — не прорезь: у всех двенадцати доноров Sweet Bonanza
        // идёт с 96.51 %, и катать это число значит расходиться с корпусом на
        // ровном месте. После заполнения ростер возвращается на место.
        if ($ростер) {
            $html = preg_replace_callback(
                '~(<h3 class="slot-name" itemprop="name">\s*)(.*?)(\s*</h3>.*?<span class="slot-rtp-value"[^>]*>\s*)([\d.,]+)(?=%)~s',
                function ($m) use ($ростер) {
                    $имя = trim($m[2]);
                    return isset($ростер[$имя]) ? $m[1] . $m[2] . $m[3] . $ростер[$имя]['rtp'] : $m[0];
                }, $html);
        }
        return $html;
    };

    $куски = [];
    foreach ($головаКлассы as $k) { if (($h = $виджет($k)) !== null) { $куски[] = $h; } }
    foreach ($выбор as $h2) {
        $r = $пул[$h2];
        $встреч = max(1, $r['встреч']);
        // Герой держится на раздел — это одна история. Числа катятся на узел:
        // «джекпот до 47к» в шести пунктах подряд не пишет ни один донор.
        $герой = $rng->pick($герои);
        $героиня = $rng->pick($героини);
        // Ставка и результат в одной фразе («зашёл с X, довёл до Y») берут одну
        // и ту же прорезь. Внутри узла рубли выдаются по возрастанию: первое
        // вхождение — из младшей половины банка, следующие крупнее. Иначе герой
        // заходит с двенадцатью тысячами и уходит с ними же.
        $рубли = array_keys($банки['РУБЛИ'] ?? []);
        usort($рубли, fn($a, $b) => v5Rubli($a) <=> v5Rubli($b));
        // Ставка героя — это сотни и тысячи, а не сорок шесть тысяч: банк рублей
        // наполовину состоит из выплат, и «младшая половина» для ставки слишком
        // крупная. Порог в десять тысяч оставляет ровно ставочный слой.
        $млад = array_values(array_filter($рубли, fn($x) => v5Rubli($x) <= 10000 && v5Rubli($x) >= 100));
        $старш = array_slice($рубли, intdiv(count($рубли), 2)) ?: $рубли;
        $узел = function () use ($контекст, $герой, $героиня, $изБанка, $rng, $млад, $рубли, $старш) {
            $ставка = $млад ? (string) $rng->pick($млад) : $изБанка('РУБЛИ');
            $крупнее = array_values(array_filter($рубли, fn($x) => v5Rubli($x) > v5Rubli($ставка)));
            // Если крупнее не нашлось, берём из старшей половины, но не ту же
            // строку: «зашёл с X и довёл до X» — единственный по-настоящему
            // заметный глазом сбой подстановки.
            if (!$крупнее) { $крупнее = array_values(array_filter($старш, fn($x) => $x !== $ставка)); }
            $счёт = 0; $выданные = [];
            return function (string $ключ) use ($контекст, $герой, $героиня, $изБанка, $rng, $ставка, $крупнее, &$счёт, &$выданные) {
                if ($ключ === 'РУБЛИ') {
                    if ($счёт++ === 0) { $выданные[] = $ставка; return $ставка; }
                    // Два независимых выбора из одного банка иногда совпадают, и
                    // тогда герой «доводит сумму» до той же цифры. Внутри узла
                    // одно значение дважды не выдаётся.
                    $свободные = array_values(array_diff($крупнее ?: [$ставка], $выданные));
                    $v = (string) ($свободные ? $rng->pick($свободные) : $ставка);
                    $выданные[] = $v;
                    return $v;
                }
                return $контекст(['ИМЯ' => $герой, 'ИМЯЖ' => $героиня,
                    'СУММА' => $изБанка('СУММА'), 'RTP' => $изБанка('RTP')])($ключ);
            };
        };

        $куски[] = v5Uzel('h2', v5Zapolnit($h2, $узел()));
        $зачинов = max(1, (int) round(count($r['зачин']) / $встреч));
        $фразВЗачине = $медиана($r['зачинДлины'] ?? [], 3);
        for ($i = 0; $i < $зачинов; $i++) {
            $текст = $абзац($r['зачинФразы'] ?? [], max(2, $фразВЗачине + $rng->int(-1, 1)), "$тип|$h2|зачин");
            if ($текст !== '') { $куски[] = v5Uzel('p', v5Zapolnit($текст, $узел())); }
        }
        foreach ($взять($r['h3'], 1, "$тип|$h2|h3") as $x) {
            $куски[] = v5Uzel('h3', v5Zapolnit($x['т'], $узел()));
        }
        $пунктов = max(3, min(9, (int) round(count($r['пункты']) / $встреч) + $rng->int(-1, 1)));
        $пункты = array_map(fn($x) => v5Zapolnit($x['т'], $узел()), $взять($r['пункты'], $пунктов, "$тип|$h2|пункты"));
        if ($пункты) { $куски[] = v5Spisok($пункты); }
        $текст = $абзац($r['финалФразы'] ?? [], max(2, $медиана($r['финалДлины'] ?? [], 3)), "$тип|$h2|финал");
        if ($текст !== '') { $куски[] = v5Uzel('p', v5Zapolnit($текст, $узел())); }
    }
    foreach ($хвостКлассы as $k) { if (($h = $виджет($k)) !== null) { $куски[] = $h; } }

    return ['html' => implode("\n", $куски) . "\n", 'скелет' => $подпись, 'разделов' => count($выбор)];
};

// ── шинглы доноров: нужны перетасовке ───────────────────────────────
$донорские = [];
foreach (glob("$корпус/*", GLOB_ONLYDIR) ?: [] as $d) {
