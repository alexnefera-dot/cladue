            $ставка = $млад ? (string) $rng->pick($млад) : $изБанка('РУБЛИ');
            $крупнее = array_values(array_filter($рубли, fn($x) => v5Rubli($x) > v5Rubli($ставка)));
            // Если крупнее не нашлось, берём из старшей половины, но не ту же
            // строку: «зашёл с X и довёл до X» — единственный по-настоящему
            // заметный глазом сбой подстановки.
            if (!$крупнее) { $крупнее = array_values(array_filter($старш, fn($x) => $x !== $ставка)); }
            $счёт = 0; $выданные = []; $местные = [];
            // Флаги «это первая сумма/ставка текущей записи». Сбрасываются
            // служебным ключом {@ЗАПИСЬ} на границе фраз абзаца.
            $перваяСумма = true; $перваяРубли = true;
            $суммаВЭтой = false; $суммаВПрошлой = false;
            return function (string $ключ) use ($контекст, $герой, $героиня, $изБанка, $rng, $ставка, $крупнее, &$счёт, &$выданные, &$местные, $банки, &$названныеRTP, &$названныеСуммы, &$суммаРаздела, &$перваяСумма, &$перваяРубли, &$суммаВЭтой, &$суммаВПрошлой) {
                if ($ключ === '@ЗАПИСЬ') {
                    // Соседство важнее самого факта повтора: спорят подряд
                    // идущие фразы с суммами, а разнесённые по абзацу читаются
                    // как разные эпизоды. Замер: сплошной повтор уполовинил
                    // дефект (1.01 → 0.49 %), но поднял промахи fact_values
                    // с 29 до 39 — различных фактов на странице стало меньше.
                    $суммаВПрошлой = $суммаВЭтой; $суммаВЭтой = false;
                    $перваяСумма = true; $перваяРубли = true; return '';
                }
                // Прорезь, перед которой стоит «ставка/поставил/закинул/депозит»:
                // всегда ставочный слой банка (100–10 000). Раньше слой давался
                // только ПЕРВОМУ {РУБЛИ} узла, а узел — это целый виджет: во
                // втором ответе FAQ ставка шла из «крупнее» и выходило «ставка
                // 15 997 025 ₽». У доноров и трёх корпусов конкурентов ставок
                // от миллиона нет ни одной на 607 упоминаний; p99 — 15 000.
                if ($ключ === 'РУБЛИ_СТАВКА') {
                    $свои = array_values(array_diff($млад ?: [$ставка], $выданные)) ?: ($млад ?: [$ставка]);
                    $v = (string) $rng->pick($свои); $выданные[] = $v; $счёт++;
                    return $v;
                }
                if ($ключ === 'РУБЛИ') {
                    if ($счёт++ === 0) { $выданные[] = $ставка; return $ставка; }
                    // Ставку к фразе НЕ привязываем. Пробовали: первое {РУБЛИ}
                    // новой записи возвращало ставку и там, где фраза называет
                    // ею исход, — выходило «зашёл с X, вывел X». Смысловая
                    // приёмка ловит это как «ставка равна результату»: находок
                    // стало 11 против 8 на пятнадцати сидах. Рост по записи
                    // остаётся только у суммы, у которой роль однозначна.
                    // Два независимых выбора из одного банка иногда совпадают, и
                    // тогда герой «доводит сумму» до той же цифры. Внутри узла
                    // одно значение дважды не выдаётся.
                    $свободные = array_values(array_diff($крупнее ?: [$ставка], $выданные));
                    $v = (string) ($свободные ? $rng->pick($свободные) : $ставка);
                    $выданные[] = $v;
                    return $v;
                }
                // Сумма — это событие: «зашёл с X, вышел с Y», и два вхождения
                // в одной фразе обязаны различаться. Всё остальное — свойство
                // площадки: RTP, процент бонуса, срок вывода внутри абзаца
                // одно на всех, иначе абзац спорит сам с собой.
                // Сумма, которую сама фраза называет небольшой: «поймал
                // небольшой куш на X», «Старт был скромный: X». Банк СУММА
                // тянется до 120 млн, и «сумма была небольшой, около 120.0 млн»
                // — то же противоречие, что джекпот из банка мелких выигрышей.
                // Значение уходит в общую последовательность узла, чтобы
                // следующая СУММА была крупнее: «скромные X превратились в Y».
                if ($ключ === 'СУММАМАЛ') {
                    $ранее = $местные['СУММА'] ?? [];
                    $банк = array_values(array_diff(array_keys($банки['СУММАМАЛ'] ?? []), $ранее));
                    $v = $банк ? (string) $rng->pick($банк) : $изБанка('СУММАМАЛ');
                    $местные['СУММА'] = array_merge($ранее, [$v]);
                    return $v;
                }
                if ($ключ === 'СУММА') {
                    $ранее = $местные['СУММА'] ?? [];
                    // Рост суммы задуман для одной фразы: «внёс X, получил Y».
                    // Но узел — это целый абзац, собранный из независимых
                    // записей, и у каждой свой законченный исход. Правило
                    // превращало их в спор: «сорвал 87к рублей … вывел 9.3 млн»
                    // в одном абзаце. Первое вхождение НОВОЙ записи берёт уже
                    // названную сумму; растёт только второе вхождение внутри
                    // той же фразы.
                    if ($перваяСумма && $ранее && $суммаВПрошлой) {
                        $перваяСумма = false; $суммаВЭтой = true; return (string) end($ранее);
                    }
                    $перваяСумма = false; $суммаВЭтой = true;
                    if (!$ранее && $суммаРаздела !== null) {
                        $местные['СУММА'] = [$суммаРаздела];
                        return $суммаРаздела;
                    }
                    $банк = array_values(array_diff(array_keys($банки['СУММА'] ?? []), $ранее));
                    // Сумма, уже названная на странице, второй раз не берётся,
                    // пока есть из чего выбрать: у доноров 11 разных сумм из 15
                    // на страницу, у нас было 8 из 14.
                    $свежие = array_values(array_diff($банк, $названныеСуммы));
                    if ($свежие) { $банк = $свежие; }
                    // «Внёс X, получил на счёт Y» и «сделал X → Y» — рост, а не
                    // случайная пара: второе вхождение крупнее первого. Рост —
                    // из ближайших восьми значений сверху: «с 500к до 120 млн»
                    // читается сказкой, «с 5к до 87к» — историей.
                    if ($ранее) {
                        $больше = array_values(array_filter($банк,
                            fn($x) => v5Rubli((string) $x) > v5Rubli((string) end($ранее))));
                        if ($больше) {
                            usort($больше, fn($a, $b) => v5Rubli((string) $a) <=> v5Rubli((string) $b));
                            $банк = array_slice($больше, 0, 8);
                        }
                    }
                    $v = $банк ? (string) $rng->pick($банк) : $изБанка('СУММА');
                    $местные['СУММА'] = array_merge($ранее, [$v]);
                    $названныеСуммы[] = $v;
                    if ($суммаРаздела === null && !$ранее) { $суммаРаздела = $v; }
                    return $v;
                }
                // Отдача в копейках считается от RTP того же узла: «RTP 96.4 %
                // означает 95 копеек с рубля» — спор, которого никто не ловит.
                if ($ключ === 'RTPКОП') {
                    if (!array_key_exists('RTP', $местные)) {
                        $местные['RTP'] = $контекст(['ИМЯ' => $герой, 'ИМЯЖ' => $героиня])('RTP');
                    }
                    return (string) (int) floor((float) str_replace(',', '.', (string) $местные['RTP']));
                }
                // ПРОЦ и ДОЛЯ — одно и то же: процент бонуса. Под двумя именами
                // они разъезжались в соседних фразах одного абзаца. А вот доля
                // отыгрыша, ревшара и банковский вклад — проценты другого
                // порядка: «слоты засчитывают 300 %» и «вклад под 177 % годовых»
                // выходили именно из-за общего банка.
                $к = $ключ === 'ДОЛЯ' ? 'ПРОЦ' : $ключ;
                // Второй конец диапазона «от X до Y»: больше первого и не равен.
                if ($ключ === 'ДОЛЯМАЛ2') {
                    $первый = (int) ($местные['ДОЛЯМАЛ'] ?? 0);
                    $выше = array_values(array_filter(array_keys($банки['ДОЛЯМАЛ'] ?? []),
                        fn($x) => (int) $x > $первый));
                    if (!array_key_exists('ДОЛЯМАЛ2', $местные)) {
                        $местные['ДОЛЯМАЛ2'] = $выше ? (string) $rng->pick($выше) : $изБанка('ДОЛЯМАЛ');
                    }
                    return $местные['ДОЛЯМАЛ2'];
                }
                // Второй RTP живёт только в диапазонах «от X до Y» и обязан быть
                // больше первого, иначе диапазон читается наоборот. Ветка стоит
                // ДО общей: та заполняла RTP2 из банка карточек слотов
                // (96.51) без сравнения, и выходило «97.0–96.51%».
                if ($ключ === 'RTP2') {
                    // Ключи банка PHP приводит к int, где может: приводим обратно.
                    if (!array_key_exists('RTP', $местные)) {
                        $местные['RTP'] = $контекст(['ИМЯ' => $герой, 'ИМЯЖ' => $героиня])('RTP');
                        $названныеRTP[] = $местные['RTP'];
                    }
                    $первый = (float) str_replace(',', '.', (string) $местные['RTP']);
                    $выше = array_values(array_filter(array_keys($банки['RTP'] ?? []),
                        fn($x) => (float) str_replace(',', '.', (string) $x) > $первый));
                    if (!array_key_exists('RTP2', $местные)) {
                        $свежие = array_values(array_diff($выше, $названныеRTP)) ?: $выше;
                        $местные['RTP2'] = $свежие ? (string) $rng->pick($свежие) : (string) $местные['RTP'];
                        $названныеRTP[] = $местные['RTP2'];
                    }
                    return $местные['RTP2'];
                }
                if (!array_key_exists($к, $местные)) {
                    if ($к === 'RTP') {
                        // Пока разных значений на странице меньше пяти, берём новое:
                        // профиль держит около пяти дробных процентов. Дальше не
                        // гонимся — иначе на страницах с десятком абзацев про RTP
                        // разброс улетает выше полосы.
                        $свежие = count(array_unique($названныеRTP)) >= 5 ? []
                            : array_values(array_diff(array_keys($банки['RTP'] ?? []), $названныеRTP));
                        $местные['RTP'] = $свежие
                            ? (string) $rng->pick($свежие)
                            : $контекст(['ИМЯ' => $герой, 'ИМЯЖ' => $героиня])('RTP');
                        $названныеRTP[] = $местные['RTP'];
                    } else {
                        $местные[$к] = $контекст(['ИМЯ' => $герой, 'ИМЯЖ' => $героиня])($к);
                    }
                }
                return $местные[$к];
            };
        };

        $куски[] = v5Uzel('h2', v5Zapolnit($h2, $узел()));
        $загВсего++; if ($поТеме($тип, $h2)) { $загПоТеме++; }
        // Тема раздела для отбора фраз: содержательные слова заголовка
        // (первые пять букв — как грубая основа) плюс слова темы типа.
        // «Провайдеры — Кто создаёт эти слоты» → провай, созда, слоты.
        $словаТемы = [];
        foreach (preg_split('~[^а-яёa-z]+~ui', mb_strtolower(strip_tags($h2))) as $w) {
            if (mb_strlen($w) >= 5 && !in_array($w, ['честн', 'честно', 'реальн', 'реальные', 'почему', 'который', 'только', 'сегодня', 'проверенн'], true)) { $словаТемы[] = mb_substr($w, 0, 5); }
        }
        // Фраза с числовым фактом — по теме всегда: на promo слова темы
        // («фриспин», «турнир», «промокод») отсеивали фразы про отдачу, и
        // дробных процентов на странице стало 1.2 при донорских 5–6, а
        // fact_values валился (promo 5.4 → 2.8, partnery 3.8 → 1.2).
        $поТемеФразы = $словаТемы
            ? function (string $т) use ($словаТемы): bool {
                if (preg_match('~\{RTP2?\}|\{ПРОЦ\}|\{ДОЛЯ\w*\}|\d[.,]\d\s*%~u', $т)) { return true; }
                $н = mb_strtolower(strip_tags($т));
                foreach ($словаТемы as $w) { if (mb_strpos($н, $w) !== false) { return true; } }
                return false;
            } : null;
        $зачинов = max(1, (int) round(count($r['зачин']) / $встреч) + $сдвигЗачинов);
        for ($i = 0; $i < $зачинов; $i++) {
            $у = $узел();
            $хужеВопрос = $вопросПодряд >= 2
                ? fn(array $x): int => v5VoprosВЗачине((string) ($x['т'] ?? '')) ? 1 : 0
                : null;
            $текст = $абзац($r['зачинФразы'] ?? [], $фразИзРаспределения($r['зачинДлины'] ?? [], 3, $сдвигФраз),
                "$тип|$h2|зачин", function (string $ч) use ($у) { $у('@ЗАПИСЬ'); return v5Zapolnit($ч, $у); },
                $хужеВопрос, $поТемеФразы);
            if ($текст !== '') {
                $куски[] = v5Uzel('p', $текст);
                $вопросПодряд = v5VoprosВЗачине($текст) ? $вопросПодряд + 1 : 0;
            }
        }
        // Хотим ли следующий h3 по теме: сравниваем текущую долю с целью,
        // считая заголовок ещё не поставленным. Виджеты добавят свои шапки
        // позже и в обе стороны, поэтому целимся чуть ниже — рычаг мягкий,
        // предпочтение уступает и запрету, и очереди по журналу.
        $хочуПоТеме = null;
        if (isset($цельПоТеме[$тип]) && $загВсего > 0) {
            $доля = $загПоТеме / $загВсего * 100;
            $хочуПоТеме = $доля < $цельПоТеме[$тип];
        }
        $хочуВопрос = null;
        if (isset($цельВопросов[$тип]) && $h3Всего > 0) {
            $хочуВопрос = $h3Вопросов / $h3Всего * 100 < $цельВопросов[$тип];
        }
        // Два пожелания складываются: запись, отвечающая обоим, идёт первой,
        // одному — второй, ни одному — последней. Ключ по-прежнему уступает
        // запрету профиля и очереди по журналу.
        $предпочесть = ($хочуПоТеме === null && $хочуВопрос === null) ? null
            : function (array $x) use ($тип, $поТеме, $вопросительный, $хочуПоТеме, $хочуВопрос): int {
                $т = (string) ($x['т'] ?? '');
                $ц = 0;
                if ($хочуПоТеме !== null && $поТеме($тип, $т) !== $хочуПоТеме) { $ц++; }
                if ($хочуВопрос !== null && $вопросительный($т) !== $хочуВопрос) { $ц++; }
                return $ц;
            };
        foreach ($взять($r['h3'], 1, "$тип|$h2|h3", 0.34, $предпочесть) as $x) {
            $куски[] = v5Uzel('h3', v5Zapolnit($x['т'], $узел()));
            $загВсего++; if ($поТеме($тип, $x['т'])) { $загПоТеме++; }
            $h3Всего++; if ($вопросительный($x['т'])) { $h3Вопросов++; }
        }
        $пунктов = max(3, min(9, (int) round(count($r['пункты']) / $встреч) + $rng->int(-1, 1)));
        // Раздел-инструкция в нумерованном наборе: тянем в список шаговые
        // пункты. Без этого нумеровать нечего — под заголовком «Как установить
        // — Пошагово» лежал перечень «Минус: весит 95 МБ», и <ol> на нём читался
        // бы как порядок действий там, где порядка нет. Предпочтение мягкое: оно
        // уступает и запрету профиля, и очереди по журналу, как все прочие.
        $хужеПункт = ($нумероватьНабор && v5ShagovyiRazdel($тип, $h2))
            ? fn(array $x): int => v5ShagovyiPunkt((string) ($x['т'] ?? '')) ? 0 : 1
            : null;
        $пункты = array_map(fn($x) => v5Zapolnit($x['т'], $узел()),
            $взять($r['пункты'], $пунктов, "$тип|$h2|пункты", 0.34, $хужеПункт));
        if ($пункты) { $куски[] = v5Spisok($пункты); }
        $уф = $узел();
        // Финальный абзац стоит между зачинными и в цепочку вопросов входит
        // наравне с ними: без него тройка складывалась как зачин-финал-зачин.
        $хужеФ = $вопросПодряд >= 2
            ? fn(array $x): int => v5VoprosВЗачине((string) ($x['т'] ?? '')) ? 1 : 0
            : null;
        $текст = $абзац($r['финалФразы'] ?? [], $фразИзРаспределения($r['финалДлины'] ?? [], 3, $сдвигФраз),
            "$тип|$h2|финал", function (string $ч) use ($уф) { $уф('@ЗАПИСЬ'); return v5Zapolnit($ч, $уф); },
            $хужеФ, $поТемеФразы);
        if ($текст !== '') {
            $куски[] = v5Uzel('p', $текст);
            $вопросПодряд = v5VoprosВЗачине($текст) ? $вопросПодряд + 1 : 0;
        }
    }
    foreach ($хвостКлассы as $k) { if (($h = $виджет($k)) !== null) { $куски[] = $h; } }

    return ['html' => implode("\n", $куски) . "\n", 'скелет' => $подпись, 'разделов' => count($выбор)];
};

