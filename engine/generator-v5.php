            'cta'         => (bool) preg_match(V5_CTA_RE, strip_tags($текст)),
            'speech'      => (bool) preg_match(V5_SPEECH_RE, $текст),
            'imperatives' => v5EstImperativ($текст),
        };
        if ($плохо) { return true; }
    }
    return false;
};
