    $потолок = (float) ($профиль['уникальность']['по_типам'][$тип]['потолок'] ?? 12.0);
    $порогСборки = $потолок + 100 / max(1, (int) ($профиль['источник']['в_расчёте'] ?? 11));
    $лучший = null; $лучшийЖурнал = $журнал;
    $запрет = [];
    // Попытка оценивается двумя числами сразу: сколько полей профиля сошлось и
    // насколько страница легла на одного донора. Гнаться только за вторым
    // бессмысленно — самый непохожий вариант обычно и самый кривой по объёму.
    // Восьми попыток хватало, пока все наборы целились в медиану корпуса. С
    // разыгранной целью страница ищет своё место в полосе, а не общий центр,
    // и восьми не хватает: пятнадцать сидов подряд не давали полного набора.
    // Сборка страницы стоит доли секунды, поэтому дешевле искать дольше, чем
    // перебирать сиды целыми комплектами. Сорок пробовал — не лучше двадцати
    // и вдвое дольше: лишние попытки меняют остаток пула для следующих
    // страниц, и выигрыш одной оборачивается проигрышем соседней.
    for ($попытка = 0; $попытка < 20; $попытка++) {
        $снимок = $журнал;
        $баланс = []; $балансНабора = [];
        $rng = new Rng($сид + $попытка * 7919 + crc32($тип));
        $стр = $собрать($тип);
