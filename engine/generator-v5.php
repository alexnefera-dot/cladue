            // «снял 270 тысяч … Через сорок минут на счёте лежали 120к».
            $второйИсход = $геройскийПлан && $i > 0 && $естьСумма;
            // Чистый абзац героя: после входа ни ссылок, ни офферов, ни призывов —
            // у A абзац истории содержит только историю; «Перед стартом можно забрать
            // пакет 250%, а коды ловятся в промокодах» внутри истории Николая — наш брак.
            $чистыйГерой = $геройскийПлан && $i > 0
                // Ссылка внутри истории у A обычна («зашёл через войти и играть», 76 % абзацев героя);
                // запрет только на офферы и призывы как отдельные предложения.
                ? fn(array $x): bool => !in_array(v5Rol((string) ($x['т'] ?? '')), ['оффер', 'cta'], true)
                : null;
