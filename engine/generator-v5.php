    foreach (PageMetrics::TOPICS[$тип] ?? [] as $w) {
        if (mb_strpos($t, $w) !== false) { return true; }
    }
    return false;
};
// Вопросительность h3 подруливается так же и по той же причине. Держит её
// только vhod, но там она мажет чаще всех: половина h3 приходит из виджета
// FAQ, где вопрос почти в каждом, и страница садится на 50–72 % при цели,
// разыгранной в полосе 16.7–66.7. Замер достижимого записал низ 0 — один
// набор случайно вышел в ноль, — поэтому зажим низкую цель не отсекает.
$вопросительный = function (string $заголовок): bool {
    $t = preg_replace('~^[^\w%]+~u', '', trim(preg_replace('~\s+~u', ' ', strip_tags($заголовок))));
    return (bool) preg_match('~^(что|как|почему|где|когда|сколько|кто|куда|можно'
        . '|зачем|нужно ли|стоит ли|чем)\b~ui', $t);
};
$цельПоТеме = []; $цельВопросов = [];
