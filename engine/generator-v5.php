        && !preg_match('~\{RTP2?\}~u', $текст)) { return true; }
    if (!isset($бюджетИмён[$тип])) { return false; }
    ['games' => $и, 'providers' => $с] = NicheLexicon::names(strip_tags($текст));
    if (!$и && !$с) { return false; }
    $б = $бюджетИмён[$тип];
    $иВсе = array_unique(array_merge($именаСтраницы['игры'], $и));
    $сВсе = array_unique(array_merge($именаСтраницы['студии'], $с));
    return count($иВсе) > ($б['игры'] ?? 0) || count($сВсе) > ($б['студии'] ?? 0)
        || count($иВсе) + count($сВсе) > ($б['всего'] ?? PHP_INT_MAX);
};

$взять = function (array $список, int $k, string $метка, float $порогБлизости = 0.34,
                   ?callable $хуже = null, ?callable $фильтр = null, ?callable $жёсткий = null)
        use (&$журнал, &$rng, &$баланс, &$балансНабора, &$запрет, $строгий, $имяНабора,
             $давностьНабора, $нарушает, $сверхБюджета, $малоДенег, &$именаСтраницы, $паспорт, $порядковый): array {
    if (!$список || $k < 1) { return []; }
    // Запреты типа понижают запись в очереди, а не выбрасывают её. Жёсткий
    // отсев мерился: нарушений вдвое меньше, но полных наборов 12/12 из
    // двадцати сидов стало ноль против четырёх — выкинутая десятая часть
    // пула не давала сойтись донорскому балансу и отбраковке почти-дублей.
    $типМетки = explode('|', $метка)[0];
    $кандидаты = [];
    foreach ($список as $x) {
        $донор = $x['д'] ?? '';
        if ($донор !== '' && in_array($донор, $запрет, true)) { continue; }
        $ключ = $метка . '|' . md5($x['т'] ?? ($x['в'] . $x['о']));
        // Невыданное идёт вне очереди; выданное — тем раньше, чем давнее ушло.
        $владелец = $журнал[$ключ] ?? null;
        $текстX = (string) ($x['т'] ?? (($x['в'] ?? '') . ' ' . ($x['о'] ?? '')));
        $кандидаты[] = ['ключ' => $ключ, 'x' => $x, 'донор' => $донор,
                        'запретно' => ($нарушает($типМетки, $текстX) || $сверхБюджета($типМетки, $текстX)) ? 1 : 0,
                        'хуже' => ($хуже === null ? 0 : (int) $хуже($x)) + (isset($x['т']) && $малоДенег($типМетки, $текстX) ? 1 : 0)
                            + (isset($x['т']) && ($именаСтраницы['геройРаздела'] ?? 0) >= 2 && preg_match('~\{ИМЯ~u', $текстX) ? 2 : 0)
                            // Второй процент в разделе — на шаг ниже, третий — на два; на
                            // типах с редкими цифрами (vhod, info, registracia, zerkalo)
                            // не трогаем: там штраф ронял numbers_per100.
                            + (isset($x['т']) && !in_array($типМетки, ['vhod', 'info', 'registracia', 'zerkalo'], true)
                                && preg_match('~\{(?:ПРОЦ|ДОЛЯ)\}~u', $текстX) ? min(2, (int) ($именаСтраницы['процентРаздела'] ?? 0)) : 0)
                            // RTP в разделе — не больше двух упоминаний: у доноров разделов с
                            // тремя и больше — ноль, у нас была четверть («RTP 99.0%» пять
                            // раз в «Демо»). Второе упоминание на шаг ниже, третье — на три.
                            + (isset($x['т']) && preg_match('~\{RTP~u', $текстX)
                                ? (($именаСтраницы['rtpРаздела'] ?? 0) >= 2 ? 3 : (int) ($именаСтраницы['rtpРаздела'] ?? 0)) : 0)
                            // Сумм в разделе — две-три, как у доноров (2: 35 %, 3: 28 %, 4: 7 %),
                            // а не одиннадцать в «Джекпот слотах»: с двух сумм запись с деньгами
                            // на шаг ниже, с трёх — на два.
                            + (isset($x['т']) && preg_match(V5_SUMMY_RE, $текстX)
                                ? min(2, max(0, (int) ($именаСтраницы['деньгиРаздела'] ?? 0) - 1)) : 0)
                            // Сумма героя — не больше двух упоминаний на раздел: «270к» шла
                            // трижды в одном абзаце («остановился после выплаты», «улов»,
                            // «из 1000 ₽ сделал»); третья запись с именем и суммой — на два ниже.
                            + (isset($x['т']) && ($именаСтраницы['суммГероя'] ?? 0) >= 2 && preg_match('~\{СУММА~u', $текстX)
                                && (preg_match('~\{ИМЯ~u', $текстX) || ($именаСтраницы['геройРаздела'] ?? 0) >= 1) ? 2 : 0)
                            // Джекпот-раздел без цифры джекпота — бюджет сумм вытеснял записи с
                            // {ДЖЕКПОТ}; первая такая запись в разделе «Джекпот…» идёт на шаг выше.
                            - (isset($x['т']) && !empty($именаСтраницы['джекпотНужен']) && str_contains($текстX, '{ДЖЕКПОТ}') ? 1 : 0)
                            // «По-честному» — у A 3.5 на страницу, у нас было 4.5–6: с третьей
                            // записи с оборотом следующая на шаг ниже, с четвёртой — на два.
                            + (isset($x['т']) && mb_stripos($текстX, 'по-честному') !== false
                                ? min(2, max(0, (int) ($именаСтраницы['поЧестному'] ?? 0) - 3)) : 0)
                            // Герой в пункте списка без фразы о нём в прозе раздела («рыбак у
                            // Станислава — 250к», где Станислав нигде не представлен) — на два ниже.
                            + (isset($x['т']) && str_contains($метка, '|пункты') && ($именаСтраницы['геройРаздела'] ?? 0) === 0
                                && preg_match('~\{ИМЯ~u', $текстX) ? 2 : 0)
                            // «Ты»-набор: запись с «вы/вас/ваш» на шаг ниже — перекрут её
                            // переведёт, но лучше взять свою. Вежливый императив не в счёт:
                            // штраф за него ронял imperatives втрое (vhod 6.1 → 2.9).
                            + (isset($x['т']) && ($паспорт['обращение'] ?? 'ты') !== 'вы'
                                && preg_match('~(?<![а-яё])(?:вы|вас|вам|вами|ваш\w*)(?![а-яё])~ui', strip_tags($текстX)) ? 1 : 0)
                            // «До этого он тоже сливал депозиты» в разделе без героя: фраза с
                            // «он/его/ему» идёт после фразы с именем, не раньше.
                            + (isset($x['т']) && ($именаСтраницы['геройРаздела'] ?? 0) === 0 && !preg_match('~\{ИМЯ~u', $текстX)
                                && preg_match('~(?:^|[.!?—]\s*)(?:<strong>)?(?:Он|У него|Его|Ему)\b~u', strip_tags($текстX)) ? 2 : 0),
                        'бывший' => $владелец === null ? 0 : 1,
                        // Запись, выданная в последних шести наборах, уходит в хвост очереди, пока
                        // есть из чего выбирать: финалы вроде «Следующая история может быть твоей»
                        // шли в 14–17 наборах подряд, и bonus/info валили уникальность.
                        'недавно' => ($владелец !== null && count($список) >= 8
                            && ($давностьНабора[$владелец] ?? 99) <= 6) ? 1 : 0,
                        'свежесть' => $владелец === null ? -1
                            : ($давностьНабора[$владелец] ?? count($давностьНабора))];
    }
    if (!$кандидаты) { return []; }
    // Запись, уже выданная ЭТОМУ набору, второй раз не идёт, пока есть из
    // чего выбирать: ключ «хуже» стоит в очереди выше ключа «бывший», и
    // предпочтение деньгам поднимало уже взятую запись с суммой над свежей
    // без суммы — «Поставил 1 000 ₽ на спин … забрал 350 тысяч» стояло в
    // двух абзацах одного раздела.
    // Не отсев, а ключ сортировки: отсев резал список до потолков и
    // близости, и FAQ на vhod и news недобирал пары (промахи faq и
    // questions_total по четыре из восьми).
    foreach ($кандидаты as &$c) { $c['свой'] = ($журнал[$c['ключ']] ?? '') === $имяНабора ? 1 : 0; }
    unset($c);
    $rng->shuffle($кандидаты);
    // Свежесть со знаком минус: чем больше номер, тем давнее ушла запись и тем
    // раньше её брать. Баланс доноров остаётся вторым ключом сортировки.
    usort($кандидаты, fn($a, $b) => [$a['запретно'], $a['свой'], $a['недавно'], $a['хуже'], $a['бывший'], -$a['свежесть'], $баланс[$a['донор']] ?? 0]
                              <=> [$b['запретно'], $b['свой'], $b['недавно'], $b['хуже'], $b['бывший'], -$b['свежесть'], $баланс[$b['донор']] ?? 0]);
    // Строгий журнал: выданное другому набору не берётся вовсе. Включается
    // только при запасе вдвое больше нужного — иначе выбор сужается до одного
    // варианта и вместе с уникальностью проседает профиль (замер: 28 страниц
    // из 36 против 32 при жёстком отсечении без запаса).
    $строгоТут = $строгий !== []
        && ($строгий === ['*'] || in_array(explode('|', $метка)[0], $строгий, true));
    if ($строгоТут) {
        $свежие = array_values(array_filter($кандидаты, fn($c) => $c['бывший'] === 0));
        if (count($свежие) >= $k * 2) { $кандидаты = $свежие; }
    }

    // Потолок на донора внутри страницы: без него отбраковка почти-дублей
    // сама сводит выбор к одному донору — тому, чьё переписывание меньше похоже
    // на соседние. На замере это давало 20 % текста страницы из одного набора.
    $доноров = count(array_unique(array_filter(array_column($кандидаты, 'донор'))));
    $взято = array_sum($баланс);
    $потолокДонора = max(60, (int) ceil(($взято + $k * 20) / max(1, $доноров) * 1.4));
    // Потолок на прошлый набор: страница собирается примерно из сотни кусков,
    // и пять из них от одного старого комплекта — уже заметная общая часть.
    // Потолок мягкий: если выбора не осталось, второй проход берёт без разбора.
    $потолокНабора = 5;

    $итог = [];
    foreach ([false, true] as $безРазбора) {
        foreach ($кандидаты as $c) {
            if (count($итог) >= $k) { break 2; }
            $т = $c['x']['т'] ?? ($c['x']['в'] . ' ' . $c['x']['о']);
            if (in_array($c['x'], $итог, true)) { continue; }
            // Жёсткий фильтр — в оба прохода: чужая история в абзаце без героя не
            // берётся и когда брать больше нечего, лучше короче абзац.
            if ($жёсткий !== null && isset($c['x']['т']) && !$жёсткий($c['x'])) { continue; }
            // Порядковая серия — по порядку: «Второй:» только после «Первый:», в
            // обоих проходах, иначе второй проход ставил «Третий» перед «Первым».
            if (isset($c['x']['т'])) {
                $н = $порядковый($т);
                if ($н > 1 && ($именаСтраницы['порядок'] ?? 0) !== $н - 1) { continue; }
                if ($н === 1 && ($именаСтраницы['порядок'] ?? 0) >= 1) { continue; }
            }
            if (!$безРазбора) {
                // Шаг плана абзаца: на первом проходе берём только фразу нужной роли.
                if ($фильтр !== null && isset($c['x']['т']) && !$фильтр($c['x'])) { continue; }
                // Список — из разных аргументов: три пункта про один бонус 100% —
                // не список, а заикание. Аргумент пункта — по ключевым словам.
                if (isset($c['x']['т']) && str_contains($метка, '|пункты')) {
                    $тема = v5TemaPunkta($т);
                    if ($тема !== 'общ') {
                        $занято = false;
                        foreach ($итог as $y) { if (isset($y['т']) && v5TemaPunkta($y['т']) === $тема) { $занято = true; break; } }
                        if ($занято) { continue; }
                    }
                }
                // «По-честному» — не больше четырёх на страницу на первом проходе.
                if (isset($c['x']['т']) && ($именаСтраницы['поЧестному'] ?? 0) >= 5 && mb_stripos($т, 'по-честному') !== false) { continue; }
                // Герой списка — только после героя в прозе.
                if (isset($c['x']['т']) && str_contains($метка, '|пункты') && ($именаСтраницы['геройРаздела'] ?? 0) === 0
                    && preg_match('~\{ИМЯ~u', $т)) { continue; }
                if ($c['донор'] !== '' && ($баланс[$c['донор']] ?? 0) >= $потолокДонора) { continue; }
                $владелец = $журнал[$c['ключ']] ?? '';
                if ($владелец !== '' && $владелец !== $имяНабора
                    && ($балансНабора[$владелец] ?? 0) >= $потолокНабора) { continue; }
                $похож = false;
                foreach ($итог as $y) {
                    $ty = $y['т'] ?? ($y['в'] . ' ' . $y['о']);
                    // Одно начало режем только у фраз: пары FAQ почти все
                    // начинаются с «Как вывести» / «Можно ли», и страж на
                    // них оставлял страницу без половины вопросов.
                    if (v5Blizost($т, $ty) > $порогБлизости
                        || (isset($c['x']['т'], $y['т']) && v5OdnoNachalo($т, $ty))
                        // Один вопрос FAQ с разными ответами — «Можно ли играть
                        // бесплатно?» дважды на странице; близость по тексту
                        // пары этого не ловила, ответы разные.
                        || (isset($c['x']['в'], $y['в'])
                            && mb_strtolower(trim(strip_tags($c['x']['в']))) === mb_strtolower(trim(strip_tags($y['в']))))) { $похож = true; break; }
                }
                if ($похож) { continue; }
                // Одно предложение или одно начало на странице дважды — в разных
                // абзацах одного раздела шли «Хочешь понять механику без риска?»
                // и «Здесь выигрывают и проигрывают — по-честному, без развода.»
                if (isset($c['x']['т'])) {
                    $повтор = false;
                    foreach (v5KlyuchiPovtora($т) as $пр) {
                        if (isset($именаСтраницы['предложения'][$пр])) { $повтор = true; break; }
                    }
                    if ($повтор) { continue; }
                }
                // Ключ сортировки считается до отбора, а абзац из шести фраз
                // берётся одним вызовом — шесть записей с RTP и суммой шли подряд.
                // Живой потолок на раздел: RTP — два упоминания, сумм — четыре
                // (у доноров пять и больше — 2 % разделов); второй проход без разбора.
                if (isset($c['x']['т'])) {
                    $r = preg_match_all('~\{RTP2?\}~u', $т); $д = preg_match_all(V5_SUMMY_RE, $т);
                    // Нужный джекпот-разделу {ДЖЕКПОТ} в потолок сумм не считается.
                    if (!empty($именаСтраницы['джекпотНужен']) && str_contains($т, '{ДЖЕКПОТ}')) { $д--; }
                    if (($r && ($именаСтраницы['rtpРаздела'] ?? 0) + $r > 2)
                        || ($д > 0 && ($именаСтраницы['деньгиРаздела'] ?? 0) + $д > 5)
                        // После двух сумм героя любая сумма без имени в его разделе тоже
                        // читается его («вышел с 67к», «ему прилетел куш на 67к»).
                        || (($именаСтраницы['суммГероя'] ?? 0) >= 2 && preg_match('~\{СУММА~u', $т)
                            && (preg_match('~\{ИМЯ~u', $т) || ($именаСтраницы['геройРаздела'] ?? 0) >= 1))) { continue; }
                }
            }
            $прежний = $журнал[$c['ключ']] ?? '';
            if ($прежний !== '' && $прежний !== $имяНабора) {
                $балансНабора[$прежний] = ($балансНабора[$прежний] ?? 0) + 1;
            }
            $журнал[$c['ключ']] = $имяНабора;
            if ($c['донор'] !== '') {
                $слов = count(preg_split('~\s+~u', v5Text($т), -1, PREG_SPLIT_NO_EMPTY));
                $баланс[$c['донор']] = ($баланс[$c['донор']] ?? 0) + $слов;
            }
            $итог[] = $c['x'];
            if (str_contains($т, '{ДЖЕКПОТ}')) { $именаСтраницы['джекпот']++; }
            if (isset($c['x']['т']) && preg_match('~\{ИМЯ~u', $т)) { $именаСтраницы['геройРаздела'] = ($именаСтраницы['геройРаздела'] ?? 0) + 1; }
            if (isset($c['x']['т']) && preg_match('~\{(?:ПРОЦ|ДОЛЯ)\}~u', $т)) { $именаСтраницы['процентРаздела'] = ($именаСтраницы['процентРаздела'] ?? 0) + 1; }
            if (isset($c['x']['т'])) {
                if (($н = $порядковый($т)) > 0) { $именаСтраницы['порядок'] = $н; }
                $именаСтраницы['поЧестному'] = ($именаСтраницы['поЧестному'] ?? 0) + preg_match_all('~по-честному~iu', $т);
                foreach (v5KlyuchiPovtora($т) as $пр) { $именаСтраницы['предложения'][$пр] = 1; }
                $именаСтраницы['rtpРаздела'] = ($именаСтраницы['rtpРаздела'] ?? 0) + preg_match_all('~\{RTP2?\}~u', $т);
                $именаСтраницы['деньгиРаздела'] = ($именаСтраницы['деньгиРаздела'] ?? 0) + preg_match_all(V5_SUMMY_RE, $т);
                if (preg_match('~\{СУММА~u', $т) && (preg_match('~\{ИМЯ~u', $т) || ($именаСтраницы['геройРаздела'] ?? 0) >= 1)) { $именаСтраницы['суммГероя'] = ($именаСтраницы['суммГероя'] ?? 0) + 1; }
                if (str_contains($т, '{ДЖЕКПОТ}')) { $именаСтраницы['джекпотНужен'] = false; }
            }
            $именаСтраницы['деньги'] += preg_match_all(V5_DENGI_RE, $т);
            ['games' => $и, 'providers' => $с] = NicheLexicon::names(strip_tags($т));
            $именаСтраницы['игры'] = array_values(array_unique(array_merge($именаСтраницы['игры'], $и)));
            $именаСтраницы['студии'] = array_values(array_unique(array_merge($именаСтраницы['студии'], $с)));
        }
    }
    return $итог;
};

/** Абзац из предложений: первое — из открывающих, остальные — из середины. */
/**
 * $заполнить — необязательный поштучный заполнитель прорезей. Он нужен, чтобы
 * узел знал границу между фразами: сумма и ставка растут внутри одной фразы,
 * а на границе начинаются заново с уже названного значения.
 */
/** Абзац открывается вопросом. Считаем по тексту записи, а не по странице. */
function v5VoprosВЗачине(string $т): bool
{
    return (bool) preg_match('~^[^.!?]{5,110}\?~u', trim(strip_tags($т)));
}

$механизмы = $пулы['общие']['механизмГероя'] ?? [];
$абзац = function (array $фразы, int $k, string $метка, ?callable $заполнить = null,
                   ?callable $хужеПерв = null, ?callable $поТемеФразы = null, ?array $план = null)
        use ($взять, $механизмы): string {
    if (!$фразы || $k < 1) { return ''; }
    // Сборка по плану: шаг за шагом, у каждого шага свои допустимые роли.
    // Первый шаг — из открывающих фраз, продолжение — от того же донора и по
    // теме, как и раньше; роль — жёсткий фильтр первого прохода, второй
    // проход берёт что есть, чтобы абзац не остался пустым.
    if ($план !== null) {
        $первые = array_values(array_filter($фразы, fn($x) => ($x['п'] ?? 0) === 1));
        $прочие = array_values(array_filter($фразы, fn($x) => ($x['п'] ?? 0) === 0));
        $части = []; $донорЗачина = ''; $геройБыл = false; $естьСумма = false;
        $геройскийПлан = in_array('ист.вход', $план[0] ?? [], true);
        foreach ($план as $i => $шаг) {
            // Цепочка истории строится по факту: если вход уже назвал сумму — дальше
            // событие (как это случилось) и вывод денег; если нет — событие, потом исход.
