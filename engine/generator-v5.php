/**
 * Генератор комплекта v5 — двенадцать страниц по корпусу доноров.
 *
 *   php engine/generator-v5.php --выход=samples/v5-final/<имя> [--сид=<n>]
 *                               [--бренд-ru=%brand_name_ru%] [--бренд-en=%brand_name_en%]
 *                               [--корпус=samples/v5-donors] [--тихо]
 *
 * Устройство повторяет фабрику, а не переизобретает её:
 *
 *  1. **Скелет** берётся из наблюдённых: у каждого типа 3–6 разных сборок
 *     («голова | H2×N | хвост»), выбор взвешен по частоте в корпусе.
 *  2. **Виджеты** переносятся разметкой один в один — доноры делают так же, и
 *     потому их главные пересекаются между собой на 15 %. Пары «вопрос-ответ»
 *     внутри виджета при этом набираются из общего пула вперемешку.
 *  3. **Проза** собирается по разделам, но не абзацами, а предложениями: H2 —
 *     позиция в меню фабрики, под ним зачин, H3, список и финал. Перенос
 *     абзацем давал с донором 16–26 % шинглов при корпусном потолке 8–11 %;
 *     шингл в шесть слов рвётся на границе предложения, и сборка из фраз
 *     разных доноров опускает долю каждого втрое.
 *  4. **Баланс доноров.** Внутри страницы очередь на выдачу отсортирована по
 *     тому, сколько кусков от этого донора уже взято. Без баланса выборка
 *     сползает к одному-двум донорам: замер показывал 18 % против 6 % у
 *     соседних.
 *  5. **Перетасовка.** Если собранная страница всё равно легла на одного
 *     донора выше потолка типа, он исключается из пулов и страница
 *     пересобирается — до пяти попыток, из них берётся лучшая.
 *  6. **Прорези** (`{ИМЯ}`, `{СУММА}`, `{RTP}`, `{ПРОЦ}`…) заполняются из
 *     банков корпуса. Каталог, число провайдеров и вейджер держатся на весь
 *     набор, герой — на раздел, числа катятся на узел.
 *  7. **Журнал выдачи** `data-v5/vydano.json` помнит, какие куски пула ушли в
 *     какой набор: следующий набор берёт сначала невыданное.
 *
