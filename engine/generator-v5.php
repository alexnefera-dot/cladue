        // отдельных слотов, ниже сетевого и без повторов. У доноров самая
        // частая сумма повторяется 2.6 раза, и на одной странице у них
        // стоят «до 8,5 млн», «достигает 12 000 000», «18,2 млн»; у нас один
        // «120.0 млн» шёл пять раз.
