// Доля заголовков «по своей теме» — поле профиля, и оно мажет в обе стороны:
// vhod держит 81–87 % при цели 72, app и registracia не дотягивают снизу.
// Пул это позволяет — у vhod по теме 71 % заголовков h3, — но очередь выдачи
// про тему ничего не знает и смещает выбор. Подруливаем на отборе: считаем
