    $запрет = [];
    $страница = $лучший['html'];
    if ($брендRu !== '%brand_name_ru%') { $страница = str_replace('%brand_name_ru%', $брендRu, $страница); }
    if ($брендEn !== '%brand_name_en%') { $страница = str_replace('%brand_name_en%', $брендEn, $страница); }
