        }
        if (isset($паспорт['каталог'][$ключ])) { return $паспорт['каталог'][$ключ]; }
        if ($ключ === 'ВЕЙДЖЕР') { return $паспорт['вейджер']; }
        if (isset($локальные[$ключ])) { return $локальные[$ключ]; }
        // Процент бонуса — три значения на страницу (пакет, релоад, кэшбэк),
        // не девять: на главной набора 313 шли 489, 350, 500, 250, 600, 350,
        // 300, 30, 60 и 400 %. У доноров разных процентов 4.9 на страницу, у
        // конкурента A 4.4; два давали 2.0 — ниже поля.
        if ($ключ === 'ПРОЦ' || $ключ === 'ДОЛЯ') {
            $список = $именаСтраницы['проценты'] ?? [];
            if (count($список) < 3) {
                $v = $изБанка('ПРОЦ');
                if (!in_array($v, $список, true)) { $именаСтраницы['проценты'][] = $v; }
                return $v;
            }
            return (string) $rng->pick($список);
        }
        // Виджет получает одного героя на заполнение — и одну сумму: вопрос
        // FAQ «выиграл 74к?» с ответом «итог — 3.2 млн» шёл из двух розыгрышей.
        // Но одна сумма — на две прорези, не на весь блок: FAQ из пяти ответов
        // нёс «87к» четырежды. Дальше — свежая, не названная в виджетах страницы.
        if ($ключ === 'СУММА' || $ключ === 'СУММАМАЛ') {
            $память['СУММАраз'] = ($память['СУММАраз'] ?? 0) + 1;
            if (!isset($память['СУММА']) || $память['СУММАраз'] > 2) {
                $названные = array_map(fn($x) => v5Summa((string) $x), $именаСтраницы['суммыВиджетов'] ?? []);
                $скромные = array_values(array_filter(array_keys($банки[$ключ] ?? []),
                    // Герой FAQ и виджетов — до 1.5 млн, как герой раздела: «дошёл до 3.2 млн» в ответе на вопрос.
                    fn($x) => v5Summa((string) $x) <= 1_500_000 && v5Summa((string) $x) >= 1_000
                        && !in_array(v5Summa((string) $x), $названные, true)));
                $память['СУММА'] = $скромные ? (string) $rng->pick($скромные) : $изБанка($ключ);
                $память['СУММАраз'] = 1;
            }
            $именаСтраницы['суммыВиджетов'][] = $память['СУММА'];
            return $память['СУММА'];
        }
        if ($ключ === 'СУММА_СТАВКА') {
            // И не выше 200к: с памятью в 3.2 млн ставка героя FAQ выходила 4 382 751 ₽.
            $потолок = min(200_000, isset($память['СУММА']) ? v5Summa((string) $память['СУММА']) : 200_000);
            $мелкие = array_values(array_filter(array_keys($банки['СУММАМАЛ'] ?? []),
                fn($x) => v5Summa((string) $x) < $потолок && v5Summa((string) $x) >= 1_000));
            return $мелкие ? (string) $rng->pick($мелкие) : '';
        }
        // И один RTP: ответ FAQ с добором нёс «RTP 99% … RTP 97%», и
        // смысловая приёмка валила набор по спору цифр.
        if ($ключ === 'RTP') { return $память['RTP'] ??= $изБанка('RTP'); }
        if ($ключ === 'RTP2') {
            $первый = (float) str_replace(',', '.', (string) ($память['RTP'] ??= $изБанка('RTP')));
            $выше = array_values(array_filter(array_keys($банки['RTP'] ?? []),
                fn($x) => (float) str_replace(',', '.', (string) $x) > $первый));
            return $память['RTP2'] ??= ($выше ? (string) $rng->pick($выше) : (string) $память['RTP']);
        }
        // Виджеты заполняются этим контекстом, а не узлом раздела, и до сих
        // пор {РУБЛИ} в них брались из всего банка, где 17 % сумм — от
        // миллиона. Ставка в ответе FAQ выходила «4 618 624 ₽». Ставочный ключ
        // (см. v5Zapolnit) здесь получает тот же слой 100–10 000, что и в узле.
        if ($ключ === 'РУБЛИ_СТАВКА') {
            $слой = array_values(array_filter(array_keys($банки['РУБЛИ'] ?? []),
                fn($x) => v5Rubli((string) $x) >= 100 && v5Rubli((string) $x) <= 10000));
            return $слой ? (string) $rng->pick($слой) : '';
        }
        return $изБанка($ключ);
    };
};

/** Пары «вопрос-ответ» внутри виджета меняются парой, разметка остаётся. */
$перебратьВиджет = function (string $html, string $тип) use (&$пулы, $взять): string {
    $замена = function (string $html, string $reВопрос, string $reОтвет, array $пары): string {
        $i = 0;
        $html = preg_replace_callback($reВопрос,
            function ($m) use (&$i, $пары) { $p = $пары[$i++] ?? null; return $p ? $m[1] . $p['в'] . $m[3] : $m[0]; },
            $html);
        $i = 0;
        return preg_replace_callback($reОтвет,
            function ($m) use (&$i, $пары) {
                $p = $пары[$i++] ?? null;
                if (!$p) { return $m[0]; }
                // Обёртка берётся у виджета: был <p> — ставим <p>, не было — нет.
                $о = str_starts_with(ltrim($m[2]), '<p>')
                    ? '<p>' . "\n            " . $p['о'] . "\n          " . '</p>'
                    : $p['о'];
                return $m[1] . $о . $m[3];
            },
            $html);
    };
    $faq = $пулы['хвосты'][$тип]['faq'] ?? [];
    if ($faq) {
        $нужно = preg_match_all('~<h3 class="faq-question" itemprop="name">~', $html);
        $пары = $взять($faq, $нужно, "$тип|faq");
        // Ответ короче 45 слов добирается второй записью. Ответы доноров —
        // 59 слов медианой, наш пул — 44, и рендер брал запись целиком без
        // усечения: коротким был сам источник. Вторая запись идёт без своих
        // ссылок: две ссылки на «информацию о казино» в одном ответе — лишнее.
        foreach ($пары as $i => $p) {
            // str_word_count кириллицу не считает — только preg_split.
            $слов = count(preg_split('~\s+~u', trim(strip_tags((string) $p['о'])), -1, PREG_SPLIT_NO_EMPTY));
            if ($слов >= 50) { continue; }
            // Добирается ОДНО предложение, а не запись целиком: целая запись
            // давала ответ в 70 слов при донорских 59 и тащила за собой лишние
            // «?» и опорные формулы — приёмка валила faq и anchors. Вопрос в
            // хвост не берём: ответ, кончающийся вопросом, — не ответ.
            // Добор — из записи с тем же предметом вопроса (общее слово от
            // пяти букв), и не с обрывка: «Она запускает серию вращений…»,
            // «Внутри самой игры — там…» продолжали чужой вопрос.
            $словаВопроса = [];
            foreach (preg_split('~[^\p{L}]+~u', mb_strtolower(strip_tags((string) $p['в']))) as $w) {
                if (mb_strlen($w) >= 5) { $словаВопроса[] = mb_substr($w, 0, 5); }
            }
            $поВопросу = function (array $x) use ($словаВопроса): int {
                $в = mb_strtolower(strip_tags((string) ($x['в'] ?? '')));
                foreach ($словаВопроса as $w) { if (mb_strpos($в, $w) !== false) { return 0; } }
                return 1;
            };
            $доп = $взять($faq, 1, "$тип|faq|добор", 0.34, $поВопросу);
            // Без общего слова вопроса добор не идёт: «Сколько ставить за
            // спин?» получал хвост «Да, демо-режим существует…».
            if ($доп && $поВопросу($доп[0]) !== 0) { $доп = []; }
            if ($доп && ($доп[0]['о'] ?? '') !== $p['о']) {
                $чист = preg_replace('~<a\b[^>]*>(.*?)</a>~s', '$1', (string) $доп[0]['о']);
                // До двух предложений, чтобы дотянуть до донорских 56–59 слов;
                // одно давало 47.
                $предл = preg_split('~(?<=[.!?])\s+~u', trim($чист), 3);
                // И не то предложение, что в ответе уже есть: «В профиле: каждое
                // вращение записано…» шло дважды в одном ответе — пары с общим
                // предметом делят и формулировки.
                // Сравнение по словам, не по строке: «живёт ровно потому» и «живёт
                // потому» — одно предложение из двух вариантов записи.
                $ужеЕсть = mb_strtolower(preg_replace('~\s+~u', ' ', strip_tags(implode(' ', array_column($пары, 'о')))));
                $словаОтветов = array_map(fn($x) => array_unique(preg_split('~[^\p{L}\d]+~u', $x, -1, PREG_SPLIT_NO_EMPTY)),
                    preg_split('~(?<=[.!?])\s+~u', $ужеЕсть));
                $знакомое = function (string $x) use ($словаОтветов): bool {
                    $a = array_unique(preg_split('~[^\p{L}\d]+~u', mb_strtolower(strip_tags($x)), -1, PREG_SPLIT_NO_EMPTY));
                    if (count($a) < 4) { return false; }
                    foreach ($словаОтветов as $b) {
                        if (count($b) >= 4 && count(array_intersect($a, $b)) >= 0.7 * min(count($a), count($b))) { return true; }
                    }
                    return false;
                };
                $предл = array_values(array_filter($предл, fn($x) =>
                    !preg_match('~^\s*(?:<strong>)?(?:он|она|оно|они|это|там|тут|здесь|внутри|потом|затем|также|ещё|а|но|и|с|из|у)\b~ui', strip_tags($x))
                    && count(preg_split('~\s+~u', trim(strip_tags($x)), -1, PREG_SPLIT_NO_EMPTY)) >= 6
                    // Связка и придаточное без главного — «Реально — в смысле…»,
                    // «Чтобы понять волатильность…» — в ответе висят.
                    && v5Rol($x) !== 'связка' && !preg_match('~^\s*(?:чтобы|реально\s+—|кстати|в смысле)~ui', strip_tags($x))
                    && !$знакомое($x)));
                $хвост = trim(implode(' ', array_slice($предл, 0, $слов < 30 ? 2 : 1)));
                if ($хвост !== '' && !str_contains($хвост, '?')) { $пары[$i]['о'] = rtrim((string) $p['о']) . ' ' . $хвост; }
            }
        }
        $html = $замена($html,
            '~(<h3 class="faq-question" itemprop="name">\s*)(.*?)(\s*</h3>)~s',
            '~(<div itemprop="text">\s*)(.*?)(\s*</div>)~s',
            $пары);
    }
    // Блок review-quotes — это отзывы игроков в кавычках, а не методичка.
    // Пул «раскрывашки» собран с других виджетов (как считается рейтинг, что
    // проверять в лицензии): подставляя его сюда, генератор вычищал со
    // страницы все четыре донорские реплики разом. Отсюда speech 1 при цели 5
    // на всех наборах подряд и заголовок «Выплаты и верификация» над абзацем
    // о методике оценки. Цитаты берём из своего пула, старый — запасной.
    $цитаты = $пулы['хвосты'][$тип]['цитаты'] ?? [];
    $рас = $цитаты ?: ($пулы['хвосты'][$тип]['раскрывашки'] ?? []);
    if ($рас) {
        // Тематический блок «О портале» делит классы faq-question и
        // review-quote-text с блоком цитат, но метки в review-quote-summary
        // у него нет. Регулярка ответа была привязана только к классу, и
        // тела тематического блока подменялись цитатами при своих заголовках:
        // «Слоты и игры» над «Вывел за 20 минут, без вопросов». Считаем и
        // подменяем только реплики с меткой.
        $нужно = preg_match_all('~<span class="review-quote-summary">~', $html);
        // Метка лежит в <span class="review-quote-summary">, а не в голом
        // <span>: прежняя регулярка не совпадала ни разу, и все наборы несли
        // одни и те же четыре донорские метки дословно.
        $html = $замена($html,
            '~(<button class="faq-question"[^>]*>\s*<span class="review-quote-summary">\s*)(.*?)(\s*</span>)~s',
            '~(<span class="review-quote-summary">(?:(?!</article>).)*?<p class="review-quote-text">\s*)(.*?)(\s*</p>)~s',
            $взять($рас, $нужно, "$тип|" . ($цитаты ? 'цитаты' : 'раскрывашки')));
    }
    // Тематический блок («О портале», «Полезно знать о слотах»): пары
    // «заголовок в голом <span> — тело в review-quote-text». Пул раскрывашек
    // собран именно с него; без подмены тела блока шли донорским текстом
    // дословно на каждом наборе.
    $раскрывашки = $пулы['хвосты'][$тип]['раскрывашки'] ?? [];
    if ($раскрывашки) {
        $нужно = preg_match_all('~<button class="faq-question"[^>]*>\s*<span>~', $html);
        if ($нужно > 0) {
            $html = $замена($html,
                '~(<button class="faq-question"[^>]*>\s*<span>\s*)(.*?)(\s*</span>)~s',
                '~(<button class="faq-question"[^>]*>\s*<span>(?:(?!</article>).)*?<p class="review-quote-text">\s*)(.*?)(\s*</p>)~s',
                $взять($раскрывашки, $нужно, "$тип|раскрывашки"));
        }
    }
    return $html;
};

