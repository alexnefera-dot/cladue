        $худший = ['—', 0.0];
        foreach ($донорские[$тип] ?? [] as $донор => $sh) {
            if (!$sh || !$наш) { continue; }
            $p = count(array_intersect_key($наш, $sh)) / min(count($наш), count($sh)) * 100;
            if ($p > $худший[1]) { $худший = [$донор, $p]; }
        }
        $карта = PageMetrics::measure($мерка, $тип,
            preg_replace('~<(?![a-zA-Z/!?])~', '&lt;', $стр['html']),
            ['ru' => '%brand_name_ru%', 'en' => '%brand_name_en%']);
        $всего = 0; $сошлось = 0;
        foreach ($профиль['страницы'][$тип]['поля'] ?? [] as $k => $п) {
            if (!$п['держат'] || !isset($карта[$k]) || !is_numeric($карта[$k])) { continue; }
            $всего++;
            // Цель своя у каждого набора: попадание считается от неё, иначе
            // все наборы сходятся в одну точку корпусной медианы.
            $цельНабора = v5CelNabora($п, $сид, $k);
            $пол = $п['дробное'] ? 0.8 : 2.0;
            if (abs((float) $карта[$k] - $цельНабора) <= max(0.25 * abs((float) $п['цель']), $пол)) { $сошлось++; }
        }
        $стр['профиль'] = $всего ? round($сошлось / $всего * 100) : 0;
        $стр['совпало'] = round($худший[1], 1);
        $стр['ближайший'] = $худший[0];
        $стр['попытка'] = $попытка + 1;
        // Сначала ворота профиля, и только среди прошедших — минимум совпадения.
        // Простой лексикографический порядок «профиль, потом совпадение» тянул
        // к варианту со 100 % полей и 30 % шинглов: одно очко профиля перевешивало
        // десять пунктов уникальности.
        $оценка = fn(array $x) => $x['профиль'] >= 95
            ? [1, -$x['совпало']]
            : [0, $x['профиль']];
        if ($лучший === null || $оценка($стр) > $оценка($лучший)) {
            $лучший = $стр;
            $лучшийЖурнал = $журнал;
        }
        // Ранний выход не окупается: сборка страницы стоит доли секунды, а
        // разброс между попытками — до десяти пунктов совпадения. Перебираем
        // все и берём лучшую; выходим раньше только на корпусной полосе.
        if ($стр['профиль'] >= 95 && $стр['совпало'] <= $потолок) { break; }
        $журнал = $снимок;             // отвергнутая попытка не тратит пул
        if ($стр['совпало'] > $порогСборки && !in_array($худший[0], $запрет, true)) {
