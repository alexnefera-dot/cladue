$сводка = [];
foreach (V5_TYPES as $тип) {
    $потолок = (float) ($профиль['уникальность']['по_типам'][$тип]['потолок'] ?? 12.0);
    $порогСборки = $потолок + 100 / max(1, (int) ($профиль['источник']['в_расчёте'] ?? 11));
    $лучший = null; $лучшийЖурнал = $журнал;
    $запрет = [];
    // Попытка оценивается двумя числами сразу: сколько полей профиля сошлось и
    // насколько страница легла на одного донора. Гнаться только за вторым
    // бессмысленно — самый непохожий вариант обычно и самый кривой по объёму.
    for ($попытка = 0; $попытка < 8; $попытка++) {
        $снимок = $журнал;
        $баланс = [];
        $rng = new Rng($сид + $попытка * 7919 + crc32($тип));
        $стр = $собрать($тип);
        $наш = shingles(chist($стр['html']));
        $худший = ['—', 0.0];
        foreach ($донорские[$тип] ?? [] as $донор => $sh) {
            if (!$sh || !$наш) { continue; }
            $p = count(array_intersect_key($наш, $sh)) / min(count($наш), count($sh)) * 100;
            if ($p > $худший[1]) { $худший = [$донор, $p]; }
        }
        $карта = PageMetrics::measure($мерка, $тип,
            preg_replace('~<(?![a-zA-Z/!?])~', '&lt;', $стр['html']),
            ['ru' => '%brand_name_ru%', 'en' => '%brand_name_en%']);
        $всего = 0; $сошлось = 0;
        foreach ($профиль['страницы'][$тип]['поля'] ?? [] as $k => $п) {
            if (!$п['держат'] || !isset($карта[$k]) || !is_numeric($карта[$k])) { continue; }
            $всего++;
            $пол = $п['дробное'] ? 0.8 : 2.0;
            if (abs((float) $карта[$k] - (float) $п['цель']) <= max(0.25 * abs((float) $п['цель']), $пол)) { $сошлось++; }
        }
        $стр['профиль'] = $всего ? round($сошлось / $всего * 100) : 0;
        $стр['совпало'] = round($худший[1], 1);
        $стр['ближайший'] = $худший[0];
        $стр['попытка'] = $попытка + 1;
        // Сначала ворота профиля, и только среди прошедших — минимум совпадения.
        // Простой лексикографический порядок «профиль, потом совпадение» тянул
        // к варианту со 100 % полей и 30 % шинглов: одно очко профиля перевешивало
        // десять пунктов уникальности.
        $оценка = fn(array $x) => $x['профиль'] >= 95
            ? [1, -$x['совпало']]
            : [0, $x['профиль']];
        if ($лучший === null || $оценка($стр) > $оценка($лучший)) {
            $лучший = $стр;
            $лучшийЖурнал = $журнал;
        }
        // Ранний выход не окупается: сборка страницы стоит доли секунды, а
        // разброс между попытками — до десяти пунктов совпадения. Перебираем
        // все восемь и берём лучшую; выходим раньше только на корпусной полосе.
        if ($стр['профиль'] >= 95 && $стр['совпало'] <= $потолок) { break; }
        $журнал = $снимок;             // отвергнутая попытка не тратит пул
        if ($стр['совпало'] > $порогСборки && !in_array($худший[0], $запрет, true)) {
            $запрет[] = $худший[0];    // донор, на которого легли, выбывает
        }
    }
    $журнал = $лучшийЖурнал;
    $запрет = [];
    $страница = $лучший['html'];
    if ($брендRu !== '%brand_name_ru%') { $страница = str_replace('%brand_name_ru%', $брендRu, $страница); }
    if ($брендEn !== '%brand_name_en%') { $страница = str_replace('%brand_name_en%', $брендEn, $страница); }
    $страница = v5PochinitDengi($страница, $банки['РУБЛИ'] ?? []);
    $страница = v5PochinitChislo($страница);
    $страница = v5PochinitKavychki($страница);
    $страница = v5UbratDubliVidzhetov($страница);
    file_put_contents("$выход/$тип.html", $страница);
    $сводка[$тип] = [
        'скелет' => $лучший['скелет'], 'разделов' => $лучший['разделов'],
        'попытка' => $лучший['попытка'], 'профиль' => $лучший['профиль'],
        'совпало' => $лучший['совпало'],
        'потолок' => $потолок, 'ближайший' => $лучший['ближайший'],
        'слов' => count(preg_split('~\s+~u', v5Text($страница), -1, PREG_SPLIT_NO_EMPTY)),
    ];
}

