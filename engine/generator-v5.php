            // описание продукта, и без этого в абзац вставал второй механизм.
            if (in_array($р, ['ист.вход', 'ист.исход', 'ист.обрывок', 'ист.оговорка'], true)) { return true; }
            return $р === 'ист.событие' && (bool) preg_match('~сработал|выпал|попал|поймал|словил|дал[аи]?\s+серию|открыл\w*\s+фриспины|пошли\s+с\s+множителем|перестал\w*\s+таять|вытянул~u', mb_strtolower(strip_tags($т)));
        });
