// Характер набора. У конкурентов объём — свойство САЙТА: сайт даёт 40–59 %
// разброса слов, стронгов и абзацев между страницами (A+B+C+D, 61 сайт), и
// комплекты расходятся между собой на 13–27 % по словам. У нас — 2 %: цель
// каждой страницы разыгрывалась в узкой донорской полосе, а сборка на цель не
// смотрела вовсе, только выбирала лучший из двадцати вариантов. Характер берём
// из того же розыгрыша, что и цель по словам (crc32('words|сид')), — тогда
// сборка тянет в ту же сторону, куда приёмка потом будет мерить.
//   темп ∈ [-1, 1]: «сухой» набор — меньше H2, меньше зачинов, короче абзацы;
//   «многословный» — наоборот. Середина полосы характера не имеет.
$темп = 0.0;
if ($сид > 0) {
    $u = (crc32('words|' . $сид) % 100000) / 100000;
    $темп = $u < 0.25 ? -1.0 : ($u > 0.75 ? 1.0 : 0.0);
}
// Фразы сдвигаются только вниз. Розыгрыш из распределения сам поднял абзац до
// донорских 45–50 слов; ещё +1 фраза на «многословном» наборе давала 29 600
// слов на комплект и валила words на трети страниц. Вверх объём набирают
// скелет и лишний зачин, вниз — все три рычага.
// Верхняя сторона мягче нижней. На «многословных» наборах промахи шли
// почти все вверх (strong, anchors, words — 8 из 8 выше цели на promo), и
// партия дорожала втрое. Вверх объём набирает только скелет, вниз — скелет,
// зачин и фраза: у поля разброс тоже несимметричен, короткие сайты дальше
// от медианы, чем длинные (A: 9 624 … 26 339 при медиане 19 386).
// Мир набора дописывает почти в каждый абзац по фразе, поэтому сборка с миром
// берёт на фразу меньше — иначе words_per_para и para_spread уходят за полосу.
$сдвигФраз    = ($темп < 0 || !empty($паспорт['мир'])) ? -1 : 0;
$сдвигЗачинов = $темп < 0 ? -1 : 0;

$собрать = function (string $тип) use (&$блоки, &$пулы, &$rng, $взять, $абзац, $медиана,
        $контекст, $перебратьВиджет, $герои, $героини, $изБанка, $банки,
        $поТеме, $цельПоТеме, $вопросительный, $цельВопросов, $цельЗнаков, $имяНабора,
        $темп, $сдвигФраз, $сдвигЗачинов, $фразИзРаспределения, &$именаСтраницы): array {
    $нумероватьНабор = v5NumerovatNabor($тип, $имяНабора);
    $именаСтраницы = ['игры' => [], 'студии' => [], 'джекпот' => 0, 'деньги' => 0, 'предложения' => []];
    $варианты = [];
    foreach ($блоки['скелеты'][$тип] ?? [] as $подпись => $n) {
        [$голова, , $хвост] = array_map('trim', explode('|', $подпись));
        $классы = array_filter(array_map('trim', array_merge(
            $голова === '' ? [] : explode(' + ', $голова),
            $хвост === '' ? [] : explode(' + ', $хвост))));
        $известны = true;
        foreach ($классы as $k) { if (!isset($блоки['блоки'][$тип][$k])) { $известны = false; break; } }
        if (!$известны) { continue; }
        // Скелет под характер: «сухой» набор чаще берёт короткий скелет
        // (меньше H2), «многословный» — длинный. Вес меняется втрое, а не
        // жёстко: у доноров и короткий сайт иногда пишет длинную главную.
        $вес = (float) $n;
        if ($темп !== 0.0 && preg_match('~H2×(\d+)~u', $подпись, $mm)) {
            $h2 = (int) $mm[1];
            $вес *= ($темп > 0) === ($h2 >= 6) ? ($темп > 0 ? 1.5 : 2.0) : ($h2 === 5 ? 1.0 : ($темп > 0 ? 1 / 1.5 : 0.5));
        }
        $варианты[$подпись] = max(1, (int) round($вес * 100));
    }
    if (!$варианты) { fwrite(STDERR, "нет скелета для $тип\n"); exit(1); }
    $подпись = $rng->weighted($варианты);
    [$головаС, $серёдкаС, $хвостС] = array_map('trim', explode('|', $подпись));
    $головаКлассы = $головаС === '' ? [] : array_map('trim', explode(' + ', $головаС));
    $хвостКлассы  = $хвостС === '' ? [] : array_map('trim', explode(' + ', $хвостС));
    $сколькоH2 = (int) (preg_match('~H2×(\d+)~u', $серёдкаС, $m) ? $m[1] : 5);

    // разделы: обязательные (есть почти у всех доноров) плюс добор по весу
    $пул = $пулы['разделы'][$тип] ?? [];
    $доноров = max(1, $блоки['источник']['наборов'] ?? 12);
    $обяз = []; $прочие = [];
    foreach ($пул as $h2 => $r) {
        if ($r['встреч'] >= $доноров * 0.9) { $обяз[$h2] = $r['встреч']; } else { $прочие[$h2] = $r['встреч']; }
    }
    // «Провайдеры» на slots — обязательный раздел и первый в списке: у 7
    // доноров из 11 он есть, а студии на странице называются только в нём.
    // Без него slots выходил с нулём студий при 1.2 у доноров и 2–4 у поля.
    if ($тип === 'slots') {
        foreach (array_keys($прочие) as $h2) {
            if (str_starts_with($h2, 'Провайдеры')) { $обяз = [$h2 => $прочие[$h2]] + $обяз; unset($прочие[$h2]); break; }
        }
    }
    // Одна тема — один раздел: «Джекпот слоты — {ИМЯ} сорвал {СУММА} здесь» и
    // «… сорвал {РУБЛИ} здесь» лежат в пуле разными ключами и вставали на
    // страницу оба. Тема — часть заголовка до тире.
    $тема = fn(string $h2): string => mb_strtolower(trim(preg_replace('~\s*[—–-].*$~u', '', strip_tags($h2))));
    $выбор = array_slice(array_keys($обяз), 0, $сколькоH2);
    $темы = array_map($тема, $выбор);
    while (count($выбор) < $сколькоH2 && $прочие) {
        $h2 = $rng->weighted($прочие);
        unset($прочие[$h2]);
        if (in_array($тема($h2), $темы, true)) { continue; }
        $выбор[] = $h2; $темы[] = $тема($h2);
    }
    usort($выбор, function ($a, $b) use ($пул) {
        $м = function ($h) use ($пул) { $p = $пул[$h]['позиции'] ?? [0]; sort($p); return $p[intdiv(count($p), 2)]; };
        return $м($a) <=> $м($b);
    });

    $загВсего = 0; $загПоТеме = 0;   // заголовки страницы и доля «по теме»
    // Доля вопросительных зачинов у нас совпадает с корпусом — 18.2 % против
    // 16.9 %. Ломается кучность: пар подряд в 2.8 раза больше донорского, а
    // троек в 46 раз (20 против одной на весь корпус). Запрещаем серию, а не
    // сам приём: после двух вопросов подряд третий абзац просит зачин без
    // вопроса. Пары остаются — они у доноров есть.
    $вопросПодряд = 0; $вопросовСтраницы = 0;
    $h3Всего = 0; $h3Вопросов = 0;   // отдельный счёт для вопросительности h3
    $ростер = $пулы['общие']['слоты'] ?? [];
    // Скелет донора называет один и тот же класс дважды — в голове и в хвосте.
    // Два независимых выбора из одного набора вариантов регулярно совпадают, и
    // страница показывает один виджет два раза подряд. Внутри страницы уже
    // выданный вариант из выбора исключается.
    $выданныеВарианты = [];
    // Герой на страницу не повторяется: «Максим» вёл и «Демо», и «Популярные»,
    // а «Александр» из «Демо» с 83 тыс в FAQ «вчера выиграл 920к».
    $героиСтраницы = [];
    $виджет = function (string $k) use (&$блоки, $тип, &$rng, $перебратьВиджет, $контекст, $герои, $героини, $ростер, &$выданныеВарианты, &$героиСтраницы) {
        $вар = $блоки['блоки'][$тип][$k] ?? [];
        if (!$вар) { return null; }
        $плоско = [];
        foreach ($вар as $класс => $список) {
            foreach ($список as $i => $x) { $плоско["$класс|$i"] = (string) $x; }
        }
        $свободные = array_diff_key($плоско, $выданныеВарианты);
        if (!$свободные) { $свободные = $плоско; }
        $ключ = (string) $rng->pick(array_keys($свободные));
        $выданныеВарианты[$ключ] = 1;
        $html = $перебратьВиджет($свободные[$ключ], $тип);
        $геройВиджета = $rng->pick(array_values(array_diff($герои, $героиСтраницы)) ?: $герои);
        if (str_contains($html, '{ИМЯ')) { $героиСтраницы[] = $геройВиджета; }
        $html = v5Zapolnit(v5Trafaret($html),
            $контекст(['ИМЯ' => $геройВиджета, 'ИМЯЖ' => $rng->pick($героини)]));
        $html = v5VidzhetVyplat($html, $rng, $герои, $героини);
        // Донорский вариант блока целиком в <strong>: жирный заголовок, жирная
        // подводка и жирные карточки. Это разметка одного донора, а не приём —
        // снимаем <strong>, обёрнутый вокруг блочных элементов.
        $html = preg_replace('~<strong>\s*(?=<(?:h[1-6]|p|div|button|article|ul|ol|li)\b)~u', '', $html);
        $html = preg_replace('~(</(?:h[1-6]|p|div|button|article|ul|ol|li)>)\s*</strong>~u', '$1', $html);
        $html = preg_replace('~(<(?:h2|p) class="review-quotes-(?:heading|desc)">\s*)<strong>(.*?)</strong>(\s*</(?:h2|p)>)~su', '$1$2$3', $html);
        // И заголовок виджета целиком в <strong> («<h2><strong>❓ Честные ответы</strong></h2>»).
        $html = preg_replace('~(<h[23]\b[^>]*>\s*)<strong>(.*?)</strong>(\s*</h[23]>)~su', '$1$2$3', $html);
        // Отдача слота — не прорезь: у всех двенадцати доноров Sweet Bonanza
        // идёт с 96.51 %, и катать это число значит расходиться с корпусом на
        // ровном месте. После заполнения ростер возвращается на место.
        if ($ростер) {
            $html = preg_replace_callback(
                '~(<h3 class="slot-name" itemprop="name">\s*)(.*?)(\s*</h3>.*?<span class="slot-rtp-value"[^>]*>\s*)([\d.,]+)(?=%)~s',
                function ($m) use ($ростер) {
                    $имя = trim($m[2]);
                    return isset($ростер[$имя]) ? $m[1] . $m[2] . $m[3] . $ростер[$имя]['rtp'] : $m[0];
                }, $html);
        }
        return $html;
    };

    // Какие RTP на странице уже назывались. Внутри абзаца значение одно, но
    // разные абзацы должны брать разные: два абзаца, случайно выпавшие на одну
    // цифру, съедают fact_values — профиль держит около пяти дробных процентов
    // на страницу, и на vhod с registracia мы из-за этого проваливались.
    $названныеRTP = []; $названныеСуммы = [];
    $куски = [];
    foreach ($головаКлассы as $k) { if (($h = $виджет($k)) !== null) { $куски[] = $h; } }
    $номерРаздела = 0;
    foreach ($выбор as $h2) {
        $r = $пул[$h2]; $номерРаздела++;
        $встреч = max(1, $r['встреч']);
        // Герой держится на раздел — это одна история. Числа катятся на узел:
        // «джекпот до 47к» в шести пунктах подряд не пишет ни один донор. Но
        // внутри узла число одно: два разных RTP в соседних предложениях
        // одного абзаца читаются как противоречие, и у доноров такого нет.
        $герой = $rng->pick(array_values(array_diff($герои, $героиСтраницы)) ?: $герои);
        $героиСтраницы[] = $герой;
        $героиня = $rng->pick($героини);
        // Сумма истории — одна на раздел, как и герой. Узлы тянули суммы
        // независимо, и в H2 «Павел сорвал 67к», в теле «вынес 83 тыс», а
        // в FAQ «выиграл 74к … итог — 3.2 млн». Первая сумма первого узла
        // раздела становится суммой героя; первое вхождение в каждом
        // следующем узле берёт её же, рост внутри фразы остаётся.
        $суммаРаздела = null;
        // Фразы без героя в разделе делят одну «вторую» сумму: рядом с
        // «сорвал 165к» стояли «Итог: 290к», «из тысячи сделать 120к», «с 135к
        // вырос до 250к» — четыре суммы без хозяина в одном разделе.
        $втораяСуммаРаздела = null; $втораяСуммаРаз = 0; $доводБыл = false;
        // Процент бонуса — один на раздел: H2 «До 50%» над телом «пакет до
        // 125%» читался спором, хотя на странице оба значения законны.
        $процентРаздела = null;
        // И RTP один на раздел: H2 «RTP 96.6%» над телом с «RTP 98.7%» читался
        // спором. Разных RTP на странице остаётся по числу разделов.
        $rtpРаздела = null;
        // Герой раздела — в двух фразах, не в четырёх: у доноров разделов с
        // тремя и больше упоминаниями героя 1 %, у нас было 21 % («Тимур
        // зашёл…» открывал три абзаца подряд). H2 с именем считается.
        $именаСтраницы['геройРаздела'] = 0;
        // Процент бонуса один на раздел, и записей с ним — не больше двух:
        // «бонус 177%» шёл шесть раз в одном разделе.
        $именаСтраницы['процентРаздела'] = 0;
        // RTP — не больше двух упоминаний на раздел, сумм — две-три; H2 считается.
        $именаСтраницы['rtpРаздела'] = preg_match_all('~\{RTP2?\}~u', $h2);
        $именаСтраницы['деньгиРаздела'] = preg_match_all(V5_SUMMY_RE, $h2);
        $именаСтраницы['суммГероя'] = preg_match('~\{ИМЯ~u', $h2) && preg_match('~\{СУММА~u', $h2) ? 1 : 0;
        $именаСтраницы['порядок'] = 0;
        $джекпотныйРаздел = mb_stripos($h2, 'джекпот') !== false;
        // Кэшбэк — не бонус на депозит: «возврат до 100%» из общего банка процентов читался нелепо.
        $кэшбэкРаздел = mb_stripos($h2, 'кэшбэк') !== false || mb_stripos($h2, 'кешбэк') !== false; $кэшбэкПроцент = null;
        // Раздел про джекпот без единой цифры джекпота — нужна хотя бы одна.
        $именаСтраницы['джекпотНужен'] = mb_stripos($h2, 'джекпот') !== false && $именаСтраницы['джекпот'] === 0;
        // Ставка и результат в одной фразе («зашёл с X, довёл до Y») берут одну
        // и ту же прорезь. Внутри узла рубли выдаются по возрастанию: первое
        // вхождение — из младшей половины банка, следующие крупнее. Иначе герой
        // заходит с двенадцатью тысячами и уходит с ними же.
        $рубли = array_keys($банки['РУБЛИ'] ?? []);
        usort($рубли, fn($a, $b) => v5Rubli($a) <=> v5Rubli($b));
        // Ставка героя — это сотни и тысячи, а не сорок шесть тысяч: банк рублей
        // наполовину состоит из выплат, и «младшая половина» для ставки слишком
        // крупная. Порог в десять тысяч оставляет ровно ставочный слой.
        $млад = array_values(array_filter($рубли, fn($x) => v5Rubli($x) <= 10000 && v5Rubli($x) >= 100));
        $старш = array_slice($рубли, intdiv(count($рубли), 2)) ?: $рубли;
        $узел = function () use ($контекст, $герой, $героиня, $изБанка, $rng, $млад, $рубли, $старш, $банки, $джекпотныйРаздел, $кэшбэкРаздел, &$кэшбэкПроцент, &$названныеRTP, &$названныеСуммы, &$суммаРаздела, &$втораяСуммаРаздела, &$втораяСуммаРаз, &$процентРаздела, &$rtpРаздела) {
            $ставка = $млад ? (string) $rng->pick($млад) : $изБанка('РУБЛИ');
            $крупнее = array_values(array_filter($рубли, fn($x) => v5Rubli($x) > v5Rubli($ставка)));
            // Если крупнее не нашлось, берём из старшей половины, но не ту же
            // строку: «зашёл с X и довёл до X» — единственный по-настоящему
            // заметный глазом сбой подстановки.
            if (!$крупнее) { $крупнее = array_values(array_filter($старш, fn($x) => $x !== $ставка)); }
            $счёт = 0; $выданные = []; $местные = [];
            // Флаги «это первая сумма/ставка текущей записи». Сбрасываются
            // служебным ключом {@ЗАПИСЬ} на границе фраз абзаца.
            $перваяСумма = true; $перваяРубли = true;
            $суммаВЭтой = false; $суммаВПрошлой = false;
            // Фраза про героя ({ИМЯ} в тексте) — только она держит сумму
            // истории раздела. Сумма во всех фразах подряд уполовинила
            // разные суммы на странице (8.2 → 5.4 при донорских 11.2):
            // «выплаты до X» и «куш X» не про героя, им своя цифра.
            $фразаОГерое = false; $фразаДиапазон = false; $ставкаЗаписи = null; $ставкиУзла = []; $джекпотВЗаписи = false; $кэшбэкВЗаписи = false; $бонусУзла = null;
            return function (string $ключ) use ($контекст, $герой, $героиня, $изБанка, $rng, $ставка, $крупнее, $млад, $джекпотныйРаздел, $кэшбэкРаздел, &$кэшбэкПроцент, &$счёт, &$выданные, &$местные, $банки, &$названныеRTP, &$названныеСуммы, &$суммаРаздела, &$втораяСуммаРаздела, &$втораяСуммаРаз, &$процентРаздела, &$rtpРаздела, &$перваяСумма, &$перваяРубли, &$суммаВЭтой, &$суммаВПрошлой, &$фразаОГерое, &$фразаДиапазон, &$ставкаЗаписи, &$ставкиУзла, &$джекпотВЗаписи, &$кэшбэкВЗаписи, &$бонусУзла) {
                if (str_starts_with($ключ, '@ЗАПИСЬ')) {
                    // Диапазон отдачи («{RTP}–{RTP2}», «от {RTP} до {RTP2}») —
                    // единственное место, где второй RTP вправе отличаться от
                    // первого. Одинокий {RTP2} при уже названном RTP узла
                    // давал «RTP 95.9% … RTP 97.0%» в одном абзаце.
                    $фразаДиапазон = (bool) preg_match('~\{RTP\}%?\s*(?:[–-]|и|или|до)\s*\{RTP2\}|от\s+\{RTP\}%?\s+до\s+\{RTP2\}|между\s+\{RTP\}~u', $ключ);
                    // Про героя — и фраза с местоимением и глаголом исхода:
                    // «У него вышло без лишних шагов: 3 535 ₽ превратились в
                    // 410к» стояла рядом с «вынес 210к» того же героя.
                    // «Итог: {СУММА} на счёт» — итог истории героя, а не чужая сумма:
                    // рядом с «забрал куш в 40к» стояло «Итог: 550к».
                    $джекпотВЗаписи = (bool) preg_match('~джекпот~ui', $ключ);
                    $кэшбэкВЗаписи = (bool) preg_match('~к[эе]шб[эе]к|возврат~ui', $ключ);
                    $фразаОГерое = (bool) preg_match('~\{ИМЯ~u', $ключ) || str_contains($ключ, '<!--герой-->')
                        || (bool) preg_match('~(?<![а-яё])Итог:\s*(?:<strong>)?\{СУММА~u', $ключ)
                        || (preg_match('~\b(?:он|она|него|неё|ему|ей|его|её)\b~ui', strip_tags($ключ))
                            && preg_match('~\b(?:вынес|вышел|вышла|ушёл|ушла|снял|сняла|поймал|поймала|забрал|забрала|поднял|подняла|вывел|вывела|превратил\w*|сорвал|сорвала|выиграл|выиграла|вытащил|вытащила|получил|получила|поднять|вывести|снять|забрать|вынести|сорвать|выиграть|вытащить|выбил|выбила)\b~ui', strip_tags($ключ)))
                        || (bool) preg_match('~\b(?:его|её)\s+(?:джекпот|куш|выигрыш|занос|итог|результат)~ui', strip_tags($ключ));
                    // Довод с суммой героя: «отдать {СУММА} или забрать всё», «те же {СУММА}» — его сумма.
                    $фразаОГерое = $фразаОГерое || (bool) preg_match('~(?:отдать|дать|кончиться|способен и на|ни|те же|такие|не обещает)\s+(?:<strong>)?\{СУММА|^\s*(?:<strong>)?\{СУММА\}(?:</strong>)?\s+за один вечер|и\s+\{СУММА\}\s+за час~ui', $ключ);
                    // Соседство важнее самого факта повтора: спорят подряд
                    // идущие фразы с суммами, а разнесённые по абзацу читаются
                    // как разные эпизоды. Замер: сплошной повтор уполовинил
                    // дефект (1.01 → 0.49 %), но поднял промахи fact_values
                    // с 29 до 39 — различных фактов на странице стало меньше.
                    $суммаВПрошлой = $суммаВЭтой; $суммаВЭтой = false;
                    $перваяСумма = true; $перваяРубли = true; $ставкаЗаписи = null; return '';
                }
                // Прорезь, перед которой стоит «ставка/поставил/закинул/депозит»:
                // всегда ставочный слой банка (100–10 000). Раньше слой давался
                // только ПЕРВОМУ {РУБЛИ} узла, а узел — это целый виджет: во
                // втором ответе FAQ ставка шла из «крупнее» и выходило «ставка
                // 15 997 025 ₽». У доноров и трёх корпусов конкурентов ставок
                // от миллиона нет ни одной на 607 упоминаний; p99 — 15 000.
                if ($ключ === 'РУБЛИ_СТАВКА') {
                    $свои = array_values(array_diff($млад ?: [$ставка], $выданные)) ?: ($млад ?: [$ставка]);
                    $v = (string) $rng->pick($свои); $выданные[] = $v; $счёт++;
                    return $v;
                }
                if ($ключ === 'РУБЛИ') {
                    if ($счёт++ === 0) { $выданные[] = $ставка; return $ставка; }
                    // Ставку к фразе НЕ привязываем. Пробовали: первое {РУБЛИ}
                    // новой записи возвращало ставку и там, где фраза называет
                    // ею исход, — выходило «зашёл с X, вывел X». Смысловая
                    // приёмка ловит это как «ставка равна результату»: находок
                    // стало 11 против 8 на пятнадцати сидах. Рост по записи
                    // остаётся только у суммы, у которой роль однозначна.
                    // Два независимых выбора из одного банка иногда совпадают, и
                    // тогда герой «доводит сумму» до той же цифры. Внутри узла
