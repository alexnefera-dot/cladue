// Порядковый зачин записи: «Первый: …», «Во-вторых, …», «Третье — …». Записи
// одной нумерованной серии берутся порознь, и «Третий:» шёл раньше «Первый:».
$порядковый = function (string $текст): int {
    static $ряд = ['перв' => 1, 'во-перв' => 1, 'втор' => 2, 'во-втор' => 2, 'трет' => 3, 'в-трет' => 3,
                   'четв' => 4, 'в-четв' => 4, 'пят' => 5, 'в-пят' => 5];
    // Только порядковые формы: «Четверг, 23:40» и «Пятница, 20:00» — дни недели.
    if (!preg_match('~^\s*(?:<strong>)?(во-первых|во-вторых|в-третьих|в-четв[её]ртых|в-пятых|(?:перв|втор|трет|четв[её]рт|пят)(?:ый|ий|ое|ье|ая|ья|ым|им|ую|ью|ой|ей))\s*(?:[:—–-]|,)~ui', strip_tags($текст), $m)) { return 0; }
    $к = mb_strtolower($m[1]);
    foreach ($ряд as $осн => $н) { if (str_starts_with($к, $осн)) { return $н; } }
    return 0;
};
