$именаСтраницы = ['игры' => [], 'студии' => [], 'джекпот' => 0];
$сверхБюджета = function (string $тип, string $текст) use ($бюджетИмён, &$именаСтраницы): bool {
    // Джекпот — константа набора, и каждая запись с {ДЖЕКПОТ} называет ту
    // же цифру: 9 раз на slots при донорских 2.6 повторах самой частой
    // суммы. Сверх трёх записей на страницу — в конец очереди, но только
    // записи без другого факта: бюджет на все записи с джекпотом ронял
    // fact_values с 5.4 до 3.8 на promo, потому что уносил с собой {RTP}.
    if ($именаСтраницы['джекпот'] >= 3 && str_contains($текст, '{ДЖЕКПОТ}')
        && !preg_match('~\{RTP2?\}|\{ПРОЦ\}|\{ДОЛЯ\w*\}|\d%~u', $текст)) { return true; }
    if (!isset($бюджетИмён[$тип])) { return false; }
    ['games' => $и, 'providers' => $с] = NicheLexicon::names(strip_tags($текст));
    if (!$и && !$с) { return false; }
    $б = $бюджетИмён[$тип];
    $иВсе = array_unique(array_merge($именаСтраницы['игры'], $и));
    $сВсе = array_unique(array_merge($именаСтраницы['студии'], $с));
    return count($иВсе) > ($б['игры'] ?? 0) || count($сВсе) > ($б['студии'] ?? 0)
        || count($иВсе) + count($сВсе) > ($б['всего'] ?? PHP_INT_MAX);
};

$взять = function (array $список, int $k, string $метка, float $порогБлизости = 0.34,
                   ?callable $хуже = null)
        use (&$журнал, &$rng, &$баланс, &$балансНабора, &$запрет, $строгий, $имяНабора,
             $давностьНабора, $нарушает, $сверхБюджета, &$именаСтраницы): array {
    if (!$список || $k < 1) { return []; }
    // Запреты типа понижают запись в очереди, а не выбрасывают её. Жёсткий
    // отсев мерился: нарушений вдвое меньше, но полных наборов 12/12 из
    // двадцати сидов стало ноль против четырёх — выкинутая десятая часть
    // пула не давала сойтись донорскому балансу и отбраковке почти-дублей.
    $типМетки = explode('|', $метка)[0];
    $кандидаты = [];
    foreach ($список as $x) {
        $донор = $x['д'] ?? '';
        if ($донор !== '' && in_array($донор, $запрет, true)) { continue; }
        $ключ = $метка . '|' . md5($x['т'] ?? ($x['в'] . $x['о']));
        // Невыданное идёт вне очереди; выданное — тем раньше, чем давнее ушло.
        $владелец = $журнал[$ключ] ?? null;
        $текстX = (string) ($x['т'] ?? (($x['в'] ?? '') . ' ' . ($x['о'] ?? '')));
        $кандидаты[] = ['ключ' => $ключ, 'x' => $x, 'донор' => $донор,
                        'запретно' => ($нарушает($типМетки, $текстX) || $сверхБюджета($типМетки, $текстX)) ? 1 : 0,
                        'хуже' => $хуже === null ? 0 : (int) $хуже($x),
                        'бывший' => $владелец === null ? 0 : 1,
                        'свежесть' => $владелец === null ? -1
                            : ($давностьНабора[$владелец] ?? count($давностьНабора))];
    }
    if (!$кандидаты) { return []; }
    $rng->shuffle($кандидаты);
    // Свежесть со знаком минус: чем больше номер, тем давнее ушла запись и тем
    // раньше её брать. Баланс доноров остаётся вторым ключом сортировки.
    usort($кандидаты, fn($a, $b) => [$a['запретно'], $a['хуже'], $a['бывший'], -$a['свежесть'], $баланс[$a['донор']] ?? 0]
                              <=> [$b['запретно'], $b['хуже'], $b['бывший'], -$b['свежесть'], $баланс[$b['донор']] ?? 0]);
    // Строгий журнал: выданное другому набору не берётся вовсе. Включается
    // только при запасе вдвое больше нужного — иначе выбор сужается до одного
    // варианта и вместе с уникальностью проседает профиль (замер: 28 страниц
    // из 36 против 32 при жёстком отсечении без запаса).
    $строгоТут = $строгий !== []
        && ($строгий === ['*'] || in_array(explode('|', $метка)[0], $строгий, true));
    if ($строгоТут) {
        $свежие = array_values(array_filter($кандидаты, fn($c) => $c['бывший'] === 0));
        if (count($свежие) >= $k * 2) { $кандидаты = $свежие; }
    }

    // Потолок на донора внутри страницы: без него отбраковка почти-дублей
    // сама сводит выбор к одному донору — тому, чьё переписывание меньше похоже
    // на соседние. На замере это давало 20 % текста страницы из одного набора.
    $доноров = count(array_unique(array_filter(array_column($кандидаты, 'донор'))));
    $взято = array_sum($баланс);
    $потолокДонора = max(60, (int) ceil(($взято + $k * 20) / max(1, $доноров) * 1.4));
    // Потолок на прошлый набор: страница собирается примерно из сотни кусков,
    // и пять из них от одного старого комплекта — уже заметная общая часть.
    // Потолок мягкий: если выбора не осталось, второй проход берёт без разбора.
    $потолокНабора = 5;

    $итог = [];
    foreach ([false, true] as $безРазбора) {
        foreach ($кандидаты as $c) {
            if (count($итог) >= $k) { break 2; }
            $т = $c['x']['т'] ?? ($c['x']['в'] . ' ' . $c['x']['о']);
            if (in_array($c['x'], $итог, true)) { continue; }
            if (!$безРазбора) {
                if ($c['донор'] !== '' && ($баланс[$c['донор']] ?? 0) >= $потолокДонора) { continue; }
                $владелец = $журнал[$c['ключ']] ?? '';
                if ($владелец !== '' && $владелец !== $имяНабора
                    && ($балансНабора[$владелец] ?? 0) >= $потолокНабора) { continue; }
                $похож = false;
                foreach ($итог as $y) {
                    $ty = $y['т'] ?? ($y['в'] . ' ' . $y['о']);
                    // Одно начало режем только у фраз: пары FAQ почти все
                    // начинаются с «Как вывести» / «Можно ли», и страж на
                    // них оставлял страницу без половины вопросов.
                    if (v5Blizost($т, $ty) > $порогБлизости
                        || (isset($c['x']['т'], $y['т']) && v5OdnoNachalo($т, $ty))
                        // Один вопрос FAQ с разными ответами — «Можно ли играть
                        // бесплатно?» дважды на странице; близость по тексту
                        // пары этого не ловила, ответы разные.
                        || (isset($c['x']['в'], $y['в'])
                            && mb_strtolower(trim(strip_tags($c['x']['в']))) === mb_strtolower(trim(strip_tags($y['в']))))) { $похож = true; break; }
                }
                if ($похож) { continue; }
            }
            $прежний = $журнал[$c['ключ']] ?? '';
            if ($прежний !== '' && $прежний !== $имяНабора) {
                $балансНабора[$прежний] = ($балансНабора[$прежний] ?? 0) + 1;
            }
            $журнал[$c['ключ']] = $имяНабора;
            if ($c['донор'] !== '') {
                $слов = count(preg_split('~\s+~u', v5Text($т), -1, PREG_SPLIT_NO_EMPTY));
                $баланс[$c['донор']] = ($баланс[$c['донор']] ?? 0) + $слов;
            }
            $итог[] = $c['x'];
            if (str_contains($т, '{ДЖЕКПОТ}')) { $именаСтраницы['джекпот']++; }
            ['games' => $и, 'providers' => $с] = NicheLexicon::names(strip_tags($т));
            $именаСтраницы['игры'] = array_values(array_unique(array_merge($именаСтраницы['игры'], $и)));
            $именаСтраницы['студии'] = array_values(array_unique(array_merge($именаСтраницы['студии'], $с)));
        }
    }
    return $итог;
};

/** Абзац из предложений: первое — из открывающих, остальные — из середины. */
/**
 * $заполнить — необязательный поштучный заполнитель прорезей. Он нужен, чтобы
 * узел знал границу между фразами: сумма и ставка растут внутри одной фразы,
 * а на границе начинаются заново с уже названного значения.
 */
/** Абзац открывается вопросом. Считаем по тексту записи, а не по странице. */
function v5VoprosВЗачине(string $т): bool
{
    return (bool) preg_match('~^[^.!?]{5,110}\?~u', trim(strip_tags($т)));
}

$абзац = function (array $фразы, int $k, string $метка, ?callable $заполнить = null,
                   ?callable $хужеПерв = null, ?callable $поТемеФразы = null)
        use ($взять): string {
    if (!$фразы || $k < 1) { return ''; }
    $первые = array_values(array_filter($фразы, fn($x) => ($x['п'] ?? 0) === 1));
    $прочие = array_values(array_filter($фразы, fn($x) => ($x['п'] ?? 0) === 0));
    // Третий вопрос подряд запрещаем жёстко, а не предпочтением: в разделе,
    // где почти все первые фразы вопросительные, мягкая сортировка серию не
    // ломала. Отбор идёт по уже имеющемуся списку и лишних записей не тратит;
    // если чистых первых нет вовсе, зачин берём из пула середины.
    $открыть = $первые ?: $фразы;
    if ($хужеПерв !== null) {
        $чистые = array_values(array_filter($открыть, fn($x) => $хужеПерв($x) === 0));
        if (!$чистые) { $чистые = array_values(array_filter($прочие, fn($x) => $хужеПерв($x) === 0)); }
        if ($чистые) { $открыть = $чистые; }
    }
    $перваяЧасть = $взять($открыть, 1, $метка . '|перв');
    // Связность абзаца: продолжение — от того же донора, что и зачин, и по
    // теме раздела. Чтение пары «конкурент — наш» показало главное отличие
    // не в метриках, а в том, что у конкурента абзац держит одну мысль, а у
    // нас — коллаж независимых фраз. У донора в разделе 9–10 фраз, и абзац
    // в 3–4 фразы из одного источника набирается. Предпочтение мягкое — оно
    // уступает запрету профиля и очереди по журналу, как все остальные.
    $донорЗачина = (string) ($перваяЧасть[0]['д'] ?? '');
    // Герой уже открыл абзац — вторая фраза с «{ИМЯ} зашёл…» читается
    // второй историей про того же человека. Один донор в абзаце поднял
    // повтор героя с 4.0 до 5.8 на сто абзацев при донорских 4.1.
    $геройВЗачине = (bool) preg_match('~^\s*(?:<strong>)?\{ИМЯ~u', (string) ($перваяЧасть[0]['т'] ?? ''));
    $хужеСред = function (array $x) use ($донорЗачина, $поТемеФразы, $геройВЗачине): int {
        $ц = 0;
        if ($донорЗачина !== '' && (string) ($x['д'] ?? '') !== $донорЗачина) { $ц++; }
        if ($поТемеФразы !== null && !$поТемеФразы((string) ($x['т'] ?? ''))) { $ц++; }
        if ($геройВЗачине && preg_match('~^\s*(?:<strong>)?\{ИМЯ~u', (string) ($x['т'] ?? ''))) { $ц += 2; }
        return $ц;
    };
    $части = array_merge($перваяЧасть,
        $взять($прочие ?: $фразы, $k - 1, $метка . '|сред', 0.34, $хужеСред));
    $тексты = array_column($части, 'т');
    // Голое местоимение в начале абзаца остаётся без лица: «Он вывел…» без
    // названного героя выше. Замер: у нас 18.3 висячих местоимения на сто
    // страниц против 6.2 у доноров, а в пуле 321 фраза из 26 494 начинается
    // с «Он/Она/Его/Ему». Перестановка внутри уже взятого — она ничего не
    // тратит: прошлая попытка отсеивать с запасом сожгла лишние записи.
    if (count($тексты) > 1 && preg_match('~^\s*(?:<strong>)?(?:Он|Она|Его|Её|Ему|Ей)\b~u', $тексты[0])) {
        foreach ($тексты as $i => $t) {
            if ($i === 0) { continue; }
            if (!preg_match('~^\s*(?:<strong>)?(?:Он|Она|Его|Её|Ему|Ей)\b~u', $t)) {
                [$тексты[0], $тексты[$i]] = [$тексты[$i], $тексты[0]];
                break;
            }
        }
    }
    if ($заполнить !== null) { $тексты = array_map($заполнить, $тексты); }
    return trim(implode(' ', $тексты));
};

$медиана = function (array $v, int $поумолчанию): int {
    $v = array_values(array_filter($v, fn($x) => $x > 0));
    if (!$v) { return $поумолчанию; }
    sort($v);
    return (int) $v[intdiv(count($v), 2)];
};

// Сколько фраз в абзаце — розыгрыш из ДОНОРСКОГО распределения, а не медиана
// с шагом ±1. Медиана по разделам — 3 при среднем 3.9: у доноров 22 %
// абзацев-зачинов длиннее четырёх фраз (5:182, 6:146, 7:79, 8:30 на 1816),
// а «3 ± 1» не даёт ни одного длиннее четырёх. Отсюда абзац в 42 слова при
// донорских 48 и доля абзацев длиннее 60 слов 11 % против 19–26 % у четырёх
// корпусов. Сдвиг — характер набора (см. $темп): «многословный» набор берёт
// на фразу больше, «сухой» — меньше, но не ниже двух.
$фразИзРаспределения = function (array $длины, int $поумолчанию, int $сдвиг = 0) use (&$rng): int {
    $гист = [];
    foreach ($длины as $x) { if ($x > 0) { $гист[(string) (int) $x] = ($гист[(string) (int) $x] ?? 0) + 1; } }
    if (!$гист) { return max(2, $поумолчанию + $сдвиг); }
    // Хвост в 7–8 фраз (6 % донорских абзацев) режем до шести: абзац в 110
    // слов рядом с виджетным в 15 давал para_spread 21 при донорских 18 и
    // полевых 17 — самый частый промах приёмки, 26 из 28 выше цели.
    return max(2, min(6, (int) $rng->weighted($гист) + $сдвиг));
};

$контекст = function (array $локальные) use ($паспорт, $изБанка, $банки, &$rng): callable {
    $память = [];
    return function (string $ключ) use ($паспорт, $локальные, $изБанка, $банки, &$rng, &$память) {
        if (isset($паспорт['каталог'][$ключ])) { return $паспорт['каталог'][$ключ]; }
        if ($ключ === 'ВЕЙДЖЕР') { return $паспорт['вейджер']; }
        if (isset($локальные[$ключ])) { return $локальные[$ключ]; }
        // Виджет получает одного героя на заполнение — и одну сумму: вопрос
        // FAQ «выиграл 74к?» с ответом «итог — 3.2 млн» шёл из двух розыгрышей.
        if ($ключ === 'СУММА' || $ключ === 'СУММАМАЛ') {
            return $память['СУММА'] ??= $изБанка($ключ);
        }
        // Виджеты заполняются этим контекстом, а не узлом раздела, и до сих
        // пор {РУБЛИ} в них брались из всего банка, где 17 % сумм — от
        // миллиона. Ставка в ответе FAQ выходила «4 618 624 ₽». Ставочный ключ
        // (см. v5Zapolnit) здесь получает тот же слой 100–10 000, что и в узле.
        if ($ключ === 'РУБЛИ_СТАВКА') {
            $слой = array_values(array_filter(array_keys($банки['РУБЛИ'] ?? []),
                fn($x) => v5Rubli((string) $x) >= 100 && v5Rubli((string) $x) <= 10000));
            return $слой ? (string) $rng->pick($слой) : '';
        }
        return $изБанка($ключ);
    };
};

/** Пары «вопрос-ответ» внутри виджета меняются парой, разметка остаётся. */
$перебратьВиджет = function (string $html, string $тип) use (&$пулы, $взять): string {
    $замена = function (string $html, string $reВопрос, string $reОтвет, array $пары): string {
        $i = 0;
        $html = preg_replace_callback($reВопрос,
            function ($m) use (&$i, $пары) { $p = $пары[$i++] ?? null; return $p ? $m[1] . $p['в'] . $m[3] : $m[0]; },
            $html);
        $i = 0;
        return preg_replace_callback($reОтвет,
            function ($m) use (&$i, $пары) {
                $p = $пары[$i++] ?? null;
                if (!$p) { return $m[0]; }
                // Обёртка берётся у виджета: был <p> — ставим <p>, не было — нет.
                $о = str_starts_with(ltrim($m[2]), '<p>')
                    ? '<p>' . "\n            " . $p['о'] . "\n          " . '</p>'
                    : $p['о'];
                return $m[1] . $о . $m[3];
            },
            $html);
    };
    $faq = $пулы['хвосты'][$тип]['faq'] ?? [];
    if ($faq) {
        $нужно = preg_match_all('~<h3 class="faq-question" itemprop="name">~', $html);
        $пары = $взять($faq, $нужно, "$тип|faq");
        // Ответ короче 45 слов добирается второй записью. Ответы доноров —
        // 59 слов медианой, наш пул — 44, и рендер брал запись целиком без
        // усечения: коротким был сам источник. Вторая запись идёт без своих
        // ссылок: две ссылки на «информацию о казино» в одном ответе — лишнее.
        foreach ($пары as $i => $p) {
            // str_word_count кириллицу не считает — только preg_split.
            $слов = count(preg_split('~\s+~u', trim(strip_tags((string) $p['о'])), -1, PREG_SPLIT_NO_EMPTY));
            if ($слов >= 50) { continue; }
            // Добирается ОДНО предложение, а не запись целиком: целая запись
            // давала ответ в 70 слов при донорских 59 и тащила за собой лишние
            // «?» и опорные формулы — приёмка валила faq и anchors. Вопрос в
            // хвост не берём: ответ, кончающийся вопросом, — не ответ.
            // Добор — из записи с тем же предметом вопроса (общее слово от
            // пяти букв), и не с обрывка: «Она запускает серию вращений…»,
            // «Внутри самой игры — там…» продолжали чужой вопрос.
            $словаВопроса = [];
            foreach (preg_split('~[^\p{L}]+~u', mb_strtolower(strip_tags((string) $p['в']))) as $w) {
                if (mb_strlen($w) >= 5) { $словаВопроса[] = mb_substr($w, 0, 5); }
            }
            $поВопросу = function (array $x) use ($словаВопроса): int {
                $в = mb_strtolower(strip_tags((string) ($x['в'] ?? '')));
                foreach ($словаВопроса as $w) { if (mb_strpos($в, $w) !== false) { return 0; } }
                return 1;
            };
            $доп = $взять($faq, 1, "$тип|faq|добор", 0.34, $поВопросу);
            if ($доп && ($доп[0]['о'] ?? '') !== $p['о']) {
                $чист = preg_replace('~<a\b[^>]*>(.*?)</a>~s', '$1', (string) $доп[0]['о']);
                // До двух предложений, чтобы дотянуть до донорских 56–59 слов;
                // одно давало 47.
                $предл = preg_split('~(?<=[.!?])\s+~u', trim($чист), 3);
                $предл = array_values(array_filter($предл, fn($x) =>
                    !preg_match('~^\s*(?:<strong>)?(?:он|она|оно|они|это|там|тут|здесь|внутри|потом|затем|также|ещё|а|но|и|с|из|у)\b~ui', strip_tags($x))
                    && count(preg_split('~\s+~u', trim(strip_tags($x)), -1, PREG_SPLIT_NO_EMPTY)) >= 6));
                $хвост = trim(implode(' ', array_slice($предл, 0, $слов < 30 ? 2 : 1)));
                if ($хвост !== '' && !str_contains($хвост, '?')) { $пары[$i]['о'] = rtrim((string) $p['о']) . ' ' . $хвост; }
            }
        }
        $html = $замена($html,
            '~(<h3 class="faq-question" itemprop="name">\s*)(.*?)(\s*</h3>)~s',
            '~(<div itemprop="text">\s*)(.*?)(\s*</div>)~s',
            $пары);
    }
    // Блок review-quotes — это отзывы игроков в кавычках, а не методичка.
    // Пул «раскрывашки» собран с других виджетов (как считается рейтинг, что
    // проверять в лицензии): подставляя его сюда, генератор вычищал со
    // страницы все четыре донорские реплики разом. Отсюда speech 1 при цели 5
    // на всех наборах подряд и заголовок «Выплаты и верификация» над абзацем
    // о методике оценки. Цитаты берём из своего пула, старый — запасной.
    $цитаты = $пулы['хвосты'][$тип]['цитаты'] ?? [];
    $рас = $цитаты ?: ($пулы['хвосты'][$тип]['раскрывашки'] ?? []);
    if ($рас) {
        // Тематический блок «О портале» делит классы faq-question и
        // review-quote-text с блоком цитат, но метки в review-quote-summary
        // у него нет. Регулярка ответа была привязана только к классу, и
        // тела тематического блока подменялись цитатами при своих заголовках:
        // «Слоты и игры» над «Вывел за 20 минут, без вопросов». Считаем и
        // подменяем только реплики с меткой.
        $нужно = preg_match_all('~<span class="review-quote-summary">~', $html);
        // Метка лежит в <span class="review-quote-summary">, а не в голом
        // <span>: прежняя регулярка не совпадала ни разу, и все наборы несли
        // одни и те же четыре донорские метки дословно.
        $html = $замена($html,
            '~(<button class="faq-question"[^>]*>\s*<span class="review-quote-summary">\s*)(.*?)(\s*</span>)~s',
            '~(<span class="review-quote-summary">(?:(?!</article>).)*?<p class="review-quote-text">\s*)(.*?)(\s*</p>)~s',
            $взять($рас, $нужно, "$тип|" . ($цитаты ? 'цитаты' : 'раскрывашки')));
    }
    // Тематический блок («О портале», «Полезно знать о слотах»): пары
    // «заголовок в голом <span> — тело в review-quote-text». Пул раскрывашек
    // собран именно с него; без подмены тела блока шли донорским текстом
    // дословно на каждом наборе.
    $раскрывашки = $пулы['хвосты'][$тип]['раскрывашки'] ?? [];
    if ($раскрывашки) {
        $нужно = preg_match_all('~<button class="faq-question"[^>]*>\s*<span>~', $html);
        if ($нужно > 0) {
            $html = $замена($html,
                '~(<button class="faq-question"[^>]*>\s*<span>\s*)(.*?)(\s*</span>)~s',
                '~(<button class="faq-question"[^>]*>\s*<span>(?:(?!</article>).)*?<p class="review-quote-text">\s*)(.*?)(\s*</p>)~s',
                $взять($раскрывашки, $нужно, "$тип|раскрывашки"));
        }
    }
    return $html;
};

