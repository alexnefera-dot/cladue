 * у доноров медиана 0 везде, на slots — до 10 игр и 9 студий; у конкурента B
 * 11.5 игр и 4 студии на slots и ноль на остальных. Цель набора разыграна
 * в той же полосе, что и в приёмке; запас в одно имя — коридор ±2. Запись
 * сверх бюджета не выбрасывается, а уходит в конец очереди, как нарушители
