                            || preg_match('~на балансе|на счету|на счёте|на счёт\b|на карту|на карте|вывел|снял|забрал|поднял|вытащил|итог|в плюсе|куш|получил|поднять|вытащить|снять|забрать|вывести|выиграть|сорвать~ui', strip_tags((string) ($x['т'] ?? '')))))
