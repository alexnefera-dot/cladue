const V5_CTA_RE = '~\b(зарегистрируйся|играй|жми|получи|забери|активируй|скачай|попробуй|переходи|успей)\b~ui';
const V5_SPEECH_RE = '~[«"][^«»"]{25,}[»"]~u';
const V5_NE_IMPER = ['сайте','интернете','комитете','пакете','кабинете','билете','буфете',
    'сюжете','бюджете','этикете','хотите','предмете','декрете','портрете','секрете',
    'браслете','планете','жилете','манжете','пикете','лете','свете','цвете'];

function v5EstImperativ(string $текст): bool
{
    preg_match_all('/\b[\p{L}]+(?:йте|ите|ьте)\b/u', mb_strtolower(strip_tags($текст)), $m);
    foreach ($m[0] as $w) { if (!in_array($w, V5_NE_IMPER, true)) { return true; } }
    return false;
}

