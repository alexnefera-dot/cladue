declare(strict_types=1);

/**
 * Каталог приёмов: чем текст действует на читателя.
 *
 *   php priyomy.php <дир|подпись> <дир|подпись> ...      — матрица приёмов
 *   php priyomy.php --primery=<приём> <дир|подпись> ...  — примеры фраз
 *
 * Это не замер качества: приёмы считаются по формулировкам, и цифра говорит
 * лишь «сколько раз текст так делает». Плотность даётся на 1000 слов, иначе
 * длинные страницы всегда выигрывают.
 *
 * Каждый приём — это ход по отношению к читателю, а не стилистическая черта:
 * ограничить собственное обещание, показать процедуру, назвать невыгодный
 * себе случай, поставить историю с именем и суммой.
 */

require_once __DIR__ . '/src/PersonNames.php';

const PRIYOMY = [
    'ограничение обещания' => [
        '~(не гарант\w+|не значит,? что|не волшебн\w+|вряд ли|не стоит ждать|важно понимать|на самом деле|в действительности|не панаце\w+|не защища\w+ от|но есть нюанс|с оговорк\w+|это не\s+\w+, а)~ui',
        'текст сам сбивает ожидания, которые только что создал',
    ],
    'ход против себя' => [
        '~(не в пользу игрока|нам отказал\w*|мы отказал\w*|решение было не|спор проигр\w+|признаём\w*|наша ошибка|мы ошиб\w+|невыгодн\w+ (?:нам|случа\w+)|чего мы не (?:делаем|просим)|никогда не прос\w+)~ui',
        'публикация случая, невыгодного самой площадке',
    ],
    'процедура на глазах' => [
        '~\b(нажима\w+|ввожу|вводит\w+|открыва\w+ раздел|захожу|жму|проверя\w+ вручную|заполня\w+|загружа\w+ документ|шаг \d|сначала\b|затем\b|после этого)~ui',
        'автор проходит действие при читателе, а не пересказывает его',
    ],
    'история с именем' => [
        null,   // считается отдельно: имя и рядом сумма
        'микро-кейс: человек, вечер, ставка, сумма, срок',
    ],
    'обращение к страху' => [
        '~(боишься|боитесь|кинут|разво[дя]\w*|обман\w+|не потеря\w+|страшно|подвох|ловушк\w+|наду\w+)~ui',
        'текст называет страх читателя прежде, чем предложить решение',
    ],
    'бытовое сравнение' => [
        '~(представь\w*|это как\b|словно\b|похоже на\b|тот же принцип|устроен\w* так же|как в\s+\w+е\b)~ui',
        'механика объясняется через предмет из быта',
    ],
    'вопрос читателю' => [
        '~[а-яё][^.!?<>]{10,}\?~ui',
        'прямой вопрос в теле текста, а не в заголовке',
    ],
    'прямая речь' => [
        '~[«"][^«»"]{15,}[»"]\s*[,—-]|—\s*(?:сказал|говорит|признаётся|пишет)~ui',
        'реплика игрока или сотрудника в кавычках',
    ],
    'авторский блок' => [
        '~(материал подготов\w+|автор\w*:|проверил\w*\s+\w+|стаж|лет в (?:нише|индустрии)|редакци\w+ проверил\w*|независим\w+ от)~ui',
        'подпись, стаж, дисклеймер — заявка на экспертизу',
    ],
    'сравнение с конкурентом' => [
        '~(в отличие от|по сравнению с|у других площадок|где-то ещё|на фоне остальных|конкурент\w+)~ui',
        'площадка описывается через отличие от других',
    ],
];

$OUT_PRIMERY = '';
$COLS = [];
foreach (array_slice($argv, 1) as $a) {
    if (preg_match('~^--primery=(.*)$~u', $a, $m)) { $OUT_PRIMERY = $m[1]; continue; }
    [$dir, $label] = array_pad(explode('|', $a, 2), 2, '');
    if (!is_dir($dir)) { fwrite(STDERR, "нет папки: $dir\n"); exit(1); }
    $COLS[] = ['dir' => rtrim($dir, '/'), 'label' => $label !== '' ? $label : basename($dir)];
}
if (!$COLS) { fwrite(STDERR, "usage: priyomy.php [--primery=<приём>] <dir|label>…\n"); exit(1); }

/** текст страницы без служебных блоков */
function plain(string $file): string
{
    $raw = (string) file_get_contents($file);
    $raw = preg_replace('~<(script|style)\b.*?</\1>~is', ' ', $raw);
    return trim(preg_replace('~\s+~u', ' ', strip_tags($raw)));
}

/** история с именем: имя и денежная сумма в одном предложении */
function stories(string $text): int
{
    $n = 0;
    foreach (preg_split('~(?<=[.!?])\s+~u', $text) as $s) {
        if (PersonNames::count($s) > 0 && preg_match('~\d[\d\s]*\s*(?:₽|руб)~ui', $s)) { $n++; }
    }
    return $n;
}

if ($OUT_PRIMERY !== '') {
    $re = PRIYOMY[$OUT_PRIMERY][0] ?? null;
    if ($re === null) { fwrite(STDERR, "приём «{$OUT_PRIMERY}» не ищется примерами\n"); exit(1); }
    foreach ($COLS as $c) {
        printf("\n===== %s\n", $c['label']);
        $shown = 0;
        foreach (glob("{$c['dir']}/*.html") as $f) {
            foreach (preg_split('~(?<=[.!?])\s+~u', plain($f)) as $s) {
                if ($shown >= 4) { break 2; }
                if (mb_strlen($s) > 30 && mb_strlen($s) < 320 && preg_match($re, $s)) {
                    printf("  · %s\n", $s); $shown++;
                }
            }
        }
    }
    exit(0);
}

printf("%-24s", 'приём / на 1000 слов');
foreach ($COLS as $c) { printf("%9s", mb_substr($c['label'], 0, 8)); }
echo "\n";
$data = [];
foreach ($COLS as $i => $c) {
    $text = '';
    foreach (glob("{$c['dir']}/*.html") as $f) { $text .= ' ' . plain($f); }
    $w = max(1, count(preg_split('~\s+~u', trim($text), -1, PREG_SPLIT_NO_EMPTY)));
    foreach (PRIYOMY as $name => [$re, $_]) {
        $n = $re === null ? stories($text) : preg_match_all($re, $text);
        $data[$name][$i] = round($n / $w * 1000, 1);
    }
}
foreach ($data as $name => $vals) {
    printf("%-24s", $name);
    foreach ($vals as $v) { printf("%9.1f", $v); }
    echo "\n";
}
