<?php
declare(strict_types=1);

/**
 * Ритм фраз. У A 8 % предложений в три слова и короче (2–15 % по сайтам с
 * миром), у нас 1–2 %. Замер по восьми сайтам A: четверть коротких — вопрос
 * с ответом («Красивая история? Да.», «Повезло? Да.», «Мог проиграть? Легко.»),
 * остальное — рубленый вердикт: «Можно выиграть. Можно проиграть.», «Гарантий
 * нет.», «Так бывает.», «Без магии. Без сказок.». Слой делает то же с нашим
 * текстом: режет штамп на два предложения, ставит вопрос-ответ после исхода
 * истории, разбивает «без X, без Y» и короткий зачин перед двоеточием, а
 * остаток добирает вердиктом в конце абзаца без героя — до цели доли, которая
 * разыграна от сида в полосе A.
 */
function v5DolyaKorotkih(string $html): float
{
    $проза = preg_replace('~<section\b.*?</section>~su', ' ', $html) ?? $html;
    preg_match_all('~<p\b[^>]*>(.*?)</p>~su', $проза, $m);
    $всего = 0; $коротких = 0;
    foreach ($m[1] as $x) {
        $т = trim(preg_replace('~\s+~u', ' ', strip_tags($x)) ?? '');
        if (mb_strlen($т) < 40) { continue; }
        foreach (preg_split('~(?<=[.!?…])\s+~u', $т) ?: [] as $s) {
            $n = count(preg_split('~\s+~u', trim($s), -1, PREG_SPLIT_NO_EMPTY));
            if ($n === 0) { continue; }
            $всего++;
            if ($n <= 3) { $коротких++; }
        }
    }
    return $всего ? 100.0 * $коротких / $всего : 0.0;
}

function v5RitmFraz(string $html, int $сид, string $тип, array $герои, float $цель, ?float $бюджетВопросов = null): string
{
    $хватит = function () use (&$html, $цель): bool { return v5DolyaKorotkih($html) >= $цель; };
    $заглавная = fn(string $s): string => mb_strtoupper(mb_substr($s, 0, 1)) . mb_substr($s, 1);
    $именаОсновы = [];
    foreach (array_merge($герои['м'] ?? [], $герои['ж'] ?? []) as $имя) {
        $имя = trim((string) $имя);
        if (mb_strlen($имя) >= 4) { $именаОсновы[] = preg_quote(mb_substr($имя, 0, mb_strlen($имя) - 1), '~'); }
    }
    $геройРег = $именаОсновы === [] ? null : '~(?<![а-яё])(?:' . implode('|', $именаОсновы) . ')[а-яё]{0,3}(?![а-яё])~u';
    $этоГерой = fn(string $т): bool => $геройРег !== null && (bool) preg_match($геройРег, strip_tags($т));
    $счётчик = 0;
    $вариант = function (array $список, string $ключ) use ($сид, $тип, &$счётчик): string {
        return $список[(crc32($ключ . '|' . $сид . '|' . $тип) + $счётчик++) % count($список)];
    };
    // Правки идут только по абзацам вне виджетов.
    $поАбзацам = function (callable $f) use (&$html): void {
        $куски = preg_split('~(<section\b.*?</section>)~su', $html, -1, PREG_SPLIT_DELIM_CAPTURE);
        foreach ($куски as $k => $кусок) {
            if ($k % 2 === 1) { continue; }
            $куски[$k] = (string) preg_replace_callback('~(<p\b[^>]*>)(.*?)(</p>)~su', fn($m) => $m[1] . $f($m[2]) . $m[3], $кусок);
        }
        $html = implode('', $куски);
    };

    // 1. «Можно выиграть, можно проиграть — гарантий нет» → три предложения. Так у A
    //    чаще всего: «Можно выиграть.», «Можно проиграть.», «Гарантий нет.» — три из
    //    десяти самых частых коротких фраз.
    $поАбзацам(function (string $т) use ($заглавная): string {
        return (string) preg_replace_callback('~(?<![а-яё])(можно\s+выиграть),?\s+(?:а\s+)?(можно\s+(?:и\s+)?проиграть)(?:\s*[—–,:-]\s*(гарантий\s+(?:здесь\s+|тут\s+)?нет|никто\s+ничего\s+не\s+обещает))?(?![а-яё])~ui',
            function ($m) use ($заглавная) {
                $итог = $m[1] . '. ' . $заглавная($m[2]) . '.';
                if (($m[3] ?? '') !== '') { $итог .= ' ' . $заглавная($m[3]) . '.'; }
                return $итог;
            }, $т);
    });
    // Точка после «проиграть.» уже стоит, лишний знак — убрать: «проиграть.,» «проиграть..».
    // Хвосты после разреза: «Гарантий нет.</strong>.» → одна точка; «Можно проиграть. — честно» и
    // «Гарантий нет. и если нужны…» → следующее предложение с заглавной.
    $html = (string) preg_replace('~(Можно проиграть\.|Гарантий (?:тут |здесь )?нет\.|Никто ничего не обещает\.)(\s*(?:</strong>|</em>)?)\s*[.,;:]~u', '$1$2', $html);
    $html = (string) preg_replace_callback('~(Можно проиграть\.|Гарантий (?:тут |здесь )?нет\.|Никто ничего не обещает\.)((?:\s*</strong>)?)\s*(?:[—–-]\s*)?([а-яё])~u',
        fn($m) => $m[1] . $m[2] . ' ' . mb_strtoupper($m[3]), $html);

    // 2. Вопрос-ответ после исхода истории героя: «Повезло? Да.» — один на страницу:
    //    каждый вопрос считается полями faq и questions_total, три на страницу
    //    выводили их за полосу и валили восемь страниц из двенадцати.
    // Вопрос стоит места в полях faq и questions_total: если на странице вопросов
    // уже не меньше цели набора, вопрос-ответ не ставится (иначе +1 выводил
    // registracia, app, bonus и zerkalo за допуск, 70 сидов без приёмки).
    $вопросовСейчас = preg_match_all('~\?~u', strip_tags(preg_replace('~<section\b.*?</section>~su', ' ', $html) ?? $html));
    $вопросМожно = $бюджетВопросов === null || $вопросовСейчас < $бюджетВопросов - 1;
    if (!$хватит() && $вопросМожно) {
        $пары = ['Повезло? Да.', 'Красивая история? Да.', 'Повторяемо? Нет.', 'Гарантированно? Нет.', 'Мог проиграть? Легко.', 'Типично? Нет.', 'Честно? Да.'];
        $сделано = 0;
        $поАбзацам(function (string $т) use (&$сделано, $этоГерой, $пары, $вариант): string {
            if ($сделано >= 1 || !$этоГерой($т) || preg_match('~\?\s*(?:Да|Нет|Легко)\.~u', strip_tags($т))) { return $т; }
            // Предложение с исходом: сумма и глагол результата.
            $новый = (string) preg_replace_callback('~([^.!?]*?(?:вывел|вывела|снял|сняла|забрал|забрала|поднял|подняла|вытащил|вытащила|сорвал|сорвала|выиграл|выиграла|унёс|вынес|на балансе|на счету)[^.!?]*\d[^.!?]*[.!])(\s+)~u',
                function ($m) use (&$сделано, $пары, $вариант) {
                    if ($сделано >= 1) { return $m[0]; }
                    $сделано++;
                    return $m[1] . ' ' . $вариант($пары, 'вопрос-ответ') . $m[2];
                }, $т, 1);
            return $новый;
        });
    }

    // 3. «Без магии, без гарантий» → «Без магии. Без гарантий.»
    if (!$хватит()) {
        $поАбзацам(function (string $т) use ($заглавная): string {
            return (string) preg_replace_callback('~(?<=^|[.!?…]\s|>\s)(Без\s+[а-яё]+(?:\s+[а-яё]+)?),\s+(без\s+[а-яё]+(?:\s+[а-яё]+)?)(?=\s*[.,—–:-])~u',
                fn($m) => $m[1] . '. ' . $заглавная($m[2]), $т);
        });
        $html = (string) preg_replace_callback('~(Без [а-яё]+(?: [а-яё]+)?\. Без [а-яё]+(?: [а-яё]+)?)\s*[,—–:-]\s*([а-яё])~u', fn($m) => $m[1] . '. ' . mb_strtoupper($m[2]), $html);
    }

    // 4. Короткий зачин перед двоеточием: «Разгадка обычная: слот отдал…» → «Разгадка обычная. Слот отдал…»
    if (!$хватит()) {
        $поАбзацам(function (string $т) use ($заглавная): string {
            return (string) preg_replace_callback('~(?<=^|[.!?…]\s)([А-ЯЁ][а-яё]+\s+[а-яё]+(?:\s+[а-яё]+)?):\s+([а-яё])~u',
                // «По механике: выпали символы» — зачин с предлога после точки не живёт («По механике.»).
                fn($m) => preg_match('~^(?:Плюс|Минус|Факт|Лайфхак|Итог|Совет|Важно|Вывод|Пример|Например|По|В|Во|На|С|Со|Для|От|К|Ко|У|Из|При|Про|Без|До|За|Под|Над|О|Об|Из-за)\b~u', $m[1]) ? $m[0] : $m[1] . '. ' . mb_strtoupper($m[2]), $т);
        });
    }

    // 5. Вердикт в конце абзаца без героя — до цели, не больше шести.
    if (!$хватит()) {
        $вердикты = ['Так бывает.', 'Это честно.', 'Без сказок.', 'Без магии.', 'Всё.', 'Это казино.'];
        $сделано = 0; $осталось = (int) ceil(max(0.0, $цель - v5DolyaKorotkih($html)));
        $поАбзацам(function (string $т) use (&$сделано, $осталось, $этоГерой, $вердикты, $вариант): string {
            if ($сделано >= min(6, $осталось + 2) || $этоГерой($т) || mb_strlen(strip_tags($т)) < 250) { return $т; }
            if (!preg_match('~[.!]\s*(?:</strong>)?\s*$~u', rtrim($т))) { return $т; }
            $сделано++;
            return rtrim($т) . ' ' . $вариант($вердикты, 'вердикт');
        });
    }
    return $html;
}
