    /** Множители: закрывают накопленное и уводят его в разряд выше. */
    private const MNOZHITELI = [
        'тысяча' => 1000, 'тысячи' => 1000, 'тысяч' => 1000, 'тысяче' => 1000,
        'тысячу' => 1000, 'тысячей' => 1000, 'тысячами' => 1000,
        'миллион' => 1000000, 'миллиона' => 1000000, 'миллионов' => 1000000,
        'миллиону' => 1000000, 'миллионом' => 1000000,
    ];

    /** «Полчаса» и «полминуты» — половина следующей единицы, не числительное. */
    private const POLOVINY = [
        'полчаса' => [0.5, 'час'], 'получаса' => [0.5, 'час'],
        'полминуты' => [0.5, 'минута'], 'полгода' => [0.5, 'год'],
        'полсуток' => [0.5, 'сутки'],
    ];

    /** Регулярка на цепочку числительных прописью, без якорей. */
    public static function shablon(): string
    {
        $slova = array_merge(
            array_keys(self::SLOVA),
            array_keys(self::MNOZHITELI),
            ['половиной', 'с']
        );
        usort($slova, static fn(string $a, string $b) => mb_strlen($b) <=> mb_strlen($a));
        $alt = implode('|', array_map('preg_quote', $slova));
        // Границы обязательны: без них «семь» находится внутри «Восемь»,
        // «сто» — внутри «стол», «два» — внутри «двадцать».
        return '(?<![\p{L}])(?:' . $alt . ')(?:[\s\x{00A0}]+(?:' . $alt . '))*(?![\p{L}])';
    }

    /** Цифровая запись: «6 200», «93,4», «1 900». */
    public static function shablonCifr(): string
    {
        return '\d{1,3}(?:[\s\x{00A0}]\d{3})+|\d+(?:[.,]\d+)?';
    }

    /** Разбирает цепочку слов в число. Возвращает null, если это не число. */
    public static function razobrat(string $fraza): ?float
    {
        $slova = preg_split('~[\s\x{00A0}]+~u', mb_strtolower(trim($fraza))) ?: [];
        $itog = 0.0;
        $tek = 0.0;
        $bylo = false;
        foreach ($slova as $w) {
            if ($w === 'с') { continue; }
            if ($w === 'половиной') { $tek += 0.5; continue; }
            if (isset(self::MNOZHITELI[$w])) {
                $itog += ($tek ?: 1.0) * self::MNOZHITELI[$w];
                $tek = 0.0;
                $bylo = true;
                continue;
            }
            if (!isset(self::SLOVA[$w])) { return null; }
            $tek += self::SLOVA[$w];
            $bylo = true;
        }
        return $bylo ? $itog + $tek : null;
    }

    /** Разбирает цифровую запись: пробелы-разряды прочь, запятая в точку. */
    public static function razobratCifry(string $s): float
    {
        return (float) str_replace(',', '.', preg_replace('~[\s\x{00A0}]~u', '', $s) ?? '');
    }

    /** @return array{0:float,1:string}|null «полчаса» → [0.5, 'час'] */
    public static function polovina(string $slovo): ?array
    {
        return self::POLOVINY[mb_strtolower($slovo)] ?? null;
    }

    /** Слова-половинки для регулярки. */
    public static function shablonPolovin(): string
    {
        return implode('|', array_keys(self::POLOVINY));
    }
