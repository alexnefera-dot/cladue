<?php
declare(strict_types=1);

/**
 * Слои страницы: узнать и снять.
 *
 * Страница образца собрана из семи слоёв, и пять из них механика, одинаковая у
 * всех комплектов по замыслу (engine/sloi-v6.php). Мерить по ним текст нельзя:
 *
 *   — ШИНГЛЫ. Собранный корпус даёт 1,67 % пар выше порога против 0,02 % у
 *     написанного. Это не потеря уникальности, а общая обвязка, которую видит
 *     счётчик: у образца ровно та же картина, 1,71 %.
 *   — СОГЛАСОВАНИЕ. Слоганы шапки и подвала — словесная россыпь вроде «Путь к
 *     процветанию Модуль мечты 9544 Игровых автоматов 97 RTP %». Проверка
 *     грамматической связности на них сорвётся вся и по делу.
 *   — СКВОЗНЫЕ ФАКТЫ. В карточках витрины стоят RTP и годы, к своду комплекта
 *     отношения не имеющие.
 *
 * Поэтому приёмка меряет поля, разметку и граф по СОБРАННОЙ странице — её и
 * получает читатель, — а текстовые проверки по СНЯТОЙ.
 */
final class Sloi
{
    /**
     * Признак собранной страницы — строка подвала, а не абзац в начале.
     *
     * Первым признаком стояло «страница начинается с <p>», и это оказалось
     * неверно: у нас так начинаются 155 написанных страниц из 462 — главная
     * открывается лидом, а внутренние сценой. Снятие срабатывало на них и
     * срезало по восемьсот знаков, а приёмка потом мерила уникальность по
     * обрубку. Строка подвала однозначна: её кладёт только сборщик, и в
     * написанном корпусе она не встречается ни разу.
     */
    public const METKA = '<p>Последнее обновление';

    public static function est(string $html): bool
    {
        return mb_strpos($html, self::METKA) !== false;
    }

    /** Вернуть написанное: слой 4 (тема) и слой 6 (FAQ) без механики. */
    public static function snyat(string $html): string
    {
        if (!self::est($html)) { return $html; }

        // Слои 1–3 режем по концу третьего, а не по второму H2: у главной между
        // слоганом и первым своим H2 стоит лид — абзац, перечень и таблица.
        if (preg_match('~<h2[^>]*>.*?</h2>\s*<p\b[^>]*>.*?</p>\s*~is', $html, $m, PREG_OFFSET_CAPTURE)
            && $m[0][1] < 600) {
            $html = substr($html, $m[0][1] + strlen($m[0][0]));
        }
        // Слой 5 — H2 с эмодзи и всё до следующего H2.
        $html = preg_replace(
            '~<h2[^>]*>\s*[\x{1F300}-\x{1FAFF}\x{2600}-\x{27BF}\x{2B00}-\x{2BFF}\x{FE0F}].*?(?=<h2|$)~us',
            '', $html
        ) ?? $html;
        // Слой 7 — от строки с датой до конца.
        $p = mb_strpos($html, self::METKA);
        if ($p !== false) { $html = mb_substr($html, 0, $p); }

        return rtrim($html) . "\n";
    }

    /** @param array<string,string> $stranicy @return array<string,string> */
    public static function snyat_vse(array $stranicy): array
    {
        return array_map(static fn(string $h) => self::snyat($h), $stranicy);
    }
}
