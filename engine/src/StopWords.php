    /** @return array<string,true> */
    public static function set(): array
    {
        if (self::$set === null) {
            self::$set = [];
            foreach (self::WORDS as $w) {
                self::$set[$w] = true;
            }
        }
        return self::$set;
    }

    public static function is(string $word): bool
    {
        return isset(self::set()[$word]);
    }
}
