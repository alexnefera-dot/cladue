<?php
declare(strict_types=1);

/**
 * Грамматические срывы, которых не видит ни одна числовая мера.
 *
 * Появился после сплошного чтения корпуса. Страница `gravernaya-1/slots`
 * прошла обе приёмки и лежала в сдаче с такими фразами:
 *
 *   «Считается ли самоходный манера в отыгрыш бонуса?»
 *   «Почти наверняка началась премиальная бонусный этап с выбором»
 *   «счёт оставшихся оставшихся кругов сбрасывается»
 *
 * Все три — след слепой замены синонимов: правка шла по словам, а
 * согласование за ней не пошло. Тошнота и шинглы при этом упали, то есть
 * меры показывали улучшение ровно там, где текст разваливался.
 *
 * Здесь важна ТОЧНОСТЬ, а не полнота. Полный разбор согласования без
 * морфологии невозможен, а приёмка, которая кричит на живой текст, будет
 * отключена в первый же день. Первая версия правил ловила 276 «срывов» в
 * нашем корпусе и 7782 у конкурентов — то есть ловила сравнительную степень
 * («свежее суток»), деепричастия («проверяя каждый»), творительный падеж
 * («точкой входа») и глаголы («какая имеет»). Все неоднозначные окончания
 * убраны: -ой и -ее не проверяются вовсе, второе слово обязано не быть
 * глаголом. Порог качества правила — ноль срабатываний на 350 чужих
 * страницах, написанных людьми.
 */
final class Soglasovanie
{
    /** Повторы, которые в русском законны. */
    private const POVTOR_MOZHNO = [
        'еле', 'чуть', 'едва', 'так', 'вот', 'уже', 'всё', 'все', 'ещё', 'бы', 'что',
    ];

    /**
     * Окончания прилагательного в именительном единственном — только
     * однозначные. -ой отброшен: «большой» и «большой ставкой» по букве не
     * различить. -ее отброшено: это ещё и сравнительная степень («быстрее»)
     * и наречие («заранее»). -яя отброшено: так же оканчиваются
     * деепричастия («проверяя»). -ий отброшено: так выглядит родительный
     * множественного у среднего и женского рода — «условий», «требований»,
     * «транзакций», и каждое такое слово давало ложный срыв.
     */
    private const OKONCHANIYA = [
        'м' => ['ый'],
        'ж' => ['ая'],
        'с' => ['ое'],
    ];

    /** Слова на -ый/-ий/-ая/-ое, которые прилагательными не являются. */
    private const NE_PRILAGATELNOE = [
        'критерий', 'сценарий', 'комментарий', 'репозиторий', 'санаторий',
        'планетарий', 'гербарий', 'семинарий', 'солярий', 'жребий', 'гений',
        'который', 'которая', 'которое', 'которые', 'третий', 'третья',
        'вдвое', 'втрое', 'вчетверо', 'заодно', 'иначе', 'наравне',
        'надвое', 'втройне', 'вдвойне', 'двое', 'трое', 'четверо', 'пятеро',
        'шестеро', 'семеро', 'вкратце', 'вполне', 'наполовину',
    ];

    /** Деепричастия на -ая: по концу слова от прилагательных не отличаются. */
    private const DEEPRICHASTIYA = [
        'читая', 'считая', 'зная', 'называя', 'оставляя', 'начиная', 'меняя',
        'теряя', 'выбирая', 'открывая', 'закрывая', 'проверяя', 'играя',
        'делая', 'полагая', 'предлагая', 'подставляя', 'сравнивая', 'собирая',
        'принимая', 'снимая', 'занимая', 'понимая', 'вычитая', 'листая',
        'включая', 'исключая', 'отдавая', 'спустя', 'обеспечивая', 'создавая',
        'учитывая', 'ограничивая', 'вытягивая', 'подозревая', 'приглашая',
        'повышая', 'понижая', 'сохраняя', 'теряя', 'получая', 'отправляя',
    ];

    /** Существительные среднего и мужского рода с «женским» концом. */
    private const ROD_ISKLYUCHENIYA = [
        'время' => 'с', 'имя' => 'с', 'знамя' => 'с', 'племя' => 'с',
        'семя' => 'с', 'стремя' => 'с', 'бремя' => 'с', 'темя' => 'с',
        'пламя' => 'с', 'вымя' => 'с',
        'папа' => 'м', 'дядя' => 'м', 'коллега' => 'м', 'судья' => 'м',
        'староста' => 'м', 'юноша' => 'м', 'дедушка' => 'м', 'мужчина' => 'м',
    ];

    /**
     * @return list<array{вид:string,текст:string,где:string}>
     */
    public static function proverit(string $html): array
    {
        $sryvy = [];
        foreach (self::uzly($html) as [$uzel, $gde]) {
            foreach (self::frazy($uzel) as $fraza) {
                $slova = preg_split('~\s+~u', trim($fraza), -1, PREG_SPLIT_NO_EMPTY) ?: [];
                $n = count($slova);
                for ($i = 0; $i + 1 < $n; $i++) {
                    $a = self::chisto($slova[$i]);
                    $b = self::chisto($slova[$i + 1]);
                    if ($a === '' || $b === '') { continue; }

                    if (self::udvoenie($a, $b)) {
                        $sryvy[] = ['вид' => 'удвоение', 'текст' => "$a $b", 'где' => $gde];
                        continue;
                    }
                    $rodA = self::rodPrilagatelnogo($a);
                    if ($rodA === null) { continue; }

                    // Два прилагательных подряд с разным родом — почти всегда
                    // след правки: «заказанная бонусный этап».
                    $rodB = self::rodPrilagatelnogo($b);
                    if ($rodB !== null) {
                        if ($rodB !== $rodA) {
                            $sryvy[] = ['вид' => 'род', 'текст' => "$a $b", 'где' => $gde];
                        }
                        continue;
                    }
                    // Прилагательное мужского рода и следом слово на «-а»:
                    // «самоходный манера». Шире эту проверку вести нельзя.
                    // Любое существительное в косвенном падеже после
                    // прилагательного среднего или женского рода выглядит
                    // рассогласованием — «введённое глазом», «содержимое
                    // страниц», — а это правильная речь. Сузили до одной
                    // пары, где ошибка однозначна.
                    if ($rodA === 'м' && self::zhenskoeNaA($b)) {
                        $sryvy[] = ['вид' => 'род', 'текст' => "$a $b", 'где' => $gde];
                    }
                }
            }
        }
        // Один и тот же срыв в шапке таблицы или в повторяющейся строке
        // не надо показывать десять раз.
        $uniq = [];
        foreach ($sryvy as $s) { $uniq[$s['вид'] . '|' . $s['текст']] = $s; }
        return array_values($uniq);
    }

    /** Текстовые узлы вместе с именем тега: соседние ячейки — не одна фраза. */
    private static function uzly(string $html): array
    {
        $out = [];
        if (!preg_match_all('~(?is)<(h2|h3|p|li|td|th|summary|blockquote)[^>]*>(.*?)</\1>~', $html, $m, PREG_SET_ORDER)) {
            return $out;
        }
        foreach ($m as $x) {
            $t = html_entity_decode(strip_tags($x[2]), ENT_QUOTES, 'UTF-8');
            $t = trim((string) preg_replace('~\s+~u', ' ', $t));
            // Битая разметка (незакрытая ячейка, вложенный <td>) склеивает
            // полстраницы в один «узел», и тогда соседями оказываются слова
            // из разных предложений. Живой абзац столько не весит.
            if ($t !== '' && mb_strlen($t) <= 1200) { $out[] = [$t, mb_strtolower($x[1])]; }
        }
        return $out;
    }

    /** Внутри узла режем по знакам: через запятую пара слов не соседи. */
    private static function frazy(string $t): array
    {
        return preg_split('~[^\p{L}\p{N}\s%-]+~u', $t, -1, PREG_SPLIT_NO_EMPTY) ?: [];
    }

    private static function chisto(string $w): string
    {
        $w = preg_replace('~[^\p{L}-]~u', '', $w);
        return mb_strtolower(str_replace('ё', 'е', (string) $w));
    }

    private static function udvoenie(string $a, string $b): bool
    {
        return $a === $b
            && mb_strlen($a) >= 3
            && !in_array($a, self::POVTOR_MOZHNO, true);
    }

    /** Род прилагательного в именительном единственном или null. */
    private static function rodPrilagatelnogo(string $w): ?string
    {
        if (mb_strlen($w) < 6) { return null; }
        if (in_array($w, self::NE_PRILAGATELNOE, true)) { return null; }
        if (in_array($w, self::DEEPRICHASTIYA, true)) { return null; }
        if (isset(self::ROD_ISKLYUCHENIYA[$w])) { return null; }
        foreach (self::OKONCHANIYA as $rod => $konec) {
            foreach ($konec as $k) {
                if (str_ends_with($w, $k)) { return $rod; }
            }
        }
        return null;
    }

    /** Личная форма глагола или причастие — родовой сверке не подлежит. */
    private static function glagol(string $w): bool
    {
        return (bool) preg_match(
            '~(ет|ёт|ит|ут|ют|ат|ят|ешь|ишь|ем|им|ете|ите|ал|ял|ил|ел|ло|ла|ли|ся|сь|ть|чь)$~u',
            $w
        );
    }

    /**
     * Слово на «-а», которое после прилагательного мужского рода может быть
     * только существительным женского рода. «-я» сюда не берём: так
     * оканчиваются деепричастия, а их полного списка нет.
     */
    private static function zhenskoeNaA(string $w): bool
    {
        if (mb_strlen($w) < 5 || !str_ends_with($w, 'а')) { return false; }
        if (isset(self::ROD_ISKLYUCHENIYA[$w])) { return false; }
        return !self::glagol($w);
    }
}
