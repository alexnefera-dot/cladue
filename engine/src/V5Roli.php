/**
 * Роли фраз и планы абзацев.
 *
 * Донорский раздел — это не набор фраз, а ход мысли: история героя (вход →
 * событие → исход → оговорка), потом математика с честным ответом, потом
 * оффер с оговоркой и практика, список из разных аргументов, финал с
 * возвратом к герою. Сборка по фразам это ломала: «Потому что» указывало в
 * пустоту, три пункта списка говорили об одном, история героя обрывалась
 * на «зашёл вечером». Здесь фраза получает роль по тексту, абзац — план из
 * шагов, шаг — набор допустимых ролей.
 */

/** Роль фразы по тексту записи (с прорезями). */
function v5Rol(string $т): string
{
    $s = strip_tags($т); $l = mb_strtolower($s);
    $герой = str_contains($s, '{ИМЯ') || (bool) preg_match('~(?:^|[^а-яё])(?:он|она|его|ему|ей|у него|у неё)(?![а-яё])~u', $l);
    if (preg_match('~^\s*(?:потому что|ответ простой|ответ в цифрах|ответ прост|поэтому|то есть|зато|но вот|итог:|вот почему|отсюда|и правильно|и это (?:правильно|нормально|честно)|именно поэтому|а значит|тогда(?![а-яё])|нет[:,]|да[:,])~u', $l)) { return 'связка'; }
    if (preg_match('~^[^.!?]{5,120}\?~u', $s)) { return 'вопрос'; }
    // «Наш игрок {ИМЯ} тоже не искал» — продолжение чужой мысли, без неё висит.
    if (preg_match('~^\s*(?:<strong>)?(?:наш игрок\s+)?\{ИМЯ\}\s+тоже\b~u', $s)) { return 'связка'; }
    // Обрывок истории без лица: «Зашёл, выбрал пару автоматов…», «Сперва шло
    // не так…», «Сел на пару раундов…», «Через сорок минут на балансе — {СУММА}».
    // Годится только как продолжение истории героя в его абзаце.
    if (!str_contains($s, '{ИМЯ') && !preg_match('~(?:^|[^а-яё])(?:он|она|его|ему|ей)(?![а-яё])~u', $l)
        && (preg_match('~^\s*(?:через|спустя)\s+[^,.]{1,25}?\s+на\s+(?:счету|счёте|балансе|карте)~u', $l)
        || preg_match('~^\s*(?:(?:сперва|сначала|потом|затем|дальше|в итоге|через\s+[^,.]{1,25}?)\s+)?(?:заш[ёе]л|зашла|сел|села|поймал|словил|взял|вывел|закинул|поставил|начал|решил|открыл|выбрал|крутил|слил|попробовал|зарегистрировался|активировал|пополнил|шло|пошло|получилось|повезло|забрал|снял|поднял|сорвал|разогнал|довёл|дошёл|вышел|ушёл|отыграл|скинул|залетел|запустил|запросил|оформил|вернулся|рискнул|проверил|вбил|ввёл|нажал|подтвердил)(?![а-яё])~u', $l))) { return 'ист.обрывок'; }
    // «На следующий день {ИМЯ} вернулся, поставил ещё…» — продолжение, не вход:
    // без первой части истории читалось началом.
    if (str_contains($s, '{ИМЯ') && preg_match('~на следующий день|вернул[ся]|снова|опять|ещё раз|в другой раз~u', $l)) { return 'ист.оговорка'; }
    if (str_contains($s, '{ИМЯ') && preg_match('~заш[ёе]л|открыл|закинул|поставил|начал|стартовал|зарегистрир|решил|зашла|залет|попробовал|проверил|однажды|как-то~u', $l)) { return 'ист.вход'; }
    if (preg_match('~\{СУММА|\{РУБЛИ~u', $s) && preg_match('~вывел|забрал|снял|сорвал|поднял|на балансе|итог|вынес|унёс|куш|в плюсе|дош[ёе]л|разогнал|превратил|получил|выиграл~u', $l) && ($герой || !preg_match('~\{RTP|бонус|джекпот~u', $l))) { return 'ист.исход'; }
    // Оговорка без лица — «в другой день тот же автомат отдал меньше» — тоже
    // продолжение истории героя: вне его абзаца висит.
    if (preg_match('~в другой день|тот же (?:сценарий|автомат|вечер|слот)|мог\w*\s+(?:бы\s+)?закончиться~u', $l)) { return 'ист.оговорка'; }
    if ($герой && preg_match('~мог\w*\s+(?:бы\s+)?(?:слить|уйти|проиграть|остаться)|до этого|честная часть|красивая история|не сказка|не гарантия|слил|в минус|перед этим|неделю до~u', $l)) { return 'ист.оговорка'; }
    if (preg_match('~поймал|словил|серия|фриспин|бонусн\w* раунд|множител|заход(?!ят|ит|ить|и(?![а-яё]))|волна|попал в|выстрел~u', $l) && !preg_match('~\{RTP~u', $s)) { return 'ист.событие'; }
    if (preg_match('~\{RTP|возврат\w*|дистанц|100 рублей|математик|волатильн|отдач\w*~u', $l)) { return 'мат'; }
    if (preg_match('~\{ПРОЦ|\{ДОЛЯ|бонус|вейджер|промокод|пакет|кэшбэк|фриспин~u', $l)) { return 'оффер'; }
    if (preg_match('~демо|играть бесплатно|вывод|выплат|верификац|зеркал|приложени|\{МИН|минут~u', $l)) { return 'практика'; }
    if (preg_match('~гарантий нет|можно выиграть|это не сюда|не заходи|движ для смелых|по-честному|без развода|честно|никто ничего не обещает~u', $l)) { return 'честн'; }
    if (preg_match('~href="/(?:registracia|vhod)"|регистрац|войти|жми~u', $l)) { return 'cta'; }
    return 'общ';
}

/** Аргумент пункта списка: два пункта об одном в списке не стоят. */
function v5TemaPunkta(string $т): string
{
    $l = mb_strtolower(strip_tags($т));
    foreach ([
        'rtp'         => '~\{RTP|rtp|возврат|отдач~u',
        'бонус'       => '~\{ПРОЦ|\{ДОЛЯ|бонус|пакет|вейджер|кэшбэк|отыгр~u',
        'вывод'       => '~вывод|выплат|cashout|\{МИН|верификац~u',
        'демо'        => '~демо|бесплатно~u',
        'джекпот'     => '~джекпот|\{ДЖЕКПОТ~u',
        'мобайл'      => '~приложени|телефон|смартфон|мобильн~u',
        'зеркало'     => '~зеркал|блокиров|домен|доступ~u',
        'новости'     => '~новост|релиз|анонс~u',
        'промо'       => '~промокод|акци|турнир~u',
        'провайдер'   => '~провайдер|студи|pragmatic|netent|nolimit|hacksaw|relax|play\'n|push gaming~u',
        'волатильность' => '~волатильн|дисперси|засух~u',
        'лимит'       => '~лимит|бюджет|дисциплин|стоп|не жалко|свободные деньги~u',
        'регистрация' => '~регистрац|аккаунт|анкет~u',
        'поддержка'   => '~поддержк|саппорт|чат~u',
        'риск'        => '~риск|проигр|слить|минус|гаранти~u',
        'герой'       => '~\{ИМЯ~u',
    ] as $тема => $re) {
        if (preg_match($re, $l)) { return $тема; }
    }
    return 'общ';
}

/**
 * План абзаца: список шагов, каждый шаг — допустимые роли. Особые метки:
 * «ИМЯ» — фраза обязана содержать {ИМЯ}, «!ИМЯ» — не должна.
 * $позиция: 0 — первый абзац раздела, 1, 2 — следующие, 'финал' — последний.
 */
function v5PlanAbzatsa(string|int $позиция, bool $геройВРазделе, int $шагов): array
{
    if ($позиция === 'финал') {
        $план = $геройВРазделе
            ? [['ист.исход:ИМЯ', 'ист.вход:ИМЯ', 'ист.событие:ИМЯ', 'честн'], ['честн', 'ист.оговорка', 'общ'], ['cta', 'честн', 'практика'], ['общ', 'cta']]
            : [['честн', 'вопрос', 'общ'], ['честн', 'практика', 'оффер'], ['cta', 'честн'], ['общ', 'cta']];
    } elseif ((int) $позиция === 0) {
        $план = $геройВРазделе
            ? [['ист.вход'], ['ист.событие:!ИМЯ', 'ист.исход:!ИМЯ', 'ист.обрывок', 'связка'], ['ист.оговорка', 'честн', 'ист.исход:!ИМЯ', 'ист.обрывок'], ['практика', 'мат', 'общ'], ['общ', 'честн']]
            : [['вопрос', 'общ', 'мат'], ['связка', 'мат', 'оффер', 'общ'], ['честн', 'практика'], ['практика', 'оффер', 'общ'], ['общ', 'честн']];
    } elseif ((int) $позиция === 1) {
        $план = [['вопрос', 'мат', 'общ'], ['связка', 'мат', 'честн'], ['честн', 'практика', 'мат'], ['оффер', 'практика', 'общ'], ['общ', 'честн']];
    } else {
        $план = [['оффер', 'практика', 'общ'], ['связка', 'оффер', 'практика', 'честн'], ['практика', 'честн', 'общ'], ['общ', 'честн', 'мат'], ['общ']];
    }
    // Шагов больше плана — добираем «общ», меньше — обрезаем.
    while (count($план) < $шагов) { $план[] = ['общ', 'честн', 'практика']; }
    return array_slice($план, 0, $шагов);
}

/** Подходит ли фраза шагу плана. */
function v5PodhoditShagu(string $т, array $шаг): bool
{
    $роль = v5Rol($т); $имя = str_contains($т, '{ИМЯ'); $сумма = (bool) preg_match('~\{СУММА|\{РУБЛИ~u', $т);
    foreach ($шаг as $треб) {
        $ч = explode(':', $треб); $р = array_shift($ч);
        // «ист.вывод» — практика или обрывок с выводом денег: «вывел за 10 минут».
        if ($р === 'ист.вывод') { if (in_array($роль, ['практика', 'ист.обрывок', 'ист.исход'], true) && v5EstVyvod($т) && !$имя) { return true; } continue; }
        if ($р !== $роль) { continue; }
        $годится = true;
        foreach ($ч as $метка) {
            if ($метка === 'ИМЯ' && !$имя) { $годится = false; }
            if ($метка === '!ИМЯ' && $имя) { $годится = false; }
            if ($метка === '!СУММА' && $сумма) { $годится = false; }
            // «!ВХОД» — обрывок не должен второй раз заводить героя: «закинул 3к и
            // получил бонус. Решил рискнуть — пополнил счёт, получил бонус».
            if ($метка === '!ВХОД' && v5EstVhodObryvka($т)) { $годится = false; }
        }
        if ($годится) { return true; }
    }
    return false;
}

/** Обрывок-вход: начинается с глагола старта — «Решил рискнуть — пополнил…», «Зашёл, выбрал…».
 *  «Поставил скромно, поймал серию» — не вход, а механизм: без него цепочка истории теряла середину. */
function v5EstVhodObryvka(string $т): bool
{
    return (bool) preg_match('~^\s*(?:(?:сперва|сначала|потом|затем)\s+)?(?:решил|заш[ёе]л|зашла|сел|села|пополнил|зарегистрировался|открыл|закинул|начал|попробовал|внёс|запустил|вбил|ввёл)(?![а-яё])~u', mb_strtolower(strip_tags($т)));
}

/** Исход уже назван: глагол выигрыша рядом с суммой — «вышел с {СУММА}», «вывел {РУБЛИ}». */
function v5EstIshod(string $т): bool
{
    return (bool) preg_match('~(?:вывел|вывела|забрал|забрала|снял|сняла|сорвал|сорвала|поднял|подняла|вышел с|вышла с|ун[ёе]с|унесла|вынес|вынесла|итог|дош[ёе]л до|дошла до|разогнал\w*|превратил\w*|выиграл|выиграла|словил|поймал|поймала|на балансе|в плюсе(?: на)?|выбил|выбила|взял|взяла|выплат\w*|остановил\w*)[^.!?]{0,40}\{(?:СУММА|РУБЛИ)~ui', strip_tags($т));
}

/** Есть ли в фразе ставка или старт истории: «закинул 3к», «поставил {РУБЛИ}», «начал с». */
function v5EstStavka(string $т): bool
{
    return (bool) preg_match('~закинул|поставил|начал с|зашёл с|зашла с|со ставк|ставк\w*\s+\{|депозит\w*\s+(?:в|на|—)?\s*\{|внёс|пополнил~u', mb_strtolower(strip_tags($т)));
}

/** Есть ли в фразе вывод денег: «вывел за {МИН} минут», «деньги на карте». */
function v5EstVyvod(string $т): bool
{
    return (bool) preg_match('~вывел|вывод|выплат|на карт|пришл\w* за|\{МИН~u', mb_strtolower(strip_tags($т)));
}

/** Фраза про героя по местоимению с глаголом прошедшего времени: «ему ответила Ирина», «он проигрывал раньше». */
function v5MestoimenieGeroya(string $т): bool
{
    $l = mb_strtolower(strip_tags($т));
    return !str_contains($т, '{ИМЯ')
        && (bool) preg_match('~(?:^|[^а-яё])(?:он|она|ему|ей|у него|у неё|его|её)(?![а-яё])~u', $l)
        && (bool) preg_match('~(?:^|[^а-яё])[а-яё]{3,}(?:ал|ил|ел|ял|ул|ёл|ыл|ла|ло|ли|лся|лась|вал|рял)(?![а-яё])~u', $l)
        && !preg_match('~(?:^|[^а-яё])(?:он|она)\s+(?:реален|реальн|не\s+(?:реален|реальн|про\b|о\b|для|гарант|обещ|волшебн|кнопк|сказк|касса)|—|это)~u', $l);
}
