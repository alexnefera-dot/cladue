/**
 * Роли фраз и планы абзацев.
 *
 * Донорский раздел — это не набор фраз, а ход мысли: история героя (вход →
 * событие → исход → оговорка), потом математика с честным ответом, потом
 * оффер с оговоркой и практика, список из разных аргументов, финал с
 * возвратом к герою. Сборка по фразам это ломала: «Потому что» указывало в
 * пустоту, три пункта списка говорили об одном, история героя обрывалась
 * на «зашёл вечером». Здесь фраза получает роль по тексту, абзац — план из
 * шагов, шаг — набор допустимых ролей.
 */

/** Роль фразы по тексту записи (с прорезями). */
function v5Rol(string $т): string
{
    $s = strip_tags($т); $l = mb_strtolower($s);
    $герой = str_contains($s, '{ИМЯ') || (bool) preg_match('~(?:^|[^а-яё])(?:он|она|его|ему|ей|у него|у неё)(?![а-яё])~u', $l);
    if (preg_match('~^\s*(?:потому что|ответ простой|поэтому|то есть|зато|но вот|итог:|вот почему|отсюда|и правильно|и это (?:правильно|нормально|честно)|именно поэтому|а значит)~u', $l)) { return 'связка'; }
    if (preg_match('~^[^.!?]{5,120}\?~u', $s)) { return 'вопрос'; }
    // Обрывок истории без лица: «Зашёл, выбрал пару автоматов…», «Сперва шло
    // не так…», «Сел на пару раундов…», «Через сорок минут на балансе — {СУММА}».
    // Годится только как продолжение истории героя в его абзаце.
    if (!str_contains($s, '{ИМЯ') && !preg_match('~(?:^|[^а-яё])(?:он|она|его|ему|ей)(?![а-яё])~u', $l)
        && preg_match('~^\s*(?:(?:сперва|сначала|потом|затем|дальше|в итоге|через\s+[^,.]{1,25}?)\s+)?(?:заш[ёе]л|зашла|сел|села|поймал|словил|взял|вывел|закинул|поставил|начал|решил|открыл|выбрал|крутил|слил|попробовал|зарегистрировался|активировал|пополнил|шло|пошло|получилось|повезло|забрал|снял|поднял|сорвал|разогнал|довёл|дошёл|вышел|ушёл|отыграл|скинул|залетел|запустил)(?![а-яё])~u', $l)) { return 'ист.обрывок'; }
    if (str_contains($s, '{ИМЯ') && preg_match('~заш[ёе]л|открыл|закинул|поставил|начал|стартовал|зарегистрир|решил|зашла|залет|попробовал|проверил|однажды|как-то~u', $l)) { return 'ист.вход'; }
    if (preg_match('~\{СУММА|\{РУБЛИ~u', $s) && preg_match('~вывел|забрал|снял|сорвал|поднял|на балансе|итог|вынес|унёс|куш|в плюсе|дош[ёе]л|разогнал|превратил|получил|выиграл~u', $l) && ($герой || !preg_match('~\{RTP|бонус|джекпот~u', $l))) { return 'ист.исход'; }
    if ($герой && preg_match('~мог\w*\s+(?:бы\s+)?(?:слить|уйти|проиграть|остаться)|до этого|честная часть|красивая история|не сказка|не гарантия|слил|в минус|перед этим|неделю до~u', $l)) { return 'ист.оговорка'; }
    if (preg_match('~поймал|словил|серия|фриспин|бонусн\w* раунд|множител|заход|волна|попал в|выстрел~u', $l) && !preg_match('~\{RTP~u', $s)) { return 'ист.событие'; }
    if (preg_match('~\{RTP|возврат\w*|дистанц|100 рублей|математик|волатильн|отдач\w*~u', $l)) { return 'мат'; }
    if (preg_match('~\{ПРОЦ|\{ДОЛЯ|бонус|вейджер|промокод|пакет|кэшбэк|фриспин~u', $l)) { return 'оффер'; }
    if (preg_match('~демо|играть бесплатно|вывод|выплат|верификац|зеркал|приложени|\{МИН|минут~u', $l)) { return 'практика'; }
    if (preg_match('~гарантий нет|можно выиграть|это не сюда|не заходи|движ для смелых|по-честному|без развода|честно|никто ничего не обещает~u', $l)) { return 'честн'; }
    if (preg_match('~href="/(?:registracia|vhod)"|регистрац|войти|жми~u', $l)) { return 'cta'; }
    return 'общ';
}

/** Аргумент пункта списка: два пункта об одном в списке не стоят. */
function v5TemaPunkta(string $т): string
{
    $l = mb_strtolower(strip_tags($т));
    foreach ([
        'rtp'         => '~\{RTP|rtp|возврат|отдач~u',
        'бонус'       => '~\{ПРОЦ|\{ДОЛЯ|бонус|пакет|вейджер|кэшбэк|отыгр~u',
        'вывод'       => '~вывод|выплат|cashout|\{МИН|верификац~u',
        'демо'        => '~демо|бесплатно~u',
        'джекпот'     => '~джекпот|\{ДЖЕКПОТ~u',
        'мобайл'      => '~приложени|телефон|смартфон|мобильн~u',
        'зеркало'     => '~зеркал|блокиров|домен|доступ~u',
        'новости'     => '~новост|релиз|анонс~u',
        'промо'       => '~промокод|акци|турнир~u',
        'провайдер'   => '~провайдер|студи|pragmatic|netent|nolimit|hacksaw|relax|play\'n|push gaming~u',
        'волатильность' => '~волатильн|дисперси|засух~u',
        'лимит'       => '~лимит|бюджет|дисциплин|стоп|не жалко|свободные деньги~u',
        'регистрация' => '~регистрац|аккаунт|анкет~u',
        'поддержка'   => '~поддержк|саппорт|чат~u',
        'риск'        => '~риск|проигр|слить|минус|гаранти~u',
        'герой'       => '~\{ИМЯ~u',
    ] as $тема => $re) {
        if (preg_match($re, $l)) { return $тема; }
    }
    return 'общ';
}

/**
 * План абзаца: список шагов, каждый шаг — допустимые роли. Особые метки:
 * «ИМЯ» — фраза обязана содержать {ИМЯ}, «!ИМЯ» — не должна.
 * $позиция: 0 — первый абзац раздела, 1, 2 — следующие, 'финал' — последний.
 */
function v5PlanAbzatsa(string|int $позиция, bool $геройВРазделе, int $шагов): array
{
    if ($позиция === 'финал') {
        $план = $геройВРазделе
            ? [['ист.исход:ИМЯ', 'ист.вход:ИМЯ', 'ист.событие:ИМЯ', 'честн'], ['честн', 'ист.оговорка', 'общ'], ['cta', 'честн', 'практика'], ['общ', 'cta']]
            : [['честн', 'вопрос', 'общ'], ['честн', 'практика', 'оффер'], ['cta', 'честн'], ['общ', 'cta']];
    } elseif ((int) $позиция === 0) {
        $план = $геройВРазделе
            ? [['ист.вход'], ['ист.событие:!ИМЯ', 'ист.исход:!ИМЯ', 'ист.обрывок', 'связка'], ['ист.оговорка', 'честн', 'ист.исход:!ИМЯ', 'ист.обрывок'], ['практика', 'мат', 'общ'], ['общ', 'честн']]
            : [['вопрос', 'общ', 'мат'], ['связка', 'мат', 'оффер', 'общ'], ['честн', 'практика'], ['практика', 'оффер', 'общ'], ['общ', 'честн']];
    } elseif ((int) $позиция === 1) {
        $план = [['вопрос', 'мат', 'общ'], ['связка', 'мат', 'честн'], ['честн', 'практика', 'мат'], ['оффер', 'практика', 'общ'], ['общ', 'честн']];
    } else {
        $план = [['оффер', 'практика', 'общ'], ['связка', 'оффер', 'практика', 'честн'], ['практика', 'честн', 'общ'], ['общ', 'честн', 'мат'], ['общ']];
    }
    // Шагов больше плана — добираем «общ», меньше — обрезаем.
    while (count($план) < $шагов) { $план[] = ['общ', 'честн', 'практика']; }
    return array_slice($план, 0, $шагов);
}

/** Подходит ли фраза шагу плана. */
function v5PodhoditShagu(string $т, array $шаг): bool
{
    $роль = v5Rol($т); $имя = str_contains($т, '{ИМЯ');
    foreach ($шаг as $треб) {
        [$р, $метка] = array_pad(explode(':', $треб, 2), 2, '');
        if ($р !== $роль) { continue; }
        if ($метка === 'ИМЯ' && !$имя) { continue; }
        if ($метка === '!ИМЯ' && $имя) { continue; }
        return true;
    }
    return false;
}
