    /**
     * Регулярка со всеми формами. Косвенные падежи — по окончанию: «Тимура»,
     * «Ольге», «Марата». Граница слова с обеих сторон обязательна, иначе
     * «Роман» ловится внутри «романтика».
     */
    public static function regex(): string
    {
        static $re = null;
        if ($re !== null) { return $re; }
        $stems = [];
        foreach (self::BASE as $n) {
            // отбрасываем конечную гласную: она и меняется при склонении
            $stems[] = preg_quote(preg_replace('~[ауеыоэяию]$~u', '', $n), '~');
        }
        $stems = array_unique($stems);
        usort($stems, fn($a, $b) => mb_strlen($b) <=> mb_strlen($a));
        $re = '~\b(?:' . implode('|', $stems) . ')(?:а|у|е|ом|ой|ы|и|ей|ю|я)?\b~u';
        return $re;
    }

    public static function count(string $text): int
    {
        return preg_match_all(self::regex(), $text);
    }
}
