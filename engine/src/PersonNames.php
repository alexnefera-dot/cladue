 *
 * Параметр «имён в тексте» держит опорный приём жанра: блок строится вокруг
 * истории с человеком. Пока словарь состоял из девяноста самых частых имён в
 * именительном падеже, он мерил не приём, а совпадение со списком: у донора
 * герои звались Павел и Николай и считались, у генерации — Влада, Гриша и
 * Земфира, и не считались ни разу. Одна сторона мерилась точно, другая нет.
 *
 * Отсюда два правила:
 *  · список общий и лежит здесь, а не копией в каждом скрипте;
 *  · в нём есть уменьшительные формы и имена за пределами русских святцев —
 *    в этой нише герои зовутся и Наилёй, и Аскаром, и просто Леной.
 * Косвенные падежи ловятся окончанием, поэтому «Тимура» и «Ольге» считаются
 * тем же именем, а «Тимуровец» — нет.
 */
