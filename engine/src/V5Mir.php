<?php
declare(strict_types=1);

/**
 * Мир набора. У конкурентов A мир есть у десяти сайтов из двадцати пяти:
 * гладиаторы и Колизей, сыщик и досье, фараон и гробница, адмирал и эскадра,
 * паровая машина, колесо фортуны, джунгли и храм, стадион и лига. Доноры D
 * миров не знают, поэтому в пулах их нет. Замер по A: 37–68 слов мира на
 * страницу, 60–90 % абзацев, 15–40 % пунктов, 15–45 % H3, в H2 — никогда.
 *
 * Приёмы у всех одни: пакет и программа лояльности названы из мира; читатель
 * получает роль («дальше дело за тобой, сыщик»); штампы звучат в декорациях
 * мира («это не сюда, джунгли такого не обещают»); объекты сайта становятся
 * предметами мира (зеркало — запасной вход в Колизей, верификация — доспех);
 * после факта — хвост-сравнение («быстрее, чем прогревается паровая машина»);
 * история героя закрывается фразой мира («просто удачный заход в правильную
 * гробницу»); короткая фраза-удар («Арена есть арена»).
 *
 * Двенадцать наших миров лежат в data-v5/miry.json. Мир получают два набора
 * из трёх (у A — четыре из десяти), остальные живут именами темы без мира.
 */
function v5Miry(): array
{
    static $миры = null;
    if ($миры === null) {
        $миры = json_decode((string) file_get_contents(__DIR__ . '/../data-v5/miry.json'), true) ?: [];
    }
    return $миры;
}

function v5Mir(int $сид): ?array
{
    $миры = v5Miry();
    if ($миры === [] || crc32('мир|' . $сид) % 3 === 0) { return null; }
    return $миры[crc32('какой мир|' . $сид) % count($миры)];
}

/** Сколько слов мира на странице: считается по основам из паспорта мира, только проза. */
function v5SlovMira(string $html, array $мир): int
{
    $основы = $мир['слова'] ?? [];
    if ($основы === []) { return 0; }
    $проза = strip_tags(preg_replace('~<section\b.*?</section>~su', ' ', $html) ?? $html);
    return preg_match_all('~(?<![а-яё])(?:' . implode('|', array_map(fn($s) => preg_quote($s, '~'), $основы)) . ')~ui', $проза);
}

/**
 * Вписать мир в страницу: до цели слов мира (разыграна от сида в полосе A),
 * в порядке заметности — штампы, концовки историй, объекты разделов, роль
 * читателя, H3, пункты, короткие фразы. Виджеты (<section>) и H2 не трогаются.
 */
function v5VpisatMir(string $html, array $мир, int $сид, array $герои, int $цель, string $тип = ''): string
{
    $счётчик = 0;
    // Розыгрыш варианта — от сида и типа страницы: одна и та же фраза про лицензию
    // не должна стоять на info, main и zerkalo одного набора.
    $вариант = function (array $список, string $ключ) use ($сид, $тип, &$счётчик): string {
        if ($список === []) { return ''; }
        return $список[(crc32($ключ . '|' . $сид . '|' . $тип) + $счётчик++) % count($список)];
    };
    $заглавная = fn(string $s): string => mb_strtoupper(mb_substr($s, 0, 1)) . mb_substr($s, 1);
    $хватит = function () use (&$html, $мир, $цель): bool { return v5SlovMira($html, $мир) >= $цель; };

    // Разбор: виджеты и FAQ в стороне. Правим только куски вне <section>, и до FAQ.
    $куски = preg_split('~(<section\b.*?</section>)~su', $html, -1, PREG_SPLIT_DELIM_CAPTURE);
    $правь = function (callable $f) use (&$куски) {
        foreach ($куски as $k => $кусок) {
            if ($k % 2 === 1) { continue; }
            // FAQ — от первого faq-блока и дальше не трогаем.
            $граница = preg_match('~<(?:div|h2)[^>]*(?:faq|ответы на вопросы)~ui', $кусок, $m, PREG_OFFSET_CAPTURE) ? $m[0][1] : null;
            $до = $граница === null ? $кусок : substr($кусок, 0, $граница);
            $после = $граница === null ? '' : substr($кусок, $граница);
            $куски[$k] = $f($до) . $после;
        }
    };
    $собрать = function () use (&$куски): string { return implode('', $куски); };

    // Абзацы героя: имя набора в тексте. Основы имён — первые четыре буквы.
    $именаОсновы = [];
    foreach (array_merge($герои['м'] ?? [], $герои['ж'] ?? []) as $имя) {
        $имя = trim((string) $имя);
        if (mb_strlen($имя) >= 4) { $именаОсновы[] = preg_quote(mb_substr($имя, 0, mb_strlen($имя) - 1), '~'); }
    }
    $геройРег = $именаОсновы === [] ? null : '~(?<![а-яё])(?:' . implode('|', $именаОсновы) . ')[а-яё]{0,3}(?![а-яё])~u';
    $этоГерой = fn(string $абзац): bool => $геройРег !== null && (bool) preg_match($геройРег, strip_tags($абзац));
    // Абзац с миром помечается: один абзац — одна вставка, а штамп в нём не переодевается.
    $естьМир = fn(string $т): bool => str_contains($т, '<!--мир-->') || v5SlovMira('<p>' . $т . '</p>', $мир) > 0;
    // Добавить предложение в конец абзаца: после точки, перед закрывающим тегом.
    $дописать = function (string $абзац, string $фраза): string {
        $фраза = trim($фраза);
        if ($фраза === '') { return $абзац; }
        $абзац = rtrim($абзац);
        if (!preg_match('~[.!?…»]$~u', $абзац)) { $абзац .= '.'; }
        return $абзац . ' ' . $фраза . '<!--мир-->';
    };

    // 1. Штампы в декорациях мира: по одному на страницу для каждого.
    $штампы = [
        'не сюда'         => ['~(?<![а-яё])(это(?:\s+точно|\s+совсем)?\s+не\s+сюда)(?![а-яё])(?![,—:])~ui', 'хвост'],
        'гарантий нет'    => ['~(?<![а-яё])(гарантий\s+(?:здесь\s+|тут\s+)?нет|нет\s+(?:никаких\s+)?гарантий)(?![а-яё])(?!\s+(?:ни|и)\b)(?!\s*[—,:]\s*(?:есть|только|зато|но))~ui', 'замена'],
        'движ для смелых' => ['~(?<![а-яё])(?<!нужен )(?<!настоящий )(?<!честный )(?<!самый )(?<!этот )(?<!такой )(?<!живой )(?<!в )(?<!на )(?<!за )(?<!любит )(?<!любишь )(?<!ищешь )(движ\s+для\s+смелых)(?![а-яё])~ui', 'замена'],
        'не заходи'       => ['~(?<![а-яё])(не\s+заходи,?\s+если\s+боишься\s+(?:проиграть|потерять|слить)(?:\s+(?:всё|деньги))?)(?![а-яё])~ui', 'замена'],
        'можно выиграть'  => ['~(?<![а-яё])(можно\s+выиграть,?\s+(?:а\s+)?можно\s+(?:и\s+)?проиграть)(?![а-яё])~ui', 'замена'],
    ];
    foreach ($штампы as $ключ => [$регулярка, $как]) {
        if ($хватит()) { break; }
        $список = $мир['штампы'][$ключ] ?? [];
        if ($список === []) { continue; }
        $сделано = 0;
        $правь(function (string $т) use ($регулярка, $как, $список, $вариант, $ключ, $заглавная, &$сделано, $естьМир): string {
            return (string) preg_replace_callback('~(<(?:p|li)\b[^>]*>)(.*?)(</(?:p|li)>)~su', function ($a) use ($регулярка, $как, $список, $вариант, $ключ, $заглавная, &$сделано, $естьМир) {
                if ($сделано >= 1 || $естьМир($a[2])) { return $a[0]; }
                $новый = (string) preg_replace_callback($регулярка, function ($m) use ($как, $список, $вариант, $ключ, $заглавная, &$сделано) {
                    if ($сделано >= 1) { return $m[0]; }
                    $сделано++;
                    $в = $вариант($список, $ключ);
                    if ($как === 'хвост') {
                        $в = preg_replace('~^это не сюда\s*[—,-]\s*~u', '', $в);
                        return $m[1] . ', ' . $в;
                    }
                    return preg_match('~^\p{Lu}~u', $m[1]) ? $заглавная($в) : $в;
                }, $a[2]);
                return $новый === $a[2] ? $a[0] : $a[1] . $новый . '<!--мир-->' . $a[3];
            }, $т);
        });
        $html = $собрать();
    }

    // 1б. Обороты внутри предложения: «на длинной дистанции» → «за весь турнир»,
    // «сорвал куш» → «взял приз турнира». Так мир сидит в самой фразе, как у A,
    // а не только дописан после неё. Каждый оборот — один раз, до трёх на страницу.
    if (!$хватит() && !empty($мир['обороты'])) {
        $всего = 0;
        foreach ($мир['обороты'] as [$от, $до]) {
            if ($всего >= 3) { break; }
            $сделано = 0;
            $правь(function (string $т) use ($от, $до, &$сделано, &$всего): string {
                return (string) preg_replace_callback('~(<(?:p|li)\b[^>]*>)(.*?)(</(?:p|li)>)~su', function ($a) use ($от, $до, &$сделано, &$всего) {
                    if ($сделано >= 1) { return $a[0]; }
                    // Снаружи ссылок и strong: метка ссылки остаётся меткой.
                    $куски = preg_split('~(<a\b[^>]*>.*?</a>|<strong>.*?</strong>)~su', $a[2], -1, PREG_SPLIT_DELIM_CAPTURE);
                    foreach ($куски as $k => $кусок) {
                        if ($k % 2 === 1 || $сделано >= 1) { continue; }
                        $новый = (string) preg_replace_callback('~(?<![а-яё])' . preg_quote($от, '~') . '(?![а-яё])~ui', function ($m) use ($до, &$сделано, &$всего) {
                            $сделано++; $всего++;
                            return preg_match('~^\p{Lu}~u', $m[0]) ? mb_strtoupper(mb_substr($до, 0, 1)) . mb_substr($до, 1) : $до;
                        }, $кусок, 1);
                        $куски[$k] = $новый;
                    }
                    return $a[1] . implode('', $куски) . $a[3];
                }, $т);
            });
            $html = $собрать();
        }
    }

    // 2. Концовки историй героя — до четырёх на страницу.
    if (!$хватит()) {
        $сделано = 0;
        $правь(function (string $т) use (&$сделано, $этоГерой, $естьМир, $дописать, $вариант, $мир): string {
            return (string) preg_replace_callback('~(<p\b[^>]*>)(.*?)(</p>)~su', function ($m) use (&$сделано, $этоГерой, $естьМир, $дописать, $вариант, $мир) {
                if ($сделано >= 4 || !$этоГерой($m[2]) || $естьМир($m[2])) { return $m[0]; }
                if (!preg_match('~(?:забрал|вывел|поднял|вытащил|снял|сорвал|выиграл|унёс|вынес|куш|на балансе|на счету|итог)~ui', strip_tags($m[2]))) { return $m[0]; }   // история с исходом
                $сделано++;
                return $m[1] . $дописать($m[2], $вариант($мир['исход'] ?? [], 'исход')) . $m[3];
            }, $т);
        });
        $html = $собрать();
    }

    // 3. Объекты сайта как предметы мира: по одному на раздел, ключ — по теме раздела.
    $ключиОбъектов = [
        'зеркало' => 'зеркал|блокиров|обход', 'верификация' => 'верификац|документ|паспорт|kyc', 'лицензия' => 'лиценз|кюрасао|аудит',
        'джекпот' => 'джекпот', 'вывод' => 'вывод|выплат', 'приложение' => 'приложени|apk|android|ios|скача', 'регистрация' => 'регистрац|аккаунт',
        'вход' => 'вход|логин|парол|авториз', 'кэшбэк' => 'кэшбэк|возврат', 'промокод' => 'промокод', 'турнир' => 'турнир',
        'партнёрка' => 'партн|реферал|трафик', 'лимиты' => 'лимит|ответственн|самоисключ', 'rtp' => 'rtp|отдач', 'бонус' => 'бонус|пакет|вейджер',
        'слоты' => 'слот|автомат|провайдер', 'поддержка' => 'поддержк|саппорт|чат', 'новости' => 'новост|анонс|обновлен',
    ];
    if (!$хватит()) {
        // Ключ на странице можно взять столько раз, сколько у мира фраз под него:
        // каждая фраза — один раз на страницу.
        $использованы = [];
        $найтиКлюч = function (string $где) use (&$использованы, $ключиОбъектов, $мир): ?string {
            $где = mb_strtolower($где);
            foreach ($ключиОбъектов as $к => $рег) {
                if (($использованы[$к] ?? 0) >= count($мир['объекты'][$к] ?? []) ) { continue; }
                if (preg_match('~' . $рег . '~u', $где)) { return $к; }
            }
            return null;
        };
        $взятьОбъект = function (string $ключ) use (&$использованы, $мир, $сид, $тип): string {
            $фразы = $мир['объекты'][$ключ] ?? [];
            if ($фразы === []) { return ''; }
            $n = $использованы[$ключ] ?? 0;
            $использованы[$ключ] = $n + 1;
            return $фразы[(crc32('объект|' . $ключ . '|' . $сид . '|' . $тип) + $n) % count($фразы)];
        };
        $правь(function (string $т) use (&$использованы, $найтиКлюч, $взятьОбъект, $мир, $этоГерой, $естьМир, $дописать, $вариант): string {
            $разделы = preg_split('~(<h2\b[^>]*>.*?</h2>)~su', $т, -1, PREG_SPLIT_DELIM_CAPTURE);
            foreach ($разделы as $i => $раздел) {
                if ($i % 2 === 1 || $i === 0) { continue; }
                $заголовок = strip_tags($разделы[$i - 1]);
                $вставлено = 0;
                $квота = preg_match_all('~<p\b~', $раздел) >= 5 ? 3 : 2;
                // Сначала ключ по самому абзацу: фраза про зеркало идёт в абзац про зеркало.
                $разделы[$i] = (string) preg_replace_callback('~(<p\b[^>]*>)(.*?)(</p>)~su', function ($m) use (&$вставлено, $квота, $найтиКлюч, $взятьОбъект, $этоГерой, $естьМир, $дописать) {
                    if ($вставлено >= $квота || $этоГерой($m[2]) || $естьМир($m[2])) { return $m[0]; }
                    $ключ = $найтиКлюч(strip_tags($m[2]));
                    if ($ключ === null) { return $m[0]; }
                    $вставлено++;
                    return $m[1] . $дописать($m[2], $взятьОбъект($ключ)) . $m[3];
                }, $раздел);
                if ($вставлено > 0) { continue; }
                // Иначе — ключ раздела по заголовку, в первый подходящий абзац.
                $ключ = $найтиКлюч($заголовок . ' ' . strip_tags($раздел));
                if ($ключ === null) { continue; }
                $разделы[$i] = (string) preg_replace_callback('~(<p\b[^>]*>)(.*?)(</p>)~su', function ($m) use (&$вставлено, $этоГерой, $естьМир, $дописать, $взятьОбъект, $ключ) {
                    if ($вставлено || $этоГерой($m[2]) || $естьМир($m[2])) { return $m[0]; }
                    $вставлено = 1;
                    return $m[1] . $дописать($m[2], $взятьОбъект($ключ)) . $m[3];
                }, $разделы[$i]);
            }
            return implode('', $разделы);
        });
        $html = $собрать();
    }

    // 4. Роль читателя — в последнем абзаце последнего раздела перед FAQ.
    if (!$хватит()) {
        $правь(function (string $т) use ($дописать, $вариант, $мир, $естьМир): string {
            if (!preg_match_all('~<p\b[^>]*>.*?</p>~su', $т, $m, PREG_OFFSET_CAPTURE)) { return $т; }
            $последний = null;
            foreach (array_reverse($m[0]) as $абз) { if (!$естьМир($абз[0])) { $последний = $абз; break; } }
            if ($последний === null) { return $т; }
            $новый = (string) preg_replace_callback('~^(<p\b[^>]*>)(.*?)(</p>)$~su',
                fn($x) => $x[1] . $дописать($x[2], $вариант($мир['обращение'] ?? [], 'обращение')) . $x[3], $последний[0]);
            return substr($т, 0, $последний[1]) . $новый . substr($т, $последний[1] + strlen($последний[0]));
        });
        $html = $собрать();
    }

    // 5. H3 — треть заголовков без двоеточия и без вопроса получают имя из мира.
    if (!$хватит()) {
        $правь(function (string $т) use ($вариант, $мир): string {
            $n = preg_match_all('~<h3(?![^>]*faq)[^>]*>.*?</h3>~su', $т);
            $квота = (int) ceil($n / 3); $сделано = 0; $номер = 0;
            return (string) preg_replace_callback('~(<h3(?![^>]*faq)[^>]*>\s*)(.*?)(\s*</h3>)~su', function ($m) use (&$сделано, &$номер, $квота, $вариант, $мир) {
                $номер++;
                $текст = trim($m[2]);
                if ($сделано >= $квота || $номер % 2 === 0 || str_contains($текст, ':') || str_contains($текст, '?') || mb_strlen(strip_tags($текст)) > 70) { return $m[0]; }
                $имя = $вариант($мир['h3'] ?? [], 'h3');
                if ($имя === '' || (str_contains($имя, 'без прикрас') && str_contains($текст, 'без прикрас'))) { return $m[0]; }
                $сделано++;
                $первая = mb_substr($текст, 0, 1);
                $строчная = preg_match('~^[А-ЯЁ][а-яё]~u', $текст) ? mb_strtolower($первая) . mb_substr($текст, 1) : $текст;
                return $m[1] . $имя . ': ' . $строчная . $m[3];
            }, $т);
        });
        $html = $собрать();
    }

    // 6. Пункты — хвост по смыслу пункта (RTP, бонус, лимит, джекпот, вывод), не больше одного на три пункта.
    if (!$хватит()) {
        $ключиПунктов = ['rtp' => 'rtp|отдач', 'джекпот' => 'джекпот', 'вывод' => 'вывод|выплат', 'лимиты' => 'лимит|остановит|дисциплин', 'бонус' => 'бонус|промокод|пакет|подар'];
        $былиПункты = [];   // один хвост пункта — один раз на страницу
        $правь(function (string $т) use ($вариант, $мир, $естьМир, $ключиПунктов, &$былиПункты): string {
            return (string) preg_replace_callback('~<ul\b[^>]*>.*?</ul>~su', function ($u) use ($вариант, $мир, $естьМир, $ключиПунктов, &$былиПункты) {
                $квота = (int) floor(preg_match_all('~<li\b~', $u[0]) / 3); $сделано = 0;
                return (string) preg_replace_callback('~(<li\b[^>]*>)(.*?)(</li>)~su', function ($m) use (&$сделано, $квота, $вариант, $мир, $естьМир, $ключиПунктов, &$былиПункты) {
                    $т = rtrim($m[2]);
                    if ($сделано >= $квота || $естьМир($т) || str_contains($т, ' — ') || mb_strlen(strip_tags($т)) < 40 || mb_strlen(strip_tags($т)) > 160) { return $m[0]; }
                    $чист = mb_strtolower(strip_tags($т)); $ключ = null;
                    foreach ($ключиПунктов as $к => $рег) { if (!isset($былиПункты[$к]) && preg_match('~' . $рег . '~u', $чист)) { $ключ = $к; break; } }
                    $фразы = $ключ === null ? [] : ($мир['пункты'][$ключ] ?? []);
                    if ($фразы === []) { return $m[0]; }
                    $сделано++; $былиПункты[$ключ] = true;
                    $т = preg_replace('~[.!]$~u', '', $т);
                    return $m[1] . $т . ' ' . $вариант($фразы, 'пункт|' . $ключ) . '.<!--мир-->' . $m[3];
                }, $u[0]);
            }, $т);
        });
        $html = $собрать();
    }

    // 7. Короткие фразы — в абзацы без мира, пока не добрана цель, не больше трёх.
    if (!$хватит()) {
        $сделано = 0; $осталось = max(0, $цель - v5SlovMira($html, $мир));
        $правь(function (string $т) use (&$сделано, $осталось, $этоГерой, $естьМир, $дописать, $вариант, $мир): string {
            return (string) preg_replace_callback('~(<p\b[^>]*>)(.*?)(</p>)~su', function ($m) use (&$сделано, $осталось, $этоГерой, $естьМир, $дописать, $вариант, $мир) {
                if ($сделано >= min(4, $осталось) || $этоГерой($m[2]) || $естьМир($m[2]) || mb_strlen(strip_tags($m[2])) < 200) { return $m[0]; }
                $сделано++;
                return $m[1] . $дописать($m[2], $вариант($мир['короткие'] ?? [], 'короткие')) . $m[3];
            }, $т);
        });
        $html = $собрать();
    }
    return str_replace('<!--мир-->', '', $html);
