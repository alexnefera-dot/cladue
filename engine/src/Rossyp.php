<?php
declare(strict_types=1);

/**
 * Россыпь: серия подряд идущих абзацев в одну фразу.
 *
 * Единственная проверка, которая НЕ отбрасывает короткие абзацы. Все
 * абзацные поля профиля — paragraphs, words_per_para, para_one_sent_pct и
 * обе её половины — считают только абзацы длиннее сорока знаков. Материал,
 * который добавлялся ради полов по первому лицу, повелительному, «вы» и
 * терминам, выходил как раз короче: одна короткая фраза на носитель. Он
 * лежал под измерительным порогом и не попадал вообще никуда, а хвост
 * страницы при этом выглядел так:
 *
 *   Я сверял начисления с журналом трижды.
 *   Мой вейджер закрывался быстрее на барабанах, чем на живых столах.
 *   Проверьте свою долю зачёта.
 *   Депозит и кэшбэк считаются раздельно, а промокод сгорает по календарю.
 *   Я держу снимок условий до активации.
 *   Проверьте свою ступень.
 *
 * Одиннадцать таких подряд на одной странице — и все меры зелёные.
 *
 * Порог взят с рынка: у 50 доноров на 266 страницах самая длинная серия
 * равна трём, серии из пяти и длиннее не встречается ни разу. Берём четыре
 * как потолок — на единицу выше рыночного максимума, чтобы правило ловило
 * россыпь, а не живой ритм.
 */
final class Rossyp
{
    /** Серия длиннее этой — уже не ритм, а россыпь. */
    public const POTOLOK = 4;

    /**
     * @return list<array{длина:int,первая:string}>
     */
    public static function proverit(string $html): array
    {
        // FAQ не в счёт: там одна фраза на ответ — это норма жанра, у
        // доноров 100 % ответов ровно такие.
        $konec = mb_strpos($html, '<details');
        $telo = $konec === false ? $html : mb_substr($html, 0, $konec);

        $seria = 0;
        $pervaya = '';
        $out = [];
        preg_match_all(
            '~(?is)<(h2|h3|p|li|table|ul|ol|blockquote)[^>]*>(.*?)</\1>~',
            $telo, $m, PREG_SET_ORDER
        );
        foreach ($m as $x) {
            $tekst = trim((string) preg_replace('~\s+~u', ' ',
                html_entity_decode(strip_tags($x[2]), ENT_QUOTES, 'UTF-8')));
            $odna = mb_strtolower($x[1]) === 'p'
                && $tekst !== ''
                && preg_match_all('~[.!?…](?:\s|$)~u', $tekst) === 1;
            if ($odna) {
                if ($seria === 0) { $pervaya = $tekst; }
                $seria++;
                continue;
            }
            if ($seria > self::POTOLOK) { $out[] = ['длина' => $seria, 'первая' => $pervaya]; }
            $seria = 0;
        }
        if ($seria > self::POTOLOK) { $out[] = ['длина' => $seria, 'первая' => $pervaya]; }
        return $out;
    }
}
