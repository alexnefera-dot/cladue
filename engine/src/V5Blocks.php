                            if (!preg_match('~(?<![а-яё])вы\s+(?:[а-яё]+\s+){0,2}$~ui', $до_)) { break; }
                        }
                        $новое = mb_substr($низ, 0, -mb_strlen($от)) . $до; break;
                    }
                }
                if ($новое === null && mb_substr($низ, -3) === 'ите' && !isset(V5_TY_НЕ_ГЛАГОЛ[$низ])) {
                    $до_ = mb_substr($кусок, 0, (int) mb_strpos($кусок, $m[0]));
                    $послеВы = (bool) preg_match('~(?<![а-яё])вы\s+(?:[а-яё]+\s+){0,2}$~ui', $до_);
                    if (!preg_match($предлог, $до_) && ($императивы || $послеВы)) {
                        // После «вы» — личная форма («вы говорите» → «говоришь»), иначе императив.
                        $новое = mb_substr($низ, 0, -3) . (preg_match('~(?<![а-яё])вы\s+(?:[а-яё]+\s+){0,2}$~ui', $до_) ? 'ишь' : 'и');
                    }
                }
            }
            if ($новое === null || $новое === $низ) { return $m[0]; }
            return preg_match('~^\p{Lu}~u', $m[0]) ? mb_strtoupper(mb_substr($новое, 0, 1)) . mb_substr($новое, 1) : $новое;
        }, $кусок);
    // «будьте честны» → «будь честен»: краткое прилагательное тоже меняет число.
    $итог = (string) preg_replace('~(?<![а-яё])([Бб]удь)\s+честны(?![а-яё])~u', '$1 честен', $итог);
    $итог = (string) preg_replace('~(?<![а-яё])([Бб]удь)\s+готовы(?![а-яё])~u', '$1 готов', $итог);
    // «чтобы вы могли» → «чтобы ты могли»: после «ты» множественное прошедшее и краткие формы — в единственное.
    static $ед = ['могли' => 'мог', 'смогли' => 'смог', 'хотели' => 'хотел', 'решили' => 'решил', 'забыли' => 'забыл',
