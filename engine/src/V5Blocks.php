function v5NaVy(string $кусок): string
{
    $правка = static function (string $слово): string {
        $низ = mb_strtolower($слово, 'UTF-8');
        if (isset(V5_VY_ИСКЛЮЧЕНИЯ[$низ])) { return V5_VY_ИСКЛЮЧЕНИЯ[$низ]; }
        if (isset(V5_VY_МЕСТОИМЕНИЯ[$низ])) { return V5_VY_МЕСТОИМЕНИЯ[$низ]; }
        if (mb_strlen($низ) >= 5 && in_array(mb_substr($низ, -2), ['ай', 'яй'], true)
            && !in_array($низ, V5_VY_НЕ_ИМПЕРАТИВ, true)) {
            return $низ . 'те';
        }
        foreach (V5_VY_ИМПЕРАТИВ as $основа) {
            if (mb_substr($низ, -mb_strlen($основа)) !== $основа) { continue; }
            // Остаток слева обязан быть глагольной приставкой, иначе основа
            // «будь» ловится в «когда-нибудь», а «бери» — в чём угодно.
            $приставка = mb_substr($низ, 0, mb_strlen($низ) - mb_strlen($основа));
            if ($приставка === '' || in_array($приставка, V5_VY_ПРИСТАВКИ, true)) {
                return $низ . 'те';
            }
        }
        foreach (['ешься' => 'етесь', 'ёшься' => 'ётесь', 'ишься' => 'итесь',
                  'ешь' => 'ете', 'ёшь' => 'ёте', 'ишь' => 'ите'] as $от => $до) {
            if (mb_substr($низ, -mb_strlen($от)) === $от && mb_strlen($низ) > mb_strlen($от) + 1) {
                return mb_substr($низ, 0, mb_strlen($низ) - mb_strlen($от)) . $до;
            }
        }
        // Возвратный императив: «регистрируйся» → «регистрируйтесь». Проверка
        // идёт ПОСЛЕ общих окончаний: «боишься» тоже кончается на «-ься», и
        // раньше них это правило давало «боишьтесь» вместо «боитесь».
        // «учиться» и «сдались» под правило не попадают: инфинитив на «-ться»
        // и прошедшее на «-лись» — не императив.
        if (mb_strlen($низ) >= 5 && mb_substr($низ, -4) !== 'ться') {
            foreach (['йся' => 'йтесь', 'ься' => 'ьтесь'] as $от => $до) {
                if (mb_substr($низ, -3) === $от) {
                    return mb_substr($низ, 0, -3) . $до;
                }
            }
            if (mb_substr($низ, -3) === 'ись' && mb_substr($низ, -4, 1) !== 'л') {
                return mb_substr($низ, 0, -3) . 'итесь';
            }
        }
        return $слово;
    };
    $кусок = preg_replace_callback('~(?<![а-яёА-ЯЁ])[а-яёА-ЯЁ]{2,}(?![а-яёА-ЯЁ])~u',
        function ($m) use ($правка) {
            $новое = $правка($m[0]);
            if ($новое === $m[0]) { return $m[0]; }
            // Заглавная в начале предложения остаётся заглавной.
            return preg_match('~^\p{Lu}~u', $m[0])
                ? mb_strtoupper(mb_substr($новое, 0, 1)) . mb_substr($новое, 1) : $новое;
        }, $кусок);
    // Согласование соседей. Пословная замена даёт «помнил вы сам»: прошедшее
    // время и краткие формы стоят при «ты» в единственном числе и обязаны
    // уехать во множественное вслед за местоимением.
    // Между местоимением и глаголом обычно стоит наречие («ты когда-нибудь
    // думал»), поэтому зазор в два служебных слова допускается; список
    // закрытый, иначе правило дотянется до чужого подлежащего.
    $зазор = '(?:\s+(?:' . implode('|', V5_VY_ЗАЗОР) . ')){0,2}';
    $перед = '(?<![а-яё])((?:вы|сами|[а-яё]+(?:йте|ите|ьте|тесь))' . $зазор . '\s+)';
    foreach (V5_VY_КРАТКИЕ as $ед => $мн) {
        $кусок = (string) preg_replace('~' . $перед . $ед . '(?![а-яё])~ui', '$1' . $мн, $кусок);
        $кусок = (string) preg_replace('~(?<![а-яё])' . $ед . '(\s+вы)(?![а-яё])~ui',
            $мн . '$1', $кусок);
    }
    // «зашёл» во множественном теряет «ё»: «зашли», а не «зашёли». У прочих
    // основ на «-ёл» беглая гласная переходит в «е»: «привёл» → «привели».
    $мн = static fn(string $основа, string $хвост): string => $хвост === 'ёл'
        ? (mb_substr($основа, -1) === 'ш' ? mb_substr($основа, 0, -1) . 'шли' : $основа . 'ели')
        : $основа . 'ли';
    // «А если готов играть — смотрите новости»: краткая форма стоит без
    // местоимения, антецедента у неё нет, и по соседству её не поймать. Но
    // после «если/раз/когда» она всегда об читателе — третье лицо потребовало
    // бы местоимения между союзом и формой.
    $союзы = '(?<![а-яё])((?:если|раз|когда|пока|чтобы|коли)\s+(?:не\s+)?)';
    foreach (V5_VY_КРАТКИЕ as $одна => $много) {
        if (in_array($одна, ['сам', 'сама', 'один'], true)) { continue; }
        $кусок = (string) preg_replace('~' . $союзы . $одна . '(?![а-яё])~ui', '$1' . $много, $кусок);
    }
    $кусок = (string) preg_replace_callback('~' . $перед . '([а-яё]{2,}?)(ёл|л[ао]?)(?![а-яё])~ui',
        fn($m) => $m[1] . $мн($m[2], $m[3]), $кусок);
    return (string) preg_replace_callback('~(?<![а-яё])([а-яё]{2,}?)(ёл|л[ао]?)(\s+вы)(?![а-яё])~ui',
        fn($m) => $мн($m[1], $m[2]) . $m[3], $кусок);
}

/**
 * Обратный перевод — «вы» → «ты» для «ты»-набора. Записи с «вы»-императивами
 * («Не отыгрывайтесь и остановитесь») попадали в «ты»-страницу как есть.
 * Правятся местоимения, императивы на -йте/-ьте/-йтесь/-ьтесь/-итесь и
 * личные формы на -ете/-ёте; «-ите» — только не после предлога и не у
