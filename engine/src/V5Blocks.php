    // бывает меньше, чем игр, и розыгрыш «игр 3, а всего имён 1» им запрещён.
    $ключЗерна = in_array($ключ, V5_S_OBJEMOM, true) ? 'words'
        : (in_array($ключ, V5_IMENA, true) ? 'names' : $ключ);
    $зерно = crc32($ключЗерна . '|' . $сид);
