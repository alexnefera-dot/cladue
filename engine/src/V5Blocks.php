/**
 * Цель поля для конкретного набора. Профиль хранит медиану корпуса, и если
 * целиться всем наборам в неё, они сходятся в одну точку: замер по держимым
 * полям давал медиану CV 8,1 % против 19,1 % у самих доноров — наши комплекты
 * выходили вдвое однообразнее корпуса, который они изображают.
 *
 * Поэтому цель разыгрывается внутри корпусной полосы (10–90 перцентиль,
 * профиль её уже посчитал) треугольным распределением с вершиной в медиане:
 * большинство наборов остаётся около центра, единицы уходят к краям — так же,
 * как расположены сами доноры. Набор перестаёт изображать среднего донора и
 * начинает изображать какого-то одного.
 *
 * Ширина розыгрыша выбрана замером, и замер вышел неожиданным. Формально
 * ближе всех к корпусу равномерный розыгрыш по краю доноров: на трёхстах
 * полях сами доноры дают медиану CV 15,5 %, он даёт 14,8 %. Но собранные им
 * наборы дали разброс НИЖЕ — 10,2 % против 11,9 % у полосы, — и приёмка на
 * них падала до 3–5 страниц из двенадцати. Цель у края материалом пулов не
 * берётся: генератор до неё не дотягивается и садится там же, где сел бы и
 * так, только теперь мимо своей цели.
 *
 * Отсюда второе ограничение: розыгрыш идёт по пересечению корпусной полосы с
 * тем, что движок реально достаёт («достижимое» в профиле, считает
 * `dostizhimoe-v5.php` по собранным страницам). На 660 полях медиана покрытия
 * — 100 %, движок почти везде свободен; но шестнадцать полей закрывают полосу
 * на 29–60 %: сборка из готовых кусков даёт абзацы в 33–42 слова, а доноры
 * пишут по 39–54, и цель в пятьдесят слов на абзац не берётся ни одной
 * попыткой. Целиться туда — не разнообразие, а гарантированный провал
 * страницы. Где пересечение вырождается, остаётся медиана.
 *
 * Ширина коридора приёмки при этом остаётся корпусной: она свойство метрики,
 * а не набора, и профиль строился именно по ней.
 *
 * Розыгрыш детерминирован от сида и КЛЮЧА ПОЛЯ, без типа страницы. Это
 * намеренно: донор пишет длинными абзацами на всех двенадцати страницах
 * сразу, а не на одной. Один и тот же розыгрыш даёт разные абсолютные цели
 * по типам, потому что полоса у каждого типа своя.
 *
 * Нулевая цель — запрет, а не полоса, и розыгрышу не подлежит.
 */
function v5CelNabora(array $поле, int $сид, string $ключ): float
{
    $цель = (float) ($поле['цель'] ?? 0.0);
    if ($сид <= 0 || $цель <= 0.0) { return $цель; }
    $дробное = !empty($поле['дробное']);
    $зерно = crc32($ключ . '|' . $сид);
    $u = ($зерно % 100000) / 100000;                 // [0, 1)

    $полоса = $поле['полоса'] ?? null;
    $низ = is_array($полоса) ? (float) ($полоса[0] ?? 0) : 0.0;
    $верх = is_array($полоса) ? (float) ($полоса[1] ?? 0) : 0.0;
    // Обрезаем полосу достижимым: цель, до которой движок не дотягивается,
    // разброса не даёт, а страницу валит.
    $дост = $поле['достижимое'] ?? null;
    if (is_array($дост) && count($дост) === 2) {
        $низ = max($низ, (float) $дост[0]);
        $верх = min($верх, (float) $дост[1]);
    }
    // Полоса вырожденная — либо корпус по этому полю не расходится, либо
    // движок не расходится вместе с ним. Выдумывать разброс там, где его
    // нет, значит писать не в жанре. Остаётся медиана.
    if ($верх - $низ < ($дробное ? 0.2 : 1.0)) { return $цель; }
    // Вершина треугольника — корпусная медиана, прижатая внутрь отрезка:
    // если медиана вне достижимого, целимся в ближний к ней край.
    $вершина = min(max($цель, $низ), $верх);
    $итог = max(0.0, v5Treugolnik($низ, $вершина, $верх, $u));
    return $дробное ? round($итог, 2) : round($итог);
}

/** Треугольное распределение: обратная функция от равномерного u. */
function v5Treugolnik(float $низ, float $вершина, float $верх, float $u): float
{
    $ширина = $верх - $низ;
    if ($ширина <= 0.0) { return $низ; }
    // Вершина на краю вырождает треугольник в половину: обе ветви ниже
    // сводятся к правильному пределу, деления на ноль тут не возникает.
    $порог = ($вершина - $низ) / $ширина;
    return $u < $порог
        ? $низ + sqrt($u * $ширина * ($вершина - $низ))
        : $верх - sqrt((1 - $u) * $ширина * ($верх - $вершина));
}

/** Число из денежной строки: «2 000 рублей» → 2000, «500₽» → 500. */
function v5Rubli(string $s): int
{
    return (int) preg_replace('~\D~u', '', $s);
}

/**
 * Род имени. Донор пишет «Елена зашла», и если подставить мужское имя, глагол
 * останется женским: пол героя — часть прорези, а не украшение. Правило —
