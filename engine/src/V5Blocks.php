/**
 * Одно начало у двух соседних фраз: «{ИМЯ} однажды зашёл на автомат ради
 * теста…» и «{ИМЯ} однажды зашёл просто проверить…» — фабрика писала пул по
 * одному шаблону, и близость по словам их не ловит. У доноров пар с общим
 * началом 0.1 на сто, у нас было 0.4, а с предпочтением одного донора в
 * абзаце — 0.9. Сравниваются первые два слова без разметки и прорезей.
 */
function v5OdnoNachalo(string $a, string $b): bool
{
    $нач = function (string $t): string {
        $t = mb_strtolower(trim(preg_replace('~\s+~u', ' ', strip_tags($t))));
        preg_match_all('~[\p{L}\p{N}{}:]+~u', $t, $m);
        return implode(" ", array_slice($m[0], 0, 2));
    };
    $x = $нач($a); $y = $нач($b);
    return $x !== '' && mb_substr_count($x, " ") >= 1 && $x === $y;
}

/**
