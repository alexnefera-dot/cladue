/** Узлы верхнего уровня: у корпуса они начинаются с нулевой колонки. */
function v5Uzly(string $html): array
{
    $lines = explode("\n", $html);
    $uzly = [];
    for ($i = 0, $n = count($lines); $i < $n; $i++) {
        $l = $lines[$i];
        if ($l === '' || $l[0] !== '<' || str_starts_with($l, '</')) { continue; }
        if (!preg_match('~^<([a-z0-9]+)([^>]*)>~i', $l, $m)) { continue; }
        [, $tag, $attrs] = $m;
        $класс = preg_match('~class="([^"]*)"~', $attrs, $c) ? $c[1] : '';
        $конец = "</$tag>";
        $j = $i;
        if (!str_contains($l, $конец)) {
            for ($j = $i + 1; $j < $n; $j++) { if (str_starts_with($lines[$j], $конец)) { break; } }
        }
        $j = min($j, $n - 1);
        $uzly[] = ['тег' => $tag, 'класс' => $класс,
                   'html' => implode("\n", array_slice($lines, $i, $j - $i + 1))];
        $i = $j;
    }
    return $uzly;
}

function v5Text(string $html): string
{
    return trim(preg_replace('~\s+~u', ' ',
        html_entity_decode(preg_replace('~<[^>]*>~', ' ', $html), ENT_QUOTES, 'UTF-8')));
}

/** Внутренность узла одной строкой — ссылки и выделения сохраняются. */
function v5Vnutr(string $html): string
{
    $t = preg_replace('~^<[a-z0-9]+[^>]*>~i', '', $html);
    $t = preg_replace('~</[a-z0-9]+>$~i', '', $t);
    return trim(preg_replace('~\s*\n\s*~u', ' ', $t));
}

function v5Klass(array $u): string
{
    $c = trim(explode(' ', $u['класс'])[0] ?? '');
    return $c !== '' ? $c : $u['тег'];
}

function v5Variant(array $u): string
{
    return preg_match('~\bvariant-(v\d+)~', $u['класс'], $m) ? $m[1] : 'v0';
}

/**
 * Трафарет: числа и герои заменяются прорезями, наблюдённые значения копятся
 * в банки (второй аргумент — по ссылке, можно пустой).
 *
 * Разметка стоит между числом и его словом («до <strong>75%</strong>»), поэтому
 * привязка идёт не к предлогу, а к форме самого числа: дробный процент в этой
 * нише всегда RTP, целый — бонус или кэшбэк. Порядок правил важен: каталог и
 * провайдеры ловятся раньше денег, иначе «1 394+ слотов» уйдёт в рубли.
 */
function v5Trafaret(string $t, array &$банки = []): string
{
    static $имена = null, $ном = null;
    if ($имена === null) {
        $r = new ReflectionClass('PersonNames');
        $ном = array_flip($r->getConstant('BASE'));
        $имена = PersonNames::regex();
    }
    $правила = [
        ['СЛОТОВ',      '~\b\d{1,2}\s?\d{3}(?=\+\s*(?:слот|игр))~u'],
        ['ПРОВАЙДЕРОВ', '~\b\d{2,3}(?=\+\s*провайдер)~u'],
        ['СУММА',       '~\b\d+(?:[.,]\d+)?\s?(?:к|тыс\.?|млн)\b~u'],
        ['РУБЛИ',       '~(?<!\d)(?<!\d )\d{1,3}(?:\s\d{3})*\s?(?:₽|рубл\w+)~u'],
        ['RTP',         '~(?<=RTP )\d{2}(?:[.,]\d)?(?=%)~u'],
        ['RTP',         '~\b\d{2}[.,]\d(?=%)~u'],
        ['ПРОЦ',        '~\b\d{2,4}(?=%)~u'],
        ['МИН',         '~(?<=за )\d{1,3}(?= мин)~u'],
        ['МИН',         '~(?<=от )\d{1,3}(?= мин)~u'],
        ['ВЕЙДЖЕР',     '~(?<=x)\d{2}\b~u'],
    ];
    foreach ($правила as [$имя, $re]) {
        $t = preg_replace_callback($re, function ($m) use ($имя, &$банки) {
            $банки[$имя][$m[0]] = ($банки[$имя][$m[0]] ?? 0) + 1;
            return '{' . $имя . '}';
        }, $t);
    }
    // Имя героя: 94 % вхождений в именительном, остальные — с окончанием,
    // и окончание переносится в прорезь, чтобы генератор склонил своё имя.
    return preg_replace_callback($имена, function ($m) use ($ном, &$банки) {
        $форма = $m[0];
        if (isset($ном[$форма])) {
            $прорезь = v5Rod($форма) === 'ж' ? 'ИМЯЖ' : 'ИМЯ';
            $банки[$прорезь][$форма] = ($банки[$прорезь][$форма] ?? 0) + 1;
            return '{' . $прорезь . '}';
        }
        foreach (['ом', 'ей', 'ой', 'а', 'у', 'е', 'ы', 'и', 'ю', 'я'] as $ок) {
            if (mb_substr($форма, -mb_strlen($ок)) !== $ок) { continue; }
            $корень = mb_substr($форма, 0, mb_strlen($форма) - mb_strlen($ок));
            foreach ([$корень, $корень . 'й', $корень . 'ь', $корень . 'а', $корень . 'я'] as $кандидат) {
                if (isset($ном[$кандидат])) {
                    return '{' . (v5Rod($кандидат) === 'ж' ? 'ИМЯЖ' : 'ИМЯ') . ':' . $ок . '}';
                }
            }
        }
        return '{ИМЯ}';
    }, $t);
}

/**
 * Род имени. Донор пишет «Елена зашла», и если подставить мужское имя, глагол
 * останется женским: пол героя — часть прорези, а не украшение. Правило —
 * окончание «а/я», за вычетом мужских имён с той же формой.
 */
function v5Rod(string $имя): string
{
    static $мужскиеНаА = ['Никита' => 1, 'Илья' => 1, 'Данила' => 1, 'Гриша' => 1, 'Паша' => 1,
        'Миша' => 1, 'Саша' => 1, 'Женя' => 1, 'Сева' => 1, 'Толя' => 1, 'Коля' => 1, 'Витя' => 1,
        'Слава' => 1, 'Дима' => 1, 'Лёша' => 1, 'Леша' => 1, 'Ваня' => 1, 'Юра' => 1, 'Костя' => 1,
        'Стёпа' => 1, 'Петя' => 1, 'Вася' => 1, 'Боря' => 1, 'Серёжа' => 1, 'Рома' => 1];
    if (isset($мужскиеНаА[$имя])) { return 'м'; }
    return in_array(mb_substr($имя, -1), ['а', 'я'], true) ? 'ж' : 'м';
}

/**
 * Склонение имени под окончание, снятое с донора. Разбор трёх типов основы
 * покрывает весь словарь: согласная (Виктор), «й» (Григорий, Андрей) и
 * «а/я» (Ольга, Илья). Падеж угадывается по окончанию донора, потому что
 * в корпусе он всегда однозначен: «у {ИМЯ:а}», «{ИМЯ:у} повезло».
 */
function v5Sklonenie(string $имя, string $ок): string
{
    $мягкая = ['а' => 'я', 'у' => 'ю', 'ом' => 'ем', 'е' => 'е', 'ы' => 'и', 'и' => 'и', 'ю' => 'ю', 'я' => 'я', 'ей' => 'ем', 'ой' => 'ем'];
    $женская = ['а' => 'ы', 'у' => 'е', 'ом' => 'ой', 'ой' => 'ой', 'е' => 'е', 'ы' => 'ы', 'и' => 'и', 'ю' => 'ю', 'я' => 'я', 'ей' => 'ей'];
    $последняя = mb_substr($имя, -1);
    if ($последняя === 'а' || $последняя === 'я') {
        return mb_substr($имя, 0, -1) . ($женская[$ок] ?? $ок);
    }
    if ($последняя === 'й' || $последняя === 'ь') {
        return mb_substr($имя, 0, -1) . ($мягкая[$ок] ?? $ок);
    }
    return $имя . $ок;
}

/**
 * Заполнение трафарета: `$значение('ПРОЦ')` возвращает значение прорези.
 * Имя выдаётся через `$значение('ИМЯ')` и склоняется здесь же.
 */
function v5Zapolnit(string $t, callable $значение): string
{
    return preg_replace_callback('~\{([А-ЯA-Z]+)(?::([а-я]{1,2}))?\}~u', function ($m) use ($значение) {
        $v = (string) $значение($m[1]);
        $имя = $m[1] === 'ИМЯ' || $m[1] === 'ИМЯЖ';
        return ($имя && ($m[2] ?? '') !== '') ? v5Sklonenie($v, $m[2]) : $v;
    }, $t);
}

/**
 * Близость двух кусков по четырёхсловным цепочкам. Пул одного раздела набран
 * с одиннадцати доноров, а фабрика писала их по одному шаблону: «Джекпот до X
 * звучит громко, однако вероятность не равна гарантии» встречается в трёх
 * переписываниях. Рядом в одном списке они читаются как заедание.
 */
function v5Blizost(string $a, string $b): float
{
    $ц = function (string $t): array {
        $w = preg_split('~\s+~u', mb_strtolower(preg_replace('~[^а-яёa-z0-9 ]+~u', ' ',
            preg_replace('~<[^>]*>~', ' ', $t))), -1, PREG_SPLIT_NO_EMPTY);
        $o = [];
        for ($i = 0; $i + 4 <= count($w); $i++) { $o[implode(' ', array_slice($w, $i, 4))] = 1; }
        return $o;
    };
    $x = $ц($a); $y = $ц($b);
    if (!$x || !$y) { return 0.0; }
    return count(array_intersect_key($x, $y)) / min(count($x), count($y));
}

/**
 * Разбор абзаца на предложения с сохранением встроенной разметки.
 *
 * Перенос абзацев целиком даёт с донором столько же совпадения, сколько доля
 * его абзацев в нашей странице, — на замере это 16–26 % против корпусного
 * потолка 8–11 %. Шингл в шесть слов рвётся на границе предложения, поэтому
 * абзац собирается из предложений разных доноров, и доля каждого падает втрое.
 *
 * Теги вынимаются перед разрезкой и возвращаются после: точка внутри
 * `href="сайт.com"` — не конец предложения. Предложение с непарным тегом
 * отбрасывается: собирать из него абзац нельзя.
 */
function v5Predlozheniya(string $html): array
{
    $теги = [];
    $без = preg_replace_callback('~<[^>]+>~', function ($m) use (&$теги) {
        $теги[] = $m[0];
        return "\x01" . (count($теги) - 1) . "\x02";
    }, $html);
    $куски = preg_split('~(?<=[.!?…])\s+~u', $без, -1, PREG_SPLIT_NO_EMPTY) ?: [];
    $итог = [];
    foreach ($куски as $к) {
        $п = preg_replace_callback('~\x01(\d+)\x02~', fn($m) => $теги[(int) $m[1]], $к);
        $открыто = preg_match_all('~<([a-z0-9]+)(?:\s[^>]*)?>~i', $п, $o);
        $закрыто = preg_match_all('~</([a-z0-9]+)>~i', $п, $c);
        if ($открыто !== $закрыто) { continue; }
        $п = trim($п);
        if (mb_strlen($п) < 15) { continue; }
        $итог[] = $п;
    }
    return $итог;
}

/**
 * Текстовые прорези виджета: строки, где лежит текст, и роль каждой — класс
 * ближайшего предка с классом (иначе itemprop, иначе тег).
 *
 * Виджет нельзя переносить от одного донора целиком: разметка у всех общая, а
 * текст в ней свой, и перенос даёт кусок дословного совпадения размером в пол
 * страницы. Роли же у доноров одни и те же — `hero-tagline`, `payout-name`,
 * `pillar-text`, — поэтому каждая строка набирается из своего пула.
 *
 * Пары «вопрос-ответ» из этого исключены: их надо менять парой, иначе ответ
 * встанет под чужим вопросом. Ими занимается отдельная подстановка.
 */
const V5_ROLI_PAROJ = ['faq-question', 'text', 'review-quote-text'];

function v5Sloty(string $html): array
{
    $строки = explode("\n", $html);
    $стек = []; $слоты = [];
    foreach ($строки as $i => $l) {
        $t = trim($l);
        if ($t === '') { continue; }
        if ($t[0] !== '<') { $слоты[] = ['строка' => $i, 'роль' => end($стек) ?: '?']; continue; }
        if (str_starts_with($t, '</')) { array_pop($стек); continue; }
        if (!preg_match('~^<([a-z0-9]+)([^>]*)>~i', $t, $m)) { continue; }
        $роль = preg_match('~class="([^"]*)"~', $m[2], $c) ? explode(' ', trim($c[1]))[0]
              : (preg_match('~itemprop="([^"]*)"~', $m[2], $ip) ? $ip[1] : $m[1]);
        if ($роль === '') { $роль = $m[1]; }
        $пустой = str_ends_with($t, '/>') || in_array(strtolower($m[1]), ['meta', 'img', 'br', 'input', 'hr'], true);
        if ($пустой) { continue; }
        if (preg_match('~^<[a-z0-9]+[^>]*>(.+)</[a-z0-9]+>\s*$~i', $t)) {
            $слоты[] = ['строка' => $i, 'роль' => $роль, 'встроенный' => true];
            continue;
        }
        $стек[] = $роль;
    }
    return $слоты;
}

/** Вёрстка узла в стиле корпуса: тег на нулевой колонке, текст с отступом. */
function v5Uzel(string $tag, string $inner, string $attrs = ''): string
{
    return "<{$tag}{$attrs}>\n  " . $inner . "\n</{$tag}>";
}

function v5Spisok(array $пункты, string $tag = 'ul'): string
{
    $o = "<{$tag}>\n";
    foreach ($пункты as $п) { $o .= "  <li>\n    " . $п . "\n  </li>\n"; }
    return $o . "</{$tag}>";
}
