function v5NaVy(string $кусок): string
{
    $правка = static function (string $слово): string {
        $низ = mb_strtolower($слово, 'UTF-8');
        if (isset(V5_VY_ИСКЛЮЧЕНИЯ[$низ])) { return V5_VY_ИСКЛЮЧЕНИЯ[$низ]; }
        if (isset(V5_VY_МЕСТОИМЕНИЯ[$низ])) { return V5_VY_МЕСТОИМЕНИЯ[$низ]; }
        if (mb_strlen($низ) >= 5 && in_array(mb_substr($низ, -2), ['ай', 'яй'], true)
            && !in_array($низ, V5_VY_НЕ_ИМПЕРАТИВ, true)) {
            return $низ . 'те';
        }
        foreach (V5_VY_ИМПЕРАТИВ as $основа) {
            if (mb_substr($низ, -mb_strlen($основа)) !== $основа) { continue; }
            // Остаток слева обязан быть глагольной приставкой, иначе основа
            // «будь» ловится в «когда-нибудь», а «бери» — в чём угодно.
            $приставка = mb_substr($низ, 0, mb_strlen($низ) - mb_strlen($основа));
            if ($приставка === '' || in_array($приставка, V5_VY_ПРИСТАВКИ, true)) {
                return $низ . 'те';
            }
        }
        foreach (['ешься' => 'етесь', 'ёшься' => 'ётесь', 'ишься' => 'итесь',
                  'ешь' => 'ете', 'ёшь' => 'ёте', 'ишь' => 'ите'] as $от => $до) {
            if (mb_substr($низ, -mb_strlen($от)) === $от && mb_strlen($низ) > mb_strlen($от) + 1) {
                return mb_substr($низ, 0, mb_strlen($низ) - mb_strlen($от)) . $до;
            }
        }
        // Возвратный императив: «регистрируйся» → «регистрируйтесь». Проверка
        // идёт ПОСЛЕ общих окончаний: «боишься» тоже кончается на «-ься», и
        // раньше них это правило давало «боишьтесь» вместо «боитесь».
        // «учиться» и «сдались» под правило не попадают: инфинитив на «-ться»
        // и прошедшее на «-лись» — не императив.
        if (mb_strlen($низ) >= 5 && mb_substr($низ, -4) !== 'ться') {
            foreach (['йся' => 'йтесь', 'ься' => 'ьтесь'] as $от => $до) {
                if (mb_substr($низ, -3) === $от) {
                    return mb_substr($низ, 0, -3) . $до;
                }
            }
            if (mb_substr($низ, -3) === 'ись' && mb_substr($низ, -4, 1) !== 'л') {
                return mb_substr($низ, 0, -3) . 'итесь';
            }
        }
        return $слово;
    };
    $кусок = preg_replace_callback('~(?<![а-яёА-ЯЁ])[а-яёА-ЯЁ]{2,}(?![а-яёА-ЯЁ])~u',
        function ($m) use ($правка) {
            $новое = $правка($m[0]);
            if ($новое === $m[0]) { return $m[0]; }
            // Заглавная в начале предложения остаётся заглавной.
            return preg_match('~^\p{Lu}~u', $m[0])
                ? mb_strtoupper(mb_substr($новое, 0, 1)) . mb_substr($новое, 1) : $новое;
        }, $кусок);
    // Согласование соседей. Пословная замена даёт «помнил вы сам»: прошедшее
    // время и краткие формы стоят при «ты» в единственном числе и обязаны
    // уехать во множественное вслед за местоимением.
    // Между местоимением и глаголом обычно стоит наречие («ты когда-нибудь
    // думал»), поэтому зазор в два служебных слова допускается; список
    // закрытый, иначе правило дотянется до чужого подлежащего.
    $зазор = '(?:\s+(?:' . implode('|', V5_VY_ЗАЗОР) . ')){0,2}';
    $перед = '(?<![а-яё])((?:вы|сами|[а-яё]+(?:йте|ите|ьте|тесь))' . $зазор . '\s+)';
    foreach (V5_VY_КРАТКИЕ as $ед => $мн) {
        $кусок = (string) preg_replace('~' . $перед . $ед . '(?![а-яё])~ui', '$1' . $мн, $кусок);
        $кусок = (string) preg_replace('~(?<![а-яё])' . $ед . '(\s+вы)(?![а-яё])~ui',
            $мн . '$1', $кусок);
    }
    // «зашёл» во множественном теряет «ё»: «зашли», а не «зашёли». У прочих
    // основ на «-ёл» беглая гласная переходит в «е»: «привёл» → «привели».
    $мн = static fn(string $основа, string $хвост): string => $хвост === 'ёл'
        ? (mb_substr($основа, -1) === 'ш' ? mb_substr($основа, 0, -1) . 'шли' : $основа . 'ели')
        : $основа . 'ли';
    // «А если готов играть — смотрите новости»: краткая форма стоит без
    // местоимения, антецедента у неё нет, и по соседству её не поймать. Но
    // после «если/раз/когда» она всегда об читателе — третье лицо потребовало
    // бы местоимения между союзом и формой.
    $союзы = '(?<![а-яё])((?:если|раз|когда|пока|чтобы|коли)\s+(?:не\s+)?)';
    foreach (V5_VY_КРАТКИЕ as $одна => $много) {
        if (in_array($одна, ['сам', 'сама', 'один'], true)) { continue; }
        $кусок = (string) preg_replace('~' . $союзы . $одна . '(?![а-яё])~ui', '$1' . $много, $кусок);
    }
    $кусок = (string) preg_replace_callback('~' . $перед . '([а-яё]{2,}?)(ёл|л[ао]?)(?![а-яё])~ui',
        fn($m) => $m[1] . $мн($m[2], $m[3]), $кусок);
    return (string) preg_replace_callback('~(?<![а-яё])([а-яё]{2,}?)(ёл|л[ао]?)(\s+вы)(?![а-яё])~ui',
        fn($m) => $мн($m[1], $m[2]) . $m[3], $кусок);
}

/**
 * Регистр обращения — свойство площадки, а не страницы. Из 76 разобранных
 * комплектов на «вы» пишут одиннадцать, и внутри такого комплекта «вы»
 * держится на всех двенадцати типах, меняется только плотность; «ты» при
 * этом никуда не девается — на registracia его у них вдвое больше, чем
 * «вы». Поэтому регистр выбирается один раз на набор, по сиду, и примерно
 * каждый седьмой набор выходит «вы»-набором.
 */
function v5ObrashchenieNabora(int $сид): string
{
    return $сид > 0 && crc32('обращение|' . $сид) % 7 === 0 ? 'вы' : 'ты';
}

/**
 * Подмена целей регистра для «вы»-набора. Абсолютные числа образцов
 * недостижимы: обращений на странице у них 20–43, у нас около двенадцати, а
 * перевод «ты» → «вы» этой суммы не меняет. Достижима доля — её и держим,
 * полем `vy_share`, где оба регистра считаются местоимениями и потому
 * сравнимы между собой.
 *
 * Поля `vy`, `ty` и `imperatives` получают числа подгруппы для отчёта, но
 * держать их нельзя: `vy` в базовом профиле стоит нулём (корпус доноров
 * пишет на «ты»), и «вы»-набор проваливал бы его при любом переводе.
 */
function v5PoliaObrashcheniya(array $поля, array $профиль, string $тип,
                              string $обращение, array $карта = []): array
{
    if ($обращение !== 'вы') { return $поля; }
    $цели = $профиль['обращение_вы']['типы'][$тип] ?? null;
    if (!$цели || !isset($цели['vy_share'])) { return $поля; }
    foreach (['vy', 'ty', 'imperatives'] as $ключ) {
        if (!isset($поля[$ключ], $цели[$ключ])) { continue; }
        $поля[$ключ]['цель'] = (float) $цели[$ключ];
        // Ни одно из трёх счётом не держим. Базовый профиль запрещает «вы» на
        // всех типах и императивы на promo и slots, а «вы»-подгруппа пишет
        // там и то и другое: две цели прямо противоречат друг другу, и
        // держать обе нельзя. Регистр держится долей — vy_share, — а эти
        // числа остаются ориентиром для рычагов перекрута и для отчёта.
        $поля[$ключ]['держат'] = false;
    }
    // Страница почти без обращений — регистру не на чем проявиться, и
    // требовать доли значит требовать вписать «вы» туда, где его нет.
    if ((int) ($карта['address_total'] ?? 0) < 4) { return $поля; }
    $ц = (float) $цели['vy_share'];
    $полуполоса = max(0.25 * $ц, 0.8);
    $поля['vy_share'] = [
        'подпись' => 'доля «вы» среди обращений, %',
        'цель'    => $ц,
        'дробное' => true,
        'держат'  => true,
        'полоса'  => [max(0.0, $ц - $полуполоса), min(100.0, $ц + $полуполоса)],
        'край'    => [max(0.0, $ц - $полуполоса), min(100.0, $ц + $полуполоса)],
    ];
    return $поля;
}

/**
 * Чужая метафорическая шкура. Один донор писал всю площадку в королевских
 * образах — трон, скипетр, корона, дворец, — другой в кладоискательских.
 * Внутри своего набора это цельный приём, но в общем пуле фразы разъезжаются
 * по чужим комплектам, и «условия отыгрыша — это страж у врат сокровищницы»
 * оказывается в тексте про бонусы рядом с обычной прозой.
 *
 * Замер: такой лексики у нас 1.24 на страницу против 0.90 у конкурента и
 * 0.53 у доноров, и весь перевес — на этих фразах.
 *
 * Третья шкура — подводная: Атлантида, жемчуг, затонувший клад, погружение
 * за сокровищами. В пулах её 215 записей (0,24 %), и в чужом наборе она
 * читается так же чужеродно: «Готовы нырнуть за своим главным сокровищем?»
 * посреди страницы про верификацию.
 *
 * Ловим только существительные шкуры. Прилагательное «королевский» —
 * обычный усилитель («королевский джекпот», «королевская сумма»), его
 * доноры пишут вне всякой сказки, и трогать его нельзя. По той же причине
 * не ловим «глубину» и «подводный»: «без подводных камней» — жанровая
