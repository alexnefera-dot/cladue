/**
 * Ворота набора: нумерованный список возможен ТОЛЬКО на promo.
 *
 * Доноры ставят <ol> на promo (6 из 12) и на app (3 из 12), но приёмка
 * считает коридор от ЦЕЛИ набора, а не от корпусной полосы:
 *   |наше − цель| ≤ max(0.25·|цель профиля|, 0.8)
 * У app ordered_pct цель 0 и держат=true, значит коридор — [0, 0.8], и любой
 * <ol> валит страницу: «ordered_pct 25→0». Корпусная полоса [0, 20] в этом
 * правиле не участвует. На promo признак не держат вовсе, и там <ol> живёт.
 *
 * Первая версия этого не учла и открывала ворота app каждому четвёртому
 * набору. Толку ноль — страница всё равно не проходила, — а сиды партия на
 * это тратила: 279–283 собрались за 37 попыток против 19 у 274–278.
 *
 * Донорские 25% на app недостижимы, пока цель профиля равна нулю. Поднять её
 * значило бы переписать стандарт приёмки под привычку трёх доноров из
 * двенадцати; это отдельное решение, а не побочный эффект правки разметки.
 */
function v5NumerovatNabor(string $тип, string $имяНабора): bool
{
    return $тип === 'promo';
}

/**
 * Смена тега ul→ol на готовой странице.
 *
 * Замер по двенадцати донорам: <ol> есть ТОЛЬКО на promo (шесть доноров,
 * доля 16.7–33.3%) и app (три донора, 14.3–25%). На остальных десяти типах
 * его нет ни у кого, и профиль держит там полосу [0, 0] — это запрет, а не
 * недобор.
 *
 * Разделение труда: пункты-шаги в список набирает генератор (v5ShagovyiPunkt),
 * а здесь остаётся только смена тега — потому что доля считается по ГОТОВОЙ
 * странице, где к нашим спискам добавились списки виджетов. Проверка тут
 * двойная и обе нужны:
 *   · не меньше пяти списков. На app полоса [0, 20], и один <ol> из четырёх
 *     списков даёт 25% — страница валит приёмку;
 *   · больше половины пунктов — шаговые. Если генератору не хватило записей и
 *     в список попал перечень, нумеровать его нельзя: <ol> обещает порядок.
 */
function v5PoryadokSpiska(string $html, string $тип, string $имяНабора): string
{
    if (!v5NumerovatNabor($тип, $имяНабора)) { return $html; }
    if (preg_match_all('~<ul\b~i', $html) + preg_match_all('~<ol\b~i', $html) < 5) { return $html; }
    $шаги = $тип === 'app' ? '~как установить~ui' : '~как использовать промокод~ui';
    // Голый <ul> без атрибутов — наш список из v5Spisok. У списков виджетов
    // есть классы, и менять им тег нельзя: на них завязана вёрстка.
    if (!preg_match_all('~<ul>\n.*?</ul>~su', $html, $mm, PREG_OFFSET_CAPTURE)) { return $html; }
    foreach ($mm[0] as $m) {
        // Именно H2, а не ближайший заголовок: между «Как установить —
        // Пошагово» и списком стоит H3 раздела, и поиск по h[23] находил его.
        $до = substr($html, 0, $m[1]);
        $заголовок = preg_match_all('~<h2[^>]*>(.*?)</h2>~su', $до, $hh) ? end($hh[1]) : '';
        if (!preg_match($шаги, strip_tags($заголовок))) { continue; }
        preg_match_all('~<li>\s*(.*?)\s*</li>~su', $m[0], $pp);
        $всего = count($pp[1]);
        if ($всего < 3) { continue; }
        $шаговых = count(array_filter($pp[1], 'v5ShagovyiPunkt'));
        if ($шаговых * 2 <= $всего) { continue; }
        return substr($html, 0, $m[1]) . '<ol>' . substr($m[0], 4, -5) . '</ol>'
             . substr($html, $m[1] + strlen($m[0]));
    }
    return $html;
}

function v5Spisok(array $пункты, string $tag = 'ul'): string
{
    $o = "<{$tag}>\n";
    foreach ($пункты as $п) { $o .= "  <li>\n    " . $п . "\n  </li>\n"; }
    return $o . "</{$tag}>";
}

/**
 * Ремонт денежной пары в предложении.
 *
 * Донор пишет ставку числом внутри фразы, а результат отдаёт прорезью {РУБЛИ}.
 * Прорезь в узле выдаётся первой, то есть из младшей — ставочной — половины
 * банка, и герой «заходит с 1000 ₽ и доводит сумму до 200 рублей». Проверка
 * смысла ловит это как «результат меньше ставки»; здесь оно чинится на месте:
 * итог заменяется на запись из банка, которая крупнее ставки, с сохранением
 * написания валюты из исходной фразы.
 *
 * @param array<string, mixed> $рубли банк РУБЛИ: ключи — денежные строки
 */
function v5PochinitDengi(string $html, array $рубли): string
{
    // Банк режется по написанию валюты: «120 000 ₽» и «120 000 рублей» — это
    // разные строки, и подставлять нужно ту, что совпадает с исходной фразой.
    $поВалюте = ['₽' => [], 'рубли' => []];
    foreach (array_keys($рубли) as $s) {
        $s = (string) $s;
        $n = v5Rubli($s);
        // «000 ₽» и «0₽» — обломки разбора: он разорвал «120 000 ₽» по пробелу.
        if ($n < 1000 || preg_match('~^\D*0~u', $s)) { continue; }
        $вид = mb_strpos($s, '₽') !== false ? '₽' : 'рубли';
        $поВалюте[$вид][$n] = trim(preg_replace('~\s*(?:₽|рубл\w+)\s*$~u', '', $s));
    }
    foreach ($поВалюте as &$список) { ksort($список); }
    unset($список);
    if (!$поВалюте['₽'] && !$поВалюте['рубли']) { return $html; }

    $re = '~((?:зашёл|зашла|начал|начала|пополнил|пополнила|поставил|поставила)[^.!?<]{0,80}?'
        . '(\d[\d\x{00A0} ]*?)\s?(?:₽|рубл\w+)[^.!?<]{0,110}?'
        . '(?:довёл|довела|поднял|подняла|вырос\w*|забрал|забрала|до)\s+)'
        . '(\d[\d\x{00A0} ]*?)\s?(₽|рубл\w+)~u';

    return (string) preg_replace_callback($re, function (array $m) use ($поВалюте): string {
        $ставка = v5Rubli($m[2]);
        $итог   = v5Rubli($m[3]);
        if ($ставка <= 0 || $итог > $ставка) { return $m[0]; }
        $вид = $m[4] === '₽' ? '₽' : 'рубли';
        $список = $поВалюте[$вид] ?: ($поВалюте['₽'] ?: $поВалюте['рубли']);
        // Результат в корпусе кратно больше ставки: «зашёл с 1000 ₽ и довёл до
        // 1050 ₽» читается не лучше сломанной подстановки. Порог — десять
        // ставок, с откатом на три и на самую крупную запись банка.
        $новое = null;
        foreach ([10, 3, 1] as $кратность) {
            foreach ($список as $n => $запись) {
                if ($n >= $ставка * $кратность) { $новое = [$n, $запись]; break 2; }
            }
        }
        if ($новое === null || $новое[0] <= $ставка) { return $m[0]; }
        return $m[1] . $новое[1] . ' ' . $m[4];
    }, $html);
}

/**
 * Согласование числительного с существительным времени.
 *
 * Донор пишет «вывод за 3 минуты» — форма верна для двух, трёх и четырёх.
 * Прорезь катит в этот шаблон любое число, и получается «за 20 минуты»,
 * «за 47 минуты». В корпусе такого нет: доноры просто не выпали на другие
 * числа. Правило простое и покрывает весь встречающийся набор слов.
 */
function v5PochinitChislo(string $html): string
{
    static $формы = [
        'минуты'  => ['минута', 'минуты', 'минут'],
        'минут'   => ['минута', 'минуты', 'минут'],
        'часа'    => ['час', 'часа', 'часов'],
        'часов'   => ['час', 'часа', 'часов'],
        'дня'     => ['день', 'дня', 'дней'],
        'дней'    => ['день', 'дня', 'дней'],
        'секунды' => ['секунда', 'секунды', 'секунд'],
        'секунд'  => ['секунда', 'секунды', 'секунд'],
    ];
    $ключи = implode('|', array_keys($формы));

    return (string) preg_replace_callback(
        '~(\S+\s)?(\d+)(\s|&nbsp;)(' . $ключи . ')\b~u',
        function (array $m) use ($формы): string {
            // «до 1 часа», «от 40 минут» — родительный по предлогу, это норма.
            static $предлоги = ['до' => 1, 'от' => 1, 'около' => 1, 'порядка' => 1,
                                'свыше' => 1, 'более' => 1, 'менее' => 1];
            // Тег между предлогом и числом не мешает: «<strong>до 24 часов</strong>»
            // читалось как «до 24 часа».
            $перед = trim(strip_tags((string) $m[1]));
            if (isset($предлоги[mb_strtolower($перед)])) { return $m[0]; }

            $n = (int) $m[2];
            $сотня = $n % 100;
            $конец = $n % 10;
            if ($сотня >= 11 && $сотня <= 14) { $форма = 2; }
            elseif ($конец === 1)             { $форма = 0; }
            elseif ($конец >= 2 && $конец <= 4) { $форма = 1; }
            else                                { $форма = 2; }

            return ($m[1] ?? '') . $m[2] . $m[3] . $формы[$m[4]][$форма];
        }, $html);
}

/**
 * Баланс кавычек на странице.
 *
 * В библиотеке попадаются куски, где реплика открылась и не закрылась —
 * разбор донора разрезал цитату пополам. На странице это выглядит как
 * «Мне повезло. без пары или как одинокая » в конце чужой фразы.
 *
 * Считаем только текст вне тегов: в атрибутах кавычки свои. Лишний
 * закрывающий убираем, незакрытый открывающий закрываем по концу его
 * предложения — донор пишет реплику именно так.
 */
function v5PochinitKavychki(string $html): string
{
    // Куски текста вне тегов: смещение в исходной строке и сам текст.
    preg_match_all('~>[^<]+~u', $html, $m, PREG_OFFSET_CAPTURE);
    if (!$m[0]) { return $html; }

    $карта = [];            // позиция в потоке → позиция в html
    $поток = '';
    foreach ($m[0] as [$кусок, $смещение]) {
        $len = strlen($кусок);
        for ($i = 1; $i < $len; $i++) {   // единицу пропускаем: это сам «>»
            $карта[strlen($поток)] = $смещение + $i;
            $поток .= $кусок[$i];
        }
    }

    $правки = [];           // позиция в html → что делать
    $стек = [];
    $длина = strlen($поток);
    for ($i = 0; $i < $длина; $i++) {
        if (substr($поток, $i, 2) === "\xc2\xab") {          // «
            $стек[] = $i;
        } elseif (substr($поток, $i, 2) === "\xc2\xbb") {    // »
            if ($стек) { array_pop($стек); }
            else { $правки[$карта[$i]] = ['убрать', 2]; }
        }
    }
    // Незакрытая реплика: ставим » после конца её предложения.
    foreach ($стек as $поз) {
        $конец = null;
        for ($i = $поз + 2; $i < $длина; $i++) {
            if (strpos('.!?', $поток[$i]) !== false) { $конец = $i; break; }
        }
        if ($конец === null || !isset($карта[$конец])) {
            $правки[$карта[$поз]] = ['убрать', 2];           // закрывать негде — снимаем открывающую
        } else {
            $правки[$карта[$конец] + 1] = ['вставить', "\xc2\xbb"];
        }
    }
    if (!$правки) { return $html; }

    krsort($правки);        // правим с конца, чтобы смещения не поехали
    foreach ($правки as $поз => [$что, $чем]) {
        $html = $что === 'убрать'
            ? substr($html, 0, $поз) . substr($html, $поз + $чем)
            : substr($html, 0, $поз) . $чем . substr($html, $поз);
    }
    return $html;
}

/**
 * Один и тот же виджет лежит в библиотеке под двумя оболочками
 * (faq-section и info-block), поэтому сборка иногда ставит на страницу
 * обе копии: одинаковый заголовок, одинаковый текст и одинаковый
 * id="toc-N". Вторую копию убираем целиком.
 *
 * Копия не всегда обёрнута в свой <div>: бывает голая пара «<h2> плюс
 * следующий блок», и по одному <div> её не поймать. Поэтому идём по
 * верхнеуровневым блокам (нулевой отступ — вложенное генератор всегда
 * печатает с отступом) и склеиваем их в группы: группа начинается на
 * блоке с <h2> и тянется до следующего такого.
 */
function v5UbratDubliVidzhetov(string $html): string
{
    $строки = explode("\n", $html);
    $всего  = count($строки);

    // верхнеуровневые блоки: от «<тег …>» в нулевой колонке до «</тег>» там же
    $блоки = [];
    for ($i = 0; $i < $всего; $i++) {
        if (!preg_match('~^<([a-z0-9]+)\b~', $строки[$i], $m)) { continue; }
        $закрытие = '</' . $m[1] . '>';
        for ($j = $i + 1; $j < $всего; $j++) {
            if ($строки[$j] === $закрытие) {
                $кусок = implode("\n", array_slice($строки, $i, $j - $i + 1));
                $ключ = preg_match('~<h2\b[^>]*>(.*?)</h2>~is', $кусок, $h)
                    ? mb_strtolower(trim(preg_replace('~\s+~u', ' ', strip_tags($h[1]))), 'UTF-8') : '';
                $блоки[] = ['от' => $i, 'до' => $j, 'ключ' => $ключ];
                $i = $j;
                break;
            }
        }
    }

    // группы: заголовок и всё, что идёт за ним до следующего заголовка
    $группы = [];
    foreach ($блоки as $б) {
        if ($б['ключ'] !== '' || !$группы) {
            $группы[] = ['ключ' => $б['ключ'], 'от' => $б['от'], 'до' => $б['до']];
        } else {
            $группы[count($группы) - 1]['до'] = $б['до'];
        }
    }

    $видели = []; $убрать = [];
    foreach ($группы as $г) {
        if ($г['ключ'] === '') { continue; }
        if (isset($видели[$г['ключ']])) {
            for ($k = $г['от']; $k <= $г['до']; $k++) { $убрать[$k] = true; }
        } else {
            $видели[$г['ключ']] = true;
        }
    }
    if (!$убрать) { return $html; }

    $итог = [];
    foreach ($строки as $н => $строка) {
        if (!isset($убрать[$н])) { $итог[] = $строка; }
    }
    return implode("\n", $итог);
}

/**
 * Якоря у заголовков разделов. Конкурент помечает `id="toc-N"` три четверти
 * своих h2, мы — одну седьмую. Правило у него простое и мы его повторяем:
 * якорь получают заголовки разделов (без класса либо с оформительским
 * `gradient-text`), а шапки виджетов — нет.
 *
 * Нумерация сквозная: один и тот же id на странице — битая разметка, а после
 * снятия дубля виджета в нумерации ещё и дыры.
 */
const V5_H2_BEZ_YAKORYA = ['hero-headline', 'value-pillars-heading',
                           'slots-dashboard-title', 'review-quotes-heading'];

function v5PeresobratToc(string $html): string
{
    $н = 0;
    return preg_replace_callback('~<h2\b([^>]*)>~i', function ($m) use (&$н) {
        $атрибуты = $m[1];
        $класс = preg_match('~\sclass="([^"]*)"~', $атрибуты, $к) ? $к[1] : '';
        foreach (V5_H2_BEZ_YAKORYA as $шапка) {
            if (str_contains($класс, $шапка)) { return $m[0]; }
        }
        $н++;
        return preg_match('~\sid="~', $атрибуты)
            ? '<h2' . preg_replace('~\sid="[^"]*"~', ' id="toc-' . $н . '"', $атрибуты, 1) . '>'
            : '<h2' . $атрибуты . ' id="toc-' . $н . '">';
    }, $html);
}
