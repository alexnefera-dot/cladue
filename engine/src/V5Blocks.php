 */
const V5_TY_МЕСТОИМЕНИЯ = ['вы' => 'ты', 'вас' => 'тебя', 'вам' => 'тебе', 'вами' => 'тобой',
    'ваш' => 'твой', 'ваша' => 'твоя', 'ваше' => 'твоё', 'ваши' => 'твои', 'вашего' => 'твоего',
    'вашей' => 'твоей', 'вашему' => 'твоему', 'вашим' => 'твоим', 'вашими' => 'твоими',
    'ваших' => 'твоих', 'вашу' => 'твою', 'вашем' => 'твоём', 'сами' => 'сам'];
const V5_TY_НЕ_ГЛАГОЛ = ['сайте' => 1, 'лимите' => 1, 'депозите' => 1, 'кредите' => 1, 'визите' => 1,
    'аудите' => 1, 'ките' => 1, 'орбите' => 1, 'элите' => 1, 'граните' => 1, 'магните' => 1,
    'реквизите' => 1, 'бите' => 1, 'ките' => 1, 'суите' => 1, 'сателлите' => 1, 'колорите' => 1,
    'паразите' => 1, 'фаворите' => 1, 'дефиците' => 1, 'профиците' => 1, 'опыте' => 1, 'бюджете' => 1];

/** Предложения записи (от пяти слов) и её начало (три слова) — ключи повтора на странице. */
function v5KlyuchiPovtora(string $t): array
{
    $чист = mb_strtolower(preg_replace('~\s+~u', ' ', strip_tags($t)));
    $ключи = [];
    foreach (preg_split('~(?<=[.!?])\s+~u', $чист) as $пр) {
        $слова = preg_split('~[^\p{L}\d{}]+~u', $пр, -1, PREG_SPLIT_NO_EMPTY);
        if (count($слова) >= 5) { $ключи[] = implode(' ', $слова); }
    }
    $слова = preg_split('~[^\p{L}\d{}]+~u', $чист, -1, PREG_SPLIT_NO_EMPTY);
    if (count($слова) >= 3) { $ключи[] = '^' . implode(' ', array_slice($слова, 0, 3)); }
    return $ключи;
}

// Зачины-вопросы на «вы» без местоимения: «Ищете слот без сказок?» — в
// «ты»-наборе они переводятся и без «вы» рядом.
const V5_TY_ЗАЧИНЫ = ['ищете' => 'ищешь', 'хотите' => 'хочешь', 'думаете' => 'думаешь', 'знаете' => 'знаешь',
    'любите' => 'любишь', 'планируете' => 'планируешь', 'мечтаете' => 'мечтаешь', 'ждёте' => 'ждёшь',
    'играете' => 'играешь', 'боитесь' => 'боишься', 'сомневаетесь' => 'сомневаешься', 'надеетесь' => 'надеешься',
    'верите' => 'веришь', 'считаете' => 'считаешь', 'решаете' => 'решаешь', 'можете' => 'можешь', 'готовы' => 'готов'];

function v5NaTy(string $кусок, bool $императивы = true): string
{
    $предлог = '~(?:^|[^а-яё])(?:на|в|во|о|об|обо|при|по|к|ко|от|до|из|у|за|со|с)\s+$~ui';
    return (string) preg_replace_callback('~(?<![а-яёА-ЯЁ])[а-яёА-ЯЁ]{2,}(?![а-яёА-ЯЁ])~u',
        function ($m) use ($кусок, $предлог, $императивы) {
            $низ = mb_strtolower($m[0]);
            $новое = null;
            if (isset(V5_TY_МЕСТОИМЕНИЯ[$низ])) { $новое = V5_TY_МЕСТОИМЕНИЯ[$низ]; }
            elseif (isset(V5_TY_ЗАЧИНЫ[$низ]) && preg_match('~^\p{Lu}~u', $m[0])) { $новое = V5_TY_ЗАЧИНЫ[$низ]; }
            elseif (mb_strlen($низ) >= 6) {
                foreach (['йтесь' => 'йся', 'ьтесь' => 'ься', 'итесь' => 'ись', 'йте' => 'й', 'ьте' => 'ь',
                          'етесь' => 'ешься', 'ётесь' => 'ёшься', 'ете' => 'ешь', 'ёте' => 'ёшь'] as $от => $до) {
                    // Вежливый императив («проверьте», «не забудьте») — норма и
                    // «ты»-страницы доноров (189 «проверьте» в корпусе, поле
                    // imperatives считает именно их); переводится только по флагу.
                    if (!$императивы && !in_array($от, ['ете', 'ёте', 'етесь', 'ётесь'], true)) { continue; }
                    if (mb_substr($низ, -mb_strlen($от)) === $от) {
                        // «-ете» у существительных: «в комплекте», «на паркете» — только после «вы».
                        if (in_array($от, ['ете', 'ёте'], true)) {
                            $до_ = mb_substr($кусок, 0, (int) mb_strpos($кусок, $m[0]));
                            if (!preg_match('~(?<![а-яё])вы\s+(?:[а-яё]+\s+){0,2}$~ui', $до_)) { break; }
                        }
                        $новое = mb_substr($низ, 0, -mb_strlen($от)) . $до; break;
                    }
                }
                if ($новое === null && mb_substr($низ, -3) === 'ите' && !isset(V5_TY_НЕ_ГЛАГОЛ[$низ])) {
                    $до_ = mb_substr($кусок, 0, (int) mb_strpos($кусок, $m[0]));
                    $послеВы = (bool) preg_match('~(?<![а-яё])вы\s+(?:[а-яё]+\s+){0,2}$~ui', $до_);
                    if (!preg_match($предлог, $до_) && ($императивы || $послеВы)) {
                        // После «вы» — личная форма («вы говорите» → «говоришь»), иначе императив.
                        $новое = mb_substr($низ, 0, -3) . (preg_match('~(?<![а-яё])вы\s+(?:[а-яё]+\s+){0,2}$~ui', $до_) ? 'ишь' : 'и');
                    }
                }
            }
            if ($новое === null || $новое === $низ) { return $m[0]; }
            return preg_match('~^\p{Lu}~u', $m[0]) ? mb_strtoupper(mb_substr($новое, 0, 1)) . mb_substr($новое, 1) : $новое;
        }, $кусок);
}

/**
 * Регистр обращения — свойство площадки, а не страницы. Из 76 разобранных
 * комплектов на «вы» пишут одиннадцать, и внутри такого комплекта «вы»
 * держится на всех двенадцати типах, меняется только плотность; «ты» при
 * этом никуда не девается — на registracia его у них вдвое больше, чем
 * «вы». Поэтому регистр выбирается один раз на набор.
 *
 * Раскладка идёт по НОМЕРУ набора, а не по сиду. Прежний ключ — crc32 от
 * сида — сам по себе честен: на шести использованных блоках он даёт 12.8%
 * «вы» при ожидаемых 14.3%, а «вы»-набор проходит приёмку не хуже «ты»
 * (замер на 14 сидах: полных 4/14 против 3/14, страниц 11.00 против 11.14).
 * Плох он другим: в партии из пяти наборов доля — лотерея, и партия 264–268
 * вышла целиком на «ты». Номер набора не лотерея: каждый седьмой — «вы»,
 * ровно 14.3%, и это видно и проверяемо в любой партии.
 *
 * Сид остаётся запасным ключом для безымянных прогонов (A/B, замеры).
 */
function v5ObrashchenieNabora(int $сид, string $имя = ''): string
{
    if (preg_match('~(\d+)$~', $имя, $m)) {
        return (int) $m[1] % 7 === 0 ? 'вы' : 'ты';
    }
    return $сид > 0 && crc32('обращение|' . $сид) % 7 === 0 ? 'вы' : 'ты';
}

/**
 * Подмена целей регистра для «вы»-набора. Абсолютные числа образцов
 * недостижимы: обращений на странице у них 20–43, у нас около двенадцати, а
 * перевод «ты» → «вы» этой суммы не меняет. Достижима доля — её и держим,
 * полем `vy_share`, где оба регистра считаются местоимениями и потому
 * сравнимы между собой.
 *
 * Поля `vy`, `ty` и `imperatives` получают числа подгруппы для отчёта, но
 * держать их нельзя: `vy` в базовом профиле стоит нулём (корпус доноров
 * пишет на «ты»), и «вы»-набор проваливал бы его при любом переводе.
 */
function v5PoliaObrashcheniya(array $поля, array $профиль, string $тип,
                              string $обращение, array $карта = []): array
{
    if ($обращение !== 'вы') {
        // «Ты»-набор без вежливых форм: императивы на -йте/-ите/-ьте не держим.
        if (isset($поля['imperatives'])) { $поля['imperatives']['держат'] = false; }
        return $поля;
    }
    $цели = $профиль['обращение_вы']['типы'][$тип] ?? null;
    if (!$цели || !isset($цели['vy_share'])) { return $поля; }
    foreach (['vy', 'ty', 'imperatives'] as $ключ) {
        if (!isset($поля[$ключ], $цели[$ключ])) { continue; }
        $поля[$ключ]['цель'] = (float) $цели[$ключ];
        // Ни одно из трёх счётом не держим. Базовый профиль запрещает «вы» на
        // всех типах и императивы на promo и slots, а «вы»-подгруппа пишет
        // там и то и другое: две цели прямо противоречат друг другу, и
        // держать обе нельзя. Регистр держится долей — vy_share, — а эти
        // числа остаются ориентиром для рычагов перекрута и для отчёта.
        $поля[$ключ]['держат'] = false;
    }
    // Страница почти без обращений — регистру не на чем проявиться, и
    // требовать доли значит требовать вписать «вы» туда, где его нет.
    if ((int) ($карта['address_total'] ?? 0) < 4) { return $поля; }
    // Один регистр: доля «вы» — почти вся страница, полоса лишь ловит утечки «ты».
    $ц = 100.0;
    $полуполоса = 12.0;
    $поля['vy_share'] = [
        'подпись' => 'доля «вы» среди обращений, %',
        'цель'    => $ц,
        'дробное' => true,
        'держат'  => true,
        'полоса'  => [max(0.0, $ц - $полуполоса), min(100.0, $ц + $полуполоса)],
        'край'    => [max(0.0, $ц - $полуполоса), min(100.0, $ц + $полуполоса)],
    ];
    return $поля;
}

/**
 * Чужая метафорическая шкура. Один донор писал всю площадку в королевских
 * образах — трон, скипетр, корона, дворец, — другой в кладоискательских.
 * Внутри своего набора это цельный приём, но в общем пуле фразы разъезжаются
 * по чужим комплектам, и «условия отыгрыша — это страж у врат сокровищницы»
 * оказывается в тексте про бонусы рядом с обычной прозой.
 *
 * Замер: такой лексики у нас 1.24 на страницу против 0.90 у конкурента и
 * 0.53 у доноров, и весь перевес — на этих фразах.
 *
 * Третья шкура — подводная: Атлантида, жемчуг, затонувший клад, погружение
 * за сокровищами. В пулах её 215 записей (0,24 %), и в чужом наборе она
 * читается так же чужеродно: «Готовы нырнуть за своим главным сокровищем?»
 * посреди страницы про верификацию.
 *
 * Ловим только существительные шкуры. Прилагательное «королевский» —
 * обычный усилитель («королевский джекпот», «королевская сумма»), его
 * доноры пишут вне всякой сказки, и трогать его нельзя. По той же причине
 * не ловим «глубину» и «подводный»: «без подводных камней» — жанровая
 * идиома, а не сказка, и таких записей в пулах три десятка.
 */
function v5ChuzhayaShkura(string $текст): bool
{
    return (bool) preg_match(
        '~\b(трон[ае]?\b|скипетр\w*|корон[аыуое]\w*|коронаци\w*|дворц\w*|дворец\b'
        . '|королевств\w*|сокровищ\w*|врата\w*|стражник\w*|заклинани\w*'
        . '|колдовств\w*|атлантид\w*|затонувш\w*|русалк\w*'
        . '|нептун\w*|погружени\w*|погрузи\w*|нырну\w*'
        // «жемчуг» ловился, «жемчужный» и «жемчужина» — нет: в корне
        // чередование г→ж. На странице проходил «Наш Жемчужный Бонус».
        . '|жемчуг\w*|жемчуж\w*'
