/** Узлы верхнего уровня: у корпуса они начинаются с нулевой колонки. */
function v5Uzly(string $html): array
{
    $lines = explode("\n", $html);
    $uzly = [];
    for ($i = 0, $n = count($lines); $i < $n; $i++) {
        $l = $lines[$i];
        if ($l === '' || $l[0] !== '<' || str_starts_with($l, '</')) { continue; }
        if (!preg_match('~^<([a-z0-9]+)([^>]*)>~i', $l, $m)) { continue; }
        [, $tag, $attrs] = $m;
        $класс = preg_match('~class="([^"]*)"~', $attrs, $c) ? $c[1] : '';
        $конец = "</$tag>";
        $j = $i;
        if (!str_contains($l, $конец)) {
            for ($j = $i + 1; $j < $n; $j++) { if (str_starts_with($lines[$j], $конец)) { break; } }
        }
        $j = min($j, $n - 1);
        $uzly[] = ['тег' => $tag, 'класс' => $класс,
                   'html' => implode("\n", array_slice($lines, $i, $j - $i + 1))];
        $i = $j;
    }
    return $uzly;
}

function v5Text(string $html): string
{
    return trim(preg_replace('~\s+~u', ' ',
        html_entity_decode(preg_replace('~<[^>]*>~', ' ', $html), ENT_QUOTES, 'UTF-8')));
}

/** Внутренность узла одной строкой — ссылки и выделения сохраняются. */
function v5Vnutr(string $html): string
{
    $t = preg_replace('~^<[a-z0-9]+[^>]*>~i', '', $html);
    $t = preg_replace('~</[a-z0-9]+>$~i', '', $t);
    return trim(preg_replace('~\s*\n\s*~u', ' ', $t));
}

function v5Klass(array $u): string
{
    $c = trim(explode(' ', $u['класс'])[0] ?? '');
    return $c !== '' ? $c : $u['тег'];
}

function v5Variant(array $u): string
{
    return preg_match('~\bvariant-(v\d+)~', $u['класс'], $m) ? $m[1] : 'v0';
}

/**
 * Трафарет: числа и герои заменяются прорезями, наблюдённые значения копятся
 * в банки (второй аргумент — по ссылке, можно пустой).
 *
 * Разметка стоит между числом и его словом («до <strong>75%</strong>»), поэтому
 * привязка идёт не к предлогу, а к форме самого числа: дробный процент в этой
 * нише всегда RTP, целый — бонус или кэшбэк. Порядок правил важен: каталог и
 * провайдеры ловятся раньше денег, иначе «1 394+ слотов» уйдёт в рубли.
 */
function v5Trafaret(string $t, array &$банки = []): string
{
    // Чужие прорези доноров приводятся к нашим сразу: иначе «{ИМЯ} проверил» и
    // «{NAME} проверил» остаются разными ключами пула, а после подстановки дают
    // один и тот же заголовок. На десятом наборе это выдало два одинаковых H2
    // подряд, причём второй без тела.
    foreach (V5_CHUZHIE_PROREZI as $чужой => $наш) {
        $t = str_replace('{' . $чужой . '}', '{' . $наш . '}', $t);
    }
    static $имена = null, $ном = null;
    if ($имена === null) {
        $r = new ReflectionClass('PersonNames');
        $ном = array_flip($r->getConstant('BASE'));
        $имена = PersonNames::regex();
    }
    $правила = [
        ['СЛОТОВ',      '~\b\d{1,2}\s?\d{3}(?=\+\s*(?:слот|игр|автомат))~u'],
        // Тот же размер каталога, но без плюса: «более 2000 автоматов».
        // Без этого правила число оставалось живым и расходилось со своей
        // же прорезью на соседней странице — смысловая приёмка ловит это
        // как «слотов расходится по страницам: 1 394 (main) · 2000 (vhod)».
        ['СЛОТОВ',      '~(?<=более )\d[\d ]{2,4}(?=\s*(?:слот|игр|автомат))~ui'],
        ['СЛОТОВ',      '~(?<=более чем )\d[\d ]{2,4}(?=\s*(?:слот|игр|автомат))~ui'],
        ['СЛОТОВ',      '~(?<=свыше )\d[\d ]{2,4}(?=\s*(?:слот|игр|автомат))~ui'],
        ['СЛОТОВ',      '~(?<=свыше чем )\d[\d ]{2,4}(?=\s*(?:слот|игр|автомат))~ui'],
        ['СЛОТОВ',      '~(?<=около )\d[\d ]{2,4}(?=\s*(?:слот|игр|автомат))~ui'],
        ['СЛОТОВ',      '~(?<=около чем )\d[\d ]{2,4}(?=\s*(?:слот|игр|автомат))~ui'],
        ['СЛОТОВ',      '~(?<=порядка )\d[\d ]{2,4}(?=\s*(?:слот|игр|автомат))~ui'],
        ['СЛОТОВ',      '~(?<=порядка чем )\d[\d ]{2,4}(?=\s*(?:слот|игр|автомат))~ui'],
        ['ПРОВАЙДЕРОВ', '~\b\d{2,3}(?=\+\s*провайдер)~u'],
        ['СУММА',       '~\b\d+(?:[.,]\d+)?\s?(?:к|тыс\.?|млн)\b~u'],
        ['РУБЛИ',       '~(?<!\d)(?<!\d )\d{1,3}(?:\s\d{3})*\s?(?:₽|рубл\w+)~u'],
        ['RTP',         '~(?<=RTP )\d{2}(?:[.,]\d)?(?=%)~u'],
        // Два знака после точки — это отдача в карточке слота («96.51%»). Без
        // отдельного правила её хвост забирал процент бонуса, и в выдаче
        // появлялось «96.286%»: целое от карточки, дробь от чужого банка.
        ['RTP2',        '~\b\d{2}[.,]\d{2}(?=%)~u'],
        ['RTP',         '~\b\d{2}[.,]\d(?=%)~u'],
        // «до 500%» и «кэшбэк 10%» — разные величины. Пока они лежали в одном
        // банке, бонус подставлялся долей, и в тексте появлялось «бонус до 13%»
        // при корпусной полосе бонуса 15–1000.
        ['ПРОЦ',        '~(?<![\d.,])\d{2,4}(?=%)~u'],
        ['МИН',         '~(?<=за )\d{1,3}(?= мин)~u'],
        ['МИН',         '~(?<=от )\d{1,3}(?= мин)~u'],
        ['ВЕЙДЖЕР',     '~(?<=x)\d{2}\b~u'],
    ];
    foreach ($правила as [$имя, $re]) {
        $t = preg_replace_callback($re, function ($m) use ($имя, &$банки, $t) {
            // «RTP достигает 92%» — это отдача, а не бонус: между словом и
            // числом стоит глагол, и лобовое правило уводило значение в банк
            // процентов, откуда потом приезжало «RTP 445%».
            $до = mb_substr($t, 0, (int) mb_strpos($t, $m[0]));
            if ($имя === 'ПРОЦ') {
                $хвост = preg_replace('~<[^>]*>~', '', mb_substr($до, -40));
                if (preg_match('~RTP[^%]{0,24}$~u', $до)) { $имя = 'RTP'; }
                elseif (!preg_match('~\bдо\s*$~u', $хвост)) { $имя = 'ДОЛЯ'; }
            }
            $банки[$имя][$m[0]] = ($банки[$имя][$m[0]] ?? 0) + 1;
            return '{' . $имя . '}';
        }, $t);
    }
    // Имя героя: 94 % вхождений в именительном, остальные — с окончанием,
    // и окончание переносится в прорезь, чтобы генератор склонил своё имя.
    return preg_replace_callback($имена, function ($m) use ($ном, &$банки) {
        $форма = $m[0];
        if (isset($ном[$форма])) {
            $прорезь = v5Rod($форма) === 'ж' ? 'ИМЯЖ' : 'ИМЯ';
            $банки[$прорезь][$форма] = ($банки[$прорезь][$форма] ?? 0) + 1;
            return '{' . $прорезь . '}';
        }
        // «Люди» разбирались как «Люда» в косвенном падеже, и в выдачу уходило
        // «Елени хвалят скорость» вместо «Люди хвалят скорость». Совпадение
        // корня с именем из банка ещё не делает форму именем.
        if (isset(V5_NE_IMENA[mb_strtolower($форма)])) { return $форма; }
        foreach (['ом', 'ей', 'ой', 'а', 'у', 'е', 'ы', 'и', 'ю', 'я'] as $ок) {
            if (mb_substr($форма, -mb_strlen($ок)) !== $ок) { continue; }
            $корень = mb_substr($форма, 0, mb_strlen($форма) - mb_strlen($ок));
            foreach ([$корень, $корень . 'й', $корень . 'ь', $корень . 'а', $корень . 'я'] as $кандидат) {
                if (isset($ном[$кандидат])) {
                    return '{' . (v5Rod($кандидат) === 'ж' ? 'ИМЯЖ' : 'ИМЯ') . ':' . $ок . '}';
                }
            }
        }
        return '{ИМЯ}';
    }, $t);
}

/**
 * Соседние предложения-двойники. Отбор фраз считает близость по цепочкам из
 * четырёх слов, и пара вроде «Если нужны гарантии — вам не сюда» и «Если
 * нужны гарантии — это не сюда» через неё проходит: общая только одна
 * цепочка. Рядом они читаются как заедание. У доноров и у конкурента таких
 * пар 0.02 на страницу, поэтому режем по составу знаменательных слов.
 */
function v5UbratSosedniiPovtor(string $html, float $порог = 0.55): string
{
    $знач = static function (string $ф): array {
        preg_match_all('~[а-яё]{4,}~u', mb_strtolower(strip_tags($ф), 'UTF-8'), $m);
        return array_flip($m[0]);
    };
    $двойник = static function (array $a, array $b) use ($порог): bool {
        if (!$a || !$b) { return false; }
        $всех = count($a + $b);
        return $всех > 0 && count(array_intersect_key($a, $b)) / $всех > $порог;
    };
    // Хвост предыдущего блока помним между вызовами: пара «последняя фраза
    // абзаца — первая фраза следующего» читается так же плохо, как пара
    // внутри одного абзаца, а разделяет их только перевод строки.
    $прошлое = null;
    return preg_replace_callback('~(?s)(<(p|li)\b[^>]*>)(.*?)(</\2>)~',
        function ($m) use ($знач, $двойник, &$прошлое) {
            // Режем по границам предложений прямо в разметке: выброшенный
            // кусок уходит вместе со своими ссылками и выделениями.
            // Точка нередко стоит внутри выделения: «…не сюда.</strong> Но…».
            // Закрывающие теги пропускаем, иначе два предложения слипаются в
            // один кусок и разница по словам размывается.
            // Точка нередко стоит внутри выделения: «…не сюда.</strong> Но…».
            // Закрывающие теги забираем в разделитель, иначе два предложения
            // слипаются в один кусок и разница по словам размывается.
            $куски = preg_split('~(?<=[.!?;])((?:\s*</[a-zA-Z]+>)*\s+)~u', $m[3], -1,
                PREG_SPLIT_NO_EMPTY | PREG_SPLIT_DELIM_CAPTURE);
            $оставить = []; $последнее = $прошлое;
            // Куски идут парами «предложение + разделитель». Выбрасываем пару
            // целиком: закрывающий тег предложения лежит в его разделителе.
            for ($i = 0; $i < count($куски); $i += 2) {
                $фраза = $куски[$i];
                $хвост = $куски[$i + 1] ?? '';
                if (trim(strip_tags($фраза)) === '') { $оставить[] = $фраза . $хвост; continue; }
                $с = $знач($фраза);
                if ($последнее !== null && $двойник($с, $последнее)) { continue; }
                $оставить[] = $фраза . $хвост;
                $последнее = $с;
            }
            $прошлое = $последнее;
            $тело = implode('', $оставить);
            // Блок, от которого ничего не осталось, убираем целиком.
            return trim(strip_tags($тело)) === '' ? '' : $m[1] . $тело . $m[4];
        }, $html);
}

/**
 * Клише в узде. «Движ для смелых» четыре раза на странице читается как
 * машина: у конкурента самый частый штамп повторяется 3.0 раза, у нас 4.2,
 * а всего штампов 12.6 против 8.7. Со второго повтора подставляем замену
 * той же длины и того же смысла, по кругу.
 */
const V5_SHTAMPY = [
    'движ для смелых'  => ['история про риск', 'затея для крепких нервов', 'игра без подстраховки'],
    'без развода'      => ['без обмана', 'начистоту'],
    'гарантий нет'     => ['никто ничего не обещает', 'обещаний тут не раздают'],
    'красивая история' => ['звучит красиво', 'история хорошая'],
    'холодной головой' => ['на трезвую голову', 'без горячки'],
    'без магии'        => ['без чудес', 'без волшебства'],
    'без сказок'       => ['без прикрас', 'без красивых слов'],
    'розовых очков'    => ['лишнего оптимизма', 'иллюзий'],
];

function v5UkrotitShtampy(string $html, int $предел = 2): string
{
    foreach (V5_SHTAMPY as $штамп => $замены) {
        $счёт = 0; $круг = 0;
        $html = preg_replace_callback('~' . preg_quote($штамп, '~') . '~ui',
            function ($m) use (&$счёт, &$круг, $замены, $предел) {
                if (++$счёт <= $предел) { return $m[0]; }
                $новое = $замены[$круг++ % count($замены)];
                // Заглавная в начале предложения сохраняется.
                return mb_strtoupper(mb_substr($m[0], 0, 1)) === mb_substr($m[0], 0, 1)
                    ? mb_strtoupper(mb_substr($новое, 0, 1)) . mb_substr($новое, 1)
                    : $новое;
            }, $html);
    }
    return $html;
}

/**
 * Падежи у ссылок. Метка ссылки — глагольная («играть бесплатно», «войти в
 * казино»), и предлог перед ней читается как обрыв: «проверить через играть
 * бесплатно», «следить за новости казино». У конкурента таких сочетаний 0.38
 * на страницу, у нас было 1.03.
 *
 * Чиним заменой метки на именную того же адреса: одна метка — один адрес,
 * это правило сохраняется.
 */
function v5PochinitPadezhi(string $html): string
{
    $правила = [
        // глагольная метка каталога после предлога → «демо-режим»
        '~\b(через|у)\s+(<a href="/slots"[^>]*>)играть бесплатно</a>~ui' => '$1 $2демо-режиме</a>',
        '~\b(в|во)\s+(<a href="/slots"[^>]*>)играть бесплатно</a>~ui'    => '$1 $2демо-режиме</a>',
        '~\b(на|за)\s+(<a href="/slots"[^>]*>)играть бесплатно</a>~ui'   => 'в $2демо-режим</a>',
        // глагольная метка входа после «через» → именная
        '~\bчерез\s+(<a href="/vhod"[^>]*>)(?:войти в казино|войти и активировать|войти)</a>~ui'
            => 'через $1вход в личный кабинет</a>',
        // «следить за слоты» → «за слотами», «за новости казино» → «новостями»
        '~\bза\s+(<a href="/slots"[^>]*>)слоты</a>~ui'   => 'за $1слотами</a>',
        '~\bза\s+(<a href="/"[^>]*>)новости казино</a>~ui' => 'за $1новостями казино</a>',
        // «после регистрацию» → «после регистрации»
        '~\b(после|без|для|из|от|около|кроме)\s+(<a href="/registracia"[^>]*>)регистрацию</a>~ui'
            => '$1 $2регистрации</a>',
    ];
    return preg_replace(array_keys($правила), array_values($правила), $html);
}

/** Формы, у которых корень совпадает с именем из банка, а сами они не имена. */
const V5_NE_IMENA = ['люди' => 1, 'дети' => 1, 'гости' => 1, 'кости' => 1,
                     'игры' => 1, 'веры' => 1, 'славы' => 1, 'розы' => 1];

/**
 * Своя цель набора внутри корпусной полосы.
 *
 * Профиль даёт медиану корпуса, и до сих пор каждый набор целился ровно в
 * неё. На тридцати одном наборе это видно: разброс между наборами у нас
 * 35.6 % против 135.4 % у конкурента — тридцать сайтов как один. Здесь
 * медиана сдвигается на половину полосы в сторону, своя у каждого набора
 * и своя у каждого поля. Ворота приёмки остаются корпусными: сдвиг вдвое
 * меньше допуска, и набор из полосы не выходит.
 *
 * Нулевая цель — запрет, а не полоса: её не двигаем.
 */
function v5CelNabora(array $поле, int $сид, string $ключ): float
{
    $цель = (float) ($поле['цель'] ?? 0.0);
    if ($цель <= 0.0) { return $цель; }
    $полуполоса = max(0.25 * abs($цель), !empty($поле['дробное']) ? 0.8 : 2.0);
    // Сдвиг детерминирован: тот же набор и то же поле дают тот же результат,
    // пересборка набора не «поедет».
    $зерно = crc32($ключ . '|' . $сид);
    $доля = ($зерно % 1000) / 1000 * 2 - 1;          // −1 … +1
    $сдвиг = $доля * $полуполоса * 0.5;
    $итог = $цель + $сдвиг;
    return empty($поле['дробное']) ? round($итог) : round($итог, 1);
}

/** Число из денежной строки: «2 000 рублей» → 2000, «500₽» → 500. */
function v5Rubli(string $s): int
{
    return (int) preg_replace('~\D~u', '', $s);
}

/**
 * Род имени. Донор пишет «Елена зашла», и если подставить мужское имя, глагол
 * останется женским: пол героя — часть прорези, а не украшение. Правило —
 * окончание «а/я», за вычетом мужских имён с той же формой.
 */
function v5Rod(string $имя): string
{
    static $мужскиеНаА = ['Никита' => 1, 'Илья' => 1, 'Данила' => 1, 'Гриша' => 1, 'Паша' => 1,
        'Миша' => 1, 'Саша' => 1, 'Женя' => 1, 'Сева' => 1, 'Толя' => 1, 'Коля' => 1, 'Витя' => 1,
        'Слава' => 1, 'Дима' => 1, 'Лёша' => 1, 'Леша' => 1, 'Ваня' => 1, 'Юра' => 1, 'Костя' => 1,
        'Стёпа' => 1, 'Петя' => 1, 'Вася' => 1, 'Боря' => 1, 'Серёжа' => 1, 'Рома' => 1];
    if (isset($мужскиеНаА[$имя])) { return 'м'; }
    return in_array(mb_substr($имя, -1), ['а', 'я'], true) ? 'ж' : 'м';
}

/**
 * Склонение имени под окончание, снятое с донора. Разбор трёх типов основы
 * покрывает весь словарь: согласная (Виктор), «й» (Григорий, Андрей) и
 * «а/я» (Ольга, Илья). Падеж угадывается по окончанию донора, потому что
 * в корпусе он всегда однозначен: «у {ИМЯ:а}», «{ИМЯ:у} повезло».
 */
function v5Sklonenie(string $имя, string $ок): string
{
    $мягкая = ['а' => 'я', 'у' => 'ю', 'ом' => 'ем', 'е' => 'е', 'ы' => 'и', 'и' => 'и', 'ю' => 'ю', 'я' => 'я', 'ей' => 'ем', 'ой' => 'ем'];
    $женская = ['а' => 'ы', 'у' => 'е', 'ом' => 'ой', 'ой' => 'ой', 'е' => 'е', 'ы' => 'ы', 'и' => 'и', 'ю' => 'ю', 'я' => 'я', 'ей' => 'ей'];
    $последняя = mb_substr($имя, -1);
    if ($последняя === 'а' || $последняя === 'я') {
        return mb_substr($имя, 0, -1) . ($женская[$ок] ?? $ок);
    }
    if ($последняя === 'й' || $последняя === 'ь') {
        return mb_substr($имя, 0, -1) . ($мягкая[$ок] ?? $ок);
    }
    return $имя . $ок;
}

/**
 * Заполнение трафарета: `$значение('ПРОЦ')` возвращает значение прорези.
 * Имя выдаётся через `$значение('ИМЯ')` и склоняется здесь же.
 */
/**
 * Прорези доноров. В корпусе остались плейсхолдеры чужой шаблонизации —
 * `{NAME}` в заголовках слотов, `{AMOUNT}` рядом с ним. Своими именами мы их
 * не знаем, а подставить надо: заголовок «Джекпот слоты — {NAME} сорвал
 * {AMOUNT} здесь» уехал в выдачу как «— 0 сорвал 0 здесь».
 */
const V5_CHUZHIE_PROREZI = ['NAME' => 'ИМЯ', 'AMOUNT' => 'СУММА'];

function v5Zapolnit(string $t, callable $значение): string
{
    // Имя прорези может содержать цифру (`{RTP2}`) — без этого подстановка
    // молча проходит мимо, и в выдачу уезжает сам плейсхолдер.
    return preg_replace_callback('~\{([А-ЯA-Z][А-ЯA-Z0-9]*)(?::([а-я]{1,2}))?\}~u', function ($m) use ($значение) {
        $ключ = V5_CHUZHIE_PROREZI[$m[1]] ?? $m[1];
        $v = (string) $значение($ключ);
        // Незнакомая прорезь остаётся собой: ноль вместо имени приёмка не
        // ловит, а сам плейсхолдер — ловит.
        if ($v === '' || $v === '0') { return $m[0]; }
        $имя = $ключ === 'ИМЯ' || $ключ === 'ИМЯЖ';
        return ($имя && ($m[2] ?? '') !== '') ? v5Sklonenie($v, $m[2]) : $v;
    }, $t);
}

/**
 * Близость двух кусков по четырёхсловным цепочкам. Пул одного раздела набран
 * с одиннадцати доноров, а фабрика писала их по одному шаблону: «Джекпот до X
 * звучит громко, однако вероятность не равна гарантии» встречается в трёх
 * переписываниях. Рядом в одном списке они читаются как заедание.
 */
function v5Blizost(string $a, string $b): float
{
    $ц = function (string $t): array {
        $w = preg_split('~\s+~u', mb_strtolower(preg_replace('~[^а-яёa-z0-9 ]+~u', ' ',
            preg_replace('~<[^>]*>~', ' ', $t))), -1, PREG_SPLIT_NO_EMPTY);
        $o = [];
        for ($i = 0; $i + 4 <= count($w); $i++) { $o[implode(' ', array_slice($w, $i, 4))] = 1; }
        return $o;
    };
    $x = $ц($a); $y = $ц($b);
    if (!$x || !$y) { return 0.0; }
    return count(array_intersect_key($x, $y)) / min(count($x), count($y));
}

/**
 * Разбор абзаца на предложения с сохранением встроенной разметки.
 *
 * Перенос абзацев целиком даёт с донором столько же совпадения, сколько доля
 * его абзацев в нашей странице, — на замере это 16–26 % против корпусного
 * потолка 8–11 %. Шингл в шесть слов рвётся на границе предложения, поэтому
 * абзац собирается из предложений разных доноров, и доля каждого падает втрое.
 *
 * Теги вынимаются перед разрезкой и возвращаются после: точка внутри
 * `href="сайт.com"` — не конец предложения. Предложение с непарным тегом
 * отбрасывается: собирать из него абзац нельзя.
 */
function v5Predlozheniya(string $html): array
{
    $теги = [];
    $без = preg_replace_callback('~<[^>]+>~', function ($m) use (&$теги) {
        $теги[] = $m[0];
        return "\x01" . (count($теги) - 1) . "\x02";
    }, $html);
    $куски = preg_split('~(?<=[.!?…])\s+~u', $без, -1, PREG_SPLIT_NO_EMPTY) ?: [];
    $итог = [];
    foreach ($куски as $к) {
        $п = preg_replace_callback('~\x01(\d+)\x02~', fn($m) => $теги[(int) $m[1]], $к);
        $открыто = preg_match_all('~<([a-z0-9]+)(?:\s[^>]*)?>~i', $п, $o);
        $закрыто = preg_match_all('~</([a-z0-9]+)>~i', $п, $c);
        if ($открыто !== $закрыто) { continue; }
        $п = trim($п);
        if (mb_strlen($п) < 15) { continue; }
        $итог[] = $п;
    }
    return $итог;
}

/**
 * Текстовые прорези виджета: строки, где лежит текст, и роль каждой — класс
 * ближайшего предка с классом (иначе itemprop, иначе тег).
 *
 * Виджет нельзя переносить от одного донора целиком: разметка у всех общая, а
 * текст в ней свой, и перенос даёт кусок дословного совпадения размером в пол
 * страницы. Роли же у доноров одни и те же — `hero-tagline`, `payout-name`,
 * `pillar-text`, — поэтому каждая строка набирается из своего пула.
 *
 * Пары «вопрос-ответ» из этого исключены: их надо менять парой, иначе ответ
 * встанет под чужим вопросом. Ими занимается отдельная подстановка.
 */
const V5_ROLI_PAROJ = ['faq-question', 'text', 'review-quote-text'];

function v5Sloty(string $html): array
{
    $строки = explode("\n", $html);
    $стек = []; $слоты = [];
    foreach ($строки as $i => $l) {
        $t = trim($l);
        if ($t === '') { continue; }
        if ($t[0] !== '<') { $слоты[] = ['строка' => $i, 'роль' => end($стек) ?: '?']; continue; }
        if (str_starts_with($t, '</')) { array_pop($стек); continue; }
        if (!preg_match('~^<([a-z0-9]+)([^>]*)>~i', $t, $m)) { continue; }
        $роль = preg_match('~class="([^"]*)"~', $m[2], $c) ? explode(' ', trim($c[1]))[0]
              : (preg_match('~itemprop="([^"]*)"~', $m[2], $ip) ? $ip[1] : $m[1]);
        if ($роль === '') { $роль = $m[1]; }
        $пустой = str_ends_with($t, '/>') || in_array(strtolower($m[1]), ['meta', 'img', 'br', 'input', 'hr'], true);
        if ($пустой) { continue; }
        if (preg_match('~^<[a-z0-9]+[^>]*>(.+)</[a-z0-9]+>\s*$~i', $t)) {
            $слоты[] = ['строка' => $i, 'роль' => $роль, 'встроенный' => true];
            continue;
        }
        $стек[] = $роль;
    }
    return $слоты;
}

/** Вёрстка узла в стиле корпуса: тег на нулевой колонке, текст с отступом. */
function v5Uzel(string $tag, string $inner, string $attrs = ''): string
{
    return "<{$tag}{$attrs}>\n  " . $inner . "\n</{$tag}>";
}

function v5Spisok(array $пункты, string $tag = 'ul'): string
{
    $o = "<{$tag}>\n";
    foreach ($пункты as $п) { $o .= "  <li>\n    " . $п . "\n  </li>\n"; }
    return $o . "</{$tag}>";
}

/**
 * Ремонт денежной пары в предложении.
 *
 * Донор пишет ставку числом внутри фразы, а результат отдаёт прорезью {РУБЛИ}.
 * Прорезь в узле выдаётся первой, то есть из младшей — ставочной — половины
 * банка, и герой «заходит с 1000 ₽ и доводит сумму до 200 рублей». Проверка
 * смысла ловит это как «результат меньше ставки»; здесь оно чинится на месте:
 * итог заменяется на запись из банка, которая крупнее ставки, с сохранением
 * написания валюты из исходной фразы.
 *
 * @param array<string, mixed> $рубли банк РУБЛИ: ключи — денежные строки
 */
function v5PochinitDengi(string $html, array $рубли): string
{
    // Банк режется по написанию валюты: «120 000 ₽» и «120 000 рублей» — это
    // разные строки, и подставлять нужно ту, что совпадает с исходной фразой.
    $поВалюте = ['₽' => [], 'рубли' => []];
    foreach (array_keys($рубли) as $s) {
        $s = (string) $s;
        $n = v5Rubli($s);
        // «000 ₽» и «0₽» — обломки разбора: он разорвал «120 000 ₽» по пробелу.
        if ($n < 1000 || preg_match('~^\D*0~u', $s)) { continue; }
        $вид = mb_strpos($s, '₽') !== false ? '₽' : 'рубли';
        $поВалюте[$вид][$n] = trim(preg_replace('~\s*(?:₽|рубл\w+)\s*$~u', '', $s));
    }
    foreach ($поВалюте as &$список) { ksort($список); }
    unset($список);
    if (!$поВалюте['₽'] && !$поВалюте['рубли']) { return $html; }

    $re = '~((?:зашёл|зашла|начал|начала|пополнил|пополнила|поставил|поставила)[^.!?<]{0,80}?'
        . '(\d[\d\x{00A0} ]*?)\s?(?:₽|рубл\w+)[^.!?<]{0,110}?'
        . '(?:довёл|довела|поднял|подняла|вырос\w*|забрал|забрала|до)\s+)'
        . '(\d[\d\x{00A0} ]*?)\s?(₽|рубл\w+)~u';

    return (string) preg_replace_callback($re, function (array $m) use ($поВалюте): string {
        $ставка = v5Rubli($m[2]);
        $итог   = v5Rubli($m[3]);
        if ($ставка <= 0 || $итог > $ставка) { return $m[0]; }
        $вид = $m[4] === '₽' ? '₽' : 'рубли';
        $список = $поВалюте[$вид] ?: ($поВалюте['₽'] ?: $поВалюте['рубли']);
        // Результат в корпусе кратно больше ставки: «зашёл с 1000 ₽ и довёл до
        // 1050 ₽» читается не лучше сломанной подстановки. Порог — десять
        // ставок, с откатом на три и на самую крупную запись банка.
        $новое = null;
        foreach ([10, 3, 1] as $кратность) {
            foreach ($список as $n => $запись) {
                if ($n >= $ставка * $кратность) { $новое = [$n, $запись]; break 2; }
            }
        }
        if ($новое === null || $новое[0] <= $ставка) { return $m[0]; }
        return $m[1] . $новое[1] . ' ' . $m[4];
    }, $html);
}

/**
 * Согласование числительного с существительным времени.
 *
 * Донор пишет «вывод за 3 минуты» — форма верна для двух, трёх и четырёх.
 * Прорезь катит в этот шаблон любое число, и получается «за 20 минуты»,
 * «за 47 минуты». В корпусе такого нет: доноры просто не выпали на другие
 * числа. Правило простое и покрывает весь встречающийся набор слов.
 */
function v5PochinitChislo(string $html): string
{
    static $формы = [
        'минуты'  => ['минута', 'минуты', 'минут'],
        'минут'   => ['минута', 'минуты', 'минут'],
        'часа'    => ['час', 'часа', 'часов'],
        'часов'   => ['час', 'часа', 'часов'],
        'дня'     => ['день', 'дня', 'дней'],
        'дней'    => ['день', 'дня', 'дней'],
        'секунды' => ['секунда', 'секунды', 'секунд'],
        'секунд'  => ['секунда', 'секунды', 'секунд'],
    ];
    $ключи = implode('|', array_keys($формы));

    return (string) preg_replace_callback(
        '~(\S+\s)?(\d+)(\s|&nbsp;)(' . $ключи . ')\b~u',
        function (array $m) use ($формы): string {
            // «до 1 часа», «от 40 минут» — родительный по предлогу, это норма.
            static $предлоги = ['до' => 1, 'от' => 1, 'около' => 1, 'порядка' => 1,
                                'свыше' => 1, 'более' => 1, 'менее' => 1];
            $перед = trim((string) $m[1]);
            if (isset($предлоги[mb_strtolower($перед)])) { return $m[0]; }

            $n = (int) $m[2];
            $сотня = $n % 100;
            $конец = $n % 10;
            if ($сотня >= 11 && $сотня <= 14) { $форма = 2; }
            elseif ($конец === 1)             { $форма = 0; }
            elseif ($конец >= 2 && $конец <= 4) { $форма = 1; }
            else                                { $форма = 2; }

            return ($m[1] ?? '') . $m[2] . $m[3] . $формы[$m[4]][$форма];
        }, $html);
}

/**
 * Баланс кавычек на странице.
 *
 * В библиотеке попадаются куски, где реплика открылась и не закрылась —
 * разбор донора разрезал цитату пополам. На странице это выглядит как
 * «Мне повезло. без пары или как одинокая » в конце чужой фразы.
 *
 * Считаем только текст вне тегов: в атрибутах кавычки свои. Лишний
 * закрывающий убираем, незакрытый открывающий закрываем по концу его
 * предложения — донор пишет реплику именно так.
 */
function v5PochinitKavychki(string $html): string
{
    // Куски текста вне тегов: смещение в исходной строке и сам текст.
    preg_match_all('~>[^<]+~u', $html, $m, PREG_OFFSET_CAPTURE);
    if (!$m[0]) { return $html; }

    $карта = [];            // позиция в потоке → позиция в html
    $поток = '';
    foreach ($m[0] as [$кусок, $смещение]) {
        $len = strlen($кусок);
        for ($i = 1; $i < $len; $i++) {   // единицу пропускаем: это сам «>»
            $карта[strlen($поток)] = $смещение + $i;
            $поток .= $кусок[$i];
        }
    }

    $правки = [];           // позиция в html → что делать
    $стек = [];
    $длина = strlen($поток);
    for ($i = 0; $i < $длина; $i++) {
        if (substr($поток, $i, 2) === "\xc2\xab") {          // «
            $стек[] = $i;
        } elseif (substr($поток, $i, 2) === "\xc2\xbb") {    // »
            if ($стек) { array_pop($стек); }
            else { $правки[$карта[$i]] = ['убрать', 2]; }
        }
    }
    // Незакрытая реплика: ставим » после конца её предложения.
    foreach ($стек as $поз) {
        $конец = null;
        for ($i = $поз + 2; $i < $длина; $i++) {
            if (strpos('.!?', $поток[$i]) !== false) { $конец = $i; break; }
        }
        if ($конец === null || !isset($карта[$конец])) {
            $правки[$карта[$поз]] = ['убрать', 2];           // закрывать негде — снимаем открывающую
        } else {
            $правки[$карта[$конец] + 1] = ['вставить', "\xc2\xbb"];
        }
    }
    if (!$правки) { return $html; }

    krsort($правки);        // правим с конца, чтобы смещения не поехали
    foreach ($правки as $поз => [$что, $чем]) {
        $html = $что === 'убрать'
            ? substr($html, 0, $поз) . substr($html, $поз + $чем)
            : substr($html, 0, $поз) . $чем . substr($html, $поз);
    }
    return $html;
}

/**
 * Один и тот же виджет лежит в библиотеке под двумя оболочками
 * (faq-section и info-block), поэтому сборка иногда ставит на страницу
 * обе копии: одинаковый заголовок, одинаковый текст и одинаковый
 * id="toc-N". Вторую копию убираем целиком.
 *
 * Копия не всегда обёрнута в свой <div>: бывает голая пара «<h2> плюс
 * следующий блок», и по одному <div> её не поймать. Поэтому идём по
 * верхнеуровневым блокам (нулевой отступ — вложенное генератор всегда
 * печатает с отступом) и склеиваем их в группы: группа начинается на
 * блоке с <h2> и тянется до следующего такого.
 */
function v5UbratDubliVidzhetov(string $html): string
{
    $строки = explode("\n", $html);
    $всего  = count($строки);

    // верхнеуровневые блоки: от «<тег …>» в нулевой колонке до «</тег>» там же
    $блоки = [];
    for ($i = 0; $i < $всего; $i++) {
        if (!preg_match('~^<([a-z0-9]+)\b~', $строки[$i], $m)) { continue; }
        $закрытие = '</' . $m[1] . '>';
        for ($j = $i + 1; $j < $всего; $j++) {
            if ($строки[$j] === $закрытие) {
                $кусок = implode("\n", array_slice($строки, $i, $j - $i + 1));
                $ключ = preg_match('~<h2\b[^>]*>(.*?)</h2>~is', $кусок, $h)
                    ? mb_strtolower(trim(preg_replace('~\s+~u', ' ', strip_tags($h[1]))), 'UTF-8') : '';
                $блоки[] = ['от' => $i, 'до' => $j, 'ключ' => $ключ];
                $i = $j;
                break;
            }
        }
    }

    // группы: заголовок и всё, что идёт за ним до следующего заголовка
    $группы = [];
    foreach ($блоки as $б) {
        if ($б['ключ'] !== '' || !$группы) {
            $группы[] = ['ключ' => $б['ключ'], 'от' => $б['от'], 'до' => $б['до']];
        } else {
            $группы[count($группы) - 1]['до'] = $б['до'];
        }
    }

    $видели = []; $убрать = [];
    foreach ($группы as $г) {
        if ($г['ключ'] === '') { continue; }
        if (isset($видели[$г['ключ']])) {
            for ($k = $г['от']; $k <= $г['до']; $k++) { $убрать[$k] = true; }
        } else {
            $видели[$г['ключ']] = true;
        }
    }
    if (!$убрать) { return $html; }

    $итог = [];
    foreach ($строки as $н => $строка) {
        if (!isset($убрать[$н])) { $итог[] = $строка; }
    }
    return implode("\n", $итог);
}

/**
 * Якоря у заголовков разделов. Конкурент помечает `id="toc-N"` три четверти
 * своих h2, мы — одну седьмую. Правило у него простое и мы его повторяем:
 * якорь получают заголовки разделов (без класса либо с оформительским
 * `gradient-text`), а шапки виджетов — нет.
 *
 * Нумерация сквозная: один и тот же id на странице — битая разметка, а после
 * снятия дубля виджета в нумерации ещё и дыры.
 */
const V5_H2_BEZ_YAKORYA = ['hero-headline', 'value-pillars-heading',
                           'slots-dashboard-title', 'review-quotes-heading'];

function v5PeresobratToc(string $html): string
{
    $н = 0;
    return preg_replace_callback('~<h2\b([^>]*)>~i', function ($m) use (&$н) {
        $атрибуты = $m[1];
        $класс = preg_match('~\sclass="([^"]*)"~', $атрибуты, $к) ? $к[1] : '';
        foreach (V5_H2_BEZ_YAKORYA as $шапка) {
            if (str_contains($класс, $шапка)) { return $m[0]; }
        }
        $н++;
        return preg_match('~\sid="~', $атрибуты)
            ? '<h2' . preg_replace('~\sid="[^"]*"~', ' id="toc-' . $н . '"', $атрибуты, 1) . '>'
            : '<h2' . $атрибуты . ' id="toc-' . $н . '">';
    }, $html);
}
