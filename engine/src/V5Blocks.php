                            || ($г($m, 'end') !== '' && preg_match('~(?<![а-яё])(?:тут|здесь|там|это|всё)\s*$~ui', $до));
                        if (!$зависимое) { return $г($m, 'end') !== '' ? '' : ' '; }
                    }
                    // Замена — если слева не прилагательное мужского рода и не предлог:
                    // «нужен движ для смелых» → «нужен риск без подушки» ломает согласование.
                    if (preg_match($слева, $до)) { return $m[0][0]; }
                    // «движ для смелых, кто понимает» / «…, а не для тех» — замена ломает связку, штамп остаётся.
                    if (preg_match('~^\s*,?\s*(?:кто|которы[а-яё]+|а не|для тех|где|(?:и\s+)?[а-яё]+(?:ых|их))(?![а-яё])~ui', $после)) { return $m[0][0]; }
                    $окно = mb_strtolower(mb_substr($до, -60) . ' ' . mb_substr($после, 0, 60));
                    // Замена не должна повторять слово, которое уже рядом: «любит риск и риск без подушки».
                    $новое = null;
                    for ($i = 0; $i < count($замены); $i++) {
                        $кандидат = $замены[($круг + $i) % count($замены)];
                        $корни = array_filter(array_map(fn($w) => mb_substr($w, 0, 5), preg_split('~\s+~u', $кандидат)), fn($w) => mb_strlen($w) >= 4);
                        $чужой = false;
                        foreach ($корни as $корень) { if (str_contains($окно, $корень)) { $чужой = true; break; } }
                        if (!$чужой) { $новое = $кандидат; $круг += $i + 1; break; }
                    }
                    if ($новое === null) { return $m[0][0]; }
                    $вх = $г($m, 'any') !== '' ? $г($m, 'any') : (string) preg_replace('~^[\s,]*(?:и\s+)?|\s+$~u', '', $m[0][0]);
                    $итог = preg_match('~^\p{Lu}~u', $вх) ? $заглавная($новое) : $новое;
                    if ($г($m, 'any') !== '' || $вх === '') { return $итог; }
                    // Совпадение с пробелом/союзом слева: возвращаем их и ставим замену.
                    $где = strpos($m[0][0], $вх);
                    return $где === false ? ' ' . $итог : substr_replace($m[0][0], $итог, $где, strlen($вх));
                }, $т, -1, $н, PREG_OFFSET_CAPTURE);
                // Метка заглавной: следующее слово — с большой буквы.
                $т = (string) preg_replace_callback('~<!--заглавная-->\s*([а-яё])~u', fn($z) => mb_strtoupper($z[1]), $т);
                $т = str_replace('<!--заглавная-->', '', $т);
                // Пунктуация после удаления: «, ,» «: .» « .» «..» «, —» «: но».
                $т = preg_replace('~(?<=\S)\s+([.,;:!?])~u', '$1', $т);
                $т = preg_replace('~([,;:—–-])\s*([.,;:])~u', '$2', $т);
                $т = preg_replace('~\.\.(?!\.)~u', '.', $т);
                $т = preg_replace('~,\s*([—–])~u', ' $1', $т);
                $т = preg_replace('~:\s+(но|а|зато|однако)(?=\s)~u', ', $1', $т);
                // «движ для смелых, но только по-честному.» → «движ для смелых.»
                $т = preg_replace('~,\s*(?:но|а|и)\s+только\s*([.!?])~u', '$1', $т);
                $т = preg_replace('~\s+(?:и|а|но|или)(\s*(?:</strong>|</em>)?)\s*([.!?;])~u', '$1$2', $т);
                $т = preg_replace('~<(strong|em)>\s*</\1>\s*~u', '', $т);
                $т = preg_replace('~(?<=\S) {2,}(?=\S)~u', ' ', $т);
                return $a[1] . $т . $a[3];
            }, $кусок);
        }
        $html = implode('', $куски);
    }
    return $html;
}

