function v5CelNabora(array $поле, int $сид, string $ключ): float
{
    $цель = (float) ($поле['цель'] ?? 0.0);
    // Нулевая медиана — не всегда запрет: у доноров имена игр на slots
    // держат 9 из 11 в нуле, но двое называют до десяти. Розыгрыш идёт
    // внутри полосы, обрезанной достижимым; где полоса [0,0] — остаётся ноль.
    if ($сид <= 0 || ($цель <= 0.0 && !in_array($ключ, V5_IMENA, true))) { return $цель; }
    $дробное = !empty($поле['дробное']);
