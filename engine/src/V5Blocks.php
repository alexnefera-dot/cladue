/**
 * Общий слой поколения v5: разбор страницы на узлы, трафареты и заполнение.
 *
 * Одни и те же правила нужны трижды — экстрактору (`bloki-v5.php`), генератору
 * (`generator-v5.php`) и приёмке (`priyomka-v5.php`). Если правило маскировки
 * живёт в двух копиях, пул и генерация расходятся молча: в пуле «{ПРОЦ}», в
 * приёмке «до 500%», и ни один счётчик об этом не скажет.
 */

