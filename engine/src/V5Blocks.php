/**
 * Склонение имени под окончание, снятое с донора. Разбор трёх типов основы
 * покрывает весь словарь: согласная (Виктор), «й» (Григорий, Андрей) и
 * «а/я» (Ольга, Илья). Падеж угадывается по окончанию донора, потому что
 * в корпусе он всегда однозначен: «у {ИМЯ:а}», «{ИМЯ:у} повезло».
 */
function v5Sklonenie(string $имя, string $ок): string
{
    // Беглая гласная: Пётр — Петра, Павел — Павла, Лев — Льва.
    static $основы = ['Пётр' => 'Петр', 'Петр' => 'Петр', 'Павел' => 'Павл', 'Лев' => 'Льв'];
    $мягкая = ['а' => 'я', 'у' => 'ю', 'ом' => 'ем', 'е' => 'е', 'ы' => 'и', 'и' => 'и', 'ю' => 'ю', 'я' => 'я', 'ей' => 'ем', 'ой' => 'ем'];
    $последняя = mb_substr($имя, -1);
    if ($последняя === 'я') {
        // Илья — Ильи, Илье, Илью, Ильёй; Женя — Жени, Жене, Женю, Женей.
        $наЯ = ['а' => 'и', 'я' => 'и', 'у' => 'е', 'ю' => 'е', 'ом' => 'ей', 'ем' => 'ей', 'ой' => 'ей', 'ей' => 'ей', 'е' => 'е', 'ы' => 'и', 'и' => 'и'];
        return mb_substr($имя, 0, -1) . ($наЯ[$ок] ?? $ок);
    }
    if ($последняя === 'а') {
        // Марина — Марины, Марине, Мариной; после г/к/х/ж/ш/щ/ч — Ольги, Наташи.
        $основа = mb_substr($имя, 0, -1);
        $и = preg_match('~[гкхжшщч]$~u', $основа) ? 'и' : 'ы';
        $наА = ['а' => $и, 'я' => $и, 'у' => 'е', 'ю' => 'е', 'ом' => 'ой', 'ем' => 'ой', 'ой' => 'ой', 'ей' => 'ой', 'е' => 'е', 'ы' => $и, 'и' => 'и'];
        return $основа . ($наА[$ок] ?? $ок);
    }
    if ($последняя === 'й' || $последняя === 'ь') {
        return mb_substr($имя, 0, -1) . ($мягкая[$ок] ?? $ок);
    }
    return ($основы[$имя] ?? $имя) . $ок;
}

/**
 * Заполнение трафарета: `$значение('ПРОЦ')` возвращает значение прорези.
 * Имя выдаётся через `$значение('ИМЯ')` и склоняется здесь же.
 */
/**
 * Прорези доноров. В корпусе остались плейсхолдеры чужой шаблонизации —
 * `{NAME}` в заголовках слотов, `{AMOUNT}` рядом с ним. Своими именами мы их
 * не знаем, а подставить надо: заголовок «Джекпот слоты — {NAME} сорвал
 * {AMOUNT} здесь» уехал в выдачу как «— 0 сорвал 0 здесь».
 */
const V5_CHUZHIE_PROREZI = ['NAME' => 'ИМЯ', 'AMOUNT' => 'СУММА'];

function v5Zapolnit(string $t, callable $значение): string
{
    // Имя прорези может содержать цифру (`{RTP2}`) — без этого подстановка
    // молча проходит мимо, и в выдачу уезжает сам плейсхолдер.
    // Позиция текущей прорези в исходнике: одинаковые прорези («{РУБЛИ} …
    // {РУБЛИ}») ищутся от места прошлой, иначе обе находят первую и вторая
    // тоже читает контекст ставки.
    $от = 0;
    return preg_replace_callback('~\{([А-ЯA-Z][А-ЯA-Z0-9_]*)(?::([а-я]{1,2}))?\}~u', function ($m) use ($значение, $t, &$от) {
        $ключ = V5_CHUZHIE_PROREZI[$m[1]] ?? $m[1];
        $поз = mb_strpos($t, $m[0], $от);
        if ($поз !== false) { $от = $поз + 1; }
        // Рубли в контексте ставки — отдельный ключ: узел даёт на него
        // ставочный слой банка. Если заполнитель ключа не знает (вернул
        // пусто), берём обычные рубли — поведение прежнее.
        if ($ключ === 'РУБЛИ') {
            $до = $поз === false ? '' : mb_substr($t, max(0, $поз - 40), min(40, $поз));
            if (preg_match('~(?:ставк\w*|поставил\w*|закинул\w*|внёс|внесл\w*|депозит\w*)\s+(?:в\s+|на\s+|—\s+|:\s+)?$~ui', strip_tags($до))) {
                $v = (string) $значение('РУБЛИ_СТАВКА');
                if ($v !== '' && $v !== '0') { return $v; }
            }
            // Рубли после «сорвал» — это куш, а не ставка: H2 «{ИМЯ} сорвал
            // {РУБЛИ} здесь» давал «сорвал 3 031 ₽». Берём сумму истории
            // узла. Только «сорвал»: с «вывел/снял/забрал» правило уводило
            // vhod с рублёвых выводов на суммы в «к» и валило страницу
            // (vhod 7 провалов из 8 против 2–3).
            // «Забрал/поднял/выиграл {РУБЛИ}» — тоже куш: H2 «сорвал 56к» шёл
            // над телом «забрал 350 тысяч рублей». «Вывел/снял» — без «куш»
            // не трогаем: на vhod это вывод.
            // В истории героя (запись с {ИМЯ}) и «вывел/снял {РУБЛИ}» — его выигрыш:
            // «поднял 38к … Через полтора часа вывел 270 тысяч рублей».
            // И продолжение его истории без имени: «Через два дня вывел {РУБЛИ}».
            $вИстории = str_contains($t, '{ИМЯ') || (bool) preg_match('~^\s*(?:через|спустя|потом|затем|после|а через|в итоге)\b~ui', strip_tags($t));
            // Оборот отыгрыша = бонус × вейджер: «вейджер x45 значит, что прокрутить надо {СУММА}».
            if (preg_match('~(?:прокрутить|отыграть|проставить|оборот\w*)\s+(?:надо|нужно|придётся|в\s+размере|—|:)?\s*(?:сумму\s+)?$~ui', strip_tags($до))) {
                $v = (string) $значение('СУММА_ОБОРОТ');
                if ($v !== '' && $v !== '0') { return $v; }
            }
            // Бонус считается от депозита: «закинул 15к и получил бонусы на {СУММА}» — не ставочный слой.
            if (preg_match('~(?:бонус\w*|пакет\w*|подар\w*)\s+(?:на|в\s+размере|до|—|:)?\s*$|получил\w*\s+(?:ещё\s+)?(?:бонус\w*\s+)?(?:на\s+)?$~ui', strip_tags($до))) {
                $v = (string) $значение('СУММА_БОНУС');
                if ($v !== '' && $v !== '0') { return $v; }
            }
            if (preg_match('~(?:(?:сорвал|забрал|поднял|выиграл|вынес|унёс|выбил)\w*\s+(?:куш\s+(?:в\s+|на\s+)?(?:—\s+)?|около\s+|почти\s+|целых\s+)?|(?:вывел|снял|поймал)\w*\s+куш\s+(?:в\s+|на\s+)?)$~ui', strip_tags($до))
                || ($вИстории && preg_match('~(?:вывел|вывела|снял|сняла|получил|получила|составил|составила|принесл[аио]\w*\s+(?:ему|ей)|итог\w*\s*[—:-]?)\s+(?:на\s+карту\s+|около\s+|почти\s+|целых\s+|свои\s+)?$~ui', strip_tags($до)))) {
                $v = (string) $значение('СУММА');
                if ($v !== '' && $v !== '0') { return $v; }
            }
        }
        // Сумма в контексте старта — тоже ставка: «начал с {СУММА}»,
        // «пополнил баланс на {СУММА}», «поставил {СУММА}». Сумма раздела
        // делала их равными выигрышу: «начал с 40к … вывел 40к».
        if ($ключ === 'СУММА' || $ключ === 'СУММАМАЛ') {
            $до = $поз === false ? '' : mb_substr($t, max(0, $поз - 50), min(50, $поз));
            // Сумма проигрыша — своя роль: ниже выигрыша героя.
            if (preg_match('~(?:бонус\w*|пакет\w*|подар\w*)\s+(?:на|в\s+размере|до|—|:)?\s*$|получил\w*\s+(?:ещё\s+)?(?:бонус\w*\s+)?(?:на\s+)?$~ui', strip_tags($до))) {
                $v = (string) $значение('СУММА_БОНУС');
                if ($v !== '' && $v !== '0') { return $v; }
            }
            if (preg_match('~(?:слил\w*|сливал\w*|проиграл\w*|проигрывал\w*|потерял\w*|терял\w*|ушл[оа]|спустил\w*|минус\w*\s+на|в\s+трубу|отдал\w*\s+обратно)\s*(?:около\s+|почти\s+|целых\s+|ещё\s+|весь\s+|все\s+|свои\s+)?$~ui', strip_tags($до))) {
                $v = (string) $значение('СУММА_ПРОИГРЫШ');
                if ($v !== '' && $v !== '0') { return $v; }
            }
            if (preg_match('~(?:начал\w*\s+с|стартовал\w*\s+с|зашёл\s+с|зашла\s+с|заш[ёе]л\w*[^.]{0,25}?\s+с|заход\w*\s*[—–-]?\s*с|поставил\w*|внёс|внесл\w*|закинул\w*|депозит\w*|пополнил\w*[^.]{0,20}?на|пополнени\w*\s+(?:на|в)|с\s+балансом|баланс\s+на|стартов\w+\s+(?:депозит\w*|банк\w*)|играть\s+от|ставк\w*\s+от|со\s+ставки|лимит\w*\s+(?:в|на|—|–|:)?\s*|потратишь\s+(?:максимум\s+)?|бюджет\w*\s+(?:в|на|—|–|:)?\s*|не\s+жалко\s+потерять\s+|банк\w*\s+(?:в|на|из|от)\s+|банкролл\w*\s+(?:в|на)\s+|бонус\w*\s+(?:на|в\s+размере|до)\s+)\s*(?:в\s+|на\s+|—\s+|:\s+|всего\s+|скромные\s+|первые\s+|свои\s+|стартовые\s+|туда\s+)?$~ui', strip_tags($до))) {
                $v = (string) $значение('СУММА_СТАВКА');
                if ($v !== '' && $v !== '0') { return $v; }
            }
        }
        $v = (string) $значение($ключ);
        // Незнакомая прорезь остаётся собой: ноль вместо имени приёмка не
        // ловит, а сам плейсхолдер — ловит.
        if ($v === '' || $v === '0') { return $m[0]; }
        $имя = $ключ === 'ИМЯ' || $ключ === 'ИМЯЖ';
        return ($имя && ($m[2] ?? '') !== '') ? v5Sklonenie($v, $m[2]) : $v;
    }, $t);
}

/**
 * Близость двух кусков по четырёхсловным цепочкам. Пул одного раздела набран
 * с одиннадцати доноров, а фабрика писала их по одному шаблону: «Джекпот до X
 * звучит громко, однако вероятность не равна гарантии» встречается в трёх
 * переписываниях. Рядом в одном списке они читаются как заедание.
 */
function v5Blizost(string $a, string $b): float
{
    $ц = function (string $t): array {
        $w = preg_split('~\s+~u', mb_strtolower(preg_replace('~[^а-яёa-z0-9 ]+~u', ' ',
            preg_replace('~<[^>]*>~', ' ', $t))), -1, PREG_SPLIT_NO_EMPTY);
        $o = [];
        for ($i = 0; $i + 4 <= count($w); $i++) { $o[implode(' ', array_slice($w, $i, 4))] = 1; }
        return $o;
    };
    $x = $ц($a); $y = $ц($b);
    if (!$x || !$y) { return 0.0; }
    return count(array_intersect_key($x, $y)) / min(count($x), count($y));
}

/**
 * Разбор абзаца на предложения с сохранением встроенной разметки.
 *
 * Перенос абзацев целиком даёт с донором столько же совпадения, сколько доля
 * его абзацев в нашей странице, — на замере это 16–26 % против корпусного
 * потолка 8–11 %. Шингл в шесть слов рвётся на границе предложения, поэтому
 * абзац собирается из предложений разных доноров, и доля каждого падает втрое.
 *
 * Теги вынимаются перед разрезкой и возвращаются после: точка внутри
 * `href="сайт.com"` — не конец предложения. Предложение с непарным тегом
 * отбрасывается: собирать из него абзац нельзя.
 */
function v5Predlozheniya(string $html): array
{
    $теги = [];
    $без = preg_replace_callback('~<[^>]+>~', function ($m) use (&$теги) {
        $теги[] = $m[0];
        return "\x01" . (count($теги) - 1) . "\x02";
    }, $html);
    $куски = preg_split('~(?<=[.!?…])\s+~u', $без, -1, PREG_SPLIT_NO_EMPTY) ?: [];
    $итог = [];
    foreach ($куски as $к) {
        $п = preg_replace_callback('~\x01(\d+)\x02~', fn($m) => $теги[(int) $m[1]], $к);
        $открыто = preg_match_all('~<([a-z0-9]+)(?:\s[^>]*)?>~i', $п, $o);
        $закрыто = preg_match_all('~</([a-z0-9]+)>~i', $п, $c);
        if ($открыто !== $закрыто) { continue; }
        $п = trim($п);
        if (mb_strlen($п) < 15) { continue; }
        $итог[] = $п;
    }
    return $итог;
}

/**
 * Текстовые прорези виджета: строки, где лежит текст, и роль каждой — класс
 * ближайшего предка с классом (иначе itemprop, иначе тег).
 *
 * Виджет нельзя переносить от одного донора целиком: разметка у всех общая, а
 * текст в ней свой, и перенос даёт кусок дословного совпадения размером в пол
 * страницы. Роли же у доноров одни и те же — `hero-tagline`, `payout-name`,
 * `pillar-text`, — поэтому каждая строка набирается из своего пула.
 *
 * Пары «вопрос-ответ» из этого исключены: их надо менять парой, иначе ответ
 * встанет под чужим вопросом. Ими занимается отдельная подстановка.
 */
const V5_ROLI_PAROJ = ['faq-question', 'text', 'review-quote-text'];

function v5Sloty(string $html): array
{
    $строки = explode("\n", $html);
    $стек = []; $слоты = [];
    foreach ($строки as $i => $l) {
        $t = trim($l);
        if ($t === '') { continue; }
        if ($t[0] !== '<') { $слоты[] = ['строка' => $i, 'роль' => end($стек) ?: '?']; continue; }
        if (str_starts_with($t, '</')) { array_pop($стек); continue; }
        if (!preg_match('~^<([a-z0-9]+)([^>]*)>~i', $t, $m)) { continue; }
        $роль = preg_match('~class="([^"]*)"~', $m[2], $c) ? explode(' ', trim($c[1]))[0]
              : (preg_match('~itemprop="([^"]*)"~', $m[2], $ip) ? $ip[1] : $m[1]);
        if ($роль === '') { $роль = $m[1]; }
        $пустой = str_ends_with($t, '/>') || in_array(strtolower($m[1]), ['meta', 'img', 'br', 'input', 'hr'], true);
        if ($пустой) { continue; }
        if (preg_match('~^<[a-z0-9]+[^>]*>(.+)</[a-z0-9]+>\s*$~i', $t)) {
            $слоты[] = ['строка' => $i, 'роль' => $роль, 'встроенный' => true];
            continue;
        }
        $стек[] = $роль;
    }
    return $слоты;
}

/** Вёрстка узла в стиле корпуса: тег на нулевой колонке, текст с отступом. */
function v5Uzel(string $tag, string $inner, string $attrs = ''): string
{
    return "<{$tag}{$attrs}>\n  " . $inner . "\n</{$tag}>";
}

/**
 * Пункт-шаг: императив в начале или слово порядка. Маркер перечня («Плюс:»,
 * «Минус:», галочка) отменяет всё — это список свойств, а не инструкция.
 */
function v5ShagovyiPunkt(string $т): bool
{
    if (preg_match('~^(?:<strong>)?\s*(?:[\x{2700}-\x{27BF}\x{2600}-\x{26FF}'
        . '\x{1F300}-\x{1FAFF}\x{2705}\x{274C}]|Плюс|Минус|Важно|Факт|Совет)~u', $т)) {
        return false;
    }
    return (bool) preg_match('~^(?:<strong>)?(?:Сначала|Затем|Потом|После|Далее|В конце'
        . '|Скачай\w*|Установи\w*|Открой\w*|Откры\w*|Нажми\w*|Разреши\w*|Введи\w*'
        . '|Подтверди\w*|Зайди\w*|Войди\w*|Перейди\w*|Выбери\w*|Заполни\w*'
        . '|Активируй\w*|Пройди\w*|Проверь\w*|Дождись|Дождитесь|Запусти\w*|Найди\w*'
        . '|Укажи\w*|Сохрани\w*|Зарегистрируй\w*|Пополни\w*)\b~u', $т);
}

/** Раздел, где нумерация уместна: инструкция, а не перечень свойств. */
function v5ShagovyiRazdel(string $тип, string $h2): bool
{
    if ($тип === 'app')   { return (bool) preg_match('~как установить~ui', $h2); }
    if ($тип === 'promo') { return (bool) preg_match('~как использовать промокод~ui', $h2); }
    return false;
}

/**
 * Ворота набора: нумерованный список возможен ТОЛЬКО на promo.
 *
 * Доноры ставят <ol> на promo (6 из 12) и на app (3 из 12), но приёмка
 * считает коридор от ЦЕЛИ набора, а не от корпусной полосы:
 *   |наше − цель| ≤ max(0.25·|цель профиля|, 0.8)
 * У app ordered_pct цель 0 и держат=true, значит коридор — [0, 0.8], и любой
 * <ol> валит страницу: «ordered_pct 25→0». Корпусная полоса [0, 20] в этом
 * правиле не участвует. На promo признак не держат вовсе, и там <ol> живёт.
 *
 * Первая версия этого не учла и открывала ворота app каждому четвёртому
 * набору. Толку ноль — страница всё равно не проходила, — а сиды партия на
 * это тратила: 279–283 собрались за 37 попыток против 19 у 274–278.
 *
 * Донорские 25% на app недостижимы, пока цель профиля равна нулю. Поднять её
 * значило бы переписать стандарт приёмки под привычку трёх доноров из
 * двенадцати; это отдельное решение, а не побочный эффект правки разметки.
 */
function v5NumerovatNabor(string $тип, string $имяНабора): bool
{
    return $тип === 'promo';
}

/**
 * Смена тега ul→ol на готовой странице.
 *
 * Замер по двенадцати донорам: <ol> есть ТОЛЬКО на promo (шесть доноров,
 * доля 16.7–33.3%) и app (три донора, 14.3–25%). На остальных десяти типах
 * его нет ни у кого, и профиль держит там полосу [0, 0] — это запрет, а не
 * недобор.
 *
 * Разделение труда: пункты-шаги в список набирает генератор (v5ShagovyiPunkt),
 * а здесь остаётся только смена тега — потому что доля считается по ГОТОВОЙ
 * странице, где к нашим спискам добавились списки виджетов. Проверка тут
 * двойная и обе нужны:
 *   · не меньше пяти списков. На app полоса [0, 20], и один <ol> из четырёх
 *     списков даёт 25% — страница валит приёмку;
 *   · больше половины пунктов — шаговые. Если генератору не хватило записей и
 *     в список попал перечень, нумеровать его нельзя: <ol> обещает порядок.
 */
function v5PoryadokSpiska(string $html, string $тип, string $имяНабора): string
{
    if (!v5NumerovatNabor($тип, $имяНабора)) { return $html; }
    if (preg_match_all('~<ul\b~i', $html) + preg_match_all('~<ol\b~i', $html) < 5) { return $html; }
    $шаги = $тип === 'app' ? '~как установить~ui' : '~как использовать промокод~ui';
    // Голый <ul> без атрибутов — наш список из v5Spisok. У списков виджетов
    // есть классы, и менять им тег нельзя: на них завязана вёрстка.
    if (!preg_match_all('~<ul>\n.*?</ul>~su', $html, $mm, PREG_OFFSET_CAPTURE)) { return $html; }
    foreach ($mm[0] as $m) {
        // Именно H2, а не ближайший заголовок: между «Как установить —
        // Пошагово» и списком стоит H3 раздела, и поиск по h[23] находил его.
        $до = substr($html, 0, $m[1]);
        $заголовок = preg_match_all('~<h2[^>]*>(.*?)</h2>~su', $до, $hh) ? end($hh[1]) : '';
        if (!preg_match($шаги, strip_tags($заголовок))) { continue; }
        preg_match_all('~<li>\s*(.*?)\s*</li>~su', $m[0], $pp);
        $всего = count($pp[1]);
        if ($всего < 3) { continue; }
        $шаговых = count(array_filter($pp[1], 'v5ShagovyiPunkt'));
        if ($шаговых * 2 <= $всего) { continue; }
        return substr($html, 0, $m[1]) . '<ol>' . substr($m[0], 4, -5) . '</ol>'
             . substr($html, $m[1] + strlen($m[0]));
    }
    return $html;
}

function v5Spisok(array $пункты, string $tag = 'ul'): string
{
    $o = "<{$tag}>\n";
    foreach ($пункты as $п) { $o .= "  <li>\n    " . $п . "\n  </li>\n"; }
    return $o . "</{$tag}>";
}

/**
 * Ремонт денежной пары в предложении.
 *
 * Донор пишет ставку числом внутри фразы, а результат отдаёт прорезью {РУБЛИ}.
 * Прорезь в узле выдаётся первой, то есть из младшей — ставочной — половины
 * банка, и герой «заходит с 1000 ₽ и доводит сумму до 200 рублей». Проверка
 * смысла ловит это как «результат меньше ставки»; здесь оно чинится на месте:
 * итог заменяется на запись из банка, которая крупнее ставки, с сохранением
 * написания валюты из исходной фразы.
 *
 * @param array<string, mixed> $рубли банк РУБЛИ: ключи — денежные строки
 */
function v5PochinitDengi(string $html, array $рубли): string
{
    // Банк режется по написанию валюты: «120 000 ₽» и «120 000 рублей» — это
    // разные строки, и подставлять нужно ту, что совпадает с исходной фразой.
    $поВалюте = ['₽' => [], 'рубли' => []];
    foreach (array_keys($рубли) as $s) {
        $s = (string) $s;
        $n = v5Rubli($s);
        // «000 ₽» и «0₽» — обломки разбора: он разорвал «120 000 ₽» по пробелу.
        if ($n < 1000 || preg_match('~^\D*0~u', $s)) { continue; }
        $вид = mb_strpos($s, '₽') !== false ? '₽' : 'рубли';
        $поВалюте[$вид][$n] = trim(preg_replace('~\s*(?:₽|рубл\w+)\s*$~u', '', $s));
    }
    foreach ($поВалюте as &$список) { ksort($список); }
    unset($список);
    if (!$поВалюте['₽'] && !$поВалюте['рубли']) { return $html; }

    $re = '~((?:зашёл|зашла|начал|начала|пополнил|пополнила|поставил|поставила)[^.!?<]{0,80}?'
        . '(\d[\d\x{00A0} ]*?)\s?(?:₽|рубл\w+)[^.!?<]{0,110}?'
        . '(?:довёл|довела|поднял|подняла|вырос\w*|забрал|забрала|до)\s+)'
        . '(\d[\d\x{00A0} ]*?)\s?(₽|рубл\w+)~u';

    return (string) preg_replace_callback($re, function (array $m) use ($поВалюте): string {
        $ставка = v5Rubli($m[2]);
        $итог   = v5Rubli($m[3]);
        if ($ставка <= 0 || $итог > $ставка) { return $m[0]; }
        $вид = $m[4] === '₽' ? '₽' : 'рубли';
        $список = $поВалюте[$вид] ?: ($поВалюте['₽'] ?: $поВалюте['рубли']);
        // Результат в корпусе кратно больше ставки: «зашёл с 1000 ₽ и довёл до
        // 1050 ₽» читается не лучше сломанной подстановки. Порог — десять
        // ставок, с откатом на три и на самую крупную запись банка.
        $новое = null;
        foreach ([10, 3, 1] as $кратность) {
            foreach ($список as $n => $запись) {
                if ($n >= $ставка * $кратность) { $новое = [$n, $запись]; break 2; }
            }
        }
        if ($новое === null || $новое[0] <= $ставка) { return $m[0]; }
        return $m[1] . $новое[1] . ' ' . $m[4];
    }, $html);
}

/**
 * Согласование числительного с существительным времени.
 *
 * Донор пишет «вывод за 3 минуты» — форма верна для двух, трёх и четырёх.
 * Прорезь катит в этот шаблон любое число, и получается «за 20 минуты»,
 * «за 47 минуты». В корпусе такого нет: доноры просто не выпали на другие
 * числа. Правило простое и покрывает весь встречающийся набор слов.
 */
function v5PochinitChislo(string $html): string
{
    static $формы = [
        'минуты'  => ['минута', 'минуты', 'минут'],
        'минут'   => ['минута', 'минуты', 'минут'],
        'часа'    => ['час', 'часа', 'часов'],
        'часов'   => ['час', 'часа', 'часов'],
        'дня'     => ['день', 'дня', 'дней'],
        'дней'    => ['день', 'дня', 'дней'],
        'секунды' => ['секунда', 'секунды', 'секунд'],
        'секунд'  => ['секунда', 'секунды', 'секунд'],
    ];
    $ключи = implode('|', array_keys($формы));

    return (string) preg_replace_callback(
        // Тег между предлогом и числом («до <strong>1 часа</strong>») входит в разбор, иначе предлог не виден.
        '~(\S+\s)?((?:<[^>]+>)?)(\d+)(\s|&nbsp;)(' . $ключи . ')\b~u',
        function (array $m) use ($формы): string {
            // «до 1 часа», «от 40 минут» — родительный по предлогу, это норма.
            static $предлоги = ['до' => 1, 'от' => 1, 'около' => 1, 'порядка' => 1,
                                'свыше' => 1, 'более' => 1, 'менее' => 1];
            // Тег между предлогом и числом не мешает: «<strong>до 24 часов</strong>»
            // читалось как «до 24 часа».
            $перед = trim(strip_tags((string) $m[1]));
            if (isset($предлоги[mb_strtolower($перед)])) { return $m[0]; }

            $n = (int) $m[3];
            $сотня = $n % 100;
            $конец = $n % 10;
            if ($сотня >= 11 && $сотня <= 14) { $форма = 2; }
            elseif ($конец === 1)             { $форма = 0; }
            elseif ($конец >= 2 && $конец <= 4) { $форма = 1; }
            else                                { $форма = 2; }

            return ($m[1] ?? '') . $m[2] . $m[3] . $m[4] . $формы[$m[5]][$форма];
        }, $html);
}

/**
 * Баланс кавычек на странице.
 *
 * В библиотеке попадаются куски, где реплика открылась и не закрылась —
 * разбор донора разрезал цитату пополам. На странице это выглядит как
 * «Мне повезло. без пары или как одинокая » в конце чужой фразы.
 *
 * Считаем только текст вне тегов: в атрибутах кавычки свои. Лишний
 * закрывающий убираем, незакрытый открывающий закрываем по концу его
 * предложения — донор пишет реплику именно так.
 */
function v5PochinitKavychki(string $html): string
{
    // Предложение, начатое ссылкой со строчной: «…завтра минус. <a>информацию о промокодах</a> смотри…».
    $html = (string) preg_replace_callback('~([.!?…]\s+)(<a\b[^>]*>)([а-яё])~u', fn($m) => $m[1] . $m[2] . mb_strtoupper($m[3]), $html);
    // Куски текста вне тегов: смещение в исходной строке и сам текст.
    preg_match_all('~>[^<]+~u', $html, $m, PREG_OFFSET_CAPTURE);
    if (!$m[0]) { return $html; }

    $карта = [];            // позиция в потоке → позиция в html
    $поток = '';
    foreach ($m[0] as [$кусок, $смещение]) {
        $len = strlen($кусок);
        for ($i = 1; $i < $len; $i++) {   // единицу пропускаем: это сам «>»
            $карта[strlen($поток)] = $смещение + $i;
            $поток .= $кусок[$i];
        }
    }

    $правки = [];           // позиция в html → что делать
    $стек = [];
    $длина = strlen($поток);
    for ($i = 0; $i < $длина; $i++) {
        if (substr($поток, $i, 2) === "\xc2\xab") {          // «
            $стек[] = $i;
        } elseif (substr($поток, $i, 2) === "\xc2\xbb") {    // »
            if ($стек) { array_pop($стек); }
            else { $правки[$карта[$i]] = ['убрать', 2]; }
        }
    }
    // Незакрытая реплика: ставим » после конца её предложения.
    foreach ($стек as $поз) {
        $конец = null;
        for ($i = $поз + 2; $i < $длина; $i++) {
            if (strpos('.!?', $поток[$i]) !== false) { $конец = $i; break; }
        }
        if ($конец === null || !isset($карта[$конец])) {
            $правки[$карта[$поз]] = ['убрать', 2];           // закрывать негде — снимаем открывающую
        } else {
            $правки[$карта[$конец] + 1] = ['вставить', "\xc2\xbb"];
        }
    }
    if (!$правки) { return $html; }

    krsort($правки);        // правим с конца, чтобы смещения не поехали
    foreach ($правки as $поз => [$что, $чем]) {
        $html = $что === 'убрать'
            ? substr($html, 0, $поз) . substr($html, $поз + $чем)
            : substr($html, 0, $поз) . $чем . substr($html, $поз);
    }
    return $html;
}

/**
 * Один и тот же виджет лежит в библиотеке под двумя оболочками
 * (faq-section и info-block), поэтому сборка иногда ставит на страницу
 * обе копии: одинаковый заголовок, одинаковый текст и одинаковый
 * id="toc-N". Вторую копию убираем целиком.
 *
 * Копия не всегда обёрнута в свой <div>: бывает голая пара «<h2> плюс
 * следующий блок», и по одному <div> её не поймать. Поэтому идём по
 * верхнеуровневым блокам (нулевой отступ — вложенное генератор всегда
 * печатает с отступом) и склеиваем их в группы: группа начинается на
 * блоке с <h2> и тянется до следующего такого.
 */
function v5UbratDubliVidzhetov(string $html): string
{
    $строки = explode("\n", $html);
    $всего  = count($строки);

    // верхнеуровневые блоки: от «<тег …>» в нулевой колонке до «</тег>» там же
    $блоки = [];
    for ($i = 0; $i < $всего; $i++) {
        if (!preg_match('~^<([a-z0-9]+)\b~', $строки[$i], $m)) { continue; }
        $закрытие = '</' . $m[1] . '>';
        for ($j = $i + 1; $j < $всего; $j++) {
            if ($строки[$j] === $закрытие) {
                $кусок = implode("\n", array_slice($строки, $i, $j - $i + 1));
                $ключ = preg_match('~<h2\b[^>]*>(.*?)</h2>~is', $кусок, $h)
                    ? mb_strtolower(trim(preg_replace('~\s+~u', ' ', strip_tags($h[1]))), 'UTF-8') : '';
                $блоки[] = ['от' => $i, 'до' => $j, 'ключ' => $ключ];
                $i = $j;
                break;
            }
        }
    }

    // группы: заголовок и всё, что идёт за ним до следующего заголовка
    $группы = [];
    foreach ($блоки as $б) {
        if ($б['ключ'] !== '' || !$группы) {
            $группы[] = ['ключ' => $б['ключ'], 'от' => $б['от'], 'до' => $б['до']];
        } else {
            $группы[count($группы) - 1]['до'] = $б['до'];
        }
    }

    $видели = []; $убрать = [];
    foreach ($группы as $г) {
        if ($г['ключ'] === '') { continue; }
        if (isset($видели[$г['ключ']])) {
            for ($k = $г['от']; $k <= $г['до']; $k++) { $убрать[$k] = true; }
        } else {
            $видели[$г['ключ']] = true;
        }
    }
    if (!$убрать) { return $html; }

    $итог = [];
    foreach ($строки as $н => $строка) {
        if (!isset($убрать[$н])) { $итог[] = $строка; }
    }
    return implode("\n", $итог);
}

/**
 * Якоря у заголовков разделов. Конкурент помечает `id="toc-N"` три четверти
 * своих h2, мы — одну седьмую. Правило у него простое и мы его повторяем:
 * якорь получают заголовки разделов (без класса либо с оформительским
 * `gradient-text`), а шапки виджетов — нет.
 *
 * Нумерация сквозная: один и тот же id на странице — битая разметка, а после
 * снятия дубля виджета в нумерации ещё и дыры.
 */
const V5_H2_BEZ_YAKORYA = ['hero-headline', 'value-pillars-heading',
                           'slots-dashboard-title', 'review-quotes-heading'];

function v5PeresobratToc(string $html): string
{
    $н = 0;
    return preg_replace_callback('~<h2\b([^>]*)>~i', function ($m) use (&$н) {
        $атрибуты = $m[1];
        $класс = preg_match('~\sclass="([^"]*)"~', $атрибуты, $к) ? $к[1] : '';
        foreach (V5_H2_BEZ_YAKORYA as $шапка) {
            if (str_contains($класс, $шапка)) { return $m[0]; }
        }
        $н++;
        return preg_match('~\sid="~', $атрибуты)
            ? '<h2' . preg_replace('~\sid="[^"]*"~', ' id="toc-' . $н . '"', $атрибуты, 1) . '>'
            : '<h2' . $атрибуты . ' id="toc-' . $н . '">';
    }, $html);
}

/**
 * Мелочи после всех проходов: род в «выиграл(а)» по имени героя, донорская
 * нумерация вопросов FAQ («3. Будут ли новые слоты?»), строчная после точки
 * перед «если» («это не сюда. если готов»).
 */
function v5PochinitMelochi(string $html): string
{
    $html = (string) preg_replace_callback('~(\p{Lu}[а-яё]+)\s+(выиграл|отыграл|снял|поднял|забрал|вывел|сорвал)\(а\)~u',
        fn($m) => $m[1] . ' ' . $m[2] . (v5Rod($m[1]) === 'ж' ? 'а' : ''), $html);
    $html = (string) preg_replace('~(<h3 class="faq-question"[^>]*>\s*)\d+\.\s+~u', '$1', $html);
    // «Вывод за сразу после верификации» — срок-фраза после «за».
    $html = (string) preg_replace('~(?<![а-яё])за\s+сразу\s+после~u', 'сразу после', $html);
    $html = (string) preg_replace('~(?<![а-яё])за\s+(в течение)~u', '$1', $html);
    // «до 1 час» → «до 1 часа», «до 3 час» → «до 3 часов».
    $html = (string) preg_replace_callback('~(?<![а-яё])до\s+(\d+)\s+час(?![а-яё])~u', fn($m) => 'до ' . $m[1] . ($m[1] === '1' ? ' часа' : ' часов'), $html);
    $html = (string) preg_replace_callback('~([.!?])(\s+)(если|а если|но если|и если)(?=\s)~u',
        fn($m) => $m[1] . $m[2] . mb_strtoupper(mb_substr($m[3], 0, 1)) . mb_substr($m[3], 1), $html);
    // «занимает около до 48 минут»: срок-фраза уже со своим «до».
    $html = (string) preg_replace('~(?<![а-яё])около\s+до\s+(\d)~u', 'до $1', $html);
    // «движ для смелых, но только.» — хвост после снятого повтора («с суммой, которую не жалко потерять»).
    $html = (string) preg_replace('~\s*[,—–-]?\s*(?:но|а|и)\s+только\s*([.!?])~u', '$1', $html);
    // «со 7 449 ₽» → «с 7 449 ₽»: «со» оставляется только перед сотней («со 100», «со 150»).
    $html = (string) preg_replace_callback('~(?<![а-яё])([Сс])о\s+(\d[\d ]*)(?=\D)~u', function ($m) {
        $ц = str_replace(' ', '', $m[2]);
        return (strlen($ц) === 3 && $ц[0] === '1') ? $m[0] : $m[1] . ' ' . $m[2];
    }, $html);
    return $html;
}

/** Ставка партнёрки — одна на набор: у доноров на partnery одна-две цифры ревшары, у нас было до десяти. */
function v5Revshara(int $сид): string
{
    return (string) [25, 30, 35, 40, 45, 50][crc32('ревшара|' . $сид) % 6];
}

/**
 * На partnery все проценты «от дохода / RevShare / ревшары / GGR / с оборота» — одна цифра набора.
 * Литералы доноров («до 50% RevShare», «18% от дохода») и записи с {ДОЛЯ} в этой роли
 * («RevShare до 600%») выравниваются на неё; диапазон «от X% до Y%» — X на десять ниже.
 */
function v5RovnayaRevshara(string $html, string $ревшара): string
{
    $р = (int) $ревшара;
    $роль = '(?:от\s+(?:чистого\s+)?дохода|revenue\s+share|revshare|ревшар[а-яё]*|от\s+ggr|с\s+каждой\s+ставки|с\s+оборота|от\s+депозитов|от\s+прибыли|партн[её]рских\s+отчислен[а-яё]+)';
    $html = (string) preg_replace('~(?<![\d.,])\d{1,3}(\s*%\s*' . $роль . ')~ui', $р . '$1', $html);
    $html = (string) preg_replace('~((?:revshare|ревшар[а-яё]*|revenue\s+share|комисси[яю]|ставк[аи]|процент[а-яё]*|доля)\s+(?:—\s*|партн[её]р[а-яё]*\s+)?до\s+)\d{1,3}(?=\s*%)~ui', '${1}' . $р, $html);
    $html = (string) preg_replace('~(до\s+)\d{1,3}(\s*%\s*(?:от\s+(?:чистого\s+)?дохода|revenue\s+share|revshare|ревшар))~ui', '${1}' . $р . '$2', $html);
    $html = (string) preg_replace_callback('~(новичкам\s+(?:от|с)\s+)\d{1,3}(\s*%[^.;]{0,30}?(?:активным|дальше|потом|опытным)\s+(?:до|—)\s+)\d{1,3}(?=\s*%)~ui',
        fn($m) => $m[1] . max(10, $р - 15) . $m[2] . $р, $html);
    $html = (string) preg_replace_callback('~(проценты\s+здесь\s+от\s+)\d{1,3}(%\s+до\s+)\d{1,3}(?=%)~ui', fn($m) => $m[1] . max(10, $р - 15) . $m[2] . $р, $html);
    return $html;
}
