<?php
declare(strict_types=1);

/**
 * Превращает сборочную спеку (Planner) в заполненный параметрический промпт —
 * инструкцию для LLM-реализатора. Факты в промпте — СЕМЕНА (перефразировать,
 * не копировать); числа и структура — жёсткие цели из коридоров корпуса.
 */
final class PromptBuilder
{
    private const TYPE_LABEL = [
        'main' => 'главная (обзор казино)',
        'zerkalo' => 'зеркало / доступ',
        'vhod' => 'вход / авторизация',
        'registracia' => 'регистрация',
        'bonus' => 'бонусы',
        'slots' => 'слоты / игры',
        'app' => 'мобильное приложение',
    ];

    public function build(array $spec): string
    {
        $t = $spec['type'];
        $b = $spec['brand'];
        $tg = $spec['targets'];
        $tone = $spec['tone'];
        $label = self::TYPE_LABEL[$t] ?? $t;

        $out = [];
        $out[] = "# Промпт генерации: страница «{$label}»";
        $out[] = "Бренд: {$b['ru']} / {$b['en']} · домен {$spec['domain']} · дата {$spec['date']} · seed {$spec['seed']}";
        if (!empty($spec['donor'])) {
            $out[] = "Режим: клонирование донора **{$spec['donor']}** — цели ниже сняты с этого сайта корпуса (не с общего распределения).";
        }
        $out[] = "";
        $out[] = "Ты — генератор SEO-контента для казино под Яндекс. Собери ОДНУ HTML-страницу типа «{$label}»";
        $out[] = "СТРОГО в рамках целей ниже. Цель — воспроизвести корпус, НЕ превзойти: не превышай объём и плотности.";
        $out[] = "";

        // РЕГИСТР письма — паттерн стиля (един на все 7 страниц; главнее всего)
        if (!empty($spec['register'])) {
            $rg = $spec['register'];
            $out[] = "## СТИЛЬ ПИСЬМА / РЕГИСТР: {$rg['label']} — пиши СТРОГО так";
            if (!empty($rg['voice']))  { $out[] = "- Голос: {$rg['voice']}."; }
            if (!empty($rg['guide']))  { $out[] = "- {$rg['guide']}"; }
            if (!empty($rg['samples'])) {
                $out[] = "- Примеры фраз в этом регистре (перефразируй в духе, не копируй): " . implode(' · ', array_map(fn($x) => "«{$x}»", $rg['samples']));
            }
            // Жанр донора — снят вычиткой реальных текстов. Регистр (местоимение)
            // жанра не задаёт: «вы» бывает и деловым, и люкс-глянцем; «ты» —
            // и дружеским, и назидательным эссе, и промо-лендингом.
            if (!empty($spec['donor_genre'])) {
                $out[] = "- ЖАНР РЕФЕРЕНСА (важнее местоимения — воспроизводи именно его): {$spec['donor_genre']}";
            }
            $out[] = "- ВАЖНО: регистр — это манера ПОВЕРХ фактов. Все цифры и данные из блока «ФАКТУРА» остаются точными.";
            $out[] = "";
        }
        // E-E-A-T: у части референсов есть подписанный автор с регалиями —
        // Яндекс это учитывает, а метрики текста не видят.
        if (!empty($spec['author_block'])) {
            $out[] = "## АВТОРСКИЙ БЛОК (E-E-A-T) — обязателен на этой странице";
            $out[] = "**МЕСТО: В НАЧАЛЕ страницы** — сразу после вводного абзаца (и паспорт-таблицы, если она есть), в первых ~10% текста. НЕ в конце: в референсах он стоит на позиции 3–9% от начала.";
            $out[] = "**ВПИСЫВАЙ В КОНТЕКСТ, не приклеивай:** вводный абзац подводит к нему, а дальше ВЕСЬ текст ведётся от лица этого автора — он рассказчик, а не подпись в подвале. Например: вступление о личном опыте → блок «кто я» → продолжение «Почему я перебрался сюда…».";
            $out[] = "Состав блока:";
            $out[] = "- Заголовок-плашка: «Проверенный материал» / «Экспертная оценка» / «Инсайдерская информация» — в тон регистру.";
            $out[] = "- Имя и регалии автора: русское имя + должность и стаж («iGaming-редактор и аналитик, 8 лет в нише», «Журналист и исследователь iGaming, стаж в индустрии — 8 лет»). Имя выдумай уместное, стаж 5–10 лет.";
            $out[] = "- Строка обновления: «Материал обновлён в %date%».";
            $out[] = "- Дисклеймер независимости: «Редакция не получает комиссию от казино за размещение» (или аналог в тон регистру).";
            $out[] = "- Если уместно жанру — короткая «Оценочная карта»: 5–7 критериев с баллами вида 8.5/10 и итоговым баллом, плюс абзац «Методика оценки» (как считали).";
            $out[] = "";
        }

        // Стиль-профиль генерации — ЕДИН на все 7 страниц связки
        if (!empty($spec['style'])) {
            $st = $spec['style'];
            $out[] = "## Стиль генерации (ЕДИН для всех 7 страниц этой связки — держи одинаковым)";
            // Манера здесь — эвристика по донору, и она прямо противоречила блоку
            // РЕГИСТРА выше («на ты, живо, сленг» vs «нейтрально-описательный»).
            // Реалайзеры на этом спотыкались. Регистр главнее — при нём эту
            // строку не печатаем вовсе, числовые цели по «я»/«вы» идут в «Тоне».
            if (empty($spec['register'])) {
                $voice = $st['first_person'] ? "повествование от первого лица" . ($st['persona'] ? " (персона «{$st['persona']}»)" : "") : "без первого лица";
                $out[] = "- Голос: {$voice}; " . ($st['vy'] ? "обращение на «вы» — да" : "без обращения на «вы»") . "; манера — {$st['address_mode']}.";
            }
            $out[] = "- Именование бренда: " . ($st['naming'] === 'en-heavy' ? "латиница преобладает ({$b['en']})" : "латиница и кириллица сбалансированы") . "; эмодзи в теле: " . ($st['emoji_site'] ? "да" : "нет") . " (сколько именно — в целях ниже).";
            $out[] = "- Тематические украшения в заголовках: " . ($st['flourish'] >= 0.2 ? "иногда (метафоры удачи/сокровищ)" : "почти нет, по-деловому") . ".";
            $out[] = "";
        }

        // Цели
        $out[] = "## Жёсткие цели (держись коридора)";
        $out[] = "- Объём: **~{$tg['words']} слов** (допуск ±10%).";
        $out[] = "- Заголовки: **{$tg['h2']} H2**, всего разделов (H2+H3) **~{$tg['sections_total']}**.";
        $out[] = "- Списков ~{$tg['lists']}, таблиц ~{$tg['tables']}, цитат-отзывов ~{$tg['quotes']}, выделений <strong> ~{$tg['strong']}.";
        $faqNote = $tg['faq_count'] <= 1 ? " — при цели ≤1 НЕ делай отдельный FAQ-блок с вопросами-подзаголовками" : "";
        $out[] = "- FAQ: **ровно {$tg['faq_count']} вопросов** (отдельный блок в конце) — не больше и не меньше{$faqNote}.";
        // Бюджет цифр в ПРОЗЕ: главный системный промах — реалайзер сыплет числа
        // сверх ФАКТУРЫ. Таблицы/стартовая фактура дают основную массу; прозе
        // оставляем малую долю от общей цели, названную конкретным числом.
        $numTotal = (float)$tg['numbers_per100'] * (int)$tg['words'] / 100.0;
        // В промо-жанрах цифры — часть подачи («вывод за 18 секунд», «до 500%»),
        // и замер показал их НЕДОБОР; там бюджет прозы шире.
        $genrePromo = (bool) preg_match('~реклам|лендинг|промо|восторж~u',
            mb_strtolower((string)($spec['donor_genre'] ?? '') . ' ' . ($spec['register']['label'] ?? '')));
        // Когда таблиц по цели НЕТ, носителем всей плотности остаётся проза — и
        // тот же «бюджет-потолок» гарантирует недобор (замер set232: 0.3–2.8 при
        // цели 2.1–6.4 на страницах без таблиц). Там нужен ПОЛ, а не потолок.
        $noTables = ((int) ($tg['tables'] ?? 0) === 0);
        if ($noTables) {
            $proseFloor = max(3, (int) round($numTotal * 0.85));
            $out[] = "- Плотность цифр: **~{$tg['numbers_per100']} чисел на 100 слов** по ВСЕЙ странице. Таблиц на этой странице нет, значит ВСЮ эту плотность несёт проза.";
            $out[] = "- **ЦИФРЫ В ПРОЗЕ — ЭТО ПОЛ, А НЕ ПОТОЛОК: не меньше ~{$proseFloor} чисел цифрами по тексту.** Суммы, проценты, сроки, лимиты, количества пиши ЦИФРАМИ («от 500 ₽», «до 200%», «за 15 минут»), а не словами — иначе страница выйдет вдвое суше референса. Не выдумывай данных сверх блока ФАКТУРА: бери числа оттуда и повторяй их в разных разрезах.";
        } else {
            $proseCap = max(3, (int) round($numTotal * ($genrePromo ? 0.6 : 0.35)));
            $out[] = "- Плотность цифр: **~{$tg['numbers_per100']} чисел на 100 слов** по ВСЕЙ странице. Основную массу дают ТАБЛИЦЫ и стартовая ФАКТУРА — в прозе числа держи по МИНИМУМУ.";
            $out[] = "- **БЮДЖЕТ ЦИФР В ПРОЗЕ: не более ~{$proseCap} чисел цифрами во всём тексте вне таблиц.** Всё остальное — проценты, суммы, сроки, количества — пиши СЛОВАМИ («около трети», «за пару минут», «более полусотни»). Числа в таблицах и в стартовой фактуре в бюджет не входят и не режутся. Это ограничение ТОЛЬКО на цифры: тематические ключи кластеров (бонус, вывод, зеркало, слот…) — словами, их не трогай.";
        }
        $out[] = "- Сущностей — **НЕ БОЛЕЕ ~{$tg['entities']}**. Считаются КАТЕГОРИИ (лицензия / провайдеры / платежи / крипта / RTP / джекпот / поддержка…), а не отдельные имена. НЕ вводи категорию, которой нет в блоке ФАКТУРА выше: если провайдеров/крипты/RTP/джекпота там нет — пиши обобщённо («слот», «провайдер», «платёжный метод»), а не конкретными брендами. На сателлитах держи набор категорий узким, как в референсе.";
        // Цель по эмодзи берём из донора ПОСТРАНИЧНО. Раньше здесь стояло жёсткое
        // «на сателлитах эмодзи нет» — правило корпуса v1, — и оно затирало
        // корректную цель: у промо-доноров эмодзи есть и на сателлитах
        // (замер set232: слоты 26, бонусы 15 — мы отдавали 0).
        $emoji = ((int) $tg['emoji_body'] > 0)
            ? "эмодзи в теле ~{$tg['emoji_body']}"
            : "эмодзи в теле НЕТ (только в навигации)";
        $out[] = "- Вставки бренда: {$b['en']} (лат.) ~{$tg['brand_en']} раз, {$b['ru']} (кир.) ~{$tg['brand_ru']} раз; {$emoji}.";
        // Прилагательные: реалайзер сходится к ~12% независимо от цели (замер:
        // 11.7–13.6 при цели 8.7–10 и 7.8–9.5 при цели 14.4–16.2). Процент сам по
        // себе не операбелен — добавляем направление относительно этой середины.
        $adjT = (float) $tg['adj_pct'];
        $adjNote = $adjT >= 12.5
            ? " Это МНОГО: почти каждое ключевое существительное идёт с оценочным или уточняющим определением («щедрый бонус», «мгновенный вывод», «свежее зеркало»)."
            : ($adjT <= 10.5
                ? " Это СКУПО: существительное чаще идёт без определения, оценки давай глаголами и фактами, а не цепочками прилагательных."
                : "");
        $out[] = "- Прилагательных ~{$tg['adj_pct']}%.{$adjNote} Академ. тошнота ~{$tone['nausea_acad']}%, водность ~{$tone['water']}% (норма ниши — высокие); плотность ключа ≤ {$tone['key_density']}% (без переспама).";
        // Водность — самое системное смещение: реалайзер пишет СУШЕ референса
        // (замер по 35 страницам: −6.9 п.п.). Числа мало — нужна операциональная
        // инструкция, КАК её набрать, иначе текст выходит телеграфным.
        // Общей формулировки «не пересушивай» не хватает, когда цель высокая:
        // замер даёт стабильный недобор ~10 п.п. на донорах с водностью 32–37%.
        $wetNote = ((float) $tone['water'] >= 30.0)
            ? " У этого референса водность ВЫСОКАЯ: почти каждый факт идёт с пояснением или оговоркой, абзацы длинные, между разделами есть связующие фразы. Голый список фактов здесь не по стилю."
            : "";
        $out[] = "- ВОДНОСТЬ ~{$tone['water']}% — это ЦЕЛЬ, а не потолок: НЕ пересушивай текст.{$wetNote} Живой SEO-текст ниши содержит связки и вводные обороты («как правило», «в большинстве случаев», «при этом», «стоит учитывать», «на практике», «если коротко»), пояснения к фактам и мягкие переходы между абзацами. Не пиши телеграфным стилем из одних фактов — читатель должен видеть рассуждение, а не таблицу в прозе.";
        // Промо-жанры (рекламный, лендинг) живут ПОВТОРАМИ: рефрены, превосходные
        // степени, эмодзи — это их природа. Замер по двум прогонам: у таких доноров
        // мы недодавали тошноту (−7.8), воду (−10), эмодзи (−5.7), прилагательные.
        // Анти-спам инструкции, верные для экспертных текстов, их душат.
        $genreTxt = mb_strtolower((string)($spec['donor_genre'] ?? '') . ' ' . ($spec['register']['label'] ?? ''));
        $isPromo = (bool) preg_match('~реклам|лендинг|промо|восторж~u', $genreTxt);
        if ($isPromo) {
            $out[] = "- ЖАНРОВЫЙ РЕЖИМ: ПРОМО. Повтор — часть этого жанра, НЕ борись с ним. Держи сквозные рефрены (одна-две ударные формулы, повторяющиеся по тексту), превосходные степени и эмоциональные усилители («лучший», «мгновенно», «всего за», «уже сегодня»). Ключевые слова можно повторять — синонимическая ротация здесь ВРЕДИТ, текст должен звучать рекламно, а не энциклопедично.";
            $out[] = "- Не пересушивай: разворачивай выгоды словами, добавляй эмоциональные связки и обращения к читателю. Эмоция набирается рефренами, восклицаниями и эмодзи — но по прилагательным и эмодзи держи ИМЕННО целевые числа выше, а не «побольше»: у части промо-доноров они как раз низкие.";
        } else {
            $out[] = "- ПРОТИВ ТОШНОТЫ: не повторяй головной ключ подряд — чередуй синонимами. Зеркало → рабочая ссылка / актуальный домен / обход блокировки; бонус → промо / поощрение / подарок; вывод → выплата / снятие средств; регистрация → создание аккаунта / открытие профиля; приложение → мобильный клиент / apk. Смысл держи, слово меняй.";
            $out[] = "- ТОШНОТА, родовые слова (главный источник на инфо-страницах): чередуй и их — казино → клуб / оператор / площадка / заведение; сайт → ресурс / платформа / портал; игр → автоматов / слотов / тайтлов / развлечений; игрок → пользователь / гость / клиент. НЕ начинай два заголовка подряд с одного слова. Одно и то же существительное — не чаще ~2 раз в абзаце.";
        }
        $out[] = "";

        // Фактура — именованные данные (защита от «ИИ без данных»)
        if (!empty($spec['data_card'])) {
            $out[] = "## ФАКТУРА — обязательно вплети эти конкретные данные (не общими словами!)";
            // При цели «таблиц ~0» эта фраза всё равно заставляла верстать таблицу
            // (замер set232: 3–4 таблицы там, где у донора их нет вовсе).
            $out[] = ((int) ($tg['tables'] ?? 0) > 0)
                ? "Это «паспорт» бренда. Вынеси часть в спец-таблицу/спец-блок в начале, остальное рассыпь по тексту. Плотность цифр набирается именно этим — конкретикой, а не водой."
                : "Это «паспорт» бренда. Таблиц на этой странице быть НЕ должно (цель — 0): вынеси часть в компактный спец-блок списком в начале, остальное рассыпь по тексту. Плотность цифр набирается конкретикой, а не водой.";
            foreach ($spec['data_card'] as $k => $v) {
                if ($v !== '') { $out[] = "- **{$k}:** {$v}"; }
            }
            $out[] = "Опирайся на эти данные как на источник конкретики, но НЕ выдумывай дополнительные числа сверх фактуры и таблиц — плотность цифр уже задана целью выше.";
            $out[] = "";
        }

        // Структурные таблицы фактуры (турнирная сетка, джекпоты, уровни)
        if (!empty($spec['data_tables'])) {
            $out[] = "## ГОТОВЫЕ ТАБЛИЦЫ (вставь как таблицы, значения — как есть)";
            foreach ($spec['data_tables'] as $title => $rows) {
                if (empty($rows)) { continue; }
                $cols = array_keys($rows[0]);
                $out[] = "**{$title}:** колонки — " . implode(' | ', $cols);
                foreach ($rows as $r) {
                    $out[] = "  · " . implode(' | ', array_values($r));
                }
            }
            $out[] = "";
        }

        // Тон
        $out[] = "## Тон";
        $addr = [];
        $addr[] = $tone['first_person'] ? "первое лицо / личный опыт — ДА" : "первое лицо — нет";
        $addr[] = $tone['vy'] ? "обращение на «вы» — ДА" : "обращение на «вы» — нет (нейтрально)";
        $out[] = "- " . implode('; ', $addr) . ". Основной режим: {$tone['address_mode']}.";
        // Обращение/лицо — числовые цели. Пишем их ЯВНО и связываем с императивами:
        // подрезка команд не должна вымывать «вы», усиление «я» — не раздувать команды.
        // Низкие цели раньше НЕ печатались (порог ≥3) — и ничем не сдерживались:
        // при цели «я»≈1 реалайзер выдавал 8–11, микро-истории уходили в первое
        // лицо. Низкое значение — это ПОТОЛОК, и его надо называть.
        $vyT = (int)($tg['vy'] ?? 0); $fpT = (int)($tg['first_person'] ?? 0);
        $addrTargets = [];
        $addrTargets[] = $vyT >= 3
            ? "обращений «вы/вам/ваш» — **~{$vyT}**"
            : "обращений «вы/вам/ваш» — **почти нет (~{$vyT})**, это потолок, а не ориентир";
        $addrTargets[] = $fpT >= 3
            ? "первого лица «я/мне/мой» — **~{$fpT}**"
            : "первого лица «я/мне/мой» — **почти нет (~{$fpT})**: истории и отзывы подавай в третьем лице («игрок из Казани вывел…»), а не от себя";
        if ($addrTargets) {
            $out[] = "- ЦЕЛИ ПО ОБРАЩЕНИЮ: " . implode('; ', $addrTargets)
                . ". Это САМОСТОЯТЕЛЬНЫЕ цели: держи их, даже когда сокращаешь побудительные глаголы. Команду убираешь — заменяй на «вы»-утверждение («Заберите бонус» → «Бонус зачисляется на ваш счёт»), а НЕ на безличную форму. Обращение и CTA — разные параметры, не вымывай одно вместе с другим.";
        }
        // Императивы — цель называется числом, но реалайзер её не считает: замер
        // показал промахи в ОБЕ стороны на одном и том же промпте (set227 главная
        // 35 при цели 7, set232 зеркало 0 при цели 7). Число на всю страницу
        // неоперабельно — переводим его в норму НА РАЗДЕЛ, её видно на месте.
        $impv = (int) ($tg['imperatives'] ?? 0);
        $secN = max(1, (int) ($tg['sections_total'] ?? $tg['h2'] ?? 1));
        if ($impv <= 1) {
            $impNote = "Побудительных/CTA («сделай/проверь/открой/жми») почти НЕТ (~{$impv}) — веди повествованием, а не призывами.";
        } else {
            $rate = $impv >= $secN
                ? "это ~" . max(1, (int) round($impv / $secN)) . " на раздел"
                : "это примерно 1 команда на каждые " . max(2, (int) round($secN / max(1, $impv))) . " разделов — в остальных разделах команд быть НЕ должно";
            $impNote = "Побудительных/CTA-глаголов («сделай/проверь/открой/пополни») ровно **~{$impv}** на весь фрагмент — {$rate}. Считай их по ходу письма: перебор так же плох, как недобор. Лишний призыв переписывай утверждением («Заберите бонус» → «Бонус зачисляется на счёт»).";
        }
        $out[] = "- Активный залог (пассив ~1.5%), читабельность низкая (тексты «тяжёлые» — это норма). {$impNote}";
        $out[] = "";

        // Семантика — ЦЕЛЕВАЯ плотность кластеров (раскрытие семантики под донора)
        $sem = $spec['semantics'] ?? [];
        if ($sem !== []) {
            $out[] = "## СЕМАНТИКА — целевая плотность кластеров (вхождений ключей на 100 слов)";
            $out[] = "Раскрой темы ровно с такой плотностью — это профиль конкретного референса под его стиль. Это ЦЕЛЬ по каждому кластеру: держи её и снизу, и сверху. Плотность набирается ТЕМАТИЧЕСКИМИ СЛОВАМИ (не цифрами): достигай цели естественными повторами ключей темы.";
            $out[] = "- Ниже цели (частая ошибка на «бонусы», «деньги/вывод», «приложение») — добавь ещё абзац/пункты по теме кластера с его ключами.";
            $out[] = "- Выше цели (частая ошибка на «доступ/зеркало» на страницах зеркала и входа) — НЕ повторяй ключи сверх нормы, перефразируй нейтрально. Перебор так же плох, как недобор.";
            arsort($sem);
            foreach ($sem as $k => $v) {
                if ((float) $v <= 0) { continue; }
                $mark = (float) $v >= 3 ? ' ← доминанта, держи ключами (НЕ выше)' : ((float) $v >= 1 ? ' ← заметно' : ' ← лёгкое касание, не разгоняй');
                $out[] = "- {$k}: **{$v}** на 100 слов{$mark}";
            }
            $out[] = "Кластеры с нулём почти не трогай — так референс держит фокус страницы.";
            $out[] = "";
        }

        // Структура по секциям
        $out[] = "## Структура (собери секции в таком порядке; ЗАГОЛОВКИ переформулируй уникально)";
        $opener = '';
        $n = 0;
        foreach ($spec['sections'] as $s) {
            if (($s['role'] ?? '') === 'opener') {
                $opener = $s['hint'];
                continue;
            }
            if (($s['role'] ?? '') === 'faq') {
                $out[] = "";
                $out[] = "### FAQ ({$s['count']} вопросов) — рамки (заполни слоты под тему страницы):";
                $frames = array_count_values($s['frames']);
                foreach ($frames as $fr => $cnt) {
                    $out[] = "  - «{$fr}» ×{$cnt}";
                }
                continue;
            }
            $n++;
            $out[] = "";
            $out[] = "**{$n}. [{$s['level']}] Тема: {$s['topic']}** _(класс: {$s['theme']})_";
            $hstyle = $s['heading_style'] === 'creative'
                ? "заголовок — креативно перефразируй по паттерну «{$s['heading_pattern']}» (двоеточие-подзаголовок / «мой опыт» / вопрос; изредка тематическое украшение)"
                : "заголовок — обычная формулировка темы";
            $out[] = "   - {$hstyle}.";
            $out[] = "   - Раскрой факт-категорию: **{$s['fact_category']}**.";
            if ($s['entities'] !== []) {
                $out[] = "   - Сущности (вплети естественно): " . implode(', ', $s['entities']) . ".";
            }
            if ($s['values'] !== []) {
                $vv = [];
                foreach ($s['values'] as $k => $v) { if ($v !== '') { $vv[] = "{$k}={$v}"; } }
                if ($vv !== []) { $out[] = "   - Числа-значения (используй как есть): " . implode(', ', $vv) . "."; }
            }
            $out[] = "   - Прикреплённый блок: " . $this->blockLabel($s['block']) . ".";
            if (!empty($s['fact_seeds'])) {
                $out[] = "   - Семена-тезисы (ПЕРЕФРАЗИРУЙ по смыслу, НЕ копируй дословно, не повторяйся между секциями):";
                foreach ($s['fact_seeds'] as $seed) {
                    $seed = mb_substr($seed, 0, 180);
                    $out[] = "     · {$seed}";
                }
            }
        }

        $out[] = "";
        // Перелинковка по принципу корпуса (число ссылок зависит от типа)
        if (!empty($spec['links'])) {
            $n = count($spec['links']);
            $out[] = "## ПЕРЕЛИНКОВКА (ровно {$n} внутренних ссылок — расставь КОНТЕКСТНО по тексту)";
            $isMain = ($spec['type'] ?? '') === 'main';
            if ($isMain) {
                $out[] = "Это страница-ХАБ: ссылок много (~{$n}). Вставляй их прямо в тело релевантных разделов (в абзацы и пункты списков), можно по несколько раз на одну цель из разных секций. НЕ сваливай всё в один навблок.";
            } else {
                $out[] = "Сателлит: {$n} контекстных ссылок в тексте, каждая — в тематически близком месте. Отдельный огромный навблок не нужен.";
            }
            $out[] = "Анкоры (в основном чистые ключи, бренд-переменная лишь изредка) — используй по списку:";
            foreach ($spec['links'] as $l) {
                $out[] = "- <a href=\"{$l['path']}\">{$l['anchor']}</a>";
            }
            $out[] = "";
        }

        // Бренд как переменная (шаблон-плейсхолдеры вместо реального названия)
        if (!empty($spec['brand_var'])) {
            $out[] = "## БРЕНД — ПЕРЕМЕННАЯ (не подставляй реальное имя!)";
            $out[] = "Везде используй плейсхолдеры как есть: %brand_name_ru% (кириллица), %brand_name_en% (латиница), %domain_name% (домен), %date% (дата). CMS подставит реальные значения. Считай вставки бренда по этим меткам.";
            $out[] = "";
        }

        $out[] = "## Обязательные инварианты";
        // Опенер (первый абзац «%brand_name_ru%. …») по умолчанию ВЫКЛЮЧЕН —
        // площадка использует первый абзац иначе. Включается флагом --opener
        // (spec['with_opener']=true). При выключенном опенере первым идёт
        // содержательный абзац/подзаголовок, без бренд-зачина.
        if (!empty($spec['with_opener'])) {
            $out[] = "- Опенер первым абзацем: {$opener}";
        } else {
            $out[] = "- БЕЗ опенера-зачина: НЕ начинай страницу с «%brand_name_ru%. …». Первым идёт обычный содержательный абзац или подзаголовок по теме. Бренд-переменные используй по тексту, но не выноси бренд в самое первое предложение.";
        }
        $out[] = "- " . implode('; ', $spec['invariants']) . ".";
        $out[] = "- Дата-стамп «Последнее обновление: {$spec['date']} · {$spec['domain']}».";
        $out[] = "- Schema (JSON-LD) в конце. НИ ОДНОГО чужого бренда. 0 изображений.";
        $out[] = "- Выведи чистый HTML-фрагмент (без <html>/<head>/<title> — их добавит CMS).";

        // КОНТРОЛЬНЫЙ ЧЕК-ЛИСТ — свод всех целей, чтобы попасть за один проход
        $out[] = "";
        $out[] = "## КОНТРОЛЬНЫЙ ЧЕК-ЛИСТ (соблюсти ВСЁ сразу, не по отдельности)";
        $out[] = "1. **Объём** ~{$tg['words']} слов (±10%) — не короче и не длиннее; ключи добавляй вместо воды, не поверх.";
        $out[] = "2. **Регистр** «" . ($spec['register']['label'] ?? '—') . "» выдержан от первого до последнего абзаца.";
        if (!empty($spec['semantics'])) {
            $sem2 = $spec['semantics']; arsort($sem2);
            $topSem = [];
            foreach (array_slice($sem2, 0, 3, true) as $k => $v) { if ((float)$v > 0) { $topSem[] = "{$k}≈{$v}"; } }
            $out[] = "3. **Семантика** — держи плотность кластеров: " . implode(', ', $topSem) . " (на 100 слов); нулевые кластеры не трогай.";
        }
        $out[] = "4. **Бренд** — {$b['en']} (лат.) ~{$tg['brand_en']} раз, {$b['ru']} (кир.) ~{$tg['brand_ru']} раз (соотношение важно для SEO).";
        $out[] = "5. **Перелинковка** — ровно " . count($spec['links'] ?? []) . " внутренних ссылок, контекстно; " . (($spec['type'] ?? '') === 'main' ? 'хаб-стиль (повторы целей)' : 'без большого навблока') . ".";
        $out[] = "6. **Структура** — H2 {$tg['h2']}, списков ~{$tg['lists']}, таблиц ~{$tg['tables']}, цитат ~{$tg['quotes']}, FAQ {$tg['faq_count']}.";
        $out[] = "7. **Инварианты** — таблица, список, цитата, дата-стамп, Schema, 0 чужих брендов.";

        return implode("\n", $out) . "\n";
    }

    private function blockLabel(string $block): string
    {
        if ($block === 'none') { return 'без блока (только абзацы)'; }
        if ($block === 'list') { return 'маркированный список'; }
        // «от первого лица» противоречило цели «я»≈1 у части доноров — лицо задают
        // числовые цели в «Тоне», здесь его не навязываем.
        if ($block === 'quote') { return 'цитата-отзыв игрока (короткая; лицо — по целям обращения выше)'; }
        if (str_starts_with($block, 'table:')) {
            $type = substr($block, 6);
            $map = [
                'спецификация' => 'таблица-спецификация (Параметр | Значение)',
                'шаги' => 'таблица шагов (Шаг | Действие)',
                'игры' => 'таблица игр (Игра | RTP/провайдер)',
                'проблема-решение' => 'таблица Проблема | Решение',
            ];
            return $map[$type] ?? 'таблица';
        }
        return $block;
    }
