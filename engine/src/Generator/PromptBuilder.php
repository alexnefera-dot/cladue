        $out[] = "4. **Бренд** — {$b['en']} (лат.) ~{$tg['brand_en']} раз, {$b['ru']} (кир.) ~{$tg['brand_ru']} раз (соотношение важно для SEO).";
        $out[] = "5. **Перелинковка** — ровно " . count($spec['links'] ?? []) . " внутренних ссылок, контекстно; " . (($spec['type'] ?? '') === 'main' ? 'хаб-стиль (повторы целей)' : 'без большого навблока') . ".";
        $out[] = "6. **Структура** — H2 {$tg['h2']}, списков ~{$tg['lists']}, таблиц ~{$tg['tables']}, цитат ~{$tg['quotes']}, FAQ {$tg['faq_count']}.";
        $out[] = "7. **Инварианты** — таблица, список, цитата, дата-стамп, Schema, 0 чужих брендов.";

        return implode("\n", $out) . "\n";
    }

    private function blockLabel(string $block): string
    {
        if ($block === 'none') { return 'без блока (только абзацы)'; }
        if ($block === 'list') { return 'маркированный список'; }
        // «от первого лица» противоречило цели «я»≈1 у части доноров — лицо задают
        // числовые цели в «Тоне», здесь его не навязываем.
        if ($block === 'quote') { return 'цитата-отзыв игрока (короткая; лицо — по целям обращения выше)'; }
        if (str_starts_with($block, 'table:')) {
            $type = substr($block, 6);
            $map = [
                'спецификация' => 'таблица-спецификация (Параметр | Значение)',
                'шаги' => 'таблица шагов (Шаг | Действие)',
                'игры' => 'таблица игр (Игра | RTP/провайдер)',
                'проблема-решение' => 'таблица Проблема | Решение',
            ];
            return $map[$type] ?? 'таблица';
        }
        return $block;
    }
