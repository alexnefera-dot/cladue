<?php
declare(strict_types=1);

/**
 * Превращает сборочную спеку (Planner) в заполненный параметрический промпт —
 * инструкцию для LLM-реализатора. Факты в промпте — СЕМЕНА (перефразировать,
 * не копировать); числа и структура — жёсткие цели из коридоров корпуса.
 */
final class PromptBuilder
{
    private const TYPE_LABEL = [
        'main' => 'главная (обзор казино)',
        'zerkalo' => 'зеркало / доступ',
        'vhod' => 'вход / авторизация',
        'registracia' => 'регистрация',
        'bonus' => 'бонусы',
        'slots' => 'слоты / игры',
        'app' => 'мобильное приложение',
    ];

    public function build(array $spec): string
    {
        $t = $spec['type'];
        $b = $spec['brand'];
        $tg = $spec['targets'];
        $tone = $spec['tone'];
        $label = self::TYPE_LABEL[$t] ?? $t;

        $out = [];
        $out[] = "# Промпт генерации: страница «{$label}»";
        $out[] = "Бренд: {$b['ru']} / {$b['en']} · домен {$spec['domain']} · дата {$spec['date']} · seed {$spec['seed']}";
        if (!empty($spec['donor'])) {
            $out[] = "Режим: клонирование донора **{$spec['donor']}** — цели ниже сняты с этого сайта корпуса (не с общего распределения).";
        }
        $out[] = "";
        $out[] = "Ты — генератор SEO-контента для казино под Яндекс. Собери ОДНУ HTML-страницу типа «{$label}»";
        $out[] = "СТРОГО в рамках целей ниже. Цель — воспроизвести корпус, НЕ превзойти: не превышай объём и плотности.";
        $out[] = "";

        // РЕГИСТР письма — паттерн стиля (един на все 7 страниц; главнее всего)
        if (!empty($spec['register'])) {
            $rg = $spec['register'];
            $out[] = "## СТИЛЬ ПИСЬМА / РЕГИСТР: {$rg['label']} — пиши СТРОГО так";
            if (!empty($rg['voice']))  { $out[] = "- Голос: {$rg['voice']}."; }
            if (!empty($rg['guide']))  { $out[] = "- {$rg['guide']}"; }
            if (!empty($rg['samples'])) {
                $out[] = "- Примеры фраз в этом регистре (перефразируй в духе, не копируй): " . implode(' · ', array_map(fn($x) => "«{$x}»", $rg['samples']));
            }
            $out[] = "- ВАЖНО: регистр — это манера ПОВЕРХ фактов. Все цифры и данные из блока «ФАКТУРА» остаются точными.";
            $out[] = "";
        }

        // Стиль-профиль генерации — ЕДИН на все 7 страниц связки
        if (!empty($spec['style'])) {
            $st = $spec['style'];
            $out[] = "## Стиль генерации (ЕДИН для всех 7 страниц этой связки — держи одинаковым)";
            $voice = $st['first_person'] ? "повествование от первого лица" . ($st['persona'] ? " (персона «{$st['persona']}»)" : "") : "без первого лица";
            $out[] = "- Голос: {$voice}; " . ($st['vy'] ? "обращение на «вы» — да" : "без обращения на «вы»") . "; манера — {$st['address_mode']}.";
            $out[] = "- Именование бренда: " . ($st['naming'] === 'en-heavy' ? "латиница преобладает ({$b['en']})" : "латиница и кириллица сбалансированы") . "; эмодзи в теле: " . ($st['emoji_site'] ? "да (только на главной)" : "нет") . ".";
            $out[] = "- Тематические украшения в заголовках: " . ($st['flourish'] >= 0.2 ? "иногда (метафоры удачи/сокровищ)" : "почти нет, по-деловому") . ".";
            $out[] = "";
        }

        // Цели
        $out[] = "## Жёсткие цели (держись коридора)";
        $out[] = "- Объём: **~{$tg['words']} слов** (допуск ±10%).";
        $out[] = "- Заголовки: **{$tg['h2']} H2**, всего разделов (H2+H3) **~{$tg['sections_total']}**.";
        $out[] = "- Списков ~{$tg['lists']}, таблиц ~{$tg['tables']}, цитат-отзывов ~{$tg['quotes']}, выделений <strong> ~{$tg['strong']}.";
        $out[] = "- FAQ: **{$tg['faq_count']} вопросов** (отдельный блок в конце).";
        $out[] = "- Плотность цифр: **~{$tg['numbers_per100']} чисел на 100 слов** (это НИЗКО — не перегружай цифрами).";
        $out[] = "- Сущностей (игры/провайдеры/платёжки) всего ~{$tg['entities']}.";
        $emoji = $t === 'main' ? "эмодзи в теле ~{$tg['emoji_body']}" : "эмодзи в теле НЕТ (только в навигации)";
        $out[] = "- Вставки бренда: {$b['en']} (лат.) ~{$tg['brand_en']} раз, {$b['ru']} (кир.) ~{$tg['brand_ru']} раз; {$emoji}.";
        $out[] = "- Прилагательных ~{$tg['adj_pct']}%; академ. тошнота ~{$tone['nausea_acad']}%, водность ~{$tone['water']}% (норма ниши — высокие); плотность ключа ≤ {$tone['key_density']}% (без переспама).";
        $out[] = "";

        // Фактура — именованные данные (защита от «ИИ без данных»)
        if (!empty($spec['data_card'])) {
            $out[] = "## ФАКТУРА — обязательно вплети эти конкретные данные (не общими словами!)";
            $out[] = "Это «паспорт» бренда. Вынеси часть в спец-таблицу/спец-блок в начале, остальное рассыпь по тексту. Плотность цифр набирается именно этим — конкретикой, а не водой.";
            foreach ($spec['data_card'] as $k => $v) {
                if ($v !== '') { $out[] = "- **{$k}:** {$v}"; }
            }
            $out[] = "Дополнительно приводи конкретику в каждом разделе: суммы (₽/\$), проценты (RTP, бонус, кэшбэк), сроки (минуты/часы), количества (игр, шагов, уровней), версии ОС, даты. Избегай общих фраз без чисел.";
            $out[] = "";
        }

        // Тон
        $out[] = "## Тон";
        $addr = [];
        $addr[] = $tone['first_person'] ? "первое лицо / личный опыт — ДА" : "первое лицо — нет";
        $addr[] = $tone['vy'] ? "обращение на «вы» — ДА" : "обращение на «вы» — нет (нейтрально)";
        $out[] = "- " . implode('; ', $addr) . ". Основной режим: {$tone['address_mode']}.";
        $out[] = "- Активный залог (пассив ~1.5%), императивы-CTA умеренно, читабельность низкая (тексты «тяжёлые» — это норма).";
        $out[] = "";

        // Семантика
        $out[] = "## Семантика (о чём страница — плотность кластеров, вхождений на 100 слов)";
        $sem = $spec['semantics'];
        arsort($sem);
        $top = array_slice($sem, 0, 6, true);
        $semLine = [];
        foreach ($top as $k => $v) { $semLine[] = "{$k} ({$v})"; }
        $out[] = "- Доминанты: " . implode(' · ', $semLine) . ".";
        $out[] = "- Разбавляй кросс-темами (слоты/зеркало/платежи/поддержка встречаются во всех типах).";
        $out[] = "";

        // Структура по секциям
        $out[] = "## Структура (собери секции в таком порядке; ЗАГОЛОВКИ переформулируй уникально)";
        $opener = '';
        $n = 0;
        foreach ($spec['sections'] as $s) {
            if (($s['role'] ?? '') === 'opener') {
                $opener = $s['hint'];
                continue;
            }
            if (($s['role'] ?? '') === 'faq') {
                $out[] = "";
                $out[] = "### FAQ ({$s['count']} вопросов) — рамки (заполни слоты под тему страницы):";
                $frames = array_count_values($s['frames']);
                foreach ($frames as $fr => $cnt) {
                    $out[] = "  - «{$fr}» ×{$cnt}";
                }
                continue;
            }
            $n++;
            $out[] = "";
            $out[] = "**{$n}. [{$s['level']}] Тема: {$s['topic']}** _(класс: {$s['theme']})_";
            $hstyle = $s['heading_style'] === 'creative'
                ? "заголовок — креативно перефразируй по паттерну «{$s['heading_pattern']}» (двоеточие-подзаголовок / «мой опыт» / вопрос; изредка тематическое украшение)"
                : "заголовок — обычная формулировка темы";
            $out[] = "   - {$hstyle}.";
            $out[] = "   - Раскрой факт-категорию: **{$s['fact_category']}**.";
            if ($s['entities'] !== []) {
                $out[] = "   - Сущности (вплети естественно): " . implode(', ', $s['entities']) . ".";
            }
            if ($s['values'] !== []) {
                $vv = [];
                foreach ($s['values'] as $k => $v) { if ($v !== '') { $vv[] = "{$k}={$v}"; } }
                if ($vv !== []) { $out[] = "   - Числа-значения (используй как есть): " . implode(', ', $vv) . "."; }
            }
            $out[] = "   - Прикреплённый блок: " . $this->blockLabel($s['block']) . ".";
            if (!empty($s['fact_seeds'])) {
                $out[] = "   - Семена-тезисы (ПЕРЕФРАЗИРУЙ по смыслу, НЕ копируй дословно, не повторяйся между секциями):";
                foreach ($s['fact_seeds'] as $seed) {
                    $seed = mb_substr($seed, 0, 180);
                    $out[] = "     · {$seed}";
                }
            }
        }

        $out[] = "";
        $out[] = "## Обязательные инварианты";
        $out[] = "- Опенер первым абзацем: {$opener}";
        $out[] = "- " . implode('; ', $spec['invariants']) . ".";
        $out[] = "- Дата-стамп «Последнее обновление: {$spec['date']} · {$spec['domain']}».";
        $out[] = "- Schema (JSON-LD) в конце. НИ ОДНОГО чужого бренда. 0 изображений.";
        $out[] = "- Выведи чистый HTML-фрагмент (без <html>/<head>/<title> — их добавит CMS).";

        return implode("\n", $out) . "\n";
    }

    private function blockLabel(string $block): string
    {
        if ($block === 'none') { return 'без блока (только абзацы)'; }
        if ($block === 'list') { return 'маркированный список'; }
        if ($block === 'quote') { return 'цитата-отзыв игрока (короткая, от первого лица)'; }
        if (str_starts_with($block, 'table:')) {
            $type = substr($block, 6);
            $map = [
                'спецификация' => 'таблица-спецификация (Параметр | Значение)',
                'шаги' => 'таблица шагов (Шаг | Действие)',
                'игры' => 'таблица игр (Игра | RTP/провайдер)',
                'проблема-решение' => 'таблица Проблема | Решение',
            ];
            return $map[$type] ?? 'таблица';
        }
        return $block;
    }
}
