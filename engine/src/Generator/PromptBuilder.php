<?php
declare(strict_types=1);

/**
 * Превращает сборочную спеку (Planner) в заполненный параметрический промпт —
 * инструкцию для LLM-реализатора. Факты в промпте — СЕМЕНА (перефразировать,
 * не копировать); числа и структура — жёсткие цели из коридоров корпуса.
 */
final class PromptBuilder
{
    private const TYPE_LABEL = [
        'main' => 'главная (обзор казино)',
        'zerkalo' => 'зеркало / доступ',
        'vhod' => 'вход / авторизация',
        'registracia' => 'регистрация',
        'bonus' => 'бонусы',
        'slots' => 'слоты / игры',
        'app' => 'мобильное приложение',
    ];

    public function build(array $spec): string
    {
        $t = $spec['type'];
        $b = $spec['brand'];
        $tg = $spec['targets'];
        $tone = $spec['tone'];
        $label = self::TYPE_LABEL[$t] ?? $t;

        $out = [];
        $out[] = "# Промпт генерации: страница «{$label}»";
        $out[] = "Бренд: {$b['ru']} / {$b['en']} · домен {$spec['domain']} · дата {$spec['date']} · seed {$spec['seed']}";
        if (!empty($spec['donor'])) {
            $out[] = "Режим: клонирование донора **{$spec['donor']}** — цели ниже сняты с этого сайта корпуса (не с общего распределения).";
        }
        $out[] = "";
        $out[] = "Ты — генератор SEO-контента для казино под Яндекс. Собери ОДНУ HTML-страницу типа «{$label}»";
        $out[] = "СТРОГО в рамках целей ниже. Цель — воспроизвести корпус, НЕ превзойти: не превышай объём и плотности.";
        $out[] = "";

        // РЕГИСТР письма — паттерн стиля (един на все 7 страниц; главнее всего)
        if (!empty($spec['register'])) {
            $rg = $spec['register'];
            // Заголовок тоже берём из читаного профиля: пуловая метка
            // («Нейтрально-справочный») противоречила бы жанру под ней.
            $rgLabel = !empty($spec['donor_register']) ? $spec['donor_register'] : $rg['label'];
            $out[] = "## СТИЛЬ ПИСЬМА / РЕГИСТР: {$rgLabel} — пиши СТРОГО так";
            // Пуловый регистр — это одна из пяти заготовок, выбранная по
            // эвристике. Когда у донора есть профиль, снятый чтением, заготовка
            // ему противоречит: замерщику от первого лица доставалось «голос
            // безличный, сухой, справочный», и реалайзер обнулял и первое лицо,
            // и побудительные глаголы. Читаный профиль главнее — заготовку тогда
            // не печатаем вовсе.
            $hasRead = !empty($spec['donor_voice']);
            if (!$hasRead) {
                if (!empty($rg['voice']))  { $out[] = "- Голос: {$rg['voice']}."; }
                if (!empty($rg['guide']))  { $out[] = "- {$rg['guide']}"; }
                if (!empty($rg['samples'])) {
                    $out[] = "- Примеры фраз в этом регистре (перефразируй в духе, не копируй): " . implode(' · ', array_map(fn($x) => "«{$x}»", $rg['samples']));
                }
            }
            // Жанр донора — снят вычиткой реальных текстов. Регистр (местоимение)
            // жанра не задаёт: «вы» бывает и деловым, и люкс-глянцем; «ты» —
            // и дружеским, и назидательным эссе, и промо-лендингом.
            if (!empty($spec['donor_genre'])) {
                $out[] = "- ЖАНР РЕФЕРЕНСА (важнее местоимения — воспроизводи именно его): {$spec['donor_genre']}";
            }
            // Профиль корпуса v3, снятый чтением. У корпусов v1/v2 этих полей
            // нет, и промпт для них не меняется ни на строку.
            if (!empty($spec['donor_voice'])) {
                $out[] = "- КТО ГОВОРИТ: {$spec['donor_voice']}. Это главнее местоимений: от субъекта речи зависит и модальность (обещание или предостережение), и то, кем назван читатель.";
            }
            if (!empty($spec['donor_register'])) {
                $out[] = "- ОБРАЩЕНИЕ: {$spec['donor_register']}.";
            }
            if (!empty($spec['donor_devices'])) {
                $out[] = "- ПРИЁМЫ РЕФЕРЕНСА — воспроизводи их, это и есть его почерк:";
                foreach ($spec['donor_devices'] as $d) { $out[] = "  · {$d}"; }
            }
            if (!empty($spec['donor_numbers'])) {
                $out[] = "- КАК УСТРОЕНЫ ЧИСЛА: {$spec['donor_numbers']}";
            }
            if (!empty($spec['donor_emoji_where'])) {
                $out[] = "- ГДЕ СТОЯТ ЭМОДЗИ: {$spec['donor_emoji_where']}";
            }
            if (!empty($spec['donor_avoid'])) {
                $out[] = "- ЧЕГО В РЕФЕРЕНСЕ НЕТ — не добавляй: " . implode('; ', $spec['donor_avoid']) . ".";
            }
            $out[] = "- ВАЖНО: регистр — это манера ПОВЕРХ фактов. Все цифры и данные из блока «ФАКТУРА» остаются точными.";
            $out[] = "";
        }
        // E-E-A-T: у части референсов есть подписанный автор с регалиями —
        // Яндекс это учитывает, а метрики текста не видят.
        if (!empty($spec['author_block'])) {
            $out[] = "## АВТОРСКИЙ БЛОК (E-E-A-T) — обязателен на этой странице";
            $out[] = "**МЕСТО: В НАЧАЛЕ страницы** — сразу после вводного абзаца (и паспорт-таблицы, если она есть), в первых ~10% текста. НЕ в конце: в референсах он стоит на позиции 3–9% от начала.";
            $out[] = "**ВПИСЫВАЙ В КОНТЕКСТ, не приклеивай:** вводный абзац подводит к нему, а дальше ВЕСЬ текст ведётся от лица этого автора — он рассказчик, а не подпись в подвале. Например: вступление о личном опыте → блок «кто я» → продолжение «Почему я перебрался сюда…».";
            $out[] = "Состав блока:";
            $out[] = "- Заголовок-плашка: «Проверенный материал» / «Экспертная оценка» / «Инсайдерская информация» — в тон регистру.";
            $out[] = "- Имя и регалии автора: русское имя + должность и стаж («iGaming-редактор и аналитик, 8 лет в нише», «Журналист и исследователь iGaming, стаж в индустрии — 8 лет»). Имя выдумай уместное, стаж 5–10 лет.";
            $out[] = "- Строка обновления: «Материал обновлён в %date%».";
            $out[] = "- Дисклеймер независимости: «Редакция не получает комиссию от казино за размещение» (или аналог в тон регистру).";
            $out[] = "- Если уместно жанру — короткая «Оценочная карта»: 5–7 критериев с баллами вида 8.5/10 и итоговым баллом, плюс абзац «Методика оценки» (как считали).";
            $out[] = "";
        }

        // Стиль-профиль генерации — ЕДИН на все 7 страниц связки
        if (!empty($spec['style'])) {
            $st = $spec['style'];
            $out[] = "## Стиль генерации (ЕДИН для всех 7 страниц этой связки — держи одинаковым)";
            // Манера здесь — эвристика по донору, и она прямо противоречила блоку
            // РЕГИСТРА выше («на ты, живо, сленг» vs «нейтрально-описательный»).
            // Реалайзеры на этом спотыкались. Регистр главнее — при нём эту
            // строку не печатаем вовсе, числовые цели по «я»/«вы» идут в «Тоне».
            if (empty($spec['register'])) {
                $voice = $st['first_person'] ? "повествование от первого лица" . ($st['persona'] ? " (персона «{$st['persona']}»)" : "") : "без первого лица";
                $out[] = "- Голос: {$voice}; " . ($st['vy'] ? "обращение на «вы» — да" : "без обращения на «вы»") . "; манера — {$st['address_mode']}.";
            }
            $out[] = "- Именование бренда: " . ($st['naming'] === 'en-heavy' ? "латиница преобладает ({$b['en']})" : "латиница и кириллица сбалансированы") . "; эмодзи в теле: " . ($st['emoji_site'] ? "да" : "нет") . " (сколько именно — в целях ниже).";
            $out[] = "- Тематические украшения в заголовках: " . ($st['flourish'] >= 0.2 ? "иногда (метафоры удачи/сокровищ)" : "почти нет, по-деловому") . ".";
            $out[] = "";
        }

        // Цели
        $out[] = "## Жёсткие цели (держись коридора)";
        $out[] = "- Объём: **~{$tg['words']} слов** (допуск ±10%).";
        $out[] = "- Заголовки: **{$tg['h2']} H2**, всего разделов (H2+H3) **~{$tg['sections_total']}**.";
        $out[] = "- Списков ~{$tg['lists']}, таблиц ~{$tg['tables']}, цитат-отзывов ~{$tg['quotes']}, выделений <strong> ~{$tg['strong']}.";
        $faqNote = $tg['faq_count'] <= 1 ? " — при цели ≤1 НЕ делай отдельный FAQ-блок с вопросами-подзаголовками" : "";
        // Считается не блок FAQ, а ВСЕ вопросительные знаки страницы. Риторика
        // в заголовках («Знаешь, в чём разница?») попадает в тот же счёт, и
        // жанр со сплошными вопросами даёт 14 при цели 7.
        $out[] = "- Вопросительных знаков на всей странице — **ровно {$tg['faq_count']}**, включая риторические вопросы в заголовках и в теле, а не только блок FAQ{$faqNote}. Это общий счёт: если жанр любит вопросы в подзаголовках, они съедают тот же лимит, что и вопросы FAQ-блока.";
        // Бюджет цифр в ПРОЗЕ: главный системный промах — реалайзер сыплет числа
        // сверх ФАКТУРЫ. Таблицы/стартовая фактура дают основную массу; прозе
        // оставляем малую долю от общей цели, названную конкретным числом.
        $numTotal = (float)$tg['numbers_per100'] * (int)$tg['words'] / 100.0;
        // В промо-жанрах цифры — часть подачи («вывод за 18 секунд», «до 500%»),
        // и замер показал их НЕДОБОР; там бюджет прозы шире.
        $genrePromo = (bool) preg_match('~реклам|лендинг|промо|восторж~u',
            mb_strtolower((string)($spec['donor_genre'] ?? '') . ' ' . ($spec['register']['label'] ?? '')));
        // Когда таблиц по цели НЕТ, носителем всей плотности остаётся проза — и
        // тот же «бюджет-потолок» гарантирует недобор (замер set232: 0.3–2.8 при
        // цели 2.1–6.4 на страницах без таблиц). Там нужен ПОЛ, а не потолок.
        // Сколько чисел реально унесут таблицы. Прежняя формула считала долю
        // прозы фиксированной (35%, у промо 60%) и на плотных донорах давала
        // недобор втрое: странице нужно 576 чисел, семь таблиц уносят ~84, а
        // бюджет разрешал 165. Теперь потолок прозы — это остаток от таблиц.
        $tblCount = (int) ($tg['tables'] ?? 0);
        $tblCap   = $tblCount * 12;               // ~12 чисел на таблицу
        $proseNeed = max(0.0, $numTotal - $tblCap);
        $noTables = ($tblCount === 0) || ($proseNeed > 0.5 * $numTotal);
        if ($noTables) {
            // Вилка должна ОБНИМАТЬ цель, а не начинаться от неё: прежние
            // 0.9…1.35 давали перебор (12.5 на 100 слов при цели 8.4), потому
            // что реалайзер целился в верх диапазона.
            $proseFloor = max(3, (int) round(($proseNeed > 0 ? $proseNeed : $numTotal) * 0.85));
            $out[] = $tblCount === 0
                ? "- Плотность цифр: **~{$tg['numbers_per100']} чисел на 100 слов** по ВСЕЙ странице. Таблиц на этой странице нет, значит ВСЮ эту плотность несёт проза."
                : "- Плотность цифр: **~{$tg['numbers_per100']} чисел на 100 слов** по ВСЕЙ странице — это ОЧЕНЬ плотно. Таблиц {$tblCount}, они унесут около {$tblCap} чисел, остальное обязана нести проза.";
            // Пол без потолка даёт перебор: замер связки показал 8.1 на 100 слов
            // при цели 5.4. Называем вилку, а не одну границу.
            $proseCeil = (int) round($proseFloor * 1.25);
            $out[] = "- **ЦИФРЫ В ПРОЗЕ — ВИЛКА: от ~{$proseFloor} до ~{$proseCeil} чисел цифрами по тексту.** Ниже нижней границы страница выйдет вдвое суше референса, выше верхней — превратится в сводку. Суммы, проценты, сроки, лимиты, количества пиши ЦИФРАМИ («от 500 ₽», «до 200%», «за 15 минут»). Не выдумывай данных сверх блока ФАКТУРА: бери числа оттуда и повторяй их в разных разрезах.";
        } else {
            $proseCap = max(3, (int) round($numTotal * ($genrePromo ? 0.6 : 0.35)));
            $out[] = "- Плотность цифр: **~{$tg['numbers_per100']} чисел на 100 слов** по ВСЕЙ странице. Основную массу дают ТАБЛИЦЫ и стартовая ФАКТУРА — в прозе числа держи по МИНИМУМУ.";
            $out[] = "- **БЮДЖЕТ ЦИФР В ПРОЗЕ: не более ~{$proseCap} чисел цифрами во всём тексте вне таблиц.** Всё остальное — проценты, суммы, сроки, количества — пиши СЛОВАМИ («около трети», «за пару минут», «более полусотни»). Числа в таблицах и в стартовой фактуре в бюджет не входят и не режутся. Это ограничение ТОЛЬКО на цифры: тематические ключи кластеров (бонус, вывод, зеркало, слот…) — словами, их не трогай.";
        }
        // Категории сущностей называем ПОИМЁННО, когда донор их дал. «Не более
        // трёх» реалайзер выполнял буквально и брал лицензию, провайдеров и RTP
        // — а у референса горели крипта, поддержка и лимиты: число совпало,
        // состав не пересёкся ни одним именем.
        $ALL_CATS = ['Лицензия', 'Провайдеры', 'Платежи', 'Крипта', 'KYC/AML', '2FA', 'RTP',
                     'Вейджер', 'Фриспины', 'Джекпот', 'Поддержка 24/7', 'Security-стек', 'Лимиты/сроки'];
        if (!empty($spec['entity_list'])) {
            $allow  = $spec['entity_list'];
            $forbid = array_values(array_diff($ALL_CATS, $allow));
            $out[] = "- Сущности — считаются КАТЕГОРИИ, а не отдельные имена. РАЗРЕШЕНЫ РОВНО ЭТИ: **" . implode(', ', $allow) . "**. Всё остальное НЕ УПОМИНАЙ ВООБЩЕ, ни словом, ни намёком: " . implode(', ', $forbid) . ". Категория засчитывается от одного упоминания, поэтому фраза «лицензия Кюрасао» или «RTP 96%» сразу добавляет категорию — если её нет в разрешённом списке, пиши без неё. Где нужен общий смысл — обобщай («площадка», «слот», «способ оплаты»).";
        } else {
            $out[] = "- Сущностей — **НЕ БОЛЕЕ ~{$tg['entities']}**. Считаются КАТЕГОРИИ (лицензия / провайдеры / платежи / крипта / RTP / джекпот / поддержка…), а не отдельные имена. НЕ вводи категорию, которой нет в блоке ФАКТУРА выше: если провайдеров/крипты/RTP/джекпота там нет — пиши обобщённо («слот», «провайдер», «платёжный метод»), а не конкретными брендами. На сателлитах держи набор категорий узким, как в референсе.";
        }
        // Цель по эмодзи берём из донора ПОСТРАНИЧНО. Раньше здесь стояло жёсткое
        // «на сателлитах эмодзи нет» — правило корпуса v1, — и оно затирало
        // корректную цель: у промо-доноров эмодзи есть и на сателлитах
        // (замер set232: слоты 26, бонусы 15 — мы отдавали 0).
        $emoji = ((int) $tg['emoji_body'] > 0)
            ? "эмодзи в теле ~{$tg['emoji_body']}"
            : "эмодзи в теле НЕТ (только в навигации)";
        $out[] = "- Вставки бренда: {$b['en']} (лат.) ~{$tg['brand_en']} раз, {$b['ru']} (кир.) ~{$tg['brand_ru']} раз; {$emoji}.";
        // Прилагательные: реалайзер сходится к ~12% независимо от цели (замер:
        // 11.7–13.6 при цели 8.7–10 и 7.8–9.5 при цели 14.4–16.2). Процент сам по
        // себе не операбелен — добавляем направление относительно этой середины.
        $adjT = (float) $tg['adj_pct'];
        $adjNote = $adjT >= 12.5
            ? " Это МНОГО: почти каждое ключевое существительное идёт с оценочным или уточняющим определением («щедрый бонус», «мгновенный вывод», «свежее зеркало»)."
            : ($adjT <= 10.5
                ? " Это СКУПО: существительное чаще идёт без определения, оценки давай глаголами и фактами, а не цепочками прилагательных."
                : "");
        $out[] = "- Прилагательных ~{$tg['adj_pct']}%.{$adjNote} Академ. тошнота ~{$tone['nausea_acad']}%, водность ~{$tone['water']}% (норма ниши — высокие); плотность ключа ≤ {$tone['key_density']}% (без переспама).";
        // Водность — самое системное смещение: реалайзер пишет СУШЕ референса
        // (замер по 35 страницам: −6.9 п.п.). Числа мало — нужна операциональная
        // инструкция, КАК её набрать, иначе текст выходит телеграфным.
        // Общей формулировки «не пересушивай» не хватает, когда цель высокая:
        // замер даёт стабильный недобор ~10 п.п. на донорах с водностью 32–37%.
        $wetNote = ((float) $tone['water'] >= 30.0)
            ? " У этого референса водность ВЫСОКАЯ: почти каждый факт идёт с пояснением или оговоркой, абзацы длинные, между разделами есть связующие фразы. Голый список фактов здесь не по стилю."
            : "";
        $out[] = "- ВОДНОСТЬ ~{$tone['water']}% — это ЦЕЛЬ, а не потолок: НЕ пересушивай текст.{$wetNote} Живой SEO-текст ниши содержит связки и вводные обороты («как правило», «в большинстве случаев», «при этом», «стоит учитывать», «на практике», «если коротко»), пояснения к фактам и мягкие переходы между абзацами. Не пиши телеграфным стилем из одних фактов — читатель должен видеть рассуждение, а не таблицу в прозе.";
        // Промо-жанры (рекламный, лендинг) живут ПОВТОРАМИ: рефрены, превосходные
        // степени, эмодзи — это их природа. Замер по двум прогонам: у таких доноров
        // мы недодавали тошноту (−7.8), воду (−10), эмодзи (−5.7), прилагательные.
        // Анти-спам инструкции, верные для экспертных текстов, их душат.
        $genreTxt = mb_strtolower((string)($spec['donor_genre'] ?? '') . ' ' . ($spec['register']['label'] ?? ''));
        $isPromo = (bool) preg_match('~реклам|лендинг|промо|восторж~u', $genreTxt);
        if ($isPromo) {
