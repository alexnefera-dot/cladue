/** Как в приёмке: одинокая «<» ломает разбор, её надо закрыть. */
function pkPochinit(string $h): string { return preg_replace('~<(?![a-zA-Z/!?])~', '&lt;', $h); }

/** Верхняя граница полосы приёмки — дальше неё перекрут не идёт. */
function pkPotolok(float $цель, bool $дробное): float
{
    return $цель + max(0.25 * abs($цель), $дробное ? 0.8 : 2.0);
}

