        }
    };

    $поТаблице(PK_IMPERATIV, 'imperatives',  'императив');
    $поТаблице(PK_VY,        'vy',           'вы');
    $поТаблице(PK_HONEST,    'honest',       'честно');
    $поТаблице(PK_TERMY,     'terms_total',  'термины');

    // ── прямая речь ──
    $осталось = $запас('speech');
    foreach (pkStroki($строки) as $i) {
        if ($осталось <= 0) { break; }
        $новое = pkSpeech($строки[$i]);
        if ($новое === null || $новое === $строки[$i]) { continue; }
        $строки[$i] = $новое; $сделано['речь']++; $осталось--;
    }

    // ── выделенные цифры ──
    $осталось = $запас('strong');
    foreach (pkStroki($строки) as $i) {
        if ($осталось <= 0) { break; }
        $новое = pkStrongFakt($строки[$i]);
        if ($новое === null || $новое === $строки[$i]) { continue; }
        $строки[$i] = $новое; $сделано['цифры']++; $осталось--;
    }

    // ── strong в начале блока ──
    // Метрика — доля, а не счёт: считаем, сколько блоков нужно поднять,
    // чтобы доля дошла до верха полосы, но не перескочила его.
    if (isset($поля['strong_lead_pct']) && $поля['strong_lead_pct']['держат']) {
        $потолок = pkPotolok((float) $поля['strong_lead_pct']['цель'], true);
        // Доля ведущих strong растёт только вместе с их общим числом, а у
        // него своя полоса. Без этого счётчика проход загонял promo на
        // strong 37 при цели 21 и валил страницу по перебору.
        $бюджетStrong = $запас('strong');
        $текст = pkPochinit(implode("\n", $строки));
        preg_match_all('~<(li|p|dd|td)\b[^>]*>(.*?)</\1>~is', $текст, $bm, PREG_SET_ORDER);
        $всего = 0; $ведущих = 0;
        foreach ($bm as $b) {
            $n = preg_match_all('~<strong\b~i', $b[2]);
            if (!$n) { continue; }
            $всего += $n;
            if (preg_match('~^\s*<strong\b~i', $b[2])) { $ведущих++; }
        }
        // Каждая правка прибавляет по единице и к ведущим, и ко всем.
        for ($k = 0; $k < 12; $k++) {
            $добавляем = $бюджетStrong > 0;
            $буд = $добавляем
                ? ($всего > 0 ? ($ведущих + 1) / ($всего + 1) * 100 : 100)
                : ($всего > 0 ? ($ведущих + 1) / $всего * 100 : 0);
            if ($буд > $потолок) { break; }
            if (!$добавляем) {
                $перенесли = false;
                foreach (pkStroki($строки) as $i) {
                    $новое = pkStrongPeremestit($строки[$i]);
                    if ($новое === null || $новое === $строки[$i]) { continue; }
                    $строки[$i] = $новое; $сделано['перенос']++;
                    $ведущих++; $перенесли = true;
                    break;
                }
                if (!$перенесли) { break; }
                continue;
            }
            $взяли = false;
            foreach (pkStroki($строки) as $i) {
                $новое = pkStrongLead($строки[$i]);
                if ($новое === null || $новое === $строки[$i]) { continue; }
                $строки[$i] = $новое; $сделано['strong']++; $бюджетStrong--;
                $ведущих++; $всего++; $взяли = true;
                break;
            }
            if (!$взяли) { break; }
        }
    }

    // ── ссылки: повторяем существующий ярлык, каждый не больше двух раз ──
    //
    // Каждый повтор снижает долю анкоров, встреченных ровно раз, а у неё
    // своя полоса снизу. Считаем, сколько повторов она выдержит: на promo
    // четыре повтора уводили долю с 41.7 на 29.4 и роняли страницу.
    $анкоры = pkAnkory(implode("\n", $строки));
    $добрать = 4;
    if (isset($карта['anchor_once_pct'], $поля['anchor_once_pct']) && $поля['anchor_once_pct']['держат']) {
        $цельДоли = (float) $поля['anchor_once_pct']['цель'];
        $низ = $цельДоли - max(0.25 * abs($цельДоли), 0.8);
        $разных = max(1, count($анкоры));
        $одиночных = (float) $карта['anchor_once_pct'] / 100 * $разных;
        // Повтор переводит ярлык из одиночных в повторные: числитель −1.
        $запасПовторов = (int) floor($одиночных - $низ / 100 * $разных);
        $добрать = max(0, min($добрать, $запасПовторов));
    }
    $занято = [];
    foreach (pkStroki($строки) as $i) {
        if ($добрать <= 0) { break; }
        $новое = pkSsylka($строки[$i], $анкоры, $занято);
        if ($новое === null) { continue; }
        $строки[$i] = $новое; $сделано['ссылки']++; $добрать--;
    }

    $итог = implode("\n", $строки);
    if ($итог !== $html) { file_put_contents($файл, $итог); }
    $сводка[$тип] = $сделано;
}

if (!$тихо) {
    $всего = [];
    foreach ($сводка as $тип => $с) {
        foreach ($с as $k => $v) { $всего[$k] = ($всего[$k] ?? 0) + $v; }
    }
    $части = [];
    foreach ($всего as $k => $v) { $части[] = "$k $v"; }
    echo 'перекрут: ' . implode(', ', $части) . ', страниц ' . count($сводка) . "\n";
}
