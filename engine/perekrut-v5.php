        $всего = (int) ($карта['address_total'] ?? 0);
        $надо = (int) round((float) $поля['vy_share']['цель'] / 100 * $всего);
        $есть = (int) round((float) ($карта['vy_share'] ?? 0) / 100 * $всего);
        $осталось = $надо - $есть;
        // Потолок в местоимениях, а не в доле: на странице с шестью обращениями
        // одно лишнее «вы» — это сразу семнадцать процентов, и «перебрать цель
        // на одно» выносит долю за полосу приёмки.
        $полуполоса = max(0.25 * (float) $поля['vy_share']['цель'], 0.8);
        $потолок = (int) floor(((float) $поля['vy_share']['цель'] + $полуполоса) / 100 * $всего);
        // Порядок блоков перемешан: подряд идущие «вы»-абзацы в начале и
        // «ты»-абзацы после читаются как склейка двух текстов, а у образцов
        // регистры чередуются по всей странице.
        // Очередь — блоками, а не строками. Абзац у нас разложен на несколько
        // строк, и перевод одной из них даёт ровно тот брак, ради которого всё
        // и затевалось: «Хочешь деталей? Выполняйте регистрацию». Ведущий
        // «<strong>» — идиома корпуса, за ним идёт обычная проза, поэтому такие
        // строки в блок входят наравне с остальными.
        $очередь = []; $текущий = [];
        $закрыть = function () use (&$очередь, &$текущий) {
            if ($текущий) { $очередь[] = $текущий; $текущий = []; }
        };
        foreach ($строки as $н => $строка) {
            $t = ltrim($строка);
            if ($t === '') { continue; }
            if ($t[0] === '<' && !str_starts_with($t, '<strong>')) {
                if (preg_match('~^</?(p|li|td|dd|blockquote)\b~i', $t)) { $закрыть(); }
                continue;
            }
            if (mb_strlen($t) >= 12) { $текущий[] = $н; }
        }
        $закрыть();
        if ($rng !== null) { $rng->shuffle($очередь); }
        foreach ($очередь as $блок) {
            if ($осталось <= 0) { break; }
            $новые = []; $прирост = 0;
            foreach ($блок as $i) {
                $новое = v5NaVy($строки[$i]);
                [$былоВы, $былоТы] = $мест($строки[$i]);
                [$сталоВы, $сталоТы] = $мест($новое);
                $новые[$i] = $новое;
                $прирост += min($сталоВы - $былоВы, $былоТы - $сталоТы);
            }
            if ($прирост <= 0) { continue; }
            // Блок берём целиком или не берём вовсе, поэтому цель он может
            // перебрать — но не выше потолка полосы.
            if ($есть + $прирост > $потолок) { continue; }
            foreach ($новые as $i => $новое) { $строки[$i] = $новое; }
            $сделано['вы'] += $прирост;
            $осталось -= $прирост; $есть += $прирост;
        }
        // Карта дальше по проходу берётся по ссылке: без правки табличные
        // рычаги потратили бы тот же запас второй раз.
        $карта['vy_share'] = $всего ? round($есть / $всего * 100, 1) : 0.0;
    }

    // В «вы»-наборе цель по императивам приёмка не держит — она противоречила
    // бы базовому профилю, — но рычагу она нужна: у «вы»-подгруппы императивов
    // втрое больше, и без добора набор звучит не своим регистром.
    if ($обращение === 'вы' && isset($поля['imperatives']['цель'])) {
        $поТаблицеДо(PK_IMPERATIV, (int) floor((float) $поля['imperatives']['цель']
            - (float) ($карта['imperatives'] ?? 0)), 'императив');
    } else {
        $поТаблице(PK_IMPERATIV, 'imperatives',  'императив');
    }
    $поТаблице(PK_VY,        'vy',           'вы');
    $поТаблице(PK_HONEST,    'honest',       'честно');
    $поТаблице(PK_TERMY,     'terms_total',  'термины');

    // ── прямая речь ──
    $осталось = $запас('speech');
    foreach (pkStroki($строки) as $i) {
        if ($осталось <= 0) { break; }
        $новое = pkSpeech($строки[$i]);
        if ($новое === null || $новое === $строки[$i]) { continue; }
        $строки[$i] = $новое; $сделано['речь']++; $осталось--;
    }

    // ── выделенные цифры ──
    $осталось = $запас('strong');
    foreach (pkStroki($строки) as $i) {
        if ($осталось <= 0) { break; }
        $новое = pkStrongFakt($строки[$i]);
        if ($новое === null || $новое === $строки[$i]) { continue; }
        $строки[$i] = $новое; $сделано['цифры']++; $осталось--;
    }

    // ── strong в начале блока ──
    // Метрика — доля, а не счёт: считаем, сколько блоков нужно поднять,
    // чтобы доля дошла до верха полосы, но не перескочила его.
    if (isset($поля['strong_lead_pct']) && $поля['strong_lead_pct']['держат']) {
        $потолок = pkPotolok((float) $поля['strong_lead_pct']['цель'], true);
        // Доля ведущих strong растёт только вместе с их общим числом, а у
        // него своя полоса. Без этого счётчика проход загонял promo на
        // strong 37 при цели 21 и валил страницу по перебору.
        $бюджетStrong = $запас('strong');
        $текст = pkPochinit(implode("\n", $строки));
        preg_match_all('~<(li|p|dd|td)\b[^>]*>(.*?)</\1>~is', $текст, $bm, PREG_SET_ORDER);
        $всего = 0; $ведущих = 0;
        foreach ($bm as $b) {
            $n = preg_match_all('~<strong\b~i', $b[2]);
            if (!$n) { continue; }
            $всего += $n;
            if (preg_match('~^\s*<strong\b~i', $b[2])) { $ведущих++; }
        }
        // Каждая правка прибавляет по единице и к ведущим, и ко всем.
        for ($k = 0; $k < 12; $k++) {
            $добавляем = $бюджетStrong > 0;
            $буд = $добавляем
                ? ($всего > 0 ? ($ведущих + 1) / ($всего + 1) * 100 : 100)
                : ($всего > 0 ? ($ведущих + 1) / $всего * 100 : 0);
            if ($буд > $потолок) { break; }
            if (!$добавляем) {
                $перенесли = false;
                foreach (pkStroki($строки) as $i) {
                    $новое = pkStrongPeremestit($строки[$i]);
                    if ($новое === null || $новое === $строки[$i]) { continue; }
                    $строки[$i] = $новое; $сделано['перенос']++;
                    $ведущих++; $перенесли = true;
                    break;
                }
                if (!$перенесли) { break; }
                continue;
            }
            $взяли = false;
            foreach (pkStroki($строки) as $i) {
                $новое = pkStrongLead($строки[$i]);
                if ($новое === null || $новое === $строки[$i]) { continue; }
                $строки[$i] = $новое; $сделано['strong']++; $бюджетStrong--;
                $ведущих++; $всего++; $взяли = true;
                break;
            }
            if (!$взяли) { break; }
        }
        // Доля уже выше потолка: цикл добора выше сюда даже не заходит.
        // Снимаем ведущие выделения, пока не вернёмся в полосу.
        for ($k = 0; $k < 12; $k++) {
            if ($всего === 0 || $ведущих / $всего * 100 <= $потолок) { break; }
            $сняли = false;
            // Первый способ дешевле и вернее: добавить выделение В СЕРЕДИНЕ.
            // Доля падает за счёт знаменателя, а начала блоков не трогаются.
            if ($бюджетStrong > 0) {
                foreach (pkStroki($строки) as $i) {
                    $новое = pkStrongFakt($строки[$i]);
                    if ($новое === null || $новое === $строки[$i]) { continue; }
                    if (preg_match('~^\s*<strong~', $новое)) { continue; }
                    $строки[$i] = $новое; $сделано['цифры']++; $бюджетStrong--;
                    $всего++; $сняли = true;
                    break;
                }
            }
            // Запаса нет — снимаем ведущее выделение, но только в абзаце.
            if (!$сняли) {
                foreach (array_keys($строки) as $i) {
                    if (!isset($вАбзаце[$i]) || mb_strlen(trim($строки[$i])) < 30) { continue; }
                    $новое = pkStrongUbratLead($строки[$i]);
                    if ($новое === null || $новое === $строки[$i]) { continue; }
                    $строки[$i] = $новое; $сделано['снято']++;
                    $ведущих--; $сняли = true;
                    break;
                }
            }
            if (!$сняли) { break; }
        }
    }

    // ── ссылки: повторяем существующий ярлык, каждый не больше двух раз ──
    //
    // Каждый повтор снижает долю анкоров, встреченных ровно раз, а у неё
    // своя полоса снизу. Считаем, сколько повторов она выдержит: на promo
    // четыре повтора уводили долю с 41.7 на 29.4 и роняли страницу.
    $анкоры = pkAnkory(implode("\n", $строки));
    $добрать = 4;
    if (isset($карта['anchor_once_pct'], $поля['anchor_once_pct']) && $поля['anchor_once_pct']['держат']) {
        $цельДоли = (float) $поля['anchor_once_pct']['цель'];
        $низ = $цельДоли - max(0.25 * abs($цельДоли), 0.8);
        $разных = max(1, count($анкоры));
        $одиночных = (float) $карта['anchor_once_pct'] / 100 * $разных;
        // Повтор переводит ярлык из одиночных в повторные: числитель −1.
        $запасПовторов = (int) floor($одиночных - $низ / 100 * $разных);
        $добрать = max(0, min($добрать, $запасПовторов));
    }
    $занято = [];
    foreach (pkStroki($строки) as $i) {
        if ($добрать <= 0) { break; }
        $новое = pkSsylka($строки[$i], $анкоры, $занято);
        if ($новое === null) { continue; }
        $строки[$i] = $новое; $сделано['ссылки']++; $добрать--;
    }

    // ── опорные формулы: тоже по свежему замеру ──
    // Повтор ярлыка (pkSsylka) сам приносит формулы: «вывод средств» —
    // и ярлык, и опорная формула разом. Если считать запас по входному
    // замеру, два прохода складываются и уводят anchors выше полосы.
    $карта = $замер(implode("\n", $строки));
    // Опорные формулы: ключи — регулярки, поэтому отдельным проходом.
    $осталосьФормул = $запасДоЦели('anchors');
    if ($осталосьФормул > 0) {
        foreach ($строки as $i => $s) {
            if ($осталосьФормул <= 0) { break; }
            if (trim($s) === '' || ltrim($s)[0] === '<') { continue; }
            $склад = [];
            $s = $спрятать($s, $склад);
            foreach (PK_ANKORY as $re => $стало) {
                $новоеS = preg_replace($re, $стало, $s, 1, $сколько);
                if (!$сколько) { continue; }
                $строки[$i] = $вернуть($новоеS, $склад);
                $сделано['формулы']++; $осталосьФормул--;
                break;
            }
        }
    }


    // ── вопросы ставим последними ──
    // Вставка двигает и число слов, и то, какая строка попадётся другим
    // проходам: если пустить её раньше, pkStrongLead выделит сам зацеп, а
    // numbers_per100 просядет на добавленных словах. Поэтому вопросы идут
    // после всех правок, и запас считается по свежему замеру, а не по тому,
    // что было на входе.
    $карта = $замер(implode("\n", $строки));
    // ── риторический вопрос ──
    // questions_total и faq считают одно и то же — знаки вопроса в тексте,
    // поэтому берём меньший из двух запасов: перебор по любому из них
    // валит страницу так же, как недобор.
    $осталось = $безВопросов ? 0 : min($запас('questions_total'), $запас('faq'));
    // Вопрос — это ещё и слова, а от их числа зависят две доли: numbers_per100
    // разбавляется, а words упирается в свой потолок. На obzor одна вставка
    // уводила цифры с 3.8 на 3.7 при нижней границе 3.75 — страница валилась
    // не по вопросам, а по разбавлению. Поэтому у прохода есть и бюджет слов.
    $словБюджет = PHP_INT_MAX;
    if (isset($карта['numbers_per100'], $карта['words'], $поля['numbers_per100'])
        && $поля['numbers_per100']['держат']) {
        $цельДоли = (float) $поля['numbers_per100']['цель'];
        $низДоли = $цельДоли - max(0.25 * abs($цельДоли), 0.8);
        $слов = (float) $карта['words'];
        $чисел = (float) $карта['numbers_per100'] / 100 * $слов;
        if ($низДоли > 0 && $слов > 0) {
            $словБюджет = min($словБюджет, (int) floor($чисел * 100 / $низДоли - $слов));
        }
    }
    if (isset($карта['words'], $поля['words']) && $поля['words']['держат']) {
        $словБюджет = min($словБюджет,
            (int) floor(pkPotolok((float) $поля['words']['цель'], false) - (float) $карта['words']));
    }
    $словБюджет = max(0, $словБюджет);
    $слов = fn(string $что): int => count(preg_split('~\s+~u', trim($что), -1, PREG_SPLIT_NO_EMPTY));
    $откат = [];
    // Какие поля стояли в полосе до вставок: только их и защищаем.
    $вПолосе = function (array $к) use ($поля): array {
        $ок = [];
        foreach ($поля as $имя => $п) {
            if (!$п['держат'] || !isset($к[$имя]) || !is_numeric($к[$имя])) { continue; }
            $цель = (float) $п['цель'];
            $пол = $п['дробное'] ? 0.8 : 2.0;
            if (abs((float) $к[$имя] - $цель) <= max(0.25 * abs($цель), $пол)) { $ок[$имя] = 1; }
        }
        return $ок;
    };
    $былоВПолосе = $вПолосе($карта);
    $занятыеВопросы = [];
    // Вопрос, уже стоящий на странице, второй раз не ставим.
    foreach (PK_RITORIKA as [$вопрос, $ответ]) {
        if (mb_strpos($html, $вопрос) !== false) { $занятыеВопросы[$вопрос] = 1; }
    }
    foreach (PK_ZACEP[$тип] ?? [] as [$вопрос, $ключи]) {
        if (mb_strpos($html, $вопрос) !== false) { $занятыеВопросы[$вопрос] = 1; }
    }
    // Абзацы, а не пункты: у доноров в теле <p> 944 вопросительных
    // предложения против 56 во всех <li> вместе взятых.
    foreach (pkStroki($строки) as $i) {
        if ($осталось <= 0) { break; }
        if (!isset($вАбзаце[$i])) { continue; }
        $новое = pkVopros($строки[$i], $занятыеВопросы);
        if ($новое === null || $новое === $строки[$i]) { continue; }
        $цена = $слов($новое) - $слов($строки[$i]);
        if ($цена > $словБюджет) { continue; }
        $откат[] = [$i, $строки[$i], 'вопрос'];
        $строки[$i] = $новое; $сделано['вопрос']++; $осталось--; $словБюджет -= $цена;
    }
    // Историй о выигрыше на «вход» и «зеркало» почти нет — там корпус ставит
    // вопрос не после рассказа, а в начале абзаца. Добираем зацепами.
    foreach (pkStroki($строки) as $i) {
        if ($осталось <= 0) { break; }
        if (!isset($вАбзаце[$i])) { continue; }
        $новое = pkZacep($строки[$i], $тип, $занятыеВопросы);
        if ($новое === null || $новое === $строки[$i]) { continue; }
        $цена = $слов($новое) - $слов($строки[$i]);
        if ($цена > $словБюджет) { continue; }
        $откат[] = [$i, $строки[$i], 'зацеп'];
        $строки[$i] = $новое; $сделано['зацеп']++; $осталось--; $словБюджет -= $цена;
    }


    // Вставка меняет не только знаки вопроса: слова разбавляют доли, и
    // спроектировать это точно нельзя — числитель numbers_per100 считается по
    // прозе, а не по тем же словам, что метрика words. Поэтому не гадаем, а
    // проверяем по факту: пока хоть одно поле, стоявшее в полосе, из неё
    // вышло, снимаем последнюю вставку.
    while ($откат) {
        $стало = $вПолосе($замер(implode("\n", $строки)));
        $испортили = array_diff_key($былоВПолосе, $стало);
        if (!$испортили) { break; }
        [$и, $прежняя, $вид] = array_pop($откат);
        $строки[$и] = $прежняя;
        $сделано[$вид]--;
    }

    // ── чистка регистра ──
    // Рычаги, идущие после перевода, вписывают свои заготовки на «ты»: зацеп
    // вопросом даёт «Хочешь деталей? Выполняйте регистрацию» в одном абзаце.
    // Поэтому в самом конце строки, попавшие в уже переведённый блок, дожимаем
    // до «вы». Доля от этого не двигается: правятся глаголы, не местоимения.
    if ($обращение === 'вы') {
        $блок = []; $естьВы = false;
        $дожать = function () use (&$строки, &$блок, &$естьВы) {
            if ($естьВы) {
                foreach ($блок as $i) { $строки[$i] = v5NaVy($строки[$i]); }
            }
            $блок = []; $естьВы = false;
        };
        $выРе = '~\b(вы|вас|вам|вами|ваш|ваша|ваше|ваши|вашего|вашей|вашему'
              . '|вашим|вашими|ваших|вашу|вашем)\b~ui';
        foreach ($строки as $н => $строка) {
            $t = ltrim($строка);
            if ($t === '') { continue; }
            if ($t[0] === '<' && !str_starts_with($t, '<strong>')) {
                if (preg_match('~^</?(p|li|td|dd|blockquote)\b~i', $t)) { $дожать(); }
                continue;
            }
            $блок[] = $н;
            if (preg_match($выРе, strip_tags($t))) { $естьВы = true; }
        }
        $дожать();
    }

    $итог = implode("\n", $строки);
    if ($итог !== $html) { file_put_contents($файл, $итог); }
    $сводка[$тип] = $сделано;
}

if (!$тихо) {
    $всего = [];
    foreach ($сводка as $тип => $с) {
        foreach ($с as $k => $v) { $всего[$k] = ($всего[$k] ?? 0) + $v; }
    }
    $части = [];
    foreach ($всего as $k => $v) { $части[] = "$k $v"; }
    echo 'перекрут: ' . implode(', ', $части) . ', страниц ' . count($сводка) . "\n";
}
