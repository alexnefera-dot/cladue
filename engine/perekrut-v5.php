/**
 * Ссылки добираются повтором уже стоящего на странице анкора, а не новым
 * текстом. Корпус ярлыки повторяет: доля анкоров, встреченных ровно раз,
 * у него около 37–54 %. Новый ярлык эту долю поднимает и валит приёмку —
 * проверено на прогоне, где три страницы ушли за верх полосы.
 *
 * @return array<string, string> текст анкора → адрес
 */
function pkAnkory(string $html): array
{
    $out = [];
    if (!preg_match_all('~<a\s+href="([^"]+)"[^>]*>([^<]{4,40})</a>~u', $html, $m, PREG_SET_ORDER)) {
        return $out;
    }
    foreach ($m as $x) {
        $текст = trim($x[2]);
        if ($текст === '' || isset($out[$текст])) { continue; }
        $out[$текст] = $x[1];
    }
    return $out;
}

/**
 * Разбор страницы на «безопасные» куски текста: строки, где нет тегов.
 * Правки идут только по ним — так разметка не может поехать.
 *
 * @return list<int> номера строк
 */
function pkStroki(array $строки): array
{
    $out = [];
    foreach ($строки as $i => $s) {
        $t = trim($s);
        if ($t === '' || $t[0] === '<') { continue; }
        if (mb_strlen($t) < 30) { continue; }
        $out[] = $i;
    }
    return $out;
}

/**
 * Первые слова строки в <strong>. Двоеточие входит в выделение — «<strong>Расклад
 * несложный:</strong> …», а тире остаётся снаружи: оно разделитель, и склеенное
 * с текстом даёт «<strong>Почему выбирают нас—</strong>».
 */
function pkStrongLead(string $s): ?string
{
    $t = ltrim($s);
    if ($t === '' || $t[0] === '<') { return null; }
    if (!preg_match('~^([^<»]{12,60}?)\s*([:—])\s+(.+)$~u', $t, $m)) { return null; }
    if (mb_strpos($m[1], '.') !== false) { return null; }
    $отступ = substr($s, 0, strlen($s) - strlen($t));
    return $m[2] === ':'
        ? $отступ . '<strong>' . $m[1] . ':</strong> ' . $m[3]
        : $отступ . '<strong>' . $m[1] . '</strong> — ' . $m[3];
}

/**
 * Предложение в кавычки. Берём только то, что и правда звучит репликой:
 * либо от первого лица, либо сразу за глаголом речи. Иначе в кавычках
 * оказывается обычное авторское предложение, и текст читается странно.
 */
function pkSpeech(string $s): ?string
{
    $t = ltrim($s);
    if ($t === '' || $t[0] === '<' || mb_strpos($t, '«') !== false) { return null; }
    // Глагол речи ищем в хвосте зачина, а не строго в его конце: донор пишет
    // «Но вот что Леонид скажет сам: …» — между глаголом и репликой ещё есть слова.
    $речь = '~(?:сказал\w*|говорит\w*|признал\w*|вспоминает|рассказ\w*|скажет|отмечает|добавляет|объясняет)~ui';
    if (!preg_match('~^(.*?)(?<=[.!?:]\s)([А-ЯЁ][^<«»]{28,150}?[.!?])(\s|$)~u', $t, $m)) { return null; }
    $отПервогоЛица = (bool) preg_match('~\b(?:я|мне|меня|мой|моя|мои|у меня)\b~ui', $m[2]);
    // Донор вводит реплику и просто именем с двоеточием: «Георгий потом: …».
    $хвостЗачина = mb_substr($m[1], -60);
    $имяИДвоеточие = preg_match('~\p{Lu}\p{Ll}{2,}[^.!?<]{0,40}:\s*$~u', $m[1]);
    if (!$отПервогоЛица && !preg_match($речь, $хвостЗачина) && !$имяИДвоеточие) { return null; }
    if (mb_strpos($m[2], '"') !== false) { return null; }
    $отступ = substr($s, 0, strlen($s) - strlen($t));
    $ядро = rtrim($m[2]);
    $знак = mb_substr($ядро, -1);
    $ядро = mb_substr($ядро, 0, -1);
    return $отступ . $m[1] . '«' . $ядро . $знак . '»' . $m[3] . mb_substr($t, mb_strlen($m[1] . $m[2] . $m[3]));
}

/**
 * Перенос выделения в начало блока без изменения их числа: снимаем strong
 * там, где он стоит в середине, и ставим на зачин. Нужно, когда счётчик
 * strong уже на верхней границе полосы и добавлять нечего, а доля ведущих
 * всё ещё ниже цели.
 */
function pkStrongPeremestit(string $s): ?string
{
    $t = ltrim($s);
    if ($t === '' || $t[0] === '<') { return null; }
    if (!preg_match('~^([^<»]{12,60}?)\s*([:—])\s+(.+)$~su', $t, $m)) { return null; }
    if (mb_strpos($m[1], '.') !== false || str_contains($m[1], '<strong')) { return null; }
    if (!preg_match('~<strong\b[^>]*>(.*?)</strong>~su', $m[3], $sm)) { return null; }
    // Снимаем ровно одно выделение — то, что нашли, — и переносим на зачин.
    $хвост = preg_replace('~<strong\b[^>]*>' . preg_quote($sm[1], '~') . '</strong>~su', $sm[1], $m[3], 1);
    $отступ = substr($s, 0, strlen($s) - strlen($t));
    return $m[2] === ':'
        ? $отступ . '<strong>' . $m[1] . ':</strong> ' . $хвост
        : $отступ . '<strong>' . $m[1] . '</strong> — ' . $хвост;
}

/**
 * Числовой факт в <strong>. Набор 53 держит strong ×1.48 к корпусной цели —
 * в основном за счёт выделенных цифр. Оборачиваем то, что уже написано:
 * «RTP 97,2%», «15 минут», «до 500к».
 */
function pkStrongFakt(string $s): ?string
{
    $t = ltrim($s);
    if ($t === '' || $t[0] === '<') { return null; }
    $re = '~(?<!<strong>)(?<![\p{L}\d])('
        . 'RTP\s?\d{1,3}[.,]?\d?\s?%'
        . '|\d{1,3}[.,]\d\s?%'
        . '|до\s\d{1,3}\s?(?:к|тыс|млн)\b'
        . '|\d{1,3}\s?(?:минут|часов|секунд)\b'
        . ')(?![\p{L}\d])~u';
    if (!preg_match($re, $t, $m, PREG_OFFSET_CAPTURE)) { return null; }
    $поз = $m[1][1];
    // Внутри уже существующего <strong> второй раз не выделяем.
    $до = substr($t, 0, $поз);
    if (substr_count($до, '<strong') > substr_count($до, '</strong')) { return null; }
    $отступ = substr($s, 0, strlen($s) - strlen($t));
    return $отступ . $до . '<strong>' . $m[1][0] . '</strong>' . substr($t, $поз + strlen($m[1][0]));
}

/** Слово в ссылку — текст не прибавляется, счётчик ссылок растёт. */
function pkSsylka(string $s, array $анкоры, array &$занято): ?string
{
    $t = ltrim($s);
    if ($t === '' || $t[0] === '<' || str_contains($t, '<a ')) { return null; }
    foreach ($анкоры as $текст => $url) {
        if (($занято[$текст] ?? 0) >= 2) { continue; }
        $поз = mb_strpos($t, $текст);
        if ($поз === false) { continue; }
        // Внутри слова ярлык не ловим: «слоты» в «слотыабв» — не анкор.
        $до = $поз > 0 ? mb_substr($t, $поз - 1, 1) : ' ';
        $после = mb_substr($t, $поз + mb_strlen($текст), 1);
        if (preg_match('~\p{L}~u', $до) || preg_match('~\p{L}~u', $после)) { continue; }
        $занято[$текст] = ($занято[$текст] ?? 0) + 1;
        $отступ = substr($s, 0, strlen($s) - strlen($t));
        return $отступ . mb_substr($t, 0, $поз) . '<a href="' . $url . '">' . $текст . '</a>'
             . mb_substr($t, $поз + mb_strlen($текст));
    }
    return null;
}

