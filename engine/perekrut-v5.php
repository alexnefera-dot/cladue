/**
 * Ссылки добираются повтором уже стоящего на странице анкора, а не новым
 * текстом. Корпус ярлыки повторяет: доля анкоров, встреченных ровно раз,
 * у него около 37–54 %. Новый ярлык эту долю поднимает и валит приёмку —
 * проверено на прогоне, где три страницы ушли за верх полосы.
 *
 * @return array<string, string> текст анкора → адрес
 */
function pkAnkory(string $html): array
{
    $out = [];
    if (!preg_match_all('~<a\s+href="([^"]+)"[^>]*>([^<]{4,40})</a>~u', $html, $m, PREG_SET_ORDER)) {
        return $out;
    }
    foreach ($m as $x) {
        $текст = trim($x[2]);
        if ($текст === '' || isset($out[$текст])) { continue; }
        $out[$текст] = $x[1];
    }
    return $out;
}

/**
 * Разбор страницы на «безопасные» куски текста: строки, где нет тегов.
 * Правки идут только по ним — так разметка не может поехать.
 *
 * @return list<int> номера строк
 */
function pkStroki(array $строки): array
{
    $out = [];
    foreach ($строки as $i => $s) {
        $t = trim($s);
        if ($t === '' || $t[0] === '<') { continue; }
        if (mb_strlen($t) < 30) { continue; }
        $out[] = $i;
    }
    return $out;
}

/**
 * Первые слова строки в <strong>. Двоеточие входит в выделение — «<strong>Расклад
 * несложный:</strong> …», а тире остаётся снаружи: оно разделитель, и склеенное
 * с текстом даёт «<strong>Почему выбирают нас—</strong>».
 */
function pkStrongLead(string $s): ?string
{
    $t = ltrim($s);
    if ($t === '' || $t[0] === '<') { return null; }
    if (!preg_match('~^([^<»]{12,60}?)\s*([:—])\s+(.+)$~u', $t, $m)) { return null; }
    if (mb_strpos($m[1], '.') !== false) { return null; }
    $отступ = substr($s, 0, strlen($s) - strlen($t));
    return $m[2] === ':'
        ? $отступ . '<strong>' . $m[1] . ':</strong> ' . $m[3]
        : $отступ . '<strong>' . $m[1] . '</strong> — ' . $m[3];
}

/**
 * Снять выделение с начала блока и поставить его внутри.
 *
 * Обратная сторона pkStrongLead. Она нужна чаще: по шестидесяти страницам
 * последних наборов strong_lead_pct выходит за полосу десять раз, и каждый
 * раз ВВЕРХ. Прежний проход умел только поднимать долю — цикл добора сразу
 * обрывался, если она уже выше потолка, и страница оставалась с провалом.
 *
 * Число выделений не меняется: одно снимаем в начале, одно ставим на зачин
 * последнего предложения строки. Меняется только доля ведущих.
 */
function pkStrongUbratLead(string $s): ?string
{
    // В отличие от остальных рычагов, этот работает как раз со строкой,
    // которая начинается с тега: ведущее выделение — это и есть <strong>
    // в первой позиции, и pkStroki такие строки отбрасывает.
    $t = ltrim($s);
    if (!preg_match('~^<strong>([^<]{6,90})</strong>(.*)$~u', $t, $m)) { return null; }
    $хвост = $m[2];
    // Нужно предложение, куда переставить: ищем последнюю точку с пробелом.
    if (!preg_match('~^(.*[.!?])\s+([^<>]{14,90}?)(\s|$)~u', $хвост, $x)) { return null; }
    $отступ = substr($s, 0, strlen($s) - strlen($t));
    return $отступ . $m[1] . $x[1] . ' <strong>' . rtrim($x[2]) . '</strong>'
         . mb_substr($хвост, mb_strlen($x[1] . ' ' . $x[2]));
}

