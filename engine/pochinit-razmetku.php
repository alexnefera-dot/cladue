<?php

declare(strict_types=1);

/**
 * pochinit-razmetku.php — ремонт битых тегов во входных комплектах.
 *
 * Линковщик, который делал эти тексты, подставлял «<a href="/" …>» поверх
 * чужой разметки: от исходного тега оставался хвост его атрибутов, и парсер
 * читал «class="cta-block glass-card pulse-glow"» как три пустых атрибута
 * плюс «pulse-glow"=""». В таком виде страницу отвергает импорт.
 *
 * Чинится ровно то, что сломано, и без выдумывания структуры:
 *
 *   · ссылка с хвостом чужих атрибутов разворачивается — текст остаётся,
 *     обёртка «<a href="/">» уходит. Она и так вела на корень, а обёрнуты
 *     ею оказывались целые абзацы и заголовки;
 *   · пустая такая ссылка удаляется целиком: слово, которое она заменила,
 *     потеряно ещё в их генераторе, и пустой якорь только мешает;
 *   · «aria-label="=" Вход="" в="" кабинет"=""» собирается обратно в
 *     «aria-label="Вход в кабинет"».
 *
 * usage: php engine/pochinit-razmetku.php <папка> [<папка>…]
 */

$папки = array_slice($argv, 1);
if (!$папки) {
    fwrite(STDERR, "usage: php engine/pochinit-razmetku.php <папка> [<папка>…]\n"); exit(1);
}

/** Признак поломки: атрибут вида «слово"=""» — хвост съеденного значения. */
const БИТЫЙ = '~\s[\w-]+"="~';

$развёрнуто = 0; $удалено = 0; $ярлыков = 0; $теги = 0; $якоря = 0; $файлов = 0;

foreach ($папки as $папка) {
    foreach (glob(rtrim($папка, '/') . '/*.html') as $файл) {
        $s = (string) file_get_contents($файл);
        $было = $s;

        // 1. «<a href="/" играть="" бесплатно<="" a="">» — текст ссылки уехал
        //    в атрибуты вместе с закрывающим тегом. Собираем обратно.
        $s = preg_replace_callback(
            '~<a\s+href="([^"]*)"((?:\s+[^\s<>"]+<?="")+)\s*a="">~u',
            function ($m) use (&$якоря) {
                // Последнее слово приходит склеенным с «<» от закрывающего тега.
                preg_match_all('~([^\s<>"]+?)<?=""~u', $m[2], $чч);
                $якоря++;
                return '<a href="' . $m[1] . '">' . trim(implode(' ', $чч[1])) . '</a>';
            }, $s);

        // 2. «<strong <div="" class="…">» — внутрь тега попал открывающий тег
        //    соседнего блока. Обломок убираем, сам тег и класс остаются.
        $s = preg_replace_callback('~<[a-zA-Z][^>]*>~u', function ($m) use (&$теги) {
            $новый = preg_replace('~\s<[\w-]+=""~u', '', $m[0]);
            if ($новый !== $m[0]) { $теги++; }
            return $новый;
        }, $s);

        // 3. «aria-label="=" Вход="" в="" кабинет"=""» — значение разорвано по
        //    словам. Склеиваем; последнее слово идёт с лишней кавычкой.
        $s = preg_replace_callback(
            '~aria-label="=?"((?:\s+[^\s<>]+="")+)~u',
            function ($m) use (&$ярлыков) {
                preg_match_all('~([^\s<>]+?)"?=""~u', $m[1], $чч);
                $ярлыков++;
                return 'aria-label="' . trim(implode(' ', $чч[1])) . '"';
            }, $s);

        // 4. пустая ссылка с битым хвостом — убираем целиком
        $s = preg_replace_callback('~<a\b[^>]*>\s*</a>~u', function ($m) use (&$удалено) {
            if (!preg_match(БИТЫЙ, $m[0])) { return $m[0]; }
            $удалено++;
            return '';
        }, $s);

        // 5. ссылка с битым хвостом вокруг текста — разворачиваем: она вела на
        //    корень и оборачивала собой целые абзацы и заголовки
        $s = preg_replace_callback('~<a\b[^>]*>(.*?)</a>~su', function ($m) use (&$развёрнуто) {
            if (!preg_match(БИТЫЙ, $m[0])) { return $m[0]; }
            $развёрнуто++;
            return $m[1];
        }, $s);

        if ($s !== $было) { file_put_contents($файл, $s); $файлов++; }
    }
}

echo "починено файлов $файлов: собрано якорей $якоря, очищено тегов $теги, "
   . "собрано ярлыков $ярлыков, развёрнуто ссылок $развёрнуто, удалено пустых $удалено\n";
