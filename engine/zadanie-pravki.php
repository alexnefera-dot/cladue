    foreach (faktyKomplekta($imya) as $k => $v) { $l[] = '  ' . $k . str_repeat(' ', max(1, 31 - mb_strlen($k))) . $v; }
    return "## Лист фактов комплекта — числа только отсюда\n"
        . "Вычитка партий 1–7: у 11–14 комплектов из 14 стояли одни и те же «6 цифр на 5 минут»,\n"
        . "«до 30 часов», «×40 на 12 дней», «реестр на 7 устройств» — по этим числам наши сайты\n"
        . "связываются между собой. У этого комплекта свои значения, и на всех его страницах\n"
        . "они одинаковые. Число, которого нет в листе и на главной, не выдумывай — пиши без\n"
        . "него. Суммы по-прежнему {count} ₽.\n"
        . implode("\n", $l) . "\n";
}

