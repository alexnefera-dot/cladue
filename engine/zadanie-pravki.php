/** Детерминированный жребий: одно и то же имя — один и тот же выбор. */
function zhrebiy(string $seed, array $iz)
{
    return $iz[crc32($seed) % count($iz)];
}

function zhrebiyChislo(string $seed, int $ot, int $do, int $shag = 1): int
{
    $n = intdiv($do - $ot, $shag) + 1;
    return $ot + (crc32($seed) % $n) * $shag;
}

