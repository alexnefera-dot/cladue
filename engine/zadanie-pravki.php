/** Полосы повелительных и обращений: цель голоса, пул — только потолок. */
function polosyGolosa(?array $golos, string $gde, int $potolokPov, int $potolokObr): string
{
    $c = $golos['цели'][$gde === 'main' ? 'main' : 'внутренние'] ?? [];
    $imp = $c['imperatives'] ?? [4, 8, 14];
    $obrKey = ($golos['обращение'] ?? 'вы') === 'ты' ? 'ty' : 'vy';
    $obr = $c[$obrKey] ?? [1, 2, 4];
    $iLo = (int) round($imp[0]); $iHi = (int) min(round($imp[2]), $potolokPov);
    if ($iHi < $iLo + 3) { $iLo = max(2, $iHi - 4); }
    // потолок пула считан по «вы»; у голоса на «ты» держим его собственную цель
    $oLo = (int) round($obr[0]);
    $oHi = (int) max(round($obr[2]), $oLo + 2);
    if ($obrKey === 'vy') { $oHi = min($oHi, $potolokObr); $oLo = min($oLo, $oHi - 1); }
    $slovo = $obrKey === 'ty' ? '«ты/тебе/твой»' : '«вы/вам/ваш»';
    return "## Полосы голоса «" . ($golos['имя'] ?? 'справочник') . "» на этой странице\n"
        . "  повелительных {$iLo}–{$iHi} (вместе с шагами и FAQ; у «ты» — формы «открой, проверь»);\n"
        . "  обращений {$slovo} {$oLo}–{$oHi}. Прошлые партии держали общую полосу для всех голосов,\n"
        . "  и приёмка по голосу ставила провал там, где голос требует больше.\n";
}

