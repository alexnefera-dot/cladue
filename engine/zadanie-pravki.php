/** Ярлыки H2 главных у соседних комплектов: левая часть до двоеточия. */
function zanyatyeYarlyki(string $root, string $korpus, string $imya): array
{
    $out = [];
    foreach (glob("$root/$korpus/*/main.html") ?: [] as $f) {
        if (basename(dirname($f)) === $imya || str_ends_with(dirname($f), '-sobrano')) { continue; }
        if (preg_match_all('~<h2[^>]*>(.*?)</h2>~is', (string) file_get_contents($f), $m)) {
            foreach ($m[1] as $h) {
                $h = trim(strip_tags($h));
                if (preg_match('~^([^:—]{3,40})[:—]~u', $h, $mm)) { $out[] = trim($mm[1]); }
            }
        }
    }
    $out = array_count_values($out);
    arsort($out);
    return array_slice(array_keys($out), 0, 60);
}

