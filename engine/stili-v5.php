<?php
/**
 * Стили комплекта — из атрибутов в один тег <style> на страницу.
 *
 * php engine/stili-v5.php <папка>
 *
 * Вёрстка (`verstka-v5.php`) и картинки пишут оформление инлайном: так блок
 * переносится в чужой шаблон без единой внешней зависимости. Здесь тот же
 * набор правил собирается в классы и уезжает в <style> в начало страницы —
 * разметка становится вдвое легче, а вид не меняется ни на пиксель.
 *
 * Правила нумеруются по первому появлению, одинаковые склеиваются в один
 * класс. Имя с приставкой `v5s-`, чтобы не столкнуться с классами шаблона.
 * Проход идемпотентен: страницу с уже вынесенными стилями пропускаем.
 */

$папка = null;
foreach (array_slice($argv, 1) as $а) {
    if ($а !== '' && $а[0] !== '-') { $папка = rtrim($а, '/'); }
}
if ($папка === null || !is_dir($папка)) {
    fwrite(STDERR, "usage: php engine/stili-v5.php <папка>\n"); exit(1);
}

/** «display:block; width:100%;» → «display:block;width:100%» */
function стНормаль(string $правило): string
{
    $части = array_filter(array_map('trim', explode(';', $правило)), fn($x) => $x !== '');
    return implode(';', $части);
}

/** Заменяет style="…" на класс, дописывая его к уже имеющимся. */
function стВынести(string $html, array &$классы): string
{
    return preg_replace_callback('~<([a-zA-Z][a-zA-Z0-9]*)((?:[^<>"]|"[^"]*")*)>~', function ($m) use (&$классы) {
        $атрибуты = $m[2];
        if (!preg_match('~\sstyle="([^"]*)"~', $атрибуты, $ст)) { return $m[0]; }
        $правило = стНормаль($ст[1]);
        if ($правило === '') { return '<' . $m[1] . preg_replace('~\sstyle="[^"]*"~', '', $атрибуты) . '>'; }
        if (!isset($классы[$правило])) { $классы[$правило] = 'v5s-' . (count($классы) + 1); }
        $имя = $классы[$правило];
        $атрибуты = preg_replace('~\sstyle="[^"]*"~', '', $атрибуты);
        $атрибуты = preg_match('~\sclass="([^"]*)"~', $атрибуты)
            ? preg_replace('~\sclass="([^"]*)"~', ' class="$1 ' . $имя . '"', $атрибуты, 1)
            : ' class="' . $имя . '"' . $атрибуты;
        return '<' . $m[1] . $атрибуты . '>';
    }, $html);
}

$всего = 0; $страниц = 0;
foreach (glob($папка . '/*.html') as $файл) {
    $html = (string) file_get_contents($файл);
    if (stripos($html, '<style') !== false) { continue; }
    $классы = [];
    $новый = стВынести($html, $классы);
    if (!$классы) { continue; }
    $правила = '';
    foreach ($классы as $правило => $имя) { $правила .= '.' . $имя . '{' . $правило . "}\n"; }
    file_put_contents($файл, "<style>\n" . $правила . "</style>\n" . $новый);
    $страниц++; $всего += count($классы);
    printf("%-14s правил: %d\n", basename($файл), count($классы));
}
printf("страниц: %d, правил всего: %d\n", $страниц, $всего);
