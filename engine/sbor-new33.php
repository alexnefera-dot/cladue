<?php
declare(strict_types=1);

/**
 * Сбор прозы из чужого корпуса в пулы v5.
 *
 *   php engine/sbor-new33.php [папка] [--выход=…] [--отчёт]
 *
 * Замер архива NEW33 показал главное: это не наш корпус — 82 % его страниц
 * не попадают в профиль, абзацы длиннее и площе, вопросов и списков меньше.
 * Поэтому берём из него не раскладку, а только материал: предложения, пункты
 * и H3. Скелет страницы, плотность абзацев и набор разделов остаются нашими.
 *
 * Что делает сбор:
 *  · режет страницу на разделы по H2 — той же грамматикой, что `bloki-v5.php`;
 *  · прогоняет текст через `v5Trafaret`: числа и имена уходят в прорези, а их
 *    незакрытые `{NAME}`/`{AMOUNT}` попадают в наши `{ИМЯ}`/`{СУММА}` — то,
 *    что в исходнике было браком, здесь становится нормальным трафаретом;
 *  · раскладывает раздел по нашему ключу H2. Точное совпадение после трафарета
 *    закрывает две трети — фабрика у них та же. Остальное идёт по доле общих
 *    слов, а что не дотянуло до порога — отбрасывается: лучше потерять абзац,
 *    чем положить рассказ про турниры в раздел про лицензию;
 *  · отсеивает то, что профиль не примет: «вы»-обращение (у восьми типов из
 *    двенадцати цель по нему ноль), обрывы, битую разметку, чужие ссылки;
 *  · снимает дубли — и внутри самого архива, и против уже собранных пулов.
 *
 * Ссылки и бренд не трогаем: у них те же шесть адресов корпуса и тот же
 * `%brand_name_ru%`, переписывать нечего.
 *
 * Результат — `data-v5/proza-new33-v5.php`, который подхватывает `bloki-v5.php`
 * тем же порядком, что и `dop*-v5.php`: пересборка из доноров его не затирает.
 */

require_once __DIR__ . '/src/V5Blocks.php';
require_once __DIR__ . '/src/PageMetrics.php';

$отчёт = in_array('--отчёт', $argv, true);
$корень = 'samples/v5-vhod33';
$выход  = __DIR__ . '/data-v5/proza-new33-v5.php';
foreach (array_slice($argv, 1) as $a) {
    if (str_starts_with($a, '--выход=')) { $выход = substr($a, strlen('--выход=')); }
    elseif ($a[0] !== '-') { $корень = rtrim($a, '/'); }
}

$пулы = json_decode((string) file_get_contents(__DIR__ . '/data-v5/pools.json'), true);
$разделыНаши = $пулы['разделы'] ?? [];
if (!$разделыНаши) { fwrite(STDERR, "нет data-v5/pools.json\n"); exit(1); }

// ── что уже лежит в пулах: против этого снимаем дубли ────────────────
// Свой прошлый сбор не считается: `pools.json` его уже содержит, и без этой
// оговорки второй запуск отсеял бы всё до единой записи как «уже в пуле».
$ужеЕсть = [];
foreach ($разделыНаши as $т => $rs) {
    foreach ($rs as $ключ => $r) {
        foreach (['зачинФразы', 'финалФразы', 'пункты', 'h3'] as $вид) {
            foreach ($r[$вид] ?? [] as $x) {
                if (str_starts_with((string) ($x['д'] ?? ''), 'n33-')) { continue; }
                $ужеЕсть[md5(mb_strtolower($x['т']))] = 1;
            }
        }
    }
}

// ── отбор ────────────────────────────────────────────────────────────
const СБ_МИН_СЛОВ = 5;
const СБ_МАКС_СЛОВ = 45;
const СБ_ПОРОГ_РОДСТВА = 0.5;

/**
 * Наши прорези. Всё остальное в фигурных скобках — чужая подстановка, которую
 * трафарет не узнал: `{CITY}`, `{BRAND}`, `{BONUS_CODE}`. Такое предложение
 * бесполезно: заполнять его нечем, а в выдаче оно останется скобками.
 */
const СБ_ПРОРЕЗИ = ['ИМЯ', 'ИМЯЖ', 'СУММА', 'RTP', 'RTP2', 'ПРОЦ', 'ДОЛЯ',
                    'МИН', 'РУБЛИ', 'СЛОТОВ', 'ПРОВАЙДЕРОВ', 'ВЕЙДЖЕР', 'БАНК'];

/** «Вы»-обращение: у восьми типов из двенадцати цель по полю vy — ноль. */
function сбВыканье(string $t): bool
{
    $плоско = mb_strtolower(strip_tags($t), 'UTF-8');
    return (bool) preg_match('~\b(вы|вас|вам|вами|ваш|ваша|ваше|ваши|ваших|вашего|вашей|вашим|вашу|вашем)\b~u', $плоско);
}

/** Причины, по которым предложение в пул не идёт. Возвращает '' если годно. */
function сбБрак(string $t, bool $заголовок = false): string
{
    $плоско = trim(preg_replace('~\s+~u', ' ', strip_tags($t)));
    $слов = count(preg_split('~\s+~u', $плоско, -1, PREG_SPLIT_NO_EMPTY));
    if ($слов < ($заголовок ? 3 : СБ_МИН_СЛОВ)) { return 'коротко'; }
    if ($слов > ($заголовок ? 14 : СБ_МАКС_СЛОВ)) { return 'длинно'; }
    // H3 точкой не заканчивается — это заголовок, а не фраза.
    if (!$заголовок && ($плоско === '' || mb_strpos('.!?»)":', mb_substr($плоско, -1)) === false)) { return 'обрыв'; }
    if (preg_match('~\s<[\w-]+=""|aria-label="="|<[\w-]+\s*<~u', $t)) { return 'битая разметка'; }
    // Чужая прорезь, которую трафарет не знает: {CITY}, {BRAND} и подобные.
    if (preg_match_all('~\{([^}]{1,20})\}~u', $t, $пр)) {
        foreach ($пр[1] as $имя) {
            if (!in_array(explode(':', $имя)[0], СБ_ПРОРЕЗИ, true)) { return 'чужая прорезь'; }
        }
    }
    if (mb_substr_count($плоско, '«') !== mb_substr_count($плоско, '»')) { return 'кавычки'; }
    if (сбДиапазонОднойПрорези($t)) { return 'диапазон одной прорези'; }
    // Проза корпуса не называет ни игру, ни провайдера, ни человека: цель по
    // games_named, providers_named и names_uniq — ноль на всех двенадцати
    // типах. Ростер живёт в витрине, герой приходит прорезью {ИМЯ}.
    if (NicheLexicon::countGames($плоско) > 0)     { return 'названа игра'; }
    if (NicheLexicon::countProviders($плоско) > 0) { return 'назван провайдер'; }
    if (NicheLexicon::uniqNames($плоско) > 0)      { return 'имя не в прорези'; }
    // Игра не из ростера метрикой не ловится, но на странице с каталогом из
    // двенадцати игр упоминание тринадцатой читается как чужой текст.
    if (сбЧужаяИгра($плоско)) { return 'игра не из ростера'; }
    // «{ИМЯ} из Самары» и «{ИМЯ} из Екатеринбурга» в соседних разделах дают
    // одного героя сразу из двух городов: имя — прорезь и повторяется, город
    // вшит в текст. Банка городов у корпуса нет, поэтому фразу не берём.
    if (preg_match('~\bиз\s+[А-ЯЁ][а-яё]{3,}~u', $плоско)) { return 'город вшит в текст'; }
    if (preg_match_all('~<a\b~i', $t) !== preg_match_all('~</a>~i', $t)) { return 'анкор не закрыт'; }
    if (preg_match_all('~<strong\b~i', $t) !== preg_match_all('~</strong>~i', $t)) { return 'strong не закрыт'; }
    // Чужой корпус жирнит охотнее нашего: 0.38 выделения на фразу против 0.31
    // у доноров, и на странице, набранной в основном из него, strong уходит
    // вдвое выше цели. Фразы с двумя и более выделениями — три процента пула,
    // без них плотность возвращается к корпусной.
    if (!$заголовок && preg_match_all('~<strong\b~i', $t) >= 2) { return 'много strong'; }
    // Фраза со строчной буквы — обрубок предыдущего предложения: в собранном
    // абзаце она встаёт после точки и читается как сбой вёрстки.
    $перв = mb_substr($плоско, 0, 1);
    if (preg_match('~\p{L}~u', $перв) && mb_strtolower($перв, 'UTF-8') === $перв) { return 'со строчной'; }
    foreach (сбАдреса($t) as $адрес) {
        if (!in_array($адрес, ['/', '/app', '/slots', '/registracia', '/vhod', '/zerkalo'], true)) {
            return 'чужая ссылка';
        }
    }
    if (сбВыканье($t)) { return 'выканье'; }
    return '';
}

/**
 * Трафарет доноров ловит «83к» и «1.5 млн», но не «83 тысячи»: там между
 * «тыс» и «ячи» нет границы слова. У доноров таких форм единицы, в чужом
 * архиве — сотни, и каждая осела бы в пуле живой цифрой.
 */
function сбДовестиТрафарет(string $t): string
{
    return preg_replace('~(?<![\d.,])\d{1,4}(?:[.,]\d+)?\s(?:тысяч\w*|миллион\w*)~u', '{СУММА}', $t);
}

/**
 * «x{ВЕЙДЖЕР}–x{ВЕЙДЖЕР}» и «от {РУБЛИ} до {РУБЛИ}»: подстановка выдаёт в обе
 * скобки одно значение, и в тексте появляется «x40–x40».
 */
function сбДиапазонОднойПрорези(string $t): bool
{
    return (bool) preg_match('~\{([^}]{1,20})\}[^{}]{0,12}[–—-][^{}]{0,12}\{\1\}~u', $t);
}

/** Латинское название из двух-четырёх слов, которого нет в ростере корпуса. */
function сбЧужаяИгра(string $плоско): bool
{
    // Магазины приложений корпус называет прямым текстом — это не игра.
    $мимо = ['App Store', 'Google Play', 'Play Market', 'Google Pay', 'Apple Pay'];
    if (!preg_match_all("~\\b(?:[A-Z][a-z']+|of|the)(?:\\s+(?:[A-Z][a-z']+|of|the|\\d+)){1,3}\\b~u", $плоско, $m)) {
        return false;
    }
    foreach ($m[0] as $имя) {
        if (!in_array($имя, $мимо, true)) { return true; }
    }
    return false;
}

function сбАдреса(string $t): array
{
    return preg_match_all('~<a\b[^>]*href="([^"]*)"~i', $t, $m) ? $m[1] : [];
}

/** Доля общих значимых слов: их H2 против нашего ключа. */
function сбРодство(string $a, string $b): float
{
    $сл = function (string $s): array {
        $s = mb_strtolower(preg_replace('~\{[^}]+\}|%[a-z_]+%~u', ' ', $s), 'UTF-8');
        $s = preg_replace('~[^a-zа-яё0-9]+~u', ' ', $s);
        return array_values(array_unique(array_filter(
            preg_split('~\s+~u', $s, -1, PREG_SPLIT_NO_EMPTY),
            fn($w) => mb_strlen($w) >= 4)));
    };
    $A = $сл($a); $B = $сл($b);
    if (!$A || !$B) { return 0.0; }
    // Сравниваем по основам: «регистрация» и «регистрацию» — одно слово.
    $осн = fn(array $w) => array_map(fn($x) => mb_substr($x, 0, 5), $w);
    $A = array_unique($осн($A)); $B = array_unique($осн($B));
    return count(array_intersect($A, $B)) / min(count($A), count($B));
}

// ── разбор корпуса ───────────────────────────────────────────────────
$банки = [];
$собрано = [];      // тип => ключ H2 => вид => список
$счёт = ['разделов' => 0, 'без ключа' => 0, 'по родству' => 0, 'точных' => 0];
$отсев = [];
$видано = [];       // md5 => 1, дубли внутри самого архива

$комплекты = [];
foreach (glob("$корень/*", GLOB_ONLYDIR) ?: [] as $группа) {
    foreach (glob("$группа/*", GLOB_ONLYDIR) ?: [] as $d) { $комплекты[] = $d; }
}
sort($комплекты);

foreach ($комплекты as $d) {
    $донор = 'n33-' . basename($d);
    foreach (V5_TYPES as $т) {
        $f = "$d/$т.html";
        if (!is_file($f)) { continue; }
        $uzly = v5Uzly((string) file_get_contents($f));

        $ключ = null; $былH3 = false;
        foreach ($uzly as $u) {
            $вн = v5Vnutr($u['html']);
            if ($вн === '') { continue; }

            if ($u['тег'] === 'h2') {
                $шаб = v5Trafaret($вн, $банки);
                $ключ = null; $былH3 = false;
                $счёт['разделов']++;
                if (isset($разделыНаши[$т][$шаб])) {
                    $ключ = $шаб; $счёт['точных']++;
                } else {
                    $лучший = null; $лучшее = 0.0;
                    foreach (array_keys($разделыНаши[$т] ?? []) as $наш) {
                        $r = сбРодство($шаб, $наш);
                        if ($r > $лучшее) { $лучшее = $r; $лучший = $наш; }
                    }
                    if ($лучший !== null && $лучшее >= СБ_ПОРОГ_РОДСТВА) {
                        $ключ = $лучший; $счёт['по родству']++;
                    } else {
                        $счёт['без ключа']++;
                    }
                }
                continue;
            }
            if ($ключ === null) { continue; }

            $положить = function (string $вид, string $текст, int $поз = 0)
                    use (&$собрано, &$видано, &$отсев, $ужеЕсть, $т, $ключ, $донор): void {
                $текст = сбДовестиТрафарет($текст);
                $причина = сбБрак($текст, $вид === 'h3');
                if ($причина !== '') { $отсев[$причина] = ($отсев[$причина] ?? 0) + 1; return; }
                $хеш = md5(mb_strtolower($текст));
                if (isset($ужеЕсть[$хеш])) { $отсев['уже в пуле'] = ($отсев['уже в пуле'] ?? 0) + 1; return; }
                if (isset($видано[$хеш]))  { $отсев['дубль в архиве'] = ($отсев['дубль в архиве'] ?? 0) + 1; return; }
                $видано[$хеш] = 1;
                $запись = ['т' => $текст, 'д' => $донор];
                if ($вид === 'зачинФразы' || $вид === 'финалФразы') { $запись['п'] = $поз; }
                $собрано[$т][$ключ][$вид][] = $запись;
            };

            $шаб = v5Trafaret($вн, $банки);
            switch ($u['тег']) {
                case 'h3':
                    $положить('h3', $шаб);
                    $былH3 = true;
                    break;
                case 'p':
                    $вид = $былH3 ? 'финалФразы' : 'зачинФразы';
                    foreach (v5Predlozheniya($шаб) as $i => $ф) {
                        $положить($вид, $ф, $i === 0 ? 1 : 0);
                    }
                    break;
                case 'ul':
                case 'ol':
                    if (preg_match_all('~<li[^>]*>(.*?)</li>~s', $u['html'], $m)) {
                        foreach ($m[1] as $li) {
                            $положить('пункты', v5Trafaret(trim(preg_replace('~\s*\n\s*~u', ' ', $li)), $банки));
                        }
                    }
                    break;
            }
        }
    }
}

// ── выкладка ─────────────────────────────────────────────────────────
ksort($собрано);
foreach ($собрано as &$rs) { ksort($rs); }
unset($rs);

$шапка = "<?php\n"
    . "// Собрано автоматически: php engine/sbor-new33.php\n"
    . "// Проза из чужого корпуса, разложенная по нашим разделам.\n"
    . "// Правится не здесь, а в sbor-new33.php — файл пересобирается целиком.\n"
    . "declare(strict_types=1);\n\nreturn ";
file_put_contents($выход, $шапка . var_export($собрано, true) . ";\n");

$итого = 0;
$поВидам = [];
foreach ($собрано as $т => $rs) {
    foreach ($rs as $ключ => $виды) {
        foreach ($виды as $вид => $сп) { $итого += count($сп); $поВидам[$вид] = ($поВидам[$вид] ?? 0) + count($сп); }
    }
}
printf("комплектов: %d, разделов встречено: %d\n", count($комплекты), $счёт['разделов']);
printf("  ключ найден точно: %d, по родству: %d, отброшено разделов: %d\n",
    $счёт['точных'], $счёт['по родству'], $счёт['без ключа']);
printf("собрано записей: %d\n", $итого);
foreach ($поВидам as $вид => $n) { printf("  %-14s %6d\n", $вид, $n); }
echo "отсев:\n";
arsort($отсев);
foreach ($отсев as $причина => $n) { printf("  %-18s %6d\n", $причина, $n); }
printf("выход: %s (%.1f МБ)\n", $выход, filesize($выход) / 1048576);

if (!$отчёт) { exit(0); }
echo "\n══ по типам ══\n";
foreach (V5_TYPES as $т) {
    $rs = $собрано[$т] ?? [];
    $n = 0;
    foreach ($rs as $виды) { foreach ($виды as $сп) { $n += count($сп); } }
    printf("%-12s разделов %2d, записей %5d\n", $т, count($rs), $n);
}
