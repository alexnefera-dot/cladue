/** Иллюстрация страницы: сюжет справа, подпись слева на затемнении. */
function нарисовать(string $файл, string $вид, float $тон, array $строки, int $вар): void {
    global $шрифт, $шрифтТонкий;
    $W = ШИР * S; $H = ВЫС * S;
    $im = imagecreatetruecolor($W, $H);
    imagealphablending($im, true);

    $золото = hsl(44, 0.88, 0.60);
    $осн    = hsl($тон + 26, 0.70, 0.54);

    фон($im, $W, $H, hsl($тон - 6, 0.70, 0.08), hsl($тон - 26, 0.60, 0.22));
    лучи($im, (int) ($W * 0.72), (int) ($H * 0.5), (int) ($W * 0.62), hsl($тон + 14, 0.76, 0.56), 22, 119);
    свечение($im, (int) ($W * 0.72), (int) ($H * 0.86), (int) ($W * 0.40), hsl($тон + 20, 0.70, 0.44), 34, 121);

    $сетка = imagecolorallocatealpha($im, 255, 255, 255, 122);
    for ($x = 0; $x < $W; $x += 76 * S) imageline($im, $x, 0, $x, $H, $сетка);
    for ($y = 0; $y < $H; $y += 76 * S) imageline($im, 0, $y, $W, $y, $сетка);

    отражение($im, (int) ($W * 0.71), (int) ($H * 0.78), (int) ($W * 0.30), (int) ($H * 0.10), $осн);
    сюжет($im, $вид, (int) ($W * 0.71), (int) ($H * 0.50), 1.45 * S, $золото, $осн, $вар);
    звезда($im, (int) ($W * 0.60), (int) ($H * 0.26), 34 * S, светлее($золото, 0.4));
    звезда($im, (int) ($W * 0.86), (int) ($H * 0.66), 24 * S, светлее($золото, 0.5));
    искры($im, $W, $H, 20, $вар * 97 + (int) $тон);
    виньетка($im, $W, $H);

    for ($x = 0; $x < (int) ($W * 0.60); $x++) {                       // подложка под подпись
        $a = 127 - (int) (76 * pow(1 - $x / ($W * 0.60), 1.6));
        if ($a >= 127) continue;
        imageline($im, $x, (int) ($H * 0.20), $x, (int) ($H * 0.72), imagecolorallocatealpha($im, 6, 8, 18, $a));
    }
    $чёрн = imagecolorallocatealpha($im, 0, 0, 0, 72);
    imagefilledrectangle($im, 78 * S, 208 * S, 166 * S, 216 * S, цв($im, $золото));
    $кегль = 46;
    while ($кегль > 26) {
        $bb = imagettfbbox($кегль * S, 0, $шрифт, $строки[0]);
        if (($bb[2] - $bb[0]) <= 500 * S) break;
        $кегль -= 2;
    }
    imagettftext($im, $кегль * S, 0, 78 * S + 3 * S, 306 * S + 3 * S, $чёрн, $шрифт, $строки[0]);
    imagettftext($im, $кегль * S, 0, 76 * S, 304 * S, imagecolorallocate($im, 248, 250, 255), $шрифт, $строки[0]);
    imagettftext($im, 23 * S, 0, 79 * S, 361 * S, imagecolorallocatealpha($im, 0, 0, 0, 90), $шрифтТонкий, $строки[1]);
    imagettftext($im, 23 * S, 0, 78 * S, 360 * S, imagecolorallocate($im, 232, 238, 250), $шрифтТонкий, $строки[1]);

    imagesetthickness($im, 3 * S);
    imagerectangle($im, 20 * S, 20 * S, $W - 21 * S, $H - 21 * S, imagecolorallocatealpha($im, 255, 255, 255, 110));
    imagesetthickness($im, 1);

    $out = imagecreatetruecolor(ШИР, ВЫС);
    imagecopyresampled($out, $im, 0, 0, 0, 0, ШИР, ВЫС, $W, $H);
    imagewebp($out, $файл, 80);
    imagedestroy($im); imagedestroy($out);
}

