/** Одна иллюстрация. */
function нарисовать(string $файл, string $вид, float $тон, array $строки, int $вар): void {
    global $шрифт, $шрифтТонкий;
    $im = imagecreatetruecolor(ШИР, ВЫС);
    imagealphablending($im, true);

    $тёмный = hsl($тон, 0.54, 0.12 + ($вар % 2) * 0.03);
    $глубокий = hsl($тон + 18, 0.58, 0.25);
    градиент($im, $тёмный, $глубокий);

    $акцент = hsl($тон + 166, 0.70, 0.58);
    $свет   = hsl($тон + 8, 0.34, 0.74);

    // фоновая сетка
    $сетка = imagecolorallocatealpha($im, 255, 255, 255, 116);
    for ($x = 0; $x < ШИР; $x += 60) imageline($im, $x, 0, $x, ВЫС, $сетка);
    for ($y = 0; $y < ВЫС; $y += 60) imageline($im, 0, $y, ШИР, $y, $сетка);

    // диагональный блик
    $блик = imagecolorallocatealpha($im, 255, 255, 255, 112);
    imagefilledpolygon($im, [0, ВЫС, 0, ВЫС - 210, 470 + $вар * 20, 0, 250 + $вар * 20, 0], 4, $блик);

    мотив($im, $вид, $акцент, $свет, $вар);

    // текст
    $бел = imagecolorallocate($im, 245, 247, 252);
    $акц = цвет($im, $акцент, 0);
    imagefilledrectangle($im, 78, 214, 78 + 88, 214 + 8, $акц);
    $кегль = 46;
    while ($кегль > 26) {
        $bb = imagettfbbox($кегль, 0, $шрифт, $строки[0]);
        if (($bb[2] - $bb[0]) <= 590) break;
        $кегль -= 2;
    }
    imagettftext($im, $кегль, 0, 76, 306, $бел, $шрифт, $строки[0]);
    $подп = imagecolorallocatealpha($im, 235, 240, 250, 40);
    imagettftext($im, 24, 0, 78, 362, $подп, $шрифтТонкий, $строки[1]);

    // рамка
    $рамка = imagecolorallocatealpha($im, 255, 255, 255, 96);
    imagerectangle($im, 22, 22, ШИР - 23, ВЫС - 23, $рамка);

    imagewebp($im, $файл, 78);
    imagedestroy($im);
}

/** Вшивает <img> после первого </p> у выбранных H2. */
function вшить(string $файл, string $страница, array $альты): int {
    $строки = explode("\n", file_get_contents($файл));
    $h2 = [];
    foreach ($строки as $i => $л) if (preg_match('~<h2[\s>]~', $л)) $h2[] = $i;
    if (!$h2) return 0;

    $цели = count($h2) >= 3 ? [$h2[0], $h2[2]] : [$h2[0], $h2[count($h2) - 1]];
    $цели = array_values(array_unique($цели));

    $вставки = [];
    foreach ($цели as $к => $iH2) {
        for ($j = $iH2 + 1; $j < min($iH2 + 60, count($строки)); $j++) {
            if (trim($строки[$j]) === '</p>') { $вставки[$j] = $к; break; }
        }
    }
    if (!$вставки) return 0;

    $итог = []; $n = 0;
    foreach ($строки as $i => $л) {
        $итог[] = $л;
        if (isset($вставки[$i])) {
            $к = $вставки[$i];
            $имя = $страница . '_img_' . ($к + 1) . '.webp';
            $alt = htmlspecialchars($альты[$к], ENT_QUOTES, 'UTF-8');
            $итог[] = '<figure class="content-visual">';
            $итог[] = '  <img src="' . $имя . '" alt="' . $alt . '" width="1200" height="630" loading="lazy">';
            $итог[] = '</figure>';
            $n++;
        }
    }
    file_put_contents($файл, implode("\n", $итог));
    return $n;
}

