/** Скруглённая рамка-кант: снаружи кант, внутри тело. */
function кант($im, int $x1, int $y1, int $x2, int $y2, int $r, array $кант, array $тело1, array $тело2, int $t): void {
    градСкругл($im, $x1, $y1, $x2, $y2, $r, светлее($кант, 0.25), темнее($кант, 0.25));
    градСкругл($im, $x1 + $t, $y1 + $t, $x2 - $t, $y2 - $t, max(2, $r - $t), $тело1, $тело2);
}

/** Отражение под предметом — даёт ощущение поверхности. */
function отражение($im, int $cx, int $cy, int $w, int $h, array $rgb): void {
    for ($i = 0; $i < 14; $i++) {
        $t = $i / 14;
        imagefilledellipse($im, $cx, $cy + (int) ($h * $t * 0.5), (int) ($w * (1 - $t * 0.55)),
                           (int) ($h * (1 - $t * 0.7)), цв($im, $rgb, 108 + (int) (18 * $t)));
    }
}

/** Четырёхлучевой блик — им подсвечивают золото на обложках автоматов. */
function звезда($im, int $cx, int $cy, int $r, array $rgb = [255, 255, 255]): void {
    imagefilledpolygon($im, [$cx, $cy - $r, $cx + (int) ($r * 0.20), $cy - (int) ($r * 0.20),
                             $cx + $r, $cy, $cx + (int) ($r * 0.20), $cy + (int) ($r * 0.20),
                             $cx, $cy + $r, $cx - (int) ($r * 0.20), $cy + (int) ($r * 0.20),
                             $cx - $r, $cy, $cx - (int) ($r * 0.20), $cy - (int) ($r * 0.20)], 8, цв($im, $rgb, 26));
    imagefilledellipse($im, $cx, $cy, (int) ($r * 0.5), (int) ($r * 0.5), цв($im, $rgb, 10));
}

/** Искры для глубины. */
function искры($im, int $w, int $h, int $n, int $сид): void {
    mt_srand($сид);
    for ($i = 0; $i < $n; $i++) {
        $x = mt_rand(0, $w); $y = mt_rand(0, $h); $r = mt_rand(2, 8) * S;
        imagefilledellipse($im, $x, $y, $r * 2, $r * 2, цв($im, [255, 255, 255], mt_rand(74, 112)));
        if ($i % 5 === 0) {
            $l = $r * 4; $c = цв($im, [255, 255, 255], 92);
            imageline($im, $x - $l, $y, $x + $l, $y, $c); imageline($im, $x, $y - $l, $x, $y + $l, $c);
        }
    }
}

