function обложка(string $файл, int $индекс, int $сид): string {
    [$вид, [$т1, $т2], $имя] = ОБЛОЖКИ[$индекс % count(ОБЛОЖКИ)];
    $W = 640 * S; $H = 480 * S;
    $im = imagecreatetruecolor($W, $H);
    imagealphablending($im, true);
    $золото = hsl(44, 0.90, 0.60);
    $осн = hsl($т2, 0.72, 0.56);

    фон($im, $W, $H, hsl($т1, 0.72, 0.09), hsl($т2, 0.62, 0.26));
    лучи($im, (int) ($W * 0.5), (int) ($H * 0.46), (int) ($W * 0.9), hsl($т2, 0.82, 0.62), 24, 114);
    свечение($im, (int) ($W * 0.5), (int) ($H * 0.9), (int) ($W * 0.5), hsl($т2 + 16, 0.74, 0.46), 32, 120);

    $cx = (int) ($W / 2); $cy = (int) ($H * 0.48);
    $k = 1.24 * S;
    отражение($im, $cx, (int) ($H * 0.80), (int) ($W * 0.36), (int) ($H * 0.12), $осн);
    switch ($вид) {
        case 'сундук':  сундук($im, $cx, $cy - (int) (10 * $k), $k, $золото); break;
        case 'корона':  корона($im, $cx, $cy, $k, $золото); break;
        case 'тигр':    тигр($im, $cx, $cy, $k, $золото); break;
        case 'джокер':  джокер($im, $cx, $cy + (int) (10 * $k), $k, $золото, $осн); break;
        case 'лампа':   лампа($im, $cx, $cy + (int) (40 * $k), $k, $золото, светлее($осн, 0.3)); break;
        case 'семёрка': семёрка($im, $cx, $cy, $k, $золото); break;
    }

    mt_srand($сид * 31 + $индекс);
    for ($i = 0; $i < 6; $i++) {
        $x = (int) ($W * (0.10 + 0.16 * $i)) + mt_rand(-10, 10) * S;
        $y = $H - mt_rand(22, 54) * S;
        if ($i % 2) монета($im, $x, $y, mt_rand(15, 21) * S, $золото);
        else        самоцвет($im, $x, $y, mt_rand(13, 19) * S, hsl($т2 + 60 + $i * 20, 0.74, 0.58));
    }
    звезда($im, (int) ($W * 0.20), (int) ($H * 0.20), 40 * S, светлее($золото, 0.35));
    звезда($im, (int) ($W * 0.82), (int) ($H * 0.30), 30 * S, светлее($золото, 0.45));
    звезда($im, (int) ($W * 0.70), (int) ($H * 0.74), 22 * S, [255, 255, 255]);
    искры($im, $W, $H, 24, $сид + $индекс);
    for ($y = 0; $y < (int) ($H * 0.16); $y++) {
        $a = 127 - (int) (52 * pow($y / ($H * 0.16), 1.8));
        if ($a >= 127) continue;
        imageline($im, 0, $H - 1 - $y, $W, $H - 1 - $y, imagecolorallocatealpha($im, 8, 8, 16, $a));
    }
    виньетка($im, $W, $H);

    imagesetthickness($im, 7 * S);
    imagerectangle($im, 10 * S, 10 * S, $W - 11 * S, $H - 11 * S, цв($im, $золото, 30));
    imagesetthickness($im, 2 * S);
    imagerectangle($im, 22 * S, 22 * S, $W - 23 * S, $H - 23 * S, imagecolorallocatealpha($im, 255, 255, 255, 86));
    imagesetthickness($im, 1);
    foreach ([[10, 10, 1, 1], [$W / S - 11, 10, -1, 1], [10, $H / S - 11, 1, -1], [$W / S - 11, $H / S - 11, -1, -1]] as [$ux, $uy, $sx, $sy]) {
        imagefilledpolygon($im, [(int) ($ux * S), (int) ($uy * S), (int) ($ux * S) + $sx * 62 * S, (int) ($uy * S),
                                 (int) ($ux * S), (int) ($uy * S) + $sy * 62 * S], 3, цв($im, $золото, 36));
    }

    $out = imagecreatetruecolor((int) ($W / S), (int) ($H / S));
    imagecopyresampled($out, $im, 0, 0, 0, 0, (int) ($W / S), (int) ($H / S), $W, $H);
    imagewebp($out, $файл, 82);
    imagedestroy($im); imagedestroy($out);
    return $имя;
}

