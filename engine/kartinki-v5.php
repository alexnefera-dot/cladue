/** Сундук с золотом: крышка дугой, окованные полосы, замок, монеты сверху. */
function сундук($im, int $cx, int $cy, int $k, array $золото): void {
    $дерево = [104, 62, 34];
    $ш = (int) (300 * $k); $в = (int) (170 * $k);
    тень($im, $cx, $cy + $в + (int) (18 * $k), (int) ($ш * 0.62), (int) (26 * $k));
    свечение($im, $cx, $cy - (int) (30 * $k), (int) (230 * $k), $золото, 40, 121);

    // корпус
    градРект($im, $cx - $ш / 2, $cy, $cx + $ш / 2, $cy + $в, светлее($дерево, 0.18), темнее($дерево, 0.38));
    // крышка: полукруг из горизонтальных линий
    $rk = (int) (150 * $k);
    for ($y = 0; $y <= $rk; $y++) {
        $w = (int) (sqrt(max(0, $rk * $rk - $y * $y)) * ($ш / 2) / $rk);
        imageline($im, $cx - $w, $cy - $y, $cx + $w, $cy - $y,
                  цв($im, смесь(светлее($дерево, 0.30), темнее($дерево, 0.22), $y / max(1, $rk))));
    }
    // оковка
    foreach ([-0.62, 0, 0.62] as $p) {
        $x = $cx + (int) ($ш / 2 * $p);
        градРект($im, $x - (int) (14 * $k), $cy - (int) (120 * $k), $x + (int) (14 * $k), $cy + $в,
                 светлее($золото, 0.30), темнее($золото, 0.30));
    }
    градРект($im, $cx - $ш / 2, $cy - (int) (10 * $k), $cx + $ш / 2, $cy + (int) (16 * $k),
             светлее($золото, 0.34), темнее($золото, 0.26));
