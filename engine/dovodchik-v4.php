<?php
declare(strict_types=1);

/**
 * Доводчик: правит счётные величины, которые нельзя испортить.
 *
 *   php engine/dovodchik-v4.php <файл.html> <тип-страницы> [--сухой]
 *
 * Граница проведена по одному признаку: **трогает ли правка форму слова**.
 *
 * Можно (правится без участия смысла):
 *   эмодзи-маркер   — символ в начале первой ячейки строки таблицы или пункта
 *                     списка; ставится и снимается, соседние слова не меняются;
 *   ol / ul         — тег списка; пункты не трогаются;
 *   бренд           — плейсхолдер ВСТАВЛЯЕТСЯ рядом с опорным словом («касса
 *                     %brand%») и снимается оттуда же; существительное на
 *                     плейсхолдер не заменяется — это ломает падеж.
 *
 * Нельзя (возвращается писателю брифом):
 *   ключевая плотность — замена «машина» → «слот» ломает падеж и согласование;
 *   двоеточие в H3     — метрика считает и двоеточие, и тире, так что обмен
 *                        разделителя её не двигает: нужен новый заголовок;
 *   выделение <strong> — где ставить, решает смысл фразы, а не счётчик;
 *   объём и абзацы     — разнести абзац значит потерять отсылку «то же самое»;
 *   регистр и сленг    — реплика, севшая в служебную строку, читается как сбой.
 *
 * Всё это уже пробовалось пакетным проходом в августе: счётчики сошлись с
 * донорскими, а в тексте появились «второй регистрация» и «к лицензия». Правки
 * этого рода тут закрыты намеренно, а не по недосмотру.
 */

require_once __DIR__ . '/src/PageMetrics.php';

$args = array_values(array_filter(array_slice($argv, 1), fn($a) => $a[0] !== '-'));
$FILE = $args[0] ?? '';
$TIP  = $args[1] ?? 'main';
$DRY  = in_array('--сухой', $argv, true);
if ($FILE === '' || !is_file($FILE)) {
    fwrite(STDERR, "usage: php engine/dovodchik-v4.php <файл.html> <тип> [--сухой]\n");
    exit(1);
}

$prof = json_decode((string) file_get_contents(__DIR__ . '/data-v4/profil-avgust.json'), true);
$norma = $prof['разметка']['страницы'][$TIP] ?? null;
$html = (string) file_get_contents($FILE);
$bylo = $html;
$otchet = [];

/** Класс эмодзи: включает 2300–23FF (⏱, ⏳) — их нет в привычных диапазонах. */
const EMO = '[\x{1F000}-\x{1FAFF}\x{2600}-\x{27BF}\x{2B00}-\x{2BFF}\x{2300}-\x{23FF}]';
/** Маркеры общего назначения: ставим только их, тематические пишет автор. */
const MARKERY = ['🔹', '📌', '🧾', '💳', '🎰', '🎁', '📱', '🔒', '📞', '🕒', '📊', '🗂', '⏳', '🌐'];

function schet(string $h): int { return preg_match_all('~' . EMO . '~u', $h); }

// ── 1. эмодзи ───────────────────────────────────────────────────────────────
if ($norma) {
    $e = $norma['emoji'];
    $est = schet($html);
    $niz = (int) $e['низ']; $verh = (int) $e['верх'];
    if ($est < $niz) {
        // ставим маркер в первую ячейку строк таблиц, по одному на строку
        $nuzhno = (int) round(($niz + (float) $e['медиана']) / 2) - $est;
        $i = 0;
        $html = preg_replace_callback('~<tr><td>(?!\s*' . EMO . ')~u', function ($m) use (&$nuzhno, &$i) {
            if ($nuzhno <= 0) { return $m[0]; }
            $nuzhno--;
            return '<tr><td>' . MARKERY[$i++ % count(MARKERY)] . ' ';
        }, $html);
        $otchet[] = 'эмодзи ' . $est . ' → ' . schet($html) . " (норма " . $niz . "–" . $verh . ")";
    } elseif ($est > $verh) {
        $lishnih = $est - (int) $e['медиана'];
        $html = preg_replace_callback('~<td>\s*(' . EMO . ')\s*~u', function ($m) use (&$lishnih) {
            if ($lishnih <= 0) { return $m[0]; }
            $lishnih--;
            return '<td>';
        }, $html);
        $otchet[] = 'эмодзи ' . $est . ' → ' . schet($html) . " (норма " . $niz . "–" . $verh . ")";
    }
}

// ── 2. двоеточие в H3: НЕ правим, только сообщаем ───────────────────────────
// Метрика считает разделителем и двоеточие, и тире, поэтому обмен одного на
// другое её не двигает: чтобы поднять долю, заголовок надо ПЕРЕПИСАТЬ так,
// чтобы у него появилась левая часть-ключ. Это работа писателя, не скрипта.
if ($norma) {
    $h = $norma['h3_colon_pct'];
    $d = dolyaH3($html);
    if ($d < (float) $h['низ'] || $d > (float) $h['верх']) {
        $otchet[] = 'H3 с двоеточием ' . $d . ' % — писателю (норма ' . $h['низ'] . '–' . $h['верх'] . ' %)';
    }
}

function dolyaH3(string $html): float
{
    preg_match_all('~<h3[^>]*>(.*?)</h3>~is', $html, $m);
    $v = count($m[1]); if (!$v) { return 0.0; }
    $c = 0;
    foreach ($m[1] as $x) { $t = strip_tags($x); if (mb_strpos($t, ':') !== false || mb_strpos($t, '—') !== false) { $c++; } }
    return round($c / $v * 100, 1);
}

// ── 3. ol / ul ──────────────────────────────────────────────────────────────
// Список с пунктами-глаголами — порядок действий, это <ol>. Иначе <ul>.
// Трогаем долю только там, где приёмка её держит. На внутренних ordered_pct
// отпущен, и правка там — шум: страница уже принята, а доводчик гонит её на
// новый круг из-за поля, которое никто не проверяет.
$derzhat = ($prof['страницы'][$TIP]['поля']['ordered_pct']['держат'] ?? false) === true;
$cel = (float) ($prof['страницы'][$TIP]['жанр']['ol_pct'] ?? $prof['страницы'][$TIP]['поля']['ordered_pct']['цель'] ?? 25);
preg_match_all('~<(ul|ol)>(.*?)</\1>~is', $derzhat ? $html : '', $sp, PREG_SET_ORDER);
$ol = 0; $vsegoSp = count($sp);
foreach ($sp as $x) { if ($x[1] === 'ol') { $ol++; } }
if ($vsegoSp) {
    $dolya = $ol / $vsegoSp * 100;
    // Коридор тот же, что у приёмки: max(0.25·цель, 0.8). Раньше тут стояло
    // ±10 и только одна ветка — вверх. Перебор нумерованных доводчик не видел
    // вовсе и молча отдавал его писателю, хотя правка чисто механическая.
    $dopusk = max(0.25 * $cel, 0.8);
    $glagol = '~^\s*<li>\s*(?:<strong>)?[А-ЯЁ][а-яё]+(?:ть|ите|йте)\b~u';
    // Шаг конвертации равен 100/числу списков. Когда списков мало, один шаг
    // перепрыгивает коридор насквозь: 2 из 6 — это 33 %, 1 из 6 — уже 17 %,
    // а коридор 18.75–31.25. Поэтому каждая замена делается только если она
    // сокращает промах; иначе доля правится числом списков, а это письмо.
    $blizhe = fn(int $bylo, int $stalo) => abs($stalo / $vsegoSp * 100 - $cel)
                                         < abs($bylo / $vsegoSp * 100 - $cel);
    if ($dolya < $cel - $dopusk) {
        // ul → ol там, где пункты начинаются глаголом: это порядок действий
        foreach ($sp as $x) {
            if (!$blizhe($ol, $ol + 1)) { break; }
            if ($x[1] !== 'ul' || !preg_match($glagol, $x[0])) { continue; }
            $html = str_replace($x[0], '<ol>' . $x[2] . '</ol>', $html);
            $ol++;
        }
    } elseif ($dolya > $cel + $dopusk) {
        // ol → ul там, где пункты глаголом НЕ начинаются: нумерация держится
        // на оформлении, а не на порядке шагов, и снимается без потери смысла
        foreach ($sp as $x) {
            if (!$blizhe($ol, $ol - 1)) { break; }
            if ($x[1] !== 'ol' || preg_match($glagol, $x[0])) { continue; }
            $html = str_replace($x[0], '<ul>' . $x[2] . '</ul>', $html);
            $ol--;
        }
    }
    $stalo = $ol / $vsegoSp * 100;
    if (abs($stalo - $dolya) > 0.01) {
        $otchet[] = 'нумерованных ' . round($dolya) . ' % → ' . round($stalo) . " % (цель $cel %)";
    } elseif (abs($stalo - $cel) > $dopusk) {
        $otchet[] = 'нумерованных ' . round($stalo) . " % при цели $cel % — писателю: "
            . "списков $vsegoSp, одной заменой в коридор не попасть";
    }
}

// ── 4. бренд: вставка рядом с опорным словом, без замены существительного ───
//
// Целимся в медиану страницы, а не в её нижнюю границу. Приёмка комплекта
// проверяет ещё и СУММУ по семи страницам, а сумма нижних границ до нижней
// границы суммы не дотягивает: 23+2+1+1+1+1+1 = 30 при норме 39–62. Страница,
// вставшая на свой низ, проходит постранично и валит комплект.
//
// На главной цель поднимается ещё раз, если сумма медиан не достаёт до низа
// комплекта: у кириллицы медианы внутренних страниц нулевые, и весь запас
// суммы (5–13) держится главной.
$shkola = $prof['бренд']['латиничная'] ?? null;
foreach ([['en', 'лат'], ['ru', 'кир']] as [$suf, $pismo]) {
    $b = $shkola['страницы'][$TIP][$pismo] ?? null;
    if (!$b) { continue; }
    $ph = '%brand_name_' . $suf . '%';
    $niz = (int) $b['низ']; $verh = (int) $b['верх']; $cel = (int) $b['медиана'];
    if ($TIP === 'main' && isset($shkola['сумма'][$pismo]['низ'])) {
        $prochie = 0;
        foreach ($shkola['страницы'] as $t => $v) {
            if ($t !== 'main') { $prochie += (int) $v[$pismo]['медиана']; }
        }
        $cel = max($cel, min($verh, (int) $shkola['сумма'][$pismo]['низ'] - $prochie));
    }
    $est = substr_count($html, $ph);
    if ($est >= $cel && $est <= $verh) { continue; }

    if ($est < $cel) {
        $nado = $cel - $est;
        // «в кассе, …» → «в кассе %brand_name_en%, …»
        //
        // Вставка разрешена ТОЛЬКО на границе оборота: после опорного слова
        // должен идти знак препинания или предлог. Иначе плейсхолдер садится
        // внутрь именной группы и ломает её: «каталог %brand% автоматов»
        // читается как «каталог Brand автоматов». Так и вышло на первом живом
        // прогоне, поэтому правило узкое, а не «после любого вхождения».
        $opora = '~\b(касс[еауы]|каталог[еауа]?|кабинет[еауа]?|площадк[еиуой]|поддержк[аеиуой]'
               . '|сайт[еауа]?|клиент[еауа]?|сборк[аеиуой]|витрин[аеыуой]|лобби)'
               . '(?=\s*[,.;:—]|\s+(?:и|в|во|на|с|со|до|после|при|через|без|для)\b)~u';
        // Вставка идёт только в прозу — в <p>. Пункт списка, ячейка таблицы и
        // заголовок служебны и коротки: имя площадки в них читается как спам.
        // На втором живом прогоне доводчик посадил два плейсхолдера в одну
        // строку списка-оглавления, поэтому правил стало три:
        //   — блок только <p>;
        //   — не больше одной вставки на блок;
        //   — блок, где имя уже стоит, не трогаем вовсе.
        $html = preg_replace_callback('~<p>(.*?)</p>~is', function ($blok) use (&$nado, $opora, $ph) {
            if ($nado <= 0) { return $blok[0]; }
            if (strpos($blok[1], '%brand_name_') !== false) { return $blok[0]; }
            if (count(preg_split('~\s+~u', trim(strip_tags($blok[1])), -1, PREG_SPLIT_NO_EMPTY)) < 20) {
                return $blok[0];
            }
            // и ни одной вставки внутри анкора: текст ссылки — не место для имени
            $chasti = preg_split('~(<a\s[^>]*>.*?</a>)~is', $blok[1], -1, PREG_SPLIT_DELIM_CAPTURE);
            $postavleno = false;
            foreach ($chasti as $i => $ch) {
                if ($postavleno || ($ch !== '' && $ch[0] === '<')) { continue; }
                $chasti[$i] = preg_replace_callback($opora, function ($m) use (&$postavleno, $ph) {
                    if ($postavleno) { return $m[0]; }
                    $postavleno = true;
                    return $m[0] . ' ' . $ph;
                }, $ch);
            }
            if (!$postavleno) { return $blok[0]; }
            $nado--;
            return '<p>' . implode('', $chasti) . '</p>';
        }, $html);
    } else {
        $lishnih = $est - $cel;
        // Снимаем только из прозы: в заголовках имя считает отдельное поле
        // brand_in_h, и вычерпывать его оттуда — значит ломать вторую норму
        // ради первой.
        $html = preg_replace_callback('~<p>(.*?)</p>~is', function ($blok) use (&$lishnih, $ph) {
            if ($lishnih <= 0) { return $blok[0]; }
            $telo = preg_replace_callback('~\s*' . preg_quote($ph, '~') . '~u', function ($m) use (&$lishnih) {
                if ($lishnih <= 0) { return $m[0]; }
                $lishnih--;
                return '';
            }, $blok[1]);
            return '<p>' . $telo . '</p>';
        }, $html);
    }

    $stalo = substr_count($html, $ph);
    $imya = $pismo === 'лат' ? 'бренд латиницей' : 'бренд кириллицей';
    // Два отчёта, а не один через elseif: доводчик может сдвинуть счётчик и всё
    // равно не дотянуть до цели. Раньше в этом случае он молчал — вставка
    // «не нашла опоры» уходила в тишину, и комплект валился на сумме бренда,
    // не сказав об этом ни строчки.
    if ($stalo !== $est) {
        $otchet[] = $imya . ' ' . $est . ' → ' . $stalo . " (цель $cel, норма " . $niz . '–' . $verh . ')';
    }
    // Цель — медиана, требование — коридор страницы. Писателю уходит только
    // выход за коридор: недобор до медианы при попадании в коридор страницу не
    // валит, а сумму по комплекту вытягивают те страницы, где вставка нашла
    // опору. Гонять принятую страницу на новый круг из-за одного плейсхолдера
    // дороже, чем этот плейсхолдер стоит.
    if ($stalo < $niz || $stalo > $verh) {
        $otchet[] = $imya . ' ' . $stalo . " при норме " . $niz . '–' . $verh . ' — писателю: '
            . 'опорных оборотов в прозе не хватило, поставь имя площадки сам';
    }
}

if (!$otchet) { echo "доводить нечего\n"; exit(0); }
if (!$DRY && $html !== $bylo) { file_put_contents($FILE, $html); }
foreach ($otchet as $o) { echo ($DRY ? 'сухо: ' : '') . $o . "\n"; }
