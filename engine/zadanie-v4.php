/** Держимые поля типа страницы: «имя — цель ± допуск». */
function polya(array $prof, string $p): string
{
    // Кириллица: printf считает байты, поэтому выравниваем сами.
    $pad = fn(string $t, int $w) => $t . str_repeat(' ', max(1, $w - mb_strlen($t)));
    $chislo = function (float $x): string {
        $s = rtrim(rtrim(number_format($x, 2, '.', ''), '0'), '.');
        return $s === '' ? '0' : $s;
    };
    $out = [];
    foreach ($prof['страницы'][$p]['поля'] as $k => $v) {
        if (!$v['держат']) { continue; }
        $pol = $v['дробное'] ? 0.8 : 2.0;
        $dop = max(0.25 * abs((float) $v['цель']), $pol);
        $imya = PageMetrics::FIELDS[$k][0] ?? $k;
        $out[] = '  ' . $pad($imya, 26) . $pad($chislo((float) $v['цель']), 8)
            . '(допуск ±' . $chislo($dop) . ')';
    }
    return implode("\n", $out);
}

/**
 * Поля, которые приёмка складывает по всему комплекту.
 *
 * Объём, профильные термины и внутренние ссылки отпущены постранично — каждое
 * поле в отдельности гуляет широко. Но приёмка складывает их по семи страницам
 * и сравнивает с суммой донорских медиан: ниже 85 % — смещение, комплект не
 * принят. Пока эти три числа не стояли в задании, писатель их не видел вовсе:
 * на живом прогоне термины вышли 46 % от донорских, потому что маска подменила
 * собой не только объяснение, но и терминологию.
 */
function summa(array $prof, string $p): string
{
    $f = $prof['страницы'][$p]['поля'];
    $slov = (int) round((float) ($f['words']['цель'] ?? 0));
    $term = (int) round((float) ($f['terms_total']['цель'] ?? 0));
    $ssyl = (int) ($prof['страницы'][$p]['жанр']['ссылок'] ?? 50);
    return "  слов                    $slov\n"
         . "  профильных терминов     $term\n"
         . "  внутренних ссылок       $ssyl\n\n"
         . "Термин — это слово ниши, а не слово маски: ставка, спин, вращение, отдача,\n"
         . "выплата, отыгрыш, вейджер, депозит, вывод, лимит, лицензия, верификация,\n"
         . "провайдер, джекпот, фриспины, множитель, барабан, линия выплат, демо-режим,\n"
         . "турнир, кэшбэк, промокод, зеркало, домен, волатильность, RTP.\n"
         . "Маска заменяет ОБЪЯСНЕНИЕ, а не терминологию. «Каталог автоматов» вместо\n"
         . "«слотов» — это подмена термина, и она уводит сумму комплекта вниз. Донор\n"
         . "пишет термин прямо и уже к нему цепляет свой предмет: «отыгрыш — это\n"
         . "противовес, который считают до подъёма».";
}

/** Разметка типа страницы: медиана, полоса и сколько доноров с нулём. */
function razmetka(array $prof, string $p): string
{
    $n = $prof['разметка']['страницы'][$p] ?? null;
    if (!$n) { return ''; }
    $s = $n['strong']; $h = $n['h3_colon_pct']; $e = $n['emoji'];
    return "  выделений <strong>      {$s['медиана']}   полоса {$s['низ']}–{$s['верх']}   без выделений: {$s['нулей']} донор(ов) из {$s['сайтов']}\n"
         . "  H3 с двоеточием         {$h['медиана']} %   полоса {$h['низ']}–{$h['верх']} %\n"
         . "  эмодзи-маркеров         {$e['медиана']}   полоса {$e['низ']}–{$e['верх']}";
}

/** Бренд: школа комплекта и норма страницы. */
function brend(array $prof, string $p): string
{
    $b = $prof['бренд']['латиничная']['страницы'][$p] ?? null;
    if (!$b) { return ''; }
    $l = $b['лат']; $k = $b['кир'];
    $s = "  %brand_name_en%         {$l['медиана']}   полоса {$l['низ']}–{$l['верх']}\n"
       . "  %brand_name_ru%         {$k['медиана']}   полоса {$k['низ']}–{$k['верх']}";
    if (($k['нулей'] ?? 0) > 0) { $s .= "   (кириллицей: ноль у {$k['нулей']} доноров из 36 — это норма)"; }
    return $s;
}

function translit(string $s): string
{
    $m = ['а'=>'a','б'=>'b','в'=>'v','г'=>'g','д'=>'d','е'=>'e','ё'=>'e','ж'=>'zh','з'=>'z','и'=>'i',
          'й'=>'y','к'=>'k','л'=>'l','м'=>'m','н'=>'n','о'=>'o','п'=>'p','р'=>'r','с'=>'s','т'=>'t',
          'у'=>'u','ф'=>'f','х'=>'h','ц'=>'c','ч'=>'ch','ш'=>'sh','щ'=>'sch','ы'=>'y','э'=>'e',
          'ю'=>'yu','я'=>'ya','ь'=>'','ъ'=>'',' '=>'-'];
    return strtr(mb_strtolower($s), $m);
}

