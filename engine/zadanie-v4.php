/**
 * Фактурный разворот узлов: чем два комплекта различаются ПО СОДЕРЖАНИЮ.
 *
 * Разведение каркаса решило половину задачи. Три схемы H2 дают разный порядок
 * разделов, но внутри раздела писатель всё равно излагает один и тот же набор
 * фактов: четыре графы анкеты, четыре точки на пути выплаты, три уровня банка
 * под ставку. Маска переписывает объяснение, а факты остаются те же — и
 * шинглы это ловят. На живом прогоне kuznica-1 против syrovarnya-1 дали 40 %
 * при пороге 6 %, причём совпадали именно таблицы: одинаковые колонки,
 * одинаковые строки, разные прилагательные.
 *
 * Поэтому у каждого узла есть три равноправные грани. Комплект берёт по одной
 * на узел, набор граней сдвигается по имени комплекта, и два соседа
 * рассказывают об одном узле РАЗНОЕ, а не одно и то же другими словами.
 *
 * Граней по пять, а не по три. С тремя вариантами пятый комплект неизбежно
 * повторял грань третьего — обойти пул по кругу быстрее, чем он кончается,
 * невозможно, и observatoriya-1 дала 9 % по шинглам против kuznica-1 на
 * общих гранях «расписка» и «арифметика отыгрыша». Пять вариантов при
 * резерве по наименее занятой отодвигают повтор на пятый круг.
 */
/**
 * Форма закрытия внутренней страницы.
 *
 * Разбор пятидесяти конкурентских комплектов показал единственный признак, по
 * которому наш текст отличался от рынка кратно: хвост. У конкурента хвосты
 * шести внутренних страниц одного сайта не пересекаются вовсе — 0 % по
 * пятисловным шинглам у всех двадцати пяти сайтов выборки. У нас один и тот
 * же абзац «…живут на сервере; ссылка, ссылка и ссылка ведут одну запись»
 * стоял в тридцати страницах из тридцати, занимал 6,3 % текста против 3,6–4,3 %
 * у рынка и давал основную долю пересечения между комплектами: до 4,35 % при
 * пороге 3,5 %.
 *
 * Отсюда пул форм. Форма задаёт ФИГУРУ закрытия, а не слова: чек-лист, личный
 * вывод, отсылка к соседней странице, таблица «стоит / не стоит», короткий
 * итог с числом, встречный вопрос. Каждая обязана унести три внутренние ссылки
 * и рефрен маски — это требование графа и жанра, — но уносит их по-своему.
 *
 * Внутри комплекта шесть страниц получают шесть РАЗНЫХ форм; между комплектами
 * пары «тип страницы → форма» разводятся тем же правилом, что и грани:
 * наименее занятая, при равенстве самая давняя, ничья — жребием по имени.
 */
function zakrytieBlok(array $zakrytiya, string $tip): string
{
    $z = $zakrytiya[$tip] ?? null;
    if (!$z) { return '—'; }
    $out = "Форма закрытия — **«{$z['форма']}»**.\n{$z['как']}\n\n"
        . "Закрытие идёт последним блоком ПЕРЕД FAQ и уносит на себе три внутренние\n"
        . "ссылки и рефрен маски. Форма задаёт фигуру, а не слова: два комплекта с\n"
        . "одной формой не имеют права совпасть ни одним пятисловным оборотом.\n"
        . "Общего для всех страниц абзаца-концовки быть не должно — приёмка меряет\n"
        . "пересечение хвостов шести внутренних страниц комплекта между собой.\n";
    if ($z['кто_брал']) {
        $out .= "\n  ↑ эту форму на такой же странице уже брали: "
            . implode(', ', $z['кто_брал']) . " — слова и числа обязаны быть другими\n";
    }
    return $out;
}

function zakrytie(string $imya, array &$zanyatye, bool $rezervirovat): array
{
    $formy = [
