// подстановка блоков, зависящих от типа (PHP heredoc не умеет вызовы)
$gotovo = [];
foreach (PAGES_Z as $p) {
    $txt = $p === 'main' ? $glavnaya : $stranicy[$p];
    $txt = str_replace(
        ['@@POLYA@@', '@@RAZM@@', '@@BREND@@', '@@SUMMA@@'],
        [polya($prof, $p), razmetka($prof, $p), brend($prof, $p), summa($prof, $p)],
        $txt
    );
    $f = "$OUT/prompt-$p.md";
    file_put_contents($f, $txt);
    $gotovo[$p] = $f;
}

// ── карточка комплекта: её читает генератор и приёмка ───────────────────────
file_put_contents("$OUT/karta.json", json_encode([
    'комплект' => $IMYA,
    'маска' => $karta['маска'],
    'ракурс' => $karta['ракурс'],
    'рефрен' => $karta['рефрен'],
    'словарь' => $karta['словарь'],
    'срезы' => $srezy,
    'промпты' => $gotovo,
], JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT));

