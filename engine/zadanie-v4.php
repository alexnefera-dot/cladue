/** Бренд: школа комплекта и норма страницы. */
function brend(array $prof, string $p): string
{
    $b = $prof['бренд']['латиничная']['страницы'][$p] ?? null;
    if (!$b) { return ''; }
    $l = $b['лат']; $k = $b['кир'];
    $s = "  %brand_name_en%         {$l['медиана']}   полоса {$l['низ']}–{$l['верх']}\n"
       . "  %brand_name_ru%         {$k['медиана']}   полоса {$k['низ']}–{$k['верх']}";
    if (($k['нулей'] ?? 0) > 0) { $s .= "   (кириллицей: ноль у {$k['нулей']} доноров из 36 — это норма)"; }
    // Полоса страницы и сумма по комплекту — два разных требования, и полоса
    // слабее. Семь страниц, каждая честно поставленная на свой низ, дают сумму
    // ниже нижней границы комплекта: полосы широкие, сумма — нет. Доводчик
    // тронуть такую страницу не может (она в полосе), и промах всплывает
    // только на приёмке комплекта. Поэтому цель писателю — медиана, а не низ.
    $su = $prof['бренд']['латиничная']['сумма'] ?? null;
    if ($su) {
        $s .= "\n\n  Целься в медиану, а не в низ полосы: сумма по семи страницам\n"
            . "  проверяется отдельно — %brand_name_en% {$su['лат']['низ']}–{$su['лат']['верх']}, "
            . "%brand_name_ru% {$su['кир']['низ']}–{$su['кир']['верх']}.\n"
            . "  Семь страниц по нижней границе в эту сумму не складываются.";
    }
    return $s;
}

function translit(string $s): string
