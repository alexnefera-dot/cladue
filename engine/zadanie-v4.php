## Формат ответа
Только HTML-фрагмент тела: `<p>`, `<h2>`, `<h3>`, `<ul>/<ol>/<li>`, `<table>`,
`<blockquote>`, `<strong>`, `<a href="/…">`, `<details>/<summary>`.
Без `<html>`, `<head>`, `<body>`, без markdown, без пояснений до и после.
Имя площадки — только `%brand_name_en%`, в тексте 2–4 раза, один раз в H2.
Слоганов, витрины, подвала и строки «Последнее обновление» не писать: их
кладёт сборщик. Эмодзи нет.

## Форма, общая для трёх страниц
Абзацы крупнее, чем на внутренних: у пула на служебной странице 5–12
абзацев, а не 12–18. Раздел — один абзац из двух-трёх предложений или
список, а не две-три строки по фразе; в одно предложение — не больше
трети абзацев. Анонсов вида «ниже — четыре канала и список…» нет: это вода.

Ключевое слово страницы — «данные», «поддержка», «счёт», «обращение» —
не стоит в каждом предложении: у пула тошнота 16–20 на about и contacts,
20–25 на privacy, у пробы вышло 27–33 из-за повтора одного слова. Дальше
идут сведения, информация, анкета, аккаунт, запрос, письмо — или
подлежащее опускается.

Тошнота about и contacts у пула 13–21 %, privacy 16–27 %: ключевое слово
ротируется, как сказано выше.

