  7. НАЗВАНИЯ ИГР ЗВУЧАТ. Со студией в скобках: «Book of Dead (Play'n GO)»,
     «Sweet Bonanza 1000 от Pragmatic Play». У семьи A их нет вовсе.

Чего у семьи B МЕНЬШЕ, чем у A, и это тоже требование: вежливого
