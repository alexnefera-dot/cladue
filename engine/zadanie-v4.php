/**
 * Семья и её стилевые меры.
 *
 * Корпус доноров распадается на два лагеря, и медиана между ними не описывает
 * никого: профиль, собранный по всем 38 сразу, проходит один донор из 38.
 * У семьи A автора в тексте нет вовсе, у семьи B он герой рассказа. Медиана
 * между «я = 1» и «я = 27» даёт 37 с полосой 1–57 — полоса шириной во весь
 * корпус, то есть отсутствие требования.
 *
 * Меры ниже приёмка НЕ считает: их нет в PageMetrics. Именно поэтому стиль и
 * выпадал — писатель видел только то, что мерят. Здесь они названы числом.
 */
function stil(array $prof, string $p): string
{
    $s = $prof['стиль']['страницы'][$p] ?? null;
    $semya = $prof['семья'] ?? 'все';
    if (!$s) { return '  (профиль собран без деления на семьи — стиль не задан)'; }
    $pad = fn(string $x, int $w) => $x . str_repeat(' ', max(1, $w - mb_strlen($x)));
    $imena = [
        'я_на_1000'     => '«я»-группа на 1000 слов',
        'сенсорных'     => 'сенсорных слов на страницу',
        'реплик_от_12'  => 'реплик в кавычках',
        'слов_арки'     => 'слов драматической арки',
        'мотив_на_1000' => 'самое частое слово, на 1000',
        'прошедших'     => 'глаголов прошедшего времени',
        'настоящих'     => 'глаголов настоящего времени',
    ];
    $out = ['  семья площадки                  ' . $semya];
    foreach ($imena as $k => $imya) {
        if (!isset($s[$k])) { continue; }
        $out[] = '  ' . $pad($imya, 32) . $s[$k];
    }
    $telo = implode("\n", $out);
    $poyasnenie = $semya === 'B'
        ? <<<'TXT'

СЕМЬЯ B — РАССКАЗ ОТ ПЕРВОГО ЛИЦА. Это не оттенок, а способ построения
страницы, и он противоположен семье A. Двадцать доноров из тридцати восьми
пишут так, и вот из чего это состоит.

  1. СЛУЧАЙ ВМЕСТО ТЕЗИСА. Страница открывается не определением и не
     объяснением, а происшествием с указанием времени и места: «В пятницу,
     около 00:15, я сидел на кухне, когда телефон прозвонил: „Вывод 3 000 ₽
     застрял“». Дальше идёт живой отказ и его разрешение. Тезис, если он
     нужен, вырастает из случая, а не предшествует ему.

  2. АРКА ВМЕСТО РАЗДЕЛОВ. H3 у доноров этой семьи прямо названы по
     драматургии: «Завязка», «Конфликт: „завис“ после Book of Dead»,
     «Кульминация: завис вывод», «Последний кадр: что дальше». Разделы —
     это шаги одной истории, а не пункты разбора.

  3. СЕНСОРНЫЙ СЛОЙ. Свет лампы, гул вентилятора, остывающая чашка, дрожь
     в пальцах, тишина после нажатия. У доноров этой семьи двадцать одно
     такое слово на страницу, у семьи A — три. Это связка текста: без неё
     сцена распадается на утверждения.

  4. ДИАЛОГ. Реплики в кавычках — короткие, по 3–6 слов, и это речь, а не
     цитата правил: «Ставка 10 RUB», «Победа! 250 RUB», «Сессия завершена,
     попробуйте снова». Двадцать шесть таких реплик на страницу.

  5. ПРОШЕДШЕЕ ВРЕМЯ НАРАВНЕ С НАСТОЯЩИМ. У семьи A настоящее время
     подавляет прошедшее впятеро: она описывает устройство. Здесь их
     примерно равно — рассказ идёт в прошедшем, объяснение внутри рассказа
     в настоящем.

  6. РЕКВИЗИТ, КОТОРЫЙ МОЖНО ПРОЧЕСТЬ. Доменные имена вида
     mirror-01.%brand_name_en%.com, номер лицензии «Curacao №1268», тип
