function chekList(array $prof, string $p): string
{
    $f = $prof['страницы'][$p]['поля'] ?? [];
    $st = $prof['стиль']['страницы'][$p] ?? [];
    $semya = $prof['семья'] ?? '';
    $c = function (string $k) use ($f) {
        return isset($f[$k]['цель']) ? (float) $f[$k]['цель'] : null;
    };
    $ok = function (?float $x, int $tochnost = 0): string {
        if ($x === null) { return '—'; }
        return $tochnost ? number_format($x, $tochnost, ',', ' ') : (string) (int) round($x);
    };
    $slov   = $c('words');
    $razdel = $c('sections');
    // Для главной берём число H2 из выбранной схемы каркаса, а не медиану
    // профиля: схемы поколения расходятся вдвое, и медиана даёт неверную
    // норму слов на блок. Для внутренних H2 всегда два — срез и FAQ.
    $h2 = $p === 'main' ? (karkasH2() ?: (int) $c('h2')) : 2;
    // Делим объём по H2, а не по всем разделам: H3 внутри одного H2 пишутся
    // одним заходом, и планировать их по отдельности бессмысленно.
    $naRazd = ($slov && $h2) ? (int) round($slov / max(1, $h2)) : null;

    // Сенсорика и реквизит заданы на страницу и на тысячу соответственно.
    $sens = $st['сенсорных'] ?? null;
    $teh1000 = $st['тех_на_1000'] ?? null;
    $teh = ($teh1000 && $slov) ? (int) round($teh1000 * $slov / 1000) : null;
    $replik = $st['реплик_от_12'] ?? null;
    $ya1000 = $st['я_на_1000'] ?? null;
    $lico = $c('first_person');
    $sensNaRazd = ($sens && $h2) ? round($sens / max(1, $h2), 1) : null;

    $strong = $c('strong');
    $lead = $c('strong_lead_pct');
    $vNachale = ($strong && $lead !== null) ? (int) round($strong * $lead / 100) : null;

    $l = [];
    $l[] = '## Чек-лист перед письмом';
    $l[] = '';
    $l[] = 'Шестнадцать пунктов ниже выписываются на бумагу и раскладываются по';
    $l[] = 'разделам ДО первой фразы. Это не проверка после письма: замер четырёх';
    $l[] = 'комплектов, написанных без списка, показал, что голос семьи ставится';
    $l[] = 'сам, а объём, сенсорный слой и технический реквизит не появляются';
    $l[] = 'никогда — объём вышел вдвое короче донорского, сенсорика вчетверо';
    $l[] = 'ниже, реквизит втрое. Доводка тех же полей потом стоила по три-пять';
    $l[] = 'проходов на страницу.';
    $l[] = '';
    $l[] = sprintf('   1. ОБЪЁМ           %s слов%s.', $ok($slov),
        $naRazd ? sprintf(' — это %s блоков H2 примерно по %d слов каждый', $ok($h2), $naRazd) : '');
    $l[] = '      Распишите разделы с их объёмом до письма. Проверка объёма после';
    $l[] = '      письма означает дописывание, а дописанное видно: оно всегда';
    $l[] = '      про то же самое другими словами.';
    if ($sens !== null) {
        $l[] = sprintf('   2. СЕНСОРНЫЙ СЛОЙ  %s на страницу%s.', $ok((float) $sens),
