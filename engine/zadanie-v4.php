            'каналы связи и сроки ответа по каждому',
            'состав письма, по которому обращение двигается с первого раза',
            'границы компетенции: что решается, а что нет',
            'спор после отказа: как его ведут письменно',
            'чего поддержка не решает никогда и куда идти вместо неё',
        ],
    ];
    // Выбор грани — не хеш от имени. Первая версия сдвигала один crc32 по
    // разрядам, и разряды оказались скоррелированы: syrovarnya-1 и kuznica-1
    // получили 6 общих граней из 10, то есть ровно ту беду, ради которой
    // разворот и вводился. Поэтому грань РЕЗЕРВИРУЕТСЯ, как срез: берётся
    // наименее занятая по реестру, ничьи разводятся хешем узла. Десять узлов
    // по три грани обходятся по кругу за три комплекта, и соседи расходятся
    // полностью.
    $reestr = &$zanyatye['грани'];
    if (!is_array($reestr)) { $reestr = []; }
    $shag = (int) ($zanyatye['грани_шаг'] ?? 0) + 1;

    // Ничьи по счёту разводятся ДАВНОСТЬЮ, а не хешем. С хешем steklo-1 взял
    // шесть граней из десяти вслед за kuznica-1: при трёх вариантах ничья
    // возникает почти на каждом узле, и хеш выбирал в ней ту же грань, что и
    // сосед. Давность разводит гарантированно — из двух одинаково занятых
    // берётся та, которую не брали дольше, а значит не соседний комплект.
    $out = '';
    $vybor = [];
    foreach ($grani as $uzel => $varianty) {
        // Своя же запись прошлого выпуска перебивает всё: перевыпуск задания
        // не должен менять разворот под уже написанной страницей.
        $luchshiy = null;
        foreach ($varianty as $v) {
            $z = $reestr[$uzel][$v] ?? ['кто' => []];
            if (in_array($imya, (array) ($z['кто'] ?? []), true)) { $luchshiy = $v; break; }
        }

        if ($luchshiy === null) {
            // Ярус наименее занятых, а внутри яруса — жребий по имени узла.
            //
            // Чистое «наименее занятая, при равенстве самая давняя» давало
            // одинаковый порядок на ВСЕХ десяти узлах: узлы резервируются
            // вместе, поэтому счёт и давность у них совпадают до единицы.
            // В итоге грани вращались целыми наборами — meteostanciya-1
            // повторила разворот syrovarnya-1 полностью, до последнего узла.
            // Жребий внутри яруса разводит узлы между собой, не ломая
            // главного правила: сильно занятую грань ярус просто не содержит.
            $min = null;
            foreach ($varianty as $v) {
                $raz = (int) ($reestr[$uzel][$v]['раз'] ?? 0);
                if ($min === null || $raz < $min) { $min = $raz; }
            }
            $yarus = [];
            foreach ($varianty as $v) {
                if ((int) ($reestr[$uzel][$v]['раз'] ?? 0) === $min) { $yarus[] = $v; }
            }
            usort($yarus, fn($a, $b) => ((int) ($reestr[$uzel][$a]['когда'] ?? 0))
                                      <=> ((int) ($reestr[$uzel][$b]['когда'] ?? 0)));
            $luchshiy = $yarus[crc32($imya . '·' . $uzel) % count($yarus)];
        }

        $vybor[$uzel] = $luchshiy;
        // Кто уже брал эту грань. Пять вариантов на узел и десяток комплектов
        // означают, что повтор неизбежен — арифметика. Молчаливый повтор и
        // случился: meteostanciya-1 получила девять граней из десяти вслед за
        // соседями и дала 16 % по шинглам, потому что писала те же факты теми
        // же таблицами. Само по себе совпадение грани не беда — беда, когда
        // писатель о нём не знает. Поэтому имя предшественника печатается
        // прямо в развороте вместе с требованием менять фактуру.
        $kto = array_values(array_filter(
            (array) ($reestr[$uzel][$luchshiy]['кто'] ?? []),
            fn($x) => $x !== $imya
        ));
        $out .= sprintf("  %-18s %s%s\n", $uzel, $luchshiy,
            $kto ? "\n                     ↑ грань уже брал: " . implode(', ', $kto)
                 . " — числа, таблицы и примеры обязаны быть другими" : '');
    }
    // Резерв грани не завязан на «комплект ещё не написан». У срезов такая
    // привязка верна: сухой прогон по готовому набору не должен занимать
    // чужое. С гранями вышло наоборот — задание перевыпускали ПОСЛЕ того, как
    // главная уже написана, резерв не записывался, и следующий комплект
    // получал ровно тот же разворот. Так tipografiya-1 повторила все десять
    // граней observatoriya-1. Поэтому резерв идёт всегда, но помечается
    // именем комплекта и потому идемпотентен: свою запись комплект узнаёт и
    // второй раз не считает.
    foreach ($vybor as $uzel => $v) {
        $z = $reestr[$uzel][$v] ?? ['раз' => 0, 'когда' => 0, 'кто' => []];
        $kto = (array) ($z['кто'] ?? []);
        if (in_array($imya, $kto, true)) { continue; }
        $kto[] = $imya;
        $reestr[$uzel][$v] = ['раз' => (int) $z['раз'] + 1, 'когда' => $shag, 'кто' => $kto];
    }
    $zanyatye['грани_шаг'] = $shag;
    return $out;
}

