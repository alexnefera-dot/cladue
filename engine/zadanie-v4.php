/** Держимые поля типа страницы: «имя — цель ± допуск». */
function polya(array $prof, string $p): string
{
    // Кириллица: printf считает байты, поэтому выравниваем сами.
    $pad = fn(string $t, int $w) => $t . str_repeat(' ', max(1, $w - mb_strlen($t)));
    $chislo = function (float $x): string {
        $s = rtrim(rtrim(number_format($x, 2, '.', ''), '0'), '.');
        return $s === '' ? '0' : $s;
    };
    $out = [];
    foreach ($prof['страницы'][$p]['поля'] as $k => $v) {
        if (!$v['держат']) { continue; }
        $pol = $v['дробное'] ? 0.8 : 2.0;
        $dop = max(0.25 * abs((float) $v['цель']), $pol);
        $imya = PageMetrics::FIELDS[$k][0] ?? $k;
        $out[] = '  ' . $pad($imya, 26) . $pad($chislo((float) $v['цель']), 8)
            . '(допуск ±' . $chislo($dop) . ')';
    }
    return implode("\n", $out);
}

