        'прошедших'     => 'глаголов прошедшего времени',
        'настоящих'     => 'глаголов настоящего времени',
    ];
    $out = ['  семья площадки                  ' . $semya];
    foreach ($imena as $k => $imya) {
        if (!isset($s[$k])) { continue; }
        $out[] = '  ' . $pad($imya, 32) . $s[$k];
