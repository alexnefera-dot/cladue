 * семьи воспроизводится сам, а три вещи не появляются никогда — объём вышел
 * 44–66 % донорского, сенсорный слой 0,8–2,6 на 1000 при медиане 7,4,
 * технический реквизит втрое ниже рынка. Догонять их правками дорого:
 * доводка одной страницы занимала от трёх до пяти проходов, и каждый
 * ломал соседнее поле. Разложенные заранее, те же числа стоят одного
 * абзаца подготовки.
