function polya(array $prof, string $p): string
{
    // Кириллица: printf считает байты, поэтому выравниваем сами.
    $pad = fn(string $t, int $w) => $t . str_repeat(' ', max(1, $w - mb_strlen($t)));
    $chislo = function (float $x): string {
        $s = rtrim(rtrim(number_format($x, 2, '.', ''), '0'), '.');
        return $s === '' ? '0' : $s;
    };
    $out = [];
    foreach ($prof['страницы'][$p]['поля'] as $k => $v) {
        if (!$v['держат']) { continue; }
        $pol = $v['дробное'] ? 0.8 : 2.0;
        $dop = max(0.25 * abs((float) $v['цель']), $pol);
        $imya = PageMetrics::FIELDS[$k][0] ?? $k;
        $out[] = '  ' . $pad($imya, 26) . $pad($chislo((float) $v['цель']), 8)
            . '(допуск ±' . $chislo($dop) . ')';
    }
    return implode("\n", $out);
}

/**
 * Плотность фактуры: поля, которые приёмка отпустила, а рынок держит.
 *
 * Поля со снятым порогом в задание не печатались вовсе, и писатель о них не
 * знал. На трёх из них это видно сразу: два свежих комплекта подряд легли на
 * нижний квартиль рынка по доле ячеек с фактом (11 % против 50 %) и по цифрам
 * на сто слов (0,4 и 0,8 против 3,5), а старая партия, правленная руками,
 * стоит в середине полосы. Приёмка такую страницу пропускает — она суха, но
 * не бракована; рядом с рынком она читается пересказом без опоры.
 *
 * Поэтому три поля печатаются отдельным блоком с прямой пометкой, что порога
 * у них нет: это ориентир, а не проверка.
 */
function plotnost(array $prof, string $p): string
{
    $pad = fn(string $t, int $w) => $t . str_repeat(' ', max(1, $w - mb_strlen($t)));
    $chislo = function (float $x): string {
        $s = rtrim(rtrim(number_format($x, 2, '.', ''), '0'), '.');
        return $s === '' ? '0' : $s;
    };
    $out = [];
    foreach (['table_cell_fact_pct', 'table_cell_latin_pct', 'numbers_per100'] as $k) {
        $v = $prof['страницы'][$p]['поля'][$k] ?? null;
        if (!$v) { continue; }
        $imya = PageMetrics::FIELDS[$k][0] ?? $k;
        $out[] = '  ' . $pad($imya, 26) . $pad($chislo((float) $v['цель']), 8)
            . '(полоса ' . $chislo((float) $v['полоса'][0]) . '–' . $chislo((float) $v['полоса'][1]) . ')';
    }
    return implode("\n", $out) . <<<'TXT'


Порога у этих трёх нет — приёмка их не валит. Держать их всё равно нужно:
ячейка с фактом — это ячейка, где стоит число, знак валюты, процент, № или
латиница («72 часа», «×35», «1 000 ₽», «Pragmatic Play»), а не пересказ
словами («довольно быстро», «повышенный»). У доноров таких ячеек больше
половины, и цифра на сто слов встречается несколько раз. Сухая страница —
та, где в таблице стоят оценки вместо величин, а в прозе нет ни одного
срока, порога и размера.
TXT;
}

