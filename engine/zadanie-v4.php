/**
 * Задание на комплект: семь промптов из профиля августа.
 *
 *   php engine/zadanie-v4.php --выход=tmp/zadanie-kran-1 [--маска=портовый кран]
 *                             [--комплект=kran-1] [--корпус=samples/v6]
 *                             [--профиль=engine/data-v6/profil-v6.json — умолчание]
 *
 * Промпт собирается ИЗ ЗАМЕРА, а не из головы. Всё, что приёмка потом
 * проверит, здесь названо числом: держимые поля с целями и допусками, жанровые
 * величины, каркас страницы, разметка, школа написания бренда, граф ссылок.
 *
 * Почему числа, а не «пиши в стиле донора». Опыт этой ветки: пока цель не
 * названа цифрой, писатель систематически недобирает — объём вышел 75 % от
 * донорского, ссылки 38 %, выделения ноль. Разброс у донора широкий, и это
 * читается как «можно меньше», хотя у него нет НИ ОДНОЙ страницы без
 * выделения. Поэтому в задании стоит и медиана, и полоса, и доля доноров с
 * нулём — чтобы было видно, где разброс, а где обязательный приём.
 *
 * Чего в задании нет намеренно: указаний «поставь strong в третий пункт».
 * Разметку писатель ставит по смыслу, а не по счётчику; счётчик проверяет
 * приёмка. Механически, без участия смысла, правятся только четыре вещи —
 * см. dovodchik-v4.php.
 *
 * РАЗБРОС ПО КОМПЛЕКТАМ (chekList, функция $cd). Одна цель на все комплекты
 * давала партию, где семь страниц сходились в медиану, а полоса образца
 * пустовала: каждый комплект приёмка принимала, а разделимость по партии
 * держалась высоко — «медиана сошлась, полоса нет». Недержимое поле берёт
 * теперь СВОЮ точку полосы, детерминированно по имени комплекта: kran-1 сядет
 * низко по strong, kran-2 высоко, и четыре комплекта вместе накроют полосу.
 * Держимые поля (words, tables/table_rows у внутренних, faq) не дрожат — у
 * них узкий шлюз приёмки. На главной tables и table_rows недержимы, и там
 * разброс включён: у образца от 11 до 33 строк, одной медианой его не отдать.
 *
 * ТОН СТРАНИЦЫ (chekList, $ton/$poDiag). Вода и прилагательные держатся
 * приёмкой (узкий шлюз), поэтому $cd их не трогает, и все страницы липли к
 * медиане обеих — корпус выходил однородным и по этим двум полям выдавал
 * автора чаще всех (разделимость water 78 %, adj 77 %). Образец же держит
 * богатые и сухие страницы вперемешку. Поэтому каждой странице задаётся тон
 * на диагонали «вода↓/прилагательные↑ ↔ вода↑/прилагательные↓», детерминиро-
 * ванно по семени: богатую пишут разными конкретными прилагательными (разом
 * поднимают adj и разбавляют воду), сухую — сдержанно, с водой к верху размаха.
 * Цель берётся из СНЯТОГО IQR образца (снятый_iqr, q1–q3 по контенту), а НЕ из
 * коридора приёмки: первая проба целила в полосу приёмки, а она лежит ниже воды
 * образца, и точное попадание сажало партию низким кластером (вода 78 % вместо
