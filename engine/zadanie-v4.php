/**
 * Фактическое число H2 выбранной схемы каркаса.
 *
 * Чек-лист делит объём страницы на блоки H2, и делить его на медиану профиля
 * нельзя: схем в поколении три, и у них 8, 10 и 12 H2. Первый комплект,
 * написанный по чек-листу, недобрал 800 слов ровно потому, что список
 * посчитал двенадцать блоков там, где каркас выдал восемь.
 */
function karkasH2(?int $set = null): int
{
    static $n = 0;
    if ($set !== null) { $n = $set; }
    return $n;
}

