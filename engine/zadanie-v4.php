/**
 * Мелочи инвентаря, по которым комплект узнаётся как машинный.
 *
 * Замер пятидесяти чужих комплектов дал набор расхождений, каждое из которых
 * по отдельности пустяк: у нас ноль <em>, ноль подстановок %date%, вчетверо
 * меньше списков и вдвое больше таблиц на внутренней странице. Вместе это
 * узнаваемый отпечаток, и он дешевле всего чинится прямо при письме.
 */
function inventar(array $prof, string $p): string
{
    $n = $prof['инвентарь']['страницы'][$p] ?? null;
    if (!$n) { return '—'; }
    $s = fn(array $d) => sprintf('%d (полоса %d–%d)', $d['медиана'], $d['q1'], $d['q3']);
    $dop = implode(', ', $prof['инвентарь']['schema']['дополнительно'] ?? []);
    return "  <em> или <i>            {$s($n['em_i'])}\n"
         . "  пунктов <li>            {$s($n['li'])}\n"
         . "  таблиц                  {$s($n['table'])}\n"
         . "  подстановок %date%      {$s($n['date'])}\n\n"
         . "Курсив идёт на терминах при первом появлении и на названиях игр — у нас\n"
         . "его не было ни одного на комплект против 17–29 у рынка. Списки несут то,\n"
         . "что мы привыкли класть в таблицу: перечень без сравнения — это <ul>, а не\n"
         . "таблица из двух колонок. Подстановка %date% ставится там, где у страницы\n"
         . "есть срок или дата замера, и раскрывается на выкладке.\n"
         . ($dop ? "Разметка schema сверх Question/Answer: $dop — у рынка их пять-девять\n"
                 . "типов против наших двух.\n" : '');
}

