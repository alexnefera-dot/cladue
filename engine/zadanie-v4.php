       . "  %brand_name_ru% в ТЕЛЕ   {$fRu}   (кириллицу в контенте образец почти не держит)";
    // Сумму приёмки добирают слои, а не тело. Замер: контент принятого
    // комплекта нёс 12 латинских имён на семь страниц, а собранный вышел на 48 —
    // слои (касса, витрина, подвал) дали +36. Ассемблированный бренд держится
    // ~48–50 почти независимо от тела, поэтому лишнее имя в теле идёт в тошноту,
    // а не в сумму. Цель писателю — образцовое число выше, самое малое.
    $su = $prof['бренд']['латиничная']['сумма'] ?? null;
    if ($su) {
        $s .= "\n\n  Сумма приёмки на СОБРАННОМ комплекте — %brand_name_en% "
            . "{$su['лат']['низ']}–{$su['лат']['верх']}, %brand_name_ru% "
            . "{$su['кир']['низ']}–{$su['кир']['верх']} — её добирают СЛОИ\n"
            . "  (касса, витрина, подвал несут бренд сами: +20–36 латиницей и ~+40\n"
            . "  кириллицей на комплект). В теле бренда нужно мало: каждое лишнее имя\n"
            . "  идёт в тошноту, а не в сумму. Кириллицу в тело почти не ставьте.";
    }
    return $s;
}

function translit(string $s): string
{
