 * доводка одной страницы занимала от трёх до пяти проходов, и каждый
 * ломал соседнее поле. Разложенные заранее, те же числа стоят одного
 * абзаца подготовки.
 *
 * Поэтому список печатается ПЕРЕД разделом «Каркас», а не после разметки:
 * его читают до письма, а не сверяют после.
 */
function chekList(array $prof, string $p, string $imya = ''): string
{
    $f = $prof['страницы'][$p]['поля'] ?? [];
    $st = $prof['стиль']['страницы'][$p] ?? [];
    $semya = $prof['семья'] ?? '';
    $c = function (string $k) use ($f) {
        return isset($f[$k]['цель']) ? (float) $f[$k]['цель'] : null;
    };
    // Дрожание цели по семени комплекта. Одна цель на все комплекты давала
    // партию, где семь страниц сошлись в медиану, а полоса образца пустовала:
    // приёмка каждый комплект принимала, а разделимость по партии держалась
    // высоко — «медиана сошлась, полоса нет». Недержимое поле здесь берёт
    // СВОЮ точку полосы, детерминированно по имени комплекта: kran-1 сядет
    // низко, kran-2 высоко, и четыре комплекта вместе накроют полосу образца.
    // Держимые поля (words, tables, faq) не трогаем — у них узкий шлюз.
    $cd = function (string $k) use ($f, $p, $imya) {
        if (!isset($f[$k]['цель'])) { return null; }
