    // безвыборную позицию с комплекта на комплект.
    $sdvig = $shag % count($tipy);
    $tipy = array_merge(array_slice($tipy, $sdvig), array_slice($tipy, 0, $sdvig));

    $vybor = [];
    $zanyatoVKomplekte = [];
    foreach ($tipy as $tip) {
        // Своя же запись прошлого выпуска перебивает всё: перевыпуск задания
        // не должен менять форму под уже написанной страницей.
        $luchshaya = null;
        foreach (array_keys($formy) as $f) {
            $z = $reestr[$tip][$f] ?? ['кто' => []];
            if (in_array($imya, (array) ($z['кто'] ?? []), true)) { $luchshaya = $f; break; }
        }
        if ($luchshaya === null) {
            $svobodnye = array_values(array_diff(array_keys($formy), $zanyatoVKomplekte));
            $min = null;
            foreach ($svobodnye as $f) {
                $raz = (int) ($reestr[$tip][$f]['раз'] ?? 0);
                if ($min === null || $raz < $min) { $min = $raz; }
            }
            $yarus = [];
            foreach ($svobodnye as $f) {
                if ((int) ($reestr[$tip][$f]['раз'] ?? 0) === $min) { $yarus[] = $f; }
            }
            usort($yarus, fn($a, $b) => ((int) ($reestr[$tip][$a]['когда'] ?? 0))
                                      <=> ((int) ($reestr[$tip][$b]['когда'] ?? 0)));
            $luchshaya = $yarus[crc32($imya . '·' . $tip) % count($yarus)];
        }
        $vybor[$tip] = $luchshaya;
        $zanyatoVKomplekte[] = $luchshaya;
    }

    if ($rezervirovat) {
        foreach ($vybor as $tip => $f) {
            $z = $reestr[$tip][$f] ?? ['раз' => 0, 'когда' => 0, 'кто' => []];
            $kto = (array) ($z['кто'] ?? []);
            if (in_array($imya, $kto, true)) { continue; }
            $kto[] = $imya;
            $reestr[$tip][$f] = ['раз' => (int) $z['раз'] + 1, 'когда' => $shag, 'кто' => $kto];
        }
        $zanyatye['закрытия_шаг'] = $shag;
    }

    $out = [];
    foreach ($vybor as $tip => $f) {
        $kto = array_values(array_filter(
            (array) ($reestr[$tip][$f]['кто'] ?? []),
            fn($x) => $x !== $imya
        ));
        $out[$tip] = [
            'форма' => $f,
            'как' => $formy[$f],
            'кто_брал' => $kto,
        ];
    }
    return $out;
}

