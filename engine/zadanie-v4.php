foreach (PAGES_Z as $p) {
    $txt = $p === 'main' ? $glavnaya : $stranicy[$p];
    $txt = str_replace(
        ['@@POLYA@@', '@@RAZM@@', '@@BREND@@', '@@SUMMA@@', '@@KARKAS@@', '@@FAKTURA@@'],
        [polya($prof, $p), razmetka($prof, $p), brend($prof, $p), summa($prof, $p), karkas($IMYA), faktura($IMYA, $maski['занято'], $novyy)],
        $txt
    );
    $f = "$OUT/prompt-$p.md";
    file_put_contents($f, $txt);
    $gotovo[$p] = $f;
}

// Реестр граней пополняется здесь, а не вместе со срезами выше: грань
// выбирается в момент подстановки блока, то есть после первого сохранения
// maski.json. Пишем повторно — иначе резерв живёт только в памяти процесса и
// следующий комплект берёт те же грани.
if ($novyy) {
    file_put_contents(__DIR__ . '/data-v4/maski.json',
        json_encode($maski, JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT));
}

// ── карточка комплекта: её читает генератор и приёмка ───────────────────────
file_put_contents("$OUT/karta.json", json_encode([
    'комплект' => $IMYA,
    'маска' => $karta['маска'],
    'ракурс' => $karta['ракурс'],
    'рефрен' => $karta['рефрен'],
    'словарь' => $karta['словарь'],
    'срезы' => $srezy,
    'промпты' => $gotovo,
], JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT));

printf("задание на «%s» готово: %s\n", $IMYA, $OUT);
printf("  маска: %s · ракурс: %s · рефрен: «%s»\n", $karta['маска'], $karta['ракурс'], $karta['рефрен']);
foreach ($srezy as $p => $s) { printf("  %-12s %s\n", $p, mb_substr($s, 0, 64)); }
