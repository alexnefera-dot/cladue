        $l[] = '      Словарь: свет, лампа, тускло, мигнуло, гул, шип, звон, шёпот,';
        $l[] = '      тишина, холод, тепло, запах, дрожь, пальцы, ладонь, чашка,';
        $l[] = '      сумерки, кухня, полночь, темнота. Ставится в зачин сцены и';
        $l[] = '      в место, где герой ждёт: там оно держит время.';
    }
    if ($teh !== null) {
        $l[] = sprintf('   3. РЕКВИЗИТ        %s меток на страницу (%s на 1000 слов).', $ok((float) $teh), $ok((float) $teh1000, 1));
        $l[] = sprintf('      Это примерно %d на каждый H2 — по одной читаемой детали в раздел.',
            $h2 ? max(1, (int) round($teh / $h2)) : 1);
        $l[] = '      Словарь: TLS, SHA-256, HTTPS, KYC, OTP, SMS, RTP, APK, Android,';
        $l[] = '      iOS, Chrome, Visa, Curacao, WHOIS, mirror-NN, номер версии,';
        $l[] = '      миллисекунды ответа. Не «быстрый вывод», а «0,12 с ответа».';
    }
    if ($replik !== null) {
        $l[] = sprintf('   4. РЕПЛИКИ         %s в кавычках, каждая 12–24 знака внутри кавычек.', $ok((float) $replik));
        $l[] = '      Речь и надписи на экране, не цитаты правил. Длиннее 24 знаков';
        $l[] = '      считается уже цитатой и попадает в отдельное поле.';
