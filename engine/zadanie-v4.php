вдвое меньше (28 % против 64 %). Рассказчик не инструктирует — он
рассказывает, и советы у него редки и коротки.
TXT
        : <<<'TXT'

СЕМЬЯ A — СПЕЦИФИКАЦИЯ БЕЗ АВТОРА. Страница открывается плотным
