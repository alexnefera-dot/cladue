#!/usr/bin/env python3
"""Все домены сентября одной таблицей: запуск, контент, индекс, деньги, бренды.

Берёт широкий свод по доменам и оставляет сентябрьские запуски, приводя имя
набора к корню (хвост «_NN» в реестре — номер домена, а не отдельный набор)
и добавляя производные колонки: индекс за трое суток и за всё время, клики
на вышедший сайт, отдачу с клика, место домена внутри своего набора.

    python3 domeny_sentyabr.py <свод.csv> <out.csv> <out.json>
"""
import sys, csv, re, json, collections, statistics

svod_p, out_csv, out_json = sys.argv[1:4]
root = lambda n: re.sub(r'_\d+$', '', n)
I = lambda r, k: int(r[k]) if r[k] not in ('', 'None') else 0
F = lambda r, k: float(r[k]) if r[k] not in ('', 'None') else 0.0

R = [r for r in csv.DictReader(open(svod_p, encoding='utf-8')) if r['день запуска'] >= '2026-09-01']

rows = []
for r in R:
    s = I(r, 'сайтов в окне') or I(r, 'сайтов')
    v3 = I(r, 'вышли за 3 суток')
    vall = I(r, 'сайтов с поиском')
    ya = I(r, 'кликов из поиска в окне')
    reg = I(r, 'регистраций в окне 3 суток')
    rows.append({
        'домен': r['домен'], 'зона': r['зона'], 'день запуска': r['день запуска'],
        'день недели': r['день недели'], 'час': I(r, 'час запуска'), 'блок часа': r['блок часа'],
        'набор контента': root(r['набор контента']), 'семейство': r['семейство'],
        'страниц': r['страниц'], 'оформление': r['оформление'], 'шаблон': r['шаблон'],
        'паттерн имени': r['паттерн имени'], 'длина метки': I(r, 'длина метки'),
        'аккаунт свежий': r['аккаунт свежий'], 'который раз аккаунт': I(r, 'который раз аккаунт'),
        'окно закрыто': r['окно закрыто'], 'сайтов': s,
        'вышли за 1 сутки': I(r, 'вышли за 1 сутки'), 'вышли за 3 суток': v3,
        'индекс 3 суток %': round(100 * v3 / s, 1) if (s and r['окно закрыто'] == 'да') else '',
        'вышли всего': vall, 'индекс всего %': round(100 * vall / s, 1) if s else '',
        'кликов из поиска в окне': ya, 'кликов на сайт': round(ya / s, 2) if s else 0,
        'кликов на вышедший сайт': round(ya / v3, 1) if v3 else 0,
        'ботов %': F(r, 'ботов в окне %'),
        'регистраций': reg, 'ФД': I(r, 'ФД в окне 3 суток'),
        'регистраций всего': I(r, 'регистраций'), 'ФД всего': I(r, 'ФД'),
        'рег на 100 сайтов': round(100 * reg / s, 3) if s else 0,
        'рег на 10 тыс. кликов': round(1e4 * reg / ya, 1) if ya else '',
        'сайтов с регистрацией': I(r, 'сайтов с регистрацией'),
        'дней до первой регистрации': r['дней до первой регистрации'],
        'какие бренды конвертили': r['какие бренды конвертили'],
    })

# место домена внутри своего набора по индексу
by = collections.defaultdict(list)
for x in rows:
    if x['индекс 3 суток %'] != '':
        by[x['набор контента']].append(x)
for k, g in by.items():
    g.sort(key=lambda x: -x['индекс 3 суток %'])
    med = statistics.median(x['индекс 3 суток %'] for x in g)
    for pos, x in enumerate(g, 1):
        x['место в наборе'] = f'{pos} из {len(g)}'
        x['к медиане набора'] = round(x['индекс 3 суток %'] / med, 2) if med else ''
for x in rows:
    x.setdefault('место в наборе', '')
    x.setdefault('к медиане набора', '')

rows.sort(key=lambda x: (-(x['индекс 3 суток %'] if x['индекс 3 суток %'] != '' else -1), -x['регистраций']))
with open(out_csv, 'w', encoding='utf-8', newline='') as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0].keys())); w.writeheader(); w.writerows(rows)
json.dump(rows, open(out_json, 'w'), ensure_ascii=False, separators=(',', ':'))
print(f'{len(rows)} доменов, {len({x["набор контента"] for x in rows})} наборов; '
      f'регистраций {sum(x["регистраций"] for x in rows)}, ФД {sum(x["ФД"] for x in rows)}')
