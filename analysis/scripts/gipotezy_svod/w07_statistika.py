REL = (0, 1, 2, 3)
MINB = 8


def build(ds, kind='рег', rels=REL, prof_src=None):
    ev = []
    for i, d in enumerate(ds):
        for rd, s in d[kind + '_все']:
            if rd in rels:
                ev.append((i, d['блок'], d['лз'], rd, s, d['домен']))
    n = len(ev)
    cnt = defaultdict(Counter)
    tot = Counter()
    for _, b, _, rd, _, _ in ev:
        cnt[b][rd] += 1
        tot[rd] += 1
    pooled = {rd: tot[rd] / n for rd in rels} if n else {}
    prof = {}
    for b in set(d['блок'] for d in ds):
        nb = sum(cnt[b].values())
        prof[b] = {rd: cnt[b][rd] / nb for rd in rels} if nb >= MINB else dict(pooled)
    if prof_src is not None:
        prof = prof_src
    O = Counter()
    E = defaultdict(float)
    wdmap = []
    for i, b, lz, rd, s, dom in ev:
        wds = tuple((lz - 1 + k) % 7 + 1 for k in rels)
        wdmap.append(wds)
        O[(lz - 1 + rd) % 7 + 1] += 1
        pb = prof.get(b, pooled)
        for j, k in enumerate(rels):
            E[wds[j]] += pb[k]
    return ev, O, E, prof, pooled, wdmap


def perm_p(ev, O, E, prof, pooled, wdmap, rels=REL, nperm=10000, seed=7):
    rng = random.Random(seed)
    n = len(ev)
    thr = {}
    for b, pb in prof.items():
        acc, t = 0.0, []
        for k in rels:
            acc += pb[k]
            t.append(acc)
        thr[b] = t
    obs_we = O[6] + O[7]
    Ewe = E[6] + E[7]
    obs_chi = sum((O[w] - E[w]) ** 2 / E[w] for w in range(1, 8) if E[w] > 0)
    rat = [O[w] / E[w] for w in range(1, 8) if E[w] > 0]
    obs_ratio = max(rat) / min(rat)
    pwe = pchi = prat = 0
    sims_we = []
    for _ in range(nperm):
        c = [0] * 8
        for j in range(n):
            t = thr.get(ev[j][1], None)
            if t is None:
                t = []
                acc = 0.0
                for k in rels:
                    acc += pooled[k]
                    t.append(acc)
            r = rng.random()
            k = 0
            while k < len(t) - 1 and r >= t[k]:
                k += 1
            c[wdmap[j][k]] += 1
        we = c[6] + c[7]
        sims_we.append(we)
        if abs(we - Ewe) >= abs(obs_we - Ewe) - 1e-9:
            pwe += 1
        ch = sum((c[w] - E[w]) ** 2 / E[w] for w in range(1, 8) if E[w] > 0)
        if ch >= obs_chi - 1e-9:
            pchi += 1
        rr = [c[w] / E[w] for w in range(1, 8) if E[w] > 0]
        if min(rr) > 0 and max(rr) / min(rr) >= obs_ratio - 1e-9:
            prat += 1
    sims_we.sort()
    lo = sims_we[int(round(0.025 * (nperm - 1)))]
    hi = sims_we[int(round(0.975 * (nperm - 1)))]
    return dict(n=n, we=obs_we, Ewe=Ewe, oe=obs_we / Ewe if Ewe else 0, chi=obs_chi,
                ratio=obs_ratio, p_we=pwe / nperm, p_chi=pchi / nperm, p_ratio=prat / nperm,
                cor=(lo / Ewe if Ewe else 0, hi / Ewe if Ewe else 0), cor_n=(lo, hi))


