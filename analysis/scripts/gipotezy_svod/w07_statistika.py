def logpmf(i, n, p):
    lg = math.lgamma
    return lg(n + 1) - lg(i + 1) - lg(n - i + 1) + i * math.log(p) + (n - i) * math.log(1 - p)


def binom_two(k, n, p0):
    if n == 0 or not (0 < p0 < 1):
        return 1.0
    ref = logpmf(k, n, p0) + 1e-9
    return min(1.0, sum(math.exp(logpmf(i, n, p0)) for i in range(n + 1) if logpmf(i, n, p0) <= ref))


def tail_le(k, n, p):
    return sum(math.exp(logpmf(i, n, p)) for i in range(0, k + 1))


def tail_ge(k, n, p):
    return sum(math.exp(logpmf(i, n, p)) for i in range(k, n + 1))


def clopper(k, n, alpha=0.05):
    """Точный 95 % интервал Клоппера–Пирсона для доли."""
    lo, hi = 0.0, 1.0
    if k > 0:
        a, b = 0.0, 1.0
        for _ in range(200):
            m = (a + b) / 2
            if tail_ge(k, n, m) < alpha / 2:
                a = m
            else:
                b = m
        lo = (a + b) / 2
    if k < n:
        a, b = 0.0, 1.0
        for _ in range(200):
            m = (a + b) / 2
            if tail_le(k, n, m) > alpha / 2:
                a = m
            else:
                b = m
        hi = (a + b) / 2
    return lo, hi


