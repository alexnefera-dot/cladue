# Редкое событие: правильный дизайн — случай-контроль, а не сравнение средних.
from statistics import NormalDist
N=NormalDist()

BASES_D   = 82          # баз в сутки (реестр 09.09-15.09: 576/7)
SUBS_BASE = 186
REG_W, FD_W = 190, 28   # конверсий в неделю
SUBS_W = BASES_D*7*SUBS_BASE

print("=== ВВОДНЫЕ: воронка за сутки ===")
print(f"  баз                {BASES_D:>10,}")
print(f"  сабдоменов         {BASES_D*SUBS_BASE:>10,}")
print(f"  прошли переобход   {int(BASES_D*SUBS_BASE*.944):>10,}   94%")
print(f"  регистраций        {REG_W/7:>10.0f}")
print(f"  ФД                 {FD_W/7:>10.0f}")
print(f"\n  1 регистрация на {SUBS_W/REG_W:>6.0f} сабдоменов")
print(f"  1 ФД          на {SUBS_W/FD_W:>6.0f} сабдоменов")
print(f"  1 ФД          на {BASES_D*7/FD_W:>6.1f} баз  -> большинство баз не дают НИЧЕГО")

# сколько баз вообще даёт хоть одну регистрацию, если конверсии распределены пуассоном
lam = REG_W/(BASES_D*7)
print(f"\n  регистраций на базу в среднем {lam:.3f}")
import math
print(f"  доля баз с нулём регистраций (Пуассон) {math.exp(-lam)*100:.1f}%")

def power_one_sample(p0, OR, n, alpha=.05):
    """Доля среди конверсионных против известной фоновой доли."""
    p1 = OR*p0/(1-p0+OR*p0)
    if n*p0 < 5: return None
    se0 = math.sqrt(p0*(1-p0)/n); se1 = math.sqrt(p1*(1-p1)/n)
    z = N.inv_cdf(1-alpha/2)
    return 1 - N.cdf((z*se0-abs(p1-p0))/se1) + N.cdf((-z*se0-abs(p1-p0))/se1)

print("\n=== ДИЗАЙН 'СЛУЧАЙ-КОНТРОЛЬ': все конверсии работают на КАЖДЫЙ параметр ===")
print("фон известен точно (306k сабдоменов), поэтому это одновыборочный тест доли\n")
weeks=[1,2,4,8,12]
for label,p0,pname in [("один параметр, 3 значения",1/3,"1/3"),
                       ("пара, 12 ячеек",1/12,"1/12"),
                       ("тройка, 36 ячеек",1/36,"1/36")]:
    print(f"-- {label}  (фоновая доля {pname}) --")
    print(f"{'сила связи':<14}"+"".join(f"{w:>4} нед" for w in weeks))
    for OR in (1.3,1.5,2.0):
        row=f"OR {OR:<11.1f}"
        for w in weeks:
            n=int(REG_W*w)
            p=power_one_sample(p0,OR,n)
            row += "   нет" if p is None else f"{100*p:>6.0f}%"
        print(row)
    print()

print("=== то же, но метрика ФД (28 в неделю) ===")
print(f"{'сила связи':<14}"+"".join(f"{w:>4} нед" for w in weeks))
for OR in (1.5,2.0,3.0):
    row=f"OR {OR:<11.1f}"
    for w in weeks:
        p=power_one_sample(1/3,OR,int(FD_W*w))
        row += "   нет" if p is None else f"{100*p:>6.0f}%"
    print(row)

print("\n=== ЧТО ЭТО МЕНЯЕТ ПРОТИВ СРАВНЕНИЯ СРЕДНИХ ===")
print(f"  сравнение средних по базам: 190 регистраций делятся на ячейки,")
print(f"     пара -> {REG_W//12} на ячейку в неделю")
print(f"  случай-контроль: все {REG_W} в неделю работают на каждый параметр,")
print(f"     делится не выборка, а ожидаемая доля")

print("\n=== КЛАСТЕРИЗАЦИЯ: насколько дороже параметры уровня базы ===")
print("параметр базы одинаков у всех 186 её сабдоменов, поэтому независимых")
print("наблюдений столько, сколько РАЗНЫХ баз среди сконвертивших\n")
for w in (1,2,4,8,12):
    B = BASES_D*7*w
    lam = REG_W*w/B
    bases_hit = B*(1-math.exp(-lam))
    cases = REG_W*w
    print(f"  {w:>2} нед: конверсий {cases:>5}, разных баз среди них {bases_hit:>6.0f}"
          f"   эффект кластера ×{cases/bases_hit:.2f}")
print("\nто есть параметр уровня базы стоит ~15% мощности, а не в 186 раз дороже.")
print("Прежний вывод 'базовых параметров не больше двух' был следствием")
print("деления на ячейки, а не кластеризации.")
